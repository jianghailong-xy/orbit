/**
 * The parent's rating of a SubAgent run, and the Model tiers quality that reads it (docs/subagent-design.md §7.1),
 * on a real PostgreSQL:
 *
 *   1. The session that started a run rates it through POST /runner/sessions/:id/subagents/:runId/rating: the score,
 *      the note, the time and the rating parent's own engine, provider and model land on the run's row. Rating it
 *      again replaces all of them. Another session of the same runner, and another account's runner, are answered
 *      as for a run that does not exist, and the row is unchanged. A run still running is refused
 *      SUBAGENT_RUN_RUNNING; the database refuses a score outside 1 to 5.
 *   2. GET /providers/subagent-tiers (subagentTierView) gives each model its SubAgent runs and the decayed average
 *      of their ratings ("Not enough ratings" below 5: no average), and its done tasks' first-pass rate (none below
 *      10). A run that failed on a usage limit or a model at capacity counts neither as a failure nor as a run, and
 *      another account's runs and tasks are never counted. A model's figures are pooled over its every row: the
 *      same id on another engine, and an id model_identity says is the same model.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/subagent-rating.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { ConflictException, NotFoundException } from '@nestjs/common';
import { type PrismaClient, type Runner, SessionDispatchOrigin } from '@prisma/client';
import { RunStatus } from '@orbit/shared';
import { uuidToBase62 } from '@orbit/shared';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { prismaClientFor } from '../prisma/prisma-client';
import { assertCoordinatorPgUrlIsIsolated, verifyCoordinatorPgIdentity } from '../projects/coordinator-pg-test-safety';
import { RunnerSubagentsController } from './runner-subagents.controller';
import { SubagentRatingDto } from './subagent-rating';
import { subagentTierView } from './subagent-route';
import { turnStateOfWord } from '../sessions/session-turn-state';

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;
const DAY = 86_400_000;
const OPUS = 'claude-opus-5-5';
const SONNET = 'claude-sonnet-5-5';
const HAIKU = 'claude-haiku-5-5';
/** An id the rules cannot tie to Haiku, decided to be Haiku in model_identity (as DeepSeek would): unique per run. */
const HAIKU_ALIAS = `haiku-alias-${randomUUID()}`;

const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

const rating = (score: number, note?: string): SubagentRatingDto =>
  Object.assign(new SubagentRatingDto(), { score, ...(note === undefined ? {} : { note }) });

test('subagent_rate: the parent rates its own run, and the Model tiers view reads it', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const catalog = {
    claude: [
      { value: OPUS, label: 'Opus 5.5', priority: 0 },
      { value: SONNET, label: 'Sonnet 5.5', priority: 1 },
      { value: HAIKU, label: 'Haiku 5.5', priority: 2 },
    ],
    // The same Sonnet on another engine, and an alias of Haiku.
    antigravity: [{ value: SONNET, label: SONNET }, { value: HAIKU_ALIAS, label: HAIKU_ALIAS }],
  };
  async function account() {
    const ownerId = randomUUID();
    await prisma.user.create({
      data: { id: ownerId, email: `rating-${ownerId}@runner-door.invalid`, name: 'owner', passwordHash: 'x' },
    });
    const runnerId = randomUUID();
    const runner = (await prisma.runner.create({
      data: { id: runnerId, name: 'the machine', ownerId, tokenHash: sha256(`rating-${runnerId}`), modelCatalog: catalog,
        lastHeartbeatAt: new Date() },
    })) as Runner;
    const workspace = await prisma.workspace.create({
      data: { ownerId, runnerId, name: `rating-${runnerId.slice(-8)}`, enabled: true },
    });
    return { ownerId, runner, workspaceId: workspace.id };
  }
  const mine = await account();
  const theirs = await account();
  const subagents = new RunnerSubagentsController(prisma as never, silent(), silent());

  async function session(of: typeof mine, data: { model?: string; engine?: string; provider?: string; taskId?: string;
    status?: RunStatus; error?: string; createdAt?: Date } = {}) {
    const row = await prisma.session.create({
      data: {
        ownerId: of.ownerId, creatorId: of.ownerId, workspaceId: of.workspaceId, assignedRunnerId: of.runner.id,
        title: 'rating spec', prompt: 'rating spec', provider: data.provider ?? 'claude', engine: data.engine ?? 'claude',
        model: data.model ?? OPUS, effort: 'high', turnState: turnStateOfWord(data.status ?? RunStatus.AWAITING_INPUT), numTurns: 1,
        dispatchOrigin: SessionDispatchOrigin.USER, startsTaskWork: Boolean(data.taskId), taskId: data.taskId ?? null,
        error: data.error ?? null, ...(data.createdAt ? { createdAt: data.createdAt } : {}),
        // A terminal status is a released session: session_release_fact_chk (1401/1402) wants finished_at with it.
        ...(['SUCCEEDED', 'FAILED', 'CANCELLED'].includes(data.status ?? '') ? { finishedAt: data.createdAt ?? new Date() } : {}),
        // A failure release carries FAILED on its turn (removal step R2), which is what reads it as one since R7.
        ...(data.status === RunStatus.FAILED ? { lastTurnOutcome: 'FAILED' } : {}),
      },
    });
    return row.id;
  }
  async function run(of: typeof mine, sessionId: string, model: string, data: { status?: string; ratingScore?: number;
    ratedAt?: Date; createdAt?: Date; raterModel?: string } = {}) {
    const row = await prisma.subagentRun.create({
      data: {
        ownerId: of.ownerId, sessionId, toolUseId: `toolu_${randomUUID()}`, type: 'general', definitionSource: 'builtin',
        status: data.status ?? 'DONE', endedAt: data.status === 'RUNNING' ? null : new Date(),
        decision: { level: 'M', engine: 'claude', provider: 'claude', model, effort: 'medium', applied: true, reasons: [] },
        attempts: [{ engine: 'claude', provider: 'claude', model, effort: 'medium', attempt: 1, outcome: data.status ?? 'DONE',
          startedAt: new Date().toISOString() }],
        ...(data.createdAt ? { createdAt: data.createdAt } : {}),
        ...(data.ratingScore === undefined ? {} : {
          ratingScore: data.ratingScore, ratedAt: data.ratedAt ?? new Date(),
          raterEngine: 'claude', raterProvider: 'claude', raterModel: data.raterModel ?? OPUS,
        }),
      },
    });
    return row.id;
  }

  await t.test('the parent rates; another session cannot; a second rating replaces the first', async () => {
    const parent = await session(mine, { model: OPUS });
    const sibling = await session(mine, { model: SONNET });
    const runId = await run(mine, parent, SONNET);

    const first = await subagents.rateSubagentRun(mine.runner, parent, runId, rating(4, '  Used it after one fix.  '));
    assert.equal(first.runId, uuidToBase62(runId));
    assert.equal(first.score, 4);
    assert.equal(first.note, 'Used it after one fix.');
    assert.equal(first.replaced, false);
    assert.deepEqual(first.rater, { engine: 'claude', provider: 'claude', model: OPUS }, "the rating parent's own model");
    let row = await prisma.subagentRun.findUniqueOrThrow({ where: { id: runId } });
    assert.equal(row.ratingScore, 4);
    assert.equal(row.ratingNote, 'Used it after one fix.');
    assert.ok(row.ratedAt instanceof Date);
    assert.deepEqual([row.raterEngine, row.raterProvider, row.raterModel], ['claude', 'claude', OPUS]);

    await assert.rejects(subagents.rateSubagentRun(mine.runner, sibling, runId, rating(1)), NotFoundException,
      'a session that did not start the run is answered as for a run that does not exist');
    await assert.rejects(subagents.rateSubagentRun(theirs.runner, parent, runId, rating(1)), NotFoundException,
      "another account's runner cannot reach the parent");
    row = await prisma.subagentRun.findUniqueOrThrow({ where: { id: runId } });
    assert.equal(row.ratingScore, 4, 'and the rating is unchanged');

    // The parent now runs on another model; the second rating says so, and leaves no note behind.
    await prisma.session.update({ where: { id: parent }, data: { model: SONNET } });
    const second = await subagents.rateSubagentRun(mine.runner, parent, runId, rating(2));
    assert.equal(second.replaced, true);
    assert.equal(second.note, null);
    row = await prisma.subagentRun.findUniqueOrThrow({ where: { id: runId } });
    assert.equal(row.ratingScore, 2, 'one rating per run: the later replaces it');
    assert.equal(row.ratingNote, null);
    assert.equal(row.raterModel, SONNET);
    assert.ok(row.ratedAt!.getTime() >= Date.parse(first.ratedAt), 'with the time of the later rating');
  });

  await t.test('a run still running is refused, and the database holds the score to 1..5', async () => {
    const parent = await session(mine);
    const running = await run(mine, parent, SONNET, { status: 'RUNNING' });
    await assert.rejects(subagents.rateSubagentRun(mine.runner, parent, running, rating(5)),
      (error: unknown) => error instanceof ConflictException
        && (error.getResponse() as { code?: string }).code === 'SUBAGENT_RUN_RUNNING');
    assert.equal((await prisma.subagentRun.findUniqueOrThrow({ where: { id: running } })).ratingScore, null);
    await assert.rejects(
      sql.query('UPDATE subagent_run SET rating_score = 6 WHERE id = $1', [running]),
      /subagent_run_rating_score_check/,
    );
  });

  await t.test('the Model tiers view: decayed average, thresholds, task first pass without limit failures', async () => {
    const view = await subagentTierView(prisma as never, mine.ownerId);
    const claudeRow = view.providers.find((p) => p.slug === 'claude' && p.kind === 'builtin')!;
    const sonnetBefore = claudeRow.models.find((m) => m.model === SONNET)!;
    // From the first test: one rated run (2), one unrated running run excluded, and the sibling's nothing.
    assert.equal(sonnetBefore.quality.subagent.ratedCount, 1);
    assert.equal(sonnetBefore.quality.subagent.runCount, 1, 'a run still running is not counted');
    assert.equal(sonnetBefore.quality.subagent.averageRating, null, 'below 5 ratings: Not enough ratings');

    // Five more Sonnet ratings: 5s today, 1s sixty days ago, and one rated 100 days ago that is out of the window.
    const parent = await session(mine);
    for (const _ of [1, 2, 3]) await run(mine, parent, SONNET, { ratingScore: 5 });
    for (const _ of [1, 2]) {
      await run(mine, parent, SONNET, { ratingScore: 1, ratedAt: new Date(Date.now() - 60 * DAY),
        createdAt: new Date(Date.now() - 60 * DAY), raterModel: SONNET });
    }
    await run(mine, parent, SONNET, { ratingScore: 1, ratedAt: new Date(Date.now() - 100 * DAY),
      createdAt: new Date(Date.now() - 100 * DAY) });
    await run(mine, parent, SONNET); // ended, never rated
    // Another account's runs on the same model are never counted.
    const elsewhere = await session(theirs);
    for (const _ of [1, 2, 3, 4, 5]) await run(theirs, elsewhere, SONNET, { ratingScore: 1 });

    // Done tasks first run on Haiku: 10 completed, 8 first pass. One more had a usage-limit failure and then passed:
    // first pass all the same. Another failed once for real before passing: not first pass.
    const haikuTask = async (runs: Array<{ status?: RunStatus; error?: string }>) => {
      const task = await prisma.task.create({ data: {
        ownerId: mine.ownerId, creatorType: 'USER', creatorId: mine.ownerId, title: 'quality task', status: 'DONE',
        completionCriterion: 'EXECUTABLE', acceptanceCommand: 'true', acceptanceExpectedExitCode: 0,
      } });
      let at = Date.now() - 5 * DAY;
      for (const r of runs) {
        await session(mine, { model: HAIKU, taskId: task.id, status: r.status ?? RunStatus.SUCCEEDED, error: r.error,
          createdAt: new Date((at += 60_000)) });
      }
    };
    for (let i = 0; i < 7; i++) await haikuTask([{}]);
    await haikuTask([{ status: RunStatus.FAILED, error: "You've hit your usage limit" }, {}]);
    await haikuTask([{ status: RunStatus.FAILED, error: 'Selected model is at capacity' }, {}]);
    await haikuTask([{ status: RunStatus.FAILED, error: 'acceptance command exited 1' }, {}]);
    // A task whose only run hit a limit, then ran on Opus: Opus's task, not Haiku's.
    const moved = await prisma.task.create({ data: {
      ownerId: mine.ownerId, creatorType: 'USER', creatorId: mine.ownerId, title: 'moved task', status: 'DONE',
      completionCriterion: 'EXECUTABLE', acceptanceCommand: 'true', acceptanceExpectedExitCode: 0,
    } });
    await session(mine, { model: HAIKU, taskId: moved.id, status: RunStatus.FAILED, error: "You've hit your usage limit. Try again later.",
      createdAt: new Date(Date.now() - 3 * DAY) });
    await session(mine, { model: OPUS, taskId: moved.id, status: RunStatus.SUCCEEDED, createdAt: new Date(Date.now() - 2 * DAY) });

    const after = await subagentTierView(prisma as never, mine.ownerId);
    const claude = after.providers.find((p) => p.slug === 'claude' && p.kind === 'builtin')!;
    const sonnet = claude.models.find((m) => m.model === SONNET)!.quality;
    assert.equal(sonnet.subagent.ratedCount, 6, 'the 100-day-old rating is out of the 90-day window');
    assert.equal(sonnet.subagent.runCount, 7);
    // Weights: 2 and three 5s today (1 each), two 1s at 60 days (0.25 each): (2 + 15 + 0.5) / 4.5 = 3.888… → 3.9.
    assert.equal(sonnet.subagent.averageRating, 3.9, 'recent ratings weigh more');
    // The first test's re-rating was made while the parent ran Sonnet; the three 5s by Opus, the two old 1s by Sonnet.
    assert.deepEqual(sonnet.subagent.raters.map((r) => [r.label, r.count]), [['Opus 5.5', 3], ['Sonnet 5.5', 3]],
      'who rated, by the names the catalogue gives');

    const haiku = claude.models.find((m) => m.model === HAIKU)!.quality;
    assert.equal(haiku.tasks.completedTaskCount, 10, "the moved task is not Haiku's");
    assert.equal(haiku.tasks.firstPassTaskCount, 9, 'a usage-limit or capacity failure is not a failure, nor a run');
    assert.equal(haiku.tasks.firstPassRate, 0.9);
    const opus = claude.models.find((m) => m.model === OPUS)!.quality;
    assert.equal(opus.tasks.completedTaskCount, 1);
    assert.equal(opus.tasks.firstPassRate, null, 'below 10 completed tasks: Not enough tasks');

    // One model, many rows: Sonnet on Antigravity reads Claude Code's figures, and an id model_identity ties to
    // Haiku reads Haiku's, under Haiku's identity.
    await prisma.modelIdentity.create({ data: { ruleKey: HAIKU_ALIAS, canonicalKey: HAIKU, name: 'Claude Haiku 5.5' } });
    const pooled = await subagentTierView(prisma as never, mine.ownerId);
    const agy = pooled.providers.find((p) => p.slug === 'antigravity' && p.kind === 'builtin')!;
    const agySonnet = agy.models.find((m) => m.model === SONNET)!;
    assert.deepEqual(agySonnet.quality, sonnet, 'the same id on another engine is the same model');
    // Named by the seed migration 1433 (069b42dd64), which knows production's ids.
    assert.deepEqual(agySonnet.identity, { key: SONNET, name: 'Claude Sonnet 5.5' });
    const alias = agy.models.find((m) => m.model === HAIKU_ALIAS)!;
    assert.deepEqual(alias.quality, haiku, 'an id model_identity ties to Haiku reads Haiku');
    assert.deepEqual(alias.identity, { key: HAIKU, name: 'Claude Haiku 5.5' });
    await prisma.modelIdentity.delete({ where: { ruleKey: HAIKU_ALIAS } });

    // An Antigravity id with its level is its base model: a run there on `claude-sonnet-5-5-high` counts for Sonnet.
    await prisma.subagentRun.create({ data: {
      ownerId: mine.ownerId, sessionId: parent, toolUseId: `toolu_${randomUUID()}`, type: 'general', definitionSource: 'builtin',
      status: 'DONE', endedAt: new Date(),
      decision: { level: 'M', engine: 'antigravity', provider: 'antigravity', model: SONNET, effort: 'high', applied: true, reasons: [] },
      attempts: [{ engine: 'antigravity', provider: 'antigravity', model: `${SONNET}-high`, effort: 'high', attempt: 1, outcome: 'DONE',
        startedAt: new Date().toISOString() }],
    } });
    const folded = await subagentTierView(prisma as never, mine.ownerId);
    const claudeSonnet = folded.providers.find((p) => p.slug === 'claude' && p.kind === 'builtin')!.models.find((m) => m.model === SONNET)!;
    assert.equal(claudeSonnet.quality.subagent.runCount, sonnet.subagent.runCount + 1, "an Antigravity level folds into its base model");

    // 1463: the seed's `-max` models are keyed by their whole id, so Qwen3.7 Max is never taken for a plain Qwen3.7.
    const max = await prisma.modelIdentity.findMany({ where: { ruleKey: { in: ['qwen3-7', 'qwen3-7-max', 'qwen4', 'qwen4-max'] } } });
    assert.deepEqual(max.map((r) => [r.ruleKey, r.canonicalKey, r.name]).sort(),
      [['qwen3-7-max', 'qwen3-7-max', 'Qwen3.7 Max'], ['qwen4-max', 'qwen4-max', 'Qwen4 Max']]);
  });
});
