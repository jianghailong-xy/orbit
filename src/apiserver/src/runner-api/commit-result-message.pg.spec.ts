declare global {
  interface BigInt { toJSON(): string; }
}
// `main.ts` installs this before it creates the app. A session row carries BIGINT columns, and
// without it the detail read answers 500 — a server-shaped failure, but not the one under test.
BigInt.prototype.toJSON = function toJSON(this: bigint): string {
  return this.toString();
};

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

/** The runner credential, in the clear. Its hash is what `RunnerAuthGuard` matches. */
const RUNNER_TOKEN = 'the-runner-token-for-commit-results';
/** Any bearer: the user door's verifier is stubbed to answer with this run's owner. */
const USER_TOKEN = 'the-owner-bearer-for-commit-results';

/** The receipt runner-go writes when it evicted the engine before committing (session_pool.go). */
const EVICTED =
  'the engine was evicted for this commit: it was running MCP servers the agent configured itself (agent-fs, agent-browser)';
/** What git says when a commit fails. */
const GIT_FAILED = "fatal: Unable to create '/work/.git/index.lock': File exists.";

/** A response, kept as text as well as JSON: a body that failed to parse has to be readable. */
interface Answer {
  status: number;
  text: string;
  json: Record<string, unknown>;
}

test('the message of a commit result is read back from the session it settled', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  let app: INestApplication | undefined;
  t.after(async () => {
    await app?.close().catch(() => undefined);
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  const runnerId = randomUUID();
  await prisma.user.create({
    data: {
      id: ownerId,
      email: `commit-result-${ownerId}@runner-door.invalid`,
      name: 'The account owner',
      passwordHash: 'x',
    },
  });
  // A real runner row: `RunnerAuthGuard` finds it by the credential's hash, and `commit-result`
  // only settles a session assigned to the runner it found.
  await prisma.runner.create({
    data: { id: runnerId, name: 'the machine the agent runs on', ownerId, tokenHash: sha256(RUNNER_TOKEN) },
  });

  /**
   * A live session whose Commit was pressed and whose request the runner process `leaseOwner`
   * claimed — the state a runner's result settles, with the operation fence it reports against.
   */
  async function claimedCommit(): Promise<{ sessionId: string; operationId: string; leaseOwner: string }> {
    const sessionId = randomUUID();
    const operationId = randomUUID();
    const leaseOwner = randomUUID();
    await prisma.session.create({
      data: {
        id: sessionId,
        ownerId,
        creatorId: ownerId,
        title: 'a live session with uncommitted work',
        prompt: 'change the tree',
        provider: 'claude',
        status: RunStatus.AWAITING_INPUT,
        dispatchOrigin: SessionDispatchOrigin.USER,
        startsTaskWork: false,
        assignedRunnerId: runnerId,
        inboxLeaseOwner: leaseOwner,
        isolationStatus: 'worktree',
        branch: `orbit/commit-result-${sessionId.slice(0, 8)}`,
        worktreeDirty: true,
        commitStatus: 'pending',
        commitRequestedAt: new Date(),
        commitOperationId: operationId,
        commitOperationOwner: leaseOwner,
      },
    });
    return { sessionId, operationId, leaseOwner };
  }

  // ── the app: both real controllers, the real guards, main.ts's middleware and interceptor ──────
  // Nothing here reaches the collaborators a commit result and a session read do not use; the empty
  // doubles answer a call with a TypeError, which surfaces as a 500 on the status asserted below.
  const queue = { notifySessionQueued: () => undefined };
  const sessions = new SessionsService(prisma as unknown as PrismaService, queue as never, {} as never);
  @Module({
    controllers: [RunnerApiController, SessionsController],
    providers: [
      { provide: PrismaService, useValue: prisma },
      { provide: QueueService, useValue: queue },
      { provide: SessionsService, useValue: sessions },
      { provide: RealtimeService, useValue: {} },
      { provide: PushService, useValue: {} },
      { provide: RunnerOrchestrationAuthorizer, useValue: {} },
      { provide: ReferenceExpansionService, useValue: {} },
      { provide: ListEventsService, useValue: {} },
      { provide: AttemptBudgetMeterService, useValue: {} },
      { provide: ProjectAcceptanceService, useValue: {} },
      { provide: TasksService, useValue: {} },
      { provide: MergeReceiptService, useValue: {} },
      { provide: SessionTagsService, useValue: {} },
      // The owner, the way `JwtAuthGuard` would have read them off a real token.
      { provide: JwtService, useValue: { verifyAsync: async () => ({ sub: ownerId }) } },
      Reflector,
      JwtAuthGuard,
      RunnerAuthGuard,
    ],
  })
  class CommitResultDoors {}

  app = await NestFactory.create(CommitResultDoors, { logger: false, abortOnError: false });
  app.use(publicIdHeaders);
  app.setGlobalPrefix('api');
  app.useGlobalPipes(
    new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }),
  );
  app.useGlobalInterceptors(new PublicIdInterceptor());
  await app.listen(0, '127.0.0.1');
  const base = await app.getUrl();

  async function send(method: 'GET' | 'POST', route: string, token: string, body?: unknown): Promise<Answer> {
    const response = await fetch(`${base}/api${route}`, {
      method,
      headers: {
        authorization: `Bearer ${token}`,
        ...(body === undefined ? {} : { 'content-type': 'application/json' }),
      },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    });
    const text = await response.text();
    let json: Record<string, unknown> = {};
    try { json = JSON.parse(text) as Record<string, unknown>; } catch { /* asserted on by the caller */ }
    return { status: response.status, text, json };
  }

  /** The runner's POST, addressed the way the runner addresses it: by the session's public id. */
  async function report(sessionId: string, result: Record<string, unknown>): Promise<void> {
    const answer = await send('POST', `/runner/sessions/${uuidToBase62(sessionId)}/commit-result`, RUNNER_TOKEN, result);
    assert.equal(answer.status, 201, `commit-result answered ${answer.status}: ${answer.text}`);
  }

  /** The session as a client reads it. */
  async function read(sessionId: string): Promise<Record<string, unknown>> {
    const answer = await send('GET', `/sessions/${uuidToBase62(sessionId)}`, USER_TOKEN);
    assert.equal(answer.status, 200, `GET /api/sessions/:id answered ${answer.status}: ${answer.text}`);
    return answer.json;
  }

  for (const status of ['committed', 'nochange'] as const) {
    await t.test(`${status}: the message the runner sent is on the session, byte for byte`, async () => {
      const commit = await claimedCommit();
      await report(commit.sessionId, {
        operationId: commit.operationId,
        leaseOwner: commit.leaseOwner,
        status,
        message: EVICTED,
      });

      const session = await read(commit.sessionId);
      assert.equal(session.commitResultMessage, EVICTED,
        `the message of a ${status} commit result cannot be read back from GET /api/sessions/:id`);
      assert.equal(session.commitStatus, status);
      assert.equal(session.commitError, null, 'a commit that went through is not an error');
      assert.equal(session.worktreeDirty, false);
    });
  }

  // The control: a failed commit's message is where it always was, and nowhere else.
  await t.test('error: git\'s message is still commitError, and only commitError', async () => {
    const commit = await claimedCommit();
    await report(commit.sessionId, {
      operationId: commit.operationId,
      leaseOwner: commit.leaseOwner,
      status: 'error',
      message: GIT_FAILED,
    });

    const session = await read(commit.sessionId);
    assert.equal(session.commitStatus, 'error');
    assert.equal(session.commitError, GIT_FAILED);
    assert.equal(session.worktreeDirty, true, 'a failed commit leaves the work uncommitted');
    assert.ok(session.commitResultMessage == null,
      `a failed commit's message was copied beside commitError: ${JSON.stringify(session.commitResultMessage)}`);
  });

  await t.test('pressing Commit again clears the message the previous commit left', async () => {
    const commit = await claimedCommit();
    await report(commit.sessionId, {
      operationId: commit.operationId,
      leaseOwner: commit.leaseOwner,
      status: 'committed',
      message: EVICTED,
    });
    // What makes the clearing below mean anything: there is a message to clear.
    assert.equal((await read(commit.sessionId)).commitResultMessage, EVICTED,
      'the committed result left no message on the session to clear');

    const pressed = await send('POST', `/sessions/${uuidToBase62(commit.sessionId)}/commit`, USER_TOKEN);
    assert.equal(pressed.status, 201, `POST /api/sessions/:id/commit answered ${pressed.status}: ${pressed.text}`);

    const session = await read(commit.sessionId);
    assert.equal(session.commitStatus, 'pending');
    assert.equal(session.commitResultMessage, null,
      'a new commit request still shows the message of the commit before it');
  });
});
