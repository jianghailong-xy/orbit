/**
 * What a runner says about a commit that went through can be read back from the session.
 *
 * Before a merge or a commit the runner may evict the session's parked engine — it was running MCP
 * servers the agent configured itself, which nothing counts as writers of the checkout — and it says
 * so in the operation receipt's `message`. The merge half of that receipt is kept (the merge
 * receipt's `detail.message`). The commit half was kept only when the commit FAILED: `commit-result`
 * wrote `commitError` for `error` and dropped the message of `committed` and `nochange`, so the one
 * sentence saying why the engine was gone survived only in the runner's own log.
 *
 * Over real HTTP and against real PostgreSQL, because the claim is about the wire at both ends: the
 * body a runner POSTs through its door, and the body `GET /api/sessions/:id` answers a person with.
 * A service call on either side would skip the column the row really has, or the payload the client
 * really receives.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/commit-result-message.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { type INestApplication, Module, ValidationPipe } from '@nestjs/common';
import { NestFactory, Reflector } from '@nestjs/core';
import { JwtService } from '@nestjs/jwt';
import { RunStatus, SessionDispatchOrigin, type PrismaClient } from '@prisma/client';
import { uuidToBase62 } from '@orbit/shared';
import { Client } from 'pg';

import { JwtAuthGuard } from '../auth/jwt-auth.guard';
import { sha256 } from '../common/crypto.util';
import { publicIdHeaders } from '../common/public-id-headers';
import { PublicIdInterceptor } from '../common/public-id.interceptor';
import { prismaClientFor } from '../prisma/prisma-client';
import { PrismaService } from '../prisma/prisma.service';
import { AttemptBudgetMeterService } from '../projects/attempt-budget-meter.service';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { ProjectAcceptanceService } from '../projects/project-acceptance.service';
import { PushService } from '../push/push.service';
import { QueueService } from '../queue/queue.service';
import { RealtimeService } from '../realtime/realtime.service';
import { SessionTagsService } from '../session-tags/session-tags.service';
import { MergeReceiptService } from '../sessions/merge-receipt.service';
