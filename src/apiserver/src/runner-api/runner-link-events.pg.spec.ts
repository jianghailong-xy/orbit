/**
 * Durable events over the runner link, end to end (docs/runner-link-design.md §5.8, §6.6, §6.7; link-events.ts).
 *
 * WHAT THIS DRIVES
 * ----------------
 * The real `RunnerApiController` behind the real `RunnerAuthGuard`, over a disposable PostgreSQL, with main.ts's error
 * boundaries, reached the way the link gateway reaches it: through the internal listener, with the gateway's secret and
 * the runner's link token, and the body the gateway forwards an EventBatch as (src/link-gateway/events.go). Beside it
 * the same route over HTTPS, as a runner posts today, and a second apiserver on the same database, the gateway's other
 * backend. Two real RealtimeServices stand for two replicas: the one the route publishes on, and another, listening on
 * the database, that a client could be watching from.
 *
 * WHAT IT ASSERTS
 * ---------------
 *   (1) One session's seqs stay contiguous through an event the link refused: a tombstone holds its seq, the events
 *       after it are stored, and the answer's durableSeq covers the batch. A batch sent again, even after newer ones,
 *       answers the same and writes no row twice: no run_event, no tombstone, no tool_call, and the session's state
 *       stays as the newest batch left it. The batches after the tombstone are stored, and the session's state derived
 *       from them, as before. No reader is ever handed the tombstone, while after_seq counts it as stored.
 *   (2) Values the database itself refuses (a lone surrogate in a jsonb payload, SQLSTATE class 22; a tool id too long
 *       for its index, 54000) are found by halves and refused alone, as EVENT_UNSTORABLE, with the rest stored.
 *   (3) A noise ping in a link batch is acknowledged and skipped: durableSeq goes past it, no row is written, and the
 *       next batch is taken. A live event sent as a durable one is refused with a tombstone.
 *   (4) pg_notify: a batch is ONE notification to the other replicas, of what was stored (whole, or as the seq range
 *       the other replica reads back), whichever door it came by; live events go into no notification and still
 *       reach this replica's streams.
 *   (5) HTTPS is served as before: a batch is stored or refused whole, answered `{ ok: true }`, and a retried one
 *       derives its tool calls again.
 *   (6) A failure that is not an event's own (here the lease fence) fails the whole link batch and tombstones nothing.
 *   (7) Two copies of one batch at once, on the two backends, both waiting for the session lock: stored once, derived
 *       once, and answered alike.
 *   (8) A batch sent again with new events after the old ones: only the new ones are written, with what they derive.
 *   (9) An event at a seq the session holds another event at, over either door: answered as before, the row there left
 *       as it was, and the event logged as an error and counted (run-event-seq-conflicts.ts). The same event sent again
 *       is neither.
 *
 * Every state is read on a second connection, never through the answer that wrote it.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/runner-link-events.pg.spec.ts
 *
 * Needs COORDINATOR_PG_URL (the script provides a disposable one). Not destructive: every id is generated by the run.
 */
