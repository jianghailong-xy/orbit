  await t.test('(7) two copies of a batch at once on two backends: stored once, derived once, answered alike', async () => {
    const s = await liveSession('two copies at once');
    const batch = [
      ev(1, RunEventType.USER, { text: 'once' }, s.turnId),
      ev(2, RunEventType.TOOL_USE, { id: 'toolu_c1', name: 'Bash', input: {} }, s.turnId),
      ev(3, RunEventType.TOOL_RESULT, { toolUseId: 'toolu_c1', content: 'one' }, s.turnId),
      ev(4, RunEventType.TOOL_RESULT, 'not an object', s.turnId),
      ev(5, RunEventType.TOOL_USE, { id: 'toolu_c2', name: 'Read', input: {} }, s.turnId),
      ev(6, RunEventType.ASSISTANT, { text: 'answered once' }, s.turnId),
    ];
    // The session's row lock, held here until both copies wait for it: the one the ingest takes first. When it is let
    // go, one copy stores the batch and the other, which waited, finds it stored.
    const holder = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
    await holder.connect();
    let copies: Promise<[Answer, Answer]> | undefined;
    try {
      await holder.query('BEGIN');
      await holder.query('SELECT id FROM "session" WHERE id = $1 FOR UPDATE', [s.sessionId]);
      copies = Promise.all([
        send(door.linkPort, 'POST', `/api/runner/sessions/${s.sessionId}/events`, viaLink(), { leaseOwner, events: batch }),
        send(door2.linkPort, 'POST', `/api/runner/sessions/${s.sessionId}/events`, viaLink(), { leaseOwner, events: batch }),
      ]);
      const deadline = Date.now() + 10_000;
      for (;;) {
        const { rows } = await sql.query<{ n: number }>(
          `SELECT count(*)::int AS n FROM pg_stat_activity
            WHERE datname = current_database() AND wait_event_type = 'Lock' AND query LIKE '%inbox_lease_owner%'`,
        );
        if (rows[0].n >= 2) break;
        if (Date.now() > deadline) assert.fail(`${rows[0].n} of the two copies reached the session lock`);
        await sleep(25);
      }
      await holder.query('COMMIT');
    } finally {
      await holder.end().catch(() => undefined);
    }
    const [a, b] = await copies!;
    assert.equal(a.status, 202, JSON.stringify(a.body));
    assert.equal(b.status, 202, JSON.stringify(b.body));
    assert.deepEqual(a.body, b.body, 'both copies are answered alike');
    assert.equal(a.body.durableSeq, 6);
    assert.deepEqual(a.body.rejected.map((r: { seq: number; code: string }) => [r.seq, r.code]), [[4, 'EVENT_PAYLOAD_INVALID']]);
    await assertContiguous(s.sessionId, 6);
    assert.deepEqual(await toolCalls(s.sessionId), [
      { toolUseId: 'toolu_c1', rows: 1, output: 'one' },
      { toolUseId: 'toolu_c2', rows: 1, output: null },
    ]);
    assert.equal((await sessionState(s.sessionId)).lastAssistantText, 'answered once');
  });

