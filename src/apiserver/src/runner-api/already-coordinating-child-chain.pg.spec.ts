/**
 * ALREADY_COORDINATING's recovery chain end to end (docs/recovery-contract.md §9), against a real
 * PostgreSQL and the real runner doors: `RunnerProjectsController` for project_create and
 * `RunnerSessionsController` for session_create, with the create receipts in front of both.
 *
 *   1. The same request replayed under a new id (the first answer was lost) is read back from its
 *      receipt: the Project the session already coordinates, `replayOf`, nothing refused or created.
 *   2. A really different Project is refused, names the bound Project by public id and title, and
 *      carries a self-contained childSessionPrompt. Nothing is created.
 *   3. The user declines: nothing more is sent, and nothing exists.
 *   4. The user agrees: ONE session_create with that prompt, ONE child project_create with the
 *      arguments the prompt carries. The child coordinates the new Project, its parent is the
 *      original session, the original binding is unchanged, and no turn is queued to the child
 *      beyond its opening prompt.
 *   5. Orchestration off: session_create is refused and creates no child; the manual fallback (the
 *      user starts a session and sends the same prompt) records the Project there.
 *
 * Capability absence on the Agent's surface (session_create not listed) is the runner's to render;
 * `recovery_render_test.go` covers it.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/already-coordinating-child-chain.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { ConflictException, ForbiddenException, HttpException } from '@nestjs/common';
import { JwtService } from '@nestjs/jwt';
import {
  type PrismaClient,
  type Runner,
  RunnerStatus,
  SessionDispatchOrigin,
  SessionRunSource,
} from '@prisma/client';
import { RunStatus } from '@orbit/shared';
import { Client } from 'pg';
import { toUuid, uuidToBase62 } from '@orbit/shared';

import { sha256 } from '../common/crypto.util';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { prismaClientFor } from '../prisma/prisma-client';
import { PrismaService } from '../prisma/prisma.service';
import { ProjectAcceptanceService } from '../projects/project-acceptance.service';
import { ProjectsService } from '../projects/projects.service';
import { SessionsService } from '../sessions/sessions.service';
import { CreateRequestReceipts } from './create-request-receipts';
import { RunnerOrchestrationAuthorizer } from './runner-orchestration-authorizer';
import { RunnerProjectsController } from './runner-projects.controller';
import { RunnerSessionsController } from './runner-sessions.controller';

declare global {
  interface BigInt { toJSON(): string; }
}
BigInt.prototype.toJSON = function toJSON(this: bigint): string {
  return this.toString();
};

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

const silent = (): unknown =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

interface Refusal {
  code: string;
  coordinatingProject: { id: string; title: string } | null;
  sessionId: string;
  childSessionPrompt: string;
  recovery: { actionCode: string; userConfirmation: string; effect: string; retryPolicy: string };
}

/** The refusal's body, or a failed assertion when it was something else. */
async function refusalOf(call: Promise<unknown>): Promise<Refusal> {
  try {
    await call;
  } catch (error) {
    assert.ok(error instanceof ConflictException, `expected a 409, got ${String(error)}`);
    return error.getResponse() as Refusal;
  }
  assert.fail('expected ALREADY_COORDINATING');
}

/** The project_create arguments a child prompt carries: what the child sends, byte for byte. */
function argumentsIn(prompt: string): Record<string, unknown> {
  const block = /(`{3,})json\n([\s\S]*?)\n\1\n/.exec(prompt);
  assert.ok(block, 'the prompt carries its project_create arguments as a JSON block');
  return JSON.parse(block[2]) as Record<string, unknown>;
}

test('ALREADY_COORDINATING: reconcile, ask, one child, and the child coordinates the new Project', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });
  const db = prisma as unknown as PrismaService;

  const ownerId = randomUUID();
  const runnerId = randomUUID();
  const workspaceId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `already-coordinating-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  await prisma.runner.create({
    data: {
      id: runnerId, ownerId, name: 'the machine', tokenHash: sha256(`token-${runnerId}`),
      status: RunnerStatus.ONLINE, lastHeartbeatAt: new Date(), capabilities: [], capabilitiesReportedAt: new Date(),
    },
  });
  await prisma.workspace.create({ data: { id: workspaceId, ownerId, runnerId, name: 'orbit', enabled: true } });
  const runner = { id: runnerId, ownerId } as Runner;

  async function liveSession(title: string): Promise<string> {
    const id = randomUUID();
    await prisma.session.create({
      data: {
        id, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title, prompt: title, provider: 'claude', providerBuiltin: true, engine: 'claude',
        turnState: 'IN_FLIGHT', startedAt: new Date(), runtimeSessionId: `runtime-${id}`,
        dispatchOrigin: SessionDispatchOrigin.USER, runSource: SessionRunSource.MANUAL,
      },
    });
    return id;
  }

  /**
   * What dispatch does before a child's first tool call: this runner claims it. Only the runner is
   * written: a status change goes through the session's dispatch guards, and `project_create` from a
   * session asks only that this runner runs it.
   */
  async function claimed(sessionId: string): Promise<void> {
    const { count } = await prisma.session.updateMany({
      where: { id: sessionId },
      data: { assignedRunnerId: runnerId },
    });
    assert.equal(count, 1, `claim ${sessionId}`);
  }

  const sessions = new SessionsService(db, { notifySessionQueued: () => undefined } as never, silent() as never);
  const orchestration = new RunnerOrchestrationAuthorizer(db, new JwtService({ secret: 'already-coordinating-pg' }));
  const receipts = new CreateRequestReceipts(db);
  const acceptance = new ProjectAcceptanceService(db);
  const projects = new ProjectsService(db, acceptance, sessions);
  const projectDoor = new RunnerProjectsController(
    projects, acceptance, {} as never, orchestration,
    undefined, undefined, undefined, undefined, receipts,
  );
  const sessionDoor = new RunnerSessionsController(
    sessions, orchestration, {} as never, { chargeSteer: async () => undefined } as never, undefined, undefined, receipts,
  );

  // Every call the chain makes is counted, so "only once" is a number rather than an impression.
  const calls = { projectCreate: 0, sessionCreate: 0 };
  const projectCreate = (from: string, body: Record<string, unknown>, requestId = `req-${randomUUID()}`) => {
    calls.projectCreate += 1;
    return projectDoor.createProject(runner, from, undefined, body as never, requestId) as Promise<Record<string, any>>;
  };
  const sessionCreate = async (parent: string, prompt: string) => {
    calls.sessionCreate += 1;
    return sessionDoor.createSession(
      runner, undefined, parent, await orchestration.issue(runnerId, parent),
      { prompt, workspaceId, engine: 'claude' }, `req-${randomUUID()}`,
    ) as Promise<Record<string, any>>;
  };
  const titled = (title: string) => prisma.project.findMany({ where: { ownerId, title } });
  const childrenOf = (parent: string) => prisma.session.findMany({ where: { parentSessionId: parent } });

  // The parent: a session that planned and recorded project A, and so coordinates it.
  const parent = await liveSession('planner');
  const projectA = { title: 'Crawl the corpus', goal: 'Index every document.' };
  const firstRequest = `req-${randomUUID()}`;
  const a = await projectCreate(parent, projectA, firstRequest);
  const aId = toUuid(a.id as string);
  assert.equal((await prisma.project.findUniqueOrThrow({ where: { id: aId } })).coordinatorSessionId, parent);

  await t.test('1. the same request under a new id is the first answer, not a second Project', async () => {
    const replay = await projectCreate(parent, projectA);
    assert.equal(replay.id, a.id);
    assert.equal(replay.replayOf.requestId, firstRequest);
    assert.equal(replay.replayOf.replayed, true);
    assert.equal((await titled(projectA.title)).length, 1);
    assert.equal((await childrenOf(parent)).length, 0, 'a replay opens nothing');
  });

  const projectB = {
    title: 'Re-crawl weekly',
    goal: 'Keep the index fresh.',
    instructions: 'One crawl at a time.',
    acceptanceCriteriaItems: [
      { text: 'A crawl runs every week.', verificationMethod: 'Read the schedule and its last run.' },
      { text: 'A failed crawl is retried once.', verificationMethod: 'Inject a failure and read the log.' },
    ],
  };
  let refusal!: Refusal;

  await t.test('2. a really different Project is refused, naming the bound one, with the child prompt', async () => {
    refusal = await refusalOf(projectCreate(parent, projectB));
    assert.equal(refusal.code, 'ALREADY_COORDINATING');
    assert.deepEqual(refusal.coordinatingProject, { id: uuidToBase62(aId), title: projectA.title });
    assert.equal(refusal.sessionId, uuidToBase62(parent));
    assert.equal(refusal.recovery.actionCode, 'CREATE_PROJECT_IN_CHILD_SESSION');
    assert.equal(refusal.recovery.userConfirmation, 'REQUIRED');
    assert.equal(refusal.recovery.effect, 'NONE');
    assert.equal(refusal.recovery.retryPolicy, 'NEVER');
    // Self-contained: title, goal, instructions and every structured criterion, as sent.
    assert.deepEqual(argumentsIn(refusal.childSessionPrompt), projectB);
    assert.match(refusal.childSessionPrompt, /PROJECT_CREATED projectId=/);
    assert.equal((await titled(projectB.title)).length, 0, 'nothing was created');
  });

  await t.test('3. the user declines: nothing is sent, and nothing exists', async () => {
    const before = { ...calls };
    // The Agent asked; the answer was no. The chain sends nothing further.
    assert.deepEqual(calls, before);
    assert.equal((await titled(projectB.title)).length, 0);
    assert.equal((await childrenOf(parent)).length, 0);
    assert.equal((await prisma.project.findUniqueOrThrow({ where: { id: aId } })).coordinatorSessionId, parent);
  });

  await t.test('4. the user agrees: one child, one child project_create, and the child coordinates it', async () => {
    const before = { ...calls };
    const child = await sessionCreate(parent, refusal.childSessionPrompt);
    const childId = toUuid(child.id as string);
    const turnsAtOpening = await prisma.conversationTurn.count({ where: { sessionId: childId } });

    await claimed(childId);
    const b = await projectCreate(childId, argumentsIn(refusal.childSessionPrompt));
    assert.deepEqual(
      { sessionCreate: calls.sessionCreate - before.sessionCreate, projectCreate: calls.projectCreate - before.projectCreate },
      { sessionCreate: 1, projectCreate: 1 },
      'the success path is exactly one session_create and one child project_create',
    );

    // What the parent reports: the Project id and the child Session id.
    assert.ok(b.id, 'a Project id');
    assert.ok(child.id, 'a child Session id');
    assert.match(b.coordinatorInstructions as string, new RegExp(`\\(id: ${uuidToBase62(toUuid(b.id as string))}\\)`), 'the child is told it now coordinates it');

    const bRow = await prisma.project.findUniqueOrThrow({ where: { id: toUuid(b.id as string) } });
    assert.equal(bRow.coordinatorSessionId, childId, 'the new Project is coordinated by the child');
    assert.equal(bRow.goal, projectB.goal);
    assert.equal(bRow.instructions, projectB.instructions);
    const criteria = await prisma.projectAcceptanceCriterionDefinition.findMany({
      where: { projectId: bRow.id }, orderBy: { ordinal: 'asc' },
    });
    assert.deepEqual(
      criteria.map((c) => ({ text: c.text, verificationMethod: c.verificationMethod })),
      projectB.acceptanceCriteriaItems,
    );

    const childRow = await prisma.session.findUniqueOrThrow({ where: { id: childId } });
    assert.equal(childRow.parentSessionId, parent, 'the child keeps where it came from');
    assert.equal(childRow.prompt, refusal.childSessionPrompt, 'its opening is the prompt, unchanged');
    assert.equal(
      (await prisma.project.findUniqueOrThrow({ where: { id: aId } })).coordinatorSessionId, parent,
      'the parent still coordinates the original Project',
    );
    assert.equal((await childrenOf(parent)).length, 1, 'one child');
    assert.equal((await titled(projectB.title)).length, 1, 'one Project');
    assert.equal(
      await prisma.conversationTurn.count({ where: { sessionId: childId } }), turnsAtOpening,
      'no session_send follows the create',
    );
  });

  await t.test('5. orchestration off: no child is opened, and the manual fallback records it', async () => {
    const other = await liveSession('another planner');
    const c = await projectCreate(other, { title: 'Project C' });
    await prisma.user.update({ where: { id: ownerId }, data: { preferences: { enableOrchestration: false } } });
    t.after(() => prisma.user.update({ where: { id: ownerId }, data: { preferences: {} } }).then(() => undefined));

    const projectD = { title: 'Project D', goal: 'A second body of work.' };
    const refused = await refusalOf(projectCreate(other, projectD));
    assert.deepEqual(refused.coordinatingProject, { id: uuidToBase62(toUuid(c.id as string)), title: 'Project C' });

    await assert.rejects(sessionCreate(other, refused.childSessionPrompt), (error) => {
      assert.ok(error instanceof ForbiddenException || error instanceof HttpException);
      return /orchestration is not enabled/.test(JSON.stringify((error as HttpException).getResponse()));
    });
    assert.equal((await childrenOf(other)).length, 0, 'a refused session_create opens nothing');
    assert.equal((await titled(projectD.title)).length, 0);

    // The user starts a session by hand and sends the prompt; that session records it.
    const manual = await liveSession('started by hand');
    const d = await projectCreate(manual, argumentsIn(refused.childSessionPrompt));
    assert.equal((await prisma.project.findUniqueOrThrow({ where: { id: toUuid(d.id as string) } })).coordinatorSessionId, manual);
    assert.equal((await prisma.project.findUniqueOrThrow({ where: { id: toUuid(c.id as string) } })).coordinatorSessionId, other);
  });
});
