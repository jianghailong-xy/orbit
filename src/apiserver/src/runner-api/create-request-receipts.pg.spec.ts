/**
 * project_create and session_create under a request id (create-request-receipts.ts, migration 0645),
 * against a real PostgreSQL and the real runner doors.
 *
 *   1. Concurrent deliveries of one named project_create create ONE Project, and every answer carries
 *      the same receipt; a later repeat (the first answer was lost after the commit) reads it back.
 *   2. A different request id from the same session is a new request: it creates a second Project,
 *      which gets a coordinator conversation of its own (one session coordinates one Project).
 *   3. The same id with another payload is refused (REQUEST_ID_REUSED), and creates nothing.
 *   4. Concurrent and serial repeats of one named session_create spawn ONE child Session.
 *   5. A 4xx refusal frees the id; a failure that may have written, or a holder whose lease ran out,
 *      leaves it UNKNOWN for good, and a repeat never runs the create again.
 *   6. With no request id nothing changes: two calls are two Projects.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/create-request-receipts.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { BadRequestException, HttpException, InternalServerErrorException } from '@nestjs/common';
import { JwtService } from '@nestjs/jwt';
import {
  type PrismaClient,
  type Runner,
  RunStatus,
  RunnerStatus,
  SessionDispatchOrigin,
  SessionRunSource,
} from '@prisma/client';
import { Client } from 'pg';
import { uuidToBase62 } from '@orbit/shared';

import { sha256 } from '../common/crypto.util';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { prismaClientFor } from '../prisma/prisma-client';
import { PrismaService } from '../prisma/prisma.service';
import { ProjectAcceptanceService } from '../projects/project-acceptance.service';
import { ProjectsService } from '../projects/projects.service';
import { SessionsService } from '../sessions/sessions.service';
import { CreateRequestReceipts, setCreateRequestReplayWaitForTest } from './create-request-receipts';
import { RunnerOrchestrationAuthorizer } from './runner-orchestration-authorizer';
import { RunnerProjectsController } from './runner-projects.controller';
import { RunnerSessionsController } from './runner-sessions.controller';

declare global {
  interface BigInt { toJSON(): string; }
}
BigInt.prototype.toJSON = function toJSON(this: bigint): string {
  return this.toString();
};

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

const silent = (): unknown =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

interface Receipted {
  id: string;
  requestReceipt?: { requestId: string; kind: string; resourceId: string | null; receivedAt: string; replayed: boolean };
}

function codeOf(error: unknown): string | undefined {
  if (!(error instanceof HttpException)) return undefined;
  const body = error.getResponse() as { code?: string };
  return body.code;
}

test('a named project_create or session_create is created once, and its repeats read the receipt', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });
  const db = prisma as unknown as PrismaService;

  const ownerId = randomUUID();
  const runnerId = randomUUID();
  const workspaceId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `create-receipts-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  await prisma.runner.create({
    data: {
      id: runnerId, ownerId, name: 'the machine', tokenHash: sha256(`token-${runnerId}`),
      status: RunnerStatus.ONLINE, lastHeartbeatAt: new Date(), capabilities: [], capabilitiesReportedAt: new Date(),
    },
  });
  await prisma.workspace.create({ data: { id: workspaceId, ownerId, runnerId, name: 'orbit', enabled: true } });
  const runner = { id: runnerId, ownerId } as Runner;

  async function liveSession(title: string): Promise<string> {
    const id = randomUUID();
    await prisma.session.create({
      data: {
        id, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title, prompt: title, provider: 'claude', providerBuiltin: true, engine: 'claude',
        status: RunStatus.RUNNING, startedAt: new Date(), runtimeSessionId: `runtime-${id}`,
        dispatchOrigin: SessionDispatchOrigin.USER, runSource: SessionRunSource.MANUAL,
      },
    });
    return id;
  }

  const sessions = new SessionsService(db, { notifySessionQueued: () => undefined } as never, silent() as never);
  const orchestration = new RunnerOrchestrationAuthorizer(db, new JwtService({ secret: 'create-receipts-pg' }));
  const receipts = new CreateRequestReceipts(db);
  const acceptance = new ProjectAcceptanceService(db);
  const projects = new ProjectsService(db, acceptance, sessions);
  const projectDoor = new RunnerProjectsController(
    projects, acceptance, {} as never, orchestration,
    undefined, undefined, undefined, undefined, receipts,
  );
  const sessionDoor = new RunnerSessionsController(
    sessions, orchestration, {} as never, { chargeSteer: async () => undefined } as never, undefined, undefined, receipts,
  );

  const projectCreate = (from: string | undefined, title: string, requestId?: string) =>
    projectDoor.createProject(runner, from, undefined, { title } as never, requestId) as Promise<Receipted>;
  const sessionCreate = async (parent: string, prompt: string, requestId?: string) =>
    sessionDoor.createSession(
      runner, undefined, parent, await orchestration.issue(runnerId, parent),
      { prompt, workspaceId, engine: 'claude' }, requestId,
    ) as Promise<Receipted>;
  const projectsTitled = (title: string) => prisma.project.findMany({ where: { ownerId, title } });

  await t.test('1. concurrent and serial repeats of one named project_create make one Project and one receipt', async () => {
    const from = await liveSession('planner');
    const requestId = `req-${randomUUID()}`;
    const answers = await Promise.all(Array.from({ length: 6 }, () => projectCreate(from, 'Receipt project', requestId)));
    const rows = await projectsTitled('Receipt project');
    assert.equal(rows.length, 1, 'six concurrent deliveries of one request are one Project');
    assert.equal(rows[0].coordinatorSessionId, from, 'and the calling session coordinates it');
    for (const answer of answers) {
      assert.equal(answer.id, rows[0].id);
      assert.deepEqual({ ...answer.requestReceipt, replayed: undefined }, {
        requestId, kind: 'PROJECT_CREATE', resourceId: uuidToBase62(rows[0].id),
        receivedAt: answers[0].requestReceipt!.receivedAt, replayed: undefined,
      });
    }
    assert.equal(answers.filter((answer) => !answer.requestReceipt!.replayed).length, 1, 'exactly one delivery created');

    // The answer to the first was lost after its commit: the caller asks again under the same id.
    const again = await projectCreate(from, 'Receipt project', requestId);
    assert.equal(again.id, rows[0].id);
    assert.equal(again.requestReceipt!.replayed, true);
    assert.equal(again.requestReceipt!.receivedAt, answers[0].requestReceipt!.receivedAt);
    assert.equal((await projectsTitled('Receipt project')).length, 1);

    // 2. A different request from the same session is a new Project with its own coordinator.
    const second = await projectCreate(from, 'Receipt project', `req-${randomUUID()}`);
    const both = await projectsTitled('Receipt project');
    assert.equal(both.length, 2, 'a new request id is a new request');
    const secondRow = both.find((row) => row.id === second.id)!;
    assert.ok(secondRow.coordinatorSessionId, 'the second Project has a coordinator');
    assert.notEqual(secondRow.coordinatorSessionId, from, 'one session coordinates one Project');

    // 3. One name, two requests.
    await assert.rejects(projectCreate(from, 'Another title', requestId), (error) => codeOf(error) === 'REQUEST_ID_REUSED');
    assert.equal((await projectsTitled('Another title')).length, 0);
    const otherCaller = await liveSession('another caller');
    await assert.rejects(projectCreate(otherCaller, 'Receipt project', requestId), (error) => codeOf(error) === 'REQUEST_ID_REUSED');
  });

  await t.test('4. concurrent and serial repeats of one named session_create spawn one child', async () => {
    const parent = await liveSession('parent');
    const requestId = `req-${randomUUID()}`;
    const answers = await Promise.all(Array.from({ length: 5 }, () => sessionCreate(parent, 'the sub-task', requestId)));
    const children = await prisma.session.findMany({ where: { parentSessionId: parent } });
    assert.equal(children.length, 1, 'five concurrent deliveries of one request are one child Session');
    for (const answer of answers) {
      assert.equal(answer.id, children[0].id);
      assert.equal(answer.requestReceipt!.resourceId, uuidToBase62(children[0].id));
      assert.equal(answer.requestReceipt!.receivedAt, answers[0].requestReceipt!.receivedAt);
    }
    const again = await sessionCreate(parent, 'the sub-task', requestId);
    assert.equal(again.id, children[0].id);
    assert.equal(again.requestReceipt!.replayed, true);
    await assert.rejects(sessionCreate(parent, 'a different sub-task', requestId), (error) => codeOf(error) === 'REQUEST_ID_REUSED');
    assert.equal(await prisma.session.count({ where: { parentSessionId: parent } }), 1);
    await sessionCreate(parent, 'the sub-task', `req-${randomUUID()}`);
    assert.equal(await prisma.session.count({ where: { parentSessionId: parent } }), 2, 'a new id is a new child');
  });

  await t.test('5. a refusal frees the id; a failure that may have written leaves it UNKNOWN', async () => {
    let calls = 0;
    const refusedId = `req-${randomUUID()}`;
    await assert.rejects(receipts.run(ownerId, 'PROJECT_CREATE', refusedId, { a: 1 }, async () => {
      calls += 1;
      throw new BadRequestException('refused');
    }), BadRequestException);
    const created = await receipts.run(ownerId, 'PROJECT_CREATE', refusedId, { a: 1 }, async () => {
      calls += 1;
      return { id: 'p1' };
    });
    assert.equal(calls, 2, 'the id was free again after a refusal that wrote nothing');
    assert.equal((created as Receipted).requestReceipt!.resourceId, 'p1');

    const brokenId = `req-${randomUUID()}`;
    await assert.rejects(receipts.run(ownerId, 'SESSION_CREATE', brokenId, { a: 1 }, async () => {
      calls += 1;
      throw new InternalServerErrorException('the connection died after the commit');
    }), InternalServerErrorException);
    const before = calls;
    await assert.rejects(
      receipts.run(ownerId, 'SESSION_CREATE', brokenId, { a: 1 }, async () => { calls += 1; return { id: 'dup' }; }),
      (error) => codeOf(error) === 'CREATE_REQUEST_OUTCOME_UNKNOWN',
    );
    assert.equal(calls, before, 'an UNKNOWN outcome never runs the create again');

    // A holder that died: its row is OPEN and past its lease.
    const deadId = `req-${randomUUID()}`;
    setCreateRequestReplayWaitForTest(300);
    let release!: () => void;
    const held = receipts.run(ownerId, 'SESSION_CREATE', deadId, { a: 1 }, () =>
      new Promise<{ id: string }>((resolve) => { release = () => resolve({ id: 's1' }); }));
    await new Promise((resolve) => setTimeout(resolve, 50));
    await assert.rejects(
      receipts.run(ownerId, 'SESSION_CREATE', deadId, { a: 1 }, async () => ({ id: 'dup' })),
      (error) => codeOf(error) === 'CREATE_REQUEST_IN_PROGRESS',
      'a repeat that outwaits a live holder is told to ask again under the same id',
    );
    await prisma.createRequestReceipt.updateMany({
      where: { ownerId, requestToken: deadId }, data: { leaseExpiresAt: new Date(Date.now() - 1_000) },
    });
    await assert.rejects(
      receipts.run(ownerId, 'SESSION_CREATE', deadId, { a: 1 }, async () => ({ id: 'dup' })),
      (error) => codeOf(error) === 'CREATE_REQUEST_OUTCOME_UNKNOWN',
    );
    release();
    await held;
    setCreateRequestReplayWaitForTest(10_000);
  });

  await t.test('6. with no request id a create is what it always was', async () => {
    const a = await projectCreate(undefined, 'Unnamed project');
    const b = await projectCreate(undefined, 'Unnamed project');
    assert.notEqual(a.id, b.id);
    assert.equal(a.requestReceipt, undefined);
    assert.equal((await projectsTitled('Unnamed project')).length, 2);
  });
});
