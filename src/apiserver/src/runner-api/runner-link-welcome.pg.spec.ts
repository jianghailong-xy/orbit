/**
 * What the runner link's Welcome says of a connecting process's sessions and release, end to end
 * (docs/runner-link-design.md §5.3, §5.4, §5.8, §7; runner-link-welcome.ts, runner-release-feed.ts).
 *
 * WHAT THIS DRIVES
 * ----------------
 * The real POST /runner/link/welcome and POST /runner/heartbeat behind the real RunnerAuthGuard, over a disposable
 * PostgreSQL, with main.ts's error boundaries, reached the way the link gateway reaches them: through the internal
 * listener, with the gateway's secret and the runner's link token (src/link-gateway/conn.go, heartbeat.go). Beside
 * them the same routes over HTTPS, and GET /runner/release as a runner asks it today. The events are stored by the real
 * ingest, over the link and over HTTPS, as runners store them. /dl is a local server standing in for the web container,
 * which answers, fails, or never answers.
 *
 * WHAT IT ASSERTS
 * ---------------
 *   (1) durableSeq is the highest seq up to which every one of the session's events is stored, counting from 1, a
 *       refused event's tombstone counting as stored: a batch past a hole moves it no further, nor does a seq that was
 *       never stored (a live event over HTTPS, a noise ping); a session whose first event is missing, and one with
 *       none, say 0.
 *   (2) leaseHeld is true for the process holding the session's inbox lease alone: false for a session leased to
 *       another process, ended, not a conversation, or not this runner's. A session that is not this runner's, an id
 *       that names nothing and a string that is no session id are answered alike: 0 and false. Each session asked
 *       about is answered once, in the order asked, as it was named.
 *   (3) Over HTTPS the answer is the same for the process the body names, and holds nothing without one; a link call
 *       is for the process its token was minted for, whatever the body says.
 *   (4) The release is the one GET /runner/release assigns this runner from what /dl publishes: in the welcome's
 *       answer and in a link heartbeat's linkHints, and in neither over HTTPS.
 *   (5) /dl not configured, failing, or not answering: no release, and the sessions answered all the same, at once.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/runner-link-welcome.pg.spec.ts
 *
 * Needs COORDINATOR_PG_URL (the script provides a disposable one). Not destructive: every id is generated by the run.
 */
