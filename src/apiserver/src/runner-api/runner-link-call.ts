/**
 * Runner link calls (docs/runner-link-design.md §5.6, §6.4): the runner routes, called by the link
 * gateway on behalf of a runner connected to it, through a listener only the gateway can reach.
 *
 * The routes and everything they decide are the ones HTTPS serves. What makes a call a link call is
 * the listener it arrives on (`listenForRunnerLinkCalls`), which takes only the gateway: its secret,
 * RUNNER_LINK_GATEWAY_TOKEN, in `Authorization`, as on the gateway's revocations route. The gateway
 * forwards each `Rpc` as an HTTP request:
 *
 *   X-Orbit-Runner-Link-Token  the link token the runner connected with (its newest refresh). It
 *                              names the runner and the process (`leaseOwner`, Hello.process_id);
 *                              RunnerAuthGuard checks it with the link's public key and reads the
 *                              runner by it, which must still hold the credential it was minted with.
 *   X-Orbit-Link-Request-Id    Rpc.request_id: a claim sent again under the same id answers the
 *                              session the first one claimed, not another (QueueService.trySessionClaim).
 *   X-Orbit-Link-Session-Id    Rpc.session_id and Rpc.after_seq: the call is handled only once that
 *   X-Orbit-Link-After-Seq     session's events are stored through after_seq (`assertAfterSeqStored`).
 *   X-Orbit-Link-Gateway-Id    the gateway node holding the runner's connection, which the heartbeat
 *                              records in the runner's presence.
 *
 * plus the headers Hello declared, which today's runner sends on every request (doVia,
 * src/runner-go/transport.go): capabilities, supported providers, OS, write contract, CLI version and
 * a managed runner's instance. A runner that disconnects has its calls cancelled by the gateway, which
 * closes them, so a route that watches its response close (the claim, the wake) sees it hang up exactly
 * as it does over HTTPS.
 *
 * What changes for a link call is what the protocol says (proto `Rpc`): the four routes that long-poll
 * over HTTPS — the claim, the inbox, the wake and an approval's decision — answer at once, as if asked
 * with `wait=0`, because a hint tells the runner when to ask; every error carries `code`, `retryable` and
 * a retry hint (common/runner-link-error.filter.ts); and the inbox hands a turn whose answer was lost back
 * to the process that leased it as soon as it says it is not running it (RunnerApiController.inbox).
 */

export const RUNNER_LINK_TOKEN_HEADER = 'x-orbit-runner-link-token';
export const LINK_REQUEST_ID_HEADER = 'x-orbit-link-request-id';
export const LINK_SESSION_ID_HEADER = 'x-orbit-link-session-id';
export const LINK_AFTER_SEQ_HEADER = 'x-orbit-link-after-seq';
export const LINK_GATEWAY_ID_HEADER = 'x-orbit-link-gateway-id';

/** What a link call says beyond the route's own request, as RunnerAuthGuard read it. */
export interface RunnerLinkContext {
  /** The process the link token was minted for: the `leaseOwner` its heartbeats carry. */
  leaseOwner: string;
  /** Rpc.request_id; null when the gateway forwarded none. */
  requestId: string | null;
  /** Rpc.session_id and Rpc.after_seq; null when the call depends on no session's events. */
  afterSeq: { sessionId: string; seq: number } | null;
  /** The gateway node that forwarded the call; null when it named none. */
  gatewayId?: string | null;
  /**
   * Set when RunnerAuthGuard left the caller's admission to the route (AdmitsLinkCallItself): the link token's
   * credential fingerprint and owner, which the route checks against the runner row before it writes anything.
   */
  admission?: { credential: string; ownerId: string };
}

/** The link call this request is, or undefined for one that came over HTTPS. */
export const CurrentRunnerLink = createParamDecorator(
  (_data: unknown, ctx: ExecutionContext): RunnerLinkContext | undefined =>
    ctx.switchToHttp().getRequest().runnerLink as RunnerLinkContext | undefined,
);

/** Generated by the runner, unique per runner (proto `Rpc.request_id`). */
const REQUEST_ID_RE = /^[A-Za-z0-9._:-]{1,128}$/;
/** `run_event.seq` is an int4: no event is ever stored past this. */
const MAX_SEQ = 2_147_483_647;

/** The gateway node's name, as the gateway sends it (its container's hostname). Anything else names none. */
const GATEWAY_ID_RE = /^[A-Za-z0-9._:-]{1,128}$/;

/** The gateway node that forwarded a call, or null. */
export function parseRunnerLinkGatewayId(headers: IncomingHttpHeaders): string | null {
  const value = single(headers[LINK_GATEWAY_ID_HEADER]);
  return value !== undefined && GATEWAY_ID_RE.test(value) ? value : null;
}

/** The link's own fields of a call: its request id and the events it waits for. */
export function parseRunnerLinkRequest(headers: IncomingHttpHeaders): Pick<RunnerLinkContext, 'requestId' | 'afterSeq'> {
  const requestId = single(headers[LINK_REQUEST_ID_HEADER]);
  if (requestId !== undefined && !REQUEST_ID_RE.test(requestId)) {
    throw new BadRequestException({
      code: 'RUNNER_LINK_BAD_REQUEST_ID',
      message: 'X-Orbit-Link-Request-Id is 1 to 128 letters, digits, dots, colons, underscores or hyphens.',
    });
  }
  const seqText = single(headers[LINK_AFTER_SEQ_HEADER]) ?? '';
  // 0 waits for nothing (proto `Rpc.after_seq`).
  if (seqText === '' || seqText === '0') return { requestId: requestId ?? null, afterSeq: null };
  const seq = /^[0-9]{1,10}$/.test(seqText) ? Number(seqText) : NaN;
  if (!(seq <= MAX_SEQ)) {
    throw new BadRequestException({
      code: 'RUNNER_LINK_BAD_AFTER_SEQ',
      message: `X-Orbit-Link-After-Seq is an event seq from 0 to ${MAX_SEQ}.`,
    });
  }
  const sessionText = single(headers[LINK_SESSION_ID_HEADER]) ?? '';
  let sessionId: string;
  try {
    sessionId = toUuid(sessionText);
  } catch {
    throw new BadRequestException({
      code: 'RUNNER_LINK_BAD_AFTER_SEQ',
      message: 'X-Orbit-Link-After-Seq needs X-Orbit-Link-Session-Id: the session whose events it counts.',
    });
  }
  return { requestId: requestId ?? null, afterSeq: { sessionId, seq } };
}

function single(value: string | string[] | undefined): string | undefined {
  return Array.isArray(value) ? value.join(', ') : value;
}

/** What a call waiting for events not yet stored is answered with. */
export const AFTER_SEQ_PENDING_CODE = 'RUNNER_LINK_AFTER_SEQ_PENDING';

/** How long it waits before it is sent again: a batch in flight is stored in milliseconds. */
export const AFTER_SEQ_RETRY_AFTER_MS = 250;

/**
 * Refuses, as retryable, a call that depends on events of `afterSeq.sessionId` up to `afterSeq.seq`
 * while they are not stored (§5.6: a turn completion is handled after its delivery receipt is stored).
 * Nothing waits here: the call is answered at once, and the gateway or the runner sends it again after
 * the hint. Refused before the route runs, so a call refused here changed nothing.
 *
 * "Stored through seq" is that the session has an event at or past it. Durable events are stored in
 * the order the runner numbers them, one batch after another, so the first of them at or past `seq`
 * stands for every one before it. An event the link refused counts too: a tombstone holds its seq
 * (link-events.ts). A noise ping is stored as nothing, so a call cannot wait for one; over the link a
 * runner sends none as a durable event.
 */
export async function assertAfterSeqStored(
  prisma: Pick<PrismaService, '$queryRaw'>,
  runnerId: string,
  afterSeq: { sessionId: string; seq: number },
): Promise<void> {
  const rows = await prisma.$queryRaw<Array<{ stored: boolean }>>`
    SELECT EXISTS (
      SELECT 1 FROM "run_event" e WHERE e."session_id" = s.id AND e."seq" >= ${afterSeq.seq}
    ) AS "stored"
    FROM "session" s
    WHERE s.id = ${afterSeq.sessionId}::uuid AND s."assigned_runner_id" = ${runnerId}::uuid
  `;
  if (rows.length === 0) throw new ForbiddenException('session does not belong to this runner');
  if (rows[0].stored) return;
  const body: Record<string, unknown> & RunnerLinkErrorFields = {
    statusCode: 503,
    error: 'Service Unavailable',
    code: AFTER_SEQ_PENDING_CODE,
    message: "This call waits for the session's events through after_seq, which are not all stored yet; the same call can be sent again.",
    afterSeq: afterSeq.seq,
    retryable: true,
    retryAfterMs: AFTER_SEQ_RETRY_AFTER_MS,
  };
  throw new HttpException(body, 503);
}

/** Where the internal listener binds unless RUNNER_LINK_INTERNAL_HOST says otherwise. */
export const RUNNER_LINK_INTERNAL_DEFAULT_HOST = '127.0.0.1';

/**
 * The internal listener's door: only the gateway, and only the runner routes. A request past it is
 * marked a link call and handed to the app, which serves it like any other.
 */
export function runnerLinkCallListener(config: RunnerLinkConfig, app: RequestListener): RequestListener {
  return (req, res) => {
    if (!(req.url ?? '').startsWith('/api/runner/')) {
      return refuse(res, 404, 'RUNNER_LINK_ROUTE_UNKNOWN', 'The runner link serves the runner routes under /api/runner/ only.');
    }
    if (!isRunnerLinkGateway(config, req.headers.authorization)) {
      return refuse(
        res,
        401,
        'RUNNER_LINK_GATEWAY_UNAUTHORIZED',
        'This listener answers the link gateway, which presents RUNNER_LINK_GATEWAY_TOKEN.',
      );
    }
    markRunnerLinkCall(req);
    app(req, res);
  };
}

function refuse(res: ServerResponse, status: number, code: string, message: string): void {
  const body = JSON.stringify({ statusCode: status, error: STATUS_CODES[status], code, message, retryable: false });
  res.writeHead(status, { 'content-type': 'application/json; charset=utf-8', 'content-length': Buffer.byteLength(body) });
  res.end(body);
}

/**
 * Opens the internal listener the link gateway calls the runner routes through (§6.4), beside the
 * public one, when RUNNER_LINK_INTERNAL_PORT is set and the link is on. It serves the same app, so a
 * link call runs the same guards, pipes, interceptors and handlers as an HTTPS request.
 *
 * It binds RUNNER_LINK_INTERNAL_HOST, 127.0.0.1 unless set: the gateway reaches it over the internal
 * network, never through the public entry. A setting that cannot be used leaves it closed and says why
 * once, and a link that is off opens nothing: the public listener is never stopped by the link.
 */
export async function listenForRunnerLinkCalls(
  app: INestApplication,
  settings: { port?: string; host?: string },
  log: Pick<Logger, 'log' | 'error'> = new Logger('RunnerLink'),
): Promise<Server | null> {
  const portText = settings.port?.trim() ?? '';
  if (portText === '') return null;
  const port = /^[0-9]{1,5}$/.test(portText) ? Number(portText) : NaN;
  if (!(port <= 65_535)) {
    log.error(`RUNNER_LINK_INTERNAL_PORT=${JSON.stringify(portText)} is not a port: runner link calls are not served`);
    return null;
  }
  const link = app.get<RunnerLinkState>(RUNNER_LINK, { strict: false });
  if (!link.config) {
    // Compose sets the port whether or not the link is on, so this is how a deployment without the link starts.
    log.log('runner link calls are not served: the runner link is off');
    return null;
  }
  const host = settings.host?.trim() || RUNNER_LINK_INTERNAL_DEFAULT_HOST;
  const server = createServer(runnerLinkCallListener(link.config, app.getHttpAdapter().getInstance()));
  try {
    await new Promise<void>((resolve, reject) => {
      server.once('error', reject);
      server.listen(port, host, () => {
        server.off('error', reject);
        resolve();
      });
    });
  } catch (error) {
    log.error(`runner link calls are not served: listening on ${host}:${port} failed (${(error as Error).message})`);
    return null;
  }
  log.log(`runner link calls are served on ${host}:${(server.address() as AddressInfo).port}`);
  return server;
}
