/**
 * A SubAgent's move to the next candidate after its account hit a limit (docs/subagent-design.md §4.3), through
 * POST /runner/sessions/:id/subagents/:runId/fallback on a real PostgreSQL. The list the run moves along is the
 * decision it opened with:
 *
 *   1. A usage-limit error on the first attempt moves the run to the tier's next candidate: the answer runs the
 *      child there, `subagent_run.attempts` holds two attempts — the first closed USAGE_LIMIT with the engine's
 *      words, the second RUNNING — and the Why gains "Moved to <model> after <model>'s account hit its limit".
 *   2. A second limit moves it once more; a third is refused SUBAGENT_FALLBACK_SPENT after 2 moves, and the
 *      run's end closes it FAILED.
 *   3. A plain failure is not moved (SUBAGENT_NOT_A_LIMIT_FAILURE): one attempt, closed with the run's end.
 *   4. No candidate left is NO_SUBAGENT_PROVIDER, listing each provider's reason.
 *   5. Another account's runner is answered as for an id that names nothing.
 *   6. An account pool is a fallback target: the run moves onto the pool's member with room, on that member's
 *      own credential, recorded on the attempt — and the parent session's pool fields are unchanged.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/subagent-fallback.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { type PrismaClient, type Runner, RunStatus, SessionDispatchOrigin } from '@prisma/client';
import type { SubagentAttempt, SubagentDecision } from '@orbit/shared';
import { ConflictException, NotFoundException } from '@nestjs/common';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { encryptSecret } from '../providers/provider-crypto';
import { prismaClientFor } from '../prisma/prisma-client';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { RunnerSubagentsController } from './runner-subagents.controller';
import { SubagentFallbackDto, SubagentRunCreateDto, SubagentRunUpdateDto } from './subagent-run';

const URL = process.env.COORDINATOR_PG_URL;
process.env.PROVIDER_SECRET_KEY ??= 'subagent-fallback-spec';
const skip = !URL;

const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

const create = (fields: Partial<SubagentRunCreateDto> & { toolUseId: string }): SubagentRunCreateDto =>
  Object.assign(new SubagentRunCreateDto(), { type: 'general', definitionSource: 'builtin', ...fields });
const fallback = (error: string): SubagentFallbackDto => Object.assign(new SubagentFallbackDto(), { error, readonly: false });
const update = (fields: Partial<SubagentRunUpdateDto>): SubagentRunUpdateDto => Object.assign(new SubagentRunUpdateDto(), fields);

const SESSION_LIMIT = "You've hit your session limit · resets 6:20pm (Europe/Berlin)";
const USAGE_LIMIT = "You've hit your usage limit. Visit https://chatgpt.com/codex/settings/usage to purchase more credits";
const WEEKLY_LIMIT = "You've hit your weekly limit · resets 1pm (Europe/Berlin)";

/** The refusal a call was answered with: its code and message. */
async function refused(call: Promise<unknown>): Promise<{ code: string; message: string }> {
  try {
    await call;
  } catch (error) {
    assert.ok(error instanceof ConflictException, `refused 409, got ${String(error)}`);
    return error.getResponse() as { code: string; message: string };
  }
  assert.fail('the call was not refused');
}

test('SubAgent quota fallback: moves, attempts, the reason, the bound and the refusals', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `fallback-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  // The parent's machine: Claude signed in with room left, Opus and Sonnet in its catalogue; nothing else installed.
  const runnerId = randomUUID();
  const runner = (await prisma.runner.create({
    data: {
      id: runnerId, name: 'the machine the parent runs on', ownerId, tokenHash: sha256(`fallback-${runnerId}`),
      planUsage: { claude: { fiveHour: { utilization: 10, resetsAt: new Date(Date.now() + 3_600_000).toISOString() } } },
      engines: [{ engine: 'claude', installed: true, auth: 'yes' }],
      modelCatalog: {
        claude: [
          { value: 'claude-opus-5-5', label: 'Opus 5.5', priority: 0 },
          { value: 'claude-sonnet-5-5', label: 'Sonnet 5.5', priority: 2 },
        ],
      },
    },
  })) as Runner;
  // Two metered keys on Claude Code, each with models of its own in tier M.
  const tag = runnerId.slice(-8);
  const first = `metered-a-${tag}`;
  const second = `metered-b-${tag}`;
  await prisma.modelProvider.createMany({
    data: [
      { slug: first, label: 'Metered A', runtime: 'claude', baseUrl: 'https://a.invalid/anthropic', apiKeyEnc: encryptSecret('sk-a'),
        models: [{ value: 'a-coder', label: 'A Coder', tier: 'M', outputPricePerMTok: 1 }], ownerId, position: 1 },
      { slug: second, label: 'Metered B', runtime: 'claude', baseUrl: 'https://b.invalid/anthropic', apiKeyEnc: encryptSecret('sk-b'),
        models: [{ value: 'b-coder', label: 'B Coder', tier: 'M', outputPricePerMTok: 2 }], ownerId, position: 2 },
    ],
  });
  t.after(async () => {
    await prisma.modelProvider.deleteMany({ where: { slug: { in: [first, second] } } });
  });
  const subagents = new RunnerSubagentsController(prisma as never, silent(), silent());

  async function parentSession() {
    const workspaceId = randomUUID();
    await prisma.workspace.create({
      data: { id: workspaceId, ownerId, runnerId, name: `orbit-worker-${workspaceId.slice(-8)}`, enabled: true, modelRoutingOptimizeFor: 'cost' },
    });
    const sessionId = randomUUID();
    await prisma.session.create({
      data: {
        id: sessionId, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title: 'fix the flaky test', prompt: 'fix the flaky test', provider: 'claude', engine: 'claude',
        model: 'claude-sonnet-5-5', effort: 'medium', status: RunStatus.AWAITING_INPUT, numTurns: 1,
        dispatchOrigin: SessionDispatchOrigin.USER, startsTaskWork: false,
      },
    });
    return sessionId;
  }
  const rowOf = async (runId: string) => {
    const row = await prisma.subagentRun.findUniqueOrThrow({ where: { id: runId } });
    return { ...row, attempts: row.attempts as unknown as SubagentAttempt[], decision: row.decision as unknown as SubagentDecision };
  };
  const brief = (a: SubagentAttempt) => [a.attempt, a.provider, a.engine, a.model, a.outcome];

  await t.test('a usage limit moves the run to the next candidate: two attempts and the reason', async () => {
    const sessionId = await parentSession();
    const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_limit_once', size: 'M' }));
    t.diagnostic(`decision pick ${opened.decision.provider}/${opened.decision.model}, fallbacks ${JSON.stringify(opened.decision.fallbacks)}`);
    assert.equal(opened.decision.provider, 'claude', 'Cost: the subscription first');
    assert.deepEqual(opened.decision.fallbacks?.map((f) => [f.provider, f.model]), [[first, 'a-coder'], [second, 'b-coder']],
      'the rest of tier M, cheapest first');
    assert.deepEqual((await rowOf(opened.runId)).attempts.map(brief), [[1, 'claude', 'claude', 'claude-sonnet-5-5', 'RUNNING']]);

    const moved = await subagents.nextSubagentCandidate(runner, sessionId, opened.runId, fallback(SESSION_LIMIT));
    t.diagnostic(`moved: attempt ${moved.attempt}, reason "${moved.reason}", exec ${moved.exec.provider}/${moved.exec.model}`);
    assert.equal(moved.attempt, 2);
    assert.equal(moved.reason, `Moved to a-coder on ${first} after claude-sonnet-5-5's account hit its limit`);
    assert.equal(moved.exec.provider, 'claude');
    assert.equal(moved.exec.model, 'a-coder');
    assert.equal(moved.exec.env?.ANTHROPIC_BASE_URL, 'https://a.invalid/anthropic', "the next candidate's own credential");

    const row = await rowOf(opened.runId);
    t.diagnostic(`subagent_run.attempts ${JSON.stringify(row.attempts)}`);
    t.diagnostic(`subagent_run.decision.reasons ${JSON.stringify(row.decision.reasons)}`);
    assert.deepEqual(row.attempts.map(brief), [
      [1, 'claude', 'claude', 'claude-sonnet-5-5', 'USAGE_LIMIT'],
      [2, first, 'claude', 'a-coder', 'RUNNING'],
    ]);
    assert.equal(row.attempts[0].error, SESSION_LIMIT);
    assert.equal(row.decision.reasons.at(-1), `Moved to a-coder on ${first} after claude-sonnet-5-5's account hit its limit`);
    assert.deepEqual(row.decision.moves, [moved.reason], 'the Why line carries the move');
    assert.equal(row.decision.runModel, 'a-coder', 'the block names the model it now runs on');

    await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({ status: 'DONE', resultSummary: 'fixed' }));
    assert.deepEqual((await rowOf(opened.runId)).attempts.map((a) => a.outcome), ['USAGE_LIMIT', 'DONE']);
  });

  await t.test('a third limit in a row is refused after 2 moves, and the run ends FAILED', async () => {
    const sessionId = await parentSession();
    const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_limit_thrice', size: 'M' }));
    const one = await subagents.nextSubagentCandidate(runner, sessionId, opened.runId, fallback(SESSION_LIMIT));
    const two = await subagents.nextSubagentCandidate(runner, sessionId, opened.runId, fallback(USAGE_LIMIT));
    assert.deepEqual([one.attempt, two.attempt], [2, 3]);
    assert.equal(two.reason, `Moved to b-coder on ${second} after a-coder's account hit its limit`);
    const spent = await refused(subagents.nextSubagentCandidate(runner, sessionId, opened.runId, fallback(WEEKLY_LIMIT)));
    t.diagnostic(`third limit: ${spent.code}: ${spent.message}`);
    assert.equal(spent.code, 'SUBAGENT_FALLBACK_SPENT');
    assert.match(spent.message, /moved 2 times/);
    await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({ status: 'FAILED', resultSummary: spent.message }));
    const row = await rowOf(opened.runId);
    t.diagnostic(`subagent_run.attempts ${JSON.stringify(row.attempts.map(brief))}`);
    assert.equal(row.status, 'FAILED');
    assert.deepEqual(row.attempts.map(brief), [
      [1, 'claude', 'claude', 'claude-sonnet-5-5', 'USAGE_LIMIT'],
      [2, first, 'claude', 'a-coder', 'USAGE_LIMIT'],
      [3, second, 'claude', 'b-coder', 'USAGE_LIMIT'],
    ]);
  });

  await t.test('a plain failure is not moved: one attempt, closed by the run\'s end', async () => {
    const sessionId = await parentSession();
    const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_plain', size: 'M' }));
    const plain = await refused(subagents.nextSubagentCandidate(runner, sessionId, opened.runId, fallback('API Error: 400 invalid_request_error')));
    t.diagnostic(`plain failure: ${plain.code}: ${plain.message}`);
    assert.equal(plain.code, 'SUBAGENT_NOT_A_LIMIT_FAILURE');
    await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({ status: 'FAILED', resultSummary: 'API Error: 400' }));
    const row = await rowOf(opened.runId);
    assert.deepEqual(row.attempts.map(brief), [[1, 'claude', 'claude', 'claude-sonnet-5-5', 'FAILED']]);
    assert.equal(row.decision.reasons.some((r) => r.startsWith('Moved to')), false);
  });

  await t.test('another account\'s runner is answered as for an id that names nothing', async () => {
    const sessionId = await parentSession();
    const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_foreign', size: 'M' }));
    const otherOwner = randomUUID();
    await prisma.user.create({ data: { id: otherOwner, email: `other-${otherOwner}@runner-door.invalid`, name: 'Someone else', passwordHash: 'x' } });
    const other = (await prisma.runner.create({
      data: { id: randomUUID(), name: 'another account', ownerId: otherOwner, tokenHash: sha256(`other-${otherOwner}`) },
    })) as Runner;
    await assert.rejects(subagents.nextSubagentCandidate(other, sessionId, opened.runId, fallback(SESSION_LIMIT)), NotFoundException);
    assert.equal((await rowOf(opened.runId)).attempts.length, 1, 'nothing was written');
  });

  await t.test('no candidate left: NO_SUBAGENT_PROVIDER with each provider\'s reason', async () => {
    await prisma.user.update({ where: { id: ownerId }, data: { preferences: { subagentBlockedProviders: [first, second] } } });
    const sessionId = await parentSession();
    const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_empty', size: 'M' }));
    const none = await refused(subagents.nextSubagentCandidate(runner, sessionId, opened.runId, fallback(SESSION_LIMIT)));
    t.diagnostic(`empty pool: ${none.code}: ${none.message}`);
    assert.equal(none.code, 'NO_SUBAGENT_PROVIDER');
    assert.match(none.message, /^No provider is left to run this SubAgent in tier M\. Each provider's reason:/);
    assert.match(none.message, /- claude \(claude\), claude-sonnet-5-5: the account hit its limit/);
    assert.ok(none.message.includes(`- ${first}: Blocked in the SubAgents settings`));
    assert.ok(none.message.includes(`- ${second}: Blocked in the SubAgents settings`));
    assert.deepEqual((await rowOf(opened.runId)).attempts.map((a) => a.outcome), ['USAGE_LIMIT']);
  });

  await t.test("an account pool is a fallback target: its member's credential, recorded on the attempt, never on the parent", async () => {
    await prisma.user.update({ where: { id: ownerId }, data: { preferences: { subagentBlockedProviders: [first, second] } } });
    const member = await prisma.modelProvider.create({
      data: { slug: `dana-${tag}`, label: 'Dana', runtime: 'claude', baseUrl: 'https://api.anthropic.com',
        apiKeyEnc: encryptSecret(`sk-ant-oat01-dana-${tag}`), models: [], ownerId },
    });
    const pool = await prisma.providerPool.create({ data: { slug: `crew-${tag}`, label: 'Crew', ownerId, engine: 'claude' } });
    await prisma.providerPoolMember.create({ data: { poolId: pool.id, providerId: member.id, ownerId } });
    t.after(async () => {
      await prisma.providerPool.deleteMany({ where: { id: pool.id } });
      await prisma.modelProvider.deleteMany({ where: { id: member.id } });
    });
    // Dana's account has half its quota left: ranked after the runner's own sign-in at 10% used.
    const resetsAt = new Date(Date.now() + 3_600_000).toISOString();
    const planUsage = {
      snapshot: (row: { id: string }) => (row.id === member.id ? { fiveHour: { utilization: 50, resetsAt } } : null),
      usageStanding: () => null,
    };
    const withPools = new RunnerSubagentsController(prisma as never, silent(), planUsage as never);
    const sessionId = await parentSession();
    const poolFields = { poolMemberProviderId: true, poolKeyId: true, poolCodexAccountId: true, poolSwitchNotice: true, provider: true } as const;
    const before = await prisma.session.findUniqueOrThrow({ where: { id: sessionId }, select: poolFields });
    const opened = await withPools.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_to_pool', size: 'M' }));
    assert.equal(opened.decision.provider, 'claude', 'the sign-in first, with more room');
    assert.deepEqual(opened.decision.fallbacks?.map((f) => f.provider), [pool.slug], 'then the pool');
    const moved = await withPools.nextSubagentCandidate(runner, sessionId, opened.runId, fallback(SESSION_LIMIT));
    t.diagnostic(`moved to the pool: ${moved.reason}; env names ${JSON.stringify(Object.keys(moved.exec.env ?? {}))}`);
    assert.equal(moved.attempt, 2);
    assert.ok(Object.values(moved.exec.env ?? {}).includes(`sk-ant-oat01-dana-${tag}`), "on Dana's own credential");
    const row = await rowOf(opened.runId);
    assert.deepEqual(row.attempts.map(brief), [
      [1, 'claude', 'claude', 'claude-sonnet-5-5', 'USAGE_LIMIT'],
      [2, pool.slug, 'claude', 'claude-sonnet-5-5', 'RUNNING'],
    ]);
    assert.deepEqual((row.attempts[1] as SubagentAttempt).poolMember, { providerId: member.id, label: 'Dana' });
    assert.deepEqual(await prisma.session.findUniqueOrThrow({ where: { id: sessionId }, select: poolFields }), before,
      "the parent session's pool fields are unchanged");
  });
});
