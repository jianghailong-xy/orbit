/**
 * SubAgent runs through the runner doors (docs/subagent-design.md §5.1, §6.1, §6.2), on a real PostgreSQL:
 *
 *   1. POST /runner/sessions/:id/subagents opens a run on the parent's own engine and model (not routed
 *      yet), PATCH …/:runId ends it DONE, and the one `subagent_run` row holds what was posted, the status,
 *      the changed files — while the parent's `cost_usd` rises by exactly the run's cost, once.
 *   2. The fifth POST on a session with four RUNNING is refused, and a POST for an agent with SubAgents
 *      turned off is refused.
 *   3. A top-level `mcp__orbit__delegate` tool_use joins `runningSubagents`, its `{ runId, status: "running" }`
 *      receipt leaves it there, and its terminal background_task removes it.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/subagent-run.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { type PrismaClient, type Runner, RunStatus, SessionDispatchOrigin } from '@prisma/client';
import { RunEventType } from '@orbit/shared';
import { ConflictException, ForbiddenException, NotFoundException } from '@nestjs/common';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { prismaClientFor } from '../prisma/prisma-client';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { RunnerApiController } from './runner-api.controller';
import { RunnerSubagentsController } from './runner-subagents.controller';
import { SUBAGENT_NOT_ROUTED_REASON, SubagentRunCreateDto, SubagentRunUpdateDto } from './subagent-run';

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

/** A collaborator whose every method answers nothing: the broadcasts the handler fires. */
const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

const create = (fields: Partial<SubagentRunCreateDto> & { toolUseId: string }): SubagentRunCreateDto =>
  Object.assign(new SubagentRunCreateDto(), { type: 'general', definitionSource: 'builtin', ...fields });

const update = (fields: Partial<SubagentRunUpdateDto>): SubagentRunUpdateDto =>
  Object.assign(new SubagentRunUpdateDto(), fields);

test('SubAgent runs: the row, the cost roll-up, the refusals and runningSubagents', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  const runnerId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `subagent-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  const runner = (await prisma.runner.create({
    data: { id: runnerId, name: 'the machine the parent runs on', ownerId, tokenHash: sha256(`subagent-${runnerId}`) },
  })) as Runner;
  const door = new RunnerApiController(prisma as never, silent(), silent(), silent(), silent(), silent());
  const subagents = new RunnerSubagentsController(prisma as never, silent());

  /** A live parent session of that runner, under an agent with SubAgents on or off. */
  async function parentSession(opts: { subagentsEnabled?: boolean; costUsd?: number } = {}) {
    const workspaceId = randomUUID();
    await prisma.workspace.create({
      data: {
        id: workspaceId, ownerId, runnerId, name: `orbit-worker-${workspaceId.slice(-8)}`, enabled: true,
        ...(opts.subagentsEnabled === undefined ? {} : { subagentsEnabled: opts.subagentsEnabled }),
      },
    });
    const sessionId = randomUUID();
    await prisma.session.create({
      data: {
        id: sessionId, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title: 'split the parser work', prompt: 'split the parser work', provider: 'claude', engine: 'claude',
        model: 'claude-opus-5-5', effort: 'high', status: RunStatus.AWAITING_INPUT, numTurns: 1,
        dispatchOrigin: SessionDispatchOrigin.USER, startsTaskWork: false, costUsd: opts.costUsd ?? 0,
      },
    });
    return sessionId;
  }

  await t.test('POST then PATCH DONE: one row with the posted fields, and the parent cost raised by exactly 0.12', async () => {
    const sessionId = await parentSession({ costUsd: 1.37 });
    const before = (await prisma.session.findUniqueOrThrow({ where: { id: sessionId } })).costUsd;

    const opened = await subagents.createSubagentRun(runner, sessionId, create({
      toolUseId: 'toolu_01DelegateParser',
      type: 'explore',
      definitionSource: '.claude/agents/explore.md',
      background: true,
      size: 'M',
      sizeReason: 'a read-only sweep of one package',
    }));
    assert.equal(opened.status, 'RUNNING');
    assert.equal(opened.decision.tierSource, 'not-routed');
    assert.deepEqual(opened.decision.reasons, [SUBAGENT_NOT_ROUTED_REASON]);
    assert.equal(opened.decision.level, 'M');
    assert.equal(opened.exec.provider, 'claude', "the target is the parent's own engine");
    assert.equal(opened.exec.model, 'claude-opus-5-5', "and the parent's own model");
    assert.equal(opened.exec.effort, 'high', "and the parent's own effort");
    assert.ok(Array.isArray(opened.exec.allowedTools) && Array.isArray(opened.exec.disallowedTools),
      'in the shape a claim hands the runner');

    const retried = await subagents.createSubagentRun(runner, sessionId, create({
      toolUseId: 'toolu_01DelegateParser', type: 'explore', definitionSource: '.claude/agents/explore.md',
    }));
    assert.equal(retried.runId, opened.runId, 'a retried POST answers with the run it opened');

    const ended = await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({
      status: 'DONE',
      resultSummary: 'The parser splits into lexer.ts and grammar.ts.',
      changedFiles: ['src/parser/lexer.ts', 'src/parser/grammar.ts'],
      costUsd: 0.12,
      usage: { inputTokens: 1200, outputTokens: 340 },
    }));
    assert.deepEqual(ended, { runId: opened.runId, status: 'DONE', applied: true });

    const rows = await prisma.subagentRun.findMany({ where: { sessionId } });
    assert.equal(rows.length, 1, 'one subagent_run row');
    const [row] = rows;
    assert.equal(row.id, opened.runId);
    assert.equal(row.ownerId, ownerId);
    assert.equal(row.toolUseId, 'toolu_01DelegateParser');
    assert.equal(row.type, 'explore');
    assert.equal(row.definitionSource, '.claude/agents/explore.md');
    assert.equal(row.background, true);
    assert.equal(row.status, 'DONE');
    assert.deepEqual(row.changedFiles, ['src/parser/lexer.ts', 'src/parser/grammar.ts']);
    assert.equal(row.resultSummary, 'The parser splits into lexer.ts and grammar.ts.');
    assert.equal(row.costUsd, 0.12);
    assert.deepEqual(row.usage, { inputTokens: 1200, outputTokens: 340 });
    assert.ok(row.endedAt instanceof Date, 'ended_at is set');
    assert.equal((row.decision as { tierSource?: string }).tierSource, 'not-routed');

    const after = (await prisma.session.findUniqueOrThrow({ where: { id: sessionId } })).costUsd;
    assert.equal(after, before + 0.12, 'the parent cost_usd rose by exactly 0.12');

    const repeated = await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({ status: 'DONE', costUsd: 0.12 }));
    assert.equal(repeated.applied, false, 'a repeated report changes nothing');
    assert.equal((await prisma.session.findUniqueOrThrow({ where: { id: sessionId } })).costUsd, after,
      'and adds no cost again');
  });

  await t.test('the fifth concurrent POST is refused once four are RUNNING, and a disabled agent is refused', async () => {
    const sessionId = await parentSession();
    for (let i = 1; i <= 4; i++) {
      const run = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: `toolu_01Parallel${i}`, background: true }));
      assert.equal(run.status, 'RUNNING');
    }
    await assert.rejects(
      subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_01Parallel5', background: true })),
      (e: unknown) =>
        e instanceof ConflictException &&
        (e.getResponse() as { code?: string }).code === 'SUBAGENT_LIMIT_REACHED',
      'the fifth is refused while four run',
    );
    assert.equal(await prisma.subagentRun.count({ where: { sessionId } }), 4, 'and wrote no row');

    const disabled = await parentSession({ subagentsEnabled: false });
    await assert.rejects(
      subagents.createSubagentRun(runner, disabled, create({ toolUseId: 'toolu_01Disabled' })),
      (e: unknown) =>
        e instanceof ForbiddenException && (e.getResponse() as { code?: string }).code === 'SUBAGENTS_DISABLED',
      'an agent with subagentsEnabled = false is refused',
    );
    assert.equal(await prisma.subagentRun.count({ where: { sessionId: disabled } }), 0);
  });

  await t.test("another account's machine is answered as for an id that names nothing, and writes nothing", async () => {
    const sessionId = await parentSession({ costUsd: 2 });
    const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_01Theirs' }));
    const strangerId = randomUUID();
    await prisma.user.create({
      data: { id: strangerId, email: `subagent-${strangerId}@runner-door.invalid`, name: 'Someone else', passwordHash: 'x' },
    });
    const stranger = (await prisma.runner.create({
      data: { id: randomUUID(), name: "someone else's machine", ownerId: strangerId, tokenHash: sha256(`stranger-${strangerId}`) },
    })) as Runner;
    const notFound = (e: unknown) => e instanceof NotFoundException;
    await assert.rejects(subagents.createSubagentRun(stranger, sessionId, create({ toolUseId: 'toolu_01Stranger' })), notFound);
    await assert.rejects(subagents.createSubagentRun(stranger, randomUUID(), create({ toolUseId: 'toolu_01Nobody' })), notFound,
      'the same answer as for a session that does not exist');
    await assert.rejects(
      subagents.updateSubagentRun(stranger, sessionId, opened.runId, update({ status: 'DONE', costUsd: 5 })), notFound);
    const row = await prisma.subagentRun.findUniqueOrThrow({ where: { id: opened.runId } });
    assert.equal(row.status, 'RUNNING', 'the run is untouched');
    assert.equal(await prisma.subagentRun.count({ where: { sessionId } }), 1, 'no row of the stranger was written');
    assert.equal((await prisma.session.findUniqueOrThrow({ where: { id: sessionId } })).costUsd, 2, 'and no cost was added');
  });

  await t.test('a top-level delegate tool_use joins runningSubagents and its terminal background_task removes it', async () => {
    const sessionId = await parentSession();
    let seq = 0;
    const leaseOwner = randomUUID();
    await door.takeoverLeases(runner, sessionId, { leaseOwner, expectedLeaseOwner: null } as never);
    const report = (events: Array<{ type: RunEventType; payload: unknown }>) =>
      door.events(runner, sessionId, {
        leaseOwner,
        events: events.map((event) => ({ ...event, seq: ++seq, ts: new Date().toISOString() })) as never,
      });
    const running = async () =>
      (await prisma.session.findUniqueOrThrow({ where: { id: sessionId }, select: { runningSubagents: true } }))
        .runningSubagents;

    await report([
      { type: RunEventType.TOOL_USE, payload: {
        id: 'toolu_01DelegateBg', name: 'mcp__orbit__delegate',
        input: { description: 'Sweep the parser', prompt: 'Read src/parser and report', background: true } } },
    ]);
    assert.deepEqual(await running(), ['toolu_01DelegateBg'], 'the delegate call joins runningSubagents');

    await report([
      { type: RunEventType.TOOL_RESULT, payload: {
        toolUseId: 'toolu_01DelegateBg', content: [{ type: 'text', text: '{"runId":"r1","status":"running"}' }] } },
    ]);
    assert.deepEqual(await running(), ['toolu_01DelegateBg'], 'its launch receipt leaves it running');

    await report([
      { type: RunEventType.BACKGROUND_TASK, payload: {
        status: 'completed', toolUseId: 'toolu_01DelegateBg', summary: 'SubAgent finished' } },
    ]);
    assert.deepEqual(await running(), [], 'its terminal background_task removes it');
  });
});
