/**
 * A SubAgent's move after its account refused it (docs/routing-account-health-design.md §7.3, §6.5, phase 2 of §10),
 * through POST /runner/sessions/:id/subagents/:runId/fallback on a real PostgreSQL:
 *
 *   1. An account that needs action (ACCOUNT_ACTION_REQUIRED, as the engine adapter classified it) moves the run to
 *      the tier's next candidate: the attempt closes ACCOUNT_ACTION_REQUIRED with the engine's words, and the Why
 *      gains "Moved to <model> after <model>'s account needed action". ACCESS_DENIED moves the same way, an
 *      unclassified failure the runner measured as refused at admission as "… could not start", and the two-move
 *      bound still holds.
 *   2. On a model the caller named, none of these moves (SUBAGENT_NAMED_MODEL_NOT_MOVED); the attempt is recorded.
 *   3. An unclassified failure that did some work, or one that reads as a dropped connection, is not moved.
 *   4. Trials (§6.5): a move onto a candidate whose account is due its trial claims it for the run; another run
 *      that reaches it while claimed skips it; the refused trial takes the next trip, releases the claim and is not
 *      one of the two moves.
 *   5. A run that opens on a due trial claims it at once; a run that ends before admission releases it, and one
 *      that succeeds clears the account.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/subagent-account-move.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { type PrismaClient, type Runner, SessionDispatchOrigin } from '@prisma/client';
import { RunStatus } from '@orbit/shared';
import { RunFailureKind, type SubagentAttempt, type SubagentDecision } from '@orbit/shared';
import { ConflictException } from '@nestjs/common';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { encryptSecret } from '../providers/provider-crypto';
import { AccountHealthService } from '../providers/account-health.service';
import { prismaClientFor } from '../prisma/prisma-client';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { RunnerSubagentsController } from './runner-subagents.controller';
import { SubagentFallbackDto, SubagentRunCreateDto, SubagentRunUpdateDto } from './subagent-run';

const URL = process.env.COORDINATOR_PG_URL;
process.env.PROVIDER_SECRET_KEY ??= 'subagent-account-move-spec';
const skip = !URL;

const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

const create = (fields: Partial<SubagentRunCreateDto> & { toolUseId: string }): SubagentRunCreateDto =>
  Object.assign(new SubagentRunCreateDto(), { type: 'general', definitionSource: 'builtin', ...fields });
const fallback = (error: string, more: Partial<SubagentFallbackDto> = {}): SubagentFallbackDto =>
  Object.assign(new SubagentFallbackDto(), { error, readonly: false, ...more });
const classified = (kind: RunFailureKind, said: string): SubagentFallbackDto =>
  fallback(said, { failure: { kind, said }, admission: true });
const update = (fields: Partial<SubagentRunUpdateDto>): SubagentRunUpdateDto => Object.assign(new SubagentRunUpdateDto(), fields);

const CURSOR_PAYMENT = 'Add a payment method to continue.';
const NOT_IN_PLAN = 'This model is not available on your plan.';
const UNMAPPED = 'Upgrade your plan to keep going';
const SESSION_LIMIT = "You've hit your session limit · resets 6:20pm (Europe/Berlin)";

/** The refusal a call was answered with: its code and message. */
async function refused(call: Promise<unknown>): Promise<{ code: string; message: string }> {
  try {
    await call;
  } catch (error) {
    assert.ok(error instanceof ConflictException, `refused 409, got ${String(error)}`);
    return error.getResponse() as { code: string; message: string };
  }
  assert.fail('the call was not refused');
}

test('SubAgent moves on an account refusal: outcomes, the Why line, named models and trials', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `account-move-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x',
      preferences: { optimizeFor: 'cost' } },
  });
  // The parent's machine: Claude signed in with room left; three metered keys of tier M on Claude Code (as in
  // subagent-fallback.pg.spec.ts), so Cost picks the subscription and then the keys, cheapest first.
  const runnerId = randomUUID();
  const runner = (await prisma.runner.create({
    data: {
      id: runnerId, name: 'the machine the parent runs on', ownerId, tokenHash: sha256(`account-move-${runnerId}`),
      planUsage: { claude: { fiveHour: { utilization: 10, resetsAt: new Date(Date.now() + 3_600_000).toISOString() } } },
      engines: [{ engine: 'claude', installed: true, auth: 'yes' }],
      modelCatalog: {
        claude: [
          { value: 'claude-opus-5-5', label: 'Opus 5.5', priority: 0 },
          { value: 'claude-sonnet-5-5', label: 'Sonnet 5.5', priority: 2 },
        ],
      },
    },
  })) as Runner;
  const tag = runnerId.slice(-8);
  const first = `metered-a-${tag}`;
  const second = `metered-b-${tag}`;
  const third = `metered-c-${tag}`;
  await prisma.modelProvider.createMany({
    data: [
      { slug: first, label: 'Metered A', runtime: 'claude', baseUrl: 'https://a.invalid/anthropic', apiKeyEnc: encryptSecret('sk-a'),
        models: [{ value: 'a-coder', label: 'A Coder', outputPricePerMTok: 1 }], modelTiers: { 'a-coder': 'M' }, ownerId, position: 1 },
      { slug: second, label: 'Metered B', runtime: 'claude', baseUrl: 'https://b.invalid/anthropic', apiKeyEnc: encryptSecret('sk-b'),
        models: [{ value: 'b-coder', label: 'B Coder', outputPricePerMTok: 2 }], modelTiers: { 'b-coder': 'M' }, ownerId, position: 2 },
      { slug: third, label: 'Metered C', runtime: 'claude', baseUrl: 'https://c.invalid/anthropic', apiKeyEnc: encryptSecret('sk-c'),
        models: [{ value: 'c-coder', label: 'C Coder', outputPricePerMTok: 3 }], modelTiers: { 'c-coder': 'M' }, ownerId, position: 3 },
    ],
  });
  const firstId = (await prisma.modelProvider.findFirstOrThrow({ where: { slug: first, ownerId }, select: { id: true } })).id;
  const firstKey = `provider:${firstId}`;
  t.after(async () => {
    await prisma.modelProvider.deleteMany({ where: { slug: { in: [first, second, third] } } });
  });
  const health = new AccountHealthService(prisma as never);
  const subagents = new RunnerSubagentsController(prisma as never, silent(), silent(), undefined, undefined, health);

  async function parentSession() {
    const workspaceId = randomUUID();
    await prisma.workspace.create({
      data: { id: workspaceId, ownerId, runnerId, name: `orbit-worker-${workspaceId.slice(-8)}`, enabled: true },
    });
    const sessionId = randomUUID();
    await prisma.session.create({
      data: {
        id: sessionId, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title: 'fix the flaky test', prompt: 'fix the flaky test', provider: 'claude', engine: 'claude',
        model: 'claude-sonnet-5-5', effort: 'medium', turnState: null, numTurns: 1,
        dispatchOrigin: SessionDispatchOrigin.USER, startsTaskWork: false,
      },
    });
    return sessionId;
  }
  const rowOf = async (runId: string) => {
    const row = await prisma.subagentRun.findUniqueOrThrow({ where: { id: runId } });
    return {
      ...row,
      attempts: row.attempts as unknown as Array<SubagentAttempt & { trialOf?: string }>,
      decision: row.decision as unknown as SubagentDecision,
    };
  };
  const brief = (a: SubagentAttempt) => [a.attempt, a.provider, a.model, a.outcome];
  /** Every health row the moves wrote is forgotten: each case starts from healthy accounts. */
  const forgetHealth = () => prisma.accountHealth.deleteMany({ where: { ownerId } });
  /** Metered A's account was blocked after a refusal and its block has just run out: its trial is due. */
  const trialDue = async () => {
    await prisma.accountHealth.deleteMany({ where: { ownerId, subjectKey: firstKey } });
    const past = new Date(Date.now() - 60_000);
    await prisma.accountHealth.create({
      data: {
        ownerId, subjectKey: firstKey, scopeModel: '', providerId: firstId, state: 'BLOCKED', kind: 'ACCOUNT_ACTION_REQUIRED',
        said: CURSOR_PAYMENT, trips: 1, firstAt: new Date(Date.now() - 3_700_000), lastAt: new Date(Date.now() - 3_700_000),
        blockedUntil: past,
      },
    });
  };
  const firstHealth = () => prisma.accountHealth.findFirst({ where: { ownerId, subjectKey: firstKey, scopeModel: '' }, orderBy: { createdAt: 'desc' } });

  await t.test('an account that needs action moves the run: ACCOUNT_ACTION_REQUIRED, the Why line, then the bound', async () => {
    await forgetHealth();
    const sessionId = await parentSession();
    const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_account_action', size: 'M' }));
    assert.equal(opened.decision.provider, 'claude', 'Cost: the subscription first');
    const moved = await subagents.nextSubagentCandidate(runner, sessionId, opened.runId,
      classified(RunFailureKind.ACCOUNT_ACTION_REQUIRED, CURSOR_PAYMENT));
    t.diagnostic(`moved: attempt ${moved.attempt}, reason "${moved.reason}"`);
    assert.equal(moved.attempt, 2);
    assert.equal(moved.reason, `Moved to a-coder on ${first} after claude-sonnet-5-5's account needed action`);
    assert.equal(moved.exec.model, 'a-coder');
    const denied = await subagents.nextSubagentCandidate(runner, sessionId, opened.runId,
      classified(RunFailureKind.ACCESS_DENIED, NOT_IN_PLAN));
    assert.equal(denied.reason, `Moved to b-coder on ${second} after a-coder's account needed action`);
    const spent = await refused(subagents.nextSubagentCandidate(runner, sessionId, opened.runId, fallback(UNMAPPED, { admission: true })));
    t.diagnostic(`third refusal: ${spent.code}: ${spent.message}`);
    assert.equal(spent.code, 'SUBAGENT_FALLBACK_SPENT', 'still at most 2 moves');
    const row = await rowOf(opened.runId);
    t.diagnostic(`subagent_run.attempts ${JSON.stringify(row.attempts.map(brief))}`);
    assert.deepEqual(row.attempts.map(brief), [
      [1, 'claude', 'claude-sonnet-5-5', 'ACCOUNT_ACTION_REQUIRED'],
      [2, first, 'a-coder', 'ACCESS_DENIED'],
      [3, second, 'b-coder', 'ADMISSION_FAILED'],
    ]);
    assert.equal(row.attempts[0].error, CURSOR_PAYMENT, "the attempt keeps the engine's words");
    assert.deepEqual(row.decision.moves, [moved.reason, denied.reason], 'the Why line carries both moves');
  });

  await t.test('an unclassified refusal at admission moves as "could not start"; one that did work, or a dropped connection, does not', async () => {
    await forgetHealth();
    const sessionId = await parentSession();
    const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_admission', size: 'M' }));
    const worked = await refused(subagents.nextSubagentCandidate(runner, sessionId, opened.runId, fallback(UNMAPPED, { admission: false })));
    assert.equal(worked.code, 'SUBAGENT_NOT_A_LIMIT_FAILURE');
    const other = await parentSession();
    const second_ = await subagents.createSubagentRun(runner, other, create({ toolUseId: 'toolu_admission_2', size: 'M' }));
    const edge = await refused(subagents.nextSubagentCandidate(runner, other, second_.runId,
      fallback('Failed to authenticate. API Error: 403 Attention Required! | Cloudflare', { admission: true })));
    assert.equal(edge.code, 'SUBAGENT_NOT_A_LIMIT_FAILURE', 'a dropped connection says nothing of the account');
    await forgetHealth();
    const third = await parentSession();
    const opened3 = await subagents.createSubagentRun(runner, third, create({ toolUseId: 'toolu_admission_3', size: 'M' }));
    const moved = await subagents.nextSubagentCandidate(runner, third, opened3.runId, fallback(UNMAPPED, { admission: true }));
    assert.equal(moved.reason, `Moved to a-coder on ${first} after claude-sonnet-5-5 could not start`);
    assert.deepEqual((await rowOf(opened3.runId)).attempts.map((a) => a.outcome), ['ADMISSION_FAILED', 'RUNNING']);
  });

  await t.test('on a model the caller named, an account refusal is not moved: the attempt is recorded', async () => {
    await forgetHealth();
    for (const [i, ask, what] of [
      [1, classified(RunFailureKind.ACCOUNT_ACTION_REQUIRED, CURSOR_PAYMENT), 'ACCOUNT_ACTION_REQUIRED'],
      [2, classified(RunFailureKind.ACCESS_DENIED, NOT_IN_PLAN), 'ACCESS_DENIED'],
      [3, fallback(UNMAPPED, { admission: true }), 'ADMISSION_FAILED'],
    ] as const) {
      // Each refusal blocks the one account that lists the named model: start every case from a healthy one.
      await forgetHealth();
      const sessionId = await parentSession();
      const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: `toolu_named_${i}`, model: 'claude-opus-5-5' }));
      assert.equal(opened.decision.tierSource, 'named-model');
      const kept = await refused(subagents.nextSubagentCandidate(runner, sessionId, opened.runId, ask));
      t.diagnostic(`named model, ${what}: ${kept.code}: ${kept.message}`);
      assert.equal(kept.code, 'SUBAGENT_NAMED_MODEL_NOT_MOVED');
      assert.match(kept.message, /on claude-opus-5-5, which the delegate call named, so it is not moved/);
      const row = await rowOf(opened.runId);
      assert.deepEqual(row.attempts.map(brief), [[1, 'claude', 'claude-opus-5-5', what]], 'one attempt, closed; nothing moved');
      assert.equal(row.decision.reasons.some((r) => r.startsWith('Moved to')), false);
    }
  });

  await t.test('a move onto a due trial claims it; another run skips it; the refused trial is not one of the two moves', async () => {
    await forgetHealth();
    await trialDue();
    const a = await parentSession();
    const b = await parentSession();
    const runA = await subagents.createSubagentRun(runner, a, create({ toolUseId: 'toolu_trial_a', size: 'M' }));
    const runB = await subagents.createSubagentRun(runner, b, create({ toolUseId: 'toolu_trial_b', size: 'M' }));
    t.diagnostic(`A's fallbacks ${JSON.stringify(runA.decision.fallbacks)}`);
    assert.equal(runA.decision.provider, 'claude');
    assert.equal((runA.decision.fallbacks?.[0] as { trial?: { subject?: string } } | undefined)?.trial?.subject, firstKey,
      "the router says Metered A's trial is due");

    // A moves onto Metered A and takes its trial.
    const ontoTrial = await subagents.nextSubagentCandidate(runner, a, runA.runId, fallback(SESSION_LIMIT));
    assert.equal(ontoTrial.exec.model, 'a-coder');
    assert.equal((await firstHealth())?.trialSessionId, runA.runId, "the run's id holds the trial");
    assert.equal((await rowOf(runA.runId)).attempts[1].trialOf, firstKey, 'the attempt says it is the trial');

    // B reaches Metered A while A holds the trial: it is skipped, as a task dispatch routes past it.
    const pastTrial = await subagents.nextSubagentCandidate(runner, b, runB.runId, fallback(SESSION_LIMIT));
    t.diagnostic(`B moved: ${pastTrial.reason}`);
    assert.equal(pastTrial.reason, `Moved to b-coder on ${second} after claude-sonnet-5-5's account hit its limit`);
    assert.equal((await firstHealth())?.trialSessionId, runA.runId, 'the trial is still A\'s');

    // The trial is refused: the next trip at once, the claim released.
    const offTrial = await subagents.nextSubagentCandidate(runner, a, runA.runId,
      classified(RunFailureKind.ACCOUNT_ACTION_REQUIRED, CURSOR_PAYMENT));
    assert.equal(offTrial.reason, `Moved to b-coder on ${second} after a-coder's account needed action`);
    const tripped = await firstHealth();
    t.diagnostic(`Metered A after its refused trial: ${JSON.stringify(tripped)}`);
    assert.equal(tripped?.trialSessionId, null, 'the claim ends with the trial');
    assert.equal(tripped?.trips, 2, 'the next step of the ladder');
    assert.ok(tripped?.blockedUntil && tripped.blockedUntil.getTime() > Date.now(), 'blocked again');

    // Two moves already, one of them off the refused trial: a third is still made, a fourth is not.
    const thirdMove = await subagents.nextSubagentCandidate(runner, a, runA.runId, classified(RunFailureKind.ACCESS_DENIED, NOT_IN_PLAN));
    t.diagnostic(`A's third move: ${thirdMove.reason}`);
    assert.equal(thirdMove.attempt, 4);
    assert.equal(thirdMove.reason, `Moved to c-coder on ${third} after b-coder's account needed action`);
    const spent = await refused(subagents.nextSubagentCandidate(runner, a, runA.runId, fallback(SESSION_LIMIT)));
    assert.equal(spent.code, 'SUBAGENT_FALLBACK_SPENT');
    const row = await rowOf(runA.runId);
    t.diagnostic(`A's attempts ${JSON.stringify(row.attempts.map(brief))}`);
    assert.deepEqual(row.attempts.slice(0, 3).map(brief), [
      [1, 'claude', 'claude-sonnet-5-5', 'USAGE_LIMIT'],
      [2, first, 'a-coder', 'ACCOUNT_ACTION_REQUIRED'],
      [3, second, 'b-coder', 'ACCESS_DENIED'],
    ]);
    assert.deepEqual(brief(row.attempts[3]), [4, third, 'c-coder', 'USAGE_LIMIT']);
  });

  await t.test('a run that opens on a due trial claims it; ending before admission releases it, succeeding clears it', async () => {
    // The subscription is cooling down after a usage limit, so the cheapest key is the pick.
    await forgetHealth();
    const cool = await parentSession();
    const cooled = await subagents.createSubagentRun(runner, cool, create({ toolUseId: 'toolu_cool', size: 'M' }));
    await subagents.nextSubagentCandidate(runner, cool, cooled.runId, fallback(SESSION_LIMIT));
    await trialDue();

    const c = await parentSession();
    const runC = await subagents.createSubagentRun(runner, c, create({ toolUseId: 'toolu_trial_c', size: 'M' }));
    t.diagnostic(`C opened on ${runC.decision.provider}/${runC.decision.model}; reasons ${JSON.stringify(runC.decision.reasons)}`);
    assert.equal(runC.decision.provider, first, 'the subscription cools down: the cheapest key, due its trial, is the pick');
    assert.equal((await rowOf(runC.runId)).attempts[0].trialOf, firstKey);
    assert.equal((await firstHealth())?.trialSessionId, runC.runId, 'claimed as the run opened');
    await subagents.updateSubagentRun(runner, c, runC.runId, update({ status: 'STOPPED', resultSummary: 'stopped' }));
    const released = await firstHealth();
    assert.equal(released?.trialSessionId, null, 'ended before admission: the trial is due again');
    assert.equal(released?.clearedAt, null, 'and the block is not lifted');

    const d = await parentSession();
    const runD = await subagents.createSubagentRun(runner, d, create({ toolUseId: 'toolu_trial_d', size: 'M' }));
    assert.equal((await firstHealth())?.trialSessionId, runD.runId);
    await subagents.updateSubagentRun(runner, d, runD.runId, update({ status: 'DONE', resultSummary: 'fixed' }));
    const cleared = await prisma.accountHealth.findFirstOrThrow({ where: { ownerId, subjectKey: firstKey }, orderBy: { createdAt: 'desc' } });
    t.diagnostic(`Metered A after a successful trial: ${JSON.stringify(cleared)}`);
    assert.ok(cleared.clearedAt, 'a trial that succeeds clears the account');
    assert.equal(cleared.trialSessionId, null);
  });
});
