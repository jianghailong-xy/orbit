    const e = await estate();
    const opened = await subagents.openSubagentRun(e.hpc, e.sessionId, create({ toolUseId: 'toolu_01Spoof', workspace: 'orbit-macos' }));
    await subagents.claimRemoteSubagentRun(e.mac, opened.runId);
    const batch = { events: [{ seq: 1, type: 'assistant', payload: { text: 'I am the Mac, honest.' } }] };
    // The parent's own runner, another runner of the same account, and another account's runner.
    const spare = await machine(e.ownerId, 'spare-linux');
    for (const impostor of [e.hpc, spare]) {
      await assert.rejects(subagents.relaySubagentEvents(impostor, opened.runId, batch), refusedWith('SUBAGENT_RUN_NOT_TARGET'),
        `${impostor.name} is refused`);
    }
    const strangerOwner = await account();
    const stranger = await machine(strangerOwner, 'someone else');
    await assert.rejects(subagents.relaySubagentEvents(stranger, opened.runId, batch),
      (error: unknown) => error instanceof HttpException && error.getStatus() === 404, "another account's runner learns nothing");
    await assert.rejects(subagents.claimRemoteSubagentRun(spare, opened.runId), refusedWith('SUBAGENT_RUN_NOT_TARGET'));
    await assert.rejects(subagents.endRemoteSubagentRun(spare, opened.runId, update({ status: 'DONE', resultSummary: 'forged' })),
      refusedWith('SUBAGENT_RUN_NOT_TARGET'));
    assert.equal(await prisma.subagentRelayEvent.count({ where: { runId: opened.runId } }), 0, 'no event was stored');
    assert.equal((await prisma.subagentRun.findUniqueOrThrow({ where: { id: opened.runId } })).status, 'RUNNING');
    await assert.rejects(
      subagents.updateSubagentRun(e.hpc, e.sessionId, opened.runId, update({ status: 'DONE', resultSummary: 'forged' })),
      refusedWith('SUBAGENT_RUN_IS_REMOTE'), "and the parent's runner does not report a remote run's end either");
