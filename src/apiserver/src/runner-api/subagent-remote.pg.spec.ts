/** A collaborator whose every method answers nothing: the broadcasts the handlers fire. */
const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

const create = (fields: Partial<SubagentRunCreateDto> & { toolUseId: string }): SubagentRunCreateDto =>
  Object.assign(new SubagentRunCreateDto(), {
    type: 'general', definitionSource: 'builtin', prompt: 'Run the iOS tests and report the failures.', ...fields,
  });

const update = (fields: Partial<SubagentRunUpdateDto>): SubagentRunUpdateDto => Object.assign(new SubagentRunUpdateDto(), fields);

/** The refusal's code and message, for an HttpException with that code. */
function refusedWith(code: string, said?: (message: string) => void) {
  return (error: unknown) => {
    if (!(error instanceof HttpException)) return false;
    const body = error.getResponse() as { code?: string; message?: string };
    if (body.code !== code) return false;
    said?.(String(body.message ?? ''));
    return true;
  };
}

