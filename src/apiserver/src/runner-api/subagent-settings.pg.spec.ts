/**
 * The SubAgents settings and the Providers page's Tier column (docs/subagent-design.md §4.2, §7), on a real
 * PostgreSQL:
 *
 *   1. Defaults: a new Agent has SubAgents on, Optimize For Cost and 4 running at once; a new account blocks
 *      no provider.
 *   2. The human doors write them: PATCH /workspaces/:id (subagentsEnabled, subagentsMaxRunning,
 *      modelRoutingOptimizeFor) and PATCH /users/me/preferences (subagentBlockedProviders).
 *   3. The runner doors refuse the same fields: PATCH and POST /runner/workspaces answer 400
 *      HUMAN_ONLY_WORKSPACE_FIELD and nothing is written, and a runner's provider write carries no tier.
 *   4. A custom endpoint's model with no tier is listed `Not set` and skipped by routeSubagent with its reason;
 *      once the owner sets a tier through PATCH /providers/mine/:id/model-tier it is listed and picked.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/subagent-settings.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { BadRequestException, ValidationPipe } from '@nestjs/common';
import { type PrismaClient } from '@prisma/client';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { prismaClientFor } from '../prisma/prisma-client';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { UpdateModelProviderDto, UpdateProviderModelTierDto } from '../providers/dto';
import { ProvidersController } from '../providers/providers.controller';
import { ProvidersService } from '../providers/providers.service';
import { UpdatePreferencesDto } from '../users/dto';
import { UsersController } from '../users/users.controller';
import { CreateWorkspaceDto, UpdateWorkspaceDto } from '../workspaces/dto';
import { WorkspacesService } from '../workspaces/workspaces.service';
import { RunnerAgentsController } from './runner-agents.controller';
import { RunnerProvidersController } from './runner-providers.controller';
import { planSubagentRoute, subagentBlockedProviders } from './subagent-route';

const URL = process.env.COORDINATOR_PG_URL;
process.env.PROVIDER_SECRET_KEY ??= 'subagent-settings-spec';
const skip = !URL;

/** A collaborator whose every method answers nothing: the broadcasts the handlers fire. */
const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

/** The body as the global ValidationPipe (main.ts) hands it to a handler typed with `metatype`. */
const asSent = <T>(metatype: new () => T, body: unknown): Promise<T> =>
  new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false })
    .transform(body, { type: 'body', metatype }) as Promise<T>;

test('SubAgents settings: defaults, the human doors, the runner refusals and the tier a custom model needs', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  const runnerId = randomUUID();
  const user = { userId: ownerId } as never;
  await prisma.user.create({
    data: { id: ownerId, email: `subagent-settings-${ownerId}@settings.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  const runner = await prisma.runner.create({
    data: {
      id: runnerId, name: 'the machine the parent runs on', ownerId, tokenHash: sha256(`subagent-settings-${runnerId}`),
      lastHeartbeatAt: new Date(),
      engines: [
        { engine: 'claude', installed: true, auth: 'yes' },
        { engine: 'codex', installed: true, auth: 'yes' },
      ],
      modelCatalog: {
        claude: [
          { value: 'claude-opus-5-5', label: 'Opus 5.5', priority: 0 },
          { value: 'claude-sonnet-5-5', label: 'Sonnet 5.5', priority: 2 },
        ],
        codex: [{ value: 'gpt-5.6-sol', label: 'GPT-5.6 Sol' }],
      },
    },
  });
  const workspaces = new WorkspacesService(prisma as never);
  const users = new UsersController(prisma as never);
  const providers = new ProvidersService(prisma as never, silent(), silent());
  const providersDoor = new ProvidersController(providers, silent(), silent(), prisma as never);
  // The orchestration gate passes: every case below is about the field rules, not who may orchestrate.
  const orchestration = { assert: async () => randomUUID() } as never;
  const runnerAgents = new RunnerAgentsController(workspaces, orchestration, silent(), prisma as never);
  const runnerProviders = new RunnerProvidersController(providers);

  const agent = await workspaces.create(ownerId, await asSent(CreateWorkspaceDto, {
    name: `orbit-worker-${runnerId.slice(-8)}`, runnerId, workDir: '/work/repo',
  }));

  await t.test('defaults: SubAgents on, Optimize For Cost, 4 at once, nothing blocked', async () => {
    assert.equal(agent.subagentsEnabled, true);
    assert.equal(agent.modelRoutingOptimizeFor, 'cost');
    assert.equal(agent.subagentsMaxRunning, 4);
    const me = await users.me(user);
    assert.deepEqual(subagentBlockedProviders(me?.preferences), [], 'a new account blocks no provider');
  });

  await t.test('the human doors write every field', async () => {
    const saved = await workspaces.update(ownerId, agent.id, await asSent(UpdateWorkspaceDto, {
      subagentsEnabled: false, subagentsMaxRunning: 2, modelRoutingOptimizeFor: 'intelligence',
    }));
    assert.equal(saved.subagentsEnabled, false);
    assert.equal(saved.subagentsMaxRunning, 2);
    assert.equal(saved.modelRoutingOptimizeFor, 'intelligence');
    const stored = await prisma.workspace.findUniqueOrThrow({ where: { id: agent.id } });
    assert.deepEqual(
      [stored.subagentsEnabled, stored.subagentsMaxRunning, stored.modelRoutingOptimizeFor],
      [false, 2, 'intelligence'],
    );
    // Out of range is the global pipe's 400, before any write.
    for (const subagentsMaxRunning of [0, 17, 2.5]) {
      await assert.rejects(asSent(UpdateWorkspaceDto, { subagentsMaxRunning }), BadRequestException,
        `subagentsMaxRunning ${subagentsMaxRunning} is refused`);
    }

    const me = await users.updatePreferences(user, await asSent(UpdatePreferencesDto, {
      subagentBlockedProviders: ['codex', 'codex', 'opencode'],
    }));
    assert.deepEqual(subagentBlockedProviders(me.preferences), ['codex', 'opencode'], 'stored once each');
    const cleared = await users.updatePreferences(user, await asSent(UpdatePreferencesDto, { subagentBlockedProviders: [] }));
    assert.deepEqual(subagentBlockedProviders(cleared.preferences), [], '[] unblocks every provider');

    await workspaces.update(ownerId, agent.id, await asSent(UpdateWorkspaceDto, {
      subagentsEnabled: true, subagentsMaxRunning: 4, modelRoutingOptimizeFor: 'cost',
    }));
  });

  await t.test('the runner doors refuse the same fields by name, and write nothing', async () => {
    const before = await prisma.workspace.findUniqueOrThrow({ where: { id: agent.id } });
    const fields: Array<[string, unknown]> = [
      ['subagentsEnabled', false],
      ['subagentsMaxRunning', 9],
      ['modelRoutingOptimizeFor', 'intelligence'],
      ['modelRoutingProviders', ['codex']],
      ['modelRouting', true],
    ];
    for (const [field, value] of fields) {
      for (const door of ['update', 'create'] as const) {
        const body = { name: door === 'create' ? 'child' : 'renamed', [field]: value };
        const refused = await (door === 'update'
          ? runnerAgents.updateWorkspace(runner, 's1', 'token', agent.id, body)
          : runnerAgents.createWorkspace(runner, 's1', 'token', body)
        ).then(() => null, (error: unknown) => error);
        assert.ok(refused instanceof BadRequestException, `${door} with ${field} is a 400`);
        const answer = refused.getResponse() as { code: string; fields: string[]; message: string };
        assert.equal(answer.code, 'HUMAN_ONLY_WORKSPACE_FIELD');
        assert.deepEqual(answer.fields, [field]);
        assert.match(answer.message, /can only be set by the owner, in the Agent's settings/);
      }
    }
    const after = await prisma.workspace.findUniqueOrThrow({ where: { id: agent.id } });
    assert.deepEqual(after, before, 'not one column of the Agent moved');
    assert.equal(await prisma.workspace.count({ where: { ownerId, name: 'child' } }), 0, 'and no Agent was created');
  });

  await t.test('a custom model with no tier is Not set and skipped by routeSubagent, until the owner sets one', async () => {
    const tag = runnerId.slice(-8);
    const slug = `my-endpoint-${tag}`;
    const created = await prisma.modelProvider.create({
      data: { slug, label: 'My endpoint', runtime: 'claude', baseUrl: 'https://llm.house.invalid', apiKeyEnc: 'x',
        models: [{ value: 'qwen-coder', label: 'Qwen Coder' }], ownerId, position: 1 },
    });
    t.after(async () => { await prisma.modelProvider.deleteMany({ where: { id: created.id } }); });
    // Only the custom endpoint is left to route onto, so whether it is picked is the tier alone.
    await prisma.user.update({
      where: { id: ownerId },
      data: { preferences: { subagentBlockedProviders: ['claude', 'codex', 'kimi', 'opencode', 'antigravity', 'dsh', 'cursor'] } },
    });
    const sessionId = randomUUID();
    await prisma.session.create({
      data: {
        id: sessionId, ownerId, creatorId: ownerId, workspaceId: agent.id, assignedRunnerId: runnerId,
        title: 'split the parser work', prompt: 'split the parser work', provider: 'claude', engine: 'claude',
        model: 'claude-opus-5-5', effort: 'high', status: 'AWAITING_INPUT', numTurns: 1,
        dispatchOrigin: 'USER', startsTaskWork: false,
      },
    });
    const plan = () => planSubagentRoute(prisma as never, {
      ownerId, workspaceId: agent.id, runnerId, parent: { engine: 'claude', provider: 'claude', model: 'claude-opus-5-5', effort: 'high' },
      dto: { toolUseId: `toolu_${randomUUID()}`, type: 'general', definitionSource: 'builtin', size: 'M' },
    });
    const row = async () => (await providersDoor.subagentTiers(user)).providers.find((entry) => entry.slug === slug);

    const untiered = await plan();
    t.diagnostic(`before: ${JSON.stringify(untiered)}`);
    assert.equal(untiered.model, null, 'nothing left to route onto');
    assert.deepEqual(
      untiered.candidates.filter((c) => c.provider === slug && c.model !== null),
      [{ provider: slug, engine: 'claude', model: 'qwen-coder', effort: null, reason: 'The model has no tier' }],
    );
    assert.deepEqual((await row())?.models, [
      { model: 'qwen-coder', levels: [], source: null, editable: true, outputPricePerMTok: null },
    ], 'the Tier column says Not set, and offers to set it');
    assert.equal((await row())?.providerId, created.id);

    // A runner's provider write cannot set it: the DTO has no such field, and the whitelist drops it.
    await runnerProviders.update(runner, slug, await asSent(UpdateModelProviderDto, {
      label: 'My endpoint', modelTiers: { 'qwen-coder': 'M' }, models: [{ value: 'qwen-coder', label: 'Qwen Coder', tier: 'M' }],
    }));
    assert.deepEqual((await prisma.modelProvider.findUniqueOrThrow({ where: { id: created.id } })).modelTiers, {});
    assert.equal((await plan()).model, null, 'still skipped after the runner write');

    // A model the key does not list, and a bad tier, are refused.
    await assert.rejects(providersDoor.setModelTier(user, created.id, await asSent(UpdateProviderModelTierDto, {
      model: 'not-listed', tier: 'M',
    })), BadRequestException);
    await assert.rejects(asSent(UpdateProviderModelTierDto, { model: 'qwen-coder', tier: 'XXL' }), BadRequestException);

    await providersDoor.setModelTier(user, created.id, await asSent(UpdateProviderModelTierDto, { model: 'qwen-coder', tier: 'M' }));
    const tiered = await plan();
    t.diagnostic(`after: ${JSON.stringify(tiered)}`);
    assert.equal(tiered.provider, slug);
    assert.equal(tiered.model, 'qwen-coder', 'picked once it has a tier');
    assert.equal(tiered.level, 'M');
    assert.deepEqual((await row())?.models, [
      { model: 'qwen-coder', levels: ['M'], source: 'owner', editable: true, outputPricePerMTok: null },
    ]);

    // Editing the model list keeps the owner's tier; clearing it takes the model out again.
    await providers.update(ownerId, created.id, await asSent(UpdateModelProviderDto, {
      models: [{ value: 'qwen-coder', label: 'Qwen Coder 2' }, { value: 'qwen-lite', label: 'Qwen Lite' }],
    }));
    assert.equal((await plan()).model, 'qwen-coder', 'a list edit leaves the tier alone');
    await providersDoor.setModelTier(user, created.id, await asSent(UpdateProviderModelTierDto, { model: 'qwen-coder', tier: null }));
    assert.equal((await plan()).model, null, 'cleared: skipped again');
  });

  await t.test('the Tier column: preset tiers from the catalogue, not editable', async () => {
    await prisma.user.update({ where: { id: ownerId }, data: { preferences: {} } });
    const view = await providersDoor.subagentTiers(user);
    const claude = view.providers.find((entry) => entry.slug === 'claude');
    assert.deepEqual(claude?.models, [
      { model: 'claude-sonnet-5-5', levels: ['S', 'M'], source: 'catalogue', editable: false, outputPricePerMTok: null },
      { model: 'claude-opus-5-5', levels: ['L', 'XL'], source: 'catalogue', editable: false, outputPricePerMTok: null },
    ]);
    assert.equal(claude?.billing, 'subscription');
    assert.deepEqual(view.providers.find((entry) => entry.slug === 'codex')?.models, [
      { model: 'gpt-5.6-sol', levels: ['S', 'M', 'L', 'XL'], source: 'catalogue', editable: false, outputPricePerMTok: null },
    ]);
    assert.deepEqual(view.providers.find((entry) => entry.slug === 'cursor')?.models, [],
      'an engine with no tier table lists no models');
    const tag = runnerId.slice(-8);
    const deepseek = await prisma.modelProvider.create({
      data: { slug: `deepseek-${tag}`, label: 'DeepSeek', runtime: 'claude', baseUrl: 'https://api.deepseek.com/anthropic',
        apiKeyEnc: 'x', presetSlug: 'deepseek', followsPreset: true, ownerId, position: 2 },
    });
    t.after(async () => { await prisma.modelProvider.deleteMany({ where: { id: deepseek.id } }); });
    const preset = (await providersDoor.subagentTiers(user)).providers.find((entry) => entry.slug === deepseek.slug);
    assert.ok(preset && preset.models.length > 0);
    for (const model of preset.models) {
      assert.equal(model.source, 'catalogue', `${model.model} takes its tier from the preset`);
      assert.equal(model.editable, false);
      assert.ok(model.levels.length > 0 && model.outputPricePerMTok !== null);
    }
    await assert.rejects(providersDoor.setModelTier(user, deepseek.id, await asSent(UpdateProviderModelTierDto, {
      model: preset.models[0].model, tier: 'S',
    })), BadRequestException, "a preset model's tier is the catalogue's");
  });
});
