/**
 * The session's Agent Tools report (docs/orbit-agent-contract.md §2.7, migration 0770), end to end against a real
 * PostgreSQL through the runner door's own event handler and the session service's own readers:
 *
 *   1. A batch carrying `agent_tools` system events stores the newest report whole in session.agent_tools, and the
 *      session's detail (GET /sessions/:id, SessionsService.get) answers it as `agentTools`.
 *   2. A later batch with no report — an ordinary turn — leaves it as it was; a later report replaces it.
 *   3. The Open list's rows do not carry it: the drawer reads the detail, and the list stays the size it was.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/agent-tools-report.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { type PrismaClient, RunStatus, SessionDispatchOrigin } from '@prisma/client';
import { type NormalizedRunEvent, RunEventType } from '@orbit/shared';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { prismaClientFor } from '../prisma/prisma-client';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { SessionsService } from '../sessions/sessions.service';
import { RunnerApiController } from './runner-api.controller';

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

/** A collaborator whose every method answers nothing: the broadcasts the two services fire. */
const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

type Reported = Pick<NormalizedRunEvent, 'type' | 'payload'>;

/** The report as runner-go's agent_tools_report.go sends it, for one MCP status. */
const report = (status: string, tools: number) => ({
  v: 1,
  at: '2026-11-14T13:00:00Z',
  engine: 'claude',
  engineVersion: '2.1.325',
  runnerVersion: '0.1.261',
  versions: { contract: '1.8.0', catalog: '1.7.0', primer: '1.2.0', guide: '1.1.0', playbooks: '1.0.0' },
  mcp: { status, tools },
  families: [
    { id: 'tasks', served: status === 'connected' ? 21 : 0, total: 21, ...(status === 'connected' ? {} : { reason: 'not_connected' }) },
    { id: 'orchestration', served: 0, total: 22, reason: 'orchestration' },
  ],
  switches: { orchestration: false, watches: true, wiki: true },
  permissionMode: 'default',
  instructions: { carrier: 'append_system_prompt', workspace: true, workspaceChars: 412 },
  skill: { name: 'orbit:playbooks', offered: true, loaded: true },
});

const agentTools = (status: string, tools: number): Reported => ({
  type: RunEventType.SYSTEM,
  payload: { subtype: 'agent_tools', agentTools: report(status, tools) },
});

test('the runner’s Agent Tools report is kept on the session and served with its detail', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  const runner = { id: randomUUID() };
  await prisma.user.create({
    data: { id: ownerId, email: `agent-tools-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  await prisma.runner.create({
    data: { id: runner.id, name: 'the machine', ownerId, tokenHash: sha256(`agent-tools-${runner.id}`) },
  });
  const door = new RunnerApiController(prisma as never, silent(), silent(), silent(), silent(), silent());
  const sessions = new SessionsService(prisma as never, silent(), silent());
  const workspaceId = randomUUID();
  await prisma.workspace.create({ data: { id: workspaceId, ownerId, name: 'the checked-out repo' } });
  const sessionId = randomUUID();
  await prisma.session.create({
    data: {
      id: sessionId,
      ownerId,
      creatorId: ownerId,
      workspaceId,
      title: 'does the agent have Orbit',
      prompt: 'file this for later',
      provider: 'claude',
      status: RunStatus.AWAITING_INPUT,
      dispatchOrigin: SessionDispatchOrigin.USER,
      startsTaskWork: false,
      assignedRunnerId: runner.id,
      numTurns: 1,
    },
  });
  let seq = 0;
  const leaseOwner = randomUUID();
  const send = (events: Reported[]) =>
    door.events(runner, sessionId, {
      leaseOwner,
      events: events.map((event) => ({ ...event, seq: ++seq, ts: new Date().toISOString() })),
    });
  await door.takeoverLeases(runner, sessionId, { leaseOwner, expectedLeaseOwner: null } as never);
  const stored = async () =>
    (await prisma.session.findUniqueOrThrow({ where: { id: sessionId }, select: { agentTools: true } })).agentTools;

  await t.test('no report yet reads as none', async () => {
    assert.equal(await stored(), null);
    const detail = (await sessions.get(ownerId, sessionId)) as { agentTools?: unknown };
    assert.equal(detail.agentTools ?? null, null);
  });

  await t.test('the newest report of a batch is stored whole, and the detail answers it', async () => {
    await send([
      agentTools('starting', 0),
      { type: RunEventType.SYSTEM, payload: { subtype: 'init', model: 'claude-opus-5-5', sessionId: 'engine-1' } },
      agentTools('connected', 102),
    ]);
    assert.deepEqual(await stored(), report('connected', 102));
    const detail = (await sessions.get(ownerId, sessionId)) as { agentTools?: unknown };
    assert.deepEqual(detail.agentTools, report('connected', 102));
  });

  await t.test('a batch without a report leaves it; a later report replaces it', async () => {
    await send([{ type: RunEventType.ASSISTANT, payload: { text: 'Filed it.' } }]);
    assert.deepEqual(await stored(), report('connected', 102));
    await send([agentTools('failed', 0)]);
    assert.deepEqual(await stored(), report('failed', 0));
  });

  await t.test('the Open list’s rows do not carry it', async () => {
    const rows = await sessions.list(ownerId, { view: 'open' });
    const row = rows.find((r) => r.id === sessionId) as Record<string, unknown> | undefined;
    assert.ok(row, 'the session is missing from its own owner’s Open list');
    assert.equal('agentTools' in row, false);
  });
});
