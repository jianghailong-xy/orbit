const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

const RUNNER_TOKEN = `create-recovery-runner-${randomUUID()}`;
const GO_TEST = 'TestCreateRecoveryAgainstARealControlPlane';
/** src/runner-go, from build/runner-api. */
const RUNNER_GO = resolve(__dirname, '../../../runner-go');

const silent = (): unknown =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

/** A service lent whole, minus the lifecycle hooks a module would otherwise run (sweeps, timers). */
function lent<T extends object>(service: T): T {
  const hooks = new Set(['onModuleInit', 'onModuleDestroy', 'onApplicationBootstrap', 'onApplicationShutdown']);
  return new Proxy(service, {
    get(target, key, receiver) {
      if (typeof key === 'string' && hooks.has(key)) return undefined;
      const value = Reflect.get(target, key, receiver) as unknown;
      return typeof value === 'function' ? (value as (...args: unknown[]) => unknown).bind(target) : value;
    },
  });
}

interface LostAnswer {
  tool: 'project_create' | 'session_create';
  lost: 'drop' | 'truncate';
  marker: string;
  firstOutcome: string;
  firstRecoveryPolicy: string;
  requestId: string;
  replayId: string;
  replayReceipt: { requestId: string; kind: string; resourceId: string; receivedAt: string; replayed: boolean };
  secondReplayId: string;
  secondReplayReceipt: { resourceId: string; receivedAt: string; replayed: boolean };
  createPostRequestIds: string[];
  createPosts: number;
  lostDeliveryStatus: number;
}

interface WaitFailure {
  outcome: 'GET_FAILED' | 'TIMEOUT';
  marker: string;
  createdId: string;
  waitSessionId: string;
  nextTool: string;
  nextSessionId: string;
  isError: boolean;
  failedGets: number;
  sessionGetId: string;
  createPosts: number;
}

function runGo(env: Record<string, string>): Promise<{ code: number | null; output: string }> {
  return new Promise((done, fail) => {
    const child = spawn('go', ['test', '-count=1', '-v', '-timeout', '15m', '-run', `^${GO_TEST}$`, '.'], {
      cwd: RUNNER_GO,
      env: { ...process.env, ...env },
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let output = '';
    child.stdout.on('data', (chunk: Buffer) => { output += chunk.toString(); });
    child.stderr.on('data', (chunk: Buffer) => { output += chunk.toString(); });
    child.on('error', fail);
    child.on('close', (code) => done({ code, output }));
  });
}

test('a create whose answer was lost after the commit, or whose wait failed, recovers to one resource', {
  skip, concurrency: 1, timeout: 20 * 60_000,
}, async (t) => {
  assert.ok(existsSync(join(RUNNER_GO, 'create_request_e2e_test.go')), `no runner tests at ${RUNNER_GO}`);
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  let app: INestApplication | undefined;
  t.after(async () => {
    await app?.close().catch(() => undefined);
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });
  const db = prisma as unknown as PrismaService;

  // ── fixtures ─────────────────────────────────────────────────────────────────────────────────
  const ownerId = randomUUID();
  const runnerId = randomUUID();
  const workspaceId = randomUUID();
  const parent = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `create-recovery-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  await prisma.runner.create({
    data: {
      id: runnerId, ownerId, name: 'the machine', tokenHash: sha256(RUNNER_TOKEN),
      status: RunnerStatus.ONLINE, lastHeartbeatAt: new Date(), capabilities: [], capabilitiesReportedAt: new Date(),
    },
  });
  await prisma.workspace.create({ data: { id: workspaceId, ownerId, runnerId, name: 'orbit', enabled: true } });
  await prisma.session.create({
    data: {
      id: parent, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
      title: 'the caller', prompt: 'the caller', provider: 'claude', providerBuiltin: true, engine: 'claude',
      status: RunStatus.RUNNING, startedAt: new Date(), runtimeSessionId: `runtime-${parent}`,
      dispatchOrigin: SessionDispatchOrigin.USER, runSource: SessionRunSource.MANUAL,
    },
  });

  // ── the control plane: the runner doors over HTTP ────────────────────────────────────────────
  const sessions = new SessionsService(db, silent() as never, silent() as never);
  const acceptance = new ProjectAcceptanceService(db);
  const projects = new ProjectsService(db, acceptance, sessions);
  const orchestration = new RunnerOrchestrationAuthorizer(db, new JwtService({ secret: 'create-recovery-http-pg' }));
  const receipts = new CreateRequestReceipts(db);

  @Module({
    controllers: [RunnerProjectsController, RunnerSessionsController],
    providers: [
      { provide: PrismaService, useValue: prisma },
      { provide: SessionsService, useValue: lent(sessions) },
      { provide: ProjectsService, useValue: lent(projects) },
      { provide: ProjectAcceptanceService, useValue: lent(acceptance) },
      { provide: RunnerOrchestrationAuthorizer, useValue: orchestration },
      { provide: CreateRequestReceipts, useValue: receipts },
      { provide: ServiceTokenAuthorizer, useValue: { verify: async () => null } },
      { provide: ProjectHandoffService, useValue: {} },
      { provide: ProjectOpenItemService, useValue: {} },
      { provide: MergeReceiptService, useValue: {} },
      { provide: SessionAttemptService, useValue: { chargeSteer: async () => undefined } },
      RunnerAuthGuard,
      RunnerSessionAuthGuard,
    ],
  })
  class RunnerDoors {}

  app = await NestFactory.create(RunnerDoors, { logger: false, abortOnError: false });
  app.use(publicIdHeaders);
  app.setGlobalPrefix('api');
  app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
  app.useGlobalInterceptors(new PublicIdInterceptor());
  const httpAdapter = app.get(HttpAdapterHost).httpAdapter;
  app.useGlobalFilters(new TransientDbConflictFilter(new PublicIdExceptionFilter(httpAdapter), httpAdapter));
  await app.listen(0, '127.0.0.1');
  const base = (await app.getUrl()).replace('[::1]', '127.0.0.1');

  const orchestrationToken = await orchestration.issue(runnerId, parent);
  async function publicGet(route: string): Promise<{ status: number; json: Record<string, any> }> {
    const response = await fetch(`${base}/api${route}`, {
      headers: {
        authorization: `Bearer ${RUNNER_TOKEN}`,
        'x-orbit-session-id': uuidToBase62(parent),
        'x-orbit-session-token': orchestrationToken,
      },
    });
    const text = await response.text();
    let json: Record<string, any> = {};
    try { json = JSON.parse(text) as Record<string, any>; } catch { /* asserted below */ }
    return { status: response.status, json };
  }

  // ── the runner, against it ───────────────────────────────────────────────────────────────────
  const tag = `recovery-${randomUUID()}`;
  const reportPath = join(mkdtempSync(join(tmpdir(), 'create-recovery-')), 'report.json');
  const go = await runGo({
    ORBIT_CREATE_E2E_API: base,
    ORBIT_CREATE_E2E_RUNNER_TOKEN: RUNNER_TOKEN,
    ORBIT_CREATE_E2E_PARENT_SESSION: uuidToBase62(parent),
    ORBIT_CREATE_E2E_ORCHESTRATION_TOKEN: orchestrationToken,
    ORBIT_CREATE_E2E_REPORT: reportPath,
    ORBIT_CREATE_E2E_TAG: tag,
    // What a runner's MCP server is started with: the agent (workspace) it runs as.
    ORBIT_CREATE_E2E_AGENT: uuidToBase62(workspaceId),
  });
  t.diagnostic(go.output.split('\n').filter((line) => /^\s*(---|===|ok|FAIL|PASS)/.test(line)).join('\n'));
  assert.equal(go.code, 0, `the runner's test failed:\n${go.output}`);
  assert.match(go.output, new RegExp(`--- PASS: ${GO_TEST} `), 'the runner test must run, not skip');
  assert.doesNotMatch(go.output, /--- SKIP/, 'no part of the runner test may skip');
  const report = JSON.parse(readFileSync(reportPath, 'utf8')) as { lostAnswers: LostAnswer[]; waitFailures: WaitFailure[] };

  await t.test('a lost answer, repeated under its request id, is one resource with one receipt', async () => {
    assert.deepEqual(
      report.lostAnswers.map((s) => `${s.tool}/${s.lost}`).sort(),
      ['project_create/drop', 'project_create/truncate', 'session_create/drop', 'session_create/truncate'],
    );
    for (const s of report.lostAnswers) {
      const where = `${s.tool}/${s.lost}`;
      assert.equal(s.firstOutcome, 'UNKNOWN', where);
      assert.equal(s.firstRecoveryPolicy, 'SAME_REQUEST_ID', where);
      assert.ok(s.lostDeliveryStatus >= 200 && s.lostDeliveryStatus < 300,
        `${where}: the server created before the answer was lost (answered ${s.lostDeliveryStatus})`);
      assert.equal(s.createPosts, 3, `${where}: the lost delivery and two repeats, nothing resent on its own`);
      assert.deepEqual(s.createPostRequestIds, [s.requestId, s.requestId, s.requestId], where);

      const kind = s.tool === 'project_create' ? 'PROJECT_CREATE' : 'SESSION_CREATE';
      let rows: Array<{ id: string }>;
      if (s.tool === 'project_create') {
        rows = await prisma.project.findMany({ where: { ownerId, title: s.marker }, select: { id: true } });
      } else {
        rows = await prisma.session.findMany({ where: { ownerId, parentSessionId: parent, prompt: s.marker }, select: { id: true } });
      }
      assert.equal(rows.length, 1, `${where}: exactly one ${s.tool === 'project_create' ? 'Project' : 'Session'} in the database`);
      const publicId = uuidToBase62(rows[0].id);

      const receipt = await prisma.createRequestReceipt.findUnique({
        where: { ownerId_actionKind_requestToken: { ownerId, actionKind: kind, requestToken: s.requestId } },
      });
      assert.equal(receipt?.status, 'COMPLETED', where);
      assert.equal((receipt?.result as { id?: string } | null)?.id, rows[0].id, `${where}: the receipt keeps the created row`);
      assert.equal(await prisma.createRequestReceipt.count({ where: { ownerId, requestToken: s.requestId } }), 1, where);

      // Both repeats name that row, with one receipt: same resource id, same receivedAt as the receipt row.
      assert.equal(s.replayId, publicId, where);
      assert.equal(s.secondReplayId, publicId, where);
      assert.equal(s.replayReceipt.resourceId, publicId, where);
      assert.equal(s.secondReplayReceipt.resourceId, publicId, where);
      assert.equal(s.replayReceipt.requestId, s.requestId, where);
      assert.equal(s.replayReceipt.kind, kind, where);
      assert.equal(s.replayReceipt.replayed, true, where);
      assert.equal(s.replayReceipt.receivedAt, receipt!.createdAt.toISOString(), where);
      assert.equal(s.secondReplayReceipt.receivedAt, receipt!.createdAt.toISOString(), where);

      const shown = await publicGet(s.tool === 'project_create' ? `/runner/projects/${publicId}` : `/runner/sessions/${publicId}`);
      assert.equal(shown.status, 200, `${where}: ${JSON.stringify(shown.json)}`);
      assert.equal(shown.json.id, publicId, `${where}: the public read answers the same resource`);
    }
  });

  await t.test('a wait that failed after the create names the child, and session_get reads that child', async () => {
    assert.deepEqual(report.waitFailures.map((w) => w.outcome).sort(), ['GET_FAILED', 'TIMEOUT']);
    for (const w of report.waitFailures) {
      const children = await prisma.session.findMany({
        where: { ownerId, parentSessionId: parent, prompt: w.marker }, select: { id: true },
      });
      assert.equal(children.length, 1, `${w.outcome}: exactly one child Session`);
      const publicId = uuidToBase62(children[0].id);
      assert.equal(w.isError, false, w.outcome);
      assert.equal(w.createdId, publicId, w.outcome);
      assert.equal(w.waitSessionId, publicId, `${w.outcome}: the answer keeps the child's public id`);
      assert.equal(w.nextTool, 'session_get', w.outcome);
      assert.equal(w.nextSessionId, publicId, w.outcome);
      assert.equal(w.sessionGetId, publicId, `${w.outcome}: session_get with the answer's arguments read the same child`);
      assert.equal(w.createPosts, 1, `${w.outcome}: no second session_create`);
      if (w.outcome === 'GET_FAILED') assert.ok(w.failedGets > 0, 'a read of the child failed');
      const shown = await publicGet(`/runner/sessions/${publicId}`);
      assert.equal(shown.status, 200);
      assert.equal(shown.json.id, publicId);
    }
    // Every child made under the caller is accounted for: one per lost-answer session_create, one per wait.
    assert.equal(await prisma.session.count({ where: { ownerId, parentSessionId: parent } }), 4);
  });
});
