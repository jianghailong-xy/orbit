/**
 * project_create and session_create recover from a lost answer, end to end: the real runner (Go, its MCP tools)
 * against the real runner doors over HTTP (Nest router, guards, pipes, the public-id interceptor) on a real
 * PostgreSQL (create-request-receipts.ts, migration 0645).
 *
 * This spec stands the control plane up and runs the runner's TestCreateRecoveryAgainstARealControlPlane
 * (src/runner-go/create_request_e2e_test.go) against it. Between the two sits that test's proxy, which loses
 * an answer only AFTER the server has sent it in full, so after the create committed:
 *
 *   1. project_create and session_create, the answer dropped or cut off after the status line: the runner sends
 *      it once and fails UNKNOWN with its request id. Sent again under that id it reads the receipt back. Here:
 *      one Project or Session in the database, one COMPLETED receipt naming it, and the public GET answers it
 *      under the id both replays carried.
 *   2. session_create with wait, every read of the child failing (GET_FAILED) or the child never settling
 *      (TIMEOUT): the answer is not an error, names the child and session_get as the next step, and that
 *      session_get, called with the answer's own arguments, reads the same child. Here: exactly one child in
 *      the database, the one both name.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/create-request-recovery-http.pg.spec.ts
 *
 * Needs `go` on PATH. A Go test that skipped is a failure here: its PASS line is required.
 * Not destructive: every id is generated by the run.
 */
