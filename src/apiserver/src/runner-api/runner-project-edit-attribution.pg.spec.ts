/**
 * WHO EDITED THE RULER, ALL THE WAY FROM THE RUNNER'S REQUEST TO THE ROW.
 *
 * WHAT WAS BROKEN
 * ===============
 * Two durable facts about a project's acceptance criteria are keyed on the conversation that
 * wrote them: `project_criteria_authorship` records which session authored each criterion
 * VERSION (migration 0251), and a held loosening proposal records which principal asked for it
 * (`project_ratified_action_intent.principal_type` / `principal_id`). Both are read off one input
 * — the `x-orbit-session-id` header on `PATCH /runner/projects/:id` — and until this task the
 * runner never sent it. `updateProject` in `src/runner-go/transport.go` went out through the
 * plain `do` helper while `createProject` next door used `doHeaders(..., sessionHeader(...))`.
 *
 * The failure was silent and it fell one way. `actingSessionId` arrived `undefined`, so
 * `principalType: actingSessionId ? 'AGENT' : 'OWNER'` recorded every agent's proposal as the
 * account owner's own, and `authoredByType: authoredBySessionId === null ? 'USER' : 'AGENT'`
 * recorded every criterion an agent wrote as owner-authored with a NULL session. A
 * separation-of-duties rule — no criterion counts at settlement if the session that wrote it is
 * the session whose evidence is being counted — compares `authored_by_session_id` against an
 * evidence-producing session. Against a column that is NULL on every real write, that comparison
 * can never match, so the rule was not merely unenforced: it was unenforceable.
 *
 * WHY THIS SPEC RUNS OVER REAL HTTP AND A REAL POSTGRESQL
 * ======================================================
 * `criteria-authorship.pg.spec.ts` already pins what the SERVICE does when it is handed an acting
 * session — it calls `ProjectsService.update(..., actingSessionId)` directly. That is the half
 * that was never broken. What was broken is upstream of it, in the wire, and a unit call cannot
 * see any of the three things between the header and the service:
 *
 *   * the header is a PUBLIC id. `publicIdHeaders` decodes base62 to a UUID before any guard runs,
 *     and a session id that reached the service in the spelling a model sees would match no row.
 *   * the route has to bind it. `@Headers('x-orbit-session-id')` on `updateProject` is one
 *     parameter decorator away from being dropped, and dropping it 200s.
 *   * absence has to stay absence. `orbit project update` (the headless owner path) sends no
 *     header, and the two facts must come out `USER` / `OWNER` for it — which is the same shape
 *     the bug produced, and the reason a spec that only asserted `AGENT` would not have caught it.
 *
 * And real PostgreSQL because both rows under test are written by machinery this file does not get
 * to fake: `revision` on a criterion version is decided by the `project_acceptance_definition_
 * normalize` BEFORE trigger and is the second half of the authorship primary key, and
 * `project_ratified_action_intent` is guarded by an immutability trigger and a BEFORE INSERT check
 * that re-derives the project's contract binding. Every row asserted below is read back over a
 * SECOND connection, never through the response that wrote it.
 *
 * WHAT THE CASES ARE, AND WHY THE CONTROL IS NOT OPTIONAL
 * ======================================================
 *   (a) the runner's own source: the PATCH carries the header when a session is known, and the
 *       headless CLI path passes none. Unconditional — it needs no database — so even a run with
 *       no PostgreSQL witnesses the half of the chain that lives in Go.
 *   (1) an attributed criteria edit that tightens → the authorship row names the acting session.
 *   (2) an attributed criteria edit that loosens → the held proposal names the acting session.
 *   (3) THE CONTROL, same fixture, same owner, byte-identical bodies, one variable: no header.
 *       Both writes still land, and they land as `USER` / `OWNER` with a NULL session.
 *
 * (3) is what makes (1) and (2) mean anything. An implementation that recorded `AGENT` for
 * everybody — or that stopped writing authorship altogether and left the table empty — passes a
 * file that only looked at the attributed project. It also states the rule the product depends on
 * in the other direction: the owner-authenticated channel is a real, distinguishable principal,
 * not "an agent we failed to identify".
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/runner-project-edit-attribution.pg.spec.ts
 *
 * Not destructive: every id is generated by the case and every assertion is scoped to its own
 * project.
 */
