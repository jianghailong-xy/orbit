/**
 * provider_list's workspace view (GET /runner/providers?workspace=), on a real PostgreSQL: each provider × engine
 * of the owner's judged against that workspace's runner by the reads and rules SubAgent routing uses.
 *
 *   1. A built-in engine the runner reports as not signed in is unusable, with a reason naming the runner.
 *   2. A key the runner can run is usable, with its own models; a signed-in engine lists the runner's catalogue.
 *   3. An account at or above the routing quota limit is unusable, with its utilization.
 *   4. The workspace's default (the pair its sessions start on) is marked, and says when it is the unusable one.
 *   5. Without `workspace` the answer is listUsable's, unchanged; an unknown or someone else's workspace is refused.
 *   6. On a runner whose Claude region verdict is blocked, every Anthropic-bound credential on claude (its own sign-in,
 *      an Anthropic-preset or anthropic.com key, a Claude pool) is unusable with routing's reason, and routing picks
 *      none of them; a DeepSeek key on Claude Code and Codex stay usable (claude-region-check-contract §8, ⑥).
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/workspace-providers.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { HttpException } from '@nestjs/common';
import { Prisma, SessionDispatchOrigin, type PrismaClient, type Runner } from '@prisma/client';
import { RunStatus } from '@orbit/shared';
import { Client } from 'pg';

import { CLAUDE_REGION_V1 } from '@orbit/shared';

import { sha256 } from '../common/crypto.util';
import { prismaClientFor } from '../prisma/prisma-client';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { encryptSecret } from '../providers/provider-crypto';
import { ProvidersService } from '../providers/providers.service';
import { RunnerProvidersController } from './runner-providers.controller';
import { routeSubagent, subagentCandidateRefusal, subagentRunnableModels } from '../tasks/model-routing';
import { subagentRouteInput } from './subagent-route';
import type { WorkspaceProviderView } from './workspace-providers';

const URL = process.env.COORDINATOR_PG_URL;
process.env.PROVIDER_SECRET_KEY ??= 'workspace-providers-spec';
const skip = !URL;

/** A collaborator whose every method answers nothing. */
const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

const refusedWith = (code: string) => (error: unknown) => {
  assert.ok(error instanceof HttpException, `an HttpException, not ${String(error)}`);
  assert.equal((error.getResponse() as { code?: string }).code, code);
  return true;
};

test('provider_list with workspace: what that workspace runner can run, judged as routing judges it', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const inAnHour = new Date(Date.now() + 3_600_000).toISOString();
  async function account() {
    const id = randomUUID();
    await prisma.user.create({ data: { id, email: `workspace-providers-${id}@spec.invalid`, name: 'Owner', passwordHash: 'x' } });
    return id;
  }
  const ownerId = await account();
  const strangerId = await account();

  // The 2026-11-16 estate: `workstation` has Claude installed but not signed in, Codex signed in near its limit.
  const runner = (await prisma.runner.create({
    data: {
      id: randomUUID(), name: 'workstation', ownerId, tokenHash: sha256(`workspace-providers-${randomUUID()}`),
      status: 'ONLINE', lastHeartbeatAt: new Date(),
      engines: [
        { engine: 'claude', installed: true, auth: 'no' },
        { engine: 'codex', installed: true, auth: 'yes' },
      ],
      modelCatalog: {
        claude: [
          { value: 'claude-opus-5-5', label: 'Opus 5.5', priority: 0 },
          { value: 'claude-sonnet-5-5', label: 'Sonnet 5.5', priority: 2 },
        ],
        codex: [{ value: 'gpt-5.6-sol', label: 'GPT-5.6 Sol' }],
      },
    },
  })) as Runner;
  const workspaceId = randomUUID();
  await prisma.workspace.create({
    data: { id: workspaceId, ownerId, runnerId: runner.id, name: 'orbit-ws03', enabled: true, workDir: '/work/orbit' },
  });
  // Its sessions start on Claude's own sign-in: the newest person-opened session ran there.
  await prisma.session.create({
    data: {
      id: randomUUID(), ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runner.id,
      title: 'a conversation', prompt: 'hello', provider: 'claude', providerBuiltin: true, engine: 'claude',
      model: 'claude-opus-5-5', turnState: null, numTurns: 1,
      dispatchOrigin: SessionDispatchOrigin.USER, startsTaskWork: false, costUsd: 0,
    },
  });
  const key = await prisma.modelProvider.create({
    data: {
      slug: `house-${workspaceId.slice(0, 8)}`, label: 'House endpoint', runtime: 'claude',
      baseUrl: 'https://llm.house.invalid', apiKeyEnc: 'x', ownerId, position: 1,
      models: [{ value: 'qwen-coder', label: 'Qwen Coder' }, { value: 'qwen-max', label: 'Qwen Max' }],
    },
  });

  const providers = new ProvidersService(prisma as never, silent(), silent());
  const door = new RunnerProvidersController(providers, prisma as never, null as never);
  const asOwner = { id: randomUUID(), ownerId } as never;
  const view = async (workspace: string) => (await door.list(asOwner, workspace)) as WorkspaceProviderView;
  const pair = (answer: WorkspaceProviderView, provider: string, engine: string) => {
    const found = answer.pairs.find((entry) => entry.provider === provider && entry.engine === engine);
    assert.ok(found, `${provider} on ${engine} is listed`);
    return found;
  };

  await t.test('a built-in engine the runner is not signed in to is unusable, with the reason', async () => {
    const answer = await view('orbit-ws03');
    assert.deepEqual(answer.workspace, { id: workspaceId, name: 'orbit-ws03' });
    assert.deepEqual(answer.runner, { name: 'workstation', online: true });
    const claude = pair(answer, 'claude', 'claude');
    assert.equal(claude.usable, false);
    assert.equal(claude.reason, 'claude is signed out on workstation');
    assert.deepEqual(claude.models, []);
  });

  await t.test('a usable key lists its own models; a signed-in engine the runner catalogue', async () => {
    const answer = await view('orbit-ws03');
    const house = pair(answer, key.slug, 'claude');
    assert.equal(house.usable, true, 'a key brings its own credential: the runner sign-in is not asked');
    assert.equal(house.reason, undefined);
    assert.equal(house.builtin, false);
    assert.deepEqual(house.models, ['qwen-coder', 'qwen-max']);
    const codex = pair(answer, 'codex', 'codex');
    assert.equal(codex.usable, true);
    assert.deepEqual(codex.models, ['gpt-5.6-sol']);
  });

  await t.test('the workspace default is marked, and says it is the unusable one', async () => {
    const answer = await view('orbit-ws03');
    assert.deepEqual(answer.pairs.filter((entry) => entry.default).map((entry) => [entry.provider, entry.engine]), [['claude', 'claude']]);
    assert.deepEqual(answer.default, {
      provider: 'claude', engine: 'claude', model: 'claude-opus-5-5', usable: false,
      reason: 'claude is signed out on workstation',
    });
  });

  await t.test('blocked and over-quota pairs are unusable with the routing reason', async () => {
    await prisma.user.update({ where: { id: ownerId }, data: { preferences: { subagentBlockedProviders: [key.slug] } } });
    await prisma.runner.update({
      where: { id: runner.id },
      data: { planUsage: { codex: { fiveHour: { utilization: 93, resetsAt: inAnHour } } } },
    });
    t.after(async () => {
      await prisma.user.update({ where: { id: ownerId }, data: { preferences: {} } });
      await prisma.runner.update({ where: { id: runner.id }, data: { planUsage: Prisma.DbNull } });
    });
    const answer = await view(workspaceId);
    assert.equal(answer.workspace.name, 'orbit-ws03', 'the workspace is found by its id too');
    assert.deepEqual([pair(answer, key.slug, 'claude').usable, pair(answer, key.slug, 'claude').reason],
      [false, 'Blocked in the SubAgents settings']);
    assert.deepEqual([pair(answer, 'codex', 'codex').usable, pair(answer, 'codex', 'codex').reason],
      [false, 'The account is at 93% of its 5-hour quota']);
  });

  await t.test("usable is what a remote delegate to the workspace can run, and its default check is delegate's", async () => {
    // planRemoteSubagent's input for this workspace: the list SUBAGENT_TARGET_CANNOT_RUN prints, and its default check.
    const input = await subagentRouteInput(prisma, {
      ownerId, workspaceId, runnerId: runner.id,
      dto: { toolUseId: 'toolu_01View', type: 'general', definitionSource: 'builtin' },
      parent: { engine: 'claude', provider: 'claude', model: '', effort: null },
      runnerLabel: 'workstation', strictNamedModel: true,
    });
    const answer = await view('orbit-ws03');
    assert.deepEqual(
      answer.pairs.filter((entry) => entry.usable && entry.models.length > 0)
        .map(({ provider, engine, models }) => ({ provider, engine, models })),
      subagentRunnableModels(input),
    );
    assert.equal(answer.default.reason, subagentCandidateRefusal(input, 'claude', 'claude'));
  });

  await t.test('on a region-blocked runner every Anthropic-bound credential on claude is out; DeepSeek and Codex stay', async () => {
    const blockedOwner = await account();
    const now = new Date().toISOString();
    const hpc = (await prisma.runner.create({
      data: {
        id: randomUUID(), name: 'HPC', ownerId: blockedOwner, tokenHash: sha256(`workspace-providers-${randomUUID()}`),
        status: 'ONLINE', lastHeartbeatAt: new Date(),
        capabilities: [CLAUDE_REGION_V1], capabilitiesReportedAt: new Date(),
        region: { verdict: 'blocked', country: 'CN', regionCode: null, name: 'mainland China', viaProxy: false,
          decidedAt: now, checkedAt: now, blockedChecks: 2 },
        engines: [{ engine: 'claude', installed: true, auth: 'yes' }, { engine: 'codex', installed: true, auth: 'yes' }],
        modelCatalog: {
          claude: [
            { value: 'claude-opus-5-5', label: 'Opus 5.5', priority: 0 },
            { value: 'claude-sonnet-5-5', label: 'Sonnet 5.5', priority: 2 },
          ],
          codex: [{ value: 'gpt-5.6-sol', label: 'GPT-5.6 Sol' }],
        },
      },
    })) as Runner;
    const hpcWorkspace = randomUUID();
    await prisma.workspace.create({
      data: { id: hpcWorkspace, ownerId: blockedOwner, runnerId: hpc.id, name: 'orbit-hpc', enabled: true, workDir: '/work/orbit' },
    });
    const tag = hpcWorkspace.slice(0, 8);
    const [anthropicPreset, anthropicEndpoint, deepseek, member] = await Promise.all([
      { slug: `anthropic-${tag}`, label: 'Anthropic', presetSlug: 'anthropic', followsPreset: true, baseUrl: 'https://api.anthropic.com' },
      { slug: `proxy-${tag}`, label: 'Anthropic endpoint', baseUrl: 'https://API.Anthropic.com./v1',
        models: [{ value: 'claude-sonnet-5-5', label: 'Sonnet' }] },
      { slug: `deepseek-${tag}`, label: 'DeepSeek', presetSlug: 'deepseek', followsPreset: true, baseUrl: 'https://api.deepseek.com/anthropic' },
      { slug: `member-${tag}`, label: 'Subscription', baseUrl: 'https://api.anthropic.com', models: [],
        apiKeyEnc: encryptSecret(`sk-ant-oat01-${tag}`) },
    ].map((row, position) => prisma.modelProvider.create({
      data: { runtime: 'claude', apiKeyEnc: 'x', ownerId: blockedOwner, position, ...row },
    })));
    const pool = await prisma.providerPool.create({ data: { slug: `team-${tag}`, label: 'Team', ownerId: blockedOwner, engine: 'claude' } });
    await prisma.providerPoolMember.create({ data: { poolId: pool.id, providerId: member.id, ownerId: blockedOwner } });

    const REFUSED = 'claude can’t use Anthropic on HPC';
    const anthropicBound = ['claude', anthropicPreset.slug, anthropicEndpoint.slug, member.slug, pool.slug];
    const answer = (await door.list({ id: randomUUID(), ownerId: blockedOwner } as never, 'orbit-hpc')) as WorkspaceProviderView;
    const on = (provider: string, engine = 'claude') => {
      const found = answer.pairs.find((entry) => entry.provider === provider && entry.engine === engine);
      assert.ok(found, `${provider} on ${engine} is listed`);
      return [found.usable, found.reason];
    };
    for (const provider of anthropicBound) assert.deepEqual(on(provider), [false, REFUSED], provider);
    assert.deepEqual(on(deepseek.slug), [true, undefined], 'a DeepSeek key on Claude Code is not Anthropic-bound');
    assert.deepEqual(on('codex', 'codex'), [true, undefined], 'another engine is not gated');

    // Routing on that runner — what a local or remote delegate there picks — removes the same with the same reason.
    const input = await subagentRouteInput(prisma, {
      ownerId: blockedOwner, workspaceId: hpcWorkspace, runnerId: hpc.id,
      dto: { toolUseId: 'toolu_01Region', type: 'general', definitionSource: 'builtin' },
      parent: { engine: 'claude', provider: 'claude', model: '', effort: null },
      runnerLabel: 'HPC',
    });
    const route = routeSubagent(input);
    t.diagnostic(`picked ${route.provider}/${route.engine}/${route.model}; removed ${JSON.stringify(route.candidates)}`);
    for (const provider of anthropicBound) {
      assert.deepEqual(route.candidates.filter((c) => c.provider === provider && c.engine === 'claude').map((c) => [c.model, c.reason]),
        [[null, REFUSED]], `${provider} is removed whole`);
      assert.equal(subagentCandidateRefusal(input, provider, 'claude'), REFUSED);
    }
    assert.ok(route.provider !== null && !anthropicBound.includes(route.provider), `routing picks no Anthropic credential: ${route.provider}`);
    assert.equal(subagentCandidateRefusal(input, deepseek.slug, 'claude'), null);
    assert.equal(subagentCandidateRefusal(input, 'codex', 'codex'), null);
  });

  await t.test('without workspace the list is listUsable, unchanged', async () => {
    assert.deepEqual(await door.list(asOwner), await providers.listUsable(ownerId));
    assert.deepEqual(await door.list(asOwner, undefined), await providers.listUsable(ownerId));
  });

  await t.test('an unknown workspace, or someone else, is refused', async () => {
    await assert.rejects(view('no-such-workspace'), refusedWith('WORKSPACE_NOT_FOUND'));
    const theirs = { id: randomUUID(), ownerId: strangerId } as never;
    await assert.rejects(door.list(theirs, 'orbit-ws03'), refusedWith('WORKSPACE_NOT_FOUND'), 'by name');
    await assert.rejects(door.list(theirs, workspaceId), refusedWith('WORKSPACE_NOT_FOUND'), 'by id');
  });
});
