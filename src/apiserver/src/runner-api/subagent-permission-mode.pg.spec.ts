/**
 * A SUBAGENT IS SPAWNED IN THE MODE IT ASKED FOR, AS A CLAIM HANDS A SESSION ITS OWN; EVERY SUBSTITUTION ITS SPAWN STILL
 * MAKES IS LOGGED AND RECORDED ON ITS ATTEMPT, AND THE PARENT'S STORED INTENT IS NEVER REWRITTEN.
 *
 * Project 350NMcNDulzkqRAFFUsXZ, criterion 55f38yosCj1Nw2KIal3Sn6. On real PostgreSQL, through the runner doors
 * (RunnerSubagentsController: POST /runner/sessions/:id/subagents and the target runner's claim of a remote run):
 *
 *   (1) A local SubAgent of an Auto parent on a Claude model whose catalogue row lists no Auto is spawned in Auto, with
 *       nothing substituted, nothing logged and nothing recorded on its attempt.
 *   (2) A remote SubAgent whose target runner's catalogue row lists no Auto for its default model is claimed in Auto
 *       the same way.
 *   (3) A scheduled run's SubAgent that asks for Default is spawned in Auto: its spawn writes a `claim-permission-mode`
 *       line naming the path, the parent session, the run, the model, the mode asked for, the mode handed and the
 *       reason, and its attempt records the substitution.
 *   (4) A Bypass parent's remote SubAgent on a root target runner is claimed in Auto, logged once at its first claim
 *       and recorded on its attempt; a claim sent again answers the same and logs nothing more.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/subagent-permission-mode.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mock, test } from 'node:test';

import { Logger } from '@nestjs/common';
import { type PrismaClient, type Runner, SessionDispatchOrigin } from '@prisma/client';
import { PermissionMode, type SubagentAttempt, type SubagentRemoteRunCreateResponse } from '@orbit/shared';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { prismaClientFor } from '../prisma/prisma-client';
import { assertCoordinatorPgUrlIsIsolated, verifyCoordinatorPgIdentity } from '../projects/coordinator-pg-test-safety';
import { RunnerSubagentsController } from './runner-subagents.controller';
import { SubagentRunCreateDto } from './subagent-run';

const URL = process.env.COORDINATOR_PG_URL;
process.env.PROVIDER_SECRET_KEY ??= 'subagent-permission-mode-spec';
const skip = !URL;

/** A collaborator whose every method answers nothing: the broadcasts the handlers fire. */
const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

const create = (fields: Partial<SubagentRunCreateDto> & { toolUseId: string }): SubagentRunCreateDto =>
  Object.assign(new SubagentRunCreateDto(), {
    type: 'general', definitionSource: 'builtin', prompt: 'Find every caller of the parser.', ...fields,
  });

/** A Claude model whose catalogue row withholds Auto (as the runner's probe reports one): the only one on offer. */
const WITHOUT_AUTO = 'claude-haiku-4-5-20251001';
const ALL_BUT_AUTO = [
  PermissionMode.DEFAULT, PermissionMode.ACCEPT_EDITS, PermissionMode.PLAN, PermissionMode.DONT_ASK, PermissionMode.BYPASS,
];
const CATALOG = { claude: [{ value: WITHOUT_AUTO, label: 'Haiku 4.5', priority: 0, permissionModes: ALL_BUT_AUTO }] };
const REPO = 'https://github.com/orbit-test/orbit.git';
const LINE = 'claim-permission-mode ';

test('the mode a SubAgent is spawned in, and every substitution its spawn still makes', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  const subagents = new RunnerSubagentsController(prisma as never, silent(), silent());
  const logged: string[] = [];
  const realLog = Logger.prototype.log;
  mock.method(Logger.prototype, 'log', function (this: Logger, message: unknown, ...rest: unknown[]) {
    if (typeof message === 'string') logged.push(message);
    return realLog.call(this, message, ...(rest as []));
  });
  t.after(async () => {
    mock.restoreAll();
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  async function account() {
    const ownerId = randomUUID();
    await prisma.user.create({
      data: {
        id: ownerId, email: `subagent-mode-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x',
        preferences: { defaultPermissionMode: PermissionMode.AUTO },
      },
    });
    return ownerId;
  }

  async function machine(ownerId: string, name: string, opts: { runsAsRoot?: boolean; capabilities?: string[] } = {}) {
    const id = randomUUID();
    return (await prisma.runner.create({
      data: {
        id, name, ownerId, tokenHash: sha256(`subagent-mode-${id}`),
        status: 'ONLINE', lastHeartbeatAt: new Date(),
        capabilities: opts.capabilities ?? ['os:linux'], capabilitiesReportedAt: new Date(),
        engines: [{ engine: 'claude', installed: true, auth: 'yes' }],
        runtimeDefaultModels: { claude: WITHOUT_AUTO },
        modelCatalog: CATALOG,
        runsAsRoot: opts.runsAsRoot ?? false,
      },
    })) as Runner;
  }

  async function workspace(ownerId: string, runner: Runner, name: string, position: number) {
    const id = randomUUID();
    await prisma.workspace.create({
      data: {
        id, ownerId, runnerId: runner.id, name, enabled: true, workDir: `/work/${name}`, repoUrl: REPO, workDirIsGit: true,
        position,
      },
    });
    return id;
  }

  /** A live parent session, claimed earlier in `mode` (its actual mode recorded as the claim records it). */
  async function parentIn(ownerId: string, workspaceId: string, runner: Runner, mode: PermissionMode, scheduleRunId?: string) {
    const sessionId = randomUUID();
    await prisma.session.create({
      data: {
        id: sessionId, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runner.id,
        title: 'split the parser work', prompt: 'split the parser work', provider: 'claude', engine: 'claude',
        model: WITHOUT_AUTO, effort: 'high', turnState: null, numTurns: 1,
        dispatchOrigin: SessionDispatchOrigin.USER, startsTaskWork: false, costUsd: 0,
        permissionMode: mode, actualPermissionMode: mode, actualPermissionModeAt: new Date(),
        ...(scheduleRunId ? { scheduleRunId } : {}),
      },
    });
    return sessionId;
  }

  async function attempts(runId: string): Promise<SubagentAttempt[]> {
    return (await prisma.subagentRun.findUniqueOrThrow({ where: { id: runId } })).attempts as unknown as SubagentAttempt[];
  }
  async function stored(sessionId: string) {
    return (await prisma.session.findUniqueOrThrow({ where: { id: sessionId }, select: { permissionMode: true } })).permissionMode;
  }
  const linesFor = (sessionId: string) =>
    logged.filter((l) => l.startsWith(LINE)).map((l) => JSON.parse(l.slice(LINE.length)) as Record<string, unknown>)
      .filter((l) => l.sessionId === sessionId);

  await t.test('(1) a local SubAgent on a model whose catalogue row lists no Auto is spawned in Auto', async () => {
    const ownerId = await account();
    const hpc = await machine(ownerId, 'workstation-gpu');
    const develop = await workspace(ownerId, hpc, 'orbit-develop', 0);
    const sessionId = await parentIn(ownerId, develop, hpc, PermissionMode.AUTO);

    const opened = await subagents.createSubagentRun(hpc, sessionId, create({ toolUseId: 'toolu_01LocalNoAutoRow' }));
    assert.equal(opened.exec.model, WITHOUT_AUTO, 'the child runs on the model whose row lists no Auto');
    assert.equal(opened.exec.permissionMode, PermissionMode.AUTO, 'and is spawned in the Auto asked for, not Default');
    const [first] = await attempts(opened.runId);
    assert.equal(first.permissionModeSubstitution, undefined, 'nothing substituted, nothing recorded');
    assert.deepEqual(linesFor(sessionId), [], 'nor logged');
    assert.equal(await stored(sessionId), PermissionMode.AUTO, "the parent's intent is untouched");
  });

  await t.test('(2) a remote SubAgent on a target whose catalogue row lists no Auto is claimed in Auto', async () => {
    const ownerId = await account();
    const hpc = await machine(ownerId, 'workstation-gpu');
    const mac = await machine(ownerId, 'mac-mini', { capabilities: ['os:darwin'] });
    const develop = await workspace(ownerId, hpc, 'orbit-develop', 0);
    await workspace(ownerId, mac, 'orbit-macos', 1);
    const sessionId = await parentIn(ownerId, develop, hpc, PermissionMode.AUTO);

    const opened = await subagents.openSubagentRun(hpc, sessionId, create({
      toolUseId: 'toolu_01RemoteNoAutoRow', workspace: 'orbit-macos',
    })) as SubagentRemoteRunCreateResponse;
    const claim = await subagents.claimRemoteSubagentRun(mac, opened.runId);
    assert.equal(claim.exec.model, WITHOUT_AUTO);
    assert.equal(claim.exec.permissionMode, PermissionMode.AUTO, 'the target runner is handed Auto, not Default');
    assert.equal((await attempts(opened.runId)).at(-1)?.permissionModeSubstitution, undefined);
    assert.deepEqual(linesFor(sessionId), []);
    assert.equal(await stored(sessionId), PermissionMode.AUTO);
  });

  await t.test("(3) a scheduled run's SubAgent that asks for Default is spawned in Auto, logged and recorded", async () => {
    const ownerId = await account();
    const hpc = await machine(ownerId, 'workstation-gpu');
    const develop = await workspace(ownerId, hpc, 'orbit-develop', 0);
    const schedule = await prisma.schedule.create({
      data: {
        ownerId, workspaceId: develop, intent: 'Every morning, check the nightly build',
        title: 'Nightly build check', prompt: 'Check the nightly build.', rule: { kind: 'DAILY' }, timezone: 'UTC',
        startAt: new Date(), accessLevel: 'CHECK_ONLY', envelopeWorkspaceId: develop, envelopeAccessLevel: 'CHECK_ONLY',
        envelopeRunsPerWeek: 7, envelopeRunLimitMinutes: 30,
      },
    });
    const run = await prisma.scheduleRun.create({
      data: {
        scheduleId: schedule.id, scheduleRevision: 1, plannedAt: new Date(), trigger: 'SCHEDULED', state: 'RUNNING',
        startedAt: new Date(), accessLevel: 'CHECK_ONLY',
      },
    });
    const sessionId = await parentIn(ownerId, develop, hpc, PermissionMode.AUTO, run.id);

    const opened = await subagents.createSubagentRun(hpc, sessionId, create({
      toolUseId: 'toolu_01ScheduledChild', permissionMode: PermissionMode.DEFAULT,
    }));
    assert.equal(opened.exec.permissionMode, PermissionMode.AUTO, 'a scheduled run on Claude Code runs in Auto');
    const substitution = { requestedMode: PermissionMode.DEFAULT, mode: PermissionMode.AUTO, reason: 'SCHEDULED_RUN' };
    assert.deepEqual((await attempts(opened.runId))[0].permissionModeSubstitution, substitution, 'recorded on its attempt');
    assert.deepEqual(linesFor(sessionId), [{
      sessionId,
      path: 'SUBAGENT',
      subagentRunId: opened.runId,
      provider: 'claude',
      model: WITHOUT_AUTO,
      from: PermissionMode.DEFAULT,
      to: PermissionMode.AUTO,
      reason: 'SCHEDULED_RUN',
    }], 'and logged once');
    // A retry answers with the run it opened, and logs nothing more.
    await subagents.createSubagentRun(hpc, sessionId, create({ toolUseId: 'toolu_01ScheduledChild', permissionMode: PermissionMode.DEFAULT }));
    assert.equal(linesFor(sessionId).length, 1);
    assert.equal(await stored(sessionId), PermissionMode.AUTO);
  });

  await t.test("(4) a Bypass parent's remote SubAgent on a root target is claimed in Auto, logged and recorded", async () => {
    const ownerId = await account();
    const hpc = await machine(ownerId, 'workstation-gpu');
    const box = await machine(ownerId, 'root-box', { runsAsRoot: true, capabilities: ['os:linux', 'gpu'] });
    const develop = await workspace(ownerId, hpc, 'orbit-develop', 0);
    await workspace(ownerId, box, 'orbit-root', 1);
    const sessionId = await parentIn(ownerId, develop, hpc, PermissionMode.BYPASS);

    const opened = await subagents.openSubagentRun(hpc, sessionId, create({
      toolUseId: 'toolu_01RootTarget', workspace: 'orbit-root',
    })) as SubagentRemoteRunCreateResponse;
    assert.equal((await attempts(opened.runId))[0].permissionModeSubstitution, undefined, 'nothing is handed before the claim');
    const claim = await subagents.claimRemoteSubagentRun(box, opened.runId);
    assert.equal(claim.exec.permissionMode, PermissionMode.AUTO, 'Claude Code exits under root in Bypass, so the child gets Auto');
    const substitution = { requestedMode: PermissionMode.BYPASS, mode: PermissionMode.AUTO, reason: 'ROOT_RUNNER' };
    assert.deepEqual((await attempts(opened.runId)).at(-1)?.permissionModeSubstitution, substitution);
    const line = {
      sessionId,
      path: 'SUBAGENT',
      subagentRunId: opened.runId,
      provider: 'claude',
      model: WITHOUT_AUTO,
      from: PermissionMode.BYPASS,
      to: PermissionMode.AUTO,
      reason: 'ROOT_RUNNER',
    };
    assert.deepEqual(linesFor(sessionId), [line]);

    const again = await subagents.claimRemoteSubagentRun(box, opened.runId);
    assert.equal(again.exec.permissionMode, PermissionMode.AUTO, 'a claim sent again answers the same');
    assert.deepEqual(linesFor(sessionId), [line], 'and logs nothing more');
    assert.deepEqual((await attempts(opened.runId)).at(-1)?.permissionModeSubstitution, substitution);
    assert.equal(await stored(sessionId), PermissionMode.BYPASS, "the parent's intent is untouched");
  });
});
