/**
 * The SubAgent lifecycle on the server (docs/subagent-design.md §2, §5.2), on a real PostgreSQL, through the runner
 * doors and SessionsService.createTurn:
 *
 *   1. Turn end with a background SubAgent running: the parent is parked between turns (AWAITING_INPUT) and still
 *      reads as working, its delegate call in runningSubagents; when the run's end is reported, a wake turn is
 *      filed for it and is delivered as `<orbit-subagent-finished>`.
 *   4. Runner restart: a run the replaced runner process left RUNNING is ended INTERRUPTED when the next process
 *      takes the session over, and the parent is woken with the reason. A runner that stopped in good order and
 *      reported INTERRUPTED itself wakes the parent with the same reason.
 *   5. The wording: a SubAgent's wake names the SubAgent by its description and run and says nothing of bg_run,
 *      while a bg_run job's wake on the same turn keeps `<background-job-wake>` and its own words.
 *   1b. A SubAgent still running when the parent's engine is rebuilt (`resumed`) is announced again by the runner,
 *      and goes back into runningSubagents, never into the bg job sets.
 *   3b. A SubAgent stopped because the session moved to another runner process is STOPPED owing a wake, and the
 *      wake names the reason and the files it left uncommitted.
 *   6. A foreground delegate past its tool timeout: the runner's RUNNING report with wake: true makes the server
 *      hold the wake, so a runner restart still wakes the parent — here filed by the wake sweep, the takeover's
 *      own filing having had no SessionsService — and a detach that arrives after the end files it at once.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/subagent-lifecycle.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { type PrismaClient, type Runner, RunStatus, SessionDispatchOrigin } from '@prisma/client';
import { RunEventType, uuidToBase62 } from '@orbit/shared';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { prismaClientFor } from '../prisma/prisma-client';
import type { PrismaService } from '../prisma/prisma.service';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { SessionsService } from '../sessions/sessions.service';
import { appendBackgroundWakeContext, BACKGROUND_WAKE_TURN_PREFIX, BackgroundWakeDto } from './background-job-wake';
import { RunnerApiController } from './runner-api.controller';
import { RunnerSubagentsController } from './runner-subagents.controller';
import { ScheduledWakeupWorker } from './scheduled-wakeup.worker';
import { SubagentRunCreateDto, SubagentRunUpdateDto } from './subagent-run';

const URL = process.env.COORDINATOR_PG_URL;
process.env.PROVIDER_SECRET_KEY ??= 'subagent-lifecycle-spec';
const skip = !URL;

/** A collaborator whose every method answers nothing: the broadcasts the handlers fire. */
const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

const create = (fields: Partial<SubagentRunCreateDto> & { toolUseId: string }): SubagentRunCreateDto =>
  Object.assign(new SubagentRunCreateDto(), { type: 'general', definitionSource: 'builtin', ...fields });

const update = (fields: Partial<SubagentRunUpdateDto>): SubagentRunUpdateDto =>
  Object.assign(new SubagentRunUpdateDto(), fields);

test('SubAgent lifecycle: turn end, runner restart, the wake and its wording', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  const runnerId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `subagent-life-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  const runner = (await prisma.runner.create({
    data: { id: runnerId, name: 'the machine the parent runs on', ownerId, tokenHash: sha256(`subagent-life-${runnerId}`) },
  })) as Runner;

  const sessions = new SessionsService(
    prisma as unknown as PrismaService, { notifySessionQueued: () => undefined } as never, silent(),
  );
  /** The runner door, with the SessionsService that files wakes — or without one, as `bare` is. */
  const doorWith = (svc?: SessionsService) => new RunnerApiController(
    prisma as never, silent(), silent(), silent(), silent(), silent(),
    undefined, undefined, undefined, undefined, undefined, svc,
  );
  const door = doorWith(sessions);
  const bare = doorWith();
  const subagents = new RunnerSubagentsController(prisma as never, silent(), silent(), sessions);
  const sweep = new ScheduledWakeupWorker(prisma as never, sessions);

  /** A parent session of that runner, parked between turns: the state the end of a turn leaves it in. */
  async function parkedParent(): Promise<string> {
    const workspaceId = randomUUID();
    await prisma.workspace.create({
      data: { id: workspaceId, ownerId, runnerId, name: `orbit-worker-${workspaceId.slice(-8)}`, enabled: true },
    });
    const sessionId = randomUUID();
    await prisma.session.create({
      data: {
        id: sessionId, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title: 'split the parser work', prompt: 'split the parser work', provider: 'claude', engine: 'claude',
        model: 'claude-opus-5-5', effort: 'high', status: RunStatus.AWAITING_INPUT, numTurns: 1,
        dispatchOrigin: SessionDispatchOrigin.USER, startsTaskWork: false,
      },
    });
    return sessionId;
  }

  const wakeTurns = (sessionId: string) =>
    prisma.conversationTurn.findMany({
      where: { sessionId, clientTurnId: { startsWith: BACKGROUND_WAKE_TURN_PREFIX } },
      orderBy: { seq: 'asc' },
    });

  /** What the runner is handed for the session's one wake turn. */
  async function delivered(sessionId: string): Promise<string> {
    const turns = await wakeTurns(sessionId);
    assert.equal(turns.length, 1, `want one wake turn, found ${turns.length}`);
    return String(await appendBackgroundWakeContext(prisma, sessionId, turns[0].clientTurnId!, turns[0].content));
  }

  await t.test('(1) turn end with a background SubAgent running: the session stays Running, and the wake arrives when it ends', async () => {
    const sessionId = await parkedParent();
    const leaseOwner = randomUUID();
    await door.takeoverLeases(runner, sessionId, { leaseOwner, expectedLeaseOwner: null } as never);
    let seq = 0;
    const report = (events: Array<{ type: RunEventType; payload: unknown }>) =>
      door.events(runner, sessionId, {
        leaseOwner,
        events: events.map((event) => ({ ...event, seq: ++seq, ts: new Date().toISOString() })) as never,
      });

    const opened = await subagents.createSubagentRun(runner, sessionId, create({
      toolUseId: 'toolu_01Split', background: true, description: 'split the parser',
    }));
    await report([
      { type: RunEventType.TOOL_USE, payload: {
        id: 'toolu_01Split', name: 'mcp__orbit__delegate',
        input: { description: 'split the parser', prompt: 'split src/parser', background: true } } },
      { type: RunEventType.TOOL_RESULT, payload: {
        toolUseId: 'toolu_01Split', content: [{ type: 'text', text: `{"runId":"${opened.runId}","status":"running"}` }] } },
    ]);
    // The turn ended. The parent is parked, and still at work: the list's "Running Agent".
    await prisma.session.update({ where: { id: sessionId }, data: { status: RunStatus.AWAITING_INPUT } });
    const parked = await prisma.session.findUniqueOrThrow({ where: { id: sessionId } });
    assert.equal(parked.status, RunStatus.AWAITING_INPUT);
    assert.deepEqual(parked.runningSubagents, ['toolu_01Split'], 'the running SubAgent keeps the parked session working');
    assert.equal((await prisma.subagentRun.findUniqueOrThrow({ where: { id: opened.runId } })).wakeOwed, true,
      'a background run owes its parent a wake from the start');
    assert.equal((await wakeTurns(sessionId)).length, 0, 'nothing wakes the parent while the SubAgent runs');

    const ended = await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({
      status: 'DONE', resultSummary: 'The parser is split into lexer.ts and grammar.ts.',
      changedFiles: ['src/parser/lexer.ts'], costUsd: 0.05, wake: true,
    }));
    assert.equal(ended.applied, true);
    await report([{ type: RunEventType.BACKGROUND_TASK, payload: { status: 'completed', toolUseId: 'toolu_01Split', subagentRunId: opened.runId } }]);

    const turns = await wakeTurns(sessionId);
    assert.equal(turns.length, 1, 'the end of the SubAgent is one wake turn');
    assert.equal(turns[0].clientTurnId, `${BACKGROUND_WAKE_TURN_PREFIX}${uuidToBase62(opened.runId)}:exit`);
    assert.equal(turns[0].status, 'PENDING');
    assert.ok(!turns[0].content, 'the wake records no words as the person\'s');
    assert.equal((await prisma.session.findUniqueOrThrow({ where: { id: sessionId } })).status, RunStatus.PENDING,
      'the wake asked for a runner slot: the parent is woken');
    const content = await delivered(sessionId);
    assert.match(content, /<orbit-subagent-finished>/);
    assert.ok(content.includes(`SubAgent split the parser (run ${uuidToBase62(opened.runId)}) finished: DONE`), content);
    assert.ok(content.includes('The parser is split into lexer.ts and grammar.ts.'), content);
    const row = await prisma.subagentRun.findUniqueOrThrow({ where: { id: opened.runId } });
    assert.ok(row.wakeFiledAt, 'the wake is settled filed');

    // A repeated report adds no second wake.
    await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({ status: 'DONE', wake: true }));
    assert.equal((await wakeTurns(sessionId)).length, 1);
  });

  await t.test('(4) runner restart: a run left RUNNING is INTERRUPTED at the takeover, and the parent is woken with the reason', async () => {
    const sessionId = await parkedParent();
    const before = randomUUID();
    await door.takeoverLeases(runner, sessionId, { leaseOwner: before, expectedLeaseOwner: null } as never);
    const opened = await subagents.createSubagentRun(runner, sessionId, create({
      toolUseId: 'toolu_01Orphan', background: true, description: 'sweep the lexer',
    }));

    // The runner process died without reporting; the next one takes the session over.
    const after = randomUUID();
    await door.takeoverLeases(runner, sessionId, { leaseOwner: after, expectedLeaseOwner: before } as never);
    const row = await prisma.subagentRun.findUniqueOrThrow({ where: { id: opened.runId } });
    assert.equal(row.status, 'INTERRUPTED');
    assert.ok(row.endedAt && row.wakeOwed && row.wakeFiledAt, 'ended, owing a wake that is filed');
    const content = await delivered(sessionId);
    assert.ok(content.includes(`SubAgent sweep the lexer (run ${uuidToBase62(opened.runId)}) finished: INTERRUPTED`), content);
    assert.ok(content.includes('The runner process hosting it stopped'), `the reason is not given:\n${content}`);
    assert.ok(content.includes('before it reported an end'), content);

    // The same process taking it over again changes nothing, and a later report of the run applies nothing.
    await door.takeoverLeases(runner, sessionId, { leaseOwner: after, expectedLeaseOwner: before } as never);
    const late = await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({ status: 'DONE', wake: true }));
    assert.equal(late.applied, false);
    assert.equal((await wakeTurns(sessionId)).length, 1);

    // A runner that stopped in good order reports INTERRUPTED itself, and the parent hears the same reason.
    const graceful = await parkedParent();
    const ran = await subagents.createSubagentRun(runner, graceful, create({ toolUseId: 'toolu_01Graceful', description: 'rename the tokens' }));
    await subagents.updateSubagentRun(runner, graceful, ran.runId, update({
      status: 'INTERRUPTED', wake: true,
      resultSummary: 'The SubAgent was interrupted: the runner process hosting it stopped (a restart or an update).',
    }));
    const said = await delivered(graceful);
    assert.ok(said.includes(`SubAgent rename the tokens (run ${uuidToBase62(ran.runId)}) finished: INTERRUPTED`), said);
    assert.ok(said.includes('The runner process hosting it stopped'), said);
  });

  await t.test('(5) a SubAgent\'s wake names the SubAgent and never bg_run, and a bg_run job\'s keeps its own words', async () => {
    const sessionId = await parkedParent();
    const opened = await subagents.createSubagentRun(runner, sessionId, create({
      toolUseId: 'toolu_01Words', background: true, description: 'check the grammar tests',
    }));
    await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({
      status: 'FAILED', resultSummary: 'grammar.test.ts fails on the empty input.', wake: true,
    }));
    const alone = await delivered(sessionId);
    assert.ok(alone.includes(`SubAgent check the grammar tests (run ${uuidToBase62(opened.runId)}) finished: FAILED`), alone);
    assert.ok(!alone.includes('bg_run'), `a SubAgent's wake speaks of bg_run:\n${alone}`);
    assert.ok(!alone.includes('<background-job-wake>'), alone);

    // A real bg_run job's exit lands on the same queued wake turn: each keeps its own block and words.
    const job = 'bgj_0123456789ab';
    const wake = Object.assign(new BackgroundWakeDto(), {
      wakeId: `${job}:exit`, jobId: job, trigger: 'exit', kind: 'job', command: 'npm test', status: 'failed', exitCode: 1,
      outputPath: `/root/.orbit/runs/x/${job}.output`, outputOffset: 0, outputSize: 20, outputExcerpt: 'FAIL grammar.test.ts',
    });
    const receipt = await door.backgroundWake(runner, sessionId, wake);
    assert.equal(receipt.outcome, 'MERGED', 'the job\'s wake joins the wake turn still queued');
    const both = await delivered(sessionId);
    const subagentBlock = both.slice(both.indexOf('<orbit-subagent-finished>'), both.indexOf('</orbit-subagent-finished>'));
    const jobBlock = both.slice(both.indexOf('<background-job-wake>'), both.indexOf('</background-job-wake>'));
    assert.ok(subagentBlock && jobBlock, both);
    assert.ok(!subagentBlock.includes('bg_run') && !subagentBlock.includes(job), subagentBlock);
    assert.ok(jobBlock.includes('A background job you started with bg_run has news'), jobBlock);
    assert.ok(jobBlock.includes(job) && !jobBlock.includes(uuidToBase62(opened.runId)), jobBlock);
  });

  await t.test('(6) a foreground delegate past its tool timeout still wakes the parent after a runner restart', async () => {
    const sessionId = await parkedParent();
    const before = randomUUID();
    await door.takeoverLeases(runner, sessionId, { leaseOwner: before, expectedLeaseOwner: null } as never);
    const opened = await subagents.createSubagentRun(runner, sessionId, create({
      toolUseId: 'toolu_01Long', description: 'port the parser tests',
    }));
    assert.equal((await prisma.subagentRun.findUniqueOrThrow({ where: { id: opened.runId } })).wakeOwed, false,
      'a foreground run is answered inline');

    // The tool call ran out of time: the runner says so, and the server holds the wake from here.
    const detached = await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({ status: 'RUNNING', wake: true }));
    assert.deepEqual(detached, { runId: opened.runId, status: 'RUNNING', applied: true });
    assert.equal((await prisma.subagentRun.findUniqueOrThrow({ where: { id: opened.runId } })).wakeOwed, true);
    assert.equal((await wakeTurns(sessionId)).length, 0, 'nothing is filed while it runs');
    await assert.rejects(
      subagents.updateSubagentRun(runner, sessionId, opened.runId, update({ status: 'RUNNING' })),
      /wake: true/, 'a RUNNING report that owes nothing is refused',
    );

    // The runner restarts before the run ends. This takeover files nothing itself (no SessionsService), so the
    // wake is the sweep's — the server's own record is all that is left of the intent.
    const after = randomUUID();
    await bare.takeoverLeases(runner, sessionId, { leaseOwner: after, expectedLeaseOwner: before } as never);
    assert.equal((await prisma.subagentRun.findUniqueOrThrow({ where: { id: opened.runId } })).status, 'INTERRUPTED');
    assert.equal((await wakeTurns(sessionId)).length, 0);
    const outcomes = await sweep.fileOwedSubagentWakes();
    assert.ok(outcomes.includes('FILED'), `the sweep filed nothing: ${outcomes.join(', ')}`);
    const content = await delivered(sessionId);
    assert.ok(content.includes(`SubAgent port the parser tests (run ${uuidToBase62(opened.runId)}) finished: INTERRUPTED`), content);
    assert.ok(content.includes('The runner process hosting it stopped'), content);
    assert.ok(!(await sweep.fileOwedSubagentWakes()).includes('FILED'), 'a filed wake is not filed again');

    // A detach that arrives after the run's end (the two race on the runner) files the wake at once.
    const raced = await parkedParent();
    const run = await subagents.createSubagentRun(runner, raced, create({ toolUseId: 'toolu_01Raced', description: 'fix the lexer' }));
    await subagents.updateSubagentRun(runner, raced, run.runId, update({ status: 'DONE', resultSummary: 'Fixed.' }));
    assert.equal((await wakeTurns(raced)).length, 0, 'a foreground end nobody detached from is answered inline');
    await subagents.updateSubagentRun(runner, raced, run.runId, update({ status: 'RUNNING', wake: true }));
    assert.ok((await delivered(raced)).includes(`SubAgent fix the lexer (run ${uuidToBase62(run.runId)}) finished: DONE`));
  });

  await t.test('(1b) after the parent engine resumes, the runner\'s re-announcement puts a running SubAgent back in runningSubagents', async () => {
    const sessionId = await parkedParent();
    const leaseOwner = randomUUID();
    await door.takeoverLeases(runner, sessionId, { leaseOwner, expectedLeaseOwner: null } as never);
    let seq = 0;
    const report = (events: Array<{ type: RunEventType; payload: unknown }>) =>
      door.events(runner, sessionId, {
        leaseOwner,
        events: events.map((event) => ({ ...event, seq: ++seq, ts: new Date().toISOString() })) as never,
      });
    const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_01Resume', background: true }));
    await report([
      { type: RunEventType.TOOL_USE, payload: { id: 'toolu_01Resume', name: 'mcp__orbit__delegate', input: { background: true } } },
      { type: RunEventType.TOOL_RESULT, payload: {
        toolUseId: 'toolu_01Resume', content: [{ type: 'text', text: `{"runId":"${opened.runId}","status":"running"}` }] } },
    ]);
    const read = () => prisma.session.findUniqueOrThrow({
      where: { id: sessionId }, select: { runningSubagents: true, runningBgJobs: true, runningBgShells: true },
    });
    assert.deepEqual((await read()).runningSubagents, ['toolu_01Resume']);

    // The engine is rebuilt: the handshake empties the set, and the runner announces the SubAgent again behind it.
    await report([{ type: RunEventType.SYSTEM, payload: { subtype: 'resumed', reason: 'config_changed' } }]);
    assert.deepEqual((await read()).runningSubagents, [], 'the handshake empties the running set');
    await report([{ type: RunEventType.BACKGROUND_TASK, payload: {
      toolUseId: 'toolu_01Resume', status: 'running', kind: 'subagent', subagentRunId: uuidToBase62(opened.runId) } }]);
    const after = await read();
    assert.deepEqual(after.runningSubagents, ['toolu_01Resume'], 'the re-announcement puts the SubAgent back: the session reads as working');
    assert.deepEqual(after.runningBgJobs, [], 'a SubAgent is not a bg job');
    assert.deepEqual(after.runningBgShells, [], 'nor a background shell');
  });

  await t.test('(3b) a SubAgent stopped by a handoff to another runner process wakes the parent with the reason and what it left uncommitted', async () => {
    const sessionId = await parkedParent();
    const opened = await subagents.createSubagentRun(runner, sessionId, create({
      toolUseId: 'toolu_01Moved', background: true, description: 'regenerate the clients',
    }));
    const runId = uuidToBase62(opened.runId);
    await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({
      status: 'STOPPED', wake: true,
      resultSummary: 'The SubAgent was stopped when this session moved to another runner process. What it changed so far' +
        ` is in the working tree, uncommitted.\n\nLeft uncommitted because SubAgent ${runId} was stopped while they changed: gen/client.ts`,
    }));
    const content = await delivered(sessionId);
    assert.ok(content.includes(`SubAgent regenerate the clients (run ${runId}) finished: STOPPED`), content);
    assert.ok(content.includes('stopped when this session moved to another runner process'), content);
    assert.ok(content.includes(`Left uncommitted because SubAgent ${runId} was stopped while they changed: gen/client.ts`), content);
    assert.ok(!content.includes('bg_run'), content);
  });

  await t.test('a parent that has ended is not woken, and its wake is settled so the sweep leaves it', async () => {
    const sessionId = await parkedParent();
    const opened = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_01Gone', background: true }));
    await prisma.session.update({ where: { id: sessionId }, data: { status: RunStatus.CANCELLED, endReason: 'ended' } });
    await subagents.updateSubagentRun(runner, sessionId, opened.runId, update({ status: 'DONE', wake: true }));
    assert.equal((await wakeTurns(sessionId)).length, 0);
    assert.ok((await prisma.subagentRun.findUniqueOrThrow({ where: { id: opened.runId } })).wakeFiledAt);
  });
});
