/**
 * The runner link gateway's merged event call, end to end (docs/runner-link-design.md §6.6, §6.7; link-events.ts,
 * RunnerApiController.ingestLinkEventCall, src/link-gateway/events_merge.go).
 *
 * WHAT THIS DRIVES
 * ----------------
 * The real RunnerApiController and RunnerLinkEventsController over a disposable PostgreSQL, with main.ts's error
 * boundaries, reached as the gateway reaches them: POST /api/runner/link/events through the internal listener with the
 * gateway's secret, each batch beside its connection's link token and headers; and, for every batch that call answers
 * `sendAlone`, the events route on its own, as the gateway then forwards it. Two accounts, each with a runner of its
 * own, connected through the same gateway. A second apiserver on the same database is the gateway's other backend; a
 * second RealtimeService, listening on the database, is another replica a client could be watching from.
 *
 * WHAT IT ASSERTS
 * ---------------
 *   (1) One call, batches of two accounts' runners: each stored and answered as the events route answers it, in one
 *       transaction whose lock hold it reports; the other replicas hear of each batch once, of what was stored, and
 *       this replica's streams of every event; the spend fuse is asked only about the session coordinating a project.
 *   (2) A batch the call cannot take is answered `sendAlone`, and nothing of it is written: another process's lease, a
 *       session no longer open, a landing, a batch that is not one, a revoked connection, a value the database refuses
 *       (the call's one run_event insert fails, the next run has each batch insert its own and finds it, and the call
 *       runs again without it). The others are stored. Sent alone, each is answered as the events route has
 *       always answered it, the refused value as EVENT_UNSTORABLE behind its tombstone.
 *   (3) Tenants: one account's connection naming the other account's session is sent alone, refused there, and that
 *       session gets nothing written and nothing derived, while both accounts' own batches in the call are stored.
 *   (4) Stored once per seq: the same call sent again; a session another writer holds, skipped (SKIP LOCKED) and stored
 *       alone after it; two copies of one call on the two backends at once, the session of one batch held until both
 *       have been sent alone and wait for it.
 *   (5) The same batches through the merged call and through the events route alone leave the same rows — events,
 *       tombstones, tool calls — the same derived session state, the same answers and the same notifications.
 *   (6) The reruns are bounded: a call whose batches the database refuses values of runs its transaction three times,
 *       then sends every batch left alone, the good one among them.
 *   (7) A merged transaction that would wait on a row another transaction holds is cut short by its lock timeout and
 *       sends every batch alone, with nothing written.
 *   (8) The route is the gateway's alone (HTTPS answers 404), a body that is not a merged call is 400, and HTTPS ingest
 *       is answered as it always was.
 *   (9) A batch at a seq the session holds another event at is answered as alone, the row there left as it was, and the
 *       event logged as an error and counted (run-event-seq-conflicts.ts); the same event sent again is neither.
 *
 * Every state is read on a second connection, never through the answer that wrote it.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/runner-link-merged-events.pg.spec.ts
 *
 * Needs COORDINATOR_PG_URL (the script provides a disposable one). Not destructive: every id is generated by the run.
 */
