/**
 * A runner-hosted background job that asked to wake its session is delivered to it as a turn,
 * through the runner door: `POST /api/runner/sessions/:id/background-wake`.
 *
 * The job may end hours after the engine that started it was recycled, so the wake cannot be the
 * engine's own: the runner reports it, and the control plane files it as a turn that goes through
 * the same queue, claim and inbox as any other. Three facts, each over real HTTP and against real
 * PostgreSQL:
 *
 *   1. A wake is one turn. The inbox hands it out with the wake written into it — which job, how it
 *      ended, the end of its output and where the rest is — and what the runner echoes back is
 *      stored as the control plane's note. None of it is recorded as words the person typed.
 *   2. Wakes nobody has been handed yet are one turn however many arrive, and a job's later wake
 *      replaces its earlier one. A wake after delivery is a turn of its own.
 *   3. A session that has ended is not woken: nothing is queued and nothing is revived. The same
 *      request to a session that is still open is.
 *   4. A job that is still running and has written nothing for as long as it asked (`wakeOnStall`)
 *      wakes its session in a block of its own, `<background-job-stall>`: which job, how long it has
 *      run, when it last wrote — on this clock, from the silence the runner reports — the end of its
 *      output, the file and how to read it. It is never written into a running turn, and a job's exit
 *      comes first: a stall arriving after the exit is dropped, and an exit replaces a stall.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/runner-api/background-job-wake.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
