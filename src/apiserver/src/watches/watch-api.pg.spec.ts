test('the canonical "all terminal or any failed" request fires through its ANY branch at create, and does not fire without one', { skip, timeout: 120_000 }, async () => {
  const h = await boot();
  const owner = await account(h, 'canonical');
  const vector = CONTRACT.vectors.find((candidate: { id: string }) => candidate.id === 'all-terminal-or-any-failed');
  const statuses: string[] = vector.given.tasks;
  const ids: string[] = [];
  for (const status of statuses) ids.push(await task(h, owner.id, status));

  const watch = await create(h, owner, watchBody(tasks(ids), { predicate: vector.given.predicate }), 'the canonical request');
  assert.equal(watch.state, vector.expect.matches ? 'MATCHED' : 'ACTIVE');
  // The reason counts each operand's leaf over the set; the operand whose count holds is the branch that fired.
  const operands = /^ANY_OF\((.*)\)$/.exec(watch.matches[0].reason)?.[1].split(', ') ?? [];
  assert.deepEqual(operands, ['ALL TASK_TERMINAL 4/7', 'ANY TASK_FAILED 1/7']);
  const holds = (operand: string) => {
    const [kind, , count] = operand.split(' ');
    const [held, of] = count.split('/').map(Number);
    return kind === 'ALL' ? held === of : held > 0;
  };
  assert.equal(operands.findIndex(holds), vector.expect.viaOperand, 'the branch the contract says fires is the one that held');
  const stateOf = statesById(watch.matches[0].perTargetSnapshot.targets);
  statuses.forEach((status, index) => {
    const terminal = ['DONE', 'CANCELLED', 'FAILED'].includes(status);
    assert.equal(stateOf.get(ids[index]), terminal ? 'SATISFIED' : 'OBSERVED', `a ${status} target`);
  });

  // The paired negative: nothing failed and not everything is terminal, so neither branch holds.
  const quiet = [await task(h, owner.id, 'DONE'), await task(h, owner.id, 'IN_PROGRESS')];
  const waiting = await create(h, owner, watchBody(tasks(quiet), { predicate: vector.given.predicate }), 'no branch holds');
  assert.equal(waiting.state, 'ACTIVE');
  assert.equal(waiting.matches.length, 0);

  const allOf = await create(
    h,
    owner,
    watchBody(tasks([ids[0], ids[1]]), {
      predicate: { kind: 'ALL_OF', operands: [{ kind: 'ANY', over: 'ALL_TARGETS', leaf: 'TASK_DONE' }, ALL_TERMINAL] },
    }),
    'an ALL_OF whose operands both hold',
  );
  assert.equal(allOf.state, 'MATCHED');
  assert.equal(allOf.matches[0].reason, 'ALL_OF(ANY TASK_DONE 2/2, ALL TASK_TERMINAL 2/2)');
});

