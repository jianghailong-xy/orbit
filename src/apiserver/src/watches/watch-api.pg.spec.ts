test('the served schema is the frozen contract: its predicate version, leaves, kinds, actions, states, refusal codes and limits', () => {
  assert.equal(WATCH_PREDICATE_VERSION, CONTRACT.predicateVersion);
  const contractLeaves = Object.fromEntries(
    Object.entries(CONTRACT.leaves as Record<string, { targetKind: string }>).map(([leaf, { targetKind }]) => [leaf, targetKind]),
  );
  assert.deepEqual(WATCH_LEAVES, contractLeaves);
  // The door and the evaluator read one grammar: what the API accepts is what gets decided.
  assert.deepEqual(WATCH_LEAF_TARGET_KIND, contractLeaves);
  assert.equal(EVALUATED_PREDICATE_VERSION, CONTRACT.predicateVersion);
  assert.deepEqual([...WATCH_RESOURCE_KINDS], CONTRACT.resourceKinds);
  assert.deepEqual([...WATCH_ACTIONS], CONTRACT.actions.map((action: { kind: string }) => action.kind));
  assert.deepEqual([...WATCH_STATES], CONTRACT.states.watch.values);
  assert.deepEqual([...WATCH_REFUSAL_CODES].sort(), CONTRACT.refusals.map((refusal: { code: string }) => refusal.code).sort());
  for (const [limit, value] of Object.entries(WATCH_LIMITS)) {
    assert.equal(value, CONTRACT.limits[limit], `limits.${limit}`);
  }
});

test('a predicate outside the v1 grammar is refused with the contract code, and nothing is written', { skip, timeout: 120_000 }, async () => {
  const h = await boot();
  const owner = await account(h, 'grammar');
  const done = await task(h, owner.id, 'DONE');
  const targets = tasks([done]);

  const refused: Array<[string, Record<string, unknown>, string]> = [
    ['a shell command', { predicate: { kind: 'SHELL', command: 'test -f /tmp/done' } }, 'UNKNOWN_PREDICATE_KIND'],
    ['a SQL query', { predicate: { kind: 'SQL', query: 'SELECT true FROM task' } }, 'UNKNOWN_PREDICATE_KIND'],
    ['a log regex', { predicate: { kind: 'LOG_REGEX', pattern: 'status=DONE$' } }, 'UNKNOWN_PREDICATE_KIND'],
    ['a free-text expression', { predicate: "task.status == 'DONE'" }, 'UNKNOWN_PREDICATE_KIND'],
    ['a script riding on a valid term', { predicate: { ...ALL_TERMINAL, script: 'rm -rf /' } }, 'UNKNOWN_PREDICATE_KIND'],
    ['a leaf outside the seven', { predicate: { ...ALL_TERMINAL, leaf: 'TASK_TERMINAL; DROP TABLE task' } }, 'UNKNOWN_PREDICATE_KIND'],
    ['a selector outside ALL_TARGETS', { predicate: { ...ALL_TERMINAL, over: 'SELECT id FROM task' } }, 'UNKNOWN_PREDICATE_KIND'],
    ['a composite with no operands', { predicate: { kind: 'ALL_OF', operands: [] } }, 'UNKNOWN_PREDICATE_KIND'],
    ['an array', { predicate: [ALL_TERMINAL] }, 'UNKNOWN_PREDICATE_KIND'],
    ['no predicate', { predicate: undefined }, 'UNKNOWN_PREDICATE_KIND'],
    [
      'three terms deep',
      { predicate: { kind: 'ANY_OF', operands: [{ kind: 'ALL_OF', operands: [ALL_TERMINAL] }] } },
      'PREDICATE_TOO_DEEP',
    ],
    ['five operands', { predicate: { kind: 'ANY_OF', operands: Array(5).fill(ALL_TERMINAL) } }, 'PREDICATE_TOO_DEEP'],
    ['no predicateVersion', { predicateVersion: undefined }, 'PREDICATE_VERSION_UNSUPPORTED'],
    ['predicateVersion 2', { predicateVersion: 2 }, 'PREDICATE_VERSION_UNSUPPORTED'],
    ['predicateVersion as text', { predicateVersion: '1' }, 'PREDICATE_VERSION_UNSUPPORTED'],
  ];
  for (const [why, over, code] of refused) {
    expectRefusal(await call(h, owner.bearer, 'POST', '/watches', watchBody(targets, over)), code, why);
  }
  assert.deepEqual(await rowsOf(h, owner.id), NOTHING, 'a refused predicate wrote something');

  // The same request with a predicate the grammar has is accepted, so each refusal above was about
  // its predicate and not about the target, the account or the rest of the body. Every shape the
  // contract lists is accepted, up to both structural limits.
  let accepted = 0;
  for (const kind of CONTRACT.aggregations) {
    for (const leaf of ['TASK_TERMINAL', 'TASK_FAILED', 'TASK_DONE']) {
      await create(h, owner, watchBody(targets, { predicate: { kind, over: CONTRACT.targetSelectors[0], leaf } }), `${kind} ${leaf}`);
      accepted += 1;
    }
  }
  for (const kind of CONTRACT.composites) {
    const operands = Array(WATCH_LIMITS.maxOperandsPerComposite).fill(ALL_TERMINAL);
    await create(h, owner, watchBody(targets, { predicate: { kind, operands } }), `${kind} at its operand limit`);
    accepted += 1;
  }
  assert.equal(accepted, 8);
  assert.equal((await rowsOf(h, owner.id)).watches, accepted);
});

test('create refuses what the contract refuses: an empty set, too many targets, a kind mismatch, a live set, a self-wake loop, a TTL out of range', { skip, timeout: 120_000 }, async () => {
  const h = await boot();
  const owner = await account(h, 'shapes');
  const done = await task(h, owner.id, 'DONE');
  const observer = await session(h, owner.id, { status: 'AWAITING_INPUT' });
  const other = await session(h, owner.id, { status: 'AWAITING_INPUT' });

  const refused: Array<[string, Record<string, unknown>, string]> = [
    ['an empty target set', watchBody([]), 'EMPTY_TARGET_SET'],
    [
      'one target past the limit',
      watchBody(Array.from({ length: WATCH_LIMITS.maxTargetsPerWatch + 1 }, () => ({ kind: 'TASK', id: randomUUID() }))),
      'TOO_MANY_TARGETS',
    ],
    ['a task leaf over a session', watchBody(sessions([other])), 'TARGET_KIND_MISMATCH'],
    [
      'a session leaf inside a composite over tasks',
      watchBody(tasks([done]), { predicate: { kind: 'ANY_OF', operands: [ALL_TERMINAL, ALL_SETTLED] } }),
      'TARGET_KIND_MISMATCH',
    ],
    ['a task list as live membership', watchBody([{ kind: 'TASK_LIST', id: randomUUID(), membership: 'live' }]), 'DYNAMIC_SET_UNSUPPORTED'],
    ['a project as live membership', watchBody([{ kind: 'PROJECT', id: randomUUID() }]), 'DYNAMIC_SET_UNSUPPORTED'],
    [
      'a resume watch naming its own observer',
      watchBody(sessions([other, observer]), { predicate: ALL_SETTLED, action: 'RESUME_SESSION', observerSessionId: observer }),
      'SELF_WATCH_LOOP',
    ],
    ['a TTL under the minimum', watchBody(tasks([done]), { ttlSeconds: WATCH_LIMITS.minTtlSeconds - 1 }), 'TTL_OUT_OF_RANGE'],
    ['a TTL over the maximum', watchBody(tasks([done]), { ttlSeconds: WATCH_LIMITS.maxTtlSeconds + 1 }), 'TTL_OUT_OF_RANGE'],
  ];
  for (const [why, body, code] of refused) {
    expectRefusal(await call(h, owner.bearer, 'POST', '/watches', body), code, why);
  }
  // Refused without a contract code because they are not domain refusals: the request is malformed.
  expectStatus(await call(h, owner.bearer, 'POST', '/watches', watchBody(tasks([done]), { mode: 'CONTINUOUS' })), 400, 'CONTINUOUS is not served');
  expectStatus(await call(h, owner.bearer, 'POST', '/watches', watchBody(tasks([done]), { action: 'RESUME_SESSION' })), 400, 'a resume watch with no observer session');
  expectStatus(await call(h, owner.bearer, 'POST', '/watches', watchBody([{ kind: 'RUNNER', id: randomUUID() }])), 400, 'a kind that is no resource');
  assert.deepEqual(await rowsOf(h, owner.id), NOTHING, 'a refused create wrote something');

  // Each boundary, from the accepted side.
  const { rows } = await h.sql.query<{ id: string }>(
    `INSERT INTO "task"("id","title","owner_id","creator_type","creator_id","status","updated_at","completion_criterion")
     SELECT gen_random_uuid(), 'one of many', $1, 'USER', $1, 'OPEN', now(), 'EVIDENCE_JUDGMENT'
       FROM generate_series(1, ${WATCH_LIMITS.maxTargetsPerWatch}) RETURNING "id"`,
    [owner.id],
  );
  const many = await create(h, owner, watchBody(tasks(rows.map((row) => row.id))), 'exactly the target limit');
  assert.equal(many.targets.length, WATCH_LIMITS.maxTargetsPerWatch);
  assert.equal(many.state, 'ACTIVE');

  for (const ttlSeconds of [WATCH_LIMITS.minTtlSeconds, WATCH_LIMITS.maxTtlSeconds, undefined]) {
    const watch = await create(h, owner, watchBody(tasks([done]), { ttlSeconds }), `ttlSeconds ${ttlSeconds}`);
    assert.equal(
      Date.parse(watch.expiresAt) - Date.parse(watch.createdAt),
      (ttlSeconds ?? WATCH_LIMITS.defaultTtlSeconds) * 1000,
      `ttlSeconds ${ttlSeconds} set the expiry`,
    );
  }
  const resume = await create(
    h,
    owner,
    watchBody(sessions([other]), { predicate: ALL_SETTLED, action: 'RESUME_SESSION', observerSessionId: observer }),
    'a resume watch over a session that is not its observer',
  );
  assert.equal(resume.observerType, 'SESSION');
  assert.equal(toUuid(resume.observerSessionId), observer);
  const twice = await create(h, owner, watchBody([...tasks([done]), ...tasks([done])]), 'a target named twice');
  assert.equal(twice.targets.length, 1, 'a target named twice is one target');
});

