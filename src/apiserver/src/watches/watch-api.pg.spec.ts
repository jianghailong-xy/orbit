/**
 * The Watch API, over real HTTP and against a real PostgreSQL.
 *
 * What is under test is what a client gets back and what the database then holds, so both are read:
 * every request goes through the real controller, the global ValidationPipe and the public-id
 * interceptor, and every claim about "nothing was written" or "exactly one Match" is a count of the
 * rows 0259 created. Only the bearer check is stood in for — `JwtService.verifyAsync` answers with
 * the account a token was issued to, which is what `JwtAuthGuard` puts on the request.
 *
 * The contract is `contracts/watch.contract.json`. The first case holds the served vocabulary to
 * it, and the leaf cases drive the contract's own vectors through the create path.
 *
 * The concurrency cases do not hope for an interleaving: they hold the owner's `user` row, which
 * every watch INSERT needs FOR KEY SHARE on, and release it only once every create is parked on a
 * lock inside its transaction — so none of them can have seen another's commit.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/watches/watch-api.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
