interface Account {
  id: string;
  bearer: string;
}

async function account(h: Harness, name: string): Promise<Account> {
  const id = randomUUID();
  await h.sql.query(
    `INSERT INTO "user"("id","email","name","password_hash") VALUES ($1,$2,$3,'x')`,
    [id, `watch-api-${id}@watch.invalid`, name],
  );
  const bearer = `bearer-${id}`;
  h.bearers.set(bearer, id);
  return { id, bearer };
}

async function task(h: Harness, ownerId: string, status: string): Promise<string> {
  const id = randomUUID();
  await h.sql.query(
    `INSERT INTO "task"("id","title","owner_id","creator_type","creator_id","status","updated_at","completion_criterion")
     VALUES ($1,'watched work',$2,'USER',$2,$3,now(),'EVIDENCE_JUDGMENT')`,
    [id, ownerId, status],
  );
  return id;
}

interface SessionShape {
  status?: string;
  endReason?: string | null;
  completedAt?: Date | null;
  deletedAt?: Date | null;
  pendingApprovals?: number;
}

async function session(h: Harness, ownerId: string, shape: SessionShape = {}): Promise<string> {
  const id = randomUUID();
  // `archived_at` is the deprecated mirror of `completed_at`; a fixture keeps the two in step.
  await h.sql.query(
    `INSERT INTO "session"("id","title","prompt","owner_id","creator_id","status","end_reason",
                           "completed_at","archived_at","deleted_at","updated_at")
     VALUES ($1,'watched session','p',$2,$2,$3,$4,$5,$5,$6,now())`,
    [id, ownerId, shape.status ?? 'RUNNING', shape.endReason ?? null, shape.completedAt ?? null, shape.deletedAt ?? null],
  );
  for (let n = 0; n < (shape.pendingApprovals ?? 0); n += 1) {
    await h.sql.query(
      `INSERT INTO "approval"("id","session_id","tool_name","input","status") VALUES ($1,$2,'Bash','{}'::jsonb,'PENDING')`,
      [randomUUID(), id],
    );
  }
  return id;
}

interface Rows {
  watches: number;
  targets: number;
  matches: number;
  deliveries: number;
}

async function rowsOf(h: Harness, ownerId: string): Promise<Rows> {
  const { rows } = await h.sql.query<Rows>(
    `SELECT (SELECT count(*) FROM "watch" w WHERE w."owner_id" = $1)::int AS watches,
            (SELECT count(*) FROM "watch_target" t JOIN "watch" w ON w."id" = t."watch_id"
              WHERE w."owner_id" = $1)::int AS targets,
            (SELECT count(*) FROM "watch_match" m JOIN "watch" w ON w."id" = m."watch_id"
              WHERE w."owner_id" = $1)::int AS matches,
            (SELECT count(*) FROM "watch_delivery" d JOIN "watch_match" m ON m."id" = d."match_id"
              JOIN "watch" w ON w."id" = m."watch_id" WHERE w."owner_id" = $1)::int AS deliveries`,
    [ownerId],
  );
  return rows[0];
}

const NOTHING: Rows = { watches: 0, targets: 0, matches: 0, deliveries: 0 };

async function create(h: Harness, who: Account, body: Record<string, unknown>, why: string) {
  const answer = await call(h, who.bearer, 'POST', '/watches', body);
  expectStatus(answer, 201, why);
  return answer.body;
}

/**
 * Run `fire` while the owner's `user` row is held FOR UPDATE, and let go only once `waiters`
 * backends are parked on a lock. Every watch INSERT's foreign key needs that row FOR KEY SHARE, so
 * each create is inside its transaction, past its reads and its idempotency lookup, and has not
 * committed; a create with a key another create already inserted waits on that one instead.
 */
async function whileOwnerRowIsHeld<T>(h: Harness, ownerId: string, waiters: number, fire: () => Promise<T>): Promise<T> {
  const holder = new Client({ connectionString: URL, connectionTimeoutMillis: 5_000 });
  await holder.connect();
  try {
    await holder.query('BEGIN');
    await holder.query(`SELECT 1 FROM "user" WHERE "id" = $1 FOR UPDATE`, [ownerId]);
    const holderPid = (await holder.query<{ pid: number }>('SELECT pg_backend_pid() AS pid')).rows[0].pid;
    // The first create's interactive transaction is open for as long as the row is held, and Prisma
    // gives it 5s. A racer answering 500 here is that timeout on a starved host, not the product.
    const heldSince = Date.now();
    let settled = false;
    const inFlight = fire().finally(() => {
      settled = true;
    });
    const deadline = Date.now() + 20_000;
    for (;;) {
      const { rows } = await h.sql.query<{ n: number }>(
        `SELECT count(*)::int AS n FROM pg_stat_activity
          WHERE datname = current_database() AND wait_event_type = 'Lock' AND pid <> $1`,
        [holderPid],
      );
      if (rows[0].n >= waiters) break;
      if (settled) {
        await inFlight;
        assert.fail(`the requests finished while only ${rows[0].n} of ${waiters} were parked on the held row`);
      }
      if (Date.now() > deadline) assert.fail(`only ${rows[0].n} of ${waiters} creates reached the held row`);
      await sleep(10);
    }
    console.log(`owner row held ${Date.now() - heldSince}ms until ${waiters} creates were parked on it`);
    await holder.query('COMMIT');
    return await inFlight;
  } finally {
    await holder.query('ROLLBACK').catch(() => undefined);
    await holder.end().catch(() => undefined);
  }
}

