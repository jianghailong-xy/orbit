interface Answer {
  status: number;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  body: any;
}

async function call(h: Harness, bearer: string | null, method: string, route: string, body?: unknown): Promise<Answer> {
  const response = await fetch(`${h.base}/api${route}`, {
    method,
    headers: { 'content-type': 'application/json', ...(bearer ? { authorization: `Bearer ${bearer}` } : {}) },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await response.text();
  let parsed: unknown = null;
  try {
    parsed = text ? JSON.parse(text) : null;
  } catch {
    parsed = { unparsed: text };
  }
  return { status: response.status, body: parsed };
}

function expectStatus(answer: Answer, status: number, why: string): void {
  assert.equal(answer.status, status, `${why}: answered ${answer.status} ${JSON.stringify(answer.body)}`);
}

function expectRefusal(answer: Answer, code: string, why: string): void {
  expectStatus(answer, code === 'PERMISSION_DENIED' ? 403 : 400, why);
  assert.equal(answer.body.code, code, `${why}: ${JSON.stringify(answer.body)}`);
  assert.equal(answer.body.kind, 'REFUSAL', why);
}

const ALL_TERMINAL = { kind: 'ALL', over: 'ALL_TARGETS', leaf: 'TASK_TERMINAL' };
const ALL_SETTLED = { kind: 'ALL', over: 'ALL_TARGETS', leaf: 'SESSION_TURN_SETTLED' };

const tasks = (ids: string[]) => ids.map((id) => ({ kind: 'TASK', id }));
const sessions = (ids: string[]) => ids.map((id) => ({ kind: 'SESSION', id }));

function watchBody(targets: unknown[], over: Record<string, unknown> = {}): Record<string, unknown> {
  return { predicateVersion: 1, predicate: ALL_TERMINAL, targets, action: 'NOTIFY_USER', ...over };
}

/** Target id → state, from either a watch's targets or a Match snapshot's. */
function statesById(targets: Array<{ targetResourceId?: string; id?: string; state: string }>): Map<string, string> {
  return new Map(targets.map((target) => [toUuid((target.targetResourceId ?? target.id)!), target.state]));
}

