/**
 * A turn Orbit writes to tell a session about a committed fact carries a `coordinatorDelivery` card —
 * against a real PostgreSQL.
 *
 * The turn's words are written for the agent (`From Orbit · project “…” has a downstream task that
 * can start now`, then paragraphs of protocol) and stay exactly that; the card beside them is what
 * lets a client draw the turn as one line — `Can start now: <task> · Sent to the coordinator ·
 * 07:30 PM` — instead of a bubble the owner typed. It is read where every turn card is read
 * (sessions/turn-cards.ts): off both views of the queue while the turn waits, and onto the runner's
 * echo when it is stored. Each case below writes the turn through the door that writes it in
 * production, reads the views, hands the turn to the runner, echoes it through the real event
 * ingest, and holds every reading to the card the rows say it is:
 *
 *   (1) a fact queued for a busy coordinator (`CoordinatorDeliveryService.queue`), its card read off
 *       the wake that names the turn — the task, and the moment the wake was bound;
 *   (2) a fact delivered through the older carrier (`deliver`, by `resume`), which binds its wake
 *       after the turn is written;
 *   (3) a delivery re-sent after its turn was taken off the queue unread (`requeue`): the card moves
 *       with the wake onto the turn that re-sends it;
 *   (4) the owner's answer to a criteria proposal, sent back to the conversation that filed it —
 *       approved, and rejected;
 *   (5) an ordinary message carries none — nor one under a derived key no wake names, nor one under
 *       a key a wake delivered to ANOTHER conversation names, nor the words of a reply on a
 *       conversation that filed no proposal — and a card the runner sends is dropped;
 *   (6) the owner's answer to a proposal a task's run filed: told to that run, and said to be — the
 *       project's own coordinator pointer names another conversation, so `toCoordinator` is false.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/projects/coordinator-delivery-turn-card.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
