const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

const METHOD = 'A person reads the criterion and says whether it holds';

/** A collaborator whose every method answers nothing: the broadcasts a turn's enqueue fires. */
const silent = (): unknown =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

/** A card as a client reads it: over the wire, so compared as the JSON it is sent as. */
const wire = (value: unknown): unknown => (value === undefined ? undefined : JSON.parse(JSON.stringify(value)));

/** Every wake here is allowed: what is under test is the turn's card, not who may be woken. */
const allow = async () => ({ allowed: true as const });

test('a turn telling a session about a committed fact carries a coordinatorDelivery card, on the queue and on the echo', {
  skip, concurrency: 1, timeout: 600_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });
  const db = prisma as unknown as PrismaService;

  // ── the world: one account, one machine, one workspace every conversation runs in ────────────
  const ownerId = randomUUID();
  const runnerId = randomUUID();
  const workspaceId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `delivery-line-${ownerId}@turn-card.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  await prisma.runner.create({
    data: {
      id: runnerId, ownerId, name: 'the machine every coordinator runs on', tokenHash: sha256(`token-${runnerId}`),
      status: RunnerStatus.ONLINE, lastHeartbeatAt: new Date(), capabilities: [], capabilitiesReportedAt: new Date(),
    },
  });
  await prisma.workspace.create({ data: { id: workspaceId, ownerId, runnerId, name: 'orbit-coordinator', enabled: true } });

  /** A conversation on this runner, parked between turns: what a coordinator is when it is told. */
  async function conversation(title: string, data: Partial<Prisma.SessionUncheckedCreateInput> = {}): Promise<string> {
    const id = randomUUID();
    await prisma.session.create({
      data: {
        id, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title, prompt: title, provider: 'claude', status: RunStatus.AWAITING_INPUT,
        numTurns: 1, startedAt: new Date(), runtimeSessionId: `runtime-${id}`,
        dispatchOrigin: SessionDispatchOrigin.USER, runSource: SessionRunSource.MANUAL,
        titleManagedByProject: true, ...data,
      },
    });
    return id;
  }

  /** A project coordinated from a conversation of record: the one a fact is told to. */
  async function coordinatedProject(title: string): Promise<{ projectId: string; coordinator: string }> {
    const coordinator = await conversation(`coordinator: ${title}`);
    const projectId = randomUUID();
    await prisma.project.create({
      data: {
        id: projectId, ownerId, title, coordinatorEnabled: true,
        coordinatorSessionId: coordinator, coordinatorWorkspaceId: workspaceId,
      },
    });
    return { projectId, coordinator };
  }

  async function task(projectId: string, title: string): Promise<string> {
    const created = await prisma.task.create({
      data: {
        ownerId, projectId, title, creatorType: 'USER', creatorId: ownerId, assigneeId: workspaceId,
        completionCriterion: 'EVIDENCE_JUDGMENT',
      },
      select: { id: true },
    });
    return created.id;
  }

  // ── the doors ─────────────────────────────────────────────────────────────────────────────────
  const queue = { notifySessionQueued: () => undefined };
  const realtime = silent();
  const sessions = new SessionsService(db, queue as never, realtime as never);
  const tasks = new TasksService(db, sessions, realtime as never);
  const deliveries = new CoordinatorDeliveryService(db, new CoordinatorWakeService(db), sessions);
  const projects = new ProjectsService(db, new ProjectAcceptanceService(db), sessions, realtime as never);
  const orchestration = new RunnerOrchestrationAuthorizer(db, new JwtService({ secret: 'delivery-line-turn-card-pg' }));
  const api = new RunnerApiController(
    db,
    queue as never,
    realtime as never,
    {} as never,
    orchestration,
    // The turns here carry no `#`-references and reach no list console.
    { expand: async (_owner: string, content?: string) => content } as never,
    { appendFor: async (_tx: unknown, _id: string, content?: string) => content } as never,
    undefined,
    undefined,
    tasks,
    undefined,
    sessions,
  );

  /** The owner's own message, waiting at the head of the queue: what the fact's turn waits behind. */
  async function ownerSays(sessionId: string, words: string, clientTurnId: string = randomUUID()): Promise<string> {
    return (await sessions.createTurn(ownerId, sessionId, { clientTurnId, content: words })).turnId;
  }

  /** The one turn of a conversation under `clientTurnId`. */
  async function turnKeyed(sessionId: string, clientTurnId: string) {
    return prisma.conversationTurn.findUniqueOrThrow({
      where: { sessionId_clientTurnId: { sessionId, clientTurnId } },
    });
  }

  /** What the runner's claim does to a queued conversation, then the polls that hand its next message out. */
  async function deliver(sessionId: string): Promise<{ turnId: string; content: string }> {
    await prisma.session.update({ where: { id: sessionId }, data: { status: RunStatus.RUNNING } });
    for (;;) {
      const handed = await (api as unknown as {
        dequeueTurn: (sessionId: string, runnerId: string, leaseGeneration: string | null) => Promise<Record<string, unknown> | null>;
      }).dequeueTurn.call(api, sessionId, runnerId, null);
      assert.ok(handed, `the inbox of ${sessionId} handed nothing out`);
      const turn = await prisma.conversationTurn.findUniqueOrThrow({ where: { id: String(handed.turnId) } });
      if (turn.kind !== 'message') continue;
      return { turnId: turn.id, content: String(handed.content ?? '') };
    }
  }

  const seqs = new Map<string, number>();
  /** The runner's event for one turn, through the real ingest. Answers the payload that was stored. */
  async function say(sessionId: string, turnId: string, type: RunEventType, payload: Record<string, unknown>) {
    const seq = (seqs.get(sessionId) ?? 100) + 1;
    seqs.set(sessionId, seq);
    await api.events({ id: runnerId } as never, sessionId, {
      events: [{ seq, type, ts: new Date().toISOString(), turnId, payload }],
    } as never);
    return (await prisma.runEvent.findFirstOrThrow({ where: { sessionId, seq } })).payload as Record<string, unknown>;
  }

  /** The turn ends as the runner reports it: something said, then the completion. */
  async function finish(sessionId: string, turnId: string) {
    await say(sessionId, turnId, RunEventType.ASSISTANT, { text: 'Done.' });
    await api.turnComplete({ id: runnerId } as never, sessionId, {
      turnId, status: SharedRunStatus.SUCCEEDED, subtype: 'success', numTurns: 1, costUsd: 0,
    } as never);
  }

  /** A card the runner made up, which ingest must drop for the one it reads. */
  const forged = { kind: 'LOOKS_FINISHED', task: null, revision: null, count: null, deliveredAt: '2000-01-01T00:00:00.000Z' };

  /**
   * The wake a fact was delivered under, as the rows hold it. Read through Prisma, as the card is:
   * `updated_at` is a timestamp without a zone, which the raw driver would read in this host's own.
   */
  async function wakeOf(fact: WakeFact) {
    const rows = await prisma.projectCoordinatorWake.findMany({
      where: { idempotencyKey: wakeIdempotencyKey(fact), status: 'DELIVERED' },
      select: { id: true, idempotencyKey: true, sessionId: true, updatedAt: true, delivery: true },
    });
    assert.equal(rows.length, 1, `expected one DELIVERED wake for ${wakeIdempotencyKey(fact)}`);
    const [row] = rows;
    return {
      id: row!.id,
      idempotency_key: row!.idempotencyKey,
      session_id: row!.sessionId,
      updated_at: row!.updatedAt,
      delivery: row!.delivery as { clientTurnId: string },
    };
  }

  /** The echo of a turn already handed out: the stored payload, with a forged card sent alongside. */
  async function echo(sessionId: string, handed: { turnId: string; content: string }) {
    return say(sessionId, handed.turnId, RunEventType.USER, { text: handed.content, coordinatorDelivery: forged });
  }

  await t.test('(1) a fact queued for a busy coordinator carries its card on both views, the accepted row and the echo', async () => {
    const { projectId, coordinator } = await coordinatedProject('the project with a task that can start');
    const taskId = await task(projectId, 'Draw coordinator deliveries as one line');
    const fact = dependentReadyFact({ projectId, taskId, title: 'Draw coordinator deliveries as one line', dispatchEpoch: 3 });
    const ahead = await ownerSays(coordinator, 'the owner says something first');
    const outcome = await deliveries.queue(fact, allow);
    assert.equal(outcome.outcome, 'DELIVERED');
    const told = await turnKeyed(coordinator, coordinatorDeliveryTurnId(wakeIdempotencyKey(fact)));
    assert.match(told.content ?? '', /^From Orbit · project “the project with a task that can start” has a downstream task/,
      'the agent’s words are what they were');

    const wake = await wakeOf(fact);
    assert.equal(wake.session_id, coordinator);
    assert.equal(wake.delivery.clientTurnId, told.clientTurnId, 'the wake names the turn it wrote');
    const expected: CoordinatorDeliveryCard = {
      kind: 'DEPENDENT_READY',
      task: { id: taskId, title: 'Draw coordinator deliveries as one line' },
      revision: null,
      count: null,
      deliveredAt: wake.updated_at.toISOString(),
      toCoordinator: true,
    };

    const queued = (await sessions.listQueuedTurns(ownerId, coordinator)).find((row) => row.turnId === told.id);
    assert.ok(queued, 'the queue view does not list the waiting turn');
    assert.deepEqual(wire(queued.coordinatorDelivery), expected, 'the queue view');
    assert.equal(queued.authoredByOrbit, true, 'nothing of it goes back to a composer');
    const active = (await sessions.listQueuedTurns(ownerId, coordinator, 'active')).find((row) => row.turnId === told.id);
    assert.ok(active, 'the active view does not list the waiting turn');
    assert.deepEqual(wire(active.coordinatorDelivery), expected, 'the active view');

    const head = await deliver(coordinator);
    assert.equal(head.turnId, ahead, 'the owner’s message ahead of it was handed out first');
    await finish(coordinator, head.turnId);
    const handed = await deliver(coordinator);
    assert.equal(handed.turnId, told.id, 'the runner was handed another turn');
    assert.ok(handed.content.startsWith(told.content!), 'the agent is handed the words the turn was written with');
    const accepted = (await sessions.listQueuedTurns(ownerId, coordinator, 'active')).find((row) => row.turnId === told.id);
    assert.ok(accepted, 'the active view lost the turn between hand-out and echo');
    assert.deepEqual(wire(accepted.coordinatorDelivery), expected, 'the accepted row');

    const stored = await echo(coordinator, handed);
    assert.deepEqual(wire(stored.coordinatorDelivery), expected, 'the echo: the card read, not the one the runner sent');
    assert.ok(String(stored.text).startsWith(told.content!), 'the echo keeps the words the agent read');
  });

  await t.test('(2) a fact delivered through the older carrier carries the card its wake was bound with', async () => {
    const { projectId, coordinator } = await coordinatedProject('the project whose work is not on main');
    const fact = criterionUnlandedFact(projectId, 'c'.repeat(16), [
      { taskId: randomUUID(), status: 'DONE' },
      { taskId: randomUUID(), status: 'DONE' },
    ], 'ON_INTEGRATION_LINE');
    assert.ok(fact, 'two finished serving tasks with no landing make the fact');
    const outcome = await deliveries.deliver(fact, allow);
    assert.equal(outcome.outcome, 'DELIVERED', JSON.stringify(outcome));
    const told = await turnKeyed(coordinator, coordinatorDeliveryTurnId(wakeIdempotencyKey(fact)));
    assert.match(told.content ?? '', /^From Orbit · project “the project whose work is not on main” has finished work/);
    const wake = await wakeOf(fact);
    const expected: CoordinatorDeliveryCard = {
      kind: 'CRITERION_UNLANDED', task: null, revision: null, count: 2, deliveredAt: wake.updated_at.toISOString(),
      toCoordinator: true,
    };

    // Nothing waits ahead of it — `resume` refuses a conversation with a message it has not read — so
    // it is the head of the queue: the active view's accepted row, until its echo.
    const active = (await sessions.listQueuedTurns(ownerId, coordinator, 'active')).find((row) => row.turnId === told.id);
    assert.ok(active, 'the active view does not list the delivered turn');
    assert.deepEqual(wire(active.coordinatorDelivery), expected, 'the active view');
    const handed = await deliver(coordinator);
    assert.equal(handed.turnId, told.id);
    const stored = await echo(coordinator, handed);
    assert.deepEqual(wire(stored.coordinatorDelivery), expected, 'the echo');
  });

  await t.test('(3) a delivery re-sent after its turn left the queue unread: the card moves with its wake', async () => {
    const { projectId, coordinator } = await coordinatedProject('the project whose delivery was withdrawn');
    const taskId = await task(projectId, 'Re-send what was taken off the queue');
    const fact = dependentReadyFact({ projectId, taskId, title: 'Re-send what was taken off the queue', dispatchEpoch: 7 });
    const ahead = await ownerSays(coordinator, 'the owner says something first');
    assert.equal((await deliveries.queue(fact, allow)).outcome, 'DELIVERED');
    const first = await turnKeyed(coordinator, coordinatorDeliveryTurnId(wakeIdempotencyKey(fact)));
    const wake = await wakeOf(fact);

    // Withdrawn by the owner, unread: the queue's own door.
    await sessions.cancelQueuedTurn(ownerId, coordinator, first.id);
    // A later moment for the re-send, so the two binds cannot round onto one millisecond.
    await new Promise((resolve) => setTimeout(resolve, 20));
    const requeued = await deliveries.requeue(fact, {
      wakeId: wake.id, idempotencyKey: wake.idempotency_key, clientTurnId: first.clientTurnId,
    });
    assert.equal(requeued.outcome, 'REQUEUED', JSON.stringify(requeued));
    const second = await turnKeyed(coordinator, coordinatorRedeliveryTurnId(wake.idempotency_key, first.clientTurnId));
    const moved = await wakeOf(fact);
    assert.equal(moved.delivery.clientTurnId, second.clientTurnId, 'the wake names the turn re-sending it');
    assert.ok(moved.updated_at.getTime() > wake.updated_at.getTime(), 'and was bound again, later');

    const queued = (await sessions.listQueuedTurns(ownerId, coordinator)).find((row) => row.turnId === second.id);
    assert.ok(queued, 'the queue view does not list the re-sent turn');
    assert.deepEqual(wire(queued.coordinatorDelivery), {
      kind: 'DEPENDENT_READY',
      task: { id: taskId, title: 'Re-send what was taken off the queue' },
      revision: null,
      count: null,
      deliveredAt: moved.updated_at.toISOString(),
      toCoordinator: true,
    }, 'the re-sent turn is drawn as the line, at the moment it was re-sent');

    const head = await deliver(coordinator);
    assert.equal(head.turnId, ahead);
    await finish(coordinator, head.turnId);
    const handed = await deliver(coordinator);
    assert.equal(handed.turnId, second.id);
    assert.deepEqual(wire((await echo(coordinator, handed)).coordinatorDelivery), wire(queued.coordinatorDelivery), 'the echo');
  });

  /** A project with two criteria stated by the owner, coordinated from a conversation that asks to drop one. */
  async function heldProposal(label: string) {
    const { projectId, coordinator } = await coordinatedProject(`the project whose criteria are proposed: ${label}`);
    await projects.update(ownerId, projectId, {
      acceptanceCriteriaItems: ['The line is one line', 'The words are unchanged']
        .map((text) => ({ text, verificationMethod: METHOD })),
    } as never);
    const [kept] = await prisma.projectAcceptanceCriterionDefinition.findMany({
      where: { projectId }, orderBy: { ordinal: 'asc' }, select: { id: true },
    });
    const held = (await projects.update(ownerId, projectId, {
      acceptanceCriteriaItems: [{ id: kept!.id, text: 'The line is one line', verificationMethod: METHOD }],
    } as never, coordinator) as { acceptanceCriteriaHold?: { intentId: string; baselineSeal: string } })
      .acceptanceCriteriaHold;
    assert.ok(held, 'dropping a criterion from a session is held for the owner');
    const { rows: [key] } = await sql.query<{ commit_token: string }>(
      `SELECT "commit_token" FROM "project_ratified_action_intent" WHERE "id" = $1::uuid`, [held.intentId],
    );
    return { projectId, coordinator, intentId: held.intentId, baseSeal: held.baselineSeal, commitToken: key!.commit_token };
  }

  for (const decision of ['APPROVE', 'REJECT'] as const) {
    await t.test(`(4) the owner’s answer to a criteria proposal, ${decision}, carries its card`, async () => {
      const proposal = await heldProposal(decision);
      const decided = await projects.decideCriteriaChange(ownerId, proposal.projectId, proposal.intentId, {
        commitToken: proposal.commitToken, decision, baseSeal: proposal.baseSeal,
      } as never) as { reply?: { channel: string; turnId?: string } | null };
      assert.equal(decided.reply?.channel, 'SESSION', 'the reply went to the conversation that asked');
      const reply = await turnKeyed(proposal.coordinator, criteriaDecisionReplyTurnId(proposal.intentId));
      assert.equal(decided.reply?.turnId, reply.id);
      assert.match(reply.content ?? '', /^From Orbit · criteria decision\n\nYour criteria proposal /, 'the words are what they were');
      const expected: CoordinatorDeliveryCard = {
        kind: decision === 'APPROVE' ? 'CRITERIA_APPROVED' : 'CRITERIA_REJECTED',
        task: null,
        revision: null,
        count: null,
        deliveredAt: reply.createdAt.toISOString(),
        toCoordinator: true,
      };

      const active = (await sessions.listQueuedTurns(ownerId, proposal.coordinator, 'active')).find((row) => row.turnId === reply.id);
      assert.ok(active, 'the active view does not list the reply');
      assert.deepEqual(wire(active.coordinatorDelivery), expected, 'the active view');
      const handed = await deliver(proposal.coordinator);
      assert.equal(handed.turnId, reply.id);
      assert.deepEqual(wire((await echo(proposal.coordinator, handed)).coordinatorDelivery), expected, 'the echo');
    });
  }

  await t.test('(5) an ordinary message carries none — nor one under a key nothing on this conversation delivered', async () => {
    const { projectId, coordinator } = await coordinatedProject('the project the owner talks to');
    const elsewhere = await conversation('the conversation that was told instead');
    // A fact delivered to the OTHER conversation, whose key a message here then takes.
    const taskId = await task(projectId, 'Told to somebody else');
    const fact = dependentReadyFact({ projectId, taskId, title: 'Told to somebody else', dispatchEpoch: 1 });
    await prisma.project.update({ where: { id: projectId }, data: { coordinatorSessionId: elsewhere } });
    assert.equal((await deliveries.queue(fact, allow)).outcome, 'DELIVERED');
    await prisma.project.update({ where: { id: projectId }, data: { coordinatorSessionId: coordinator } });
    // And a proposal answered to a conversation, whose reply's words and key a message HERE then copies.
    const proposal = await heldProposal('copied');
    await projects.decideCriteriaChange(ownerId, proposal.projectId, proposal.intentId, {
      commitToken: proposal.commitToken, decision: 'APPROVE', baseSeal: proposal.baseSeal,
    } as never);
    const copied = (await turnKeyed(proposal.coordinator, criteriaDecisionReplyTurnId(proposal.intentId))).content!;

    const ahead = await ownerSays(coordinator, 'the owner says something first');
    const ours = [
      await ownerSays(coordinator, 'what is the status of t4?'),
      await ownerSays(coordinator, 'a key shaped like a delivery', derivedUuid('nobody-delivered-this')),
      await ownerSays(coordinator, 'the key of a delivery to another conversation', coordinatorDeliveryTurnId(wakeIdempotencyKey(fact))),
      await ownerSays(coordinator, copied, criteriaDecisionReplyTurnId(proposal.intentId)),
    ];
    const views = [
      ['queue', await sessions.listQueuedTurns(ownerId, coordinator)],
      ['active', await sessions.listQueuedTurns(ownerId, coordinator, 'active')],
    ] as const;
    for (const [view, rows] of views) {
      for (const turnId of ours) {
        const row = rows.find((each) => each.turnId === turnId);
        assert.ok(row, `the ${view} view does not list ${turnId}`);
        assert.equal(row.coordinatorDelivery, undefined, `the ${view} view: ${turnId} carries a card`);
      }
    }
    // Each echoed through the ingest: none is stored with a card — not even the one the runner sends.
    const head = await deliver(coordinator);
    assert.equal(head.turnId, ahead);
    await finish(coordinator, head.turnId);
    for (const turnId of ours) {
      const handed = await deliver(coordinator);
      assert.equal(handed.turnId, turnId, 'the turns are handed out in the order they were queued');
      const stored = await echo(coordinator, handed);
      assert.equal(stored.coordinatorDelivery, undefined, `the echo of ${turnId} carries a card`);
      await finish(coordinator, turnId);
    }
  });

  await t.test('(6) the answer to a proposal a task’s run filed is told to that run, and says so — not the coordinator', async () => {
    const { projectId, coordinator } = await coordinatedProject('the project a task’s run asks to loosen');
    await projects.update(ownerId, projectId, {
      acceptanceCriteriaItems: ['The line is one line', 'The words are unchanged']
        .map((text) => ({ text, verificationMethod: METHOD })),
    } as never);
    const [kept] = await prisma.projectAcceptanceCriterionDefinition.findMany({
      where: { projectId }, orderBy: { ordinal: 'asc' }, select: { id: true },
    });
    // A run of one of the project's tasks, parked between turns, asks to drop a criterion.
    const taskId = await task(projectId, 'Say where the reply went');
    const run = await conversation('Task: Say where the reply went', { taskId });
    const held = (await projects.update(ownerId, projectId, {
      acceptanceCriteriaItems: [{ id: kept!.id, text: 'The line is one line', verificationMethod: METHOD }],
    } as never, run) as { acceptanceCriteriaHold?: { intentId: string; baselineSeal: string } }).acceptanceCriteriaHold;
    assert.ok(held, 'dropping a criterion from a task’s run is held for the owner');
    const { rows: [key] } = await sql.query<{ commit_token: string }>(
      `SELECT "commit_token" FROM "project_ratified_action_intent" WHERE "id" = $1::uuid`, [held.intentId],
    );
    // Something waits ahead of the answer, so it is on both views of the queue until it is handed out.
    const ahead = await ownerSays(run, 'the owner says something first');
    const decided = await projects.decideCriteriaChange(ownerId, projectId, held.intentId, {
      commitToken: key!.commit_token, decision: 'REJECT', baseSeal: held.baselineSeal,
    } as never) as { reply?: { channel: string; turnId?: string } | null };
    assert.equal(decided.reply?.channel, 'SESSION', 'the reply went to the run that asked');
    const reply = await turnKeyed(run, criteriaDecisionReplyTurnId(held.intentId));
    assert.equal(decided.reply?.turnId, reply.id);
    assert.match(reply.content ?? '', /^From Orbit · criteria decision\n\nYour criteria proposal /, 'the words are what they were');
    assert.equal(
      await prisma.conversationTurn.count({ where: { sessionId: coordinator, clientTurnId: reply.clientTurnId } }), 0,
      'nothing of it went to the coordinator',
    );
    const expected: CoordinatorDeliveryCard = {
      kind: 'CRITERIA_REJECTED',
      task: null,
      revision: null,
      count: null,
      deliveredAt: reply.createdAt.toISOString(),
      toCoordinator: false,
    };
    /** The reply's card on each view of the run's queue. */
    const views = async () => {
      const queue = (await sessions.listQueuedTurns(ownerId, run)).find((row) => row.turnId === reply.id);
      const active = (await sessions.listQueuedTurns(ownerId, run, 'active')).find((row) => row.turnId === reply.id);
      assert.ok(queue && active, 'a view of the queue does not list the reply');
      return { queue: wire(queue.coordinatorDelivery), active: wire(active.coordinatorDelivery) };
    };
    assert.deepEqual(await views(), { queue: expected, active: expected }, 'both views of the queue');

    // The project's pointer says who the run is, not what kind of session it is: while the pointer
    // names it, the same task run is the coordinator, and the same reply reads as the coordinator's.
    await prisma.project.update({ where: { id: projectId }, data: { coordinatorSessionId: run } });
    const asCoordinator = { ...expected, toCoordinator: true };
    assert.deepEqual(await views(), { queue: asCoordinator, active: asCoordinator }, 'the run, while it is the coordinator');
    await prisma.project.update({ where: { id: projectId }, data: { coordinatorSessionId: coordinator } });

    const head = await deliver(run);
    assert.equal(head.turnId, ahead, 'the owner’s message ahead of it was handed out first');
    await finish(run, head.turnId);
    const handed = await deliver(run);
    assert.equal(handed.turnId, reply.id);
    assert.deepEqual(wire((await echo(run, handed)).coordinatorDelivery), expected, 'the echo');
  });
});
