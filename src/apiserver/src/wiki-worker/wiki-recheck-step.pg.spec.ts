const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

interface Harness {
  base: string;
  sql: Client;
  prisma: PrismaClient;
  app: INestApplication;
  service: WikiService;
  retrieval: WikiRetrieval;
  bearers: Map<string, string>;
}

let harness: Promise<Harness> | undefined;

function boot(): Promise<Harness> {
  harness ??= (async () => {
    assertCoordinatorPgUrlIsIsolated(URL);
    const sql = new Client({ connectionString: URL, connectionTimeoutMillis: 5_000 });
    await sql.connect();
    await verifyCoordinatorPgIdentity(sql);
    const prisma = prismaClientFor(URL);
    const bearers = new Map<string, string>();
    const hub = { publishWikiChanged: () => undefined } as unknown as RealtimeService;
    const service = new WikiService(prisma as unknown as PrismaService, hub, {} as unknown as PushService);
    const retrieval = new WikiRetrieval(prisma as unknown as PrismaService);

    @Module({
      controllers: [WikiController],
      providers: [
        { provide: WikiService, useValue: service },
        { provide: WikiRetrieval, useValue: retrieval },
        { provide: PrismaService, useValue: prisma },
        JwtAuthGuard,
        Reflector,
        {
          provide: JwtService,
          useValue: {
            verifyAsync: async (token: string) => {
              const sub = bearers.get(token);
              if (!sub) throw new Error('not a bearer this run issued');
              return { sub, email: `${sub}@wiki.invalid` };
            },
          },
        },
      ],
    })
    class WikiRecheckModule {}

    const app = await NestFactory.create(WikiRecheckModule, { logger: false, abortOnError: false });
    app.setGlobalPrefix('api');
    app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
    app.useGlobalInterceptors(new PublicIdInterceptor());
    await app.listen(0, '127.0.0.1');
    return { base: await app.getUrl(), sql, prisma, app, service, retrieval, bearers };
  })();
  return harness;
}

after(async () => {
  if (!harness) return;
  const { app, prisma, sql } = await harness;
  await app.close().catch(() => undefined);
  await prisma.$disconnect().catch(() => undefined);
  await sql.end().catch(() => undefined);
});

// eslint-disable-next-line @typescript-eslint/no-explicit-any
async function call(h: Harness, bearer: string, method: string, route: string, body?: unknown): Promise<{ status: number; body: any }> {
  const response = await fetch(`${h.base}/api${route}`, {
    method,
    headers: { 'content-type': 'application/json', authorization: `Bearer ${bearer}` },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await response.text();
  return { status: response.status, body: text ? JSON.parse(text) : null };
}

const sha = (label: string): string => createHash('sha1').update(label).digest('hex');
const HEAD_1 = sha('origin/main at the first run');
const HEAD_2 = sha('origin/main at the second run');
const FIX = sha('fix: drop overflowing lifetime token sums from session');
const LANDING = sha('feat(wiki): check an agent\'s memory notes in the maintenance run');

interface Space {
  owner: string;
  bearer: string;
  spaceId: string;
}

async function space(h: Harness, name: string): Promise<Space> {
  const owner = randomUUID();
  await h.sql.query(`INSERT INTO "user"("id","email","name","password_hash") VALUES ($1,$2,$3,'x')`, [owner, `wiki-recheck-${owner}@wiki.invalid`, name]);
  const bearer = `bearer-${owner}`;
  h.bearers.set(bearer, owner);
  const made = await call(h, bearer, 'POST', '/wiki/spaces', { title: `${name}'s codebase` });
  assert.equal(made.status, 201, JSON.stringify(made.body));
  return { owner, bearer, spaceId: toUuid(made.body.id as string) };
}

/** An entry the owner writes, live at once, recorded ten days ago so that it is not fresh. */
async function entry(h: Harness, s: Space, content: Record<string, unknown>): Promise<string> {
  const written = await call(h, s.bearer, 'POST', `/wiki/spaces/${s.spaceId}/changesets`, {
    rationale: `the owner records ${String(content.title)}`,
    idempotencyKey: `recheck-${randomUUID()}`,
    ops: [{ op: 'add', entry: content }],
  });
  assert.equal(written.status, 200, JSON.stringify(written.body));
  assert.equal(written.body.ops[0].status, 'applied', JSON.stringify(written.body.ops[0]));
  const id = toUuid(written.body.ops[0].entryId as string);
  await h.sql.query(`UPDATE "wiki_entry" SET "recorded_at" = now() - interval '10 days' WHERE "id" = $1`, [id]);
  return id;
}

const pitfall = (title: string, paths: string[], cause: string): Record<string, unknown> => ({
  kind: 'pitfall',
  title,
  summary: `What goes wrong: ${title}.`,
  fields: { symptom: 'turns stay IN_FLIGHT', cause, fix: 'see the migration', trigger: { paths, commands: [], errorSignature: 'integer out of range' } },
  anchors: [{ type: 'path', path: paths[0] }],
});

/** The runner and the model, scripted: what each history entry answers and what each unit says. */
interface Script {
  diff: string[];
  screen: Map<string, Partial<WikiHistoryAnswerEntry>>;
  detail: Map<string, Partial<WikiHistoryAnswerEntry>>;
  answers: Map<string, string>;
  failHistory?: string;
  failModel?: string;
}

interface Seen {
  ops: Array<{ kind: string; input: Record<string, unknown> }>;
  units: string[];
  prompts: Map<string, string>;
}

function deps(h: Harness, s: Space, head: string, script: Script, seen: Seen, reaches: string[]): WikiRecheckStepDeps {
  return {
    prisma: h.prisma as unknown as Prisma.TransactionClient,
    wiki: h.service,
    ownerId: s.owner,
    spaceId: s.spaceId,
    jobId: randomUUID(),
    head,
    reaches: new Set(reaches),
    operation: async (kind, input): Promise<WikiRepoOpWait> => {
      seen.ops.push({ kind, input });
      if (kind === 'diff') {
        return { state: 'succeeded', error: null, result: { diff: { files: script.diff.map((path) => ({ status: 'M', path, from: null })), docs: [] } } };
      }
      if (script.failHistory) return { state: 'failed', error: script.failHistory, result: null };
      const entries = (input.entries as WikiHistoryRequestEntry[]).map((request) => ({
        id: request.id,
        base: request.from ?? HEAD_1.replace(/^./u, '0'),
        baseDate: '2026-10-01T00:00:00Z',
        census: [],
        moved: [],
        changed: false,
        ...(request.detail ? { commits: [], commitsTotal: 0, lines: [], linesTotal: 0, diff: '', diffTruncated: false } : {}),
        ...((request.detail ? script.detail : script.screen).get(request.id) ?? {}),
      }));
      return { state: 'succeeded', error: null, result: { history: { sha: head, date: '2026-11-06T09:00:00Z', entries } } };
    },
    ask: async (unit, _system, prompt) => {
      seen.units.push(unit);
      seen.prompts.set(unit, prompt);
      if (script.failModel) throw new Error(script.failModel);
      const answer = script.answers.get(unit) ?? script.answers.get(unit.replace(/#second$/u, ''));
      if (!answer) throw new Error(`no scripted answer for ${unit}`);
      return answer;
    },
    log: () => undefined,
    signal: new AbortController().signal,
  };
}

async function row(h: Harness, id: string) {
  return h.prisma.wikiEntry.findFirstOrThrow({ where: { id } });
}

test('the screen ranks, the budget asks, two answers act, and agents stop finding the entry until the owner answers', { skip }, async () => {
  const h = await boot();
  const s = await space(h, 'recheck');
  const sums = await entry(h, s, pitfall('session.sum_cache_read is int4 and overflows', ['src/apiserver/prisma/schema.prisma', 'src/apiserver/src/runner-api/runner-api.controller.ts'], 'sum_cache_read is an int4 accrual'));
  const claims = await entry(h, s, {
    kind: 'decision',
    title: 'Claims code stays on the wiki-claims-replay branch',
    summary: 'The claims code is kept on a branch and not merged to main.',
    fields: { context: 'The replay failed its gates.', decision: 'Keep the code on wiki-claims-replay.', alternatives: [{ option: 'Merge it', whyRejected: 'The gates failed.' }], consequences: 'Off on main.', decidedAt: '2026-11-04' },
    anchors: [{ type: 'path', path: 'src/apiserver/src/wiki/wiki-dossier.ts' }],
  });
  const quiet = await entry(h, s, {
    kind: 'convention',
    title: 'Model a closed set as TEXT plus a CHECK',
    summary: 'Closed sets are TEXT columns with a CHECK.',
    fields: { rule: 'Use TEXT with a CHECK constraint, never a Postgres enum.', scope: ['migrations'] },
    anchors: [{ type: 'path', path: 'docs/conventions.md' }],
  });
  const touched = await entry(h, s, pitfall('a retry loop holds the turn', ['src/apiserver/src/runner-api/runner-turns.ts'], 'turnComplete retries without a deadline'));
  // An entry that names no path is never screened, and a principle is out of scope.
  const pathless = await entry(h, s, { kind: 'convention', title: 'Deploys wait for the owner', summary: 'The owner approves deploys.', fields: { rule: 'Ask the owner before a deploy.', scope: ['deploys'] }, anchors: [] });

  const script: Script = {
    diff: [],
    screen: new Map([
      [sums, { census: [{ term: 'sum_cache_read', base: 1, head: 0 }], changed: true }],
      [claims, { census: [{ term: 'wiki-claims-replay', base: 0, head: 2 }], changed: true }],
      [quiet, { changed: false }],
      [touched, { census: [{ term: 'turnComplete', base: 3, head: 3 }], changed: true }],
    ]),
    detail: new Map([
      [sums, { commits: [{ sha: FIX, date: '2026-10-02T04:15:47Z', subject: 'fix: drop overflowing lifetime token sums from session', matched: true }], commitsTotal: 1 }],
      [claims, { commits: [{ sha: LANDING, date: '2026-11-05T05:58:29Z', subject: "feat(wiki): check an agent's memory notes", matched: true }], commitsTotal: 1 }],
    ]),
    answers: new Map([
      [sums, `{"verdict": "fixed", "commit": "${FIX.slice(0, 12)}", "reason": "Migration 0347 dropped the column"}`],
      [claims, `{"verdict": "obsolete", "commit": "${LANDING.slice(0, 12)}", "reason": "The claims code landed on main"}`],
      [`${claims}#second`, '{"verdict": "holds", "commit": null, "reason": "The branch is still named"}'],
      [touched, '{"verdict": "holds", "commit": null, "reason": "turnComplete still retries"}'],
    ]),
  };
  const seen: Seen = { ops: [], units: [], prompts: new Map() };
  const first = await runWikiRecheck(deps(h, s, HEAD_1, script, seen, [HEAD_1]));

  // 1. The first run has no screen to start from: every entry with a path is screened from its sources.
  assert.equal(seen.ops[0]!.kind, 'history', 'no diff is asked for before the space has a screen');
  const screenInput = seen.ops[0]!.input.entries as WikiHistoryRequestEntry[];
  assert.deepEqual(screenInput.map((request) => request.id).sort(), [sums, claims, quiet, touched].sort());
  assert.ok(screenInput.every((request) => request.since !== undefined && request.from === undefined && request.detail === false));
  assert.ok(!screenInput.some((request) => request.id === pathless), 'an entry with no path is not screened');
  const sumsScreen = screenInput.find((request) => request.id === sums)!;
  assert.deepEqual(sumsScreen.paths, ['src/apiserver/prisma/schema.prisma', 'src/apiserver/src/runner-api/runner-api.controller.ts']);
  assert.ok(sumsScreen.terms.includes('sum_cache_read'), JSON.stringify(sumsScreen.terms));
  assert.deepEqual({ ...first, head: undefined }, {
    head: undefined, from: null, screened: 4, ranked: { '0': 0, '1': 1, '2': 1, '3': 1 },
    asked: 3, calls: 5, holds: 1, fixed: 1, obsolete: 0, unsure: 1, due: 0, skipped: null,
  });
  const space1 = await h.prisma.wikiSpace.findFirstOrThrow({ where: { id: s.spaceId } });
  assert.equal(space1.claimRecheckRef, HEAD_1);

  // 2. The budget asked the ranked three, lowest rank first, each with the detail from its sources.
  const detail = seen.ops[1]!;
  assert.equal(detail.kind, 'history');
  assert.deepEqual((detail.input.entries as WikiHistoryRequestEntry[]).map((request) => [request.id, request.detail]), [[sums, true], [claims, true], [touched, true]]);
  assert.deepEqual([...seen.units].sort(), [sums, `${sums}#second`, claims, `${claims}#second`, touched].sort());
  assert.match(seen.prompts.get(sums)!, /^\* [0-9a-f]{12} 2026-10-02 fix: drop overflowing lifetime token sums from session$/mu);

  const fixed = await row(h, sums);
  assert.equal(fixed.claimState, 'fixed');
  assert.equal(fixed.claimCheckedRef, HEAD_1);
  assert.equal(fixed.claimDueRank, null);
  assert.equal(fixed.challenged, true, 'the challenge takes it out of the push at once');
  const check = fixed.claimCheck as Record<string, unknown>;
  assert.deepEqual(check.commit, { sha: FIX, date: '2026-10-02T04:15:47Z', subject: 'fix: drop overflowing lifetime token sums from session' });
  assert.equal(check.wrongWhenRecorded, true, 'the fix is older than the entry');
  assert.deepEqual(check.answers, ['fixed', 'fixed']);
  const unsure = await row(h, claims);
  assert.equal(unsure.claimState, 'unsure', 'two answers that disagree act on nothing');
  assert.equal(unsure.challenged, false);
  assert.equal((await row(h, touched)).claimState, 'holds');
  const untouched = await row(h, quiet);
  assert.equal(untouched.claimState, 'unchecked');
  assert.equal(untouched.claimDueAt, null);
  assert.notEqual(untouched.claimScreenedAt, null, 'screened with nothing to say');

  // One system challenge, in Review, that names the commit and proposes Retire.
  const ops = await h.prisma.wikiChangesetOp.findMany({ where: { entryId: sums, op: 'challenge' } });
  assert.equal(ops.length, 1);
  assert.equal(ops[0]!.decision, 'pending');
  const reason = String((ops[0]!.payload as { reason?: string }).reason);
  assert.match(reason, /^Claim recheck on origin\/main at [0-9a-f]{12}: fixed by [0-9a-f]{12} \(2026-10-02, "fix: drop overflowing lifetime token sums from session"\)\./u);
  assert.match(reason, /It was already so before this entry was recorded on/u);
  assert.match(reason, /Proposed answer: Retire\.$/u);

  // Agents' search leaves it out; the owner's search and wiki_get still have it, marked.
  const agentSession = randomUUID();
  const asAgent = await h.retrieval.search({ ownerId: s.owner, spaceId: s.spaceId, sessionId: agentSession, q: 'sum_cache_read' });
  assert.ok(!asAgent.hits.some((hit) => toUuid(hit.id) === sums), 'agents no longer find a fixed entry');
  const asOwner = await h.retrieval.search({ ownerId: s.owner, spaceId: s.spaceId, q: 'sum_cache_read' });
  assert.ok(asOwner.hits.some((hit) => toUuid(hit.id) === sums), 'the owner still finds it');
  const read = await call(h, s.bearer, 'GET', `/wiki/entries/${sums}`);
  assert.equal(read.status, 200, JSON.stringify(read.body));
  assert.equal(read.body.claimState, 'fixed');
  assert.equal(read.body.claimCheck.commit.sha, FIX);

  // 3. The next run screens only what its diff touched, from the last screen's commit; an entry asked this week waits.
  script.diff = ['docs/conventions.md', 'src/apiserver/src/runner-api/runner-turns.ts', 'src/apiserver/prisma/schema.prisma'];
  script.screen.set(quiet, { census: [{ term: 'TEXT', base: 2, head: 1 }], changed: true });
  script.screen.set(touched, { census: [{ term: 'turnComplete', base: 3, head: 0 }], changed: true });
  script.answers.set(quiet, '{"verdict": "holds", "commit": null, "reason": "Still TEXT and a CHECK"}');
  const seen2: Seen = { ops: [], units: [], prompts: new Map() };
  const second = await runWikiRecheck(deps(h, s, HEAD_2, script, seen2, [HEAD_1, HEAD_2]));
  assert.deepEqual(seen2.ops[0], { kind: 'diff', input: { from: HEAD_1, to: HEAD_2 } });
  const screened2 = seen2.ops[1]!.input.entries as WikiHistoryRequestEntry[];
  assert.deepEqual(screened2.map((request) => request.id).sort(), [quiet, touched].sort(), 'a fixed entry is not screened again, an untouched one not at all');
  assert.ok(screened2.every((request) => request.from === HEAD_1 && request.since === undefined));
  assert.equal(second.from, HEAD_1);
  assert.deepEqual(second.ranked, { '0': 0, '1': 1, '2': 1, '3': 0 });
  assert.deepEqual(seen2.units, [quiet], 'the entry asked within the week waits');
  assert.equal(second.asked, 1);
  assert.equal(second.due, 1);
  const waiting = await row(h, touched);
  assert.equal(waiting.claimDueRank, 1);
  assert.equal(waiting.claimState, 'holds');

  // 4. The owner re-confirms: the claim holds at the verdict's commit, and agents find it again.
  const review = await call(h, s.bearer, 'GET', `/wiki/review?space=${s.spaceId}`);
  assert.equal(review.status, 200);
  const changeset = (review.body as Array<{ id: string; ops: Array<{ id: string; op: string; entryId: string }> }>)
    .find((cs) => cs.ops.some((op) => op.op === 'challenge' && toUuid(op.entryId) === sums))!;
  const op = changeset.ops.find((candidate) => candidate.op === 'challenge')!;
  const decided = await call(h, s.bearer, 'POST', `/wiki/changesets/${changeset.id}/decide`, { decisions: [{ opId: op.id, action: 'reconfirm' }] });
  assert.equal(decided.status, 200, JSON.stringify(decided.body));
  const reconfirmed = await row(h, sums);
  assert.equal(reconfirmed.claimState, 'holds');
  assert.equal((reconfirmed.claimCheck as Record<string, unknown>).ownerReconfirmed, true);
  assert.equal(reconfirmed.challenged, false);
  const again = await h.retrieval.search({ ownerId: s.owner, spaceId: s.spaceId, sessionId: agentSession, q: 'sum_cache_read' });
  assert.ok(again.hits.some((hit) => toUuid(hit.id) === sums), 'agents find a re-confirmed entry again');

  // An amend that changes what the entry says makes its claim unchecked again, to be screened from its sources.
  const amended = await call(h, s.bearer, 'POST', `/wiki/spaces/${s.spaceId}/changesets`, {
    rationale: 'the owner rewrites it',
    idempotencyKey: `recheck-${randomUUID()}`,
    ops: [{ op: 'amend', entryId: touched, baseRevision: 1, changes: { summary: 'What goes wrong when a retry loop holds the turn.' } }],
  });
  assert.equal(amended.status, 200, JSON.stringify(amended.body));
  const reset = await row(h, touched);
  assert.equal(reset.claimState, 'unchecked');
  assert.equal(reset.claimScreenedAt, null);
  assert.equal(reset.claimDueAt, null);
  // A topic-only amend leaves the claim as it was.
  const retopic = await call(h, s.bearer, 'POST', `/wiki/spaces/${s.spaceId}/changesets`, {
    rationale: 'the owner files it under a topic',
    idempotencyKey: `recheck-${randomUUID()}`,
    ops: [{ op: 'amend', entryId: quiet, baseRevision: 1, changes: { topics: ['database'] } }],
  });
  assert.equal(retopic.status, 200, JSON.stringify(retopic.body));
  assert.equal((await row(h, quiet)).claimState, 'holds');
});

test('a runner that does not know the history operation, or a model that cannot answer, leaves everything as it was', { skip }, async () => {
  const h = await boot();
  const s = await space(h, 'recheck-old-runner');
  const sums = await entry(h, s, pitfall('session.sum_cache_read is int4 and overflows', ['src/apiserver/prisma/schema.prisma'], 'sum_cache_read is an int4 accrual'));
  const script: Script = {
    diff: [],
    screen: new Map([[sums, { census: [{ term: 'sum_cache_read', base: 1, head: 0 }], changed: true }]]),
    detail: new Map(),
    answers: new Map(),
    failHistory: 'history is not a repository operation this runner knows',
  };
  const old = await runWikiRecheck(deps(h, s, HEAD_1, script, { ops: [], units: [], prompts: new Map() }, [HEAD_1]));
  assert.match(String(old.skipped), /^the history operation failed: history is not a repository operation this runner knows$/u);
  assert.equal(old.screened, 0);
  const untouched = await row(h, sums);
  assert.equal(untouched.claimScreenedAt, null);
  assert.equal(untouched.claimDueAt, null);
  assert.equal((await h.prisma.wikiSpace.findFirstOrThrow({ where: { id: s.spaceId } })).claimRecheckRef, null, 'the screen did not move');

  delete script.failHistory;
  script.failModel = 'the System model is down';
  const seen: Seen = { ops: [], units: [], prompts: new Map() };
  const down = await runWikiRecheck(deps(h, s, HEAD_1, script, seen, [HEAD_1]));
  assert.equal(down.skipped, 'the model: the System model is down');
  assert.equal(down.asked, 0);
  assert.equal(down.due, 1, 'the entry stays due for the next run');
  const still = await row(h, sums);
  assert.equal(still.claimState, 'unchecked');
  assert.equal(still.claimDueRank, 1);
  assert.equal(still.claimCheckedAt, null);
});

test('a run handed back runs no finished step again, and takes a screened one on to its asks', { skip }, async () => {
  const h = await boot();
  const s = await space(h, 'recheck-replay');
  const sums = await entry(h, s, pitfall('session.sum_cache_read is int4 and overflows', ['src/apiserver/prisma/schema.prisma'], 'sum_cache_read is an int4 accrual'));
  const script: Script = {
    diff: [],
    screen: new Map([[sums, { census: [{ term: 'sum_cache_read', base: 1, head: 0 }], changed: true }]]),
    detail: new Map([[sums, { commits: [{ sha: FIX, date: '2026-10-02T04:15:47Z', subject: 'fix: drop sums', matched: true }], commitsTotal: 1 }]]),
    answers: new Map([[sums, '{"verdict": "holds", "commit": null, "reason": "still int4"}']]),
  };
  const kept: Array<{ phase: string; screened: number; asked: number }> = [];
  let carry: Parameters<NonNullable<WikiRecheckStepDeps['keep']>>[0] | null = null;
  const withCarry = (seen: Seen, earlier: typeof carry): WikiRecheckStepDeps => ({
    ...deps(h, s, HEAD_1, script, seen, [HEAD_1]),
    earlier,
    keep: async (next) => {
      carry = next;
      kept.push({ phase: next.phase, screened: next.report.screened, asked: next.report.asked });
    },
  });
  const seen: Seen = { ops: [], units: [], prompts: new Map() };
  const straight = await runWikiRecheck(withCarry(seen, null));
  assert.deepEqual(kept, [{ phase: 'screened', screened: 1, asked: 0 }, { phase: 'asked', screened: 1, asked: 1 }]);
  // A replay on the same commit after the step finished: the same report, and nothing asked of the runner or the model.
  const replay: Seen = { ops: [], units: [], prompts: new Map() };
  assert.deepEqual(await runWikiRecheck(withCarry(replay, carry)), straight);
  assert.deepEqual([replay.ops.length, replay.units.length], [0, 0]);
  // A replay of a run stopped after its screen: no screen again, its asks, and the screen's counts kept.
  await h.sql.query(`UPDATE "wiki_entry" SET "claim_state" = 'unchecked', "claim_checked_at" = NULL, "claim_checked_ref" = NULL, "claim_check" = NULL,
                            "claim_due_rank" = 1, "claim_due_at" = now() WHERE "id" = $1`, [sums]);
  const screened = { report: { ...straight, asked: 0, calls: 0, holds: 0 }, phase: 'screened' as const };
  const resumed: Seen = { ops: [], units: [], prompts: new Map() };
  const after = await runWikiRecheck(withCarry(resumed, screened));
  assert.deepEqual(resumed.ops.map((op) => (op.input.entries as WikiHistoryRequestEntry[])[0]!.detail), [true], 'only the detail is asked for');
  assert.deepEqual({ screened: after.screened, ranked: after.ranked, asked: after.asked, holds: after.holds }, { screened: 1, ranked: straight.ranked, asked: 1, holds: 1 });
  // A carry of another commit is another run's: the step runs whole.
  const other: Seen = { ops: [], units: [], prompts: new Map() };
  await runWikiRecheck({ ...withCarry(other, null), head: HEAD_2, reaches: new Set([HEAD_1, HEAD_2]), earlier: { report: { ...straight }, phase: 'asked' } });
  assert.ok(other.ops.length > 0, 'a carry of another commit is not reused');
});
