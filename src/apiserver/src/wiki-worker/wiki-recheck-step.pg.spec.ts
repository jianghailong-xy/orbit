/**
 * The claim recheck (contracts/wiki.contract.json `maintenance.job.server.recheck`, docs/wiki-claim-recheck-design.md)
 * against a real PostgreSQL: the maintain job's `recheck` step (`runWikiRecheck`) with the runner's operations and the
 * System model's answers scripted, and everything it writes read back from the database and the owner's doors.
 *
 *   1. the screen ranks what changed (a vanished term 1, a changed count 2, a touched file 3, nothing none), puts the
 *      ranked entries in the due queue and moves the space's screen to the run's commit;
 *   2. the budget asks the queue's top with the operation's detail, a second time for a fixed or obsolete answer, and
 *      only two agreeing answers act: the entry's claim is fixed, one system challenge proposes Retire, the entry
 *      leaves agents' search and the push, and the owner's own search and wiki_get still show it, marked;
 *   3. the next run screens only what its diff touched, from the last screen's commit, and an entry asked within
 *      the week waits in the queue;
 *   4. the owner's Re-confirm makes the claim hold again, and an amend makes it unchecked;
 *   5. a runner that does not know the operation, and a model that cannot answer, leave everything as it was.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki-worker/wiki-recheck-step.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run created.
 */
