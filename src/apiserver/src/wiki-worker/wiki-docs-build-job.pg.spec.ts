/** Passes of the worker until `ok`. */
async function passes(w: { queue: WikiModelRequestQueue; executor: WikiJobExecutor }, ok: () => Promise<boolean>, what: string, seconds = 60): Promise<void> {
  const deadline = Date.now() + seconds * 1000;
  for (;;) {
    await w.executor.runOnce();
    await w.queue.runOnce();
    if (await ok()) return;
    assert.ok(Date.now() < deadline, `${what} within ${seconds}s`);
    await delay(25);
  }
}

// ── the space's runner ───────────────────────────────────────────────────────────────────────────────

interface Tree {
  sha: string;
  files: Record<string, string>;
}

/** What one `read` item answers, as src/runner-go/wiki_repo_ops.go's wikiRepoOpReadOne answers it. */
function readOne(tree: Tree, item: { path: string; maxChars?: number }, left: number): Record<string, unknown> {
  const text = tree.files[item.path] ?? '';
  if (text === '') return { path: item.path, found: false, chars: 0 };
  let max = item.maxChars && item.maxChars > 0 ? item.maxChars : (item.path.startsWith('contracts/') || item.path.endsWith('.json') ? 2500 : 4200);
  max = Math.min(max, 22_000, left);
  if (max <= 0) return { path: item.path, found: true, truncated: true, chars: 0 };
  const runes = Array.from(text);
  if (runes.length <= max) return { path: item.path, found: true, text, chars: runes.length };
  const marker = '\n…（后略）\n';
  const cut = runes.slice(0, max - Array.from(marker).length).join('') + marker;
  return { path: item.path, found: true, text: cut, truncated: true, chars: Array.from(cut).length };
}

/**
 * The space's runner: claims what its heartbeat would be handed and answers each operation from the tree — a
 * snapshot as the index of its paths and sizes (or skipped, when the space holds that commit), a read as the text.
 */
function playRunner(h: Harness, runnerId: string, tree: () => Tree): { ops: Array<{ kind: string; input: Record<string, unknown> }>; stop: () => Promise<void> } {
  const ops = new WikiRepoOps(h.prisma as unknown as PrismaService);
  const seen: Array<{ kind: string; input: Record<string, unknown> }> = [];
  let running = true;
  const loop = (async () => {
    while (running) {
      const claimed = await ops.dispatch({ runnerId, leaseOwner: randomUUID(), draining: false, capabilities: [WIKI_REPO_OP_CAPABILITY] }).catch(() => []);
      for (const op of claimed) {
        seen.push({ kind: op.kind, input: op.input });
        const at = tree();
        let result: Record<string, unknown>;
        if (op.kind === 'snapshot') {
          const held = await h.prisma.wikiRepoSnapshot.findFirst({ where: { sha: at.sha }, select: { sha: true } });
          result = op.input.skipSha === at.sha && held
            ? { sha: at.sha, skipped: true }
            : { sha: at.sha, index: JSON.stringify({ sha: at.sha, files: Object.entries(at.files).map(([path, text]) => ({ path, size: Buffer.byteLength(text) })), commits: [at.sha] }) };
        } else {
          const items = (op.input.items as Array<{ path: string; maxChars?: number }>) ?? [];
          let chars = 0;
          const answered = items.map((item) => {
            const one = readOne(at, item, 22_000 - chars);
            chars += one.chars as number;
            return one;
          });
          result = { read: { sha: op.input.sha, items: answered, chars } };
        }
        await ops.applyWikiRepoOpResult({
          id: op.id, runnerId,
          body: { claimGeneration: op.claimGeneration, leaseOwner: op.leaseOwner, state: 'succeeded', result },
        });
      }
      await delay(15);
    }
  })();
  const player = { ops: seen, stop: async () => { running = false; await loop; } };
  players.push(player);
  return player;
}

// ── requests ─────────────────────────────────────────────────────────────────────────────────────────

interface Answer {
  status: number;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  body: any;
}

interface Caller {
  bearer?: string;
  runner?: string;
  session?: string;
}

async function call(h: Harness, who: Caller, method: string, route: string, body?: unknown): Promise<Answer> {
  const headers: Record<string, string> = { 'content-type': 'application/json' };
  if (who.bearer) headers.authorization = `Bearer ${who.bearer}`;
  if (who.runner) headers['x-runner-token'] = who.runner;
  if (who.session) headers['x-orbit-session-id'] = who.session;
  const response = await fetch(`${h.base}/api${route}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  const text = await response.text();
  let parsed: unknown = null;
  try {
    parsed = text ? JSON.parse(text) : null;
  } catch {
    parsed = { unparsed: text };
  }
  return { status: response.status, body: parsed };
}

function expectStatus(answer: Answer, status: number, why: string): void {
  assert.equal(answer.status, status, `${why}: answered ${answer.status} ${JSON.stringify(answer.body).slice(0, 1500)}`);
}

