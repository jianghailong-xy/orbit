/**
 * The space's first draft, stored by a maintenance run as a plan job's run stores one — under the runner switch,
 * whatever the test's: drafting is the plan's pipeline, not the documents'.
 */
async function draft(h: Harness, s: Scene, plan: Record<string, unknown>): Promise<number> {
  const mode = process.env.ORBIT_WIKI_EXECUTOR;
  const owners = process.env.ORBIT_WIKI_EXECUTOR_CANARY_OWNERS;
  executor('runner');
  try {
    const drafted = await call(h, s.maintainer, 'POST', `/runner/wiki/spaces/${s.spaceId}/plan/drafts`, {
      baseVersion: null, target: { min: 1, max: 10 }, plan, repoCheck: { sha: 'a'.repeat(40), checked: 3, missing: [] }, model: MODEL,
    });
    expectStatus(drafted, 200, 'the maintenance run drafts the plan');
    return drafted.body.version as number;
  } finally {
    if (mode === undefined) delete process.env.ORBIT_WIKI_EXECUTOR;
    else process.env.ORBIT_WIKI_EXECUTOR = mode;
    if (owners === undefined) delete process.env.ORBIT_WIKI_EXECUTOR_CANARY_OWNERS;
    else process.env.ORBIT_WIKI_EXECUTOR_CANARY_OWNERS = owners;
  }
}

/** The owner's edit of the overview's covers: a new draft on the newest version. */
async function editOverview(h: Harness, s: Scene, base: number, covers: string): Promise<number> {
  const plan = await call(h, { bearer: s.owner.bearer }, 'GET', `/wiki/spaces/${s.spaceId}/plan`);
  const doc = (plan.body.draft ?? plan.body.confirmed).docs.find((d: { slug: string }) => d.slug === SLUG);
  const section = doc.sections.find((one: { kind: string }) => one.kind === 'overview');
  const edited = await call(h, { bearer: s.owner.bearer }, 'POST', `/wiki/spaces/${s.spaceId}/plan/edits`, {
    baseVersion: base,
    docSlug: SLUG,
    sectionKey: section.key,
    section: { key: section.key, title: section.title, kind: 'overview', covers, length: section.length, sources: {} },
  });
  expectStatus(edited, 200, 'the owner edits the overview');
  return edited.body.version as number;
}

async function confirm(h: Harness, s: Scene, version: number): Promise<void> {
  expectStatus(await call(h, { bearer: s.owner.bearer }, 'POST', `/wiki/spaces/${s.spaceId}/plan/versions/${version}/confirm`), 200, `the owner confirms version ${version}`);
}

interface BuildRow {
  id: string;
  state: string;
  version: number | null;
  task_id: string | null;
  job_id: string | null;
  outcome: string | null;
  error: string | null;
  report: Record<string, unknown> | null;
  progress: Record<string, unknown> | null;
}

async function builds(h: Harness, spaceId: string): Promise<BuildRow[]> {
  return (await h.sql.query<BuildRow>(
    `SELECT "id","state","version","task_id","job_id","outcome","error","report","progress" FROM "wiki_plan_job"
      WHERE "space_id" = $1 AND "kind" = 'build' ORDER BY "created_at","id"`,
    [spaceId],
  )).rows;
}

interface JobRow {
  id: string;
  kind: string;
  priority: number;
  state: string;
  input: Record<string, unknown>;
  report: Record<string, unknown> | null;
  error: string | null;
}

async function job(h: Harness, id: string): Promise<JobRow> {
  return (await h.sql.query<JobRow>('SELECT "id","kind","priority","state","input","report","error" FROM "wiki_job" WHERE "id" = $1', [id])).rows[0];
}

async function buildTasks(h: Harness, s: Scene): Promise<number> {
  return (await h.sql.query<{ n: number }>(`SELECT count(*)::int AS n FROM "task" WHERE "list_id" = $1 AND "title" LIKE 'Wiki documents:%'`, [s.listId])).rows[0].n;
}

async function runToEnd(h: Harness, w: { queue: WikiModelRequestQueue; executor: WikiJobExecutor }, jobId: string): Promise<JobRow> {
  await passes(w, async () => ['succeeded', 'failed', 'cancelled'].includes((await job(h, jobId)).state), `the build ${jobId} to end`);
  await w.executor.whenIdle();
  return job(h, jobId);
}

// ── 1 and 2. canary: two builds ──────────────────────────────────────────────────────────────────────

test('canary: the confirmation makes a docs_build job and no task; the worker builds every section with the System model, and the next build leaves what did not change', { skip, timeout: 180_000 }, async () => {
  const h = await boot();
  await modelUp(h);
  h.model.hits.length = 0;
  const s = await scene(h, 'canary');
  const v1 = await draft(h, s, planFor(s));
  executor('canary', [s.owner.id]);
  await confirm(h, s, v1);

  // The build is the worker's: a job of the documents' kind, owner-initiated, naming its plan job — and no task.
  const [first] = await builds(h, s.spaceId);
  assert.deepEqual([first.state, first.version, first.task_id], ['made', v1, null]);
  assert.ok(first.job_id, 'the plan job is made by a wiki job');
  const made = await job(h, first.job_id!);
  assert.deepEqual([made.kind, made.priority, made.state, made.input], [WIKI_DOCS_BUILD_JOB.kind, WIKI_DOCS_BUILD_JOB.priority, 'queued', { planJobId: first.id }]);
  assert.equal(await buildTasks(h, s), 0, 'no task of the hidden list was made for the build');
  const page = await call(h, { bearer: s.owner.bearer }, 'GET', `/wiki/spaces/${s.spaceId}/plan`);
  assert.deepEqual([page.body.job.kind, page.body.job.state, page.body.job.taskId, page.body.job.provider], ['build', 'running', null, null],
    'the plan page reads the build as writing the documents');

  const HEAD = createHash('sha1').update(`head-${randomUUID()}`).digest('hex');
  const runner = playRunner(h, s.runner.id, () => tree(HEAD));
  const w = worker(h);
  const ended = await runToEnd(h, w, made.id);
  assert.equal(ended.state, 'succeeded', JSON.stringify(ended));
  const report = ended.report as Record<string, unknown>;
  assert.deepEqual([report.kind, report.planJobId, report.planVersion, report.repoSha, report.written, report.unchanged, report.failed],
    ['docs_build', first.id, v1, HEAD, 3, 0, 0]);

  // The plan job ended as a session's run would have said it: succeeded, the version written, its report.
  const [built] = await builds(h, s.spaceId);
  assert.deepEqual([built.state, built.outcome, built.version], ['ended', 'succeeded', v1]);
  assert.deepEqual(built.progress, { docs: { done: 1, total: 1 }, current: null });
  assert.deepEqual(built.report, {
    planVersion: v1, repoSha: HEAD, docs: { total: 1, written: 1 }, sections: { written: 3, unchanged: 0, failed: 0 },
    tokens: (built.report as { tokens: unknown }).tokens, seconds: (built.report as { seconds: unknown }).seconds, model: MODEL,
  });

  // The repository was read through the runner at the snapshot's commit: one snapshot, and reads of the files named.
  assert.equal(runner.ops[0]?.kind, 'snapshot');
  const read = runner.ops.filter((op) => op.kind === 'read').flatMap((op) => (op.input.items as Array<{ path: string }>).map((item) => item.path));
  assert.deepEqual([...read].sort(), ['contracts/session.contract.json', 'docs/design.md', 'src/runloop.go'], 'the files the sections name, each once');
  for (const op of runner.ops.filter((one) => one.kind === 'read')) assert.equal(op.input.sha, HEAD);

  // Every call went through the queue to the System model, as the documents' writer: its system prompt, its
  // max_tokens, one user message, no tools and no thinking, the deployment's key.
  const firstHits = h.model.hits.length;
  assert.ok(firstHits >= 5, `${firstHits} calls`);
  for (const hit of h.model.hits) {
    assert.equal(hit.system, WIKI_DOCS_BUILD_SYSTEM_PROMPT);
    assert.deepEqual(Object.keys(hit.body).sort(), ['max_tokens', 'messages', 'model', 'stream', 'system']);
    assert.equal(hit.body.max_tokens, WIKI_DOCS_BUILD_JOB.maxTokens);
    assert.equal(hit.authorization, `Bearer ${KEY}`);
  }
  const requests = (await h.sql.query<{ step: string; state: string; n: number }>(
    'SELECT "step","state",count(*)::int AS n FROM "wiki_model_request" WHERE "job_id" = $1 GROUP BY 1,2 ORDER BY 1,2', [made.id])).rows;
  assert.ok(requests.every((row) => row.state === 'succeeded' && row.step.startsWith('docs_')), JSON.stringify(requests));
  assert.equal(requests.reduce((sum, row) => sum + row.n, 0), firstHits, 'one request a call');

  // What was written: every section at the commit read, a repository quote found in its file there.
  const written = await call(h, { bearer: s.owner.bearer }, 'GET', `/wiki/spaces/${s.spaceId}/docs/${SLUG}`);
  expectStatus(written, 200, 'the owner reads the document');
  assert.deepEqual(written.body.sections.map((section: { written: boolean; repoSha: string }) => [section.written, section.repoSha]),
    [[true, HEAD], [true, HEAD], [true, HEAD]]);
  const repoNotes = written.body.footnotes.filter((note: { path: string | null }) => note.path !== null);
  assert.ok(repoNotes.length >= 3 && repoNotes.every((note: { sha: string; verdict: string }) => note.sha === HEAD && note.verdict === 'verified'),
    JSON.stringify(repoNotes.map((note: { path: string; verdict: string }) => [note.path, note.verdict])));
  assert.ok(written.body.footnotes.some((note: { kind: string }) => note.kind === 'turn'), 'the conventions cite the owner\'s words');

  // 2. The owner edits the overview's covers and confirms: the next build leaves the two sections whose material
  // did not change as they are — nothing asked of the model for them — and writes the overview again.
  const v2 = await editOverview(h, s, v1, '这篇讲一个会话怎么运转，第二稿。');
  await confirm(h, s, v2);
  const second = (await builds(h, s.spaceId)).find((row) => row.version === v2 && row.state === 'made');
  assert.ok(second?.job_id, 'the second confirmation made a second build job');
  const again = await runToEnd(h, w, second!.job_id!);
  assert.equal(again.state, 'succeeded', JSON.stringify(again));
  const sections = ((again.report as { docs: Array<{ sections: Array<{ key: string; outcome: string; calls: number }> }> }).docs[0].sections);
  assert.deepEqual(sections.map((section) => [section.outcome, section.calls]), [['written', 1], ['unchanged', 0], ['unchanged', 0]],
    'the overview written again from one call; the sections whose material did not change left as they are');
  assert.deepEqual([(again.report as Record<string, unknown>).written, (again.report as Record<string, unknown>).unchanged], [1, 2]);
  assert.equal(h.model.hits.length - firstHits, 1, 'one call in all: the overview\'s');
  assert.ok(h.model.hits.slice(firstHits).every((hit) => hit.prompt.includes('（概述，')));
  const [, secondRow] = await builds(h, s.spaceId);
  assert.deepEqual([secondRow.state, secondRow.outcome, secondRow.version, (secondRow.report as { sections: unknown }).sections],
    ['ended', 'succeeded', v2, { written: 1, unchanged: 2, failed: 0 }]);
  // The snapshot was not sent again: the space already held that commit.
  assert.deepEqual(runner.ops.filter((op) => op.kind === 'snapshot').map((op) => op.input.skipSha), [null, HEAD]);
});

