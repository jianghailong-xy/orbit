// ── 6. a worker that stops mid-build ─────────────────────────────────────────────────────────────────

test('a worker that stops mid-build: the next one finishes it, asking again only what was in flight and writing each section once', { skip, timeout: 180_000 }, async () => {
  const h = await boot();
  await modelUp(h);
  h.model.hits.length = 0;
  const s = await scene(h, 'restart');
  const v1 = await draft(h, s, planFor(s));
  executor('canary', [s.owner.id]);
  await confirm(h, s, v1);
  const [row] = await builds(h, s.spaceId);
  const HEAD = createHash('sha1').update(`head-${randomUUID()}`).digest('hex');
  playRunner(h, s.runner.id, () => tree(HEAD));
  const first = worker(h);
  // Run until a section is written, then stop the worker as SIGTERM would.
  await passes(first, async () => {
    const { rows } = await h.sql.query<{ n: number }>(
      `SELECT count(*)::int AS n FROM "wiki_doc_section" x JOIN "wiki_doc" d ON d."id" = x."doc_id" WHERE d."space_id" = $1`, [s.spaceId]);
    return rows[0].n >= 1;
  }, 'a first section written');
  await first.executor.onModuleDestroy();
  await first.queue.onModuleDestroy();
  const asked = h.model.hits.length;
  const second = worker(h);
  const ended = await runToEnd(h, second, row.job_id!);
  assert.equal(ended.state, 'succeeded', JSON.stringify(ended));
  // A call answered before the stop is not asked again: its row answers the replay. One the stop cut off is asked
  // again (design §5.4) — at most the job's calls in flight.
  const counts = new Map<string, number>();
  for (const hit of h.model.hits) counts.set(hit.prompt, (counts.get(hit.prompt) ?? 0) + 1);
  const repeated = [...counts.values()].filter((n) => n > 1).length;
  assert.ok(repeated <= 4, `${repeated} calls asked twice (${asked} before the stop, ${h.model.hits.length} in all)`);
  const rows = (await h.sql.query<{ state: string; n: number }>(
    'SELECT "state",count(*)::int AS n FROM "wiki_model_request" WHERE "job_id" = $1 GROUP BY 1', [row.job_id])).rows;
  assert.deepEqual(rows, [{ state: 'succeeded', n: counts.size }], 'one request a call, each answered once and reused');
  const report = ended.report as { written: number; unchanged: number; failed: number };
  assert.equal(report.failed, 0);
  assert.equal(report.written + report.unchanged, 3, 'every section written once: what the first worker wrote is unchanged for the second');
  const versions = (await h.sql.query<{ n: number }>(
    `SELECT count(*)::int AS n FROM "wiki_doc_section" x JOIN "wiki_doc" d ON d."id" = x."doc_id" WHERE d."space_id" = $1`, [s.spaceId])).rows[0].n;
  assert.equal(versions, 3);
});

