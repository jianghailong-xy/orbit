/**
 * `orbit wiki import` on the server (contracts/wiki.contract.json `import.server`, design §2.2 and §8, P5), against a
 * real PostgreSQL, the real runner door and wiki service, and a System model played by a local Node http server.
 *
 * The cases are `src/runner-go/wiki_import_test.go`'s, case for case, as the server runs them — the command's
 * own half (listing the files, their frontmatter, its memory) stays the runner's and is tested there:
 *
 *   1. each note is read as the server kept it, and what the model found is proposed: a dry run, then the batch
 *      under its key as the calling session, origin import; a principle counted and never proposed; the quote the
 *      note's own; the anchors the snapshot's — and the call itself is the importer's: its system prompt, its
 *      max_tokens, one user message, no tools and no thinking;
 *   2. what needs review goes a batch at a time: an op refused for what it says is dropped, and from the first one
 *      refused for room the rest wait — the next job proposes them without reading anything again, and a queue with
 *      no room stops the run;
 *   3. it takes effect as the space's mode says: Tiered applies, Automatic holds for the verification;
 *   4. a run picks up where the last one stopped: the notes it did not reach, and the ops it did not propose;
 *   5. the same batch sent again is the same key, and recorded once;
 *   6. a refused key pauses the import rather than failing it, and a restarted worker goes on from there;
 *   7. a model that is away is waited for, and a request that waited past its limit is asked again when the job
 *      is retried — once the model is back, the job finishes;
 *   8. an answer that does not hold up is asked about once more, with what was wrong, and a note the model never
 *      answers readably is failed and not read again;
 *   9. a Chinese note's entries are titled in Chinese;
 *  10. the anchors are held to a fresh snapshot when the space's runner can take one, and to the one the space
 *      holds when it cannot;
 *  11. a worker that dies mid-import: the next one finishes it, asking nothing twice and proposing once;
 *  12. the door: which path an import takes, a job made once under its id, the notes the space's own, nothing for
 *      an account the runner serves, and another owner's job is not there;
 *  13. the session's own model is out of it: when the server reads, the note route refuses a command that would
 *      read the note itself (WIKI_SERVER_EXECUTES) and hands the text to none, and the proposal route takes no
 *      entries a session's model wrote — and under the default runner both answer exactly as they always have.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki-worker/wiki-import-job.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every row belongs to an account the run created.
 */
