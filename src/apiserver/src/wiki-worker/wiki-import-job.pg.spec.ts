// ── the System model ─────────────────────────────────────────────────────────────────────────────────

interface Hit {
  prompt: string;
  system: string;
  body: Record<string, unknown>;
  authorization: string;
}

type Reply = { status: number; text?: string };

interface FakeModel {
  base: string;
  health: number;
  answer: (prompt: string) => Reply;
  hits: Hit[];
  close: () => Promise<void>;
}

async function fakeModel(): Promise<FakeModel> {
  const sockets = new Set<Socket>();
  const model = { base: '', health: 200, answer: (): Reply => ({ status: 200, text: '[]' }), hits: [] as Hit[] } as unknown as FakeModel;
  const server = createServer((request: IncomingMessage, response: ServerResponse) => {
    let raw = '';
    request.on('data', (chunk: Buffer) => {
      raw += chunk.toString();
    });
    request.on('end', () => {
      if (request.url === '/health') {
        response.writeHead(model.health, { 'content-type': 'application/json' });
        response.end('{}');
        return;
      }
      const body = JSON.parse(raw) as { system?: string; messages?: Array<{ content?: string }> };
      const prompt = body.messages?.[0]?.content ?? '';
      model.hits.push({ prompt, system: body.system ?? '', body: body as Record<string, unknown>, authorization: String(request.headers.authorization ?? '') });
      const reply = model.answer(prompt);
      if (reply.status !== 200) {
        response.writeHead(reply.status, { 'content-type': 'application/json' });
        response.end(JSON.stringify({ type: 'error', error: { type: reply.status === 401 ? 'authentication_error' : 'api_error', message: 'no' } }));
        return;
      }
      response.writeHead(200, { 'content-type': 'text/event-stream' });
      const event = (name: string, data: unknown) => `event: ${name}\ndata: ${JSON.stringify(data)}\n\n`;
      response.write(event('message_start', { type: 'message_start', message: { model: MODEL, usage: { input_tokens: 100, output_tokens: 1 } } }));
      response.write(event('content_block_delta', { type: 'content_block_delta', index: 0, delta: { type: 'text_delta', text: reply.text ?? '' } }));
      response.write(event('message_delta', { type: 'message_delta', delta: { stop_reason: 'end_turn' }, usage: { output_tokens: 20 } }));
      response.write(event('message_stop', { type: 'message_stop' }));
      response.end();
    });
  });
  server.on('connection', (socket: Socket) => {
    sockets.add(socket);
    socket.on('close', () => sockets.delete(socket));
  });
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  model.base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  model.close = async () => {
    for (const socket of sockets) socket.destroy();
    await new Promise<void>((resolve) => server.close(() => resolve()));
  };
  return model;
}

/** Each note answered by its path; a note it names nothing for gets []. */
function scripted(answers: Record<string, string>): (prompt: string) => Reply {
  return (prompt) => {
    for (const [path, text] of Object.entries(answers)) {
      if (prompt.includes(`==== NOTE (${path},`)) return { status: 200, text };
    }
    return { status: 200, text: '[]' };
  };
}

function manyEntries(prefix: string, n: number): string {
  const entries = [];
  for (let i = 1; i <= n; i += 1) {
    entries.push(`{"kind":"concept","title":"${prefix} ${i}","summary":"What ${prefix} ${i} means.","definition":"It is ${i}.",`
      + `"boundaries":"Not ${i + 1}.","anchors":{"paths":[],"commits":[]},"quote":"fact"}`);
  }
  return `[${entries.join(',')}]`;
}

// ── the harness ──────────────────────────────────────────────────────────────────────────────────────

interface Harness {
  base: string;
  sql: Client;
  prisma: PrismaClient;
  app: INestApplication;
  service: WikiService;
  model: FakeModel;
  bearers: Map<string, string>;
  /** Every proposal the job made, as the wiki service was asked for it. */
  proposals: Array<{ principal: WikiPrincipal; spaceId: string; input: WikiProposeInput }>;
}

let harness: Promise<Harness> | undefined;

function boot(): Promise<Harness> {
  process.env.ORBIT_WIKI_EXECUTOR = 'server';
  harness ??= (async () => {
    assertCoordinatorPgUrlIsIsolated(URL_);
    const sql = new Client({ connectionString: URL_, connectionTimeoutMillis: 5_000 });
    await sql.connect();
    await verifyCoordinatorPgIdentity(sql);
    const prisma = prismaClientFor(URL_ as string);
    const bearers = new Map<string, string>();
    const hub = { publishWikiChanged: () => undefined } as unknown as RealtimeService;
    const push = { notifyWikiReviewModeTripped: async () => undefined } as unknown as PushService;
    const service = new WikiService(prisma as unknown as PrismaService, hub, push);
    const proposals: Harness['proposals'] = [];
    const submit = service.submitChangeset.bind(service);
    service.submitChangeset = async (principal, spaceId, input) => {
      proposals.push({ principal, spaceId, input: JSON.parse(JSON.stringify(input)) as WikiProposeInput });
      return submit(principal, spaceId, input);
    };

    @Module({
      controllers: [WikiController, RunnerWikiController],
      providers: [
        { provide: WikiService, useValue: service },
        { provide: WikiRetrieval, useValue: new WikiRetrieval(prisma as unknown as PrismaService) },
        { provide: PrismaService, useValue: prisma },
        RunnerAuthGuard,
        JwtAuthGuard,
        Reflector,
        {
          provide: JwtService,
          useValue: {
            verifyAsync: async (token: string) => {
              const sub = bearers.get(token);
              if (!sub) throw new Error('not a bearer this run issued');
              return { sub, email: `${sub}@wiki.invalid` };
            },
          },
        },
      ],
    })
    class WikiImportJobModule {}

    const app = await NestFactory.create(WikiImportJobModule, { logger: false, abortOnError: false });
    app.setGlobalPrefix('api');
    app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
    app.useGlobalInterceptors(new PublicIdInterceptor());
    await app.listen(0, '127.0.0.1');
    return { base: await app.getUrl(), sql, prisma, app, service, model: await fakeModel(), bearers, proposals };
  })();
  return harness;
}

after(async () => {
  if (!harness) return;
  const { app, prisma, sql, model } = await harness;
  delete process.env.ORBIT_WIKI_EXECUTOR;
  await sql.query('DELETE FROM "wiki_model_status"').catch(() => undefined);
  await app.close().catch(() => undefined);
  await prisma.$disconnect().catch(() => undefined);
  await sql.end().catch(() => undefined);
  await model.close().catch(() => undefined);
});

/** The workers a case started: one that fails halfway must not leave one claiming the next case's jobs. */
const live: Array<{ queue: WikiModelRequestQueue; executor: WikiJobExecutor }> = [];

afterEach(async () => {
  for (const one of live.splice(0)) {
    await one.executor.onModuleDestroy().catch(() => undefined);
    await one.queue.onModuleDestroy().catch(() => undefined);
  }
});

function config(h: Harness): WikiSystemModelConfig {
  return readWikiSystemModel({
    ORBIT_WIKI_MODEL_BASE_URL: h.model.base,
    ORBIT_WIKI_MODEL_API_KEY: KEY,
    ORBIT_WIKI_MODEL: MODEL,
    ORBIT_WIKI_MODEL_CONCURRENCY: '4',
  });
}

/** A worker as the wiki-worker module builds one, with fast timings: the import kind in its map. */
function worker(h: Harness, over: { snapshotWaitMs?: number } = {}): { queue: WikiModelRequestQueue; executor: WikiJobExecutor } {
  const options = { leaseMs: 1_000, renewMs: 200, partialMs: 40, pollMs: 25 };
  const prisma = h.prisma as unknown as PrismaService;
  const probe = new WikiModelStatusProbe(prisma, config(h));
  const queue = new WikiModelRequestQueue(prisma, config(h), probe, undefined, options);
  const runners = {
    import: wikiImportJobRunner({
      prisma, wiki: h.service, repoOps: new WikiRepoOps(prisma), model: MODEL, snapshotWaitMs: over.snapshotWaitMs ?? 5_000,
    }),
  };
  const executor = new WikiJobExecutor(prisma, queue, options, runners);
  live.push({ queue, executor });
  return { queue, executor };
}

/** The model up, as a fresh worker's first probe writes it. */
async function modelUp(h: Harness): Promise<void> {
  h.model.health = 200;
  await h.sql.query('DELETE FROM "wiki_model_status"');
  await new WikiModelStatusProbe(h.prisma as unknown as PrismaService, config(h)).check();
}

async function reset(h: Harness): Promise<void> {
  h.model.hits.length = 0;
  h.model.answer = () => ({ status: 200, text: '[]' });
  h.proposals.length = 0;
  await modelUp(h);
}

// ── requests ─────────────────────────────────────────────────────────────────────────────────────────

interface Answer {
  status: number;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  body: any;
}

interface Caller {
  bearer?: string;
  runner?: string;
  session?: string;
}

async function call(h: Harness, who: Caller, method: string, route: string, body?: unknown): Promise<Answer> {
  const headers: Record<string, string> = { 'content-type': 'application/json' };
  if (who.bearer) headers.authorization = `Bearer ${who.bearer}`;
  if (who.runner) headers['x-runner-token'] = who.runner;
  if (who.session) headers['x-orbit-session-id'] = who.session;
  const response = await fetch(`${h.base}/api${route}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  const text = await response.text();
  let parsed: unknown = null;
  try {
    parsed = text ? JSON.parse(text) : null;
  } catch {
    parsed = { unparsed: text };
  }
  return { status: response.status, body: parsed };
}

function expectStatus(answer: Answer, status: number, why: string): void {
  assert.equal(answer.status, status, `${why}: answered ${answer.status} ${JSON.stringify(answer.body)}`);
}

