type Mode = 'manual' | 'tiered' | 'automatic';

/** The owner, their machine, a workspace (with the secret in its env), a space in `mode`, and a session that imports. */
interface Importer {
  ownerId: string;
  bearer: string;
  runnerId: string;
  workspaceId: string;
  spaceId: string;
  session: string;
  as: Caller;
}

async function importer(h: Harness, mode: Mode): Promise<Importer> {
  const ownerId = randomUUID();
  await h.sql.query(`INSERT INTO "user"("id","email","name","password_hash") VALUES ($1,$2,'import job spec','x')`, [
    ownerId, `wiki-import-job-${ownerId}@wiki.invalid`,
  ]);
  const bearer = `bearer-${ownerId}`;
  h.bearers.set(bearer, ownerId);
  const runnerId = randomUUID();
  const token = `runner-${runnerId}`;
  await h.sql.query(
    `INSERT INTO "runner"("id","name","owner_id","token_hash","capabilities","capabilities_reported_at","last_heartbeat_at")
     VALUES ($1,'spec',$2,$3,$4,now(),now())`,
    [runnerId, ownerId, createHash('sha256').update(token).digest('hex'), [WIKI_REPO_OP_CAPABILITY]],
  );
  const workspaceId = randomUUID();
  await h.sql.query(`INSERT INTO "workspace"("id","name","owner_id","env","runner_id","work_dir") VALUES ($1,'spec',$2,$3,$4,'/tmp/import-spec')`, [
    workspaceId, ownerId, JSON.stringify({ VAULT_KEY: SECRET }), runnerId,
  ]);
  const made = await call(h, { bearer }, 'POST', '/wiki/spaces', { title: `An ${mode} import` });
  expectStatus(made, 201, 'the owner creates a space');
  const spaceId = toUuid(made.body.id as string);
  expectStatus(await call(h, { bearer }, 'PATCH', `/wiki/spaces/${spaceId}`, { reviewMode: mode }), 200, `the space goes ${mode}`);
  const session = await sessionOf(h, ownerId, workspaceId, runnerId);
  return { ownerId, bearer, runnerId, workspaceId, spaceId, session, as: { runner: token, session } };
}

async function sessionOf(h: Harness, ownerId: string, workspaceId: string, runnerId: string): Promise<string> {
  const id = randomUUID();
  await h.sql.query(
    `INSERT INTO "session"("id","title","prompt","owner_id","creator_id","workspace_id","assigned_runner_id","dispatch_origin","updated_at")
     VALUES ($1,'an import session','p',$2,$2,$3,$4,'USER',now())`,
    [id, ownerId, workspaceId, runnerId],
  );
  return id;
}

/** One file registered through the door, as the command registers it when the server reads: its id as the door answers it. */
async function note(h: Harness, who: Importer, path: string, text: string): Promise<{ id: string }> {
  const answer = await call(h, who.as, 'POST', `/runner/wiki/spaces/${who.spaceId}/notes`, { path, text, readBy: 'server' });
  expectStatus(answer, 200, `the file ${path} is registered as a note`);
  assert.equal('text' in answer.body, false, 'the text the server reads is not handed back');
  return answer.body as { id: string };
}

/** The space's snapshot, as a settled snapshot operation leaves it: the tree and the commits origin/main reaches. */
async function snapshot(h: Harness, who: Importer, sha: string, files: string[], commits: string[]): Promise<void> {
  const index = JSON.stringify({ sha, files: files.map((path) => ({ path, size: 1 })), commits });
  await h.prisma.wikiRepoSnapshot.deleteMany({ where: { spaceId: who.spaceId } });
  await h.prisma.wikiRepoSnapshot.create({
    data: {
      spaceId: who.spaceId, ownerId: who.ownerId, sha,
      digest: createHash('sha256').update(index).digest('hex'), sizeBytes: BigInt(Buffer.byteLength(index)), fragmentCount: 1,
    },
  });
  await h.prisma.wikiRepoSnapshotFragment.create({ data: { spaceId: who.spaceId, ordinal: 0, content: index } });
}

interface JobNote {
  noteId: string;
  file: string;
  date: string;
  ops?: Array<{ index: number; body: Record<string, unknown> }>;
}

/** The job the command makes: its id named, through the door. */
async function makeJob(h: Harness, who: Importer, notes: JobNote[], over: Record<string, unknown> = {}): Promise<string> {
  const id = randomUUID();
  const made = await call(h, who.as, 'POST', `/runner/wiki/spaces/${who.spaceId}/import-jobs`, { id, maxOps: 30, concurrency: 4, notes, ...over });
  expectStatus(made, 200, 'the import job is made');
  return id;
}

/** The job as the command reads it. */
async function readJob(h: Harness, who: Importer, id: string): Promise<Answer> {
  return call(h, who.as, 'GET', `/runner/wiki/spaces/${who.spaceId}/import-jobs/${id}`);
}

/** Run the worker until the job ends, and read it as the command would. */
async function drive(
  h: Harness,
  who: Importer,
  id: string,
  w: { queue: WikiModelRequestQueue; executor: WikiJobExecutor },
  seconds = 20,
): Promise<Answer> {
  await passes(w, async () => {
    const { rows: [row] } = await h.sql.query<{ state: string }>('SELECT "state" FROM "wiki_job" WHERE "id" = $1', [id]);
    return ['succeeded', 'failed', 'cancelled'].includes(row.state);
  }, `the job ${id} to end`, seconds);
  await w.executor.whenIdle();
  return readJob(h, who, id);
}

/** Passes of the worker until `ok`, with no wait for what the job is still doing. */
async function passes(
  w: { queue: WikiModelRequestQueue; executor: WikiJobExecutor },
  ok: () => Promise<boolean>,
  what: string,
  seconds = 20,
): Promise<void> {
  const deadline = Date.now() + seconds * 1000;
  for (;;) {
    await w.executor.runOnce();
    await w.queue.runOnce();
    if (await ok()) return;
    assert.ok(Date.now() < deadline, `${what} within ${seconds}s`);
    await delay(25);
  }
}

// eslint-disable-next-line @typescript-eslint/no-explicit-any
function titles(ops: any[]): string[] {
  return ops.map((op) => op.entry?.title as string);
}

/** Every op the job proposed for real, in order. */
function proposed(h: Harness): Array<Record<string, unknown>> {
  return h.proposals.filter((one) => !one.input.dryRun).flatMap((one) => one.input.ops as Array<Record<string, unknown>>);
}

