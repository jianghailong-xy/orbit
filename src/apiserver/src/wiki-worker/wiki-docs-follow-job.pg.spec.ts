// ── 5. who runs beside whom ─────────────────────────────────────────────────────────────────────────

test('a follow job runs beside articles and verify and waits for maintain, and the two indexes hold it for two schedulers', { skip, timeout: 60_000 }, async () => {
  const h = await boot();
  const s = await scene(h, 'overlap');
  const prisma = h.prisma as unknown as PrismaService;
  // The space's first draft waits on the server too: it is not this case's.
  await h.sql.query(`UPDATE "wiki_job" SET "state" = 'cancelled', "ended_at" = now() WHERE "space_id" = $1 AND "state" = 'queued'`, [s.spaceId]);
  const kinds = ['verify', 'articles', 'import', 'docs_build', 'maintain', 'smoke', WIKI_DOCS_FOLLOW.kind];
  const claim = () => claimWikiJobs(prisma, { workerId: randomUUID(), kinds, owners: [s.owner.id], limit: 4 });
  const make = async (kind: string): Promise<string> => {
    const id = randomUUID();
    await enqueueWikiJob(prisma, { id, ownerId: s.owner.id, spaceId: s.spaceId, kind });
    await delay(5);
    return id;
  };
  const end = async (claimed: { id: string; leaseGeneration: string }) => assert.ok(await succeedWikiJob(prisma, { id: claimed.id, generation: claimed.leaseGeneration }));

  // articles runs; a follow job queued after it runs beside it.
  const articles = await make('articles');
  const [a] = await claim();
  assert.equal(a?.id, articles);
  const follow = await make(WIKI_DOCS_FOLLOW.kind);
  const [f] = await claim();
  assert.equal(f?.id, follow, 'the follow job runs beside articles');
  // verify waits for articles (two jobs that write no document still wait for each other), and maintain for both.
  const verify = await make('verify');
  const maintain = await make('maintain');
  assert.deepEqual(await claim(), [], 'verify waits for articles, maintain for both');
  // articles ends: verify runs beside the follow job; maintain still waits.
  await end(a);
  const [v] = await claim();
  assert.equal(v?.id, verify, 'verify runs beside the follow job');
  assert.deepEqual(await claim(), [], 'maintain waits for the follow job and verify');
  // verify ends: the follow job alone runs, and maintain still waits for it.
  await end(v);
  assert.deepEqual(await claim(), [], 'maintain waits for the follow job');
  // The database holds it for two schedulers that read at once: a writer beside the follow job is refused by one
  // index, and a second job that writes no document beside another by the other.
  const running = (id: string) => h.sql.query(
    `UPDATE "wiki_job" SET "state" = 'running', "lease_owner" = gen_random_uuid(), "lease_generation" = gen_random_uuid(),
            "lease_deadline_at" = now() + interval '1 minute' WHERE "id" = $1`, [id]);
  const refusedBy = (index: string) => (error: { code?: string; constraint?: string }) => error.code === '23505' && error.constraint === index;
  await assert.rejects(running(maintain), refusedBy('wiki_job_space_running_writer_key'));
  await end(f);
  // Once the space is free, maintain runs; a follow job made now waits for it, and so does articles.
  const [m] = await claim();
  assert.equal(m?.id, maintain);
  const nextFollow = await make(WIKI_DOCS_FOLLOW.kind);
  const nextArticles = await make('articles');
  assert.deepEqual(await claim(), [], 'the follow job and articles wait for maintain');
  await assert.rejects(running(nextFollow), refusedBy('wiki_job_space_running_writer_key'));
  await assert.rejects(running(nextArticles), refusedBy('wiki_job_space_running_other_key'));
  await end(m);
  // The space's own order: the follow job made first goes first, one job of a space a claim, and articles runs beside it.
  const both = await claim();
  assert.deepEqual(both.map((one) => one.id), [nextFollow], 'one job of a space a claim');
  const [second] = await claim();
  assert.equal(second?.id, nextArticles, 'articles runs beside the follow job');
});

// ── 6. a verdict's withdrawal beside a follow job's write ────────────────────────────────────────────

test('a verdict\'s withdrawal and a follow job\'s write of the same section, in either order, both commit without a deadlock', { skip, timeout: 240_000 }, async () => {
  const h = await boot();
  const { s, keys, w } = await built(h, 'deadlock');
  const entryId = await cardEntry(h, s);
  const talk = await chat(h, s, 'Chat about delivery', CHAT_WORDS);
  // The delivery section cites through the entry: a press handed it the entry's source.
  const first = await press(h, s, { chatId: talk.id, sections: [{ doc: SLUG, key: keys.delivery }], entryIds: [entryId] });
  assert.equal((await runToEnd(h, w, first.jobId)).state, 'succeeded');
  const via = (await h.sql.query(`SELECT count(*)::int AS "n" FROM "wiki_doc_footnote" WHERE "owner_id" = $1 AND "via_entry_id" = $2`, [s.owner.id, entryId])).rows[0].n;
  assert.ok(via > 0, 'the section cites through the entry');

  // Every retried transaction says so: a deadlock PostgreSQL broke would be one of them, with its SQLSTATE.
  const said: string[] = [];
  const keep = (message: unknown) => said.push(String(message));
  Logger.overrideLogger({ log: () => undefined, warn: keep, error: keep, debug: () => undefined, verbose: () => undefined });
  const deadlocks = async (): Promise<number> => (await h.sql.query(`SELECT "deadlocks"::int AS "n" FROM pg_stat_database WHERE "datname" = current_database()`)).rows[0].n;
  const deadlocksBefore = await deadlocks();
  const waiting = async (): Promise<number> => (await h.sql.query(
    `SELECT count(*)::int AS "n" FROM pg_stat_activity WHERE "datname" = current_database() AND "wait_event_type" = 'Lock'`)).rows[0].n;
  const until = async (n: number, what: string): Promise<void> => {
    const deadline = Date.now() + 30_000;
    while ((await waiting()) < n) {
      assert.ok(Date.now() < deadline, `${what} within 30s`);
      await delay(20);
    }
  };
  // A verdict, as wiki.recordVerifications runs one in its entry's own transaction: the entry written first — the row
  // applyOp writes — then the sentences that came through it withdrawn and their section marked stale through
  // withdrawDocSentences, which takes the documents after the entry (recomputeFlags, docs.withdrawal).
  const verdict = () => h.prisma.$transaction(async (tx) => {
    await tx.$executeRaw`UPDATE "wiki_entry" SET "anchor_state" = "anchor_state" WHERE "id" = ${entryId}::uuid`;
    return withdrawDocSentences(tx, s.owner.id, entryId, 'rejected');
  }, { timeout: 60_000 });
  // The document's row, held by a third transaction while the two line up behind it: it orders them, and takes no
  // lock either of them would not take itself.
  const holders: Client[] = [];
  const hold = async (): Promise<Client> => {
    const holder = new Client({ connectionString: URL_ });
    await holder.connect();
    holders.push(holder);
    await holder.query('BEGIN');
    await holder.query(`SELECT "id" FROM "wiki_doc" WHERE "space_id" = $1 AND "slug" = $2 FOR NO KEY UPDATE`, [s.spaceId, SLUG]);
    return holder;
  };
  const release = async (holder: Client): Promise<void> => {
    await holder.query('COMMIT');
    await holder.end();
    holders.splice(holders.indexOf(holder), 1);
  };
  let halted = false;
  const ended = async (jobId: string) => halted || ['succeeded', 'failed', 'cancelled'].includes((await job(h, jobId)).state);
  const follow = (jobId: string) => passes(w, () => ended(jobId), 'the follow job to end', 120);
  // What runs in the background is awaited where the case needs it; a case that fails first leaves nothing behind.
  const quietly = <T>(promise: Promise<T>): Promise<T> => {
    promise.catch(() => undefined);
    return promise;
  };

  try {
    // The verdict first: it holds the entry and waits for the document; the follow job's write then waits for the
    // entry, which a document write takes before its document. Let go, the verdict commits, then the write.
    const one = await press(h, s, { chatId: talk.id, sections: [{ doc: SLUG, key: keys.delivery }], entryIds: [entryId] });
    let holder = await hold();
    const withdrew = quietly(verdict());
    await until(1, 'the verdict waits for the document');
    const writing = quietly(follow(one.jobId));
    await until(2, 'the follow job\'s write waits for the entry the verdict holds');
    await release(holder);
    assert.ok((await withdrew) > 0, 'the verdict withdrew the sentences that came through the entry');
    await writing;
    assert.equal((await job(h, one.jobId)).state, 'succeeded', JSON.stringify(await job(h, one.jobId)).slice(0, 800));

    // The write first: it holds the entry FOR SHARE and waits for the document; the verdict then waits for the entry.
    // Let go, the write commits, then the verdict.
    const two = await press(h, s, { chatId: talk.id, sections: [{ doc: SLUG, key: keys.delivery }], entryIds: [entryId] });
    holder = await hold();
    const written = quietly(follow(two.jobId));
    await until(1, 'the follow job\'s write waits for the document, the entry in its hands');
    const withdrewAfter = quietly(verdict());
    await until(2, 'the verdict waits for the entry the write holds');
    await release(holder);
    await written;
    assert.equal((await job(h, two.jobId)).state, 'succeeded', JSON.stringify(await job(h, two.jobId)).slice(0, 800));
    assert.ok((await withdrewAfter) > 0, 'the verdict withdrew what the write had just written through the entry');
  } finally {
    halted = true;
    for (const holder of holders.splice(0)) {
      await holder.query('ROLLBACK').catch(() => undefined);
      await holder.end().catch(() => undefined);
    }
    Logger.overrideLogger(false);
  }
  assert.deepEqual(said.filter((line) => /40P01|deadlock/iu.test(line)), [], 'no transaction met a deadlock');
  await delay(1_200);
  assert.equal(await deadlocks(), deadlocksBefore, 'PostgreSQL detected no deadlock in this database');
});
