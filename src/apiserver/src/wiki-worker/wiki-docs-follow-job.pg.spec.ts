// ── 1. the facts, and what makes no job ───────────────────────────────────────────────────────────────

test('a merge into main makes one follow job: the same receipt again and a second merge join it, a press raises it, one while it runs queues the next, and no fact makes none', { skip, timeout: 120_000 }, async () => {
  const h = await boot();
  const s = await scene(h, 'facts');
  await confirmPlan(h, s);
  const commits = history();
  const A = headOf(commits);
  const B = commit(commits, { 'src/runloop.go': RUNLOOP_CHANGED });
  const C = commit(commits, { 'README.md': 'An app, again.\n' });
  const D = commit(commits, { 'contracts/session.contract.json': CONTRACT_CHANGED });

  // One receipt, one job: queued, at a merge's priority, carrying the fact.
  const first = await mergingSession(h, s, 'Shorten the offline window');
  const source = sha1('source');
  const { id: receipt } = await merged(h, s, first, A, B, { sourceSha: source });
  let jobs = await follows(h, s.spaceId);
  assert.equal(jobs.length, 1, 'one receipt, one job');
  assert.deepEqual([jobs[0].state, jobs[0].priority], ['queued', WIKI_DOCS_FOLLOW.priorities.merge]);
  assert.deepEqual(jobs[0].input.facts.map((fact) => [fact.kind, fact.receiptId, fact.from, fact.sha, fact.title, fact.chat]),
    [['merge', receipt, A, B, 'Shorten the offline window', false]]);

  // The same merge reported again — the door's replay — is the same fact: still one job, carrying it once. So is another
  // receipt of the same change of main, as a promotion writes one for each of its tasks.
  assert.equal((await merged(h, s, first, A, B, { sourceSha: source })).created, false, 'the door answers the first receipt');
  await merged(h, s, await mergingSession(h, s, 'Another task of the same promotion'), A, B);
  jobs = await follows(h, s.spaceId);
  assert.deepEqual(jobs.map((one) => one.input.facts.length), [1], 'a receipt delivered twice, or one change of main twice, is carried once');

  // A second merge while the job is queued joins it, in one write.
  const second = await mergingSession(h, s, 'Retry delivery from the stored row');
  await merged(h, s, second, B, C);
  jobs = await follows(h, s.spaceId);
  assert.equal(jobs.length, 1, 'still one queued job a space');
  assert.deepEqual(jobs[0].input.facts.map((fact) => fact.sha), [B, C]);

  // No fact, no job: a merge that did not land, a merge into another branch, a landed receipt naming no range of
  // commits (an observation, a check that found the work there), and a merge on a repository whose space has no
  // confirmed plan.
  const quiet = await mergingSession(h, s, 'Nothing reached main');
  await h.receipts.record(s.owner.id, quiet, { result: 'ERROR', sourceSha: sha1('source'), targetBranch: 'main', detail: { message: 'the push was refused' } } as never, 'USER');
  await merged(h, s, quiet, C, D, { targetBranch: 'feat/elsewhere' });
  await h.receipts.record(s.owner.id, quiet, { result: 'ALREADY_MERGED', sourceSha: sha1('source'), targetBranch: 'main' } as never, 'USER');
  const other = await scene(h, 'no plan');
  const elsewhere = await mergingSession(h, other, 'A merge in a space with no plan');
  await merged(h, other, elsewhere, A, B);
  jobs = await follows(h, s.spaceId);
  assert.deepEqual(jobs.map((one) => one.input.facts.length), [2], 'no receipt that is no fact joined the job');
  assert.equal((await follows(h, other.spaceId)).length, 0, 'a space with no confirmed plan has no follow job');

  // A press joins it too, at the press's priority: the owner's work, ahead of background maintenance.
  const talk = await chat(h, s, 'Chat about delivery', CHAT_WORDS);
  const pressed = await press(h, s, { chatId: talk.id, sections: [{ doc: SLUG, key: 'anything-of-the-plan' }], entryIds: [] });
  jobs = await follows(h, s.spaceId);
  assert.equal(jobs.length, 1);
  assert.equal(pressed.jobId, jobs[0].id, 'the press joined the queued job');
  assert.deepEqual([jobs[0].priority, jobs[0].input.facts.map((fact) => fact.kind)], [WIKI_DOCS_FOLLOW.priorities.press, ['merge', 'merge', 'press']]);

  // One that comes while the job runs queues the next, which the claim takes once the running one ends.
  const [claimed] = await claimWikiJobs(h.prisma as unknown as PrismaService, { workerId: randomUUID(), kinds: [WIKI_DOCS_FOLLOW.kind], owners: [s.owner.id], limit: 1 });
  assert.equal(claimed?.id, jobs[0].id, 'the follow job is running');
  const third = await mergingSession(h, s, 'Order the contract by seq');
  await merged(h, s, third, C, D);
  jobs = await follows(h, s.spaceId);
  assert.deepEqual(jobs.map((one) => [one.state, one.input.facts.map((fact) => fact.sha ?? fact.kind)]), [['running', [B, C, 'press']], ['queued', [D]]]);
  assert.deepEqual(await claimWikiJobs(h.prisma as unknown as PrismaService, { workerId: randomUUID(), kinds: [WIKI_DOCS_FOLLOW.kind], owners: [s.owner.id], limit: 4 }), [],
    'the next follow job waits for the one that runs');
});

// ── 2. only what the merge touched; an unchanged fingerprint asks nothing; catch-up does not skip it ──────

test('a merge has only the sections citing a file it changed written, while the space catches up, and a change no section reads asks the model nothing', { skip, timeout: 180_000 }, async () => {
  const h = await boot();
  const { s, keys, history: commits, w, A } = await built(h, 'affected');
  const before = await writtenAt(h, s.spaceId);
  assert.deepEqual([...before.values()], [A, A, A, A], 'every section written at the first commit');

  // The merge changes the run loop inside `runLoop` and a README nothing cites. Its session settled three days ago,
  // so the space is behind: a maintenance run made now would skip its documents step (maintenance.job.catchUp).
  const B = commit(commits, { 'src/runloop.go': RUNLOOP_CHANGED, 'README.md': 'An app that runs sessions.\n' });
  const session = await mergingSession(h, s, 'Beat while claiming', new Date(Date.now() - 3 * 24 * 3600 * 1000));
  const backlog = await countBacklog(h.prisma as never, await spaceScope(h.prisma as unknown as PrismaService, s.owner.id, s.spaceId), null);
  assert.equal((await wikiMaintenanceCatchUpOf(h.prisma as never, s.owner.id, s.spaceId, backlog.oldestPendingAt, new Date())).state, 'active',
    'the space is catching up');
  const hits = h.model.hits.length;
  await merged(h, s, session, A, B);
  const [follow] = await follows(h, s.spaceId);
  const ended = await runToEnd(h, w, follow.id);
  assert.equal(ended.state, 'succeeded', JSON.stringify(ended).slice(0, 1200));
  const report = ended.report!;
  assert.equal(report.sha, B);
  // The flow section, which reads the run loop, is written; the overview over it as its fingerprint decides; the two
  // sections that read the design and the contract are not taken up at all.
  const taken = new Map(report.sections.map((section) => [section.key, section]));
  assert.equal(taken.get(keys.flow)?.outcome, 'written');
  assert.equal(taken.get(keys.flow)?.forced, false);
  assert.equal(taken.has(keys.delivery), false, 'the design\'s section was not taken up');
  assert.equal(taken.has(keys.contract), false, 'the contract\'s section was not taken up');
  assert.equal(report.left, 0);
  const asked = writePrompts(h, hits);
  assert.ok(asked.length >= 1 && asked.every((prompt) => !prompt.includes('docs/design.md') && !prompt.includes('contracts/session.contract.json')),
    'no write asked about a section the merge did not touch');
  const after = await writtenAt(h, s.spaceId);
  assert.deepEqual([after.get(keys.flow), after.get(keys.delivery), after.get(keys.contract)], [B, A, A]);
  // The version it replaced is kept with the merge's reason: the session's title and the commit it put on main.
  const kept = await latestVersion(h, s.spaceId, keys.flow);
  assert.deepEqual([kept?.reason, kept?.reason_title, kept?.reason_sha, kept?.job_id], ['merge', 'Beat while claiming', B, follow.id]);
  assert.equal(await latestVersion(h, s.spaceId, keys.delivery), undefined, 'the design\'s section kept no version: it was not written');

  // A merge that changes the run loop outside `runLoop`: the flow section cites the file, but its own material — the
  // function it names — is what it was, so nothing is written and the model is asked nothing at all.
  const C = commit(commits, { 'src/runloop.go': RUNLOOP_APPENDED });
  const quiet = await mergingSession(h, s, 'Add a helper');
  const hitsBefore = h.model.hits.length;
  await merged(h, s, quiet, B, C);
  const next = (await follows(h, s.spaceId)).find((one) => one.state === 'queued')!;
  const quietEnd = await runToEnd(h, w, next.id);
  assert.equal(quietEnd.state, 'succeeded', JSON.stringify(quietEnd).slice(0, 800));
  assert.deepEqual(quietEnd.report!.sections, [], 'no section was taken up');
  assert.equal(h.model.hits.length, hitsBefore, 'not one model call');
  assert.equal((await writtenAt(h, s.spaceId)).get(keys.flow), B, 'the flow section is left as it was written');
});

