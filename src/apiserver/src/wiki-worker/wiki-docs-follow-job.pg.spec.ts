/** Passes of the worker until `ok`. */
async function passes(w: Worker, ok: () => Promise<boolean>, what: string, seconds = 90): Promise<void> {
  const deadline = Date.now() + seconds * 1000;
  for (;;) {
    await w.executor.runOnce();
    await w.queue.runOnce();
    if (await ok()) return;
    assert.ok(Date.now() < deadline, `${what} within ${seconds}s`);
    await delay(25);
  }
}

// ── the space's runner, and the history of commits it reads ──────────────────────────────────────────

/** origin/main's commits, oldest first, and the files of each. */
interface History {
  commits: string[];
  trees: Map<string, Record<string, string>>;
}

function sha1(seed: string): string {
  return createHash('sha1').update(`${seed}-${randomUUID()}`).digest('hex');
}

/** A new commit on top of the history: its files are the head's with `changes` laid over (null deletes). */
function commit(history: History, changes: Record<string, string | null>): string {
  const head = history.commits[history.commits.length - 1];
  const files = { ...(head ? history.trees.get(head) : {}) };
  for (const [path, text] of Object.entries(changes)) {
    if (text === null) delete files[path];
    else files[path] = text;
  }
  const sha = sha1('commit');
  history.commits.push(sha);
  history.trees.set(sha, files);
  return sha;
}

const headOf = (history: History): string => history.commits[history.commits.length - 1];

/** What one `read` item answers, as the runner's wikiRepoOpReadOne answers it: the whole file. */
function readOne(files: Record<string, string>, item: { path: string }): Record<string, unknown> {
  if (!(item.path in files)) return { path: item.path, found: false, chars: 0 };
  const text = files[item.path];
  const size = Buffer.byteLength(text, 'utf8');
  if (size > WIKI_REPO_OPS.wholeFileBytes) return { path: item.path, found: false, reason: 'too_large', size, chars: 0 };
  return { path: item.path, found: true, size, text, truncated: false, chars: Array.from(text).length };
}

/** `git diff --name-status` between two commits of the history, as the runner's wikiRepoOpDiff answers it. */
function diffOf(history: History, from: string, to: string): Record<string, unknown> {
  const a = history.trees.get(from) ?? {};
  const b = history.trees.get(to) ?? {};
  const files: Array<{ status: string; path: string }> = [];
  for (const path of [...new Set([...Object.keys(a), ...Object.keys(b)])].sort()) {
    if (!(path in a)) files.push({ status: 'A', path });
    else if (!(path in b)) files.push({ status: 'D', path });
    else if (a[path] !== b[path]) files.push({ status: 'M', path });
  }
  const docs = files.filter((file) => file.status === 'A' && file.path.startsWith('docs/')).map((file) => file.path);
  return { diff: { from, to, files, docs } };
}

/**
 * The space's runner: claims what its heartbeat would be handed and answers each operation from the history — a
 * snapshot at the head (or skipped, when the space holds that commit), a read at the commit it names, a diff between
 * two commits — and records what it was asked.
 */
function playRunner(h: Harness, runnerId: string, history: History): { ops: Array<{ kind: string; input: Record<string, unknown> }>; stop: () => Promise<void> } {
  const ops = new WikiRepoOps(h.prisma as unknown as PrismaService);
  const seen: Array<{ kind: string; input: Record<string, unknown> }> = [];
  let running = true;
  const loop = (async () => {
    while (running) {
      // The heartbeat a live runner sends, which is what reads it as online.
      await h.sql.query('UPDATE "runner" SET "last_heartbeat_at" = now() WHERE "id" = $1', [runnerId]).catch(() => undefined);
      const claimed = await ops.dispatch({ runnerId, leaseOwner: randomUUID(), draining: false, capabilities: [WIKI_REPO_OP_CAPABILITY, WIKI_REPO_OP_READ_CAPABILITY] }).catch(() => []);
      for (const op of claimed) {
        seen.push({ kind: op.kind, input: op.input });
        const head = headOf(history);
        let result: Record<string, unknown>;
        if (op.kind === 'snapshot') {
          const held = await h.prisma.wikiRepoSnapshot.findFirst({ where: { sha: head }, select: { sha: true } });
          const files = history.trees.get(head)!;
          result = op.input.skipSha === head && held
            ? { sha: head, skipped: true }
            : { sha: head, index: JSON.stringify({ sha: head, files: Object.entries(files).map(([path, text]) => ({ path, size: Buffer.byteLength(text) })), commits: [...history.commits].reverse() }) };
        } else if (op.kind === 'diff') {
          result = diffOf(history, String(op.input.from), String(op.input.to));
        } else {
          const files = history.trees.get(String(op.input.sha)) ?? {};
          const items = ((op.input.items as Array<{ path: string }>) ?? []).map((item) => readOne(files, item));
          result = { read: { sha: op.input.sha, items, chars: items.reduce((sum, item) => sum + (item.chars as number), 0) } };
        }
        await ops.applyWikiRepoOpResult({
          id: op.id, runnerId,
          body: { claimGeneration: op.claimGeneration, leaseOwner: op.leaseOwner, state: 'succeeded', result },
        });
      }
      await delay(15);
    }
  })();
  const player = { ops: seen, stop: async () => { running = false; await loop; } };
  players.push(player);
  return player;
}

// ── requests ─────────────────────────────────────────────────────────────────────────────────────────

interface Answer {
  status: number;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  body: any;
}

async function call(h: Harness, bearer: string, method: string, route: string, body?: unknown): Promise<Answer> {
  const response = await fetch(`${h.base}/api${route}`, {
    method,
    headers: { 'content-type': 'application/json', authorization: `Bearer ${bearer}` },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await response.text();
  let parsed: unknown = null;
  try {
    parsed = text ? JSON.parse(text) : null;
  } catch {
    parsed = { unparsed: text };
  }
  return { status: response.status, body: parsed };
}

function expectStatus(answer: Answer, status: number, why: string): void {
  assert.equal(answer.status, status, `${why}: answered ${answer.status} ${JSON.stringify(answer.body).slice(0, 1500)}`);
}

