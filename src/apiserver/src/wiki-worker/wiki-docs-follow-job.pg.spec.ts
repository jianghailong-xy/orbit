/** The confirmed plan's section keys, by kind. */
interface Keys {
  overview: string;
  flow: string;
  delivery: string;
  contract: string;
}

/** The plan drafted and confirmed: the confirmation makes the space's docs_build job. */
async function confirmPlan(h: Harness, s: Scene): Promise<{ keys: Keys; build: string }> {
  const drafted = await h.plans.submitServerDraft(s.drafter, {
    baseVersion: null, target: { min: 1, max: 10 }, plan: planFor(), repoCheck: { sha: 'a'.repeat(40), checked: 3, missing: [] }, model: MODEL,
  });
  expectStatus(await call(h, s.owner.bearer, 'POST', `/wiki/spaces/${s.spaceId}/plan/versions/${drafted.version}/confirm`), 200, 'the owner confirms the plan');
  const plan = await call(h, s.owner.bearer, 'GET', `/wiki/spaces/${s.spaceId}/plan`);
  const sections = plan.body.confirmed.docs.find((doc: { slug: string }) => doc.slug === SLUG).sections as Array<{ key: string; kind: string }>;
  const key = (kind: string) => sections.find((section) => section.kind === kind)!.key;
  const [made] = (await h.sql.query<{ job_id: string }>(`SELECT "job_id" FROM "wiki_plan_job" WHERE "space_id" = $1 AND "kind" = 'build' AND "state" = 'made'`, [s.spaceId])).rows;
  return { keys: { overview: key('overview'), flow: key('flow'), delivery: key('concepts'), contract: key('interface') }, build: made.job_id };
}

interface JobRow {
  id: string;
  kind: string;
  state: string;
  priority: number;
  input: { facts: Array<Record<string, unknown>> };
  report: (WikiDocsFollowReport & Record<string, unknown>) | null;
  error: string | null;
}

async function job(h: Harness, id: string): Promise<JobRow> {
  return (await h.sql.query<JobRow>('SELECT "id","kind","state","priority","input","report","error" FROM "wiki_job" WHERE "id" = $1', [id])).rows[0];
}

/** The space's follow jobs, oldest first. */
async function follows(h: Harness, spaceId: string): Promise<JobRow[]> {
  return (await h.sql.query<JobRow>(
    `SELECT "id","kind","state","priority","input","report","error" FROM "wiki_job" WHERE "space_id" = $1 AND "kind" = 'docs_follow' ORDER BY "created_at","id"`,
    [spaceId],
  )).rows;
}

async function runToEnd(h: Harness, w: Worker, jobId: string): Promise<JobRow> {
  await passes(w, async () => ['succeeded', 'failed', 'cancelled'].includes((await job(h, jobId)).state), `the job ${jobId} to end`);
  await w.executor.whenIdle();
  return job(h, jobId);
}

/** A space whose documents are written at the history's first commit: the plan confirmed and its build run. */
async function built(h: Harness, name: string): Promise<{ s: Scene; keys: Keys; history: History; w: Worker; A: string }> {
  await modelUp(h);
  const s = await scene(h, name);
  const { keys, build } = await confirmPlan(h, s);
  const commits = history();
  playRunner(h, s.runnerId, commits);
  const w = worker(h);
  const ended = await runToEnd(h, w, build);
  assert.equal(ended.state, 'succeeded', `the build: ${JSON.stringify(ended).slice(0, 800)}`);
  return { s, keys, history: commits, w, A: headOf(commits) };
}

/** A session of the space's workspace that will merge, settled at `settledAt`. */
async function mergingSession(h: Harness, s: Scene, title: string, settledAt = new Date()): Promise<string> {
  const id = randomUUID();
  await h.sql.query(
    `INSERT INTO "session"("id","title","prompt","owner_id","creator_id","workspace_id","assigned_runner_id","status","dispatch_origin","branch","last_turn_at","updated_at")
     VALUES ($1,$2,'p',$3,$3,$4,$5,'SUCCEEDED'::run_status,'USER',$6,$7,now())`,
    [id, title, s.owner.id, s.workspaceId, s.runnerId, `orbit/${id.slice(0, 8)}`, settledAt],
  );
  return id;
}

/** A merge into main recorded through the door every merge receipt goes through: main from `from` to `to`. */
async function merged(h: Harness, s: Scene, sessionId: string, from: string, to: string, over: Record<string, unknown> = {}): Promise<{ id: string; created: boolean }> {
  const { receipt, created } = await h.receipts.record(s.owner.id, sessionId, {
    result: 'MERGED', sourceSha: sha1('source'), targetBranch: 'main', targetShaBefore: from, targetShaAfter: to, ...over,
  } as never, 'USER');
  return { id: receipt.id, created };
}

/** The newest version a section kept, as the versions table holds it. */
async function latestVersion(h: Harness, spaceId: string, key: string): Promise<{ id: string; reason: string; reason_title: string | null; reason_sha: string | null; job_id: string | null } | undefined> {
  return (await h.sql.query(
    `SELECT "id","reason","reason_title","reason_sha","job_id" FROM "wiki_doc_section_version"
      WHERE "space_id" = $1 AND "doc_slug" = $2 AND "section_key" = $3 ORDER BY "seq" DESC LIMIT 1`,
    [spaceId, SLUG, key],
  )).rows[0];
}

/** The commit each section of the document was written at, by key. */
async function writtenAt(h: Harness, spaceId: string): Promise<Map<string, string>> {
  const rows = (await h.sql.query<{ key: string; repo_sha: string }>(
    `SELECT x."key", x."repo_sha" FROM "wiki_doc_section" x JOIN "wiki_doc" d ON d."id" = x."doc_id" WHERE d."space_id" = $1 AND d."slug" = $2`,
    [spaceId, SLUG],
  )).rows;
  return new Map(rows.map((row) => [row.key, row.repo_sha]));
}

/** The prompts that asked the model to write a section, not an overview, since `from`. */
function writePrompts(h: Harness, from: number): string[] {
  return h.model.hits.slice(from).map((hit) => hit.prompt)
    .filter((prompt) => prompt.includes('# Task: write the document') && !prompt.includes('(the overview, about'));
}

/** A press of a card in its own transaction, as C6's Apply makes one. */
