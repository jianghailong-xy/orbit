/** One read answered the way wiki_repo_ops.go answers it: each item within its own limit, the whole within one section's material. */
function readAnswer(input: { sha: string; items: Array<{ path: string; maxChars?: number }> }): Record<string, unknown> {
  let total = 0;
  const items = input.items.map((item) => {
    const text = FIXTURE.files[item.path];
    if (text === undefined) return { path: item.path, found: false, chars: 0 };
    let max = item.maxChars && item.maxChars > 0 ? item.maxChars : WIKI_REPO_OPS.docSectionChars;
    max = Math.min(max, WIKI_REPO_OPS.sectionChars, WIKI_REPO_OPS.sectionChars - total);
    const runes = [...text];
    const cut = runes.length <= max ? text : `${runes.slice(0, max - 8).join('')}\n…（后略）\n`;
    total += [...cut].length;
    return { path: item.path, found: true, text: cut, truncated: cut !== text, chars: [...cut].length };
  });
  return { read: { sha: input.sha, items, chars: total } };
}

interface PlayedRunner {
  /** Every operation the runner was handed, in order. */
  ops: Array<{ kind: string; input: Record<string, unknown> }>;
  stop: () => Promise<void>;
}

/** The space's runner, as its heartbeat would be: it claims what is queued for it and answers from the fixture. */
function playRunner(h: Harness, o: Owner, over: { sha?: string; index?: string } = {}): PlayedRunner {
  const ops = new WikiRepoOps(h.prisma as unknown as PrismaService);
  const seen: PlayedRunner['ops'] = [];
  let stopped = false;
  const loop = (async () => {
    while (!stopped) {
      const claimed = await ops.dispatch({ runnerId: o.runnerId, leaseOwner: randomUUID(), draining: false, capabilities: [WIKI_REPO_OP_CAPABILITY] });
      for (const op of claimed) {
        seen.push({ kind: op.kind, input: op.input });
        const result = op.kind === 'snapshot'
          ? { sha: over.sha ?? SHA, index: over.index ?? JSON.stringify(FIXTURE.index) }
          : readAnswer(op.input as { sha: string; items: Array<{ path: string; maxChars?: number }> });
        await ops.applyWikiRepoOpResult({
          id: op.id, runnerId: o.runnerId,
          body: { claimGeneration: op.claimGeneration, leaseOwner: op.leaseOwner, state: 'succeeded', result },
        });
      }
      await delay(15);
    }
  })();
  const played = { ops: seen, stop: async () => {
    stopped = true;
    await loop;
  } };
  live.push(played);
  return played;
}

/** Passes of the worker until the plan job ends, and its row then. */
async function drive(h: Harness, w: Worker, planJobId: string, seconds = 60): Promise<Record<string, any>> {
  const deadline = Date.now() + seconds * 1000;
  for (;;) {
    await w.executor.runOnce();
    await w.queue.runOnce();
    const { rows: [row] } = await h.sql.query('SELECT "state", "job_id" FROM "wiki_plan_job" WHERE "id" = $1', [planJobId]);
    const { rows: [job] } = row?.job_id ? await h.sql.query('SELECT "state" FROM "wiki_job" WHERE "id" = $1', [row.job_id]) : { rows: [undefined] };
    if (row?.state === 'ended' && job && !['queued', 'running', 'waiting'].includes(job.state)) break;
    assert.ok(Date.now() < deadline, `the plan job ${planJobId} to end within ${seconds}s (it is ${row?.state}, its job ${job?.state})`);
    await delay(20);
  }
  await w.executor.whenIdle();
  const { rows: [row] } = await h.sql.query('SELECT * FROM "wiki_plan_job" WHERE "id" = $1', [planJobId]);
  return row;
}

/** The wiki_job a plan job was made with. */
async function wikiJobOf(h: Harness, planJobId: string): Promise<Record<string, any>> {
  const { rows: [row] } = await h.sql.query('SELECT j.* FROM "wiki_job" j JOIN "wiki_plan_job" p ON p."job_id" = j."id" WHERE p."id" = $1', [planJobId]);
  return row;
}

async function requests(h: Harness, jobId: string): Promise<Array<Record<string, any>>> {
  return (await h.sql.query('SELECT * FROM "wiki_model_request" WHERE "job_id" = $1 ORDER BY "enqueued_at", "id"', [jobId])).rows;
}

async function versions(h: Harness, spaceId: string): Promise<Array<Record<string, any>>> {
  return (await h.sql.query('SELECT * FROM "wiki_plan" WHERE "space_id" = $1 ORDER BY "version"', [spaceId])).rows;
}

