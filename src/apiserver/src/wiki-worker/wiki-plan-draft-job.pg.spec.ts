/**
 * A plan drafted and revised on the server (contracts/wiki.contract.json `plan.jobs.server`, design §8, P6),
 * against a real PostgreSQL, the real doors and plan service, a System model played by a local Node http server,
 * and the space's runner played by this file: it claims the job's repository operations and answers them with
 * the snapshot index and the file texts of `wiki-plan.fixture.json` — a real checkout, indexed by the runner's own
 * code.
 *
 * The cases are `src/runner-go/wiki_plan_job_test.go`'s, as the server runs them — the command's own half (its
 * flags, its work directory, its clean Claude Code) stays the runner's and is tested there:
 *
 *   1. a draft in four steps — the catalogue, each category's details, each document's outline, the rules beside
 *      them — every call a queue request at the plan's max_tokens, each outline given its own document's
 *      materials; gated here and on the server, stored as the job's version; its rounds on the plan job, which is
 *      what the plan page reads; no task, no session;
 *   2. a catalogue outside the target is written again before any document of it, with the gate's own count error;
 *   3. a count still outside after two tries is the gate's, and three rounds end the plan job failed with the
 *      last errors and the last draft;
 *   4. every file, docs section and symbol is checked on the snapshot — a symbol the index does not name by the
 *      text a read at the sha brings — and only the document with errors is written again, told every one;
 *   5. what the server's gate finds goes back to the model the same way, and three rounds of it fail the job;
 *   6. a revision keeps the protected document as it is, moves only a convention into the agents' category,
 *      holds the count, and names the projects it hands the model by title;
 *   7. a job taken over after its worker died, or replayed after its draft was stored, asks nothing twice and
 *      stores one version — and a snapshot that moved under it makes it start over;
 *   8. a job runs only as its own: one whose plan job ended asks nothing, and a revision without the owner's
 *      words ends failed;
 *   9. where the switch puts a plan job: a wiki_job at the owner's priority under server and for a listed canary
 *      account, a task under runner and for an account canary does not list — and a job that never started is
 *      cancelled when the switch moves back;
 *  10. the runner door hands no session a plan job when the server drafts (WIKI_SERVER_EXECUTES), so an `orbit
 *      wiki plan draft` that predates this asks no model — while a build job's session, the runner's until the
 *      documents move (P7), keeps its job routes; under runner it answers exactly as it always has.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki-worker/wiki-plan-draft-job.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every row belongs to an account the run created.
 */
