interface Hit {
  prompt: string;
  system: string;
  body: Record<string, unknown>;
  authorization: string;
}

/** The scripted model of wiki_plan_job_test.go (`planModel`): each prompt answered by what it asks. */
interface PlanModel {
  skeleton?: (n: number) => string;
  outline?: (title: string) => string | undefined;
  redo?: (title: string, prompt: string) => string;
  revise?: (round: number, prompt: string) => string;
  rewrite?: (title: string) => string;
  /** Called with each prompt before it is answered: what a case does at a moment of the run. */
  onPrompt?: (prompt: string) => Promise<void> | void;
}

interface FakeModel {
  base: string;
  hits: Hit[];
  script: PlanModel;
  skeletons: number;
  rounds: number;
  /** Answer with this status instead, while it is set. */
  status: number;
  close: () => Promise<void>;
}

const TITLE_IN = /《([^》]+)》/u;

function answerOf(model: FakeModel, prompt: string): string {
  const s = model.script;
  const title = TITLE_IN.exec(prompt.slice(prompt.lastIndexOf('# 任务')))?.[1] ?? '';
  if (prompt.includes('第一步：文档目录的骨架') || prompt.includes('# 任务：改正 wiki「')) {
    model.skeletons += 1;
    return s.skeleton ? s.skeleton(model.skeletons) : SKELETON;
  }
  if (prompt.includes('第二步：给大类「产品」')) return CLEAN.details['1'];
  if (prompt.includes('第二步：给大类「开发约定」')) return CLEAN.details['2'];
  if (prompt.includes('第三步 —— 给《')) return s.outline?.(title) ?? ({ 服务概览: OUTLINE_OVERVIEW, 存储: OUTLINE_STORAGE, 测试约定: CLEAN.outlines.testing } as Record<string, string>)[title] ?? '';
  if (prompt.includes('第四步 —— 三条规则的草案')) return RULES;
  if (prompt.includes('按 owner 的要求修订 plan 的目录')) {
    model.rounds += 1;
    return s.revise!(model.rounds, prompt);
  }
  if (prompt.includes('# 任务：写新草稿里《')) return s.rewrite!(title);
  if (prompt.includes('# 任务：改正 plan 里《')) return s.redo!(title, prompt);
  return '（不认得的提示）';
}

async function fakeModel(): Promise<FakeModel> {
  const sockets = new Set<Socket>();
  const model = { base: '', hits: [] as Hit[], script: {}, skeletons: 0, rounds: 0, status: 200 } as FakeModel;
  const server = createServer((request: IncomingMessage, response: ServerResponse) => {
    let raw = '';
    request.on('data', (chunk: Buffer) => {
      raw += chunk.toString();
    });
    request.on('end', () => {
      void (async () => {
        if (request.url === '/health') {
          response.writeHead(200, { 'content-type': 'application/json' });
          response.end('{}');
          return;
        }
        const body = JSON.parse(raw) as { system?: string; messages?: Array<{ content?: string }> };
        const prompt = body.messages?.[0]?.content ?? '';
        model.hits.push({ prompt, system: body.system ?? '', body: body as Record<string, unknown>, authorization: String(request.headers.authorization ?? '') });
        if (model.status !== 200) {
          response.writeHead(model.status, { 'content-type': 'application/json' });
          response.end(JSON.stringify({ type: 'error', error: { type: 'api_error', message: 'away' } }));
          return;
        }
        await model.script.onPrompt?.(prompt);
        const text = answerOf(model, prompt);
        response.writeHead(200, { 'content-type': 'text/event-stream' });
        const event = (name: string, data: unknown) => `event: ${name}\ndata: ${JSON.stringify(data)}\n\n`;
        response.write(event('message_start', { type: 'message_start', message: { model: MODEL, usage: { input_tokens: 100, output_tokens: 1 } } }));
        response.write(event('content_block_delta', { type: 'content_block_delta', index: 0, delta: { type: 'text_delta', text } }));
        response.write(event('message_delta', { type: 'message_delta', delta: { stop_reason: 'end_turn' }, usage: { output_tokens: 20 } }));
        response.write(event('message_stop', { type: 'message_stop' }));
        response.end();
      })();
    });
  });
  server.on('connection', (socket: Socket) => {
    sockets.add(socket);
    socket.on('close', () => sockets.delete(socket));
  });
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  model.base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  model.close = async () => {
    for (const socket of sockets) socket.destroy();
    await new Promise<void>((resolve) => server.close(() => resolve()));
  };
  return model;
}

