// ── 7. a replay ──────────────────────────────────────────────────────────────────────────────────────

test('a job replayed — taken over, or after its draft was stored — asks nothing twice and stores one version; a moved snapshot starts it over', { skip, timeout: 180_000 }, async () => {
  const h = await boot();
  await reset(h);
  const o = await owner(h);
  await clearJobs(h, o.spaceId);
  await baseVersion(h, o, { min: 3, max: 3 });
  // The worker dies once the outlines are under way: its lease runs out, and the next one takes the job over.
  let first: Worker | null = worker(h);
  let killed = false;
  h.model.script.onPrompt = async (prompt) => {
    if (!killed && prompt.includes('第三步 —— 给《')) {
      killed = true;
      const dying = first!;
      first = null;
      void dying.executor.onModuleDestroy().then(() => dying.queue.onModuleDestroy());
    }
  };
  const planJobId = await redraft(h, o);
  playRunner(h, o);
  const deadline = Date.now() + 30_000;
  while (!killed) {
    assert.ok(Date.now() < deadline, 'the first worker reached the outlines');
    if (first) {
      await first.executor.runOnce();
      await first.queue.runOnce();
    }
    await delay(20);
  }
  const second = worker(h);
  const end = await drive(h, second, planJobId, 90);
  assert.equal(end.outcome, 'succeeded', end.error);
  const job = await wikiJobOf(h, planJobId);
  const rows = await requests(h, job.id);
  const units = rows.map((row) => `${row.step}/${row.unit}`);
  assert.equal(new Set(units).size, units.length, 'no unit was asked twice');
  assert.equal(rows.length, 7);
  assert.ok(rows.every((row) => row.state === 'succeeded'));
  // Once a unit — and again only a call the dead worker had in flight, which the takeover re-issues.
  assert.ok(h.model.hits.length >= rows.length && h.model.hits.length <= rows.length + WIKI_MODEL_QUEUE.maxInFlightPerJob,
    `the model was asked ${h.model.hits.length} times for ${rows.length} units`);
  const hitsAfter = h.model.hits.length;
  assert.equal((await versions(h, o.spaceId)).length, 2);

  // Its draft was stored and its end was not said — the worker died between the two: replayed, it is answered
  // with the version its draft became, and asks the model nothing.
  await h.sql.query(`UPDATE "wiki_plan_job" SET "state" = 'made', "outcome" = NULL, "version" = NULL, "ended_at" = NULL, "report" = NULL WHERE "id" = $1`, [planJobId]);
  await h.sql.query(`UPDATE "wiki_job" SET "state" = 'queued', "ended_at" = NULL, "report" = NULL WHERE "id" = $1`, [job.id]);
  const replayed = await drive(h, second, planJobId, 60);
  assert.equal(replayed.outcome, 'succeeded');
  assert.equal(replayed.version, 2, 'the version the first submission stored');
  assert.equal((await versions(h, o.spaceId)).length, 2, 'one version');
  assert.equal(h.model.hits.length, hitsAfter, 'nothing was asked again');

  // A frame a run left at a sha the space's snapshot is no longer at (another job of the space took a newer one):
  // the replay starts over at the snapshot as it is, its materials read again.
  const next = await redraft(h, o);
  const moved = { sha: 'e'.repeat(40), date: '2026-10-01', materials: { title: 'App' }, texts: {} };
  await h.sql.query('UPDATE "wiki_plan_job" SET "materials" = $2 WHERE "id" = $1', [next, JSON.stringify(moved)]);
  const over = await drive(h, second, next, 60);
  assert.equal(over.outcome, 'succeeded', over.error);
  assert.equal(over.materials.sha, SHA, 'the frame is the snapshot\'s as it is');
  assert.equal(over.materials.materials.projects.length, 3, 'and the materials were read again');
  assert.equal(over.version, 3);
});

// ── 8. only its own job ──────────────────────────────────────────────────────────────────────────────

test('a job runs only as its own: one whose plan job ended asks nothing, and one its plan job was not made with asks nothing either', { skip, timeout: 120_000 }, async () => {
  const h = await boot();
  await reset(h);
  const o = await owner(h);
  const [created] = await planJobs(h, o.spaceId);
  const job = await wikiJobOf(h, created.id);
  await h.sql.query(`UPDATE "wiki_plan_job" SET "state" = 'ended', "outcome" = 'failed', "ended_at" = now(), "error" = 'ended by its owner' WHERE "id" = $1`, [created.id]);
  const w = worker(h);
  const ended = async (id: string): Promise<Record<string, any>> => {
    const deadline = Date.now() + 20_000;
    for (;;) {
      await w.executor.runOnce();
      const { rows: [row] } = await h.sql.query('SELECT "state", "error" FROM "wiki_job" WHERE "id" = $1', [id]);
      if (row.state === 'failed' || row.state === 'succeeded') return row;
      assert.ok(Date.now() < deadline, `the job ${id} ends`);
      await delay(20);
    }
  };
  const first = await ended(job.id);
  assert.equal(first.state, 'failed');
  assert.ok(String(first.error).includes('ended by its owner'), first.error);
  // A job whose input names a plan job another job was made with — say, one written by hand — is not its own.
  const stray = randomUUID();
  await h.sql.query(`INSERT INTO "wiki_job"("id","owner_id","space_id","kind","input","priority","state") VALUES ($1,$2,$3,'plan_draft',$4,1,'queued')`, [
    stray, o.id, o.spaceId, JSON.stringify({ planJobId: created.id }),
  ]);
  const second = await ended(stray);
  assert.equal(second.state, 'failed');
  assert.ok(String(second.error).includes('not this job\'s'), second.error);
  assert.equal(h.model.hits.length, 0, 'neither asked the model anything');
  const { rows: [{ n }] } = await h.sql.query('SELECT count(*)::int AS "n" FROM "wiki_repo_op" WHERE "space_id" = $1', [o.spaceId]);
  assert.equal(n, 0, 'nor the repository');
});

