  async function http(method: 'GET' | 'POST', route: string, bearer: string, body?: unknown): Promise<Answer> {
    const response = await fetch(`${base}/api${route}`, {
      method,
      headers: {
        authorization: `Bearer ${bearer}`,
        ...(body === undefined ? {} : { 'content-type': 'application/json' }),
      },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    });
    const text = await response.text();
    let json: Record<string, unknown> = {};
    try { json = JSON.parse(text) as Record<string, unknown>; } catch { /* asserted on by the caller */ }
    return { status: response.status, text, json };
  }
  const asRunner = (method: 'GET' | 'POST', route: string, body?: unknown) => http(method, route, RUNNER_TOKEN, body);
  /** The owner's read of a route, which has to answer 200. */
  async function owner(route: string, bearer = `bearer-${ownerId}`): Promise<unknown> {
    const answer = await http('GET', route, bearer);
    assert.equal(answer.status, 200, `${route} answered ${answer.status}: ${answer.text}`);
    return JSON.parse(answer.text);
  }

  /** What the runner's claim does to a queued session, then the inbox poll that hands the next turn out. */
  async function claimAndPoll(sessionId: string): Promise<Answer> {
    await prisma.$transaction(async (tx) => {
      await tx.$executeRaw`SELECT set_config('orbit.claim_reads_session_engine', '1', true)`;
      await tx.session.update({ where: { id: sessionId }, data: { status: RunStatus.RUNNING } });
    });
    const delivered = await asRunner('GET', `/runner/sessions/${uuidToBase62(sessionId)}/inbox?leaseGeneration=${await sessionLease(prisma, sessionId)}`);
    assert.equal(delivered.status, 200, `inbox answered ${delivered.status}: ${delivered.text}`);
    return delivered;
  }

  /** The inbox after an interrupt-and-send: the interrupt goes out first, then the message. */
  async function claimToMessage(sessionId: string): Promise<Answer> {
    let delivered = await claimAndPoll(sessionId);
    for (let i = 0; i < 2 && delivered.json.kind !== 'message'; i++) {
      delivered = await asRunner('GET', `/runner/sessions/${uuidToBase62(sessionId)}/inbox?leaseGeneration=${await sessionLease(prisma, sessionId)}`);
      assert.equal(delivered.status, 200, `inbox answered ${delivered.status}: ${delivered.text}`);
    }
    assert.equal(delivered.json.kind, 'message', `the inbox never handed out the message: ${delivered.text}`);
    return delivered;
  }

  /** Each session's next event seq: the runner numbers a session's events, once each. */
  const seqs = new Map<string, number>();
  const nextSeq = (sessionId: string) => {
    const seq = (seqs.get(sessionId) ?? 0) + 1;
    seqs.set(sessionId, seq);
    return seq;
  };

  /** The runner's echo of the turn it was handed, as the `user` event, and the payload ingest stored. */
  async function echo(sessionId: string, delivered: Answer): Promise<Record<string, unknown>> {
    const seq = nextSeq(sessionId);
    const posted = await asRunner('POST', `/runner/sessions/${uuidToBase62(sessionId)}/events`, {
      events: [{
        seq, type: 'user', ts: new Date().toISOString(), turnId: delivered.json.turnId,
        payload: { text: String(delivered.json.content ?? '') },
      }],
    });
    assert.equal(posted.status, 202, `events answered ${posted.status}: ${posted.text}`);
    return (await prisma.runEvent.findFirstOrThrow({ where: { sessionId, seq } })).payload as Record<string, unknown>;
  }

  /** The workspace answering that turn: its reply, the event that clears the pending message. */
  async function reply(sessionId: string, delivered: Answer, text = 'Thanks — on it.'): Promise<void> {
    const posted = await asRunner('POST', `/runner/sessions/${uuidToBase62(sessionId)}/events`, {
      events: [{
        seq: nextSeq(sessionId), type: 'assistant', ts: new Date().toISOString(), turnId: delivered.json.turnId,
        payload: { text },
      }],
    });
    assert.equal(posted.status, 202, `events answered ${posted.status}: ${posted.text}`);
  }

  /** The `session.updated` summary the control-plane stream would send the owner, public ids spelled as it spells them. */
  async function pushed(sessionId: string): Promise<Row> {
    const updated = firstValueFrom(realtime.streamForUser(ownerId).pipe(
      filter((event) => event.type === ControlEventType.SESSION_UPDATED && event.sessionId === sessionId),
      timeout(5_000),
    ));
    realtime.publishSessionUpdated(sessionId);
    // The public-id boundary the HTTP control-plane stream applies to every event it sends.
    return addTwins((await updated).data, true) as unknown as Row;
  }

  /**
   * Every surface's account of the row's pending message, which must all be `expected`: the list, the
   * same list as the project sessions page reads it and as a delta, the detail, and the summary.
   */
  async function assertEverywhere(sessionId: string, expected: Expected, label: string, projectId?: string) {
    const id = uuidToBase62(sessionId);
    const want = expected.from === null ? null : addTwins({ ...expected.from }, true);
    const listed = (await owner('/sessions') as Row[]).find((row) => row.id === id);
    assert.ok(listed, `${label}: GET /sessions omitted the session`);
    const delta = await owner('/sessions?since=') as { full: boolean; sessions: Row[] };
    assert.equal(delta.full, true, `${label}: a first delta read is the whole list`);
    const fromDelta = delta.sessions.find((row) => row.id === id);
    const surfaces: Array<[string, Row | undefined]> = [
      ['list', listed],
      ['delta', fromDelta],
      ['detail', await owner(`/sessions/${id}`) as Row],
      ['push', await pushed(sessionId)],
    ];
    if (projectId) {
      const page = await owner(`/sessions?projectId=${uuidToBase62(projectId)}`) as Row[];
      surfaces.push(['project', page.find((row) => row.id === id)]);
    }
    for (const [surface, row] of surfaces) {
      assert.ok(row, `${label}: ${surface} omitted the session`);
      assert.equal(row.lastUserText, expected.text, `${label}: ${surface} lastUserText`);
      assert.deepEqual(row.lastUserFrom, want, `${label}: ${surface} lastUserFrom`);
    }
    if (want) {
      // The public spelling, in the key the codec rewrites by name wherever it is nested.
      assert.equal(listed.lastUserFrom?.sessionId, uuidToBase62(expected.from!.sessionId), `${label}: not a public id`);
    }
    // And the columns behind them, which are written and cleared together.
    assert.deepEqual(await columnsOf(sessionId), {
      text: expected.text, fromId: expected.from?.sessionId ?? null, fromTitle: expected.from?.title ?? null,
    }, `${label}: the columns`);
  }

  // ── 1. session_send ───────────────────────────────────────────────────────────────────────────────

  await t.test('session_send names the sender from enqueue to the echo, as the echo’s card does, and the reply clears it', async () => {
    const worker = await session('Worker: criterion 3');
    const recipient = await session('the conversation the worker reports to');
    const words = 'criterion 3 is ready — the evidence is on the task';
    await sessionSend(worker, recipient, words);
    await assertEverywhere(recipient, { text: words, from: { sessionId: worker, title: 'Worker: criterion 3' } }, 'enqueued');

    // The title as it stood when the message was written: a rename since is not read back through.
    await prisma.session.update({ where: { id: worker }, data: { title: 'Worker: criterion 3, renamed' } });
    await assertEverywhere(recipient, { text: words, from: { sessionId: worker, title: 'Worker: criterion 3' } }, 'after a rename');

    // The echo writes the row again, from the card stored with it: the same session, by the same title.
    const delivered = await claimAndPoll(recipient);
    const stored = await echo(recipient, delivered);
    const card = stored.sessionMessage as { fromSessionId: string; fromTitle: string } | undefined;
    assert.ok(card, 'the echo was stored with no card');
    assert.deepEqual([card.fromSessionId, card.fromTitle], [worker, 'Worker: criterion 3, renamed']);
    await assertEverywhere(recipient, { text: words, from: { sessionId: card.fromSessionId, title: card.fromTitle } }, 'echoed');

    // The reply answers it: the sender goes with the text, in the same write.
    await reply(recipient, delivered);
    await assertEverywhere(recipient, { text: null, from: null }, 'answered');
  });

  await t.test('a message that revives its recipient names its sender too', async () => {
    const worker = await session('Worker: picks a thread back up');
    const parked = await ended('a conversation that has ended');
    const revived = await sessionSend(worker, parked, 'pick this back up', randomUUID(), { resumeIfEnded: true });
    assert.equal((revived as { revived?: boolean }).revived, true, `nothing was revived: ${JSON.stringify(revived)}`);
    await assertEverywhere(parked, {
      text: 'pick this back up', from: { sessionId: worker, title: 'Worker: picks a thread back up' },
    }, 'revived');
  });

  // ── 2. project_send ───────────────────────────────────────────────────────────────────────────────

  await t.test('project_send names the sending session on the coordinator’s row, live or revived, until it is answered', async () => {
    const worker = await session('Worker: landing check');
    const live = await project('live');
    await projectSend(worker, live.projectId, 'the landing needs a decision');
    const sender = { sessionId: worker, title: 'Worker: landing check' };
    await assertEverywhere(live.coordinatorSessionId, { text: 'the landing needs a decision', from: sender }, 'project live', live.projectId);

    const delivered = await claimAndPoll(live.coordinatorSessionId);
    await echo(live.coordinatorSessionId, delivered);
    await assertEverywhere(live.coordinatorSessionId, { text: 'the landing needs a decision', from: sender }, 'project echoed', live.projectId);
    await reply(live.coordinatorSessionId, delivered, 'I will look at the landing now.');
    await assertEverywhere(live.coordinatorSessionId, { text: null, from: null }, 'project answered', live.projectId);

    const parked = await project('ended', { status: RunStatus.SUCCEEDED, completedAt: new Date(Date.now() - 60_000) });
    const revived = await projectSend(worker, parked.projectId, 'the landing needs a decision');
    assert.equal(revived.sessionId, parked.coordinatorSessionId, 'the ended coordinator was replaced, not revived');
    assert.equal((await prisma.session.findUniqueOrThrow({ where: { id: parked.coordinatorSessionId } })).status, RunStatus.PENDING);
    await assertEverywhere(parked.coordinatorSessionId, { text: 'the landing needs a decision', from: sender }, 'project revived', parked.projectId);
  });

  // ── 3. session_interrupt, and the owner ───────────────────────────────────────────────────────────

  await t.test('session_interrupt’s message names its sender, and the owner’s interrupt-and-send replaces it with nobody', async () => {
    const worker = await session('Worker: has to redirect a run');
    const recipient = await session('a conversation that gets redirected');
    const sender = { sessionId: worker, title: 'Worker: has to redirect a run' };
    await sessionInterrupt(worker, recipient, 'stop — the spec changed, read it again');
    await assertEverywhere(recipient, { text: 'stop — the spec changed, read it again', from: sender }, 'interrupted by a session');
    const delivered = await claimToMessage(recipient);
    await echo(recipient, delivered);
    await assertEverywhere(recipient, { text: 'stop — the spec changed, read it again', from: sender }, 'its echo');

    // The owner stops that turn and says something else: the row is the owner's now.
    await sessions.interrupt(ownerId, recipient, { content: 'never mind that, I will handle it', clientTurnId: randomUUID() });
    await assertEverywhere(recipient, { text: 'never mind that, I will handle it', from: null }, 'interrupted by the owner');
  });

  await t.test('the owner’s message names nobody and replaces the sender; the row names whoever sent what it previews', async () => {
    const worker = await session('Worker: reports while the owner types');
    const sender = { sessionId: worker, title: 'Worker: reports while the owner types' };

    // Enqueued after the worker's: the owner's words are the row's, with nobody named.
    const recipient = await session('a conversation both of them write to');
    await sessionSend(worker, recipient, 'the build is green');
    await assertEverywhere(recipient, { text: 'the build is green', from: sender }, 'the worker’s');
    await ownerSend(recipient, 'and this one is mine');
    await assertEverywhere(recipient, { text: 'and this one is mine', from: null }, 'the owner’s, queued behind');
    // The runner takes the worker's message first, and the row previews it again — with its sender.
    const first = await claimAndPoll(recipient);
    assert.ok(String(first.json.content ?? '').startsWith('the build is green'), first.text);
    await echo(recipient, first);
    await assertEverywhere(recipient, { text: 'the build is green', from: sender }, 'the worker’s, echoed');
    await reply(recipient, first);
    await assertEverywhere(recipient, { text: null, from: null }, 'answered');

    // Enqueued before it: the echo of the owner's message clears the sender the worker's enqueue wrote.
    const other = await session('a conversation the owner wrote to first');
    await ownerSend(other, 'mine came first');
    await sessionSend(worker, other, 'then the report');
    await assertEverywhere(other, { text: 'then the report', from: sender }, 'the worker’s, queued behind');
    const mine = await claimAndPoll(other);
    assert.equal(mine.json.content, 'mine came first', mine.text);
    const stored = await echo(other, mine);
    assert.equal(stored.sessionMessage, undefined, 'the owner’s message was stored with a card');
    await assertEverywhere(other, { text: 'mine came first', from: null }, 'the owner’s, echoed');
  });

  // ── 4. other accounts ─────────────────────────────────────────────────────────────────────────────

  await t.test('another account never reads the row, and its session is never named as a sender', async () => {
    const worker = await session('Worker: writes to a shared conversation');
    const recipient = await session('a conversation of this account');
    await sessionSend(worker, recipient, 'a report for this account only');
    const id = uuidToBase62(recipient);

    // The other account's own reads: no row, no detail, no summary.
    const theirs = await owner('/sessions', `bearer-${strangerId}`) as Row[];
    assert.equal(theirs.some((row) => row.id === id), false, 'another account listed the row');
    assert.equal((await http('GET', `/sessions/${id}`, `bearer-${strangerId}`)).status, 404);
    const seenByStranger: ControlEvent[] = [];
    const subscription = realtime.streamForUser(strangerId).subscribe((event) => seenByStranger.push(event));
    try {
      await pushed(recipient);
    } finally {
      subscription.unsubscribe();
    }
    assert.equal(seenByStranger.some((event) => event.sessionId === recipient), false, 'another account was sent the summary');

    // A turn whose sender is another account's session — which no door writes: the service option is set
    // only from a proven credential — names nobody, at enqueue and at the echo alike.
    const foreign = await session('a conversation a foreign sender reaches');
    await sessions.createTurn(ownerId, foreign, { content: 'from somewhere else', clientTurnId: randomUUID() } as never, {
      senderSessionId: strangerSession,
    });
    await assertEverywhere(foreign, { text: 'from somewhere else', from: null }, 'a foreign sender, enqueued');
    const delivered = await claimAndPoll(foreign);
    const stored = await echo(foreign, delivered);
    assert.equal(stored.sessionMessage, undefined, 'the card named another account’s session');
    await assertEverywhere(foreign, { text: 'from somewhere else', from: null }, 'a foreign sender, echoed');
    for (const route of ['/sessions', `/sessions/${uuidToBase62(foreign)}`]) {
      assert.equal((await http('GET', route, `bearer-${ownerId}`)).text.includes(strangerTitle), false, `${route} carried the other account’s title`);
    }
    assert.equal(JSON.stringify(await pushed(foreign)).includes(strangerTitle), false, 'the summary carried the other account’s title');
  });
