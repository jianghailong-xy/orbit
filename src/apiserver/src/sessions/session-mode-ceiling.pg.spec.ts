  // ── a coordinator's rotation and first open ──────────────────────────────────────────────────
  async function projectWithCoordinator(shape: 'none' | 'trashed' | 'live'): Promise<{ projectId: string; coordinator: string | null }> {
    const projectId = randomUUID();
    await prisma.project.create({
      data: {
        id: projectId,
        ownerId,
        title: `a project whose coordinator is ${shape} ${projectId}`,
        coordinatorEnabled: true,
        ...(shape === 'none' ? {} : { coordinatorWorkspaceId: workspaceId }),
      },
    });
    await establishProjectContractForPgTest(prisma, ownerId, projectId, shape);
    if (shape === 'none') {
      await taskFor('work the coordinator would land beside', { projectId });
      return { projectId, coordinator: null };
    }
    const coordinator = await sessionIn('auto', 'claude', {
      status: RunStatus.AWAITING_INPUT,
      numTurns: 1,
      runtimeSessionId: `runtime-${randomUUID()}`,
      titleManagedByProject: true,
      ...(shape === 'trashed' ? { deletedAt: new Date() } : {}),
    });
    await prisma.project.update({ where: { id: projectId }, data: { coordinatorSessionId: coordinator } });
    return { projectId, coordinator };
  }

  const pointerOf = async (projectId: string) =>
    (await prisma.project.findUniqueOrThrow({ where: { id: projectId }, select: { coordinatorSessionId: true } })).coordinatorSessionId;
  const ensureRoute = (projectId: string) => `/runner/projects/${uuidToBase62(projectId)}/coordinator/ensure`;
  const messageRoute = (projectId: string) => `/runner/projects/${uuidToBase62(projectId)}/coordinator/messages`;

  for (const shape of ['none', 'trashed'] as const) {
    await t.test(`opening a coordinator from a narrower session is refused (${shape === 'none' ? 'first open' : 'rotation'})`, async () => {
      await accountDefault(null);
      const { projectId, coordinator } = await projectWithCoordinator(shape);
      const sessionsBefore = await prisma.session.count({ where: { ownerId } });
      for (const mode of ['plan', 'default', 'acceptEdits']) {
        const headers = await asSession(await sessionIn(mode));
        assertRefused(await send('POST', ensureRoute(projectId), undefined, headers), /coordinator opens in the account default/);
        assertRefused(await send('POST', messageRoute(projectId), { message: 'hello' }, headers), /coordinator opens in the account default/);
      }
      assert.equal(await pointerOf(projectId), coordinator, 'nothing moved');
      assert.equal(await prisma.session.count({ where: { ownerId } }), sessionsBefore + 3, 'only the three callers were added');
      // From a session the default does not exceed, the same request opens one.
      const opened = await send('POST', ensureRoute(projectId), undefined, await asSession(await sessionIn('auto')));
      assert.equal(opened.status, 201, opened.text);
      assert.equal(opened.json.created, true, opened.text);
    });
  }

  await t.test('a live coordinator is handed back to any session, and opens nothing', async () => {
    await accountDefault(null);
    const { projectId, coordinator } = await projectWithCoordinator('live');
    for (const mode of ['plan', 'default', 'auto']) {
      const ensured = await send('POST', ensureRoute(projectId), undefined, await asSession(await sessionIn(mode)));
      assert.equal(ensured.status, 201, ensured.text);
      assert.equal(ensured.json.sessionId, uuidToBase62(coordinator!), ensured.text);
      assert.equal(ensured.json.created, false, ensured.text);
    }
    // Who may then write to it is session-reach.pg.spec.ts: not this ceiling's question.
    const sent = await send('POST', messageRoute(projectId), { message: 'hello' }, await asSession(await sessionIn('auto')));
    assert.equal(sent.status, 201, sent.text);
    assert.equal(sent.json.sessionId, uuidToBase62(coordinator!), sent.text);
    assert.equal(await pointerOf(projectId), coordinator);
  });

