  async function ask(sessionId: string, input: unknown): Promise<Answer> {
    const answer = await send('POST', `/runner/sessions/${uuidToBase62(sessionId)}/approvals`, {
      toolName: 'orbit_task_create',
      input,
      toolUseId: `call-${randomUUID()}`,
    });
    assert.equal(answer.status, 201, answer.text);
    return answer;
  }

  await t.test('a coordinator narrower than the account default asks a person; its task then runs in that default', async () => {
    await accountDefault(null);
    const coordinator = await sessionIn('default');
    const projectId = await automaticProject(coordinator);
    const input = createInput('filed by a narrower coordinator', projectId);

    pushed.length = 0;
    const card = await ask(coordinator, input);
    assert.equal(card.json.status, 'PENDING', card.text);
    assert.deepEqual(pushed, [coordinator], 'the card is in front of a person');
    assert.equal(await prisma.task.count({ where: { projectId } }), 0, 'nothing is filed until they answer');

    await sessions.decideApproval(ownerId, coordinator, card.json.id as string, { behavior: 'allow' } as never);
    const polled = await send('GET', `/runner/sessions/${uuidToBase62(coordinator)}/approvals/${card.json.id}`);
    assert.equal(polled.json.status, 'ALLOWED', polled.text);

    const written = await send('POST', '/runner/tasks', input, {
      'x-orbit-session-id': uuidToBase62(coordinator),
      'x-orbit-workspace-id': uuidToBase62(workspaceId),
    });
    assert.equal(written.status, 201, written.text);
    const task = await prisma.task.findFirstOrThrow({ where: { projectId }, select: { id: true } });

    // The automatic door a sweep takes. It reads no session, so the run takes the account's default.
    const door = tasks as unknown as {
      dispatchReadyTask(owner: string, id: string, epoch: bigint): Promise<{ ok: boolean }>;
      dispatchEpochOf(id: string): Promise<bigint>;
    };
    const dispatched = await door.dispatchReadyTask(ownerId, task.id, await door.dispatchEpochOf(task.id));
    assert.equal(dispatched.ok, true);
    assert.deepEqual((await runsOf(task.id)).map((run) => run.permissionMode), [null], 'an unset default is Auto');
  });

