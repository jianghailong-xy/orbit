/**
 * The transcript read from the middle (sessions/transcript-around.ts), over real HTTP and against a
 * real PostgreSQL: what a link that names one record — a turn, an event or a tool call — opens on.
 *
 *   1. `GET /sessions/:id/events/page?around=<record>` returns the page that record sits in, the
 *      anchor it resolved to, and a cursor each way; paging out with `before=` and `after=` walks the
 *      whole transcript, contiguously, from either end of that page;
 *   2. each of the three kinds lands where the reader expects it: an event on itself, a turn on the
 *      message it sent, a tool call on its use;
 *   3. across tenants it is 404, every way round: another owner's session, another owner's record in
 *      one's own session, and a record of one's own other session.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/sessions/session-transcript-around.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the bearer check is stood in for.
 */
