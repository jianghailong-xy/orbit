/**
 * `session.listed_at` (migration 1490, session-listed-at.ts), the session list's order key, against a real PostgreSQL.
 *
 * It moves when the session changes for its owner, and only then:
 *   - created (the column default);
 *   - the owner sends it a message (POST /sessions/:id/turns, SessionsController.turn);
 *   - a turn ends on the owner: any turn — a person's, another session's message, a watch's or a background job's
 *     wake — answered and parked AWAITING_INPUT (/turn-complete), a permission card raised (/approvals), an owner
 *     request filed (ask_owner), a turn that FAILED;
 *   - completed (POST /sessions/:id/complete).
 * And it stays where it was on everything that only says the session is alive, while `last_turn_at` — the liveness
 * clock the reaper and the active-session window read, left as it was — keeps moving:
 *   - a session-to-session send, a watch's wake, a background job's wake (/background-wake);
 *   - the queue's claim (QueueService.claimSessionForRunner);
 *   - the runner's reconnect: lease takeover and activation, and the engine's init / resumed events;
 *   - streamed text, tool calls and their results (/events);
 *   - a turn's end with another turn queued behind it.
 * Then the list (GET /sessions, SessionsController.list) carries `listedAt` and is ordered by it, not by lastTurnAt,
 * and the `session.updated` summary carries it too.
 *
 * Production code throughout: SessionsService, SessionsController, QueueService, RunnerApiController,
 * OwnerRequestsService and the real RealtimeService for the summary.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/session-listed-at.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { type PrismaClient, RunStatus, RunnerStatus, SessionDispatchOrigin } from '@prisma/client';
import { ControlEventType, RunEventType, RunStatus as SharedRunStatus } from '@orbit/shared';
import { Client } from 'pg';
import { filter, firstValueFrom, timeout } from 'rxjs';

import { OwnerRequestsService } from '../owner-requests/owner-requests.service';
import { OwnerSecretsService } from '../owner-requests/owner-secrets.service';
import { prismaClientFor } from '../prisma/prisma-client';
import type { PrismaService } from '../prisma/prisma.service';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { ProviderPlanUsageService } from '../providers/plan-usage.service';
import { QueueService } from '../queue/queue.service';
import { RealtimeService } from '../realtime/realtime.service';
import type { BackgroundWakeDto } from '../runner-api/background-job-wake';
import { RunnerApiController } from '../runner-api/runner-api.controller';
import { SessionsController } from './sessions.controller';
import { SessionsService } from './sessions.service';
import { WATCH_TURN_KEY_PREFIX } from './watch-turn-key';

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

/** A collaborator whose every method answers nothing: the broadcasts and pushes the doors fire. */
const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

/** Both clocks, as epoch milliseconds read in SQL (a TIMESTAMP column read by node-postgres is host-local). */
interface Clocks { listed: number; live: number | null }

test('listed_at moves only when the session changes for its owner', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const db: PrismaClient = prismaClientFor(url);
  const prisma = db as unknown as PrismaService;
  const summaries = new RealtimeService(prisma, { scheduleBadgeSync: () => undefined } as never);
  t.after(async () => {
    summaries.onModuleDestroy();
    await db.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  // ── the doors ─────────────────────────────────────────────────────────────────────────────────
  const realtime = silent() as RealtimeService;
  const queue = new QueueService(prisma, realtime, new ProviderPlanUsageService(realtime));
  const sessions = new SessionsService(prisma, queue, realtime);
  const api = new RunnerApiController(
    prisma, queue, realtime,
    { notifyApprovalRequest: async () => undefined } as never,
    {} as never,
    { expand: async (_owner: string, content?: string) => content } as never,
    { appendFor: async (_tx: unknown, _id: string, content?: string) => content } as never,
    undefined, undefined, undefined, undefined,
    sessions,
  );
  const inbox = api as unknown as {
    dequeueTurn(
      sessionId: string, runnerId: string, leaseGeneration: string | null, acceptsSteer: boolean,
      declaredCapabilities: readonly string[],
    ): Promise<{ turnId: string; kind: string } | null>;
  };
  const owners = new SessionsController(sessions, prisma, realtime, {} as never, {} as never, {} as never);
  const requests = new OwnerRequestsService(prisma, new OwnerSecretsService(prisma), undefined, undefined, realtime);

  // ── the world: one account, one machine, one workspace ────────────────────────────────────────
  const ownerId = randomUUID();
  const runnerId = randomUUID();
  const workspaceId = randomUUID();
  await db.user.create({
    data: { id: ownerId, email: `listed-at-${ownerId}@listed-at.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  await db.runner.create({
    data: {
      id: runnerId, ownerId, name: 'listed-at-runner', tokenHash: `hash-${runnerId}`, status: RunnerStatus.ONLINE,
      maxConcurrent: 8, capabilities: [], capabilitiesReportedAt: new Date(), lastHeartbeatAt: new Date(),
    },
  });
  await db.workspace.create({ data: { id: workspaceId, ownerId, runnerId, name: 'listed-at-ws', enabled: true, workDir: '/tmp/listed-at' } });
  const runner = { id: runnerId, ownerId };
  const user = { userId: ownerId } as never;

  /**
   * A session a person opened that has run a turn and is parked, its engine up — the state almost every event below
   * arrives in. Both clocks are put an hour back, so a move is a move and not the instant of creation.
   */
  async function parked(title: string): Promise<string> {
    const id = randomUUID();
    await db.session.create({
      data: {
        id, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId, title, prompt: title,
        provider: 'claude', providerBuiltin: true, model: 'claude-opus-5', permissionMode: 'default',
        status: RunStatus.AWAITING_INPUT, numTurns: 1, startedAt: new Date(), runtimeSessionId: randomUUID(),
        usesRuntimeDefaultModel: true, engineStartedAt: new Date(Date.now() - 60_000),
        dispatchOrigin: SessionDispatchOrigin.USER,
      },
    });
    await db.conversationTurn.create({
      data: {
        sessionId: id, seq: 1, clientTurnId: `initial-${id}`, kind: 'message', content: title,
        status: 'ANSWERED', deliveredAt: new Date(), answeredAt: new Date(),
      },
    });
    await sql.query(
      `UPDATE "session" SET "listed_at" = now() - interval '1 hour', "last_turn_at" = now() - interval '1 hour'
        WHERE "id" = $1::uuid`,
      [id],
    );
    return id;
  }

  async function clocks(id: string): Promise<Clocks> {
    const { rows: [row] } = await sql.query<{ listed: number; live: number | null }>(
      `SELECT extract(epoch FROM "listed_at")::float8 * 1000 AS "listed",
              extract(epoch FROM "last_turn_at")::float8 * 1000 AS "live"
         FROM "session" WHERE "id" = $1::uuid`,
      [id],
    );
    return row;
  }
  const status = async (id: string) => (await db.session.findUniqueOrThrow({ where: { id }, select: { status: true } })).status;

  async function moved(id: string, before: Clocks, label: string): Promise<Clocks> {
    const after = await clocks(id);
    assert.ok(after.listed > before.listed, `${label}: listed_at did not move (${before.listed} → ${after.listed})`);
    return after;
  }
  /** listed_at exactly where it was; with `live`, last_turn_at moved — so the event really was written. */
  async function stayed(id: string, before: Clocks, label: string, live = false): Promise<Clocks> {
    const after = await clocks(id);
    assert.equal(after.listed, before.listed, `${label}: listed_at moved`);
    if (live) assert.ok((after.live ?? 0) > (before.live ?? 0), `${label}: last_turn_at did not move, so nothing happened`);
    return after;
  }

  // ── the runner's side of one turn ─────────────────────────────────────────────────────────────
  const seqs = new Map<string, number>();
  const nextSeq = (id: string) => {
    const seq = (seqs.get(id) ?? 1) + 1;
    seqs.set(id, seq);
    return seq;
  };

  /** The claim, the runner process's reconnect handshake (takeover + activation), and the inbox handing a turn out. */
  async function claimAndTake(id: string, expectedLeaseOwner: string | null = null) {
    const claimed = await queue.claimSessionForRunner({ id: runnerId, supportedProviders: ['claude'] } as never);
    assert.equal(claimed?.sessionId, id, 'the queue claimed another session');
    const afterClaim = await clocks(id);
    const [leaseOwner, generation] = [randomUUID(), randomUUID()];
    await api.takeoverLeases(runner, id, { leaseOwner, expectedLeaseOwner } as never);
    await api.activateLeases(runner, id, { leaseGeneration: generation, leaseOwner } as never);
    const handed = await inbox.dequeueTurn(id, runnerId, generation, false, []);
    assert.ok(handed, 'the inbox handed nothing out');
    return { leaseOwner, generation, turnId: handed.turnId, afterClaim };
  }

  function events(id: string, leaseOwner: string, turnId: string | null, list: Array<[RunEventType, Record<string, unknown>]>) {
    return api.events(runner, id, {
      leaseOwner,
      events: list.map(([type, payload]) => ({
        seq: nextSeq(id), type, ts: new Date().toISOString(), ...(turnId ? { turnId } : {}), payload,
      })),
    } as never);
  }

  async function complete(id: string, leaseOwner: string, turnId: string, outcome: 'SUCCEEDED' | 'FAILED' = 'SUCCEEDED') {
    await events(id, leaseOwner, turnId, [[RunEventType.ASSISTANT, { text: 'Done.' }]]);
    await api.turnComplete(runner, id, {
      turnId, leaseOwner, status: SharedRunStatus[outcome], subtype: outcome === 'SUCCEEDED' ? 'success' : 'error',
      numTurns: 1, costUsd: 0, ...(outcome === 'FAILED' ? { error: 'the engine exited 1' } : {}),
    } as never);
  }

  // ── the cases ─────────────────────────────────────────────────────────────────────────────────

  await t.test('created: a new row is listed at its creation, with no writer naming the column', async () => {
    const id = randomUUID();
    await db.session.create({
      data: { id, ownerId, creatorId: ownerId, workspaceId, title: 'new', prompt: 'new', provider: 'claude' },
    });
    const { rows: [row] } = await sql.query<{ gap: number | null }>(
      `SELECT abs(extract(epoch FROM "listed_at" - "created_at"))::float8 AS "gap" FROM "session" WHERE "id" = $1::uuid`,
      [id],
    );
    assert.notEqual(row.gap, null, 'listed_at is null on a new row');
    assert.ok(row.gap! < 1, `listed_at is ${row.gap}s away from created_at`);
  });

  await t.test('a person\'s message and its answer move it; the claim, the reconnect and the stream do not', async () => {
    const id = await parked('owner send');
    let at = await clocks(id);

    // The owner's own door.
    const sent = await owners.turn(user, id, { clientTurnId: randomUUID(), content: 'fix the login flow' } as never);
    at = await moved(id, at, 'owner send');
    const turn = await db.conversationTurn.findUniqueOrThrow({ where: { id: sent.turnId }, select: { byPerson: true } });
    assert.equal(turn.byPerson, true, 'the owner\'s turn is not marked as a person\'s');

    // The claim moves the liveness clock and nothing else.
    const { leaseOwner, turnId, afterClaim } = await claimAndTake(id);
    assert.equal(turnId, sent.turnId);
    assert.equal(afterClaim.listed, at.listed, 'the queue claim moved listed_at');
    assert.ok((afterClaim.live ?? 0) > (at.live ?? 0), 'the claim did not move last_turn_at');
    // The reconnect handshake (takeover + activation) left it too.
    at = await stayed(id, afterClaim, 'lease takeover and activation');

    // The engine coming up, and the turn streaming: init, text, a tool call and its result.
    await events(id, leaseOwner, null, [[RunEventType.SYSTEM, { subtype: 'init', sessionId: 'runtime-x' }]]);
    at = await stayed(id, at, 'the engine\'s init event');
    await events(id, leaseOwner, turnId, [[RunEventType.ASSISTANT, { text: 'Looking at the redirect.' }]]);
    at = await stayed(id, at, 'streamed text', true);
    await events(id, leaseOwner, turnId, [
      [RunEventType.TOOL_USE, { id: 'toolu_1', name: 'Bash', input: { command: 'npm test' } }],
      [RunEventType.TOOL_RESULT, { toolUseId: 'toolu_1', content: 'ok' }],
    ]);
    at = await stayed(id, at, 'a tool call and its result', true);

    // The person's turn answered, nothing queued behind it: it waits on them now.
    await complete(id, leaseOwner, turnId);
    assert.equal(await status(id), RunStatus.AWAITING_INPUT);
    await moved(id, at, 'a person\'s turn ending AWAITING_INPUT');
  });

  await t.test('another session\'s message and a watch\'s wake do not move it; the last of their turns to end does', async () => {
    const id = await parked('platform sends');
    const other = await parked('the sender');
    let at = await clocks(id);
    await sessions.createTurn(ownerId, id, { clientTurnId: randomUUID(), content: 'status?', intent: 'NEXT_TURN' }, {
      senderSessionId: other,
    });
    at = await stayed(id, at, 'a session-to-session send', true);
    await sessions.createTurn(ownerId, id, { clientTurnId: `${WATCH_TURN_KEY_PREFIX}${randomUUID()}:1`, content: '', intent: 'NEXT_TURN' });
    at = await stayed(id, at, 'a watch\'s wake', true);
    // Both turns run and end: the first with the wake queued behind it, so it stays; the wake's end parks the session
    // on its owner with a new reply, so it moves (owner 2026-11-26).
    const first = await claimAndTake(id);
    at = await stayed(id, { ...first.afterClaim, listed: at.listed }, 'the claim');
    await complete(id, first.leaseOwner, first.turnId);
    at = await stayed(id, at, 'the session-to-session turn ending', true);
    // The slot passes straight to the queued wake: the same process is handed it, with no claim between.
    const next = await inbox.dequeueTurn(id, runnerId, first.generation, false, []);
    assert.ok(next, 'the watch\'s turn was not handed out');
    await complete(id, first.leaseOwner, next.turnId);
    at = await moved(id, at, 'the watch\'s turn ending AWAITING_INPUT');
    assert.equal(await status(id), RunStatus.AWAITING_INPUT);
  });

  await t.test('a background job\'s wake, its claim and its stream leave it where it was; its end moves it', async () => {
    const id = await parked('ci wait');
    let at = await clocks(id);
    const jobId = 'bgj_0123456789ab';
    await api.backgroundWake(runner, id, {
      wakeId: `${jobId}:exit`, jobId, trigger: 'exit', kind: 'watch', command: 'gh run watch', description: 'CI',
      status: 'succeeded', exitCode: 0, outputPath: `/tmp/${jobId}.output`, outputOffset: 0, outputSize: 10,
      outputExcerpt: 'CI 4/7 passed',
    } as BackgroundWakeDto);
    at = await stayed(id, at, 'a background job\'s wake', true);
    const { leaseOwner, turnId, afterClaim } = await claimAndTake(id);
    at = await stayed(id, { ...afterClaim, listed: at.listed }, 'the wake\'s claim');
    await events(id, leaseOwner, turnId, [[RunEventType.ASSISTANT, { text: 'CI 4/7, still waiting.' }]]);
    at = await stayed(id, at, 'the wake turn\'s stream', true);
    await complete(id, leaseOwner, turnId);
    assert.equal(await status(id), RunStatus.AWAITING_INPUT);
    await moved(id, at, 'a wake turn ending AWAITING_INPUT');
  });

  await t.test('a permission card and an owner request move it: the turn is waiting on the owner', async () => {
    const id = await parked('asks');
    let at = await clocks(id);
    await api.createApproval(runner as never, id, { toolName: 'Bash', input: { command: 'sudo systemctl restart orbit' }, toolUseId: 'toolu_ask' });
    at = await moved(id, at, 'a permission card');
    await requests.file(ownerId, id, { kind: 'CONFIRM', title: 'Restart the runner?', why: 'It stopped answering.' } as never);
    await moved(id, at, 'an owner request');
  });

  await t.test('a turn that fails moves it, whoever started the turn', async () => {
    const id = await parked('fails');
    let at = await clocks(id);
    await api.backgroundWake(runner, id, {
      wakeId: 'bgj_fedcba987654:exit', jobId: 'bgj_fedcba987654', trigger: 'exit', kind: 'build', command: 'make',
      status: 'failed', exitCode: 2, outputPath: '/tmp/x.output', outputOffset: 0, outputSize: 1, outputExcerpt: 'x',
    } as BackgroundWakeDto);
    at = await stayed(id, at, 'the wake that the failing turn runs');
    const { leaseOwner, turnId } = await claimAndTake(id);
    at = await clocks(id);
    await complete(id, leaseOwner, turnId, 'FAILED');
    assert.equal(await status(id), RunStatus.FAILED);
    await moved(id, at, 'a FAILED turn');
  });

  await t.test('completing it moves it', async () => {
    const id = await parked('done');
    const at = await clocks(id);
    await owners.complete(user, id);
    await moved(id, at, 'completion');
  });

  await t.test('landing a merge moves it; a merge that fails does not', async () => {
    // The merge queue lives in the real RealtimeService, so these two doors are built over it.
    const merging = new SessionsService(prisma, queue, summaries);
    const mergeApi = new RunnerApiController(
      prisma, queue, summaries, silent(), {} as never,
      { expand: async (_owner: string, content?: string) => content } as never,
      { appendFor: async (_tx: unknown, _id: string, content?: string) => content } as never,
    );
    const branch = async (title: string) => {
      const id = await parked(title);
      await db.session.update({
        where: { id },
        data: { status: RunStatus.SUCCEEDED, finishedAt: new Date(), branch: `orbit/${randomUUID()}`, isolationStatus: 'worktree' },
      });
      await sql.query(`UPDATE "session" SET "listed_at" = now() - interval '1 hour' WHERE "id" = $1::uuid`, [id]);
      return id;
    };
    const mergeOnce = async (id: string, status: 'merged' | 'error') => {
      await merging.mergeToMain(ownerId, id, 'main');
      const lease = randomUUID();
      const [operation] = await summaries.drainMergeRequests(runnerId, lease);
      assert.ok(operation, 'the runner was handed no merge');
      await mergeApi.mergeResult(runner, id, {
        status, operationId: operation.operationId, leaseOwner: lease, sourceSha: 'a'.repeat(40), targetBranch: 'main',
        ...(status === 'merged' ? { targetShaBefore: 'f'.repeat(40), mergedSha: '4'.repeat(40) } : { message: 'conflict' }),
      } as never);
    };
    const failing = await branch('merge fails');
    let at = await clocks(failing);
    await mergeOnce(failing, 'error');
    await stayed(failing, at, 'a merge that failed');
    const landing = await branch('lands');
    at = await clocks(landing);
    await mergeOnce(landing, 'merged');
    assert.equal((await db.session.findUniqueOrThrow({ where: { id: landing }, select: { branchMerged: true } })).branchMerged, true);
    await moved(landing, at, 'a landed merge');
  });

  await t.test('the list carries listedAt and is ordered by it, not by lastTurnAt; so does session.updated', async () => {
    // Older listing but the freshest activity, against a newer listing whose activity is an hour old.
    const busy = await parked('busy on CI');
    const fresh = await parked('just asked you');
    await sql.query(
      `UPDATE "session" SET "listed_at" = now() - interval '2 hours', "last_turn_at" = now() WHERE "id" = $1::uuid`, [busy],
    );
    await sql.query(`UPDATE "session" SET "listed_at" = now() - interval '5 minutes' WHERE "id" = $1::uuid`, [fresh]);
    const list = await owners.list(user, undefined, workspaceId) as unknown as Array<{ id: string; listedAt: Date; lastTurnAt: Date }>;
    const ids = list.map((row) => row.id);
    assert.ok(ids.indexOf(fresh) >= 0 && ids.indexOf(busy) >= 0, 'the list omitted the sessions');
    assert.ok(ids.indexOf(fresh) < ids.indexOf(busy), 'the list is not ordered by listedAt');
    for (const row of list) assert.ok(row.listedAt instanceof Date, `row ${row.id} carries no listedAt`);
    const sorted = [...list].sort((a, b) => b.listedAt.getTime() - a.listedAt.getTime() || 0);
    assert.deepEqual(ids, sorted.map((row) => row.id), 'the list is not in listedAt order');
    const busyRow = list.find((row) => row.id === busy)!;
    assert.equal(busyRow.listedAt.getTime(), (await clocks(busy)).listed);

    const updated = firstValueFrom(summaries.streamForUser(ownerId).pipe(
      filter((event) => event.type === ControlEventType.SESSION_UPDATED && event.sessionId === busy),
      timeout(5_000),
    ));
    summaries.publishSessionUpdated(busy);
    const summary = (await updated).data as { listedAt?: string };
    assert.equal(summary.listedAt, busyRow.listedAt.toISOString(), 'session.updated carries no listedAt, or another one');
  });
});
