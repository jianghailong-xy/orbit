/**
 * SubAgent permissions and approvals (docs/subagent-design.md §5.3), on a real PostgreSQL, through the doors the
 * runner calls:
 *
 *   1. Modes. A SubAgent whose definition names a mode wider than its parent's is refused (403
 *      PERMISSION_MODE_WIDER_THAN_SESSION) and no run is written; one that names none runs in the parent's own
 *      mode; one that names a narrower mode runs in it; a read-only definition runs in plan.
 *   2. Approvals. A SubAgent's card is filed under the parent's session, names its run, and carries the child's
 *      call id prefixed with the run id. The parent's own calls returning — its own Bash and the `delegate` call
 *      itself — collect the parent's card and leave the SubAgent's; so does the parent's turn ending, and the
 *      listing still offers it on the parked session. A run id of another session is 404. The run ending collects
 *      the card, with the sentence naming the SubAgent.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/subagent-approvals.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { NotFoundException } from '@nestjs/common';
import { PrismaClient, RunStatus, RunnerStatus, SessionDispatchOrigin, type Runner } from '@prisma/client';
import { RunEventType, RunStatus as SharedRunStatus } from '@orbit/shared';
import { Client } from 'pg';

import { PERMISSION_MODE_WIDER_THAN_SESSION } from '../common/permission-mode';
import { prismaClientFor } from '../prisma/prisma-client';
import type { PrismaService } from '../prisma/prisma.service';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import type { QueueService } from '../queue/queue.service';
import type { RealtimeService } from '../realtime/realtime.service';
import { RunnerApiController } from '../runner-api/runner-api.controller';
import { RunnerSubagentsController } from '../runner-api/runner-subagents.controller';
import { SubagentRunCreateDto, SubagentRunUpdateDto } from '../runner-api/subagent-run';
import {
  APPROVAL_ABANDONED_CALL_MESSAGE,
  APPROVAL_ABANDONED_STATUS,
  APPROVAL_ABANDONED_SUBAGENT_MESSAGE,
} from './abandoned-approvals';
import { SessionsService } from './sessions.service';

const URL = process.env.COORDINATOR_PG_URL;
process.env.PROVIDER_SECRET_KEY ??= 'subagent-approvals-spec';
const skip = !URL;

const silent = (): never =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) }) as never;

const create = (fields: Partial<SubagentRunCreateDto> & { toolUseId: string }): SubagentRunCreateDto =>
  Object.assign(new SubagentRunCreateDto(), { type: 'general', definitionSource: 'builtin', ...fields });

test('SubAgent permissions and approvals', { skip, concurrency: 1, timeout: 300_000 }, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const db: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await db.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });
  const prisma = db as unknown as PrismaService;
  const queue = { notifySessionQueued: () => undefined } as unknown as QueueService;
  const realtime = silent() as RealtimeService;
  const sessions = new SessionsService(prisma, queue, realtime);
  const api = new RunnerApiController(
    prisma,
    queue,
    realtime,
    { notifyApprovalRequest: async () => undefined } as never,
    {} as never,
    {} as never,
    { appendFor: async (_tx: unknown, _sessionId: string, content?: string) => content } as never,
  );
  const subagents = new RunnerSubagentsController(prisma, queue, silent());

  const ownerId = randomUUID();
  const runnerId = randomUUID();
  await db.user.create({
    data: { id: ownerId, email: `subagent-approvals-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  const runner = (await db.runner.create({
    data: {
      id: runnerId, ownerId, name: 'the machine the parent runs on', tokenHash: `hash-${runnerId}`,
      status: RunnerStatus.ONLINE, capabilities: [], capabilitiesReportedAt: new Date(), lastHeartbeatAt: new Date(),
    },
  })) as Runner;

  /** A parent session of that runner in `permissionMode`, generating a turn that is IN_FLIGHT. */
  async function parent(permissionMode: string) {
    const workspaceId = randomUUID();
    await db.workspace.create({
      data: { id: workspaceId, ownerId, runnerId, name: `orbit-worker-${workspaceId.slice(-8)}`, enabled: true },
    });
    const sessionId = randomUUID();
    await db.session.create({
      data: {
        id: sessionId, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title: 'port the retry', prompt: 'port the retry', provider: 'claude', engine: 'claude',
        model: 'claude-opus-5-5', effort: 'high', permissionMode, status: RunStatus.RUNNING, engineTurnActive: true,
        dispatchOrigin: SessionDispatchOrigin.USER, startsTaskWork: false, startedAt: new Date(),
        runtimeSessionId: randomUUID(),
      },
    });
    const turn = await db.conversationTurn.create({
      data: {
        sessionId, seq: 1, clientTurnId: SessionsService.initialTurnClientId(sessionId), kind: 'message',
        content: 'port the retry', status: 'IN_FLIGHT', deliveredAt: new Date(),
      },
      select: { id: true },
    });
    return { sessionId, turnId: turn.id };
  }

  await t.test('(1) a wider mode is refused; no mode runs in the parent\'s; a narrower one and read-only narrow it', async () => {
    const { sessionId } = await parent('default');
    for (const wider of ['bypassPermissions', 'auto']) {
      await assert.rejects(
        subagents.createSubagentRun(runner, sessionId, create({ toolUseId: `toolu_wide_${wider}`, permissionMode: wider })),
        (err: { getStatus(): number; getResponse(): { code?: string; message?: string } }) => {
          assert.equal(err.getStatus(), 403);
          assert.equal(err.getResponse().code, PERMISSION_MODE_WIDER_THAN_SESSION);
          assert.match(err.getResponse().message ?? '', new RegExp(`runs in "default".*"${wider}"`));
          assert.match(err.getResponse().message ?? '', /Remove permissionMode from the SubAgent's definition/);
          return true;
        },
        `a SubAgent asking for ${wider} under a default parent is refused`,
      );
    }
    assert.equal(await db.subagentRun.count({ where: { sessionId } }), 0, 'and no run was written for either');

    const inherited = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_inherit' }));
    assert.equal(inherited.exec.permissionMode, 'default', "a SubAgent that names no mode runs in its parent's");

    const narrower = await subagents.createSubagentRun(runner, sessionId, create({ toolUseId: 'toolu_narrow', permissionMode: 'plan' }));
    assert.equal(narrower.exec.permissionMode, 'plan', 'a narrower mode it names is the one it runs in');

    const readonly = await subagents.createSubagentRun(runner, sessionId, create({
      toolUseId: 'toolu_readonly', type: 'explore', readonly: true,
    }));
    assert.equal(readonly.exec.permissionMode, 'plan', 'a read-only definition runs in plan');

    const edits = await parent('acceptEdits');
    const fromEdits = await subagents.createSubagentRun(runner, edits.sessionId, create({ toolUseId: 'toolu_inherit' }));
    assert.equal(fromEdits.exec.permissionMode, 'acceptEdits', "and under an Accept Edits parent, in Accept Edits");
  });

  await t.test('(2) a SubAgent\'s card survives its parent\'s calls and turn, and goes with its run', async () => {
    const f = await parent('default');
    const other = await parent('default');
    let seq = 0;
    const send = (type: string, payload: Record<string, unknown>, turnId?: string) =>
      api.events({ id: runnerId }, f.sessionId, {
        events: [{ seq: ++seq, type: type as never, ts: new Date().toISOString(), payload, ...(turnId ? { turnId } : {}) }],
      });
    const approval = (id: string) => db.approval.findUniqueOrThrow({ where: { id } });

    // The parent calls delegate, and the runner opens the run.
    const delegateId = `toolu_${randomUUID().slice(0, 8)}`;
    await send(RunEventType.TOOL_USE, { id: delegateId, name: 'mcp__orbit__delegate', input: { description: 'Port the retry to the Go runner', prompt: 'Port it.' } });
    const { runId } = await subagents.createSubagentRun(runner, f.sessionId, create({ toolUseId: delegateId }));
    const otherRun = await subagents.createSubagentRun(runner, other.sessionId, create({ toolUseId: 'toolu_elsewhere' }));

    // The child's call, as the runner rewrites it into the parent's stream, and its card.
    const childCall = `${runId}:toolu_child_bash`;
    await send(RunEventType.TOOL_USE, { id: childCall, name: 'Bash', input: { command: 'go test ./quota/...' }, parentToolUseId: delegateId, subagentRunId: runId });
    const fromSubagent = await api.createApproval({ id: runnerId, ownerId } as never, f.sessionId, {
      toolName: 'Bash', input: { command: 'go test ./quota/...' }, toolUseId: childCall, subagentRunId: runId,
    });
    // The parent's own card, beside it: the control.
    const parentCall = `toolu_${randomUUID().slice(0, 8)}`;
    await send(RunEventType.TOOL_USE, { id: parentCall, name: 'Bash', input: { command: 'git status' } });
    const fromParent = await api.createApproval({ id: runnerId, ownerId } as never, f.sessionId, {
      toolName: 'Bash', input: { command: 'git status' }, toolUseId: parentCall,
    });

    const filed = await approval(fromSubagent.id);
    assert.equal(filed.sessionId, f.sessionId, "the SubAgent's card is filed under its parent's session");
    assert.equal(filed.subagentRunId, runId, 'naming its run');
    assert.equal(filed.toolUseId, childCall, "with the child's call id, prefixed with the run id");
    const listed = await sessions.listApprovals(ownerId, f.sessionId, 'PENDING');
    assert.deepEqual(listed.map((a) => [a.id, a.subagentRunId ?? null]).sort(),
      [[fromParent.id, null], [fromSubagent.id, runId]].sort(), 'both are offered, the SubAgent card saying whose it is');

    await assert.rejects(
      api.createApproval({ id: runnerId, ownerId } as never, f.sessionId, {
        toolName: 'Bash', input: {}, toolUseId: `${otherRun.runId}:toolu_x`, subagentRunId: otherRun.runId,
      }),
      NotFoundException,
      "a run of another session names nothing here",
    );
    // Another account's run, on its own machine: the same answer.
    const strangerId = randomUUID();
    const strangerRunner = randomUUID();
    await db.user.create({ data: { id: strangerId, email: `stranger-${strangerId}@runner-door.invalid`, name: 'Another account', passwordHash: 'x' } });
    await db.runner.create({ data: { id: strangerRunner, ownerId: strangerId, name: 'theirs', tokenHash: `hash-${strangerRunner}` } });
    const strangerWs = randomUUID();
    await db.workspace.create({ data: { id: strangerWs, ownerId: strangerId, runnerId: strangerRunner, name: `theirs-${strangerWs.slice(-8)}`, enabled: true } });
    const strangerSession = randomUUID();
    await db.session.create({ data: {
      id: strangerSession, ownerId: strangerId, creatorId: strangerId, workspaceId: strangerWs, assignedRunnerId: strangerRunner,
      title: 'theirs', prompt: 'theirs', provider: 'claude', status: RunStatus.RUNNING, dispatchOrigin: SessionDispatchOrigin.USER,
    } });
    const theirRun = await db.subagentRun.create({ data: {
      ownerId: strangerId, sessionId: strangerSession, toolUseId: 'toolu_theirs', type: 'general', definitionSource: 'builtin', decision: {},
    } });
    await assert.rejects(
      api.createApproval({ id: runnerId, ownerId } as never, f.sessionId, {
        toolName: 'Bash', input: {}, toolUseId: `${theirRun.id}:toolu_x`, subagentRunId: theirRun.id,
      }),
      NotFoundException,
      "another account's run names nothing here either",
    );
    assert.equal(await db.approval.count({ where: { subagentRunId: theirRun.id } }), 0, 'and no card names it');

    // The parent's own calls return: its Bash, and the delegate call itself (a foreground wait that ran out).
    await send(RunEventType.TOOL_RESULT, { toolUseId: parentCall, content: 'approval poll failed', isError: true });
    await send(RunEventType.TOOL_RESULT, { toolUseId: delegateId, content: '{"runId":"r","status":"running"}' });
    assert.equal((await approval(fromParent.id)).status, APPROVAL_ABANDONED_STATUS, "the parent's own card goes with its call");
    assert.equal((await approval(fromParent.id)).message, APPROVAL_ABANDONED_CALL_MESSAGE);
    const survived = await approval(fromSubagent.id);
    assert.equal(survived.status, 'PENDING', "the SubAgent's card is not collected when the parent's calls return");
    assert.equal(survived.message, null);

    // The parent's turn ends; the SubAgent runs on in the background.
    await send(RunEventType.ASSISTANT, { text: 'The SubAgent is porting it.' }, f.turnId);
    const done = await api.turnComplete({ id: runnerId } as never, f.sessionId, { turnId: f.turnId, status: SharedRunStatus.SUCCEEDED });
    assert.equal(done.status, RunStatus.AWAITING_INPUT, 'the turn completed the ordinary way');
    assert.equal((await approval(fromSubagent.id)).status, 'PENDING', "nor when the parent's turn ends");
    assert.deepEqual((await sessions.listApprovals(ownerId, f.sessionId, 'PENDING')).map((a) => a.id), [fromSubagent.id],
      'and the parked session still offers it: its reader is the SubAgent, still running');

    // The run ends: its child engine, the card's only reader, has gone.
    await subagents.updateSubagentRun(runner, f.sessionId, runId, Object.assign(new SubagentRunUpdateDto(), { status: 'STOPPED' }));
    const ended = await approval(fromSubagent.id);
    assert.equal(ended.status, APPROVAL_ABANDONED_STATUS, 'the card goes with its run');
    assert.equal(ended.message, APPROVAL_ABANDONED_SUBAGENT_MESSAGE, 'saying it was the SubAgent that ended');
    assert.equal(ended.decidedAt, null, 'nobody decided it');
    assert.deepEqual(await sessions.listApprovals(ownerId, f.sessionId, 'PENDING'), [], 'and nothing is offered any more');
  });
});
