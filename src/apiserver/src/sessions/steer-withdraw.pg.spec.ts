/**
 * Taking back a message sent into a running turn, against a real PostgreSQL (sessions/steer-withdraw.ts).
 *
 * DELETE /sessions/:id/turns/:turnId on a steer the runner holds files a `withdraw` turn, the inbox
 * hands it over mid-turn to a poller that declared the arm for it, and the runner's completion is the
 * one thing that removes the steer — on the row shapes and constraints migrations give the table, and
 * with the request that filed it waiting on the outcome the whole time. The runner's side is played
 * by hand here: what it polls, and what it answers for the engine.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/steer-withdraw.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { ConflictException, ServiceUnavailableException } from '@nestjs/common';
import { type PrismaClient, type Runner, RunnerStatus, RunStatus, SessionDispatchOrigin, SessionRunSource } from '@prisma/client';
import {
  RunStatus as SharedRunStatus,
  SESSION_CLAUDE_STEER_WITHDRAW_V1,
  SESSION_CURRENT_WORK_ROUTING_V1,
  STEER_WITHDRAW_ERRORS,
  TURN_COMPLETE_STEER_WITHDRAW,
} from '@orbit/shared';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { prismaClientFor } from '../prisma/prisma-client';
import { PrismaService } from '../prisma/prisma.service';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { RunnerApiController } from '../runner-api/runner-api.controller';
import { SessionsService } from './sessions.service';

declare global {
  interface BigInt { toJSON(): string; }
}
// `main.ts` installs this before it creates the app; a session row carries BIGINT columns.
BigInt.prototype.toJSON = function toJSON(this: bigint): string {
  return this.toString();
};

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;
const ROUTING = [SESSION_CURRENT_WORK_ROUTING_V1];
const WITHDRAW = [SESSION_CURRENT_WORK_ROUTING_V1, SESSION_CLAUDE_STEER_WITHDRAW_V1];

/** A collaborator whose every method answers nothing: the broadcasts a turn's enqueue fires. */
const silent = (): unknown =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

const codeOf = (err: unknown) => ((err as ConflictException).getResponse() as { code?: string }).code;

test('a steer is taken back through the runner, and only the engine\'s word removes it', {
  skip, concurrency: 1, timeout: 600_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });
  const db = prisma as unknown as PrismaService;

  const ownerId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `steer-withdraw-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });

  /** A machine that declared `capabilities`, its workspace, and a Claude session on it, parked. */
  async function world(capabilities: string[]) {
    const runnerId = randomUUID();
    const workspaceId = randomUUID();
    const sessionId = randomUUID();
    await prisma.runner.create({
      data: {
        id: runnerId, ownerId, name: `machine ${runnerId}`, tokenHash: sha256(`token-${runnerId}`),
        status: RunnerStatus.ONLINE, lastHeartbeatAt: new Date(), capabilities, capabilitiesReportedAt: new Date(),
      },
    });
    await prisma.workspace.create({ data: { id: workspaceId, ownerId, runnerId, name: 'orbit-worker', enabled: true } });
    await prisma.session.create({
      data: {
        id: sessionId, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title: 'fix the export', prompt: 'fix the export', provider: 'claude', status: RunStatus.AWAITING_INPUT,
        numTurns: 1, startedAt: new Date(), runtimeSessionId: `runtime-${sessionId}`,
        dispatchOrigin: SessionDispatchOrigin.USER, runSource: SessionRunSource.MANUAL,
      },
    });
    return { runnerId, sessionId, runner: { id: runnerId, ownerId } as Runner, capabilities };
  }

  const realtime = silent();
  const queue = { notifySessionQueued: () => undefined };
  const sessions = new SessionsService(db, queue as never, realtime as never);
  const api = new RunnerApiController(
    db,
    queue as never,
    realtime as never,
    {} as never,
    {} as never,
    { expand: async (_owner: string, content?: string) => content } as never,
    { appendFor: async (_tx: unknown, _id: string, content?: string) => content } as never,
  );
  type Dequeue = (
    sessionId: string, runnerId: string, leaseGeneration: string | null, acceptsSteer: boolean,
    declaredCapabilities: readonly string[],
  ) => Promise<Record<string, unknown> | null>;
  const dequeue = (w: Awaited<ReturnType<typeof world>>) =>
    (api as unknown as { dequeueTurn: Dequeue }).dequeueTurn.call(api, w.sessionId, w.runnerId, null, true, w.capabilities);

  /** The person's message, claimed and handed to the engine: the turn everything below is sent into. */
  async function running(w: Awaited<ReturnType<typeof world>>): Promise<string> {
    const sent = await sessions.createTurn(ownerId, w.sessionId, {
      clientTurnId: randomUUID(), content: 'run the full test suite', intent: 'NEXT_TURN',
    } as never) as { turnId: string };
    await prisma.$transaction(async (tx) => {
      await tx.$executeRaw`SELECT set_config('orbit.claim_reads_session_engine', '1', true)`;
      await tx.session.update({ where: { id: w.sessionId }, data: { status: RunStatus.RUNNING } });
    });
    const handed = await dequeue(w);
    assert.equal(handed?.turnId, sent.turnId, 'the running message was not the one handed out');
    return sent.turnId;
  }

  /** A message typed while that turn runs: filed as a steer aimed at it. */
  async function steer(w: Awaited<ReturnType<typeof world>>, words = 'then push it to main'): Promise<string> {
    const sent = await sessions.createTurn(ownerId, w.sessionId, {
      clientTurnId: randomUUID(), content: words, intent: 'CURRENT_WORK',
    } as never) as { turnId: string; kind: string };
    assert.equal(sent.kind, 'steer', `a message sent mid-turn was filed as a ${sent.kind}`);
    return sent.turnId;
  }

  /** The runner's side: poll until the withdraw comes out, then answer it as the engine did. */
  async function answerWithdrawal(w: Awaited<ReturnType<typeof world>>, steerId: string, result: string) {
    for (let i = 0; i < 100; i++) {
      const handed = await dequeue(w);
      if (handed?.kind === 'withdraw') {
        assert.deepEqual(JSON.parse(String(handed.content)), { turnId: steerId });
        await api.turnComplete({ id: w.runnerId } as never, w.sessionId, {
          turnId: String(handed.turnId), status: SharedRunStatus.SUCCEEDED, subtype: TURN_COMPLETE_STEER_WITHDRAW,
          result, ...(result === 'withdrawn' ? {} : { error: 'the engine had already read it into the turn' }),
        } as never);
        return String(handed.turnId);
      }
      await new Promise((resolve) => setTimeout(resolve, 20));
    }
    assert.fail('no withdraw turn was handed to the runner');
  }

  await t.test('a steer the engine drops is gone, and the turn it was aimed at runs on', async () => {
    const w = await world(WITHDRAW);
    const target = await running(w);
    const steerId = await steer(w);
    const leased = await dequeue(w);
    assert.equal(leased?.turnId, steerId, 'the steer was not handed to the runner');

    const asked = sessions.cancelQueuedTurn(ownerId, w.sessionId, steerId);
    const withdrawId = await answerWithdrawal(w, steerId, 'withdrawn');

    assert.deepEqual(await asked, { ok: true, withdrawn: true });
    assert.equal(await prisma.conversationTurn.findUnique({ where: { id: steerId } }), null, 'the steer is still there');
    const withdraw = await prisma.conversationTurn.findUniqueOrThrow({ where: { id: withdrawId } });
    assert.deepEqual(JSON.parse(String(withdraw.content)), { turnId: steerId, outcome: 'withdrawn' });
    // Nothing about the session or the running turn moved.
    const turn = await prisma.conversationTurn.findUniqueOrThrow({ where: { id: target } });
    assert.equal(turn.status, 'IN_FLIGHT');
    assert.equal((await prisma.session.findUniqueOrThrow({ where: { id: w.sessionId } })).status, RunStatus.RUNNING);
  });

  await t.test('a steer the engine had already read stays where it was, and the person is told so', async () => {
    const w = await world(WITHDRAW);
    await running(w);
    const steerId = await steer(w, 'and count them');
    await dequeue(w);

    const asked = sessions.cancelQueuedTurn(ownerId, w.sessionId, steerId);
    await answerWithdrawal(w, steerId, 'already_read');

    const err = await asked.then(() => assert.fail('withdrawn anyway'), (e: unknown) => e);
    assert.ok(err instanceof ConflictException);
    assert.equal(codeOf(err), STEER_WITHDRAW_ERRORS.ALREADY_READ);
    const row = await prisma.conversationTurn.findUniqueOrThrow({ where: { id: steerId } });
    assert.equal(row.status, 'IN_FLIGHT');
  });

  await t.test('a steer nothing has taken yet goes the way a queued message does', async () => {
    const w = await world(WITHDRAW);
    await running(w);
    const steerId = await steer(w, 'and the docs too');

    assert.deepEqual(await sessions.cancelQueuedTurn(ownerId, w.sessionId, steerId), { ok: true });
    assert.equal(await prisma.conversationTurn.findUnique({ where: { id: steerId } }), null);
    assert.equal(
      await prisma.conversationTurn.count({ where: { sessionId: w.sessionId, kind: 'withdraw' } }),
      0,
      'nothing needed asking: the runner never had it',
    );
  });

  await t.test('a runner without the arm for it is never asked, and the refusal says why', async () => {
    const w = await world(ROUTING);
    await running(w);
    const steerId = await steer(w);
    await dequeue(w);

    const err = await sessions.cancelQueuedTurn(ownerId, w.sessionId, steerId).then(
      () => assert.fail('withdrawn without a runner that can do it'),
      (e: unknown) => e,
    );
    assert.equal(codeOf(err), STEER_WITHDRAW_ERRORS.NOT_WITHDRAWABLE);
    assert.equal(await prisma.conversationTurn.count({ where: { sessionId: w.sessionId, kind: 'withdraw' } }), 0);
  });

  await t.test('no answer in time leaves the steer, and takes the unanswered request back', async () => {
    const w = await world(WITHDRAW);
    await running(w);
    const steerId = await steer(w);
    await dequeue(w);
    (sessions as unknown as { steerWithdrawWaitMs: number }).steerWithdrawWaitMs = 300;
    t.after(() => {
      (sessions as unknown as { steerWithdrawWaitMs: number }).steerWithdrawWaitMs = 15_000;
    });

    const err = await sessions.cancelQueuedTurn(ownerId, w.sessionId, steerId).then(
      () => assert.fail('withdrawn with nobody answering'),
      (e: unknown) => e,
    );
    assert.ok(err instanceof ServiceUnavailableException);
    assert.equal(codeOf(err), STEER_WITHDRAW_ERRORS.NO_ANSWER);
    assert.equal(await prisma.conversationTurn.count({ where: { sessionId: w.sessionId, kind: 'withdraw' } }), 0);
    assert.equal((await prisma.conversationTurn.findUniqueOrThrow({ where: { id: steerId } })).status, 'IN_FLIGHT');
    // And a poller that comes for it later finds nothing to act on.
    const later = await dequeue(w);
    assert.notEqual(later?.kind, 'withdraw');
  });
});
