/**
 * Interrupting a session takes the payload of every `bg-wake:` turn it deletes with it.
 *
 * The other half of `background-wake-withdraw.pg.spec.ts`. A control-plane wake turn carries nobody's
 * words: what it delivers lives in `background_job_wake` and `session_scheduled_wakeup`, keyed by the
 * turn's `client_turn_id` and written into the content only at the claim. `SessionsService.interrupt`
 * deletes every follow-up queued behind the turn it stops — stopping means stop — and a wake turn is
 * one of them, so it reaches the same payload a withdrawal does, in bulk instead of by name, and it
 * settled only the Watch half of it (`deadLetterQueuedWatchWakes`). Against real PostgreSQL, the real
 * runner door and the real scheduled-wakeup worker:
 *
 *   1. A due wakeup filed onto an interrupted turn does not stay DELIVERED against a turn that no
 *      longer exists. It is CANCELLED — called off before it woke anybody, the state a
 *      `schedule_wakeup({stop: true})` writes, and the one a withdrawal writes — and the worker that
 *      only ever scans PENDING agrees: a later drain files nothing and opens no turn. DROPPED would
 *      be the other thing it could say, and it would be untrue: an interrupted session has not ended.
 *   2. An interrupted turn's job wakes do not come back. `background_job_wake` is unique on
 *      `(session_id, client_turn_id, job_id)` and a job's wake turn is keyed by the job itself, so a
 *      row left behind would be found, updated and delivered by that job's NEXT wake. The turn the
 *      next wake opens carries that wake alone.
 *   3. The negative control: interrupting a session whose queue holds an ordinary message behaves
 *      exactly as it did — and reaches nothing carried by a turn it does not delete, neither the wake
 *      turn the runner had already taken in that same session nor another session's queued one.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/sessions/background-wake-interrupt.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
