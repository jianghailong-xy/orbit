/**
 * POST /sessions/:id/background/jobs/:jobId/stop — the owner's stop of one running bg_run job — over real HTTP and
 * against a real PostgreSQL, with what GET /sessions/:id/background and the runner's heartbeat say about it.
 *
 * Fixtures, as persisted run_event rows in the shapes runner-go background_job.go writes them:
 *   - session A on a runner that declares bg-owner-stop/v1: job RUNNING (in running_bg_jobs) and job DONE (completed);
 *   - session B of the same owner on a runner that predates it: job OLD, running;
 *   - session C of another owner, on the new runner, with a running job.
 *
 * Asserted:
 *   - the list marks RUNNING stoppable, and DONE and OLD not;
 *   - the stop answers 202 `stopping`, keeps the job on the session once (a repeat is idempotent), wakes the runner,
 *     and the runner's heartbeat read (backgroundJobStopsFor) lists it — to the new runner only;
 *   - the job's terminal report (killed, stopped_by_owner) takes it off that list; the list then shows it killed with
 *     the reason and not stoppable, and a further stop answers 200 `killed`;
 *   - DONE answers 409 BACKGROUND_JOB_ENDED, an unknown id 404 BACKGROUND_JOB_NOT_FOUND, OLD 409
 *     RUNNER_CANNOT_STOP_JOB, and another owner's session 404 — none of which writes anything.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/sessions/session-background-job-stop.pg.spec.ts
 *
 * Not destructive: every id is generated by the run. Only the bearer check is stood in for.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { Module, ValidationPipe } from '@nestjs/common';
import { NestFactory, Reflector } from '@nestjs/core';
import { JwtService } from '@nestjs/jwt';
import { BG_JOB_STOPPED_BY_OWNER, BG_OWNER_STOP_V1, RunEventType, uuidToBase62 } from '@orbit/shared';
import { Client } from 'pg';

import { JwtAuthGuard } from '../auth/jwt-auth.guard';
import { PublicIdInterceptor } from '../common/public-id.interceptor';
import { prismaClientFor } from '../prisma/prisma-client';
import { PrismaService } from '../prisma/prisma.service';
import { assertCoordinatorPgUrlIsIsolated, verifyCoordinatorPgIdentity } from '../projects/coordinator-pg-test-safety';
import { RealtimeService } from '../realtime/realtime.service';
import { backgroundJobStopsFor } from '../runner-api/background-job-stops';
import { SessionTagsService } from '../session-tags/session-tags.service';
import { AutoRetryService } from './auto-retry.service';
import { MergeReceiptService } from './merge-receipt.service';
import { SessionsController } from './sessions.controller';
import { SessionsService } from './sessions.service';

const URL = process.env.COORDINATOR_PG_URL;

const LIFECYCLE = new Set(['then', 'onModuleInit', 'onApplicationBootstrap', 'onModuleDestroy',
  'beforeApplicationShutdown', 'onApplicationShutdown']);

/** A collaborator this route never reaches: any call on it is the route going somewhere it should not. */
const unreachable = (name: string): unknown =>
  new Proxy({}, {
    get: (_target, key) => {
      if (typeof key === 'symbol' || LIFECYCLE.has(key)) return undefined;
      return () => {
        throw new Error(`${name}.${key} is not part of the background job stop`);
      };
    },
  });

const RUNNING = 'bgj_5a0000000001';
const DONE = 'bgj_5a0000000002';
const OLD = 'bgj_5a0000000003';
const THEIRS = 'bgj_5a0000000004';
const UNKNOWN = 'bgj_5a00000000ff';

test('the owner stops one running bg_run job; ended, unknown, old-runner and foreign jobs are refused', {
  skip: !URL, concurrency: 1, timeout: 120_000,
}, async (t) => {
  assertCoordinatorPgUrlIsIsolated(URL);
  const sql = new Client({ connectionString: URL, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma = prismaClientFor(URL!);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  const otherId = randomUUID();
  const bearers = new Map([[`bearer-${ownerId}`, ownerId], [`bearer-${otherId}`, otherId]]);
  const woken: string[] = [];
  const realtime = new Proxy({ notifyRunnerWake: (runnerId: string) => { woken.push(runnerId); } }, {
    get: (target, key) => {
      if (key === 'notifyRunnerWake') return target.notifyRunnerWake;
      return (unreachable('realtime') as Record<string | symbol, unknown>)[key];
    },
  });
  const sessions = new SessionsService(
    prisma as unknown as PrismaService,
    unreachable('queue') as never,
    realtime as never,
  );

  @Module({
    controllers: [SessionsController],
    providers: [
      { provide: SessionsService, useValue: sessions },
      { provide: PrismaService, useValue: prisma },
      { provide: RealtimeService, useValue: realtime },
      { provide: SessionTagsService, useValue: unreachable('tags') },
      { provide: MergeReceiptService, useValue: unreachable('mergeReceipts') },
      { provide: AutoRetryService, useValue: unreachable('autoRetry') },
      JwtAuthGuard,
      Reflector,
      {
        provide: JwtService,
        useValue: {
          verifyAsync: async (token: string) => {
            const sub = bearers.get(token);
            if (!sub) throw new Error('not a bearer this run issued');
            return { sub, email: `${sub}@background-job-stop.invalid` };
          },
        },
      },
    ],
  })
  class BackgroundJobStopModule {}

  const app = await NestFactory.create(BackgroundJobStopModule, { logger: false, abortOnError: false });
  app.setGlobalPrefix('api');
  app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
  app.useGlobalInterceptors(new PublicIdInterceptor());
  await app.listen(0, '127.0.0.1');
  t.after(() => app.close());
  const base = await app.getUrl();

  // ── fixtures ──────────────────────────────────────────────────────────────────────────────────
  for (const id of [ownerId, otherId]) {
    await sql.query(`INSERT INTO "user"("id","email","name","password_hash") VALUES ($1,$2,'owner','x')`, [
      id, `background-job-stop-${id}@background-job-stop.invalid`,
    ]);
  }
  const newRunner = randomUUID();
  const oldRunner = randomUUID();
  const theirRunner = randomUUID();
  for (const [id, owner, capabilities] of [
    [newRunner, ownerId, [BG_OWNER_STOP_V1]], [oldRunner, ownerId, []], [theirRunner, otherId, [BG_OWNER_STOP_V1]],
  ] as const) {
    await prisma.runner.create({ data: {
      id, ownerId: owner, name: `runner-${id.slice(0, 8)}`, tokenHash: randomUUID(), status: 'ONLINE',
      lastHeartbeatAt: new Date(), capabilities: [...capabilities], capabilitiesReportedAt: new Date(),
    } });
  }
  async function session(owner: string, runnerId: string, running: string[]): Promise<string> {
    const id = randomUUID();
    await sql.query(
      `INSERT INTO "session"("id","title","prompt","owner_id","creator_id","turn_state","dispatch_origin","assigned_runner_id",
                             "running_bg_shells","running_bg_jobs","created_at","updated_at")
       VALUES ($1,'background job stop','p',$2,$2,NULL,'USER',$3,$4,$4,now(),now())`,
      [id, owner, runnerId, running],
    );
    return id;
  }
  const mine = await session(ownerId, newRunner, [RUNNING]);
  const onOld = await session(ownerId, oldRunner, [OLD]);
  const theirs = await session(otherId, theirRunner, [THEIRS]);

  let seq = 0;
  async function event(sessionId: string, type: string, payload: unknown): Promise<void> {
    seq += 1;
    await sql.query(
      `INSERT INTO "run_event"("id","session_id","seq","type","payload","created_at") VALUES ($1,$2,$3,$4,$5,now())`,
      [randomUUID(), sessionId, seq, type, JSON.stringify(payload)],
    );
  }
  const output = (id: string) => `/root/.orbit/runs/spec/${id}.output`;
  /** runner-go background_job.go: the launch pair and the `running` record. */
  async function launch(sessionId: string, id: string, command: string): Promise<void> {
    await event(sessionId, RunEventType.TOOL_USE, { id, name: 'Bash', input: { command, run_in_background: true } });
    await event(sessionId, RunEventType.TOOL_RESULT, {
      toolUseId: id, content: `Command running in background with ID: ${id}. Output is being written to: ${output(id)}. `,
    });
    await event(sessionId, RunEventType.BACKGROUND_TASK, {
      shellId: id, toolUseId: id, status: 'running', kind: 'job', command, outputPath: output(id), idleMs: 0,
    });
  }
  /** runner-go background_job.go endPayload. */
  async function end(sessionId: string, id: string, status: 'completed' | 'killed', reason?: string): Promise<void> {
    const payload: Record<string, unknown> = {
      shellId: id, toolUseId: id, status, kind: 'job', command: 'sleep 600', output: '', outputPath: output(id),
      summary: status === 'killed' ? 'Background job was killed' : 'Background job completed (exit code 0)',
    };
    if (status === 'completed') payload.exitCode = 0;
    if (reason) payload.reason = reason;
    await event(sessionId, RunEventType.BACKGROUND_TASK, payload);
  }
  await launch(mine, RUNNING, 'sleep 600');
  await launch(mine, DONE, 'npm test');
  await end(mine, DONE, 'completed');
  await launch(onOld, OLD, 'sleep 600');
  await launch(theirs, THEIRS, 'sleep 600');

  // ── the two doors ───────────────────────────────────────────────────────────────────────────────
  async function list(sessionId: string, as = ownerId): Promise<Map<string, Record<string, unknown>>> {
    const response = await fetch(`${base}/api/sessions/${uuidToBase62(sessionId)}/background`, {
      headers: { authorization: `Bearer bearer-${as}` },
    });
    const text = await response.text();
    assert.equal(response.status, 200, text.slice(0, 400));
    return new Map((JSON.parse(text) as Record<string, unknown>[]).map((row) => [row.shellId as string, row]));
  }
  async function stop(sessionId: string, jobId: string, as = ownerId): Promise<{ status: number; body: Record<string, unknown> }> {
    const response = await fetch(`${base}/api/sessions/${uuidToBase62(sessionId)}/background/jobs/${jobId}/stop`, {
      method: 'POST', headers: { authorization: `Bearer bearer-${as}` },
    });
    return { status: response.status, body: JSON.parse(await response.text()) as Record<string, unknown> };
  }
  const requests = async (sessionId: string): Promise<string[]> =>
    (await sql.query(`SELECT "bg_job_stop_requests" AS r FROM "session" WHERE "id" = $1`, [sessionId])).rows[0].r;

  // ── before: who may be stopped ──────────────────────────────────────────────────────────────────
  const before = await list(mine);
  assert.equal(before.get(RUNNING)?.stoppable, true, 'a running job on a runner that stops jobs is stoppable');
  assert.equal(before.get(DONE)?.stoppable, false, 'an ended job is not stoppable');
  assert.equal((await list(onOld)).get(OLD)?.stoppable, false, 'a job on a runner that predates the stop is not stoppable');

  // ── the refusals, each writing nothing ────────────────────────────────────────────────────────
  const ended = await stop(mine, DONE);
  assert.equal(ended.status, 409, JSON.stringify(ended.body));
  assert.equal(ended.body.code, 'BACKGROUND_JOB_ENDED');
  const unknown = await stop(mine, UNKNOWN);
  assert.equal(unknown.status, 404, JSON.stringify(unknown.body));
  assert.equal(unknown.body.code, 'BACKGROUND_JOB_NOT_FOUND');
  const old = await stop(onOld, OLD);
  assert.equal(old.status, 409, JSON.stringify(old.body));
  assert.equal(old.body.code, 'RUNNER_CANNOT_STOP_JOB');
  const foreign = await stop(theirs, THEIRS);
  assert.equal(foreign.status, 404, `another owner's session is refused: ${JSON.stringify(foreign.body)}`);
  const foreignOfMine = await stop(mine, RUNNING, otherId);
  assert.equal(foreignOfMine.status, 404, `my session is refused to another owner: ${JSON.stringify(foreignOfMine.body)}`);
  assert.deepEqual([await requests(mine), await requests(onOld), await requests(theirs)], [[], [], []],
    'no refusal writes a stop');
  assert.deepEqual(woken, [], 'no refusal wakes a runner');

  // ── the stop, and its repeat ────────────────────────────────────────────────────────────────────
  const first = await stop(mine, RUNNING);
  assert.equal(first.status, 202, JSON.stringify(first.body));
  assert.deepEqual(first.body, { jobId: RUNNING, status: 'stopping' });
  const again = await stop(mine, RUNNING);
  assert.equal(again.status, 202, JSON.stringify(again.body));
  assert.deepEqual(again.body, { jobId: RUNNING, status: 'stopping' });
  assert.deepEqual(await requests(mine), [RUNNING], 'the stop is kept once');
  assert.deepEqual(woken, [newRunner, newRunner], 'each stop wakes the runner hosting the session');

  // The runner's heartbeat: listed to the runner hosting it, and to no other.
  assert.deepEqual(await backgroundJobStopsFor(prisma, newRunner), [{ sessionId: mine, jobId: RUNNING }]);
  assert.deepEqual(await backgroundJobStopsFor(prisma, oldRunner), []);
  assert.deepEqual(await backgroundJobStopsFor(prisma, theirRunner), []);

  // ── the runner's report of the kill ─────────────────────────────────────────────────────────────
  await end(mine, RUNNING, 'killed', BG_JOB_STOPPED_BY_OWNER);
  await sql.query(`UPDATE "session" SET "running_bg_jobs" = '{}', "running_bg_shells" = '{}' WHERE "id" = $1`, [mine]);
  assert.deepEqual(await backgroundJobStopsFor(prisma, newRunner), [], 'an ended job is no longer listed to the runner');
  const after = (await list(mine)).get(RUNNING);
  assert.deepEqual([after?.status, after?.reason, after?.stoppable], ['killed', BG_JOB_STOPPED_BY_OWNER, false],
    'the list says the job was killed because its owner stopped it');
  assert.equal((await list(mine)).get(DONE)?.reason, undefined, 'a job that completed carries no kill reason');
  const settled = await stop(mine, RUNNING);
  assert.equal(settled.status, 200, JSON.stringify(settled.body));
  assert.deepEqual(settled.body, { jobId: RUNNING, status: 'killed' }, 'a stop of a job already stopped changes nothing');
  assert.equal(woken.length, 2, 'a stop of a job already stopped wakes no runner');
});
