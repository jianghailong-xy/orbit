/** A collaborator whose every method answers nothing: the broadcasts a turn's enqueue fires. */
const silent = (): unknown =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

/** A value as a client reads it: over the wire, so compared as the JSON it is sent as. */
const wire = <T>(value: T): T => (value === undefined ? value : JSON.parse(JSON.stringify(value)) as T);

/** Every wake here is allowed: what is under test is the row, not who may be woken. */
const allow = async () => ({ allowed: true as const });

const clip = (text: string | null): string | null =>
  text === null || text.length <= PREVIEW_LEN ? text : [...text].slice(0, PREVIEW_LEN).join('');

