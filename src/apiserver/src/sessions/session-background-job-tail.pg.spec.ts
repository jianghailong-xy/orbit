/**
 * GET /sessions/:id/background/jobs/:jobId/tail — the newest lines of one bg_run job's output — over real HTTP and
 * against a real PostgreSQL, with the runner link's NATS in memory and a stand-in for the gateway and the runner on
 * the runner's subject (rnr.<runnerId>) answering as src/link-gateway/bgtail.go and src/runner-go/background_owner_tail.go do.
 *
 * Fixtures, as persisted run_event rows in the shapes runner-go background_job.go writes them:
 *   - session A on a runner that declares bg-output-tail/v1 and is online: job RUNNING and job DONE (completed), and
 *     jobs whose answers stand for the gateway's NO_CONNECTION, UNSUPPORTED and TIMEOUT;
 *   - session B on a runner that predates the read, session C on one that is offline, session D on one no gateway
 *     holds (nobody answers its subject);
 *   - session E of another owner, on the new runner.
 *
 * Asserted:
 *   - the read is asked of the runner hosting the session, over its subject, naming the session, the job, the lines
 *     asked for (capped at 40) and the 8 KB cap; its answer comes back as lines, at most 40 and 8 KB, without colour
 *     codes, with the job's status and exit code;
 *   - an ended job the runner no longer holds answers 404 BACKGROUND_JOB_OUTPUT_GONE;
 *   - an unknown id 404 BACKGROUND_JOB_NOT_FOUND, another owner's session 404, an old runner 409
 *     RUNNER_CANNOT_READ_JOB_OUTPUT, an offline one 503 RUNNER_OFFLINE — none of them asking the runner anything;
 *   - the gateway's NO_CONNECTION 503 RUNNER_OFFLINE, UNSUPPORTED 409, TIMEOUT and nobody answering 504
 *     RUNNER_DID_NOT_ANSWER, the link down 503 RUNNER_LINK_UNAVAILABLE, and `lines` that is not a whole N ≥ 1 a 400.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/sessions/session-background-job-tail.pg.spec.ts
 *
 * Not destructive: every id is generated by the run. Only the bearer check is stood in for.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { Module, ValidationPipe } from '@nestjs/common';
import { NestFactory, Reflector } from '@nestjs/core';
import { JwtService } from '@nestjs/jwt';
import { BG_JOB_TAIL_MAX_BYTES, BG_OUTPUT_TAIL_V1, RunEventType, uuidToBase62 } from '@orbit/shared';
import { Client } from 'pg';

import { JwtAuthGuard } from '../auth/jwt-auth.guard';
import { PublicIdInterceptor } from '../common/public-id.interceptor';
import { prismaClientFor } from '../prisma/prisma-client';
import { PrismaService } from '../prisma/prisma.service';
import { assertCoordinatorPgUrlIsIsolated, verifyCoordinatorPgIdentity } from '../projects/coordinator-pg-test-safety';
import { RealtimeService } from '../realtime/realtime.service';
import { RunnerHints, runnerHintSubject } from '../realtime/runner-hints';
import { SessionTagsService } from '../session-tags/session-tags.service';
import { MemoryNats } from '../test-support/memory-nats';
import { AutoRetryService } from './auto-retry.service';
import { MergeReceiptService } from './merge-receipt.service';
import { SessionsController } from './sessions.controller';
import { SessionsService } from './sessions.service';

const URL = process.env.COORDINATOR_PG_URL;

const LIFECYCLE = new Set(['then', 'onModuleInit', 'onApplicationBootstrap', 'onModuleDestroy',
  'beforeApplicationShutdown', 'onApplicationShutdown']);

/** A collaborator this route never reaches: any call on it is the route going somewhere it should not. */
const unreachable = (name: string): unknown =>
  new Proxy({}, {
    get: (_target, key) => {
      if (typeof key === 'symbol' || LIFECYCLE.has(key)) return undefined;
      return () => {
        throw new Error(`${name}.${key} is not part of the background job tail`);
      };
    },
  });

const RUNNING = 'bgj_7a0000000001';
const DONE = 'bgj_7a0000000002';
const NO_CONNECTION = 'bgj_7a0000000003';
const UNSUPPORTED = 'bgj_7a0000000004';
const TIMEOUT = 'bgj_7a0000000005';
const OLD = 'bgj_7a0000000006';
const OFFLINE = 'bgj_7a0000000007';
const UNHELD = 'bgj_7a0000000008';
const THEIRS = 'bgj_7a0000000009';
const UNKNOWN = 'bgj_7a00000000ff';

/** 60 lines in colour, as a test runner writes them, and one line far longer than the byte cap. */
const RUNNING_OUTPUT = Array.from({ length: 60 }, (_, i) => `\x1b[1;32mok ${i + 1}\x1b[0m test ${i + 1}`).join('\n') + '\n';

test('the owner reads a running job\'s newest lines from its runner; ended, unknown, old, offline and foreign are refused', {
  skip: !URL, concurrency: 1, timeout: 120_000,
}, async (t) => {
  assertCoordinatorPgUrlIsIsolated(URL);
  const sql = new Client({ connectionString: URL, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma = prismaClientFor(URL!);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  const otherId = randomUUID();
  const bearers = new Map([[`bearer-${ownerId}`, ownerId], [`bearer-${otherId}`, otherId]]);

  // ── the runner link: NATS in memory, and the gateway with the runner behind it on the new runner's subject ──────
  const nats = new MemoryNats();
  const bus = nats.connect('apiserver');
  const hints = new RunnerHints(prisma as never, 'nats://memory.test:4222', () => bus);
  hints.onModuleInit();
  t.after(() => hints.onModuleDestroy());
  const asked: Array<Record<string, unknown>> = [];
  let longLine = false;
  /** What the runner (or, for three jobs, the gateway) answers, by job. */
  function answerFor(req: Record<string, unknown>): Record<string, unknown> {
    const base = { requestId: req.requestId, sessionId: req.sessionId, jobId: req.jobId };
    switch (req.jobId) {
      case RUNNING:
        return {
          ...base, outcome: 'BACKGROUND_JOB_TAIL_OUTCOME_OK', status: 'running', truncated: true, outputBytes: '4321',
          // A runner holds to the request's caps; this one sends more, which the route holds to them all the same.
          text: longLine ? RUNNING_OUTPUT + 'x'.repeat(10_000) + '\n' : RUNNING_OUTPUT,
        };
      case NO_CONNECTION:
        return { ...base, outcome: 'BACKGROUND_JOB_TAIL_OUTCOME_NO_CONNECTION' };
      case UNSUPPORTED:
        return { ...base, outcome: 'BACKGROUND_JOB_TAIL_OUTCOME_UNSUPPORTED' };
      case TIMEOUT:
        return { ...base, outcome: 'BACKGROUND_JOB_TAIL_OUTCOME_TIMEOUT' };
      default: // DONE: its session's job service is gone from the runner.
        return { ...base, outcome: 'BACKGROUND_JOB_TAIL_OUTCOME_NOT_FOUND' };
    }
  }

  const sessions = new SessionsService(
    prisma as unknown as PrismaService,
    unreachable('queue') as never,
    unreachable('realtime') as never,
    undefined,
    undefined,
    undefined,
    undefined,
    hints,
  );

  @Module({
    controllers: [SessionsController],
    providers: [
      { provide: SessionsService, useValue: sessions },
      { provide: PrismaService, useValue: prisma },
      { provide: RealtimeService, useValue: unreachable('realtime') },
      { provide: SessionTagsService, useValue: unreachable('tags') },
      { provide: MergeReceiptService, useValue: unreachable('mergeReceipts') },
      { provide: AutoRetryService, useValue: unreachable('autoRetry') },
      JwtAuthGuard,
      Reflector,
      {
        provide: JwtService,
        useValue: {
          verifyAsync: async (token: string) => {
            const sub = bearers.get(token);
            if (!sub) throw new Error('not a bearer this run issued');
            return { sub, email: `${sub}@background-job-tail.invalid` };
          },
        },
      },
    ],
  })
  class BackgroundJobTailModule {}

  const app = await NestFactory.create(BackgroundJobTailModule, { logger: false, abortOnError: false });
  app.setGlobalPrefix('api');
  app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
  app.useGlobalInterceptors(new PublicIdInterceptor());
  await app.listen(0, '127.0.0.1');
  t.after(() => app.close());
  const base = await app.getUrl();

  // ── fixtures ──────────────────────────────────────────────────────────────────────────────────
  for (const id of [ownerId, otherId]) {
    await sql.query(`INSERT INTO "user"("id","email","name","password_hash") VALUES ($1,$2,'owner','x')`, [
      id, `background-job-tail-${id}@background-job-tail.invalid`,
    ]);
  }
  const newRunner = randomUUID();
  const oldRunner = randomUUID();
  const offlineRunner = randomUUID();
  const unheldRunner = randomUUID();
  const theirRunner = randomUUID();
  const longAgo = new Date(Date.now() - 10 * 60_000);
  for (const [id, owner, capabilities, beat] of [
    [newRunner, ownerId, [BG_OUTPUT_TAIL_V1], new Date()],
    [oldRunner, ownerId, [], new Date()],
    [offlineRunner, ownerId, [BG_OUTPUT_TAIL_V1], longAgo],
    [unheldRunner, ownerId, [BG_OUTPUT_TAIL_V1], new Date()],
    [theirRunner, otherId, [BG_OUTPUT_TAIL_V1], new Date()],
  ] as const) {
    await prisma.runner.create({ data: {
      id, ownerId: owner, name: `runner-${id.slice(0, 8)}`, tokenHash: randomUUID(), status: 'ONLINE',
      lastHeartbeatAt: beat, capabilities: [...capabilities], capabilitiesReportedAt: new Date(),
    } });
  }
  bus.subscribe(runnerHintSubject(newRunner), (data, reply) => {
    const req = (JSON.parse(Buffer.from(data).toString('utf8')) as { backgroundJobTailRequest?: Record<string, unknown> })
      .backgroundJobTailRequest;
    if (!req || !reply) return;
    asked.push(req);
    reply(JSON.stringify({ backgroundJobTailResponse: answerFor(req) }));
  });
  async function session(owner: string, runnerId: string, running: string[]): Promise<string> {
    const id = randomUUID();
    await sql.query(
      `INSERT INTO "session"("id","title","prompt","owner_id","creator_id","turn_state","dispatch_origin","assigned_runner_id",
                             "running_bg_shells","running_bg_jobs","created_at","updated_at")
       VALUES ($1,'background job tail','p',$2,$2,NULL,'USER',$3,$4,$4,now(),now())`,
      [id, owner, runnerId, running],
    );
    return id;
  }
  const mine = await session(ownerId, newRunner, [RUNNING, NO_CONNECTION, UNSUPPORTED, TIMEOUT]);
  const onOld = await session(ownerId, oldRunner, [OLD]);
  const onOffline = await session(ownerId, offlineRunner, [OFFLINE]);
  const onUnheld = await session(ownerId, unheldRunner, [UNHELD]);
  const theirs = await session(otherId, theirRunner, [THEIRS]);

  let seq = 0;
  async function event(sessionId: string, type: string, payload: unknown): Promise<void> {
    seq += 1;
    await sql.query(
      `INSERT INTO "run_event"("id","session_id","seq","type","payload","created_at") VALUES ($1,$2,$3,$4,$5,now())`,
      [randomUUID(), sessionId, seq, type, JSON.stringify(payload)],
    );
  }
  const output = (id: string) => `/root/.orbit/runs/spec/${id}.output`;
  /** runner-go background_job.go: the launch pair and the `running` record. */
  async function launch(sessionId: string, id: string, command: string): Promise<void> {
    await event(sessionId, RunEventType.TOOL_USE, { id, name: 'Bash', input: { command, run_in_background: true } });
    await event(sessionId, RunEventType.TOOL_RESULT, {
      toolUseId: id, content: `Command running in background with ID: ${id}. Output is being written to: ${output(id)}. `,
    });
    await event(sessionId, RunEventType.BACKGROUND_TASK, {
      shellId: id, toolUseId: id, status: 'running', kind: 'job', command, outputPath: output(id), idleMs: 0,
    });
  }
  for (const id of [RUNNING, DONE, NO_CONNECTION, UNSUPPORTED, TIMEOUT]) await launch(mine, id, 'npm test');
  await event(mine, RunEventType.BACKGROUND_TASK, {
    shellId: DONE, toolUseId: DONE, status: 'completed', kind: 'job', command: 'npm test', output: 'ok', outputPath: output(DONE),
    exitCode: 0, summary: 'Background job completed (exit code 0)',
  });
  await launch(onOld, OLD, 'sleep 600');
  await launch(onOffline, OFFLINE, 'sleep 600');
  await launch(onUnheld, UNHELD, 'sleep 600');
  await launch(theirs, THEIRS, 'sleep 600');

  async function tail(sessionId: string, jobId: string, query = '', as = ownerId): Promise<{ status: number; body: Record<string, unknown> }> {
    const response = await fetch(`${base}/api/sessions/${uuidToBase62(sessionId)}/background/jobs/${jobId}/tail${query}`, {
      headers: { authorization: `Bearer bearer-${as}` },
    });
    return { status: response.status, body: JSON.parse(await response.text()) as Record<string, unknown> };
  }
  const refused = async (sessionId: string, jobId: string, status: number, code: string | null, query = '', as = ownerId) => {
    const got = await tail(sessionId, jobId, query, as);
    assert.equal(got.status, status, `${jobId}${query}: ${JSON.stringify(got.body)}`);
    if (code) assert.equal(got.body.code, code, `${jobId}${query}: ${JSON.stringify(got.body)}`);
    if (code) assert.match(String(got.body.message), /\S/, `${code} says why in words`);
  };

  // ── the refusals made before the runner is asked ─────────────────────────────────────────────
  await refused(theirs, THEIRS, 404, null);
  await refused(mine, RUNNING, 404, null, '', otherId);
  await refused(mine, UNKNOWN, 404, 'BACKGROUND_JOB_NOT_FOUND');
  await refused(onOld, OLD, 409, 'RUNNER_CANNOT_READ_JOB_OUTPUT');
  await refused(onOffline, OFFLINE, 503, 'RUNNER_OFFLINE');
  await refused(mine, RUNNING, 400, 'INVALID_TAIL_LINES', '?lines=abc');
  await refused(mine, RUNNING, 400, 'INVALID_TAIL_LINES', '?lines=0');
  assert.equal(asked.length, 0, 'no refusal asks the runner anything');

  // ── the read ───────────────────────────────────────────────────────────────────────────────────
  const read = await tail(mine, RUNNING, '?lines=100');
  assert.equal(read.status, 200, JSON.stringify(read.body));
  assert.equal(asked.length, 1, 'the read is asked of the runner hosting the session, once');
  assert.deepEqual(
    { ...asked[0], requestId: typeof asked[0].requestId },
    { requestId: 'string', sessionId: mine, jobId: RUNNING, maxLines: 40, maxBytes: BG_JOB_TAIL_MAX_BYTES },
    'the runner is asked for at most 40 lines and 8 KB of the session\'s job',
  );
  const lines = read.body.lines as string[];
  assert.equal(lines.length, 40, 'at most 40 lines');
  assert.equal(lines[0], 'ok 21 test 21');
  assert.equal(lines[39], 'ok 60 test 60', 'the newest line last');
  assert.ok(lines.every((line) => !line.includes('\x1b')), 'no colour codes');
  assert.deepEqual(
    [read.body.jobId, read.body.status, read.body.exitCode, read.body.truncated, read.body.outputBytes],
    [RUNNING, 'running', null, true, 4321],
  );
  assert.ok(!Number.isNaN(Date.parse(String(read.body.readAt))), 'readAt is a time');

  const three = await tail(mine, RUNNING, '?lines=3');
  assert.equal(three.status, 200, JSON.stringify(three.body));
  assert.equal(asked[1].maxLines, 3, 'the lines asked for reach the runner');
  assert.deepEqual(three.body.lines, ['ok 58 test 58', 'ok 59 test 59', 'ok 60 test 60']);

  longLine = true;
  const capped = await tail(mine, RUNNING);
  assert.equal(capped.status, 200, JSON.stringify(capped.body));
  const cappedLines = capped.body.lines as string[];
  assert.ok(Buffer.byteLength(cappedLines.join('\n'), 'utf8') <= BG_JOB_TAIL_MAX_BYTES, 'at most 8 KB in all');
  assert.deepEqual(cappedLines, ['x'.repeat(BG_JOB_TAIL_MAX_BYTES)], 'a line longer than the cap keeps its end');

  // ── what the runner and the gateway answer ──────────────────────────────────────────────────────
  await refused(mine, DONE, 404, 'BACKGROUND_JOB_OUTPUT_GONE');
  await refused(mine, NO_CONNECTION, 503, 'RUNNER_OFFLINE');
  await refused(mine, UNSUPPORTED, 409, 'RUNNER_CANNOT_READ_JOB_OUTPUT');
  await refused(mine, TIMEOUT, 504, 'RUNNER_DID_NOT_ANSWER');
  await refused(onUnheld, UNHELD, 504, 'RUNNER_DID_NOT_ANSWER');
  bus.up = false;
  await refused(mine, RUNNING, 503, 'RUNNER_LINK_UNAVAILABLE');
  bus.up = true;
  assert.equal(asked.length, 7, 'every read that got past the refusals was asked once');
});
