/**
 * One turn, one set of cards: a waiting turn is listed with the cards its echo is stored with
 * (sessions/turn-cards.ts) — against a real PostgreSQL.
 *
 * A turn the control plane opened is drawn as a card rather than as the owner's bubble, and it is
 * drawn at three moments: while it waits, off `listQueuedTurns` — the queue view the native clients
 * read and the active view the web reads — and once the runner echoes it, off the `user` event's
 * payload. For each kind of card this queues one such turn through the door that writes it in
 * production, reads both views, hands the turn to the runner and echoes it through the real event
 * ingest, and asserts that the card fields are the same in all three, field by field — and in the
 * active view's accepted row between hand-out and echo, for the turns that view keeps there.
 *
 * The card fields are listed below under a type that `TurnCards` keys, so a card added there does not
 * compile here until it is listed, and the last case is red until it has a case of its own.
 *
 * The doors are the real services and controllers; the inbox, the event ingest and the turn
 * completion are the real RunnerApiController methods, called as the runner does.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/turn-cards-parity.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
