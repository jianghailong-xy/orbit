  /** The pair for one cell of the table, at a door whose target has this shape. */
  async function pair(
    row: (typeof TABLE)[number],
    cell: Cell,
    shape: Shape = {},
  ): Promise<{ from: string; to: string }> {
    if (cell === 'wider, related') return RELATIONS['parent to its child'](row.caller, row.wider, shape);
    return {
      from: await sessionIn(row.caller),
      to: await sessionIn(cell === 'not wider' ? row.notWider : row.wider, shape),
    };
  }

  /** What a door could have changed on the target: the row's lifecycle, and how many turns it holds. */
  async function stateOf(sessionId: string) {
    const row = await prisma.session.findUniqueOrThrow({
      where: { id: sessionId },
      select: {
        status: true, endReason: true, completedAt: true, deletedAt: true, mergeStatus: true, cancelRequestedAt: true,
      },
    });
    const turns = await prisma.conversationTurn.count({ where: { sessionId } });
    const charges = await prisma.sessionMessageCharge.count({ where: { toSessionId: sessionId } });
    const asked = await prisma.sessionRequest.count({ where: { toSessionId: sessionId } });
    return JSON.stringify({ ...row, turns, charges, asked });
  }

