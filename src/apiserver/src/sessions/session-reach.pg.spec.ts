/**
 * What a session may do to another session, over real HTTP and a real PostgreSQL.
 *
 *   | The caller's stored mode       | Target no wider | Target wider, directly related | Target wider, unrelated |
 *   |--------------------------------|-----------------|--------------------------------|-------------------------|
 *   | Auto, Bypass                   | allowed         | allowed                        | allowed                 |
 *   | Default, Accept Edits, Don't Ask | allowed       | allowed, the message says so   | refused                 |
 *   | Plan                           | allowed         | refused                        | refused                 |
 *
 * Every cell at every door: `session_send` (plain, `resumeIfEnded`, `expectReply`), `session_interrupt`
 * (with and without a message), `project_send`, `task_start` handing a paused run its brief,
 * `session_end`, `session_complete` and its old `archive` route, `session_delete` and `session_merge`.
 *
 * Besides the table:
 *   - each direct relation, each way round, read from the server's own records, and what looks like
 *     one and is not; a caller has no way to declare a relation;
 *   - a stored mode that is null reads as the account's default, and a mode that runs as Bypass on its
 *     engine counts as Bypass, by the same comparison the ceiling on starting sessions uses;
 *   - the words of each refusal, and what a refusal leaves behind: nothing;
 *   - `session_reply` is not held to any of this, and neither is a session acting on itself, a person's
 *     own door, or a retry of a message already filed;
 *   - the block and the card say the sender's mode, and say when the sender is the narrower one;
 *   - the run of a verification task takes a message only from its project's coordinator and the
 *     judgment sessions opened for that project, whatever the sender's mode;
 *   - what this rule does not cover: a credential with no session in it.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/session-reach.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
