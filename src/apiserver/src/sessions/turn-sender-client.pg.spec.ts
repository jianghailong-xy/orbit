declare global {
  interface BigInt { toJSON(): string; }
}
// `main.ts` installs this before it creates the app; a session row carries BIGINT columns.
BigInt.prototype.toJSON = function toJSON(this: bigint): string {
  return this.toString();
};

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

/** The runner credential, in the clear. Its hash is what the runner guard matches. */
const RUNNER_TOKEN = 'the-runner-token-for-turn-sender-clients';

interface Answer {
  status: number;
  text: string;
  json: Record<string, unknown>;
}

interface Streamed { seq: number; type: string; payload: Record<string, unknown> }

test('each turn says which client sent it, on the events page and the SSE, and never what a body says', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  let app: INestApplication | undefined;
  t.after(async () => {
    await app?.close().catch(() => undefined);
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  // ── the world: one account, one machine, one workspace ──────────────────────────────────────
  const ownerId = randomUUID();
  const runnerId = randomUUID();
  const workspaceId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `turn-sender-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });
  await prisma.runner.create({
    data: {
      id: runnerId, ownerId, name: 'build-box', tokenHash: sha256(RUNNER_TOKEN),
      status: RunnerStatus.ONLINE, lastHeartbeatAt: new Date(), capabilities: [], capabilitiesReportedAt: new Date(),
    },
  });
  await prisma.workspace.create({ data: { id: workspaceId, ownerId, runnerId, name: 'shop-api', enabled: true } });
  const runner = { id: runnerId, ownerId } as Runner;

  async function session(title: string, data: Partial<Prisma.SessionUncheckedCreateInput> = {}): Promise<string> {
    const id = randomUUID();
    await prisma.session.create({
      data: {
        id, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title, prompt: title, provider: 'claude', status: RunStatus.AWAITING_INPUT,
        numTurns: 1, startedAt: new Date(), runtimeSessionId: `runtime-${id}`,
        dispatchOrigin: SessionDispatchOrigin.USER, runSource: SessionRunSource.MANUAL,
        ...data,
      },
    });
    return id;
  }

  // ── the live hub: what the ingest broadcasts is what a connected SSE streams ─────────────────
  const hub = new Subject<{ runId: string; event: unknown }>();
  const hubMethods: Record<string, unknown> = {
    publishBatch: (runId: string, events: readonly unknown[]) => events.forEach((event) => hub.next({ runId, event })),
    publishBatchHere: (runId: string, events: readonly unknown[]) => events.forEach((event) => hub.next({ runId, event })),
    publish: (runId: string, event: unknown) => hub.next({ runId, event }),
    streamForRun: (runId: string) => hub.pipe(filter((m) => m.runId === runId), map((m) => m.event)),
    turnPrefix: () => ({ text: '', thinking: '' }),
  };
  const realtime = new Proxy(hubMethods, {
    get: (target, key) => (typeof key === 'string' && key in target ? target[key] : key === 'then' ? undefined : () => undefined),
  });
  const silent = (): unknown =>
    new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

  // ── the doors ─────────────────────────────────────────────────────────────────────────────────
  const queue = { notifySessionQueued: () => undefined };
  const sessions = new SessionsService(prisma as unknown as PrismaService, queue as never, realtime as never);
  const orchestration = new RunnerOrchestrationAuthorizer(
    prisma as unknown as PrismaService,
    new JwtService({ secret: 'turn-sender-client-pg' }),
  );
  const attempts = { chargeSteer: async () => undefined };
  const runnerDoor = new RunnerSessionsController(sessions, orchestration, {} as never, attempts as never);
  const ownerDoor = new SessionsController(
    sessions, prisma as unknown as PrismaService, realtime as never, {} as never, {} as never, {} as never,
  );

  const login: AuthUser = { userId: ownerId, email: 'owner@x.invalid', credential: { kind: 'LOGIN' } };
  const terminal: AuthUser = {
    userId: ownerId, email: 'owner@x.invalid',
    credential: { kind: 'TERMINAL', terminalId: randomUUID(), runnerId, machineName: 'build-box' },
  };

  /** `POST /sessions/:id/turns` as Express hands it the credential, the body and the two headers. */
  async function ownerSend(
    user: AuthUser, to: string, client: string | undefined, device: string | undefined,
    body: Record<string, unknown> = {},
  ): Promise<void> {
    await ownerDoor.turn(user, to, { content: 'also add a test', clientTurnId: randomUUID(), ...body } as never, client, device);
  }

  // ── the app: the real runner door, its guard, main.ts's middleware and interceptor ─────────────
  @Module({
    controllers: [RunnerApiController],
    providers: [
      { provide: PrismaService, useValue: prisma },
      { provide: QueueService, useValue: queue },
      { provide: SessionsService, useValue: sessions },
      { provide: RealtimeService, useValue: realtime },
      { provide: PushService, useValue: silent() },
      { provide: RunnerOrchestrationAuthorizer, useValue: orchestration },
      { provide: ReferenceExpansionService, useValue: { expand: async (_owner: string, content?: string) => content } },
      { provide: ListEventsService, useValue: { appendFor: async (_tx: unknown, _id: string, content?: string) => content } },
      { provide: AttemptBudgetMeterService, useValue: { meterQuietly: async () => undefined } },
      { provide: ProjectAcceptanceService, useValue: {} },
      { provide: TasksService, useValue: {} },
      { provide: MergeReceiptService, useValue: {} },
      RunnerAuthGuard,
    ],
  })
  class RunnerDoor {}

  app = await NestFactory.create(RunnerDoor, { logger: false, abortOnError: false });
  app.use(publicIdHeaders);
  app.setGlobalPrefix('api');
  app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
  app.useGlobalInterceptors(new PublicIdInterceptor());
  await app.listen(0, '127.0.0.1');
  const base = await app.getUrl();

  async function http(method: 'GET' | 'POST', route: string, body?: unknown): Promise<Answer> {
    const response = await fetch(`${base}/api${route}`, {
      method,
      headers: {
        authorization: `Bearer ${RUNNER_TOKEN}`,
        ...(body === undefined ? {} : { 'content-type': 'application/json' }),
      },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    });
    const text = await response.text();
    let json: Record<string, unknown> = {};
    try { json = JSON.parse(text) as Record<string, unknown>; } catch { /* asserted on by the caller */ }
    return { status: response.status, text, json };
  }

  /** The runner's claim of the queued session, then the inbox poll that hands it the turn. */
  async function claimAndPoll(sessionId: string): Promise<Answer> {
    await prisma.$transaction(async (tx) => {
      await tx.$executeRaw`SELECT set_config('orbit.claim_reads_session_engine', '1', true)`;
      await tx.session.update({ where: { id: sessionId }, data: { status: RunStatus.RUNNING } });
    });
    const delivered = await http('GET', `/runner/sessions/${uuidToBase62(sessionId)}/inbox?leaseGeneration=${await sessionLease(prisma, sessionId)}`);
    assert.equal(delivered.status, 200, `inbox answered ${delivered.status}: ${delivered.text}`);
    assert.equal(delivered.json.kind, 'message', `the inbox handed out no message: ${delivered.text}`);
    return delivered;
  }

  /** The SSE as a client holds it open: every event it streams, until `stop`. */
  function openStream(sessionId: string, sinceSeq?: string) {
    const got: Streamed[] = [];
    const sub = ownerDoor.events(login, sessionId, sinceSeq).subscribe((frame: MessageEvent) => {
      const data = frame.data as Streamed;
      if (data.type !== 'ping') got.push(data);
    });
    return { got, stop: () => sub.unsubscribe() };
  }

  async function until(what: string, check: () => boolean): Promise<void> {
    for (let i = 0; i < 200 && !check(); i++) await new Promise((r) => setTimeout(r, 25));
    assert.ok(check(), `timed out waiting for ${what}`);
  }

  /**
   * Delivers the turn just sent, echoes it as the runner does — with `forged` riding on the echo, as a runner
   * could send — and answers its `user` event as the events page, the live SSE and the SSE's replay give it.
   */
  async function readBack(sessionId: string, forged: Record<string, unknown> = {}) {
    const live = openStream(sessionId, '0');
    try {
      const delivered = await claimAndPoll(sessionId);
      const echoed = await http('POST', `/runner/sessions/${uuidToBase62(sessionId)}/events`, {
        events: [{ seq: 1, type: 'user', ts: new Date().toISOString(), turnId: delivered.json.turnId,
          payload: { text: String(delivered.json.content ?? ''), ...forged } }],
      });
      assert.equal(echoed.status, 202, `events answered ${echoed.status}: ${echoed.text}`);
      await until('the live user event', () => live.got.some((e) => e.type === 'user'));
    } finally {
      live.stop();
    }
    const page = (await ownerDoor.eventPage(login, sessionId, '50')) as { events: Array<{ type: string; payload: unknown }> };
    const paged = page.events.find((e) => e.type === 'user');
    assert.ok(paged, 'the events page has no user event');
    const replay = openStream(sessionId);
    try {
      await until('the replayed user event', () => replay.got.some((e) => e.type === 'user'));
    } finally {
      replay.stop();
    }
    return {
      page: (paged.payload as Record<string, unknown>).sentFrom,
      live: live.got.find((e) => e.type === 'user')!.payload.sentFrom,
      replay: replay.got.find((e) => e.type === 'user')!.payload.sentFrom,
    };
  }

  function assertSentFrom(read: Awaited<ReturnType<typeof readBack>>, want: unknown, door: string): void {
    assert.deepEqual(read.page, want, `${door}: events/page`);
    assert.deepEqual(read.live, want, `${door}: the SSE as it was broadcast`);
    assert.deepEqual(read.replay, want, `${door}: the SSE's replay`);
  }

  // ── 1. each door ──────────────────────────────────────────────────────────────────────────────

  const doors: Array<{ door: string; send: (to: string) => Promise<void>; want: unknown }> = [
    { door: 'web', send: (to) => ownerSend(login, to, 'web/0.1.114', undefined), want: { client: 'web' } },
    { door: 'iPhone', send: (to) => ownerSend(login, to, 'ios/1.8.0', 'iphone'), want: { client: 'ios', device: 'iphone' } },
    { door: 'iPad', send: (to) => ownerSend(login, to, 'ios/1.8.0', 'ipad'), want: { client: 'ios', device: 'ipad' } },
    { door: 'iOS without a device header', send: (to) => ownerSend(login, to, 'ios/1.7.0', undefined), want: { client: 'ios' } },
    { door: 'Mac', send: (to) => ownerSend(login, to, 'macos/1.8.0', undefined), want: { client: 'macos' } },
    { door: 'Android', send: (to) => ownerSend(login, to, 'android/1.8.0', undefined), want: { client: 'android' } },
    {
      door: 'TERMINAL credential', send: (to) => ownerSend(terminal, to, undefined, undefined),
      want: { client: 'terminal', machineName: 'build-box' },
    },
    {
      door: 'session_send',
      send: async (to) => {
        const worker = await session('Worker: rate limit on /login');
        await runnerDoor.sendMessage(runner, undefined, worker, await orchestration.issue(runnerId, worker), to,
          { message: 'also add a test', clientTurnId: randomUUID() });
      },
      want: { client: 'session', sessionTitle: 'Worker: rate limit on /login' },
    },
    {
      door: 'the runner’s headless credential',
      send: async (to) => {
        await runnerDoor.sendMessage(runner, undefined, undefined, undefined, to,
          { message: 'also add a test', clientTurnId: randomUUID() });
      },
      want: { client: 'runner' },
    },
  ];
  for (const { door, send, want } of doors) {
    await t.test(`a turn sent through ${door} comes back with its client`, async () => {
      const to = await session(`the conversation ${door} writes to`);
      await send(to);
      assertSentFrom(await readBack(to), want, door);
    });
  }

  await t.test('a resume that revives an ended session records the client too', async () => {
    const to = await session('a conversation that has ended', { status: RunStatus.SUCCEEDED, completedAt: new Date(Date.now() - 60_000) });
    const answer = await ownerDoor.resume(login, to, { content: 'pick this back up', clientTurnId: randomUUID() } as never,
      'android/1.8.0', undefined);
    assert.equal((answer as { revived?: boolean }).revived, true, `nothing was revived: ${JSON.stringify(answer)}`);
    const [turn] = await prisma.conversationTurn.findMany({ where: { sessionId: to, content: 'pick this back up' } });
    assert.deepEqual([turn.senderClient, turn.senderClientDetail], ['android', null]);
  });

  // ── 2. never what a body says ─────────────────────────────────────────────────────────────────

  await t.test('a label the body, a header naming no app, or the runner’s echo supplies is ignored', async () => {
    const forgedBody = { sentFrom: { client: 'ios', device: 'ipad' }, senderClient: 'terminal', senderClientDetail: 'forged' };
    // The body says iPad and terminal; the header says web: it is web.
    const web = await session('the body names another client');
    await ownerSend(login, web, 'web/0.1.114', undefined, forgedBody);
    assertSentFrom(await readBack(web, { sentFrom: { client: 'session', sessionTitle: 'forged' } }), { client: 'web' },
      'a forged body and echo');
    const row = await prisma.conversationTurn.findFirstOrThrow({ where: { sessionId: web } });
    assert.deepEqual([row.senderClient, row.senderClientDetail], ['web', null]);

    // No header naming an app, a body naming one, and an echo naming one: nothing is recorded or said.
    for (const header of [undefined, 'terminal/1.0', 'feishu/1.0', 'iPhone']) {
      const none = await session(`nothing names the client (${String(header)})`);
      await ownerSend(login, none, header, 'ipad', forgedBody);
      assertSentFrom(await readBack(none, { sentFrom: { client: 'web' } }), undefined, `header ${String(header)}`);
      const stored = await prisma.conversationTurn.findFirstOrThrow({ where: { sessionId: none } });
      assert.deepEqual([stored.senderClient, stored.senderClientDetail], [null, null]);
    }
  });
});
