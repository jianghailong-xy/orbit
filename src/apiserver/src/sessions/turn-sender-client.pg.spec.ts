/**
 * Which client sent each turn (migration 0595, sessions/turn-sender-client.ts), against a real PostgreSQL: what
 * `orbit` in a terminal reads to draw "· from iPhone" beside a message it did not send (project criterion 6,
 * docs/mocks/terminal-session/board-1.png marker 3).
 *
 *   1. A turn sent through each door — the web app, the iOS app on an iPhone and on an iPad, the Mac app, the
 *      Android app (by the `X-Orbit-Client` / `X-Orbit-Device` headers they send), a TERMINAL credential (with its
 *      machine's name), another session's `session_send` (with that session's title), the runner's own headless
 *      credential, and a resume that revives an ended session — has its `user` event come back on
 *      `GET /sessions/:id/events/page`, on the SSE as it is broadcast, and on the SSE's replay, with the matching
 *      `sentFrom`.
 *   2. A label the body supplies is ignored: a body naming `sentFrom` / `senderClient`, a header naming no app,
 *      and a `sentFrom` the runner's echo carries all leave the event with what the door recorded, or nothing.
 *
 * The owner doors are the real SessionsController methods with the credential and headers JwtAuthGuard and
 * Express hand them; the runner's doors, the inbox and the event ingest are reached over real HTTP, through the
 * guard and the public-id interceptor main.ts installs. A TERMINAL credential is handed to the turn route
 * directly: the route allowlist that admits it (T2) is not this task's.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/turn-sender-client.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { type INestApplication, type MessageEvent, Module, ValidationPipe } from '@nestjs/common';
import { NestFactory } from '@nestjs/core';
