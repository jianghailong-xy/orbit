/**
 * A run ends with its task, so a session held back from ending a run is held back from doing it from the task's side, over
 * real HTTP and a real PostgreSQL. The table is the one in session-reach.ts:
 *
 *   | The caller's stored mode       | Run no wider | Run wider, directly related | Run wider, unrelated |
 *   |--------------------------------|--------------|-----------------------------|----------------------|
 *   | Auto, Bypass                   | allowed      | allowed                     | allowed              |
 *   | Default, Accept Edits, Don't Ask | allowed    | allowed                     | refused              |
 *   | Plan                           | allowed      | refused                     | refused              |
 *
 * Every cell at every door: `task_update` writing CANCELLED, `task_delete` and `tasklist_delete`.
 *
 * Besides the table:
 *   - each direct relation, each way round, and what looks like one and is not;
 *   - only what the door would end is asked: a task with no live run, or a session the door leaves alone, goes on as it
 *     did, and so does every other write of the task;
 *   - a delete ends the runs of the checks it takes with it, and a list's delete every run of the list;
 *   - a stored mode that is null reads as the account's default, and a mode that runs as Bypass on its engine counts as
 *     Bypass, by the one comparison;
 *   - the words of each refusal, and what a refusal leaves behind: nothing;
 *   - a person's own door, a credential with no session in it, and a session acting on itself are not held.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/session-stop-reach.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
