      assertRefused(answer, door.name);
      const words = String(answer.json.message);
      assert.ok(words.includes(`This session runs in "default", and session ${uuidToBase62(stop.run)} runs in "auto", which is wider`), words);
      assert.ok(words.includes(`so this session may not ${ACT_WORDS[door.name]}. Nothing was changed.`), words);
      assert.ok(words.includes('Ask your own coordinator to do this'), words);
      assert.ok(words.includes('ask the account owner to switch this session\'s mode'), words);
