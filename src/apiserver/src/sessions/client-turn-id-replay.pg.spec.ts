/**
 * One clientTurnId leaves one durable effect, against a real PostgreSQL.
 *
 * The runner (src/runner-go/call_identity.go) sends every delivery of one logical `session_send` or
 * `session_interrupt`-with-a-message under one clientTurnId: in-call resends after a lost answer, and
 * the agent's replay of the id its error named. This holds the server's half of that protocol at the
 * runner door itself (RunnerSessionsController, with the real orchestration credential and the real
 * SessionsService):
 *
 *   1. session_send: concurrent deliveries under one key, then a replay after the answer was "lost"
 *      (committed, never read), all answer the same turn, and the database holds ONE turn under that
 *      key, charged ONCE to the pair's window and once as a steer.
 *   2. The same key with a different message is refused 409 and writes nothing: no turn, no charge.
 *   3. session_interrupt with a message: the same, for the interrupt control turn
 *      (`interrupt-<key>`) and the follow-up turn (`<key>`): one of each, however many deliveries,
 *      and a different follow-up under the key is refused with nothing written.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/client-turn-id-replay.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { JwtService } from '@nestjs/jwt';
import {
  type Prisma,
  type PrismaClient,
  type Runner,
  RunStatus,
  RunnerStatus,
  SessionDispatchOrigin,
  SessionRunSource,
} from '@prisma/client';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { prismaClientFor } from '../prisma/prisma-client';
import { PrismaService } from '../prisma/prisma.service';
import { RunnerOrchestrationAuthorizer } from '../runner-api/runner-orchestration-authorizer';
import { RunnerSessionsController } from '../runner-api/runner-sessions.controller';
import { SessionsService } from './sessions.service';

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

/** How many deliveries race under one key. */
const RACERS = 8;

const silent = (): unknown =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

function statusOf(error: unknown): number | undefined {
  return (error as { getStatus?: () => number }).getStatus?.();
}

test('one clientTurnId is one message and one interrupt, however many times it is delivered', {
  skip, concurrency: 1, timeout: 300_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  const runnerId = randomUUID();
  const workspaceId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `client-turn-id-${ownerId}@runner-door.invalid`, name: 'owner', passwordHash: 'x' },
  });
  await prisma.runner.create({
    data: {
      id: runnerId, ownerId, name: 'the machine', tokenHash: sha256(`token-${runnerId}`),
      status: RunnerStatus.ONLINE, lastHeartbeatAt: new Date(), capabilities: [], capabilitiesReportedAt: new Date(),
    },
  });
  await prisma.workspace.create({ data: { id: workspaceId, ownerId, runnerId, name: 'orbit-worker', enabled: true } });
  const runner = { id: runnerId, ownerId } as Runner;

  async function session(title: string, data: Partial<Prisma.SessionUncheckedCreateInput> = {}): Promise<string> {
    const id = randomUUID();
    await prisma.session.create({
      data: {
        id, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title, prompt: title, provider: 'claude', status: RunStatus.AWAITING_INPUT,
        numTurns: 1, startedAt: new Date(), runtimeSessionId: `runtime-${id}`,
        dispatchOrigin: SessionDispatchOrigin.USER, runSource: SessionRunSource.MANUAL,
        ...data,
      },
    });
    return id;
  }

  const sessions = new SessionsService(
    prisma as unknown as PrismaService,
    { notifySessionQueued: () => undefined } as never,
    silent() as never,
  );
  const orchestration = new RunnerOrchestrationAuthorizer(
    prisma as unknown as PrismaService,
    new JwtService({ secret: 'client-turn-id-replay-pg' }),
  );
  const steers: string[] = [];
  const attempts = { chargeSteer: async (_owner: string, sessionId: string) => { steers.push(sessionId); } };
  const door = new RunnerSessionsController(sessions, orchestration, {} as never, attempts as never);

  const send = async (from: string, to: string, message: string, clientTurnId: string) =>
    door.sendMessage(runner, undefined, from, await orchestration.issue(runnerId, from), to, { message, clientTurnId });
  const interrupt = async (from: string, to: string, message: string, clientTurnId: string) =>
    door.interruptSession(runner, undefined, from, await orchestration.issue(runnerId, from), to, { message, clientTurnId });

  async function turnsUnder(sessionId: string, clientTurnId: string): Promise<Array<{ id: string; kind: string; content: string | null }>> {
    const rows = await sql.query<{ id: string; kind: string; content: string | null }>(
      `SELECT "id"::text AS "id", "kind"::text AS "kind", "content" FROM "conversation_turn"
        WHERE "session_id" = $1::uuid AND "client_turn_id" = $2`,
      [sessionId, clientTurnId],
    );
    return rows.rows;
  }
  /** A session in the middle of a turn: RUNNING, with the message it is running IN_FLIGHT — what an
   *  interrupt stops. */
  async function running(title: string): Promise<string> {
    const id = await session(title);
    const clientTurnId = randomUUID();
    await sessions.createTurn(ownerId, id, { content: 'the running turn', clientTurnId } as never);
    await prisma.conversationTurn.updateMany({ where: { sessionId: id, clientTurnId }, data: { status: 'IN_FLIGHT' } });
    await prisma.session.update({ where: { id }, data: { status: RunStatus.RUNNING } });
    return id;
  }
  const allTurns = (sessionId: string) => prisma.conversationTurn.count({ where: { sessionId } });
  async function charges(from: string, to: string): Promise<number> {
    const rows = await sql.query<{ n: string }>(
      `SELECT count(*)::text AS n FROM "session_message_charge"
        WHERE "from_session_id" = $1::uuid AND "to_session_id" = $2::uuid`,
      [from, to],
    );
    return Number(rows.rows[0].n);
  }

  await t.test('session_send: racing deliveries and a replay after a lost answer file one turn, charged once', async () => {
    const from = await session('the sender');
    const to = await session('the recipient');
    const key = randomUUID();
    const turnsBefore = await allTurns(to);

    const raced = await Promise.allSettled(
      Array.from({ length: RACERS }, () => send(from, to, 'adjust the tests', key)),
    );
    const answered = raced.map((r) => {
      assert.equal(r.status, 'fulfilled', `a delivery under the key was refused: ${r.status === 'rejected' ? String(r.reason) : ''}`);
      return (r as PromiseFulfilledResult<Awaited<ReturnType<typeof send>>>).value as unknown as { turn?: { id: string }; turnId?: string };
    });
    const turnIdOf = (a: { turn?: { id: string }; turnId?: string }) => a.turnId ?? a.turn?.id;
    const first = turnIdOf(answered[0]);
    assert.ok(first, `the answer names no turn: ${JSON.stringify(answered[0])}`);
    for (const a of answered) assert.equal(turnIdOf(a), first, 'two deliveries of one key answered two turns');

    // The answer to this delivery is "lost": it committed and nobody read it. The replay under the
    // same key reads the same turn back.
    const replay = await send(from, to, 'adjust the tests', key) as unknown as { turn?: { id: string }; turnId?: string };
    assert.equal(turnIdOf(replay), first, 'the replay filed a second turn');

    const rows = await turnsUnder(to, key);
    assert.equal(rows.length, 1, `the key holds ${rows.length} turns`);
    assert.equal(rows[0].content, 'adjust the tests');
    assert.equal(await allTurns(to), turnsBefore + 1, 'more than one turn was written');
    assert.equal(await charges(from, to), 1, 'the pair window was charged more than once');
    assert.equal(steers.filter((s) => s === to).length, 1, 'the steer budget was charged more than once');
  });

  await t.test('session_send: the same key with another message is refused and writes nothing', async () => {
    const from = await session('the sender');
    const to = await session('the recipient');
    const key = randomUUID();
    await send(from, to, 'the first message', key);
    const turnsBefore = await allTurns(to);
    const chargesBefore = await charges(from, to);
    const steersBefore = steers.length;

    await assert.rejects(send(from, to, 'a different message', key), (error: unknown) => {
      assert.equal(statusOf(error), 409, `refused with ${String(error)}`);
      assert.match(String((error as Error).message), /clientTurnId was already used/);
      return true;
    });

    const rows = await turnsUnder(to, key);
    assert.equal(rows.length, 1);
    assert.equal(rows[0].content, 'the first message', 'the mismatch overwrote the first message');
    assert.equal(await allTurns(to), turnsBefore, 'the mismatch wrote a turn');
    assert.equal(await charges(from, to), chargesBefore, 'the mismatch was charged');
    assert.equal(steers.length, steersBefore, 'the mismatch spent a steer');
  });

  await t.test('session_interrupt with a message: racing deliveries and a replay record one interrupt and one follow-up', async () => {
    const from = await session('the sender');
    const to = await running('the recipient');
    const key = randomUUID();
    const turnsBefore = await allTurns(to);

    const raced = await Promise.allSettled(
      Array.from({ length: RACERS }, () => interrupt(from, to, 'stop; do this instead', key)),
    );
    const answered = raced.map((r) => {
      assert.equal(r.status, 'fulfilled', `a delivery under the key was refused: ${r.status === 'rejected' ? String(r.reason) : ''}`);
      return (r as PromiseFulfilledResult<Awaited<ReturnType<typeof interrupt>>>).value as unknown as { turnId?: string };
    });
    const first = answered[0].turnId;
    assert.ok(first, `the answer names no follow-up turn: ${JSON.stringify(answered[0])}`);
    for (const a of answered) assert.equal(a.turnId, first, 'two deliveries of one key answered two follow-ups');

    const replay = await interrupt(from, to, 'stop; do this instead', key) as unknown as { turnId?: string };
    assert.equal(replay.turnId, first, 'the replay filed a second follow-up');

    const control = await turnsUnder(to, `interrupt-${key}`);
    const followUp = await turnsUnder(to, key);
    assert.equal(control.length, 1, `the interrupt was recorded ${control.length} times`);
    assert.equal(control[0].kind, 'interrupt');
    assert.equal(followUp.length, 1, `the follow-up was filed ${followUp.length} times`);
    assert.equal(followUp[0].content, 'stop; do this instead');
    assert.equal(await allTurns(to), turnsBefore + 2, 'more than one interrupt and one follow-up were written');
    assert.equal(await charges(from, to), 1, 'the pair window was charged more than once');
  });

  await t.test('session_interrupt: the same key with another follow-up is refused and writes nothing', async () => {
    const from = await session('the sender');
    const to = await running('the recipient');
    const key = randomUUID();
    await interrupt(from, to, 'the first follow-up', key);
    const turnsBefore = await allTurns(to);
    const chargesBefore = await charges(from, to);

    await assert.rejects(interrupt(from, to, 'a different follow-up', key), (error: unknown) => {
      assert.equal(statusOf(error), 409, `refused with ${String(error)}`);
      assert.match(String((error as Error).message), /clientTurnId was already used/);
      return true;
    });

    assert.equal((await turnsUnder(to, `interrupt-${key}`)).length, 1, 'a second interrupt was recorded');
    const followUp = await turnsUnder(to, key);
    assert.equal(followUp.length, 1);
    assert.equal(followUp[0].content, 'the first follow-up', 'the mismatch overwrote the follow-up');
    assert.equal(await allTurns(to), turnsBefore, 'the mismatch wrote a turn');
    assert.equal(await charges(from, to), chargesBefore, 'the mismatch was charged');
  });
});
