import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import test from 'node:test';

import { combinations, STORED_END_REASONS, STORED_STATUSES } from './session-state-legacy-fields.fixture';
import { withSessionState } from './session-state';

/**
 * Plan step 4.8 of docs/session-three-state-plan.md: one projector produces the legacy wire fields `status`,
 * `runStatus`, `runState`, `sessionState` and `filingState` from the stored facts (withSessionState, over the derive
 * functions of @orbit/shared enums.ts), and what it produces is byte-identical to what it produced before the step.
 *
 * session-state-legacy-fields.golden.json holds the five fields for every stored combination
 * (session-state-legacy-fields.fixture.ts), generated by the BUILT projector at the commit its `base` names, before
 * any change of this step. Never regenerate it to make this spec pass: a difference is a changed wire value, which an
 * already-shipped app or deployed runner reads.
 *
 * Since task T4 of docs/session-status-retirement-plan.md the words are derived from facts
 * (sessions/session-legacy-words.ts) and no longer copied from the stored one. The rows that read otherwise were
 * restated, for the kinds of the plan's §3.4 alone: each carries its `kind` and, in `was`, the words the base commit
 * produced. Where no writer leaves a combination (an old SUCCEEDED row with an end reason other than `task_done`, a
 * FAILED one with `idle`, `orphaned` or the empty string, ...) it is filed under the kind of its word change.
 */

const REPO = path.resolve(__dirname, '../../../..');
const GOLDEN = path.join(REPO, 'src/apiserver/src/sessions/session-state-legacy-fields.golden.json');

interface GoldenRow {
  key: string;
  status: string;
  runStatus: string;
  runState: string;
  sessionState: string;
  filingState: string;
  kind?: string;
  was?: Pick<GoldenRow, 'status' | 'runStatus' | 'runState' | 'sessionState'>;
}

const golden = JSON.parse(readFileSync(GOLDEN, 'utf8')) as { base: string; rows: GoldenRow[] };

test('the fixture enumerates every stored status, end reason and filing fact', () => {
  const cases = combinations();
  assert.equal(cases.length, STORED_STATUSES.length * STORED_END_REASONS.length * 5);
  assert.equal(new Set(cases.map((c) => c.key)).size, cases.length);
  assert.deepEqual([...new Set(cases.map((c) => c.row.status))], [...STORED_STATUSES]);
  assert.equal(golden.rows.length, cases.length);
  assert.match(golden.base, /^[0-9a-f]{40}$/);
});

test('a restated row names a §3.4 kind and differs from the words it replaced', () => {
  const restated = golden.rows.filter((row) => row.kind !== undefined || row.was !== undefined);
  assert.ok(restated.length > 0);
  for (const row of restated) {
    assert.match(row.kind ?? '', /^C[1-7]$/, row.key);
    assert.notEqual(row.was!.status, row.status, row.key);
  }
});

test('the five legacy fields are the golden ones for every stored combination', () => {
  const byKey = new Map(golden.rows.map((row) => [row.key, row]));
  const differences: string[] = [];
  for (const { key, row } of combinations()) {
    const projected = withSessionState({ ...row });
    const now = JSON.stringify({
      key,
      status: projected.status,
      runStatus: projected.runStatus,
      runState: projected.runState,
      sessionState: projected.sessionState,
      filingState: projected.filingState,
    });
    const then = JSON.stringify(byKey.get(key));
    if (now !== then) differences.push(`${key}: base ${then}, now ${now}`);
  }
  assert.deepEqual(differences, [], `\n${differences.join('\n')}\n`);
});
