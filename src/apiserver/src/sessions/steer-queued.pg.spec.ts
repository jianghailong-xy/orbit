/**
 * The tray's Steer against a real PostgreSQL (SessionsService.steerQueuedTurn).
 *
 * A message queued for the next turn becomes the CURRENT_WORK steer aimed at the running turn — on
 * the row shapes and constraints migrations give the table — and the inbox hands it to the runner at
 * once, ahead of a message queued before it, which keeps waiting for the turn's result. Where there
 * is no turn to join, or nothing here that can take it, the message stays exactly as it was queued.
 * The runner's side is played by hand: what it polls.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/steer-queued.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { ConflictException } from '@nestjs/common';
import { type PrismaClient, RunnerStatus, RunStatus, SessionDispatchOrigin, SessionRunSource } from '@prisma/client';
import { SESSION_CURRENT_WORK_ROUTING_V1 } from '@orbit/shared';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { prismaClientFor } from '../prisma/prisma-client';
import { PrismaService } from '../prisma/prisma.service';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { RunnerApiController } from '../runner-api/runner-api.controller';
import { SessionsService } from './sessions.service';

declare global {
  interface BigInt { toJSON(): string; }
}
// `main.ts` installs this before it creates the app; a session row carries BIGINT columns.
BigInt.prototype.toJSON = function toJSON(this: bigint): string {
  return this.toString();
};

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;
const ROUTING = [SESSION_CURRENT_WORK_ROUTING_V1];

/** A collaborator whose every method answers nothing: the broadcasts a turn's enqueue fires. */
const silent = (): unknown =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

const reasonOf = (err: unknown) =>
  ((err as ConflictException).getResponse() as { code?: string; reason?: string });

test('a queued message is sent into the running turn, or stays queued', {
  skip, concurrency: 1, timeout: 600_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });
  const db = prisma as unknown as PrismaService;

  const ownerId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `steer-queued-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });

  /** A machine that declared `capabilities`, its workspace, and a Claude session on it, parked. */
  async function world(capabilities: string[]) {
    const runnerId = randomUUID();
    const workspaceId = randomUUID();
    const sessionId = randomUUID();
    await prisma.runner.create({
      data: {
        id: runnerId, ownerId, name: `machine ${runnerId}`, tokenHash: sha256(`token-${runnerId}`),
        status: RunnerStatus.ONLINE, lastHeartbeatAt: new Date(), capabilities, capabilitiesReportedAt: new Date(),
      },
    });
    await prisma.workspace.create({ data: { id: workspaceId, ownerId, runnerId, name: 'orbit-worker', enabled: true } });
    await prisma.session.create({
      data: {
        id: sessionId, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title: 'fix the export', prompt: 'fix the export', provider: 'claude', status: RunStatus.AWAITING_INPUT,
        numTurns: 1, startedAt: new Date(), runtimeSessionId: `runtime-${sessionId}`,
        dispatchOrigin: SessionDispatchOrigin.USER, runSource: SessionRunSource.MANUAL,
      },
    });
    return { runnerId, sessionId, capabilities };
  }

  const realtime = silent();
  const queue = { notifySessionQueued: () => undefined };
  const sessions = new SessionsService(db, queue as never, realtime as never);
  const api = new RunnerApiController(
    db,
    queue as never,
    realtime as never,
    {} as never,
    {} as never,
    { expand: async (_owner: string, content?: string) => content } as never,
    { appendFor: async (_tx: unknown, _id: string, content?: string) => content } as never,
  );
  type Dequeue = (
    sessionId: string, runnerId: string, leaseGeneration: string | null, acceptsSteer: boolean,
    declaredCapabilities: readonly string[],
  ) => Promise<Record<string, unknown> | null>;
  const dequeue = (w: Awaited<ReturnType<typeof world>>) =>
    (api as unknown as { dequeueTurn: Dequeue }).dequeueTurn.call(api, w.sessionId, w.runnerId, null, true, w.capabilities);

  const send = async (w: Awaited<ReturnType<typeof world>>, content: string) =>
    await sessions.createTurn(ownerId, w.sessionId, {
      clientTurnId: randomUUID(), content, intent: 'NEXT_TURN',
    } as never) as { turnId: string; kind: string; placement: string };

  /** The person's message, claimed and handed to the engine: the turn everything below is sent into. */
  async function running(w: Awaited<ReturnType<typeof world>>): Promise<string> {
    const sent = await send(w, 'run the full test suite');
    await prisma.$transaction(async (tx) => {
      await tx.$executeRaw`SELECT set_config('orbit.claim_reads_session_engine', '1', true)`;
      await tx.session.update({ where: { id: w.sessionId }, data: { status: RunStatus.RUNNING } });
    });
    const handed = await dequeue(w);
    assert.equal(handed?.turnId, sent.turnId, 'the running message was not the one handed out');
    return sent.turnId;
  }

  await t.test('it becomes the steer aimed at the running turn, and goes ahead of what was queued first', async () => {
    const w = await world(ROUTING);
    const target = await running(w);
    const first = await send(w, 'then update the changelog');
    const second = await send(w, 'and push it to main');
    assert.deepEqual([first.placement, second.placement], ['queued', 'queued']);

    assert.deepEqual(await sessions.steerQueuedTurn(ownerId, w.sessionId, second.turnId), {
      turnId: second.turnId,
      seq: (await prisma.conversationTurn.findUniqueOrThrow({ where: { id: second.turnId } })).seq,
      kind: 'steer',
      placement: 'steer',
      targetTurnId: target,
    });
    const row = await prisma.conversationTurn.findUniqueOrThrow({ where: { id: second.turnId } });
    assert.deepEqual(
      { kind: row.kind, status: row.status, sendIntent: row.sendIntent, targetTurnId: row.targetTurnId, content: row.content },
      { kind: 'steer', status: 'PENDING', sendIntent: 'CURRENT_WORK', targetTurnId: target, content: 'and push it to main' },
    );
    // The queue now reads it as on its way into this turn.
    const listed = await sessions.listQueuedTurns(ownerId, w.sessionId, 'active');
    assert.deepEqual(
      listed.filter((turn) => turn.turnId !== target).map((turn) => [turn.content, turn.placement]),
      [['then update the changelog', 'queued'], ['and push it to main', 'steer']],
    );

    // The runner is handed the steer now, mid-turn; the message queued before it waits for the result.
    const handed = await dequeue(w);
    assert.equal(handed?.turnId, second.turnId);
    assert.equal(handed?.kind, 'steer');
    assert.equal(handed?.targetTurnId, target);
    assert.equal(await dequeue(w), null, 'the queued message was handed out mid-turn');
    assert.equal((await prisma.conversationTurn.findUniqueOrThrow({ where: { id: first.turnId } })).status, 'PENDING');

    // Pressed again: the same steer, nothing changed.
    const again = await sessions.steerQueuedTurn(ownerId, w.sessionId, second.turnId);
    assert.equal(again.kind, 'steer');
    assert.equal((await prisma.conversationTurn.findUniqueOrThrow({ where: { id: second.turnId } })).status, 'IN_FLIGHT');
  });

  await t.test('with no turn running there is nothing to join, and the message stays queued', async () => {
    const w = await world(ROUTING);
    const sent = await send(w, 'then update the changelog');

    const err = await sessions.steerQueuedTurn(ownerId, w.sessionId, sent.turnId).then(
      () => assert.fail('steered with nothing running'),
      (e: unknown) => e,
    );
    assert.ok(err instanceof ConflictException);
    assert.deepEqual(
      { code: reasonOf(err).code, reason: reasonOf(err).reason },
      { code: 'CURRENT_WORK_UNAVAILABLE', reason: 'NO_CURRENT_WORK' },
    );
    const row = await prisma.conversationTurn.findUniqueOrThrow({ where: { id: sent.turnId } });
    assert.deepEqual({ kind: row.kind, sendIntent: row.sendIntent, targetTurnId: row.targetTurnId }, {
      kind: 'message', sendIntent: 'NEXT_TURN', targetTurnId: null,
    });
  });

  await t.test('a runner that cannot aim a steer at one turn is never handed one', async () => {
    const w = await world([]);
    await running(w);
    const sent = await send(w, 'and push it to main');

    const err = await sessions.steerQueuedTurn(ownerId, w.sessionId, sent.turnId).then(
      () => assert.fail('steered on a runner without routing'),
      (e: unknown) => e,
    );
    assert.equal(reasonOf(err).reason, 'STEER_UNSUPPORTED');
    assert.equal((await prisma.conversationTurn.findUniqueOrThrow({ where: { id: sent.turnId } })).kind, 'message');
  });

  await t.test('after Stop, what was queued is the next instruction, not part of the stopped turn', async () => {
    const w = await world(ROUTING);
    await running(w);
    const sent = await send(w, 'and push it to main');
    // Stop without a follow-up drops what was queued; one queued after the Stop is what Steer is asked about.
    await sessions.interrupt(ownerId, w.sessionId);
    const after = await send(w, 'actually, leave main alone');

    const err = await sessions.steerQueuedTurn(ownerId, w.sessionId, after.turnId).then(
      () => assert.fail('steered into a stopping turn'),
      (e: unknown) => e,
    );
    assert.equal(reasonOf(err).reason, 'NO_CURRENT_WORK');
    assert.equal((await prisma.conversationTurn.findUniqueOrThrow({ where: { id: after.turnId } })).kind, 'message');
    assert.equal(await prisma.conversationTurn.findUnique({ where: { id: sent.turnId } }), null, 'Stop kept the queued message');
  });
});
