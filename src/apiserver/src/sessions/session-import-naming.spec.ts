import assert from 'node:assert/strict';
import { test } from 'node:test';
import { SessionsService } from './sessions.service';

/**
 * `SessionsService.nameUntitledImport` — the name an imported session gets when its transcript
 * carried no `ai-title` (Claude writes none for a `claude -p` or Agent SDK conversation). Read
 * from the first real prompt among the run events the import stored, and swapped in only while
 * the row still reads the import's placeholder.
 */

const SESSION_ID = '11111111-1111-4111-8111-111111111111';
const CLAUDE_ID = 'ae7ebd9e-f37c-494d-8017-bb4e9beffeef';
const PLACEHOLDER = 'Imported session ae7ebd9e';

function makeService(opts: { title?: string; userTexts?: unknown[]; updateCount?: number } = {}) {
  const updates: Array<{ where: Record<string, unknown>; data: Record<string, unknown> }> = [];
  const published: string[] = [];
  const prisma = {
    session: {
      findUnique: async () => ({
        id: SESSION_ID,
        ownerId: 'owner-1',
        provider: 'claude',
        providerBuiltin: true,
        model: null,
        title: opts.title ?? PLACEHOLDER,
        runtimeSessionId: CLAUDE_ID,
      }),
      updateMany: async (args: { where: Record<string, unknown>; data: Record<string, unknown> }) => {
        updates.push(args);
        return { count: opts.updateCount ?? 1 };
      },
    },
    runEvent: {
      findMany: async () => (opts.userTexts ?? []).map((text) => ({ payload: { text } })),
    },
    // beautifySessionLater's reads: a built-in engine's subscription holds no key the server may spend.
    modelProvider: { findFirst: async () => null },
    user: { findUnique: async () => ({ preferences: {} }) },
  };
  const realtime = { publishSessionUpdated: (id: string) => published.push(id) } as never;
  const service = new SessionsService(prisma as never, {} as never, realtime);
  return { service, updates, published };
}

test('an untitled import is named from the first line of its first prompt', async () => {
  delete process.env.DEEPSEEK_API_KEY;
  const h = makeService({ userTexts: ['帮我看看为什么 runner 都离线了\n日志在 /var/log'] });

  await h.service.nameUntitledImport(SESSION_ID);

  assert.equal(h.updates.length, 1);
  assert.deepEqual(h.updates[0].where, { id: SESSION_ID, title: PLACEHOLDER, titleManagedByProject: false });
  assert.equal(h.updates[0].data.title, '帮我看看为什么 runner 都离线了');
  assert.deepEqual(h.published, [SESSION_ID]);
});

test('text Claude Code put in the user turn is passed over for what the person typed', async () => {
  delete process.env.DEEPSEEK_API_KEY;
  const h = makeService({
    userTexts: [
      'Caveat: The messages below were generated by the user while running local commands.',
      '<command-name>/model</command-name>',
      '<local-command-stdout>Set model to opus</local-command-stdout>',
      '   ',
      'Fix the runner heartbeat',
    ],
  });

  await h.service.nameUntitledImport(SESSION_ID);

  assert.equal(h.updates[0]?.data.title, 'Fix the runner heartbeat');
});

test('a session renamed since, or with no prompt to read, keeps its title', async () => {
  delete process.env.DEEPSEEK_API_KEY;
  const renamed = makeService({ title: 'Runner outage', userTexts: ['Fix it'] });
  await renamed.service.nameUntitledImport(SESSION_ID);
  assert.deepEqual(renamed.updates, []);

  const wordless = makeService({ userTexts: ['<command-name>/clear</command-name>'] });
  await wordless.service.nameUntitledImport(SESSION_ID);
  assert.deepEqual(wordless.updates, []);

  const raced = makeService({ userTexts: ['Fix it'], updateCount: 0 });
  await raced.service.nameUntitledImport(SESSION_ID);
  assert.deepEqual(raced.published, [], 'a rename that landed first is not announced over');
});
