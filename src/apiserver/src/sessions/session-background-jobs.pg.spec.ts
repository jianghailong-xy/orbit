/**
 * `GET /sessions/:id/background` lists a session's runner-hosted `bg_run` jobs beside its Bash
 * background shells, agents and workflows, over real HTTP and against a real PostgreSQL.
 *
 * One live session holds, as persisted run_event rows in the shapes their producers write them:
 *   - four bg_run jobs as runner-go background_job.go reports them: the launch pair (a Bash tool_use
 *     with run_in_background and its "running in background with ID" result), then the job record,
 *     a `running` background_task at launch and one terminal background_task at its end. One is
 *     still running (a `watch`), one completed, one failed, one was killed;
 *   - a `service` job (a dev server), which is not listed: the same rule that keeps it out of
 *     Session.runningBgJobs, the "background job in flight" state;
 *   - an engine's own Bash(run_in_background) shell that completed, and one still running;
 *   - a background Agent and a Workflow that both completed.
 *
 * For each row the route returns, the spec asserts the id, kind, description (a job's label),
 * command, startedTs, endedAt (present exactly for the ended ones) and status. A job's status and
 * endedAt are read off its terminal job record: the record's status, in the shared BgShell
 * vocabulary (`completed` is `done`, as for every other row), and the time that record was stored.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/sessions/session-background-jobs.pg.spec.ts
 *
 * Not destructive: every id is generated by the run. Only the bearer check is stood in for.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { Module, ValidationPipe } from '@nestjs/common';
import { NestFactory, Reflector } from '@nestjs/core';
import { JwtService } from '@nestjs/jwt';
import { RunEventType, uuidToBase62 } from '@orbit/shared';
import { Client } from 'pg';

import { JwtAuthGuard } from '../auth/jwt-auth.guard';
import { PublicIdInterceptor } from '../common/public-id.interceptor';
import { prismaClientFor } from '../prisma/prisma-client';
import { PrismaService } from '../prisma/prisma.service';
import { assertCoordinatorPgUrlIsIsolated, verifyCoordinatorPgIdentity } from '../projects/coordinator-pg-test-safety';
import { RealtimeService } from '../realtime/realtime.service';
import { SessionTagsService } from '../session-tags/session-tags.service';
import { AutoRetryService } from './auto-retry.service';
import { MergeReceiptService } from './merge-receipt.service';
import { SessionsController } from './sessions.controller';
import { SessionsService } from './sessions.service';

const URL = process.env.COORDINATOR_PG_URL;

const LIFECYCLE = new Set(['then', 'onModuleInit', 'onApplicationBootstrap', 'onModuleDestroy',
  'beforeApplicationShutdown', 'onApplicationShutdown']);

/** A collaborator this read never reaches: any call on it is the route going somewhere it should not. */
const unreachable = (name: string): unknown =>
  new Proxy({}, {
    get: (_target, key) => {
      if (typeof key === 'symbol' || LIFECYCLE.has(key)) return undefined;
      return () => {
        throw new Error(`${name}.${key} is not part of the background list read`);
      };
    },
  });

/** A bg_run job as the runner holds it: what bg_run was given, and how it ended. */
interface RunnerJob {
  id: string;
  kind: 'job' | 'watch' | 'service';
  command: string;
  description?: string;
  /** The terminal record's status, as the runner writes it; absent while it runs. */
  ended?: { status: 'completed' | 'failed' | 'killed'; exitCode?: number };
}

const JOBS: RunnerJob[] = [
  { id: 'bgj_1a2b3c4d5e01', kind: 'watch', command: 'gh run watch 19283 --exit-status', description: 'Wait for CI on main' },
  { id: 'bgj_1a2b3c4d5e02', kind: 'job', command: 'npm test -w @orbit/apiserver', description: 'Apiserver unit tests',
    ended: { status: 'completed', exitCode: 0 } },
  { id: 'bgj_1a2b3c4d5e03', kind: 'job', command: 'docker run --rm swift:6.1 swift test', description: 'OrbitKit tests',
    ended: { status: 'failed', exitCode: 1 } },
  { id: 'bgj_1a2b3c4d5e04', kind: 'job', command: 'npm run build',
    ended: { status: 'killed' } },
];
const SERVICE: RunnerJob = { id: 'bgj_1a2b3c4d5e05', kind: 'service', command: 'vite dev --port 5173', description: 'Web dev server' };

const SHELL_DONE = 'bei75180m';
const SHELL_RUNNING = 'b7k2q9x1p';
const AGENT = 'a05fc3596d22b3d3e';
const WORKFLOW = 'w2f3yv1s8';

test('GET /sessions/:id/background lists bg_run jobs beside shells, agents and workflows, with end times', {
  skip: !URL, concurrency: 1, timeout: 120_000,
}, async (t) => {
  assertCoordinatorPgUrlIsIsolated(URL);
  const sql = new Client({ connectionString: URL, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma = prismaClientFor(URL!);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });

  const ownerId = randomUUID();
  const bearer = `bearer-${ownerId}`;
  const sessions = new SessionsService(
    prisma as unknown as PrismaService,
    unreachable('queue') as never,
    unreachable('realtime') as never,
  );

  @Module({
    controllers: [SessionsController],
    providers: [
      { provide: SessionsService, useValue: sessions },
      { provide: PrismaService, useValue: prisma },
      { provide: RealtimeService, useValue: unreachable('realtime') },
      { provide: SessionTagsService, useValue: unreachable('tags') },
      { provide: MergeReceiptService, useValue: unreachable('mergeReceipts') },
      { provide: AutoRetryService, useValue: unreachable('autoRetry') },
      JwtAuthGuard,
      Reflector,
      {
        provide: JwtService,
        useValue: {
          verifyAsync: async (token: string) => {
            if (token !== bearer) throw new Error('not a bearer this run issued');
            return { sub: ownerId, email: `${ownerId}@background-jobs.invalid` };
          },
        },
      },
    ],
  })
  class BackgroundJobsModule {}

  const app = await NestFactory.create(BackgroundJobsModule, { logger: false, abortOnError: false });
  app.setGlobalPrefix('api');
  app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
  app.useGlobalInterceptors(new PublicIdInterceptor());
  await app.listen(0, '127.0.0.1');
  t.after(() => app.close());
  const base = await app.getUrl();

  // ── fixtures ──────────────────────────────────────────────────────────────────────────────────
  await sql.query(`INSERT INTO "user"("id","email","name","password_hash") VALUES ($1,$2,'owner','x')`, [
    ownerId, `background-jobs-${ownerId}@background-jobs.invalid`,
  ]);
  const sessionId = randomUUID();
  await sql.query(
    `INSERT INTO "session"("id","title","prompt","owner_id","creator_id","turn_state","dispatch_origin","created_at","updated_at")
     VALUES ($1,'background jobs','p',$2,$2,NULL,'USER',now(),now())`,
    [sessionId, ownerId],
  );

  // Every event at its own whole second, so each row's start and end are distinct, known instants.
  const t0 = Date.parse('2026-11-17T02:40:00.000Z');
  let seq = 0;
  /** Stores one event as the runner door would, and answers the instant it was stored at. */
  async function event(type: string, payload: unknown): Promise<string> {
    seq += 1;
    const at = new Date(t0 + seq * 1000).toISOString();
    await sql.query(
      `INSERT INTO "run_event"("id","session_id","seq","type","payload","created_at") VALUES ($1,$2,$3,$4,$5,$6)`,
      [randomUUID(), sessionId, seq, type, JSON.stringify(payload), at],
    );
    return at;
  }
  const output = (id: string) => `/root/.orbit/runs/spec/tasks/${id}.output`;

  /** runner-go background_job.go: the launch pair and the `running` record (runningPayload). */
  async function launchJob(job: RunnerJob): Promise<string> {
    const input: Record<string, unknown> = { command: job.command, run_in_background: true };
    if (job.description) input.description = job.description;
    const at = await event(RunEventType.TOOL_USE, { id: job.id, name: 'Bash', input });
    await event(RunEventType.TOOL_RESULT, {
      toolUseId: job.id,
      content: `Command running in background with ID: ${job.id}. Output is being written to: ${output(job.id)}. `
        + 'Read it with mcp__orbit__bg_output.',
    });
    await event(RunEventType.BACKGROUND_TASK, {
      shellId: job.id, toolUseId: job.id, status: 'running', kind: job.kind,
      command: job.command, outputPath: output(job.id), idleMs: 0,
    });
    return at;
  }
  /** runner-go background_job.go endPayload: the one terminal record. */
  async function endJob(job: RunnerJob): Promise<string> {
    const ended = job.ended!;
    const payload: Record<string, unknown> = {
      shellId: job.id, toolUseId: job.id, status: ended.status, kind: job.kind, command: job.command,
      summary: ended.status === 'killed' ? `Background ${job.kind} was killed`
        : `Background ${job.kind} completed (exit code ${ended.exitCode})`,
      output: 'tail of the output\n', outputPath: output(job.id),
    };
    if (ended.exitCode !== undefined) payload.exitCode = ended.exitCode;
    if (ended.status === 'killed') payload.reason = 'killed with bg_kill';
    return event(RunEventType.BACKGROUND_TASK, payload);
  }
  /** An engine's own Bash(run_in_background), as Claude Code's stream carries it. */
  async function launchShell(shellId: string, toolUseId: string, command: string, description: string): Promise<string> {
    const at = await event(RunEventType.TOOL_USE, {
      id: toolUseId, name: 'Bash', input: { command, description, run_in_background: true },
    });
    await event(RunEventType.TOOL_RESULT, {
      toolUseId,
      content: `Command running in background with ID: ${shellId}. Output is being written to: ${output(shellId)}`,
    });
    return at;
  }

  const started = new Map<string, string>();
  const endedAt = new Map<string, string>();
  for (const job of JOBS) started.set(job.id, await launchJob(job));
  started.set(SERVICE.id, await launchJob(SERVICE));
  started.set(SHELL_DONE, await launchShell(SHELL_DONE, 'toolu_shell_done', 'npm run lint', 'Lint the tree'));
  started.set(SHELL_RUNNING, await launchShell(SHELL_RUNNING, 'toolu_shell_live', 'tail -f server.log', 'Follow the log'));
  started.set(AGENT, await event(RunEventType.TOOL_USE, {
    id: 'toolu_agent', name: 'Agent', input: { description: 'Deep-read the importer', run_in_background: true },
  }));
  await event(RunEventType.TOOL_RESULT, {
    toolUseId: 'toolu_agent',
    content: [{ type: 'text', text: `Async agent launched successfully. agentId: ${AGENT}` }],
  });
  started.set(WORKFLOW, await event(RunEventType.TOOL_USE, { id: 'toolu_wf', name: 'Workflow', input: {} }));
  await event(RunEventType.TOOL_RESULT, {
    toolUseId: 'toolu_wf',
    content: `Workflow launched in background. Task ID: ${WORKFLOW}\nSummary: Review the diff\nTranscript dir: /tmp/wf`,
  });
  for (const job of JOBS) if (job.ended) endedAt.set(job.id, await endJob(job));
  endedAt.set(SHELL_DONE, await event(RunEventType.BACKGROUND_TASK, {
    toolUseId: 'toolu_shell_done', shellId: SHELL_DONE, status: 'completed',
  }));
  endedAt.set(AGENT, await event(RunEventType.BACKGROUND_TASK, { toolUseId: 'toolu_agent', shellId: AGENT, status: 'completed' }));
  endedAt.set(WORKFLOW, await event(RunEventType.BACKGROUND_TASK, { toolUseId: 'toolu_wf', shellId: WORKFLOW, status: 'completed' }));

  // ── the read ──────────────────────────────────────────────────────────────────────────────────
  const response = await fetch(`${base}/api/sessions/${uuidToBase62(sessionId)}/background`, {
    headers: { authorization: `Bearer ${bearer}` },
  });
  const text = await response.text();
  assert.equal(response.status, 200, text.slice(0, 400));
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const rows: any[] = JSON.parse(text);
  const fields = (row: Record<string, unknown>) => ({
    shellId: row.shellId, kind: row.kind, description: row.description, command: row.command,
    startedTs: row.startedTs, endedAt: row.endedAt, status: row.status,
  });
  const got = new Map(rows.map((row) => [row.shellId as string, fields(row)]));

  /** The shared vocabulary for a terminal record's status (background.ts terminalFromStatus). */
  const vocabulary = { completed: 'done', failed: 'failed', killed: 'killed' } as const;

  // Every bg_run job: its values are the runner's job record.
  for (const job of JOBS) {
    assert.deepEqual(got.get(job.id), {
      shellId: job.id,
      kind: 'job',
      description: job.description,
      command: job.command,
      startedTs: started.get(job.id),
      endedAt: job.ended ? endedAt.get(job.id) : undefined,
      status: job.ended ? vocabulary[job.ended.status] : 'running',
    }, `bg_run job ${job.id}`);
    assert.equal('endedAt' in rows.find((row) => row.shellId === job.id), job.ended !== undefined,
      `${job.id}: endedAt is present exactly when the job ended`);
  }
  // The literal answers, so the mapping above cannot hide a mistake.
  assert.deepEqual(JOBS.map((job) => [got.get(job.id)?.status, got.get(job.id)?.endedAt]), [
    ['running', undefined],
    ['done', '2026-11-17T02:40:24.000Z'],
    ['failed', '2026-11-17T02:40:25.000Z'],
    ['killed', '2026-11-17T02:40:26.000Z'],
  ]);

  // A service is never listed.
  assert.equal(got.has(SERVICE.id), false, 'a service job is not listed');

  // The engine's own shells, the agent and the workflow: ended ones carry an end time too.
  assert.deepEqual(got.get(SHELL_DONE), {
    shellId: SHELL_DONE, kind: 'shell', description: 'Lint the tree', command: 'npm run lint',
    startedTs: started.get(SHELL_DONE), endedAt: endedAt.get(SHELL_DONE), status: 'done',
  });
  assert.deepEqual(got.get(SHELL_RUNNING), {
    shellId: SHELL_RUNNING, kind: 'shell', description: 'Follow the log', command: 'tail -f server.log',
    startedTs: started.get(SHELL_RUNNING), endedAt: undefined, status: 'running',
  });
  assert.deepEqual(got.get(AGENT), {
    shellId: AGENT, kind: 'agent', description: 'Deep-read the importer', command: '',
    startedTs: started.get(AGENT), endedAt: endedAt.get(AGENT), status: 'done',
  });
  assert.deepEqual(got.get(WORKFLOW), {
    shellId: WORKFLOW, kind: 'workflow', description: 'Review the diff', command: '',
    startedTs: started.get(WORKFLOW), endedAt: endedAt.get(WORKFLOW), status: 'done',
  });

  // Nothing else, in launch order.
  assert.deepEqual(rows.map((row) => row.shellId), [...JOBS.map((job) => job.id), SHELL_DONE, SHELL_RUNNING, AGENT, WORKFLOW]);
});
