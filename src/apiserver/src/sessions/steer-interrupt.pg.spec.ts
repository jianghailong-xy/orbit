/**
 * Stop pressed while a message sent into the running turn is still waiting to be read, against a real
 * PostgreSQL (owner, 2026-10-16: option A).
 *
 * A steer the engine has not read when somebody stops the turn it was sent into is not delivered, and
 * it does not come back as a turn of its own afterwards: re-filed, it would run straight after the
 * Stop, the one thing the person just asked not to happen. Whoever still wants it sends it again, or
 * takes it back before stopping (steer-withdraw.pg.spec.ts). Two timings, one outcome:
 *
 *   - PENDING: the runner had not taken it yet, and the interrupt itself writes it off
 *     (`SessionsService.interrupt`).
 *   - IN_FLIGHT: the runner had written it into the engine, which had not read it — the steer line
 *     says "Waiting to be read". The stopped turn's completion writes off whatever the runner did not
 *     settle, and the runner's own report about the steer comes to the same answer whichever runner
 *     sends it: a current one reports it undelivered, and one older than this rule hands it back
 *     (`steer_requeue`), which the control plane no longer re-files once a Stop overtook its turn.
 *
 * A message sent AFTER the Stop is the person's next instruction, not part of the stopped work: it is
 * never steered into the stopping turn, and it runs as the next turn once that one is over.
 *
 * The runner's side is played by hand: what it polls, the events it writes and what it reports.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/steer-interrupt.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { test } from 'node:test';

import { ConflictException } from '@nestjs/common';
import { type PrismaClient, RunnerStatus, RunStatus, SessionDispatchOrigin, SessionRunSource } from '@prisma/client';
import {
  RunEventType,
  RunStatus as SharedRunStatus,
  SESSION_CURRENT_WORK_ROUTING_V1,
  TURN_COMPLETE_STEER_REQUEUE,
} from '@orbit/shared';
import { Client } from 'pg';

import { sha256 } from '../common/crypto.util';
import { prismaClientFor } from '../prisma/prisma-client';
import { PrismaService } from '../prisma/prisma.service';
import {
  assertCoordinatorPgUrlIsIsolated,
  verifyCoordinatorPgIdentity,
} from '../projects/coordinator-pg-test-safety';
import { RunnerApiController } from '../runner-api/runner-api.controller';
import { CURRENT_WORK_INTERRUPTED } from './current-work-delivery';
import { SessionsService } from './sessions.service';

declare global {
  interface BigInt { toJSON(): string; }
}
// `main.ts` installs this before it creates the app; a session row carries BIGINT columns.
BigInt.prototype.toJSON = function toJSON(this: bigint): string {
  return this.toString();
};

const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;
const ROUTING = [SESSION_CURRENT_WORK_ROUTING_V1];
/** What a current runner says about a steer whose turn was stopped first (runner-go claude_delivery.go). */
const STOPPED = 'the turn was interrupted by Stop before the engine read this message';

/** A collaborator whose every method answers nothing: the broadcasts a turn's enqueue fires. */
const silent = (): unknown =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

test('a message waiting to be read when its turn is stopped is not delivered, and nothing runs after the Stop', {
  skip, concurrency: 1, timeout: 600_000,
}, async (t) => {
  const url = URL!;
  assertCoordinatorPgUrlIsIsolated(url);
  const sql = new Client({ connectionString: url, connectionTimeoutMillis: 5_000 });
  await sql.connect();
  await verifyCoordinatorPgIdentity(sql);
  const prisma: PrismaClient = prismaClientFor(url);
  t.after(async () => {
    await prisma.$disconnect().catch(() => undefined);
    await sql.end().catch(() => undefined);
  });
  const db = prisma as unknown as PrismaService;

  const ownerId = randomUUID();
  await prisma.user.create({
    data: { id: ownerId, email: `steer-interrupt-${ownerId}@runner-door.invalid`, name: 'The account owner', passwordHash: 'x' },
  });

  /** A machine that declared routing-v1, its workspace, and a Claude session on it, parked. */
  async function world() {
    const runnerId = randomUUID();
    const workspaceId = randomUUID();
    const sessionId = randomUUID();
    await prisma.runner.create({
      data: {
        id: runnerId, ownerId, name: `machine ${runnerId}`, tokenHash: sha256(`token-${runnerId}`),
        status: RunnerStatus.ONLINE, lastHeartbeatAt: new Date(), capabilities: ROUTING, capabilitiesReportedAt: new Date(),
      },
    });
    await prisma.workspace.create({ data: { id: workspaceId, ownerId, runnerId, name: 'orbit-worker', enabled: true } });
    await prisma.session.create({
      data: {
        id: sessionId, ownerId, creatorId: ownerId, workspaceId, assignedRunnerId: runnerId,
        title: 'fix the export', prompt: 'fix the export', provider: 'claude', status: RunStatus.AWAITING_INPUT,
        numTurns: 1, startedAt: new Date(), runtimeSessionId: `runtime-${sessionId}`,
        dispatchOrigin: SessionDispatchOrigin.USER, runSource: SessionRunSource.MANUAL,
      },
    });
    return { runnerId, sessionId, seq: 0 };
  }
  type World = Awaited<ReturnType<typeof world>>;

  const realtime = silent();
  const queue = { notifySessionQueued: () => undefined };
  const sessions = new SessionsService(db, queue as never, realtime as never);
  const api = new RunnerApiController(
    db,
    queue as never,
    realtime as never,
    silent() as never,
    {} as never,
    { expand: async (_owner: string, content?: string) => content } as never,
    { appendFor: async (_tx: unknown, _id: string, content?: string) => content } as never,
    undefined,
    undefined,
    undefined,
    undefined,
    sessions,
  );
  type Dequeue = (
    sessionId: string, runnerId: string, leaseGeneration: string | null, acceptsSteer: boolean,
    declaredCapabilities: readonly string[],
  ) => Promise<Record<string, unknown> | null>;
  /** One poll of the inbox, by a runner that writes steers into Claude and declared routing-v1. */
  const dequeue = (w: World) =>
    (api as unknown as { dequeueTurn: Dequeue }).dequeueTurn.call(api, w.sessionId, w.runnerId, null, true, ROUTING);

  /** The runner's events, through the real ingest, each filed under the turn running when it was said. */
  async function say(w: World, turnId: string, type: RunEventType, payload: Record<string, unknown>) {
    w.seq += 1;
    await api.events({ id: w.runnerId } as never, w.sessionId, {
      events: [{ seq: w.seq, type, ts: new Date().toISOString(), turnId, payload }],
    } as never);
  }

  /** The person's message, claimed and handed to the engine, which starts on it: the turn that gets stopped. */
  async function running(w: World): Promise<string> {
    const sent = await sessions.createTurn(ownerId, w.sessionId, {
      clientTurnId: randomUUID(), content: 'run the full test suite', intent: 'NEXT_TURN',
    } as never) as { turnId: string };
    await prisma.$transaction(async (tx) => {
      await tx.$executeRaw`SELECT set_config('orbit.claim_reads_session_engine', '1', true)`;
      await tx.session.update({ where: { id: w.sessionId }, data: { status: RunStatus.RUNNING } });
    });
    const handed = await dequeue(w);
    assert.equal(handed?.turnId, sent.turnId, 'the running message was not the one handed out');
    await say(w, sent.turnId, RunEventType.USER, { text: 'run the full test suite', delivery: 'enqueued' });
    await say(w, sent.turnId, RunEventType.ASSISTANT, { text: 'running the suite; this takes a while' });
    return sent.turnId;
  }

  /** A message typed while that turn runs: filed as a CURRENT_WORK steer aimed at it. */
  async function steer(w: World, target: string, words = 'and skip the slow e2e specs'): Promise<string> {
    const sent = await sessions.createTurn(ownerId, w.sessionId, {
      clientTurnId: randomUUID(), content: words, intent: 'CURRENT_WORK',
    } as never) as { turnId: string; kind: string; targetTurnId?: string };
    assert.equal(sent.kind, 'steer', `a message sent mid-turn was filed as a ${sent.kind}`);
    assert.equal(sent.targetTurnId, target);
    return sent.turnId;
  }

  /** The runner takes the steer and writes it into the engine, which has not read it: "Waiting to be read". */
  async function waitingToBeRead(w: World, target: string, steerId: string) {
    const handed = await dequeue(w);
    assert.equal(handed?.turnId, steerId, 'the steer was not handed to the runner');
    assert.equal(handed?.steerRequeue, true);
    await say(w, steerId, RunEventType.USER, {
      text: 'and skip the slow e2e specs', steer: true, delivery: 'enqueued', withdrawable: true,
    });
    await say(w, target, RunEventType.USER_DELIVERY, { turnId: steerId, delivery: 'written' });
  }

  /** Stop: the interrupt is filed, and the runner takes it to the engine. */
  async function stop(w: World) {
    await sessions.interrupt(ownerId, w.sessionId);
    const handed = await dequeue(w);
    assert.equal(handed?.kind, 'interrupt', 'the Stop was not handed to the runner');
  }

  /** The stopped turn ends the way an interrupted Claude turn does. */
  async function endInterrupted(w: World, target: string) {
    await say(w, target, RunEventType.INTERRUPT, { requestId: `interrupt-${target}` });
    await api.turnComplete({ id: w.runnerId } as never, w.sessionId, {
      turnId: target, status: SharedRunStatus.INTERRUPTED, subtype: 'error_during_execution',
      result: 'interrupted', numTurns: 1, costUsd: 0,
    } as never);
  }

  /** What a current runner reports for a steer its stopped turn ended without reading. */
  async function reportedNotDelivered(w: World, target: string, steerId: string) {
    await say(w, target, RunEventType.USER_DELIVERY, {
      turnId: steerId, delivery: 'failed', reason: STOPPED, retryable: true,
    });
    await api.turnComplete({ id: w.runnerId } as never, w.sessionId, {
      turnId: steerId, status: SharedRunStatus.FAILED, subtype: 'steer',
      result: `steer not delivered to the engine: ${STOPPED}`,
    } as never);
  }

  /** What a runner older than this rule does with the same steer: hands it back to run as its own turn. */
  async function handedBack(w: World, target: string, steerId: string) {
    await say(w, target, RunEventType.USER_DELIVERY, { turnId: steerId, delivery: 'requeued' });
    await api.turnComplete({ id: w.runnerId } as never, w.sessionId, {
      turnId: steerId, status: SharedRunStatus.SUCCEEDED, subtype: TURN_COMPLETE_STEER_REQUEUE,
    } as never);
  }

  const turnRow = (id: string) => prisma.conversationTurn.findUniqueOrThrow({ where: { id } });
  const listed = async (w: World) =>
    (await sessions.listQueuedTurns(ownerId, w.sessionId, 'active')) as unknown as Array<Record<string, unknown>>;

  /** The steer is a receipt that says it was not delivered because of the Stop, and still a steer. */
  async function notDelivered(steerId: string) {
    const row = await turnRow(steerId);
    assert.deepEqual(
      { kind: row.kind, status: row.status, deliveryStatus: row.deliveryStatus, code: row.deliveryFailureCode },
      { kind: 'steer', status: 'ANSWERED', deliveryStatus: 'FAILED', code: CURRENT_WORK_INTERRUPTED },
    );
  }

  /** Nothing starts after the Stop: no turn waits to run, the session is parked, and the inbox is empty. */
  async function nothingRunsAfterTheStop(w: World) {
    assert.equal(
      await prisma.conversationTurn.count({
        where: { sessionId: w.sessionId, kind: { in: ['message', 'shell'] }, status: { in: ['PENDING', 'IN_FLIGHT'] } },
      }),
      0,
      'a turn is waiting to run after the Stop',
    );
    assert.equal((await prisma.session.findUniqueOrThrow({ where: { id: w.sessionId } })).status, RunStatus.AWAITING_INPUT);
    assert.equal(await dequeue(w), null, 'the inbox handed something out after the Stop');
  }

  await t.test('PENDING: a steer the runner had not taken yet is written off by the Stop itself', async () => {
    const w = await world();
    const target = await running(w);
    const steerId = await steer(w, target);

    await stop(w);
    await notDelivered(steerId);
    await endInterrupted(w, target);

    await notDelivered(steerId);
    await nothingRunsAfterTheStop(w);
    // It never reached the transcript, so the queue's own line is where it says so.
    const row = (await listed(w)).find((listedRow) => listedRow.turnId === steerId);
    assert.deepEqual(
      [row?.placement, row?.delivery, row?.deliveryCode],
      ['steer', 'failed', CURRENT_WORK_INTERRUPTED],
    );
  });

  await t.test('IN_FLIGHT, a current runner: it reports the steer undelivered, and the receipt names the Stop', async () => {
    const w = await world();
    const target = await running(w);
    const steerId = await steer(w, target);
    await waitingToBeRead(w, target, steerId);

    await stop(w);
    // The interrupt leaves a steer the runner holds alone: the engine may still read it before it stops.
    assert.deepEqual(
      [(await turnRow(steerId)).status, (await turnRow(steerId)).deliveryStatus],
      ['IN_FLIGHT', null],
    );
    await reportedNotDelivered(w, target, steerId);
    await endInterrupted(w, target);

    await notDelivered(steerId);
    await nothingRunsAfterTheStop(w);
    // The runner's own `failed` already says so in the transcript; the receipt is not listed twice.
    assert.ok(!(await listed(w)).some((listedRow) => listedRow.turnId === steerId));
  });

  await t.test('IN_FLIGHT, a runner older than this rule: the steer it hands back is not re-filed', async () => {
    const w = await world();
    const target = await running(w);
    const steerId = await steer(w, target);
    await waitingToBeRead(w, target, steerId);

    await stop(w);
    await handedBack(w, target, steerId);
    // Settled as soon as the runner hands it back, before the stopped turn's own completion.
    await notDelivered(steerId);
    await endInterrupted(w, target);

    await notDelivered(steerId);
    await nothingRunsAfterTheStop(w);
    // The runner said "requeued", which is no longer true: the receipt the clients read says what is.
    const row = (await listed(w)).find((listedRow) => listedRow.turnId === steerId);
    assert.deepEqual(
      [row?.placement, row?.delivery, row?.deliveryCode],
      ['steer', 'failed', CURRENT_WORK_INTERRUPTED],
    );
  });

  await t.test('IN_FLIGHT, nothing heard of the steer: the stopped turn\'s completion writes it off', async () => {
    // The dequeue committed and its response was lost: the runner never had it, so nothing reports it.
    const w = await world();
    const target = await running(w);
    const steerId = await steer(w, target);
    assert.equal((await dequeue(w))?.turnId, steerId);

    await stop(w);
    await endInterrupted(w, target);

    await notDelivered(steerId);
    await nothingRunsAfterTheStop(w);
  });

  await t.test('a Stop that loses the race to the turn\'s own end still overtakes the unread steer', async () => {
    // The turn finished on its own before the interrupt reached the engine. The steer was still waiting
    // to be read when the person pressed Stop, which is what decides it.
    const w = await world();
    const target = await running(w);
    const steerId = await steer(w, target);
    await waitingToBeRead(w, target, steerId);
    const unheard = await steer(w, target, 'and post the summary');
    assert.equal((await dequeue(w))?.turnId, unheard);

    await stop(w);
    // The runner's fence at a normal end hands an unread steer back, from either runner.
    await handedBack(w, target, steerId);
    await say(w, target, RunEventType.ASSISTANT, { text: 'the suite is green' });
    await api.turnComplete({ id: w.runnerId } as never, w.sessionId, {
      turnId: target, status: SharedRunStatus.SUCCEEDED, subtype: 'success', numTurns: 1, costUsd: 0,
    } as never);

    await notDelivered(steerId);
    await notDelivered(unheard);
    await nothingRunsAfterTheStop(w);
  });

  await t.test('a message sent after the Stop waits for the next turn instead of joining the stopping one', async () => {
    // Typed after pressing Stop, while the stopped turn is still winding down: the composer sends it as
    // CURRENT_WORK, and the turn it would join is the one being stopped.
    const w = await world();
    const target = await running(w);
    await stop(w);

    const clientTurnId = randomUUID();
    const words = 'now write the release notes instead';
    const refusal = await sessions.createTurn(ownerId, w.sessionId, {
      clientTurnId, content: words, intent: 'CURRENT_WORK',
    } as never).then(() => assert.fail('it was steered into the turn being stopped'), (error: unknown) => error);
    assert.ok(refusal instanceof ConflictException);
    const refused = refusal.getResponse() as { code?: string; reason?: string };
    assert.deepEqual([refused.code, refused.reason], ['CURRENT_WORK_UNAVAILABLE', 'NO_CURRENT_WORK']);
    // The web composer sends the same message again for the next turn (composerSendState.ts).
    const sent = await sessions.createTurn(ownerId, w.sessionId, {
      clientTurnId, content: words, intent: 'NEXT_TURN',
    } as never) as { turnId: string; kind: string; placement: string };
    assert.deepEqual([sent.kind, sent.placement], ['message', 'queued']);

    await endInterrupted(w, target);

    // It runs as the next turn, and nothing says it was not delivered.
    const row = await turnRow(sent.turnId);
    assert.deepEqual(
      [row.kind, row.sendIntent, row.targetTurnId, row.status, row.deliveryStatus],
      ['message', 'NEXT_TURN', null, 'PENDING', null],
    );
    assert.equal((await prisma.session.findUniqueOrThrow({ where: { id: w.sessionId } })).status, RunStatus.RUNNING);
    assert.equal((await dequeue(w))?.turnId, sent.turnId, 'the message sent after the Stop is not the next turn');
    assert.ok(!(await listed(w)).some((listedRow) => listedRow.turnId === sent.turnId && listedRow.delivery != null));
  });

  await t.test('without a Stop, a steer the runner hands back unread still runs as the next turn', async () => {
    const w = await world();
    const target = await running(w);
    const steerId = await steer(w, target);
    await waitingToBeRead(w, target, steerId);

    await handedBack(w, target, steerId);
    await say(w, target, RunEventType.ASSISTANT, { text: 'the suite is green' });
    await api.turnComplete({ id: w.runnerId } as never, w.sessionId, {
      turnId: target, status: SharedRunStatus.SUCCEEDED, subtype: 'success', numTurns: 1, costUsd: 0,
    } as never);

    const row = await turnRow(steerId);
    assert.deepEqual([row.kind, row.status, row.deliveryStatus], ['message', 'PENDING', null]);
    assert.equal((await prisma.session.findUniqueOrThrow({ where: { id: w.sessionId } })).status, RunStatus.RUNNING);
    assert.equal((await dequeue(w))?.turnId, steerId, 'the re-filed message is not the next turn');
  });
});
