  /** Everything a door could change, as it stands. */
  async function snapshot(stop: Stop): Promise<string> {
    const task = await prisma.task.findUnique({
      where: { id: stop.taskId },
      select: { status: true, verdict: true, verdictRevision: true, deliveredSha: true, updatedAt: true },
    });
    const run = await prisma.session.findUniqueOrThrow({
      where: { id: stop.run },
      select: { status: true, endReason: true, completedAt: true, deletedAt: true, cancelRequestedAt: true, taskId: true },
    });
    const turns = await prisma.conversationTurn.count({ where: { sessionId: stop.run } });
    const decisions = await prisma.taskEvidenceDecision.count({ where: { taskId: stop.taskId } });
    const records = await prisma.taskOwnerConfirmationReviewRecord.count({ where: { taskId: stop.taskId } });
    return JSON.stringify({ task, run, turns, decisions, records });
  }

