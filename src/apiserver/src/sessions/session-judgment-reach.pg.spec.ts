/**
 * The answers a session gives about a run's work end that run or give it a turn, so a session held back from doing either to a
 * run is held back from doing it this way too, over real HTTP and a real PostgreSQL. The table is the one in session-reach.ts:
 *
 *   | The caller's stored mode       | Run no wider | Run wider, directly related | Run wider, unrelated |
 *   |--------------------------------|--------------|-----------------------------|----------------------|
 *   | Auto, Bypass                   | allowed      | allowed                     | allowed              |
 *   | Default, Accept Edits, Don't Ask | allowed    | allowed                     | refused              |
 *   | Plan                           | allowed      | refused                     | refused              |
 *
 * Every cell at every door: `task_evidence_decide` CONFIRM and SEND_BACK, `task_update {verdict}` and `task_confirmation_return`.
 *
 * Besides the table:
 *   - each direct relation, and what looks like one and is not;
 *   - only what the door would end or give a turn to is asked: a run that has ended, a write that ends nothing, go on as they did;
 *   - every refusal the door already had comes first, in its own words, and so does a version already answered;
 *   - a run of a verification task takes the two doors that carry words only as `session_send` does;
 *   - a stored mode that is null reads as the account's default, and a mode that runs as Bypass on its engine counts as Bypass;
 *   - the words of each refusal, what the refused reviewer is told to do instead, and that doing it works;
 *   - what the two blocks say about who sent them, in the words the session message block uses;
 *   - a person's own door, a credential with no session in it, and a session acting on itself are not held.
 *
 *   bash scripts/run-pg-spec.sh src/apiserver/src/sessions/session-judgment-reach.pg.spec.ts
 *
 * Not destructive: every id is generated by the run.
 */
