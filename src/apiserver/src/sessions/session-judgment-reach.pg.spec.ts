/** Whether the table lets a caller of this tier through in this cell. */
function allowed(tier: 'free' | 'asks' | 'plan', cell: Cell): boolean {
  if (tier === 'free' || cell === 'run no wider') return true;
  return tier === 'asks' && cell === 'run wider, related';
}

