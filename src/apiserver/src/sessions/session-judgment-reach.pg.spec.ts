const silent = (): unknown =>
  new Proxy({}, { get: (_target, key) => (key === 'then' ? undefined : () => undefined) });

/** A service lent to the door whole: an instance a module owns gets its onModuleInit, which starts the sweeps. */
function lent<T extends object>(service: T): T {
  return new Proxy(service, {
    get(target, key) {
      if (key === 'onModuleInit' || key === 'onModuleDestroy' || key === 'then') return undefined;
      const value = (target as Record<string | symbol, unknown>)[key];
      return typeof value === 'function' ? (value as (...args: unknown[]) => unknown).bind(target) : value;
    },
  }) as T;
}

