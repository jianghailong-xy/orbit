  // ── the two blocks ───────────────────────────────────────────────────────────────────────────
  /** What the run is handed, as it stands: the send-back's turn is written whole, and the return's is rendered from its record. */
  async function blockOf(door: Door, stop: Stop): Promise<string> {
    if (door === SEND_BACK) return (await sentBackTurn(stop))?.content ?? '';
    const turn = await returnTurn(stop);
    return turn ? queuedConfirmationReviewContent(prisma as never, turn.clientTurnId) : '';
  }
  /** The sentence, as the session message block has it for these two sessions. */
  function sessionBlockSentence(callerMode: string, recipientMode: string, engine: string | null = 'claude'): string {
    const block = sessionMessageBlock(
      { id: randomUUID(), title: 'x', taskId: null, workspace: null, mode: callerMode, engine: 'claude' },
      null,
      { mode: recipientMode, engine },
    );
    const line = block.split('\n').find((each) => SENTENCE.test(each));
    assert.ok(line, `the session block says it: ${block}`);
    return line;
  }
  for (const door of [SEND_BACK, RETURN]) {
    await t.test(`${door.name}: the block names the narrower session and its mode, and says what the session message block says`, async () => {
      const { from, stop } = await RELATIONS['the session that filed the task']!(door, 'default', 'auto');
      assertWent(await door.call(stop, from), door.name);
      const block = await blockOf(door, stop);
      assert.ok(block.includes(`from-session="${uuidToBase62(from)}"`), block);
      assert.ok(block.includes('from-mode="default"'), block);
      assert.ok(block.includes(sessionBlockSentence('default', 'auto')), block);
    });

    await t.test(`${door.name}: the block says what the run really runs as, as the session message block does`, async () => {
      const from = await sessionIn('dontAsk');
      const stop = await door.stage('auto', { creatorSessionId: from }, { engine: 'kimi' });
      await door.bind(stop, from);
      assertWent(await door.call(stop, from), door.name);
      const block = await blockOf(door, stop);
      assert.ok(block.includes(sessionBlockSentence('dontAsk', 'auto', 'kimi')), block);
      assert.match(block, /runs as bypassPermissions/);
    });

    await t.test(`${door.name}: a sender no narrower is named with its mode, and the sentence is not there`, async () => {
      for (const [callerMode, runMode] of [['auto', 'auto'], ['default', 'default'], ['plan', 'plan'], ['auto', 'default']] as const) {
        const { from, stop } = await RELATIONS['the session that filed the task']!(door, callerMode, runMode);
        assertWent(await door.call(stop, from), `${door.name}, ${callerMode} to ${runMode}`);
        const block = await blockOf(door, stop);
        assert.ok(block.includes(`from-session="${uuidToBase62(from)}"`), block);
        assert.ok(block.includes(`from-mode="${callerMode}"`), block);
        assert.doesNotMatch(block, SENTENCE);
      }
    });
  }
