  /** A session of a verifier's own run, or a conversation it opened, writes that verifier as itself: only runs of other tasks are refused. */
  const refusedAsARun = (door: Door, relation: string): boolean =>
    door.fromRun !== null && RUNS_ITSELF.has(relation) && !(door === VERDICT && relation === 'a child of the run');

