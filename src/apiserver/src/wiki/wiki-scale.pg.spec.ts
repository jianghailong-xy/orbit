interface Answer {
  status: number;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  body: any;
  ms: number;
}

/** One owner-door changeset, timed from the request to the answer — which comes after the commit. */
async function propose(h: Harness, owner: Account, spaceId: string, body: Record<string, unknown>): Promise<Answer> {
  const started = performance.now();
  const response = await fetch(`${h.base}/api/wiki/spaces/${spaceId}/changesets`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: `Bearer ${owner.bearer}` },
    body: JSON.stringify({ rationale: 'the near-neighbour lookup at scale', ...body }),
  });
  const text = await response.text();
  const ms = performance.now() - started;
  let parsed: unknown = null;
  try {
    parsed = text ? JSON.parse(text) : null;
  } catch {
    parsed = { unparsed: text };
  }
  return { status: response.status, body: parsed, ms };
}

interface Similar {
  id: string;
  score: number;
  rejectedReason: string | null;
}

/** An op's `similar[]` as raw ids — the door answers in public ids — with the score and the reason. */
function similarOf(answer: Answer, seq = 0): Similar[] {
  assert.equal(answer.status, 200, `the owner's changeset: answered ${answer.status} ${JSON.stringify(answer.body)}`);
  const op = (answer.body.ops as Array<{ status: string; similar?: Array<Record<string, unknown>> }>)[seq];
  assert.notEqual(op.status, 'refused', `op ${seq} was refused: ${JSON.stringify(op)}`);
  return (op.similar ?? []).map((s) => ({
    id: toUuid(String(s.id)),
    score: Number(s.score),
    rejectedReason: (s.rejectedReason as string | undefined) ?? null,
  }));
}

