// ── the lookup, before 0313 ─────────────────────────────────────────────────────────────────────

/**
 * The lookup as it stood before 0313, word for word (commit 1f64da2cc, `nearNeighbours`), with the
 * template's parameters numbered: $1 the draft's text, $2 the owner, $3 the space, $4 the excluded
 * entry. The "before" that `similar[]` is held to.
 */
const NEIGHBOURS_BEFORE_0313 = `
      SELECT e."id" AS "id",
             e."kind" AS "kind",
             e."title" AS "title",
             e."status" AS "status",
             e."trust" AS "trust",
             similarity(wiki_entry_search_text(e."title", e."summary", e."aliases", e."fields"), $1)::float8 AS "score",
             (SELECT o."decision_reason"
                FROM "wiki_changeset_op" o
               WHERE o."result_entry_id" = e."id" AND o."decision" = 'rejected'
               ORDER BY o."decided_at" DESC NULLS LAST
               LIMIT 1) AS "rejectedReason"
        FROM "wiki_entry" e
       WHERE e."owner_id" = $2::uuid
         AND e."space_id" = $3::uuid
         AND ($4::uuid IS NULL OR e."id" <> $4::uuid)
         AND wiki_entry_search_text(e."title", e."summary", e."aliases", e."fields") % $1
       ORDER BY "score" DESC, e."recorded_at" DESC
       LIMIT 5
    `;

/** The five as the lookup before 0313 found them — under the function's cost before 0313 too. */
async function neighboursBefore0313(h: Harness, ownerId: string, spaceId: string, exclude: string | null): Promise<Similar[]> {
  const text = `${DRAFT.title} ${DRAFT.summary}`.trim();
  await h.sql.query('BEGIN');
  try {
    await h.sql.query('ALTER FUNCTION "wiki_entry_search_text"(TEXT, TEXT, TEXT[], JSONB) COST 100');
    const rows = await h.sql.query<{ id: string; score: number; rejectedReason: string | null }>(
      NEIGHBOURS_BEFORE_0313,
      [text, ownerId, spaceId, exclude],
    );
    return rows.rows.map((row) => ({ id: row.id, score: Number(row.score), rejectedReason: row.rejectedReason }));
  } finally {
    await h.sql.query('ROLLBACK');
  }
}

