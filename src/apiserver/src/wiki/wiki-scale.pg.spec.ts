interface Vocabulary {
  latin: string[];
  cjk: string[];
}

let vocabulary: Vocabulary | undefined;

/** 20,000 Latin words and 3,000 ideographs, the same every run. */
function words(): Vocabulary {
  if (vocabulary) return vocabulary;
  const rand = mulberry32(12_345);
  const latin = [...CORE_WORDS];
  const seen = new Set(latin);
  while (latin.length < 20_000) {
    let word = '';
    for (let i = 3 + Math.floor(rand() * 8); i > 0; i -= 1) word += String.fromCharCode(97 + Math.floor(rand() * 26));
    if (!seen.has(word)) {
      seen.add(word);
      latin.push(word);
    }
  }
  const cjk: string[] = [];
  const seenCjk = new Set<string>();
  while (cjk.length < 3_000) {
    const ideograph = String.fromCodePoint(0x4e00 + Math.floor(rand() * 0x5000));
    if (!seenCjk.has(ideograph)) {
      seenCjk.add(ideograph);
      cjk.push(ideograph);
    }
  }
  vocabulary = { latin, cjk };
  return vocabulary;
}

/** Rank r drawn with weight 1/r, the way words are used. */
function zipf(n: number, rand: () => number): () => number {
  const cdf = new Float64Array(n);
  let sum = 0;
  for (let i = 0; i < n; i += 1) {
    sum += 1 / (i + 1);
    cdf[i] = sum;
  }
  return () => {
    const x = rand() * sum;
    let lo = 0;
    let hi = n - 1;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if (cdf[mid] < x) lo = mid + 1;
      else hi = mid;
    }
    return lo;
  };
}

interface Text {
  title: string;
  summary: string;
  fields: { definition: string; boundaries: string };
}

/** A seeded stream of concept entries: runs of one to eight ideographs between Latin words. */
function corpus(seed: number): () => Text {
  const rand = mulberry32(seed);
  const { latin, cjk } = words();
  const pickLatin = zipf(latin.length, rand);
  const pickCjk = zipf(cjk.length, rand);
  const phrase = (min: number, max: number): string => {
    const parts: string[] = [];
    for (let n = min + Math.floor(rand() * (max - min + 1)); n > 0; n -= 1) {
      if (rand() < 0.5) {
        parts.push(latin[pickLatin()]);
      } else {
        let run = '';
        for (let k = 1 + Math.floor(rand() * 8); k > 0; k -= 1) run += cjk[pickCjk()];
        parts.push(rand() < 0.3 ? `${run}，` : run);
      }
    }
    return parts.join(' ');
  };
  const clip = (text: string, max: number): string => (text.length <= max ? text : text.slice(0, max).trimEnd());
  return () => ({
    title: clip(phrase(3, 7), 120),
    summary: clip(phrase(8, 18), 280),
    fields: { definition: phrase(8, 18), boundaries: phrase(5, 12) },
  });
}

