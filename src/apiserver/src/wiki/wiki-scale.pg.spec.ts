test('0313 · the near-neighbour lookup at 2,606 and at 10,000 entries', { skip, concurrency: 1, timeout: 600_000 }, async (t) => {
  const h = await boot();
  const add = { op: 'add', entry: { kind: 'concept', ...DRAFT }, sources: [] };

  await t.test('at production\'s size, the space alone in the table as it was there, the lookup reads the index and not every entry', async () => {
    // Where the bug lived. A scan's price grows with the table, and the index's with the draft's
    // trigrams — about a hundred for a title and a summary — so with the test the scan repeats on every
    // row unpriced, the scan was the cheaper plan up to a few thousand entries: production read and
    // tested all 2,606, 290–470 ms an add. Past ~5,000 the index won even so, which is why this is
    // asked here and not only among the 10,000 below.
    const px = await productionLoaded(h);
    await analyze(h);
    await assertReadsTheIndex(h, px.owner, px.productionSized, PRODUCTION);
  });

  const fx = await loaded(h);

  await t.test('another owner\'s entries never reach this owner\'s neighbours, though they are neighbours in their own space', async () => {
    const mine = similarOf(await propose(h, fx.owner, fx.big, { dryRun: true, ops: [add] }));
    const theirs = new Set(Object.values(fx.otherFamily));
    assert.equal(mine.length, 5, 'the planted family is five neighbours deep');
    assert.deepEqual(mine.filter((s) => theirs.has(s.id)), [], 'another owner\'s entry is among this owner\'s neighbours');
    const outside = await h.sql.query(
      `SELECT count(*)::int AS n FROM "wiki_entry" WHERE "id" = ANY($1::uuid[]) AND "space_id" <> $2`,
      [mine.map((s) => s.id), fx.big],
    );
    assert.equal(outside.rows[0].n, 0, 'a neighbour came from outside the space asked about');
    // The twins are neighbours of the same draft where they live: absent above because of whose they
    // are, not because of what they say.
    const inTheirSpace = similarOf(await propose(h, fx.other, fx.otherSpace, { dryRun: true, ops: [add] }));
    assert.deepEqual(
      inTheirSpace.map((s) => s.id),
      ['twin', 'same', 'close', 'rejected', 'fifth'].map((key) => fx.otherFamily[key]),
      'in its own space the other owner\'s family is the five neighbours',
    );
  });

  await t.test('similar[] is what the lookup before 0313 returned: the same five in the same order, reasons kept', async () => {
    const before = await neighboursBefore0313(h, fx.owner.id, fx.big, null);
    const now = similarOf(await propose(h, fx.owner, fx.big, { dryRun: true, ops: [add] }));
    assert.deepEqual(now, before, 'an add\'s similar[] is not what the lookup before 0313 found');
    // What that comparison rests on, so it cannot pass by comparing two empty lists: the five in the
    // ranking's own order — score, then the later-recorded of a tie — the sixth left out, and the
    // rejected one carrying its latest reason.
    assert.deepEqual(
      now.map((s) => s.id),
      ['twin', 'same', 'close', 'rejected', 'fifth'].map((key) => fx.family[key]),
      'the five, in order',
    );
    assert.equal(now[0].score, now[1].score, 'the first two tie on score, and are ordered by when they were recorded');
    assert.deepEqual(
      now.map((s) => s.rejectedReason),
      [null, null, null, 'duplicate', null],
      'the rejected neighbour carries the reason of its latest rejection, and no other carries one',
    );

    // A supersede excludes the entry it replaces; the one after the five moves up.
    const superseding = {
      op: 'supersede',
      entryId: fx.family.close,
      baseRevision: 1,
      entry: { kind: 'concept', ...DRAFT },
      sources: [],
    };
    const beforeExcluding = await neighboursBefore0313(h, fx.owner.id, fx.big, fx.family.close);
    const nowExcluding = similarOf(await propose(h, fx.owner, fx.big, { dryRun: true, ops: [superseding] }));
    assert.deepEqual(nowExcluding, beforeExcluding, 'a supersede\'s similar[] is not what the lookup before 0313 found');
    assert.deepEqual(
      nowExcluding.map((s) => s.id),
      ['twin', 'same', 'rejected', 'fifth', 'sixth'].map((key) => fx.family[key]),
      'the superseded entry is left out and the sixth takes its place',
    );
  });

  await t.test('after an explicit ANALYZE the lookup reads the trigram index, not the table, and asks a reason per row it returns', async () => {
    await analyze(h);
    // What steers every caller of the function to its index, stated where a later migration cannot
    // quietly undo it: a `CREATE OR REPLACE FUNCTION "wiki_entry_search_text"` resets COST to 100.
    const cost = await h.sql.query<{ procost: number }>(
      `SELECT procost FROM pg_proc WHERE proname = 'wiki_entry_search_text'`,
    );
    assert.deepEqual(cost.rows.map((row) => Number(row.procost)), [10_000], 'wiki_entry_search_text lost the COST 0313 gave it');
    await assertReadsTheIndex(h, fx.owner, fx.big, BIG);
    await assertReadsTheIndex(h, fx.other, fx.otherSpace, OTHER);
  });

  await t.test(`${OPS} adds into ${BIG.toLocaleString('en-US')} entries commit within ${OVER_BASELINE_MS / 1_000} s of the same into an empty space`, async () => {
    const warm = await space(h, fx.owner.id, 'warm-up');
    const empty = await space(h, fx.owner.id, 'empty');
    const next = corpus(3);
    const drafts = Array.from({ length: OPS }, () => ({ op: 'add', entry: { kind: 'concept', ...next() }, sources: [] }));
    const applied = (answer: Answer): number =>
      (answer.body?.ops as Array<{ status: string }> | undefined)?.filter((op) => op.status === 'applied').length ?? 0;

    // Once through the door first: the first request of a process pays for what every later one
    // reuses (query compilation, the pool's connections), and a server that is up has paid it.
    const warmUp = await propose(h, fx.owner, warm, { ops: drafts.slice(0, 3) });
    assert.equal(warmUp.status, 200, `the warm-up: answered ${warmUp.status} ${JSON.stringify(warmUp.body)}`);

    const baseline = await propose(h, fx.owner, empty, { ops: drafts });
    assert.equal(baseline.status, 200, `the empty space: answered ${baseline.status} ${JSON.stringify(baseline.body)}`);
    assert.equal(applied(baseline), OPS, 'every add into the empty space applies');

    // A transaction Prisma closed (P2028) answers 500, and writes nothing.
    const loadedRun = await propose(h, fx.owner, fx.big, { ops: drafts });
    t.diagnostic(`baseline (empty space) ${Math.round(baseline.ms)} ms; ${BIG.toLocaleString('en-US')} entries ${Math.round(loadedRun.ms)} ms`);
    assert.equal(loadedRun.status, 200, `the big space: answered ${loadedRun.status} ${JSON.stringify(loadedRun.body)}`);
    assert.equal(applied(loadedRun), OPS, 'every add into the big space applies');
    assert.ok(
      loadedRun.ms <= baseline.ms + OVER_BASELINE_MS,
      `${OPS} adds took ${Math.round(loadedRun.ms)} ms among ${BIG} entries and ${Math.round(baseline.ms)} ms in an `
        + `empty space: the lookup costs more than ${OVER_BASELINE_MS} ms a changeset at this size`,
    );
    const committed = await h.sql.query(
      `SELECT count(*)::int AS n FROM "wiki_entry" WHERE "space_id" = $1 AND "status" = 'active'`,
      [fx.big],
    );
    assert.equal(committed.rows[0].n, BIG + OPS, 'the big space holds its entries and the thirty new ones');
  });
});
