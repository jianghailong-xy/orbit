test('every foreign key into a wiki table goes with its parent, and finds its rows by index', { skip }, async () => {
  const h = await boot();
  const { rows } = await h.sql.query<{ name: string; child: string; parent: string; on_delete: string; indexed: boolean }>(`
    SELECT c.conname AS name, c.conrelid::regclass::text AS child, c.confrelid::regclass::text AS parent, c.confdeltype AS on_delete,
           EXISTS (
             SELECT 1 FROM pg_index i
              WHERE i.indrelid = c.conrelid AND i.indisvalid AND i.indkey[0] = c.conkey[1]
           ) AS indexed
      FROM pg_constraint c
     WHERE c.contype = 'f' AND c.confrelid::regclass::text LIKE 'wiki\\_%'`);
  assert.ok(rows.length >= 30, `the census read the wiki's keys, ${rows.length} of them`);

  // NO ACTION on these two alone: both ends of a supersede are in one space, and the one statement over the
  // space's entries takes both before the check runs. The case below proves that on a real chain.
  const held = rows.filter((row) => row.on_delete !== 'c').map((row) => row.name).sort();
  assert.deepEqual(held, ['wiki_entry_superseded_by_fkey', 'wiki_entry_supersedes_fkey'],
    'a new key into a wiki table that does not cascade is one more thing that stops a wiki being deleted, or leaves rows behind');

  // A key under the space itself is read once per delete, whatever its size, and two queue tables have no index for it.
  const unindexed = rows.filter((row) => !row.indexed && row.parent !== 'wiki_space').map((row) => `${row.child} (${row.name})`).sort();
  assert.deepEqual(unindexed, [], 'a cascade over a key with no index reads the whole child table per parent row');
});

