/**
 * The wiki's Trash (contract `space.trash`, docs/mocks/wiki-trash), over real HTTP and against a real PostgreSQL.
 *
 *   - the schema: every foreign key into a wiki table goes with its parent, but the two supersede links, and each below
 *     the space is indexed, so a batch of the purge finds its rows by index at any size;
 *   - moving a wiki to Trash: one short write that keeps every row, hides the wiki from its lists and pages, frees its
 *     name and repository, turns its maintenance off and drops the work queued or running for it;
 *   - whose it is: a session header is refused, another account's wiki is a 404, and neither writes or announces;
 *   - sessions meanwhile: one on the repository makes no new wiki and is told its wiki is in Trash, as is one bound to a
 *     wiki with no repository (docs/wiki-explicit-creation-design.md §3.3);
 *   - restoring: its name or the next free one, its repository unless a newer wiki holds it, its settings with
 *     maintenance off, everything it held, and the workspaces that did not join another wiki;
 *   - what was running: a job loses its row and ends with nothing to requeue, a runner's late result is told the
 *     operation is gone;
 *   - deleting for good: at once from Trash, then in the background a batch at a time, every row of the wiki and nothing
 *     of anything else; a pass cut short goes on where it stopped, a lease keeps two passes off one wiki, and a wiki is
 *     due 365 days after its move;
 *   - its size: a wiki of thousands of entries moves in one short write, and goes in batches none of which is long.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-trash.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run created. Only
 * the credential check is stood in for, as in the other wiki specs.
 */
