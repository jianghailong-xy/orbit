/** The space's row as the Trash columns hold it. */
async function trashColumns(h: Harness, spaceId: string) {
  return h.prisma.wikiSpace.findUniqueOrThrow({
    where: { id: spaceId },
    select: { slug: true, repoUrlNorm: true, deletedAt: true, purgeAt: true, purgeLeaseUntil: true, trashedSlug: true, trashedRepoUrlNorm: true, settings: true },
  });
}

/** Every due wiki of earlier cases deleted, so that a pass below works on this case's alone. */
async function drain(h: Harness): Promise<void> {
  for (let pass = 0; pass < 20; pass += 1) {
    const { partial } = await purgeDueWikiSpaces(h.prisma as unknown as PrismaService, { budgetMs: 120_000 });
    if (partial === null) return;
  }
  assert.fail('the earlier cases left a purge that does not end');
}

const DAY_MS = 24 * 60 * 60 * 1000;

/** What a wiki holds, as `rowsOf` counts it, without the work done for it: the move to Trash drops what is unfinished. */
const held = (rows: Record<string, number>) =>
  Object.fromEntries(Object.entries(rows).filter(([table]) => !['wiki_job', 'wiki_plan_job', 'wiki_model_request', 'wiki_repo_op'].includes(table)));

// ── moving a wiki to Trash ───────────────────────────────────────────────────────────────────────

test('moving a wiki to Trash keeps every row, and takes it out of every list and page', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const stranger = await account(h);
  const machine = await runner(h, owner.id);
  const url = repository();
  const made = await titled(h, owner, 'A wiki', url);
  const spaceId = made.id;
  const otherId = await space(h, owner);
  const strangerId = await space(h, stranger);
  const home = await workspace(h, owner.id, url, machine.id);
  const talk = await session(h, owner.id, home, machine.id);

  const old = await entry(h, owner.id, spaceId, 'The old way');
  const current = await entry(h, owner.id, spaceId, 'The new way');
  await h.sql.query(`UPDATE "wiki_entry" SET "status" = 'superseded', "retired_at" = now(), "superseded_by_id" = $2 WHERE "id" = $1`, [old, current]);
  await h.sql.query(`UPDATE "wiki_entry" SET "supersedes_id" = $2 WHERE "id" = $1`, [current, old]);
  await h.sql.query(`INSERT INTO "wiki_space_workspace"("id","space_id","owner_id","workspace_id") VALUES (gen_random_uuid(),$1,$2,$3)`, [spaceId, owner.id, home]);
  await h.sql.query(`INSERT INTO "share_link"("id","owner_id","token","wiki_space_id") VALUES (gen_random_uuid(),$1,$2,$3)`, [owner.id, `token-${randomUUID()}`, spaceId]);
  await h.sql.query(`UPDATE "wiki_space" SET "settings" = "settings" || jsonb_build_object('maintenance', jsonb_build_object('enabled', true, 'workspaceId', $2::text)) WHERE "id" = $1`, [spaceId, home]);
  // Work for it: a queued job, and one that ended, which is a record and stays.
  const queued = randomUUID();
  await enqueueWikiJob(h.prisma as unknown as PrismaService, { id: queued, ownerId: owner.id, spaceId, kind: 'smoke' });
  const ended = randomUUID();
  await enqueueWikiJob(h.prisma as unknown as PrismaService, { id: ended, ownerId: owner.id, spaceId, kind: 'smoke' });
  await h.sql.query(`UPDATE "wiki_job" SET "state" = 'cancelled', "ended_at" = now() WHERE "id" = $1`, [ended]);

  const kept = await entry(h, owner.id, otherId, 'Another wiki keeps this');
  const theirs = await entry(h, stranger.id, strangerId, 'Another account keeps this');
  const before = await rowsOf(h, spaceId, [old, current]);
  for (const table of ['wiki_entry', 'wiki_changeset', 'wiki_job', 'wiki_space_workspace', 'share_link', 'wiki_entry_revision', 'wiki_exposure', 'wiki_changeset_op']) {
    assert.ok(before[table] > 0, `the fixture has a row in ${table}`);
  }
  const keptBefore = await rowsOf(h, otherId, [kept]);
  const theirsBefore = await rowsOf(h, strangerId, [theirs]);
  h.announced.length = 0;

  const startedAt = Date.now();
  const answer = await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${spaceId}`);
  expectStatus(answer, 200, 'the owner moves the wiki to Trash');
  assert.equal(toUuid(answer.body.spaceId as string), spaceId, 'the answer names it');
  const deletedAt = Date.parse(answer.body.deletedAt as string);
  assert.ok(Math.abs(deletedAt - startedAt) < 60_000, 'moved now');
  assert.equal(Date.parse(answer.body.purgeAt as string) - deletedAt, 365 * DAY_MS, 'and deleted for good 365 days on');
  assert.deepEqual(h.announced, [spaceId], 'announced once, after the commit');

  assert.deepEqual(held(await rowsOf(h, spaceId, [old, current])), held(before), 'every row of what it holds stays');
  assert.equal(await h.prisma.wikiJob.count({ where: { id: queued } }), 0, 'the queued job is dropped');
  assert.equal(await h.prisma.wikiJob.count({ where: { id: ended } }), 1, 'and the one that ended stays, a record');
  assert.equal(await h.prisma.wikiPlanJob.count({ where: { spaceId, state: { not: 'ended' } } }), 0, 'and no plan job waits for it');
  const row = await trashColumns(h, spaceId);
  assert.equal(row.trashedSlug, made.slug, 'its name is set aside');
  assert.ok(row.trashedRepoUrlNorm && url.endsWith(row.trashedRepoUrlNorm.split('/').pop()!), 'and its repository');
  assert.equal(row.repoUrlNorm, null, 'which it no longer holds');
  assert.match(row.slug, /^trashed-[0-9a-f]{32}$/, 'nor its name');
  assert.deepEqual((row.settings as { maintenance: unknown }).maintenance, { enabled: false, workspaceId: home }, 'its maintenance is off');

  assert.deepEqual(await rowsOf(h, otherId, [kept]), keptBefore, 'the owner\'s other wiki is as it was');
  assert.deepEqual(await rowsOf(h, strangerId, [theirs]), theirsBefore, 'and so is another account\'s');
  assert.equal(await h.prisma.workspace.count({ where: { id: home, deletedAt: null } }), 1, 'the workspace stays');
  assert.equal(await h.prisma.session.count({ where: { id: talk } }), 1, 'and so does its session');

  const list = await call(h, { bearer: owner.bearer }, 'GET', '/wiki/spaces');
  assert.deepEqual((list.body as Array<{ id: string }>).map((one) => toUuid(one.id)), [otherId], 'the sidebar lists what is left');
  expectStatus(await call(h, { bearer: owner.bearer }, 'GET', `/wiki/spaces/${spaceId}`), 404, 'its pages answer that it is not there');
  expectStatus(await call(h, { bearer: owner.bearer }, 'GET', `/wiki/entries/${current}`), 404, 'and so do its entries');
  const trash = await call(h, { bearer: owner.bearer }, 'GET', '/wiki/trash');
  expectStatus(trash, 200, 'the Trash');
  assert.deepEqual(trash.body.spaces.map(({ publicId: _twin, ...one }: Record<string, unknown>) => ({ ...one, id: toUuid(one.id as string) })), [{
    id: spaceId,
    slug: made.slug,
    title: 'A wiki',
    repoUrlNorm: row.trashedRepoUrlNorm,
    deletedAt: answer.body.deletedAt,
    purgeAt: answer.body.purgeAt,
    entries: 1,
  }], 'holds it, with the name it had and its active entries');
  assert.deepEqual((await call(h, { bearer: stranger.bearer }, 'GET', '/wiki/trash')).body, { spaces: [] }, 'and only the owner\'s Trash does');

  // Its name and repository are free: a new wiki takes both.
  const again = await titled(h, owner, 'A wiki', url);
  assert.equal(again.slug, made.slug, 'a new wiki takes its name');
  assert.ok(again.id !== spaceId, 'as a wiki of its own');
});

// ── whose it is ──────────────────────────────────────────────────────────────────────────────────

test('the Trash is the owner\'s: a session is refused, another account\'s wiki is a 404, and neither writes or announces', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const stranger = await account(h);
  const machine = await runner(h, owner.id);
  const url = repository();
  const spaceId = await space(h, owner, url);
  const inTrash = await space(h, owner);
  await moveToTrash(h, owner, inTrash);
  const home = await workspace(h, owner.id, url, machine.id);
  const talk = await session(h, owner.id, home, machine.id);
  h.announced.length = 0;

  for (const [method, route] of [
    ['DELETE', `/wiki/spaces/${spaceId}`],
    ['POST', `/wiki/spaces/${inTrash}/restore`],
    ['DELETE', `/wiki/spaces/${inTrash}/purge`],
  ] as const) {
    const asSession = await call(h, { bearer: owner.bearer, session: talk }, method, route);
    expectStatus(asSession, 403, `${method} ${route} with a session`);
    assert.equal(asSession.body.code, 'WIKI_OWNER_CHANNEL_ONLY');
    expectStatus(await call(h, { bearer: stranger.bearer }, method, route), 404, `${method} ${route} by another account`);
  }
  assert.equal((await trashColumns(h, spaceId)).deletedAt, null, 'the wiki in use stays in use');
  const trashed = await trashColumns(h, inTrash);
  assert.ok(trashed.deletedAt && trashed.purgeAt && trashed.purgeAt.getTime() > Date.now(), 'and the one in Trash stays in Trash, not due');
  assert.deepEqual(h.announced, [], 'and nothing was announced');

  expectStatus(await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${inTrash}`), 404, 'a wiki already in Trash is not moved again');
  expectStatus(await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${spaceId}/purge`), 404, 'and one in use is not deleted for good');
  assert.deepEqual(h.announced, [], 'nor announced');
});

