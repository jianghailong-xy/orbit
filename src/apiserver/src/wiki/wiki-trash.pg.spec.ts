/**
 * One entry and what hangs off it: a revision with a source, an exposure, and an op that names it both ways, which is
 * the second cascade path to an op (contract `storage`).
 */
async function entry(h: Harness, ownerId: string, spaceId: string, title: string): Promise<string> {
  const id = randomUUID();
  await h.sql.query(
    `INSERT INTO "wiki_entry"("id","owner_id","space_id","kind","status","trust","current_revision","title","summary","fields","valid_from","recorded_at")
     VALUES ($1,$2,$3,'concept','active','confirmed',1,$4,'a summary','{}'::jsonb,now(),now())`,
    [id, ownerId, spaceId, title],
  );
  const revision = randomUUID();
  await h.sql.query(
    `INSERT INTO "wiki_entry_revision"("id","entry_id","owner_id","revision","title","summary","fields","content_sha256","author_kind","author_user_id")
     VALUES ($1,$2,$3,1,$4,'a summary','{}'::jsonb,$5,'owner',$3)`,
    [revision, id, ownerId, title, SHA],
  );
  await h.sql.query(`INSERT INTO "wiki_source"("id","revision_id","owner_id","kind","ref") VALUES (gen_random_uuid(),$1,$2,'note','a ref')`, [revision, ownerId]);
  await h.sql.query(`INSERT INTO "wiki_exposure"("id","owner_id","entry_id","revision","channel") VALUES (gen_random_uuid(),$1,$2,1,'search')`, [ownerId, id]);
  const changeset = randomUUID();
  await h.sql.query(
    `INSERT INTO "wiki_changeset"("id","owner_id","space_id","origin","status","decided_at") VALUES ($1,$2,$3,'owner','settled',now())`,
    [changeset, ownerId, spaceId],
  );
  await h.sql.query(
    `INSERT INTO "wiki_changeset_op"("id","changeset_id","owner_id","seq","op","payload","entry_id","result_entry_id","decision","decided_at")
     VALUES (gen_random_uuid(),$1,$2,0,'reinforce','{}'::jsonb,$3,$3,'accepted',now())`,
    [changeset, ownerId, id],
  );
  return id;
}

/** Every row of a space, table by table: each table with a `space_id` column, and the ones under its entries. */
async function rowsOf(h: Harness, spaceId: string, entryIds: readonly string[] = []): Promise<Record<string, number>> {
  const { rows: tables } = await h.sql.query<{ table_name: string }>(
    `SELECT table_name FROM information_schema.columns WHERE table_schema = current_schema() AND column_name = 'space_id' ORDER BY 1`,
  );
  const counts: Record<string, number> = {};
  for (const { table_name: table } of tables) {
    const { rows } = await h.sql.query<{ n: number }>(`SELECT count(*)::int AS n FROM "${table}" WHERE "space_id" = $1`, [spaceId]);
    if (rows[0].n > 0) counts[table] = rows[0].n;
  }
  const { rows: links } = await h.sql.query<{ n: number }>(`SELECT count(*)::int AS n FROM "share_link" WHERE "wiki_space_id" = $1`, [spaceId]);
  if (links[0].n > 0) counts.share_link = links[0].n;
  for (const table of ['wiki_entry_revision', 'wiki_exposure', 'wiki_changeset_op']) {
    const { rows } = await h.sql.query<{ n: number }>(`SELECT count(*)::int AS n FROM "${table}" WHERE "entry_id" = ANY($1::uuid[])`, [entryIds]);
    if (rows[0].n > 0) counts[table] = rows[0].n;
  }
  return counts;
}

