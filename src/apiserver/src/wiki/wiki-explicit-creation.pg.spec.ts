const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

interface Harness {
  base: string;
  sql: Client;
  prisma: PrismaClient;
  app: INestApplication;
  bearers: Map<string, string>;
  /** Which spaces were announced, in order. */
  announced: string[];
}

let harness: Promise<Harness> | undefined;

function boot(): Promise<Harness> {
  harness ??= (async () => {
    assertCoordinatorPgUrlIsIsolated(URL);
    const sql = new Client({ connectionString: URL, connectionTimeoutMillis: 5_000 });
    await sql.connect();
    await verifyCoordinatorPgIdentity(sql);
    const prisma = prismaClientFor(URL);
    const bearers = new Map<string, string>();
    const announced: string[] = [];
    const hub = { publishWikiChanged: (_owner: string, spaceId: string) => void announced.push(spaceId) } as unknown as RealtimeService;
    const push = { notifyWikiReviewModeTripped: async () => undefined, notifyWikiVerificationTripped: async () => undefined } as unknown as PushService;
    const service = new WikiService(prisma as unknown as PrismaService, hub, push);

    @Module({
      controllers: [WikiController, RunnerWikiController],
      providers: [
        { provide: WikiService, useValue: service },
        { provide: WikiRetrieval, useValue: new WikiRetrieval(prisma as unknown as PrismaService) },
        { provide: PrismaService, useValue: prisma },
        RunnerAuthGuard,
        JwtAuthGuard,
        Reflector,
        {
          provide: JwtService,
          useValue: {
            verifyAsync: async (token: string) => {
              const sub = bearers.get(token);
              if (!sub) throw new Error('not a bearer this run issued');
              return { sub, email: `${sub}@wiki.invalid` };
            },
          },
        },
      ],
    })
    class WikiExplicitCreationModule {}

    const app = await NestFactory.create(WikiExplicitCreationModule, { logger: false, abortOnError: false });
    app.setGlobalPrefix('api');
    app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
    app.useGlobalInterceptors(new PublicIdInterceptor());
    await app.listen(0, '127.0.0.1');
    return { base: await app.getUrl(), sql, prisma, app, bearers, announced };
  })();
  return harness;
}

after(async () => {
  if (!harness) return;
  const { app, prisma, sql } = await harness;
  await app.close().catch(() => undefined);
  await prisma.$disconnect().catch(() => undefined);
  await sql.end().catch(() => undefined);
});

// ── requests ─────────────────────────────────────────────────────────────────────────────────────

interface Answer {
  status: number;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  body: any;
}

interface Caller {
  bearer?: string;
  runner?: string;
  session?: string;
}

async function call(h: Harness, who: Caller, method: string, route: string, body?: unknown): Promise<Answer> {
  const headers: Record<string, string> = { 'content-type': 'application/json' };
  if (who.bearer) headers.authorization = `Bearer ${who.bearer}`;
  if (who.runner) headers['x-runner-token'] = who.runner;
  if (who.session) headers['x-orbit-session-id'] = who.session;
  const response = await fetch(`${h.base}/api${route}`, {
    method,
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await response.text();
  return { status: response.status, body: text ? JSON.parse(text) : null };
}

function expectStatus(answer: Answer, status: number, why: string): void {
  assert.equal(answer.status, status, `${why}: answered ${answer.status} ${JSON.stringify(answer.body).slice(0, 1500)}`);
}

// ── fixtures ─────────────────────────────────────────────────────────────────────────────────────

interface Account {
  id: string;
  bearer: string;
}

async function account(h: Harness): Promise<Account> {
  const id = randomUUID();
  await h.sql.query(`INSERT INTO "user"("id","email","name","password_hash") VALUES ($1,$2,'spec','x')`, [id, `wiki-explicit-${id}@wiki.invalid`]);
  h.bearers.set(`bearer-${id}`, id);
  return { id, bearer: `bearer-${id}` };
}

async function runner(h: Harness, ownerId: string): Promise<{ id: string; token: string }> {
  const id = randomUUID();
  const token = `runner-${id}`;
  await h.sql.query(`INSERT INTO "runner"("id","name","owner_id","token_hash") VALUES ($1,'build-01',$2,$3)`, [
    id,
    ownerId,
    createHash('sha256').update(token).digest('hex'),
  ]);
  return { id, token };
}

async function workspace(h: Harness, ownerId: string, repoUrl: string | null, runnerId: string): Promise<string> {
  const id = randomUUID();
  await h.sql.query(`INSERT INTO "workspace"("id","name","owner_id","repo_url","runner_id") VALUES ($1,'lfs',$2,$3,$4)`, [id, ownerId, repoUrl, runnerId]);
  return id;
}

async function session(h: Harness, ownerId: string, workspaceId: string, runnerId: string): Promise<string> {
  const id = randomUUID();
  await h.sql.query(
    `INSERT INTO "session"("id","title","prompt","owner_id","creator_id","workspace_id","assigned_runner_id",
                            "status","dispatch_origin","updated_at")
     VALUES ($1,'a session','p',$2,$2,$3,$4,'RUNNING'::run_status,'USER',now())`,
    [id, ownerId, workspaceId, runnerId],
  );
  return id;
}

const repository = () => `https://github.com/spec/${randomUUID()}`;

const NO_WIKI_WRITE = 'No wiki for this repository yet, so nothing was recorded. Only the owner can start one: if they asked '
  + 'for a wiki here, file request_owner_action with kind WIKI_CREATE; otherwise carry on without it.';
const IN_TRASH_WRITE = 'The wiki for this repository is in Trash: the owner restores it from Trash.';
const NO_WIKI_READ = 'This workspace has no wiki.';

/** What a session's wiki tools could have written: the rows a wiki is made of, and the rows that ask for its plan. */
async function made(h: Harness, ownerId: string) {
  const [spaces, planJobs, bindings, exposures, changesets] = await Promise.all([
    h.prisma.wikiSpace.count({ where: { ownerId } }),
    h.prisma.wikiPlanJob.count({ where: { ownerId } }),
    h.prisma.wikiSpaceWorkspace.count({ where: { ownerId } }),
    h.prisma.wikiExposure.count({ where: { ownerId } }),
    h.prisma.wikiChangeset.count({ where: { ownerId } }),
  ]);
  return { spaces, planJobs, bindings, exposures, changesets };
}

const proposal = {
  rationale: 'what this session learned',
  ops: [{
    op: 'add',
    entry: {
      kind: 'pitfall',
      title: 'A skipped pg spec exits zero',
      summary: 'A pg spec that skips itself proves nothing about what it tests.',
      fields: {
        trigger: { paths: ['src/apiserver/src/wiki/*.pg.spec.ts'], commands: ['node --test build/x.pg.spec.js'] },
        symptom: 'node exits 0 and no assertion ran.',
        cause: 'A pg spec skips itself when the URL is unset.',
        fix: 'Run it through scripts/run-pg-spec.sh, which treats a skip as red.',
      },
    },
    sources: [{ kind: 'turn', session: 'self' }],
  }],
};

/** The five tools, called as `as`, answered as design §3.3 says for a workspace with no wiki. */
async function fiveDoorsAnswerNoWiki(h: Harness, as: Caller, unavailable: 'no_wiki' | 'wiki_in_trash', writeSentence: string): Promise<void> {
  const search = await call(h, as, 'GET', '/runner/wiki/search?q=%2Fetc%2Fwireguard%2Fwg1.conf');
  expectStatus(search, 200, 'wiki_search is answered, not refused');
  assert.deepEqual(search.body, { q: '/etc/wireguard/wg1.conf', semantic: false, hits: [], unavailable }, 'nothing found, and why');

  const get = await call(h, as, 'GET', `/runner/wiki/entries/${randomUUID()}`);
  expectStatus(get, 404, 'wiki_get');
  assert.equal(get.body.code, 'WIKI_SPACE_UNBOUND');
  assert.equal(get.body.message, NO_WIKI_READ);

  const propose = await call(h, as, 'POST', '/runner/wiki/changesets', proposal);
  expectStatus(propose, 409, 'wiki_propose');
  assert.equal(propose.body.code, 'WIKI_SPACE_UNBOUND');
  assert.equal(propose.body.message, writeSentence);

  const note = await call(h, as, 'POST', '/runner/wiki/notes', { text: 'The runner reads its WireGuard config from /etc/wireguard/wg1.conf.' });
  expectStatus(note, 409, 'wiki_note');
  assert.equal(note.body.code, 'WIKI_SPACE_UNBOUND');
  assert.equal(note.body.message, writeSentence);

  const draft = await call(h, as, 'POST', '/runner/wiki/drafts', { sections: [] });
  expectStatus(draft, 409, 'wiki_draft');
  assert.equal(draft.body.code, 'WIKI_SPACE_UNBOUND');
  assert.equal(draft.body.message, writeSentence);
}

// ── no wiki ──────────────────────────────────────────────────────────────────────────────────────

test('from a workspace on a repository with no wiki, the five tools make no wiki and no plan job', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const machine = await runner(h, owner.id);
  const lfs = await workspace(h, owner.id, `git@github.com:spec/${randomUUID()}.git`, machine.id);
  const talk = await session(h, owner.id, lfs, machine.id);
  assert.deepEqual(await made(h, owner.id), { spaces: 0, planJobs: 0, bindings: 0, exposures: 0, changesets: 0 }, 'the account starts with no wiki');

  await fiveDoorsAnswerNoWiki(h, { runner: machine.token, session: talk }, 'no_wiki', NO_WIKI_WRITE);
  // Twice, as an agent that searches before every edit does: the second call finds no wiki either.
  await fiveDoorsAnswerNoWiki(h, { runner: machine.token, session: talk }, 'no_wiki', NO_WIKI_WRITE);

  assert.deepEqual(await made(h, owner.id), { spaces: 0, planJobs: 0, bindings: 0, exposures: 0, changesets: 0 }, 'and after them all, still none');
  assert.deepEqual(h.announced, [], 'and nothing was announced');
});

test('from a workspace with no repository and no wiki, search answers no_wiki rather than refusing', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const machine = await runner(h, owner.id);
  const home = await workspace(h, owner.id, null, machine.id);
  const talk = await session(h, owner.id, home, machine.id);

  await fiveDoorsAnswerNoWiki(h, { runner: machine.token, session: talk }, 'no_wiki', NO_WIKI_WRITE);
  assert.deepEqual(await made(h, owner.id), { spaces: 0, planJobs: 0, bindings: 0, exposures: 0, changesets: 0 }, 'nothing is made');
});

// ── a wiki in Trash ──────────────────────────────────────────────────────────────────────────────

test('with the repository\'s wiki in Trash, the five tools make no new wiki and say it is in Trash', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const machine = await runner(h, owner.id);
  const url = repository();
  const created = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'lfs-builder', repoUrl: url });
  expectStatus(created, 201, 'the owner creates the wiki');
  const spaceId = toUuid(created.body.id as string);
  const bound = await workspace(h, owner.id, url, machine.id);
  const never = await workspace(h, owner.id, `${url}.git`, machine.id);
  const talk = await session(h, owner.id, bound, machine.id);
  const fresh = await session(h, owner.id, never, machine.id);
  expectStatus(await call(h, { runner: machine.token, session: talk }, 'GET', '/runner/wiki/search?q=x'), 200, 'one workspace reads the wiki, which binds it');
  assert.equal((await h.prisma.wikiSpaceWorkspace.findUniqueOrThrow({ where: { workspaceId: bound } })).spaceId, spaceId);

  expectStatus(await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${spaceId}`), 200, 'the owner moves the wiki to Trash');
  const before = await made(h, owner.id);
  assert.equal(before.spaces, 1, 'the one wiki, in Trash');

  await fiveDoorsAnswerNoWiki(h, { runner: machine.token, session: talk }, 'wiki_in_trash', IN_TRASH_WRITE);
  await fiveDoorsAnswerNoWiki(h, { runner: machine.token, session: fresh }, 'wiki_in_trash', IN_TRASH_WRITE);

  assert.deepEqual(await made(h, owner.id), before, 'no wiki, plan job, binding or exposure was made');
  assert.equal(await h.prisma.wikiSpace.count({ where: { ownerId: owner.id, deletedAt: null } }), 0, 'no wiki is in use');
  assert.equal((await h.prisma.wikiSpaceWorkspace.findUniqueOrThrow({ where: { workspaceId: bound } })).spaceId, spaceId, 'the row still names the wiki in Trash');

  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${spaceId}/restore`), 200, 'the owner restores it');
  const again = await call(h, { runner: machine.token, session: fresh }, 'GET', '/runner/wiki/search?q=x');
  expectStatus(again, 200, 'and both workspaces read it again');
  assert.equal(again.body.unavailable, undefined, 'with a wiki to search');
});

// ── a wiki in use ────────────────────────────────────────────────────────────────────────────────

test('a workspace whose repository has a wiki still binds to it on first use, and asks for no plan draft', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const machine = await runner(h, owner.id);
  const created = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'orbit', repoUrl: 'https://github.com/spec/explicit-orbit' });
  expectStatus(created, 201, 'the owner creates the wiki');
  const spaceId = toUuid(created.body.id as string);
  const before = await made(h, owner.id);
  assert.equal(before.spaces, 1);
  assert.equal(before.planJobs, 1, 'the owner\'s creation asked for its plan');
  assert.equal(before.bindings, 0, 'no workspace has a row yet');

  // The same repository, written the other way.
  const ws = await workspace(h, owner.id, 'git@github.com:spec/explicit-orbit.git', machine.id);
  const talk = await session(h, owner.id, ws, machine.id);
  const search = await call(h, { runner: machine.token, session: talk }, 'GET', '/runner/wiki/search?q=x');
  expectStatus(search, 200, 'the session searches the wiki');
  assert.equal(search.body.unavailable, undefined, 'there is a wiki to search');
  const row = await h.prisma.wikiSpaceWorkspace.findUniqueOrThrow({ where: { workspaceId: ws } });
  assert.equal(row.spaceId, spaceId, 'the workspace joined the wiki in use for its repository');
  assert.equal(row.leftOutAt, null);

  const proposed = await call(h, { runner: machine.token, session: talk }, 'POST', '/runner/wiki/changesets', proposal);
  expectStatus(proposed, 200, 'and proposes to it');
  const after = await made(h, owner.id);
  assert.equal(after.spaces, 1, 'no second wiki');
  assert.equal(after.planJobs, 1, 'no second plan job');
  assert.equal(after.bindings, 1, 'one row, written once');
});

// ── POST /api/wiki/spaces: the owner's, one per repository ────────────────────────────────────────

test('POST /wiki/spaces with a session header is refused WIKI_OWNER_CHANNEL_ONLY and makes nothing', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const machine = await runner(h, owner.id);
  const ws = await workspace(h, owner.id, null, machine.id);
  const talk = await session(h, owner.id, ws, machine.id);

  const plain = await call(h, { bearer: owner.bearer, session: talk }, 'POST', '/wiki/spaces', { title: 'agent-made', repoUrl: repository() });
  expectStatus(plain, 403, 'a session asking for a wiki with no maintenance');
  assert.equal(plain.body.code, 'WIKI_OWNER_CHANNEL_ONLY');
  const maintained = await call(h, { bearer: owner.bearer, session: talk }, 'POST', '/wiki/spaces', {
    title: 'agent-made',
    maintenance: { enabled: true, dailyRunLimit: 2 },
  });
  expectStatus(maintained, 403, 'and one naming maintenance');
  assert.equal(maintained.body.code, 'WIKI_OWNER_CHANNEL_ONLY');

  assert.deepEqual(await made(h, owner.id), { spaces: 0, planJobs: 0, bindings: 0, exposures: 0, changesets: 0 }, 'no wiki and no plan job');
});

test('a second wiki for a repository is refused 409 WIKI_SPACE_EXISTS with no new row; the owner\'s first create succeeds', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const url = repository();

  const first = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'lfs-builder', repoUrl: url });
  expectStatus(first, 201, 'the owner creates the wiki');
  assert.equal(first.body.repoUrlNorm, url.replace('https://', ''));
  const before = await made(h, owner.id);
  assert.deepEqual([before.spaces, before.planJobs], [1, 1], 'one wiki, and its plan asked for');

  // The same repository, as the form would send it again, and in another spelling.
  for (const repoUrl of [url, `${url.replace('https://github.com/', 'git@github.com:')}.git`]) {
    const again = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'lfs-builder again', repoUrl });
    expectStatus(again, 409, `a second wiki for ${repoUrl}`);
    assert.deepEqual(again.body, { code: 'WIKI_SPACE_EXISTS', message: 'This repository already has a wiki.' });
  }
  assert.deepEqual(await made(h, owner.id), before, 'no new wiki_space row and no plan job');

  // Another account's wiki for the same repository is no business of this one's.
  const other = await account(h);
  expectStatus(await call(h, { bearer: other.bearer }, 'POST', '/wiki/spaces', { title: 'theirs', repoUrl: url }), 201, 'another owner creates theirs');

  // A wiki with no repository never collides.
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'notes' }), 201, 'a wiki with no repository');
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'notes' }), 201, 'and another');

  // With the repository's wiki in Trash, the owner may create a new one.
  expectStatus(await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${first.body.id}`), 200, 'the owner moves it to Trash');
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'lfs-builder anew', repoUrl: url }), 201, 'a new wiki once the old is in Trash');
});

test('two creates of one repository at once: one wiki, the other answered WIKI_SPACE_EXISTS, never a 500', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const url = repository();
  const answers = await Promise.all(Array.from({ length: 4 }, () => call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'race', repoUrl: url })));
  const statuses = answers.map((a) => a.status).sort();
  assert.deepEqual(statuses, [201, 409, 409, 409], JSON.stringify(answers.map((a) => a.body)).slice(0, 1500));
  for (const a of answers.filter((x) => x.status === 409)) assert.equal(a.body.code, 'WIKI_SPACE_EXISTS');
  assert.equal(await h.prisma.wikiSpace.count({ where: { ownerId: owner.id } }), 1, 'one wiki');
});
