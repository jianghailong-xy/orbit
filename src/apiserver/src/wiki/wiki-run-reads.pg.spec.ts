/**
 * The reads that let the owner take back ANY run (criterion 8; contracts/wiki.contract.json
 * `reviewModes.run`), over real HTTP and against a real PostgreSQL.
 *
 * Criterion 8 asks that the entries one run applied can be taken back as a whole. The clients could
 * only open a run that still had a card in Review — the one read that tied an op to its changeset —
 * and an Automatic run draws no spot check by default, so once its verdicts applied it there was
 * nothing left to open it from. What is under test is the three reads that close that gap:
 *
 *   1. the timeline names each op's changeset, and the review mode that applied any op of it;
 *   2. `GET /api/wiki/changesets/:id` reads such a run — every op settled, nothing in Review — with
 *      what it did counted and what Revert run… would undo, by the revert's own rules; another
 *      account's is a 404, and a request carrying a session header is refused;
 *   3. an entry's read says where its current revision came from: the changeset, the mode that
 *      applied it and the verdict it was applied on;
 *
 * and, beside them, the article read naming the entries it was written from (`entryIds`, the pool its
 * generation stored), which is what the list under an article is drawn from.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-run-reads.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the two credential checks are stood in for, as in the other wiki specs; the verdicts
 * are recorded through `WikiService.recordVerifications`, the call the runner door's route makes.
 */
