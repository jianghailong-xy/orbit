interface Space {
  owner: Account;
  machine: { id: string; token: string };
  spaceId: string;
  workspaceId: string;
  listId: string;
}

/** A space bound to a workspace, its maintenance on and pinned to that workspace. */
async function maintainedSpace(h: Harness, name: string, settings: Record<string, unknown> = {}): Promise<Space> {
  const owner = await account(h, name);
  const machine = await runner(h, owner.id);
  const workspaceId = await workspace(h, owner.id, '~/orbit');
  const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: `${name} space`, repoUrl: `https://github.com/spec/${name}-${randomUUID().slice(0, 8)}` });
  expectStatus(made, 201, 'the owner creates a space');
  const spaceId = toUuid(made.body.id as string);
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${spaceId}/workspaces`, { workspaceId }), 200, 'the owner binds the workspace');
  const on = await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${spaceId}`, {
    maintenance: { enabled: true, workspaceId, provider: 'local-vllm', ...settings },
  });
  expectStatus(on, 200, 'the owner turns maintenance on');
  return { owner, machine, spaceId, workspaceId, listId: toUuid(on.body.settings.maintenance.listId as string) };
}

/** Sessions of the space that came to rest about `minutes` ago, each one fact: the first the oldest. */
async function settledSessions(h: Harness, s: Space, count: number, minutes = 30): Promise<string[]> {
  const ids: string[] = [];
  for (let n = 0; n < count; n += 1) {
    ids.push(await session(h, s.owner.id, { workspaceId: s.workspaceId, lastTurnAt: minutesAgo(minutes + (count - n) / 10) }));
  }
  return ids;
}

const hintOf = (sessionIds: string[] = [], taskIds: string[] = []): WikiMaintenanceHint => ({ sessionIds, taskIds });

function consider(h: Harness, s: Space, hint: WikiMaintenanceHint) {
  return considerWikiMaintenance(h.prisma as unknown as PrismaService, s.owner.id, s.spaceId, hint);
}

async function maintenanceTasks(h: Harness, s: Space) {
  return (await h.sql.query<{
    id: string; status: string; assignee_id: string; provider: string; run_at: Date | null; completion_criterion: string;
    acceptance_command: string; acceptance_expected_exit_code: number; acceptance_timeout_seconds: number; title: string; description: string;
  }>(`SELECT "id","status","assignee_id","provider","run_at","completion_criterion","acceptance_command",
             "acceptance_expected_exit_code","acceptance_timeout_seconds","title","description"
        FROM "task" WHERE "list_id" = $1 ORDER BY "created_at"`, [s.listId])).rows;
}

async function cursorRow(h: Harness, s: Space) {
  return (await h.sql.query<{
    position_at: Date | null; consecutive_failures: number; last_outcome: string | null; held_reason: string | null; held_at: Date | null;
  }>(`SELECT "position_at","consecutive_failures","last_outcome","held_reason","held_at" FROM "wiki_cursor" WHERE "space_id" = $1`, [s.spaceId])).rows[0];
}

/** The maintenance task's own session, on the space's runner, as a claim would have made it. */
async function runSession(h: Harness, s: Space, taskId: string): Promise<string> {
  await h.sql.query(`UPDATE "task" SET "status" = 'IN_PROGRESS' WHERE "id" = $1`, [taskId]);
  return session(h, s.owner.id, { workspaceId: s.workspaceId, runnerId: s.machine.id, taskId, status: 'RUNNING', lastTurnAt: minutesAgo(1) });
}

/** Page the dossiers a run covers, from the cursor up to what its task expects, as `orbit wiki maintain` does. */
async function pageToExpected(h: Harness, s: Space, sessionId: string, expect: string): Promise<{ token: string; sessions: string[] }> {
  let after = '';
  const sessions: string[] = [];
  for (let n = 0; n < 100; n += 1) {
    const query = new URLSearchParams({ until: expect, limit: '5', ...(after ? { after } : {}) });
    const page = await call(h, { runner: s.machine.token, session: sessionId }, 'GET', `/runner/wiki/spaces/${s.spaceId}/dossiers?${query}`);
    expectStatus(page, 200, 'the run reads a page');
    for (const dossier of page.body.dossiers as Array<{ sessionId: string }>) sessions.push(toUuid(dossier.sessionId));
    after = page.body.cursor as string;
    if (!page.body.more) return { token: after, sessions };
  }
  throw new Error('the pages never ended');
}

