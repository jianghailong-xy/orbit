/**
 * Page the dossiers a run covers, from the cursor up to the position its run row expects, as the server's run
 * reads them (`WikiMaintenance.dossierPage`): the last page's token, and where the first page starts.
 */
async function pageToExpected(h: Harness, s: Space, expect: string): Promise<{ token: string; from: string; sessions: string[] }> {
  let after = '';
  let from = '';
  const sessions: string[] = [];
  for (let n = 0; n < 100; n += 1) {
    const page = await h.maintenance.dossierPage(s.owner.id, s.spaceId, { until: expect, limit: 5, after: after || null });
    if (after) assert.equal(page.from, after, 'a page starts where the one before it ended');
    from ||= page.from as string;
    for (const dossier of page.dossiers) sessions.push(toUuid(dossier.sessionId));
    after = page.cursor as string;
    if (!page.more) return { token: after, from, sessions };
  }
  throw new Error('the pages never ended');
}

