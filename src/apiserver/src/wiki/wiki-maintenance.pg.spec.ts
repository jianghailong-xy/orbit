// ── 6. the circuit breaker over a run ────────────────────────────────────────────────────────────

test('the circuit breaker counts a whole maintenance run: its changesets stop at 10% of what it began with', { skip }, async () => {
  const h = await boot();
  const s = await maintainedSpace(h, 'breaker');
  await activeEntries(h, s, WIKI_REVIEW_RULES.breakerMinActiveEntries);
  const sessions = await settledSessions(h, s, WIKI_MAINTENANCE_RULES.backlogThreshold);
  const cite = await turn(h, sessions[0]!, 'the record every proposal of this run cites');
  const made = await consider(h, s, hintOf([sessions[0]!]));
  assert.equal(made.made, true);
  if (!made.made) return;
  assert.equal(made.runSessions, 1, 'a hundred active entries at six entries a session: a run of one session');
  const run = await runSession(h, s, made.taskId);
  const propose = (ops: unknown[], dryRun = false) => call(h, { runner: s.machine.token, session: run }, 'POST',
    `/runner/wiki/spaces/${s.spaceId}/maintenance/changesets`, { ops, rationale: 'what the run learned', idempotencyKey: randomUUID(), dryRun });

  // Eight adds the Tiered mode applies: eight of the hundred.
  const first = await propose(adds(8, cite, 'first'));
  expectStatus(first, 200, 'the first changeset is recorded');
  assert.deepEqual((first.body.ops as Array<{ status: string }>).map((op) => op.status), Array(8).fill('applied'));
  const origin = await h.sql.query<{ origin: string }>(`SELECT "origin" FROM "wiki_changeset" WHERE "id" = $1`, [toUuid(first.body.changesetId)]);
  assert.equal(origin.rows[0]!.origin, 'maintenance', 'a maintenance run proposes as maintenance');

  // Five more: the space holds 108 active entries now, and five is nowhere near a changeset's 10% of them —
  // but the run began with 100, and has changed eight: the ninth and tenth pass, the eleventh trips.
  const second = await propose(adds(5, cite, 'second'));
  expectStatus(second, 200, 'what fits is recorded');
  const statuses = (second.body.ops as Array<{ status: string; reasons?: Array<{ code: string; message: string }> }>);
  assert.deepEqual(statuses.map((op) => op.status), ['applied', 'applied', 'refused', 'refused', 'refused']);
  assert.equal(statuses[2]!.reasons![0]!.code, 'WIKI_QUOTA');
  assert.match(statuses[2]!.reasons![0]!.message, /circuit breaker: this Wiki maintenance run has already changed 10 of the 100 entries/u);
  // A dry run of the same says the same, before anything is recorded.
  const dry = await propose(adds(1, cite, 'dry'), true);
  assert.equal((dry.body.ops as Array<{ status: string }>)[0]!.status, 'refused', 'the run is spent');

  // The run stops: it ends failed, the cursor stays, and its check fails.
  const { token } = await pageToExpected(h, s, run, made.expect);
  const failed = await call(h, { runner: s.machine.token, session: run }, 'POST', `/runner/wiki/spaces/${s.spaceId}/maintenance/finish`, {
    to: token,
    outcome: 'failed',
    error: 'circuit breaker: the run would change more than 10% of the active entries',
    report: { stoppedAt: 'propose', ops: { proposed: 13, recorded: 10, refused: 3 }, tokens: { input: 1, output: 1, calls: 1 } },
  });
  expectStatus(failed, 200, 'a failed run is recorded');
  assert.equal(failed.body.advanced, false);
  const cursor = await cursorRow(h, s);
  assert.equal(cursor.position_at, null, 'a tripped run moves no cursor');
  assert.equal(cursor.consecutive_failures, 1);
  const row = await h.prisma.wikiMaintenanceRun.findUniqueOrThrow({ where: { taskId: made.taskId } });
  assert.equal(row.outcome, 'failed');
  assert.equal(row.opsRefused, 3);
  const check = await call(h, { runner: s.machine.token }, 'GET', `/runner/wiki/spaces/${s.spaceId}/maintenance/check?expect=${encodeURIComponent(made.expect)}`);
  assert.equal(check.body.ok, false);

  // Below a hundred active entries there is no breaker: a space's first batch goes in whole.
  const young = await maintainedSpace(h, 'young');
  await activeEntries(h, young, WIKI_REVIEW_RULES.breakerMinActiveEntries - 1);
  const youngSessions = await settledSessions(h, young, WIKI_MAINTENANCE_RULES.backlogThreshold);
  const youngCite = await turn(h, youngSessions[0]!, 'a record');
  const youngTask = await consider(h, young, hintOf([youngSessions[0]!]));
  assert.equal(youngTask.made, true);
  if (!youngTask.made) return;
  const youngRun = await runSession(h, young, youngTask.taskId);
  for (const prefix of ['one', 'two']) {
    const answer = await call(h, { runner: young.machine.token, session: youngRun }, 'POST', `/runner/wiki/spaces/${young.spaceId}/maintenance/changesets`,
      { ops: adds(12, youngCite, prefix), rationale: 'the first batch', idempotencyKey: randomUUID() });
    expectStatus(answer, 200, 'no breaker below a hundred');
    assert.deepEqual((answer.body.ops as Array<{ status: string }>).map((op) => op.status), Array(12).fill('applied'));
  }
});

// ── the check, and who may run ───────────────────────────────────────────────────────────────────

test('the check passes a run that reached its position with no op refused, and nothing else; only the run proposes', { skip }, async () => {
  const h = await boot();
  const s = await maintainedSpace(h, 'check');
  const sessions = await settledSessions(h, s, WIKI_MAINTENANCE_RULES.backlogThreshold);
  const cite = await turn(h, sessions[0]!, 'what the owner said');
  const made = await consider(h, s, hintOf([sessions[0]!]));
  assert.equal(made.made, true);
  if (!made.made) return;
  const run = await runSession(h, s, made.taskId);
  const route = (path: string) => `/runner/wiki/spaces/${s.spaceId}/maintenance/${path}`;

  // Nobody but the run starts, proposes to or ends it.
  const other = await session(h, s.owner.id, { workspaceId: s.workspaceId, runnerId: s.machine.id, status: 'RUNNING' });
  for (const [method, path, body] of [['GET', 'run', undefined], ['POST', 'changesets', { ops: adds(1, cite, 'x'), rationale: 'r' }],
    ['POST', 'finish', { outcome: 'failed', error: 'e' }]] as const) {
    const refused = await call(h, { runner: s.machine.token, session: other }, method, route(path), body);
    expectStatus(refused, 403, `another session of the owner may not ${method} ${path}`);
    assert.equal(refused.body.code, 'WIKI_NOT_MAINTENANCE_SESSION');
    expectStatus(await call(h, { runner: s.machine.token }, method, route(path), body), 400, `a headless ${method} ${path} is refused`);
  }
  const stranger = await maintainedSpace(h, 'check-stranger');
  expectStatus(await call(h, { runner: stranger.machine.token }, 'GET', `${route('check')}?expect=${encodeURIComponent(made.expect)}`), 404,
    "another owner's runner meets a 404");
  const otherCheck = await call(h, { runner: s.machine.token, session: other }, 'GET', `${route('check')}?expect=${encodeURIComponent(made.expect)}`);
  expectStatus(otherCheck, 403, 'a session that is not the run may not check through it');

  // The run: where it starts, its proposal, its dossiers, its end.
  const context = await call(h, { runner: s.machine.token, session: run }, 'GET', route('run'));
  expectStatus(context, 200, 'the run reads where it starts');
  assert.equal(context.body.expect, made.expect);
  assert.equal(context.body.reviewMode, 'tiered');
  assert.equal(context.body.workspace.workDir, '~/orbit', 'the work directory as stored: the runner expands ~');
  assert.equal(context.body.runSessions, WIKI_MAINTENANCE_JOB.runSessionsMax);
  assert.ok((context.body.topics as unknown[]).length > 0, 'the topics an entry may name');
  const started = await h.prisma.wikiMaintenanceRun.findUniqueOrThrow({ where: { taskId: made.taskId } });
  assert.equal(started.sessionId, run, 'the run is recorded as started by its session');

  const proposed = await call(h, { runner: s.machine.token, session: run }, 'POST', route('changesets'),
    { ops: adds(2, cite, 'checked'), rationale: 'what the run learned', idempotencyKey: randomUUID() });
  expectStatus(proposed, 200, 'the run proposes');
  const { token, sessions: covered } = await pageToExpected(h, s, run, made.expect);
  assert.equal(covered.length, WIKI_MAINTENANCE_RULES.backlogThreshold, 'the pages up to the expected position cover the twenty sessions');

  // Before it ends, the check fails: the cursor has not moved.
  const early = await call(h, { runner: s.machine.token }, 'GET', `${route('check')}?expect=${encodeURIComponent(made.expect)}`);
  assert.equal(early.body.ok, false);

  const ended = await call(h, { runner: s.machine.token, session: run }, 'POST', route('finish'), {
    to: token,
    outcome: 'succeeded',
    report: { sessions: 20, ops: { proposed: 2, recorded: 2, refused: 0 }, tokens: { input: 1200, output: 300, calls: 20 }, seconds: 42 },
  });
  expectStatus(ended, 200, 'the run ends');
  assert.equal(ended.body.advanced, true, 'a succeeded run moves the cursor to its token');
  const passed = await call(h, { runner: s.machine.token }, 'GET', `${route('check')}?expect=${encodeURIComponent(made.expect)}`);
  expectStatus(passed, 200, 'the check answers');
  assert.equal(passed.body.ok, true, `the run passes its check: ${JSON.stringify(passed.body)}`);
  assert.equal(passed.body.reached, true);
  assert.deepEqual(passed.body.problems, []);
  const row = await h.prisma.wikiMaintenanceRun.findUniqueOrThrow({ where: { taskId: made.taskId } });
  assert.equal(row.outcome, 'succeeded');
  assert.equal(row.opsRefused, 0);
  assert.deepEqual((row.report as { tokens: unknown }).tokens, { input: 1200, output: 300, calls: 20 }, 'the token spend is kept with the run');

  // The same run, had the server refused two of its ops, does not pass.
  await h.prisma.wikiMaintenanceRun.update({ where: { taskId: made.taskId }, data: { opsRefused: 2 } });
  const refused = await call(h, { runner: s.machine.token }, 'GET', `${route('check')}?expect=${encodeURIComponent(made.expect)}`);
  assert.equal(refused.body.ok, false);
  assert.deepEqual(refused.body.problems, ["The server refused 2 of the run's ops."]);
  // Nor one that said nothing of its ops.
  await h.prisma.wikiMaintenanceRun.update({ where: { taskId: made.taskId }, data: { opsRefused: null } });
  assert.equal((await call(h, { runner: s.machine.token }, 'GET', `${route('check')}?expect=${encodeURIComponent(made.expect)}`)).body.ok, false);
  // A token no task expects: the cursor is past it, and still no run vouches for it.
  const behind = await call(h, { runner: s.machine.token }, 'GET', `${route('check')}?expect=${encodeURIComponent(context.body.expect)}x`);
  expectStatus(behind, 400, 'a token that does not decode is refused');
  assert.equal(behind.body.code, 'WIKI_CURSOR_INVALID');
});
