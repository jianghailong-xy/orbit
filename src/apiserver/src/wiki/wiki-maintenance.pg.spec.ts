  assert.equal(statuses.filter((op) => op.status === 'applied').length, (rehearsal.breaker as { remaining: number }).remaining);
  assert.equal(statuses[2]!.reasons![0]!.code, 'WIKI_QUOTA');
  assert.match(statuses[2]!.reasons![0]!.message, /circuit breaker: this Wiki maintenance run has already changed 10 of the 100 entries/u);
  // Spent: the dry run says nothing remains, and refuses the next.
  const dry = await propose(adds(1, cite, 'dry'), true);
  assert.deepEqual(dry.breaker, { scope: 'run', activeAtStart: 100, changed: 10, remaining: 0 });
  assert.equal((dry.ops as OpOutcome[])[0]!.status, 'refused', 'the run is spent');
  assert.equal(await h.prisma.wikiChangeset.count({ where: { jobId: made.jobId } }), 2, 'no dry run recorded anything');

