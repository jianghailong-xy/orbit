// ── 4. one task at a time ────────────────────────────────────────────────────────────────────────

test('a fact arriving while the maintenance task has not ended makes no second one; the next one after it does', { skip }, async () => {
  const h = await boot();
  const s = await maintainedSpace(h, 'unfinished');
  const sessions = await settledSessions(h, s, WIKI_MAINTENANCE_RULES.backlogThreshold);
  await h.maintenance.cursorState(s.owner.id, s.spaceId);
  // Two facts arriving together: one task between them.
  const both = await Promise.all([consider(h, s, hintOf([sessions[0]!])), consider(h, s, hintOf([sessions[1]!]))]);
  assert.equal(both.filter((outcome) => outcome.made).length, 1, `one of the two made the task: ${JSON.stringify(both)}`);
  assert.equal((await maintenanceTasks(h, s)).length, 1);
  const first = (await maintenanceTasks(h, s))[0]!;

  for (const status of ['OPEN', 'IN_PROGRESS']) {
    await h.sql.query(`UPDATE "task" SET "status" = $2::task_status WHERE "id" = $1`, [first.id, status]);
    const more = await session(h, s.owner.id, { workspaceId: s.workspaceId, lastTurnAt: minutesAgo(8) });
    assert.deepEqual(await consider(h, s, hintOf([more])), { made: false, spaceId: s.spaceId, why: 'unfinished' },
      `a task ${status} is the run this fact waits for`);
  }
  assert.equal((await maintenanceTasks(h, s)).length, 1, 'no second task');

  // It ended (failed, say): the next fact makes the next task, from the same cursor.
  await h.sql.query(`UPDATE "task" SET "status" = 'FAILED' WHERE "id" = $1`, [first.id]);
  const after = await session(h, s.owner.id, { workspaceId: s.workspaceId, lastTurnAt: minutesAgo(6) });
  const second = await consider(h, s, hintOf([after]));
  assert.equal(second.made, true, `the next fact after it ended makes the next task: ${JSON.stringify(second)}`);
  assert.equal((await maintenanceTasks(h, s)).length, 2);
});

// ── the day's limit, in the health ───────────────────────────────────────────────────────────────

test('a due space whose runs for the day are used up makes none, and says so in its health until one is made', { skip }, async () => {
  const h = await boot();
  const s = await maintainedSpace(h, 'limit', { dailyRunLimit: 1 });
  const sessions = await settledSessions(h, s, WIKI_MAINTENANCE_RULES.backlogThreshold);
  const first = await consider(h, s, hintOf([sessions[0]!]));
  assert.equal(first.made, true);
  if (!first.made) return;
  await h.sql.query(`UPDATE "task" SET "status" = 'FAILED' WHERE "id" = $1`, [first.taskId]);

  const next = await session(h, s.owner.id, { workspaceId: s.workspaceId, lastTurnAt: minutesAgo(5) });
  assert.deepEqual(await consider(h, s, hintOf([next])), { made: false, spaceId: s.spaceId, why: 'daily_limit_reached' });
  assert.equal((await maintenanceTasks(h, s)).length, 1, 'no second task today');
  const held = await cursorRow(h, s);
  assert.equal(held.held_reason, 'daily_limit_reached');
  const heldAt = held.held_at!.getTime();
  const state = await h.maintenance.cursorState(s.owner.id, s.spaceId);
  assert.deepEqual(state.held, { reason: 'daily_limit_reached', at: new Date(heldAt).toISOString() }, 'the health says why');
  // A later fact held for the same reason keeps the time it first held.
  const later = await session(h, s.owner.id, { workspaceId: s.workspaceId, lastTurnAt: minutesAgo(4) });
  assert.equal((await consider(h, s, hintOf([later]))).made, false);
  assert.equal((await cursorRow(h, s)).held_at!.getTime(), heldAt);

  // The owner raises the limit: the next fact makes the task, and the health is clear again.
  expectStatus(await call(h, { bearer: s.owner.bearer }, 'PATCH', `/wiki/spaces/${s.spaceId}`, { maintenance: { dailyRunLimit: 2 } }), 200, 'raise the limit');
  const again = await session(h, s.owner.id, { workspaceId: s.workspaceId, lastTurnAt: minutesAgo(3) });
  assert.equal((await consider(h, s, hintOf([again]))).made, true);
  assert.equal((await cursorRow(h, s)).held_reason, null, 'made: held no more');
  assert.equal((await h.maintenance.cursorState(s.owner.id, s.spaceId)).held, null);
});

