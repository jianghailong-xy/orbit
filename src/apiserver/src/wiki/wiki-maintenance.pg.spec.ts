type JobState = 'queued' | 'running' | 'waiting' | 'succeeded' | 'failed' | 'cancelled';

/**
 * A wiki job put in `state` as the worker leaves it: running under a lease, parked on its repository, or ended —
 * what the trigger reads to tell a run that has not ended from one that has.
 */
async function jobIn(h: Harness, jobId: string, state: JobState): Promise<void> {
  const running = state === 'running';
  const ended = state === 'succeeded' || state === 'failed' || state === 'cancelled';
  await h.prisma.wikiJob.update({
    where: { id: jobId },
    data: {
      state,
      leaseOwner: running ? randomUUID() : null,
      leaseGeneration: running ? randomUUID() : null,
      leaseDeadlineAt: running ? new Date(Date.now() + 60_000) : null,
      waitingFor: state === 'waiting' ? 'repo' : null,
      endedAt: ended ? new Date() : null,
    },
  });
}

