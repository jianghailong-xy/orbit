/**
 * The Wiki maintenance job (criterion 3; contracts/wiki.contract.json `maintenance.job`, `maintenance.job.server`),
 * against a real PostgreSQL: the trigger that makes a space's run — a `maintain` job of the wiki worker and the run row
 * that names it — and the services the run reads and writes through, called as the server's run calls them.
 *
 * What criterion 3's verification method asks, each read back from the rows the job wrote:
 *
 *   1. the threshold — twenty sessions with a fact after the cursor make the run, nineteen do not;
 *   2. the day — a fact arriving while the oldest pending fact is more than 24 hours old makes it, and the
 *      age alone, with no fact arriving, makes nothing;
 *   3. no new fact, no run — an event that names nothing new of the space (a session still running, a session
 *      already taken in, another workspace's task) makes nothing, however due;
 *   4. one run at a time — a fact arriving while the space's `maintain` job has not ended makes no second one,
 *      and the next fact after it ended makes the next;
 *   5. the circuit breaker — a maintenance run's changesets are one run to it (the run's wiki job): what the
 *      earlier ones changed through the mode is spent, so the run stops at ten percent of the active entries it
 *      began with, where the same ops in one changeset each would have passed; a dry run says what remains, and
 *      the proposal is refused exactly past it; a run that held back the rest ends succeeded before it;
 *   6. what a failed run left waiting for its verification is the next run's to verify
 *      (`reviewModes.verification.adoption`): it reads them and its verdicts apply, a later op's live entry of
 *      the same content is never joined by a second copy, every floor holds, and nobody but the space's
 *      maintenance run reads them;
 *   7. the documents follow what changed (criterion 3 revision 3, criterion 11): the entries a run wrote make
 *      only the sections they fit to be written again; what fits no section is one plan proposal, and the plan
 *      does not change until the owner confirms; a space with no confirmed plan writes no document; and a
 *      repository file gone from origin/main withdraws the sentences citing it;
 *   8. the cursor moves once a run's ops are recorded (criterion 3 revision 4), and a space that is behind
 *      catches up: its runs are made in catch-up, a failed one is not counted against the day, and after three
 *      failures in a row the catch-up pauses until a run succeeds;
 *
 * and beside them: the daily limit holds a due space and says so in its health; the settings door asks no
 * provider, and the day's limit — 8 by default, 1 to 48 — counts the runs the space's jobs made since midnight
 * UTC; and a run's end that does not say whose its failure was is read off its error.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-maintenance.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the two credential checks are stood in for, as in the other wiki specs.
 */
