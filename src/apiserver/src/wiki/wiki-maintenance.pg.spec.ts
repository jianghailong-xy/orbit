/**
 * The Wiki maintenance job (criterion 3; contracts/wiki.contract.json `maintenance.job`), against a real
 * PostgreSQL and over the runner door's real routes.
 *
 * What criterion 3's verification method asks, each read back from the rows the job wrote:
 *
 *   1. the threshold — twenty sessions with a fact after the cursor make the task, nineteen do not;
 *   2. the day — a fact arriving while the oldest pending fact is more than 24 hours old makes it, and the
 *      age alone, with no fact arriving, makes nothing;
 *   3. no new fact, no task — an event that names nothing new of the space (a session already taken in, the
 *      maintenance run's own session and task, another space's work) makes nothing, however due;
 *   4. one task at a time — a fact arriving while the maintenance task has not ended makes no second one,
 *      and the next fact after it ended makes the next;
 *   5. a truncated run does not move the cursor — it is one more consecutive failure, and its check fails;
 *   6. the circuit breaker — a maintenance run's changesets are one run to it: what the earlier ones
 *      changed through the mode is spent, so the run stops at ten percent of the active entries it began
 *      with, where the same ops in one changeset each would have passed; a dry run says what remains, and
 *      the proposal is refused exactly past it; a run that held back the rest ends succeeded before it;
 *   7. what a failed run left waiting for its verification is the next run's to verify
 *      (`reviewModes.verification.adoption`): it reads them and its verdicts apply, a later op's live entry
 *      of the same content is never joined by a second copy, every floor holds, and nobody but a
 *      maintenance run of the space reads them;
 *   8. the documents follow what changed (criterion 3 revision 3, criterion 11): the owner's confirmation
 *      of a plan version makes one build task — a second confirmation while it runs records one build
 *      that waits, never two, and the build's task ending makes it; the entries a run wrote make only the
 *      sections they fit to be written again; what fits no section is one plan proposal, and the plan does
 *      not change until the owner confirms; a space with no confirmed plan writes no document; and a
 *      repository file gone from origin/main withdraws the sentences citing it;
 *   9. a plan job goes before the next run (2026-10-01): a build or a draft queued behind a maintenance
 *      run is made when the run's task ends — the change published on the run's session, as the runner's
 *      door publishes it — and no fact makes a run while one waits, however due: the trigger makes the
 *      job's task instead; once the job's task ended, the next fact makes the run by the rules as they were;
 *
 * and beside them: the daily limit holds a due space and says so in its health; the task is made pinned,
 * at once, with `orbit wiki check --expect-cursor` as its one criterion; the run proposes as `maintenance`
 * and nobody else may; and the check passes only for a run that reached the position with no op refused.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-maintenance.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the two credential checks are stood in for, as in the other wiki specs.
 */
