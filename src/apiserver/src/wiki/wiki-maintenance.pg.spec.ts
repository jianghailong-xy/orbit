interface Harness {
  base: string;
  sql: Client;
  prisma: PrismaClient;
  app: INestApplication;
  service: WikiService;
  maintenance: WikiMaintenance;
  bearers: Map<string, string>;
  /** What the trigger's owner-scoped announcements said. */
  announced: Array<{ ownerId: string; type: string; change: unknown }>;
  published: Subject<{ runId: string; event: NormalizedRunEvent }>;
  trigger: WikiMaintenanceTrigger;
}

let harness: Promise<Harness> | undefined;

function boot(): Promise<Harness> {
  harness ??= (async () => {
    assertCoordinatorPgUrlIsIsolated(URL);
    const sql = new Client({ connectionString: URL, connectionTimeoutMillis: 5_000 });
    await sql.connect();
    await verifyCoordinatorPgIdentity(sql);
    const prisma = prismaClientFor(URL);
    const bearers = new Map<string, string>();
    const announced: Harness['announced'] = [];
    const published = new Subject<{ runId: string; event: NormalizedRunEvent }>();
    const hub = {
      publishWikiChanged: () => undefined,
      publishForUser: (ownerId: string, type: string, change: unknown) => announced.push({ ownerId, type, change }),
      localPublications: () => published.asObservable(),
    } as unknown as RealtimeService;
    const push = {} as unknown as PushService;
    const service = new WikiService(prisma as unknown as PrismaService, hub, push);
    const maintenance = new WikiMaintenance(prisma as unknown as PrismaService);
    const trigger = new WikiMaintenanceTrigger(prisma as unknown as PrismaService, hub);
    trigger.onModuleInit();

    @Module({
      controllers: [WikiController, RunnerWikiController, RunnerWikiMaintenanceController, RunnerWikiMaintainController],
      providers: [
        { provide: WikiService, useValue: service },
        { provide: WikiMaintenance, useValue: maintenance },
        { provide: WikiRetrieval, useValue: new WikiRetrieval(prisma as unknown as PrismaService) },
        { provide: PrismaService, useValue: prisma },
        RunnerAuthGuard,
        JwtAuthGuard,
        Reflector,
        {
          provide: JwtService,
          useValue: {
            verifyAsync: async (token: string) => {
              const sub = bearers.get(token);
              if (!sub) throw new Error('not a bearer this run issued');
              return { sub, email: `${sub}@wiki.invalid` };
            },
          },
        },
      ],
    })
    class WikiMaintenanceJobModule {}

    const app = await NestFactory.create(WikiMaintenanceJobModule, { logger: false, abortOnError: false });
    app.setGlobalPrefix('api');
    app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
    app.useGlobalInterceptors(new PublicIdInterceptor());
    await app.listen(0, '127.0.0.1');
    return { base: await app.getUrl(), sql, prisma, app, service, maintenance, bearers, announced, published, trigger };
  })();
  return harness;
}

after(async () => {
  if (!harness) return;
  const { app, prisma, sql, trigger } = await harness;
  trigger.onModuleDestroy();
  await app.close().catch(() => undefined);
  await prisma.$disconnect().catch(() => undefined);
  await sql.end().catch(() => undefined);
});

