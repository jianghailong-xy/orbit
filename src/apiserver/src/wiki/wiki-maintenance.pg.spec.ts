/**
 * A space whose maintenance is on, whose first draft job has run on the server: the draft its creation asked for
 * made at once as the worker's `plan_draft` job, stored by that job (`WikiPlans.submitServerDraft`) and ended
 * succeeded (`finishServerJob`) — so the space has a draft for its owner to confirm.
 */
async function plannedSpace(h: Harness, name: string): Promise<PlannedSpace> {
  const owner = await account(h, name);
  const machine = await runner(h, owner.id);
  const workspaceId = await workspace(h, owner.id, '~/orbit');
  const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', {
    title: `${name} space`,
    repoUrl: `https://github.com/spec/${name}-${randomUUID().slice(0, 8)}`,
    maintenance: { workspaceId },
  });
  expectStatus(made, 201, 'the owner creates a space');
  const spaceId = toUuid(made.body.id as string);
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${spaceId}/workspaces`, { workspaceId }), 200, 'the owner binds the workspace');
  const on = await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${spaceId}`, { maintenance: { enabled: true, workspaceId } });
  expectStatus(on, 200, 'the owner turns maintenance on');
  const s: Space = { owner, machine, spaceId, workspaceId };
  await h.sql.query(`INSERT INTO "wiki_topic"("id","space_id","owner_id","slug","title") VALUES ($1,$2,$3,'plans','Plans')`, [randomUUID(), spaceId, owner.id]);
  const { projectId, turnId } = await projectTurn(h, s, '文档先有 plan，owner 确认后再逐节写。');
  // The draft the space's creation asked for: made at once as the worker's job, which stores it and ends.
  const [draftJob] = (await h.sql.query<{ id: string; state: string; job_id: string }>(
    `SELECT "id","state","job_id" FROM "wiki_plan_job" WHERE "space_id" = $1 AND "kind" = 'draft'`, [spaceId])).rows;
  assert.equal(draftJob?.state, 'made', 'the new space\'s draft job is made');
  const drafted = await h.plans.submitServerDraft({ ownerId: owner.id, spaceId, wikiJobId: draftJob.job_id }, {
    baseVersion: null,
    target: { min: 1, max: 10 },
    plan: docsPlan(projectId),
    repoCheck: { sha: 'a'.repeat(40), checked: 3, missing: [] },
    model: 'qwen3.8-27b-fp8',
  });
  assert.equal(await h.plans.finishServerJob({ ownerId: owner.id, spaceId, planJobId: draftJob.id, wikiJobId: draftJob.job_id }, {
    outcome: 'succeeded', version: drafted.version,
  }), true, 'the draft job says it succeeded');
  await jobIn(h, draftJob.job_id, 'succeeded');
  return { ...s, projectId, projectTurnId: turnId, version: drafted.version };
}

