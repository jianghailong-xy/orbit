/** A space bound to a workspace, its maintenance on and pinned to that workspace. */
async function maintainedSpace(h: Harness, name: string, settings: Record<string, unknown> = {}): Promise<Space> {
  const owner = await account(h, name);
  const machine = await runner(h, owner.id);
  const workspaceId = await workspace(h, owner.id, '~/orbit');
  const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: `${name} space`, repoUrl: `https://github.com/spec/${name}-${randomUUID().slice(0, 8)}` });
  expectStatus(made, 201, 'the owner creates a space');
  const spaceId = toUuid(made.body.id as string);
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${spaceId}/workspaces`, { workspaceId }), 200, 'the owner binds the workspace');
  const on = await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${spaceId}`, {
    maintenance: { enabled: true, workspaceId, provider: 'local-vllm', ...settings },
  });
  expectStatus(on, 200, 'the owner turns maintenance on');
  return { owner, machine, spaceId, workspaceId, listId: toUuid(on.body.settings.maintenance.listId as string) };
}

/** Sessions of the space that came to rest about `minutes` ago, each one fact: the first the oldest. */
async function settledSessions(h: Harness, s: Space, count: number, minutes = 30): Promise<string[]> {
  const ids: string[] = [];
  for (let n = 0; n < count; n += 1) {
    ids.push(await session(h, s.owner.id, { workspaceId: s.workspaceId, lastTurnAt: minutesAgo(minutes + (count - n) / 10) }));
  }
  return ids;
}

