/**
 * The run a Wiki maintenance session is claimed with (contracts/wiki.contract.json `maintenance.run`,
 * wiki-maintenance-session.ts), against a real PostgreSQL, through the claim and the reclaim a runner makes:
 *
 *   1. only a maintenance session gets it — the provider and workspace its space's settings pin it to, no
 *      provider to fall back to, 120 model turns, sub-agents and the web disallowed, the clean start — and
 *      its agent config carries the same guardrails; an ordinary session, and a task session of any other
 *      list, get none of it;
 *   2. a runner that does not declare wiki-maintenance-run/v1 is never handed one, on the claim or the reclaim;
 *   3. the pin holds and nothing falls back: a provider turned off, deleted, on another runtime or an account
 *      pool, a session that names another provider or sits in another workspace, and maintenance turned off —
 *      each is claimed with its refusal and with no other provider's endpoint, and no pool member is chosen —
 *      while an ordinary session on a provider that cannot dispatch still waits, PENDING, and says why;
 *   4. the settings door takes only a provider on the Claude Code runtime, and `dailyRunLimit` — 8 by
 *      default, 1 to 48 — is what `wikiMaintenanceRunsToday` counts the day's runs against.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-maintenance-session.pg.spec.ts
 *
 * Not destructive: every id is generated by the run. Only the two credential checks are stood in for.
 */
