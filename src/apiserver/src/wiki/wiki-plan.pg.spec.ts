/**
 * The plan (criterion 11; contracts/wiki.contract.json `plan`, migration 0325), over real HTTP and
 * against a real PostgreSQL.
 *
 * What the task's verification asks, each read back from the doors and from the database:
 *
 *   1. with no confirmed plan, `requireConfirmedPlan` refuses — a draft is not enough;
 *   2. a revision is a new version, and a confirmed version does not change: its rows are the same
 *      bytes after every later draft, edit and confirmation;
 *   3. the gate stops a draft with a field outside the schema, a document count outside its target, a
 *      protected document changed, or a project or topic that does not exist — and says each one;
 *   4. a proposal changes nothing before the owner accepts it;
 *   5. another tenant's read is a 404, every one of them, and a confirmation that carries a session
 *      header is refused.
 *
 * and beside them what the design leans on: a field declared as needing adding passes and is shown,
 * only a maintenance run of the space drafts or proposes, a draft built on a version that is no longer
 * the newest is refused, and the migration's CHECKs are the contract's closed sets.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-plan.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the two credential checks are stood in for, as in the other wiki specs.
 */
