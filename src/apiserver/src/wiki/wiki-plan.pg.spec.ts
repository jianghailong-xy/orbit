test('a proposal changes nothing until the owner accepts it; accepting makes a draft, rejecting changes nothing', { skip }, async () => {
  const h = await boot();
  const s = await scene(h);
  expectStatus(await draft(h, s, null, planOf(20)), 200, 'the first draft');
  expectStatus(await confirm(h, s, 1), 200, 'the owner confirms it');
  const before = await snapshot(h, s.spaceId, 1);
  const knowledge = await entry(h, s.owner.id, s.spaceId);

  const propose = (body: Record<string, unknown>): Promise<Answer> =>
    call(h, s.maintainer, 'POST', `/runner/wiki/spaces/${s.spaceId}/plan/proposals`, body);
  // A new document in a new category, for knowledge that fits no section.
  const newDoc = docOf(20, 21, { category: 'ops', slug: 'backups' });
  const made = await propose({
    reason: 'Backups came up in three sessions and no document covers them.',
    change: { doc: newDoc, category: { key: 'ops', title: 'Operations' } },
    facts: [{ kind: 'entry', id: knowledge }, { kind: 'session', id: s.maintenanceSession }],
  });
  expectStatus(made, 200, 'a proposal for a new document');
  assert.equal(made.body.status, 'pending');
  assert.equal(made.body.baseVersion, 1);
  // A section added to an existing document, the other way a proposal changes the plan.
  const extended = docOf(5, 20);
  (extended.sections as unknown[]).push({ title: 'Decisions', kind: 'decisions', covers: 'Why it is this way.', length: 400, sources: { sessions: { projects: [PROJECT], keywords: ['why'] } } });
  const second = await propose({ reason: 'A decision that fits no section of doc-5.', change: { doc: extended }, facts: [{ kind: 'entry', id: knowledge }] });
  expectStatus(second, 200, 'a proposal that adds a section');

  // Before anyone answers, the plan is as it was: the same versions, the same confirmed rows.
  assert.deepEqual(await statuses(h, s.spaceId), [[1, 'confirmed']]);
  assert.equal(await snapshot(h, s.spaceId, 1), before, 'a pending proposal changed the confirmed version');
  const state = await planState(h, s);
  expectStatus(state, 200, 'the plan');
  assert.equal(state.body.draft, null);
  assert.equal(state.body.confirmed.docs.length, 20);
  assert.deepEqual(state.body.proposals.map((p: { id: string }) => toUuid(p.id)), [toUuid(made.body.id as string), toUuid(second.body.id as string)]);

  // The gate holds a proposal too: a protected document, a fact that is not one, a field made up.
  const bad = await propose({
    reason: 'x',
    change: { doc: docOf(21, 22, { slug: 'extra-doc', protected: true, mood: 'hopeful' }) },
    facts: [{ kind: 'entry', id: randomUUID() }],
  });
  expectGate(bad, 'protected', 'plan.docs[20].protected', 'a proposal that protects a document');
  expectGate(bad, 'schema', 'change.doc.mood', 'a proposal with a field the schema does not have');
  expectGate(bad, 'references', 'facts[0].id', 'a proposal naming an entry that does not exist');
  assert.equal((await planState(h, s)).body.proposals.length, 2, 'a refused proposal was stored');

  // Rejecting one changes nothing but the proposal.
  const rejected = await call(h, { bearer: s.owner.bearer }, 'POST', `/wiki/plan-proposals/${made.body.id}/decide`, { action: 'reject', note: 'Not now.' });
  expectStatus(rejected, 200, 'the owner rejects the first proposal');
  assert.equal(rejected.body.proposal.status, 'rejected');
  assert.equal(rejected.body.proposal.decisionNote, 'Not now.');
  assert.equal(rejected.body.draft, null);
  assert.deepEqual(await statuses(h, s.spaceId), [[1, 'confirmed']]);
  assert.equal(await snapshot(h, s.spaceId, 1), before, 'a rejection changed the confirmed version');
  const twice = await call(h, { bearer: s.owner.bearer }, 'POST', `/wiki/plan-proposals/${made.body.id}/decide`, { action: 'accept' });
  expectStatus(twice, 409, 'answering a decided proposal');
  assert.equal(twice.body.code, 'WIKI_PLAN_STALE');

  // Accepting the other makes a draft with the section added; the confirmed version is still the one in force.
  const accepted = await call(h, { bearer: s.owner.bearer }, 'POST', `/wiki/plan-proposals/${second.body.id}/decide`, { action: 'accept' });
  expectStatus(accepted, 200, 'the owner accepts the second proposal');
  assert.equal(accepted.body.proposal.status, 'accepted');
  assert.equal(accepted.body.proposal.resultVersion, 2);
  assert.equal(accepted.body.draft.version, 2);
  assert.equal(toUuid(accepted.body.draft.proposalId as string), toUuid(second.body.id as string));
  assert.deepEqual(accepted.body.draft.docs[5].sections.map((section: { key: string; title: string }) => [section.key, section.title]), [
    ['s1', 'Overview'],
    ['s2', 'How it runs'],
    ['s3', 'Known pitfalls'],
    ['s4', 'Decisions'],
  ]);
  assert.deepEqual(await statuses(h, s.spaceId), [[1, 'confirmed'], [2, 'draft']]);
  assert.equal(await snapshot(h, s.spaceId, 1), before, 'an acceptance changed the confirmed version');
  const pending = await planState(h, s);
  assert.equal(pending.body.proposals.length, 0);
  assert.equal(pending.body.draft.version, 2);
});

