/** A document as the database holds it: its sections by key, each with its sentences and their footnotes in order. */
async function stored(h: Harness, spaceId: string, slug: string) {
  const doc = await h.prisma.wikiDoc.findFirst({
    where: { spaceId, slug },
    include: {
      sections: {
        include: { sentences: { orderBy: { position: 'asc' }, include: { footnotes: { orderBy: { position: 'asc' } } } } },
      },
    },
  });
  return { doc, sections: new Map((doc?.sections ?? []).map((section) => [section.key, section])) };
}

/** The values a CHECK spells out, in the order it spells them. */
async function checkValues(h: Harness, table: string, constraint: string): Promise<string[]> {
  const def = await h.sql.query<{ def: string }>(
    `SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conname = $1 AND conrelid = $2::regclass`,
    [constraint, table],
  );
  assert.equal(def.rowCount, 1, `${table} has no constraint ${constraint}`);
  return [...def.rows[0].def.matchAll(/'([^']+)'::text/gu)].map((m) => m[1]);
}

