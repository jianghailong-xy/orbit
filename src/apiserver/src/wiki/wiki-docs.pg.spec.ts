test('the migration\'s CHECKs are the contract\'s closed sets, and deleting the space deletes its documents', { skip }, async () => {
  const h = await boot();
  assert.deepEqual(await checkValues(h, 'wiki_doc', 'wiki_doc_status_chk'), [...WIKI_DOC_STATUSES]);
  assert.deepEqual(await checkValues(h, 'wiki_doc_sentence', 'wiki_doc_sentence_status_chk'), [...WIKI_DOC_SENTENCE_STATUSES]);
  assert.deepEqual(await checkValues(h, 'wiki_doc_sentence', 'wiki_doc_sentence_withdrawn_reason_chk'), [...WIKI_DOC_WITHDRAW_REASONS]);
  assert.deepEqual(await checkValues(h, 'wiki_doc_footnote', 'wiki_doc_footnote_kind_chk'), [...WIKI_DOC_FOOTNOTE_KINDS]);
  assert.deepEqual(await checkValues(h, 'wiki_doc_footnote', 'wiki_doc_footnote_verdict_chk'), [...WIKI_DOC_VERDICTS]);
  assert.deepEqual(await checkValues(h, 'wiki_doc_footnote', 'wiki_doc_footnote_checked_by_chk'), [...WIKI_DOC_CHECKERS]);
  assert.deepEqual(CONTRACT.docs.tables, ['wiki_doc', 'wiki_doc_section', 'wiki_doc_sentence', 'wiki_doc_footnote']);

  const s = await scene(h);
  const version = await confirmPlan(h, s);
  expectStatus(await writeDoc(h, s, 'session-runtime', writeBody(version, [{
    key: 's2',
    markdown: '派发由 `claimTask` 开始[1]。',
    footnotes: [code('export function claimTask(')],
  }])), 200, 'a document');
  const { sections } = await stored(h, s.spaceId, 'session-runtime');
  const sentence = sections.get('s2')!.sentences[0];
  // A repository footnote with no sha, written past the service, is refused by its CHECK.
  const unpinned = await h.sql.query(
    `INSERT INTO "wiki_doc_footnote"("id","sentence_id","owner_id","position","kind","ref","verdict","checked_by","quote")
     VALUES ($1,$2,$3,5,'code','src/x.ts','verified','runner','x')`,
    [randomUUID(), sentence.id, s.owner.id],
  ).then(() => null, (e: Error) => e);
  assert.ok(unpinned, 'a code footnote with no sha was stored');
  assert.match(unpinned.message, /wiki_doc_footnote_repository_chk/u);
  // A withdrawn sentence that says nothing of why is refused by its CHECK.
  const unexplained = await h.sql.query(`UPDATE "wiki_doc_sentence" SET "status" = 'withdrawn' WHERE "id" = $1`, [sentence.id]).then(() => null, (e: Error) => e);
  assert.ok(unexplained, 'a withdrawal with no reason was stored');
  assert.match(unexplained.message, /wiki_doc_sentence_withdrawn_chk/u);

  await h.sql.query(`DELETE FROM "wiki_space" WHERE "id" = $1`, [s.spaceId]);
  const left = await h.sql.query<{ n: number }>(
    `SELECT ((SELECT count(*) FROM "wiki_doc" WHERE "owner_id" = $1)
           + (SELECT count(*) FROM "wiki_doc_section" WHERE "owner_id" = $1)
           + (SELECT count(*) FROM "wiki_doc_sentence" WHERE "owner_id" = $1)
           + (SELECT count(*) FROM "wiki_doc_footnote" WHERE "owner_id" = $1))::int AS n`,
    [s.owner.id],
  );
  assert.equal(left.rows[0].n, 0);
});
