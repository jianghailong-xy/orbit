test('a quote is found folded, as one passage: punctuation, emphasis, code marks and comment markers aside — never translated, spliced or elided', () => {
  // Full-width punctuation reads as ASCII, whitespace goes, ** and backticks go.
  assert.ok(findQuote(T1, '先存后投: turn 先落库, runner 再通过出站 long-poll 从 inbox 领取'));
  assert.ok(findQuote(E1, 'inbox handler 会 hold 至多 25 秒，然后返回 204'));
  assert.ok(findQuote('用 \\*星号\\* 转义', '用 *星号* 转义'), 'a Markdown escape reads as what it escapes');
  // A code comment's words, without the marker each line starts with.
  assert.ok(findQuote('    // Park until a turn is enqueued\n    // for this run.', 'Park until a turn is enqueued for this run.'));
  assert.ok(findQuote('# 标题行\n正文', '标题行正文'));
  // Where it was found is where it is, in code points of the source.
  const at = findQuote(T1, '先存后投: turn 先落库, runner 再通过出站 long-poll 从 inbox 领取');
  assert.equal(Array.from(T1).slice(at!.start, at!.end).join(''), '先存后投：turn 先落库，runner 再通过出站 long-poll 从 inbox 领取');
  // Not the words: made up, translated, two passages joined, an ellipsis over a gap, a summary.
  assert.equal(findQuote(T1, '网关的 WebSocket 握手总是成功'), null);
  assert.equal(findQuote(T1, 'Store first, then deliver: the turn lands in the database first'), null);
  assert.equal(findQuote(T1, '先存后投，所以别用 WebSocket'), null);
  assert.equal(findQuote(T1, '先存后投……从 inbox 领取'), null);
  assert.equal(findQuote(T1, 'Runner 用 long-poll 领取 turn'), null);
  // Too short to say anything: found nowhere.
  assert.equal(findQuote(T1, '先存'), null);
  // A range narrows the search.
  assert.equal(findQuote(T1, '所以别用 WebSocket', { start: 0, end: 20 }), null);
  assert.ok(findQuote(T1, '所以别用 WebSocket', { start: 0, end: Array.from(T1).length }));
});

