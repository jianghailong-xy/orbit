/**
 * Orbit Wiki's retrieval, over real HTTP and against a real PostgreSQL.
 *
 * What is under test is what a caller gets back — the entries, why each one matched, and the order
 * — so every request goes through the real controllers, the real WikiRetrieval and WikiService, the
 * global ValidationPipe and the public-id interceptor, and every fixture is written through the
 * doors a client uses. Only the two credential checks are stood in for (`JwtService.verifyAsync`
 * answers with the account a bearer was issued to, and the runner guard reads the runner row this
 * file wrote), which is what `wiki-api.pg.spec.ts` stands in for and for the same reason.
 *
 * The design is §6 and the contract is `searchMatches`; each case below is one of the behaviours
 * this task's acceptance criteria names: a Chinese query reaching a Chinese entry, a Chinese word
 * reaching an entry whose only Chinese is an alias, a path reaching an entry through its anchor or
 * its pitfall trigger, an entry that both legs found ranking above one only the keyword leg did,
 * tenant and space isolation on both doors, the match reasons the contract lists, and the semantic
 * placeholder changing nothing. And what the read fix added: the keyword leg's last pass, and the
 * `wiki_exposure` row a session's search or read leaves, which a failed write does not cost the read.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-search.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created.
 */
