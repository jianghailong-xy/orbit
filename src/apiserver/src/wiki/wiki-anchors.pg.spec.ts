test('a report against a revision that moved is stale, and a malformed one is refused, writing nothing', { skip }, async () => {
  const h = await boot();
  const m = await maintainedSpace(h, 'stale');
  const entryId = await ownerEntry(h, m, 'Paths are repo-relative', [{ type: 'path', path: 'docs/a.md' }, { type: 'symbol', path: 'src/a.ts', symbol: 'foo' }]);
  const amended = await call(h, { bearer: m.owner.bearer }, 'POST', `/wiki/spaces/${m.spaceId}/changesets`, {
    rationale: 'the owner sharpens it',
    idempotencyKey: `anchors-${randomUUID()}`,
    ops: [{ op: 'amend', entryId, baseRevision: 1, changes: { summary: 'Paths are repo-relative, with no leading slash.' } }],
  });
  expectStatus(amended, 200, 'the owner amends the entry after the list was read');

  const late = await report(h, m, REF_1, [{ entryId, revision: 1, checks: [{ index: 0, type: 'path', state: 'missing' }] }]);
  expectStatus(late, 200, 'a stale entry is no failure of the report');
  assert.equal(late.body.outcomes[0].status, 'stale');
  assert.match(late.body.outcomes[0].message, /revision 2/u);
  const wrongType = await report(h, m, REF_1, [{ entryId, revision: 2, checks: [{ index: 0, type: 'symbol', state: 'missing' }] }]);
  expectStatus(wrongType, 200, 'an anchor list that moved');
  assert.equal(wrongType.body.outcomes[0].status, 'stale');
  let row = await entryRow(h, entryId);
  assert.equal(row.anchorState, 'unchecked', 'nothing of a stale report is written');
  assert.equal(row.anchorCheckedRef, null);

  const badRef = await report(h, m, 'origin/main', [{ entryId, revision: 2, checks: [{ index: 0, type: 'path', state: 'verified' }] }]);
  expectStatus(badRef, 400, 'the ref is a commit sha');
  assert.equal(badRef.body.code, 'WIKI_SCHEMA');
  const noHash = await report(h, m, REF_1, [{ entryId, revision: 2, checks: [{ index: 1, type: 'symbol', state: 'verified' }] }]);
  expectStatus(noHash, 400, 'a symbol found carries the hash of its region');
  assert.equal(noHash.body.outcomes[0].code, 'WIKI_SCHEMA');
  assert.match(noHash.body.outcomes[0].message, /regionSha256/u);
  const pathChanged = await report(h, m, REF_1, [{ entryId, revision: 2, checks: [{ index: 0, type: 'path', state: 'changed' }] }]);
  expectStatus(pathChanged, 400, 'a path is verified or missing, never changed');
  const elsewhere = await maintainedSpace(h, 'elsewhere');
  const foreign = await ownerEntry(h, elsewhere, 'Not this space', [{ type: 'path', path: 'docs/a.md' }]);
  const notHere = await report(h, m, REF_1, [{ entryId: foreign, revision: 1, checks: [{ index: 0, type: 'path', state: 'missing' }] }]);
  expectStatus(notHere, 404, "another space's entry is not this space's to report");
  row = await entryRow(h, entryId);
  assert.equal(row.anchorState, 'unchecked', 'no refused report wrote anything');
  assert.equal((await entryRow(h, foreign)).anchorState, 'unchecked');

  // And one that is well formed now: both anchors, at the entry's current revision.
  const good = await report(h, m, REF_1, [{ entryId, revision: 2, checks: [
    { index: 0, type: 'path', state: 'verified' },
    { index: 1, type: 'symbol', state: 'verified', regionSha256: REGION_1 },
  ] }]);
  expectStatus(good, 200, 'a report of the current revision');
  assert.equal(good.body.outcomes[0].anchorState, 'verified');
});

// ── Tiered reads what a check writes ────────────────────────────────────────────────────────────

test('a pitfall Tiered applied as Unreviewed becomes Auto once its anchors verify, when its sources span two sessions', { skip }, async () => {
  const h = await boot();
  const m = await maintainedSpace(h, 'tiered');
  const space = await h.prisma.wikiSpace.findFirstOrThrow({ where: { id: m.spaceId } });
  assert.equal((space.settings as { reviewMode?: string }).reviewMode, 'tiered', 'a space made today is Tiered');
  const proposer = await session(h, m.owner.id, m.workspaceId, m.machine.id);
  const first = await toolCall(h, await session(h, m.owner.id, m.workspaceId, m.machine.id), 'exited 0 with every case skipped');
  const second = await toolCall(h, await session(h, m.owner.id, m.workspaceId, m.machine.id), 'the same spec skipped every case again');
  const agent: WikiPrincipal = { origin: 'agent', ownerId: m.owner.id, userId: null, sessionId: proposer, toolCallId: null };
  const pitfall = (title: string, sources: unknown[]) => ({
    op: 'add',
    entry: {
      kind: 'pitfall',
      title,
      summary: 'A green run that witnessed no assertion.',
      fields: {
        trigger: { paths: ['src/apiserver/src/wiki/'], commands: ['node --test build/wiki/x.pg.spec.js'] },
        symptom: 'A green run that witnessed no assertion.',
        cause: 'A pg spec skips itself without a database.',
        fix: 'Run it through scripts/run-pg-spec.sh.',
      },
      anchors: [{ type: 'path', path: 'scripts/run-pg-spec.sh' }],
    },
    sources,
  });
  const proposed = await h.service.submitChangeset(agent, m.spaceId, {
    rationale: 'two pitfalls this session ran into',
    idempotencyKey: `anchors-${randomUUID()}`,
    ops: [
      pitfall('A pg spec with no database skips green', [
        { kind: 'tool_call', ref: first, quote: 'exited 0 with every case skipped' },
        { kind: 'tool_call', ref: second, quote: 'skipped every case again' },
      ]),
      pitfall('One session saw a skipped spec', [{ kind: 'tool_call', ref: first, quote: 'every case skipped' }]),
    ],
  });
  const [twice, once] = (proposed.ops as Array<{ status: string; entryId: string }>).map((op) => {
    assert.equal(op.status, 'applied', 'Tiered applies an add at once');
    return toUuid(op.entryId);
  });
  for (const id of [twice, once]) {
    const row = await entryRow(h, id);
    assert.equal(row.trust, 'unreviewed', 'a new pitfall\'s anchors are unchecked, so it is not machine-verified yet');
  }
  const unpushed = await pushed(h, m);
  assert.equal(unpushed.has(twice), false, 'an unreviewed entry is never pushed');

  const checked = await report(h, m, REF_1, [
    { entryId: twice, revision: 1, checks: [{ index: 0, type: 'path', state: 'verified' }] },
    { entryId: once, revision: 1, checks: [{ index: 0, type: 'path', state: 'verified' }] },
  ]);
  expectStatus(checked, 200, 'the check is recorded');
  assert.deepEqual(checked.body.outcomes.map((outcome: { trust: string }) => outcome.trust), ['auto', 'unreviewed'],
    'verified anchors and two sessions make a pitfall Auto; one session does not');
  assert.equal((await entryRow(h, twice)).trust, 'auto');
  assert.equal((await entryRow(h, once)).trust, 'unreviewed');
  const handed = await pushed(h, m);
  assert.equal(handed.has(twice), true, 'what Tiered made Auto is pushed');
  assert.equal(handed.has(once), false);

  // And a pitfall the check found broken is out of the push again, challenged, and keeps its trust for the owner to judge.
  const broken = await report(h, m, REF_2, [{ entryId: twice, revision: 1, checks: [{ index: 0, type: 'path', state: 'missing' }] }]);
  expectStatus(broken, 200, 'the next check');
  assert.equal(broken.body.outcomes[0].challenged, true);
  assert.equal((await pushed(h, m)).has(twice), false);
  // Re-confirming what the machine wrote confirms it.
  const challenge = await theChallenge(h, m, twice);
  expectStatus(await decide(h, m, challenge.changesetId, { opId: challenge.opId, action: 'reconfirm' }), 200, 'the owner re-confirms');
  const confirmed = await entryRow(h, twice);
  assert.equal(confirmed.trust, 'confirmed');
  assert.deepEqual(confirmed.anchors, [], 'the anchor that went is dropped');
  assert.equal(confirmed.anchorState, 'unchecked', 'an entry with no anchor is unchecked');
  const sources = await h.prisma.wikiSource.count({ where: { revision: { entryId: twice, revision: confirmed.currentRevision } } });
  assert.equal(sources, 2, 'the owner\'s revision rests on the sources the entry rested on');
  assert.equal(confirmed.unsupported, false);
  assert.equal((await pushed(h, m)).has(twice), true, 'and it is pushed again');
});
