/** The refs a run checked on, and the region hashes it found: the server takes both as reported. */
const REF_1 = createHash('sha1').update('origin/main, first check').digest('hex');
const REF_2 = createHash('sha1').update('origin/main, second check').digest('hex');
const REF_3 = createHash('sha1').update('origin/main, third check').digest('hex');
const REGION_1 = createHash('sha256').update('export function foo() {\n').digest('hex');
const REGION_2 = createHash('sha256').update('export function foo(bar: string) {\n').digest('hex');
const COMMIT = createHash('sha1').update('a commit the entry names').digest('hex');

