/**
 * The anchor re-verification (criterion 4; contracts/wiki.contract.json `anchorRules.verify`), over
 * real HTTP and against a real PostgreSQL.
 *
 * What criterion 4's verification method asks, each read back from the doors and from the database:
 *
 *   1. an entry whose anchor a check finds missing or changed is not in the next push;
 *   2. Review holds one more card for it: a system challenge, filed once however often the check says so;
 *   3. the owner's Re-confirm (a new baseline), Amend and Retire each do what they say, on the owner's
 *      door alone;
 *   4. a session that is not a maintenance run of the space reports nothing;
 *
 * and beside them: the list hands out each entry's git anchors at its revision, and the checkout the
 * space's workspace names as stored; a symbol is held to its baseline by the server whatever the runner
 * says; a report against a revision that moved is stale and writes nothing; a revision stores its
 * anchors without the check; and a Tiered pitfall whose anchors verified becomes Auto when its sources
 * span two sessions, and only then.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-anchors.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the two credential checks are stood in for, as in the other wiki specs.
 */
