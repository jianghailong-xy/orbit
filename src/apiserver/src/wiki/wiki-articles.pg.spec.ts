test('another owner reads none of it: every read is a 404', { skip }, async () => {
  const h = await boot();
  const s = await setUp(h);
  // Make sure there is something to read.
  const own = await input(h, s.maintainer, s.spaceId, 'web-client');
  await call(h, s.maintainer, 'POST', `/runner/wiki/spaces/${s.spaceId}/articles/web-client`, writeBody(own.body.entrySetSha256, [
    { part: 0, kind: 'article', title: 'Web 客户端', markdown: 'lib 里一律走 api 模块[1]。', notes: [s.e.web] },
  ]));
  expectStatus(await call(h, { bearer: s.owner.bearer }, 'GET', `/wiki/spaces/${s.spaceId}/articles/web-client`), 200, 'the owner reads it');

  const stranger = await account(h, 'reader from elsewhere');
  const reads = [
    `/wiki/spaces/${s.spaceId}/articles`,
    `/wiki/spaces/${s.spaceId}/articles/web-client`,
    `/wiki/spaces/${s.spaceId}/articles/web-client/1`,
    `/wiki/spaces/${s.spaceId}/article-index`,
  ];
  for (const route of reads) {
    const answer = await call(h, { bearer: stranger.bearer }, 'GET', route);
    expectStatus(answer, 404, `another owner reads ${route}`);
    assert.ok(!JSON.stringify(answer.body).includes('Web 客户端'), 'and learns nothing of it');
  }
  // Their own space with the same slugs is theirs alone, and empty.
  const theirWs = await workspace(h, stranger.id);
  const theirSpace = await space(h, stranger, theirWs, 'The reader\'s own space');
  const theirs = await call(h, { bearer: stranger.bearer }, 'GET', `/wiki/spaces/${theirSpace}/articles`);
  expectStatus(theirs, 200, 'their own directory');
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  assert.equal(theirs.body.categories.flatMap((c: any) => c.topics).length, 0, 'a space nobody planned has no topic');
  expectStatus(await call(h, { bearer: stranger.bearer }, 'GET', `/wiki/spaces/${theirSpace}/articles/web-client`), 404, 'no such topic in their space');
  // And the owner's own address mistakes are 404s too.
  expectStatus(await call(h, { bearer: s.owner.bearer }, 'GET', `/wiki/spaces/${s.spaceId}/articles/no-such-topic`), 404, 'an unknown topic');
  expectStatus(await call(h, { bearer: s.owner.bearer }, 'GET', `/wiki/spaces/${s.spaceId}/articles/sessions`), 404, 'a topic with no article yet');
  expectStatus(await call(h, { bearer: s.owner.bearer }, 'GET', `/wiki/spaces/${randomUUID()}/articles`), 404, 'an unknown space');
});
