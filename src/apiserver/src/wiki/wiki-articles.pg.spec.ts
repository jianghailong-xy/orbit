/** One topic's generation input, read as the maintenance run reads it. */
async function input(h: Harness, who: Caller, spaceId: string, slug: string): Promise<Answer> {
  return call(h, who, 'GET', `/runner/wiki/spaces/${spaceId}/articles/${slug}/input`);
}

/** The entry ids an input answer carries, as uuids. */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const inputIds = (answer: Answer): string[] => answer.body.entries.map((entry: any) => toUuid(entry.id as string));

/** The values a CHECK spells out, in the order it spells them. */
async function checkValues(h: Harness, table: string, constraint: string): Promise<string[]> {
  const def = await h.sql.query<{ def: string }>(
    `SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conname = $1 AND conrelid = $2::regclass`,
    [constraint, table],
  );
  assert.equal(def.rowCount, 1, `${table} has no constraint ${constraint}`);
  return [...def.rows[0].def.matchAll(/'([^']+)'::text/gu)].map((m) => m[1]);
}

