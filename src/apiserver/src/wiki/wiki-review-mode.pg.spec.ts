/**
 * A space's review mode — Manual, Tiered, Automatic — over real HTTP and against a real PostgreSQL
 * (criterion 7 of the wiki's phase 2; contracts/wiki.contract.json `reviewModes`).
 *
 * The four things the criterion's verification names are four cases here, each read back from the
 * database and from the push the way a session would be handed it:
 *
 *   1. three modes × six kinds × three kinds of source (the owner's own words, a machine
 *      verification, an agent's say-so alone), cell by cell: what took effect, with which trust, and
 *      whether the next session is pushed it — in Automatic, nothing before its verdict, and what a
 *      supported verdict applies after it (revision 3; `wiki-verify.pg.spec.ts` takes the verdicts
 *      one by one);
 *   2. each of the five floors, in Automatic, with a counter-example that is not let through;
 *   3. Tiered's spot checks drawn by fact, a reject rate over the line sending the space back to
 *      Manual, and the owner told once — not again on the next rejection;
 *   4. a whole run reverted, and every entry it touched out of the push.
 *
 * Around them, what those four rest on: who may switch a mode (the owner's JWT, never a session), a
 * new space Tiered and an old one Manual, the owner's Reject of one entry, and the one-off import
 * the preview space is loaded with — origin import, authored by the system, bare record ids for
 * sources, an idempotency key that keeps a replay from writing twice, and thirty ops a changeset.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-review-mode.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the two credential checks are stood in for, as in `wiki-api.pg.spec.ts`; the push is
 * the real `appendWikiContext`, and the owner's notification a stand-in that records each call.
 */
