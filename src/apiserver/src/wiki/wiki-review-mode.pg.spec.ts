// ── 1. the matrix ───────────────────────────────────────────────────────────────────────────────

/**
 * Criterion 7's first assertion: every mode, every kind, every kind of source.
 *
 * - The owner's own words: an add citing a message the owner sent from the web, quoted verbatim.
 * - A machine verification: the next amend of an entry a mode applied before, whose anchors the
 *   re-verification found `verified`, citing records from two independent sessions and leaving the
 *   anchors alone. (A new entry's anchors are unchecked, so an add is never machine-verified.)
 * - An agent's say-so alone: an add citing the agent's own tool output.
 *
 * Each cell says what took effect (`pending`, applied `auto`, applied `unreviewed`, or the refusal
 * code), and whether a session starting next in the space's workspace is pushed it. An Automatic cell
 * takes effect only through its verdict (revision 3): before one, it waits and nothing of it is
 * pushed; a supported verdict applies it as `auto`, which is the cell's effect.
 */
type Source = 'owner_words' | 'machine_verified' | 'agent_alone';
type Cell = { effect: 'pending' } | { effect: 'applied'; trust: 'auto' | 'unreviewed' } | { effect: 'refused'; code: string };

function expected(mode: Mode, kind: WikiKind, source: Source): Cell {
  // Floor one, in every mode: a principle is the owner's to write.
  if (kind === 'principle') return { effect: 'refused', code: 'WIKI_KIND_OWNER_ONLY' };
  // The machine-verified op is an amend, and a decision is only ever superseded.
  if (source === 'machine_verified' && !KIND_SPECS[kind].amendable) return { effect: 'refused', code: 'WIKI_SCHEMA' };
  if (mode === 'manual') return { effect: 'pending' };
  // Once its verdict says supported: before it, the op waits for its verification (asserted apart).
  if (mode === 'automatic') return { effect: 'applied', trust: 'auto' };
  const auto =
    (source === 'owner_words' && (kind === 'decision' || kind === 'convention'))
    // A recipe is machine-verified by a green re-run of its verify command, which nothing reports yet.
    || (source === 'machine_verified' && kind === 'pitfall');
  return { effect: 'applied', trust: auto ? 'auto' : 'unreviewed' };
}

test('review modes · three modes × six kinds × three sources, cell by cell', { skip, concurrency: 1, timeout: 600_000 }, async () => {
  const h = await boot();
  const table: string[] = [];
  for (const mode of ['manual', 'tiered', 'automatic'] as const) {
    const owner = await account(h, `matrix ${mode}`);
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    const space = await modeSpace(h, owner, mode, ws);
    // Where the cited records live: the owner's conversation, and two agent sessions of their own.
    const talk = await session(h, owner.id, ws, machine);
    const said = 'We decided: a closed set is a TEXT column with a CHECK constraint, never an enum type.';
    const ownerTurn = await turn(h, talk, said);
    const first = await session(h, owner.id, ws, machine);
    const second = await session(h, owner.id, ws, machine);
    const firstCall = await toolCall(h, first, 'Bash', 'node --test build/wiki/x.pg.spec.js exited 0 with every case skipped');
    const secondCall = await toolCall(h, second, 'Bash', 'the same spec skipped every case again in a second session');

    const cells: Array<{ kind: WikiKind; source: Source; outcome: Outcome; entryId: string | null; proposer: string }> = [];
    for (const kind of WIKI_KINDS) {
      for (const source of ['owner_words', 'machine_verified', 'agent_alone'] as const) {
        // One session per cell: in Manual every op here waits, and a session's quota counts those.
        const proposer = await session(h, owner.id, ws, machine);
        const title = `${mode} ${kind} from ${source.replace('_', ' ')}`;
        let op: Record<string, unknown>;
        if (source === 'owner_words') {
          op = { op: 'add', entry: draft(kind, title), sources: [{ kind: 'turn', ref: ownerTurn, quote: 'a closed set is a TEXT column with a CHECK constraint' }] };
        } else if (source === 'agent_alone') {
          const own = await toolCall(h, proposer, 'Bash', `what this session saw about ${title}`);
          op = { op: 'add', entry: draft(kind, title), sources: [{ kind: 'tool_call', ref: own, quote: `what this session saw about ${title}` }] };
        } else {
          const target = await machineEntry(h, owner.id, space, kind, title, { sourceSession: first });
          op = {
            op: 'amend',
            entryId: target,
            baseRevision: 1,
            changes: { summary: `A sharper summary of ${title.toLowerCase()}, checked twice.` },
            sources: [
              { kind: 'tool_call', ref: firstCall, quote: 'exited 0 with every case skipped' },
              { kind: 'tool_call', ref: secondCall, quote: 'skipped every case again' },
            ],
          };
        }
        const answer = await call(h, { runner: machine, headers: { 'x-orbit-session-id': proposer } }, 'POST', '/runner/wiki/changesets', {
          rationale: `the ${source} cell for a ${kind}`,
          ops: [op],
        });
        const outcome = answer.body.ops?.[0] as Outcome;
        assert.ok(outcome, `${mode}/${kind}/${source}: no outcome in ${JSON.stringify(answer.body)}`);
        const entryId = outcome.entryId ? toUuid(outcome.entryId) : (op.entryId as string | undefined) ?? null;
        cells.push({ kind, source, outcome, entryId, proposer });
      }
    }

    if (mode === 'automatic') {
      // Before any verdict: every cell the mode took waits for its verification, nothing of it is
      // live, and nothing of it is pushed. Then each proposer reports its op supported.
      const before = await pushed(h, owner.id, ws, await session(h, owner.id, ws, machine));
      for (const { kind, source, outcome, entryId, proposer } of cells) {
        if (expected(mode, kind, source).effect === 'refused') continue;
        const label: string = `automatic × ${kind} × ${source}, before its verdict`;
        assert.equal(outcome.status, 'pending', `${label}: ${JSON.stringify(outcome)}`);
        assert.equal(outcome.waitsFor, 'verification', label);
        const op = await h.prisma.wikiChangesetOp.findFirstOrThrow({ where: { id: toUuid(outcome.opId!) } });
        assert.equal(op.decision, 'verifying', label);
        const entry = await entryRow(h, entryId!);
        if (source === 'machine_verified') assert.equal(entry.currentRevision, 1, `${label}: an amend wrote a revision`);
        else assert.equal(entry.status, 'proposed', label);
        assert.equal(before.has(entryId!), false, `${label}: pushed`);
        await verifyAll(h, agent(owner.id, proposer), space, [outcome]);
      }
    }

    const handed = await pushed(h, owner.id, ws, await session(h, owner.id, ws, machine));
    for (const { kind, source, outcome, entryId } of cells) {
      const want = expected(mode, kind, source);
      const where = `${mode} × ${kind} × ${source}`;
      if (want.effect === 'refused') {
        assert.equal(outcome.status, 'refused', `${where}: ${JSON.stringify(outcome)}`);
        assert.equal(outcome.reasons?.[0]?.code, want.code, `${where}: refused for the wrong reason`);
        table.push(`${where}: refused ${want.code}`);
        continue;
      }
      // An Automatic cell answered pending when it was proposed, and its verdict applied it since.
      assert.equal(outcome.status, mode === 'automatic' ? 'pending' : want.effect, `${where}: ${JSON.stringify(outcome)}`);
      const entry = await entryRow(h, entryId!);
      const op = await h.prisma.wikiChangesetOp.findFirstOrThrow({ where: { id: toUuid(outcome.opId!) } });
      if (want.effect === 'pending') {
        // What waits changes nothing live: an add's lineage is born proposed, an amend's entry keeps its revision.
        assert.equal(op.decision, 'pending', where);
        assert.equal(op.appliedByMode, null, where);
        if (source === 'machine_verified') {
          assert.equal(entry.currentRevision, 1, `${where}: a waiting amend changed its entry`);
        } else {
          assert.equal(entry.status, 'proposed', where);
        }
      } else {
        assert.equal(entry.status, 'active', where);
        assert.equal(entry.trust, want.trust, `${where}: applied with the wrong trust`);
        assert.equal(op.appliedByMode, mode, `${where}: the op does not name the mode that applied it`);
        assert.ok(op.decision === 'auto_applied' || (op.decision === 'pending' && op.spotCheck), `${where}: ${op.decision}`);
      }
      // Pushed exactly when it is live, `auto`, and of a kind the push carries at all.
      const shouldPush = want.effect === 'applied' && want.trust === 'auto' && KIND_SPECS[kind].push !== 'never';
      assert.equal(handed.has(entryId!), shouldPush, `${where}: pushed=${handed.has(entryId!)}, expected ${shouldPush}`);
      table.push(`${where}: ${want.effect === 'applied' ? `applied ${want.trust}` : 'pending'}, ${shouldPush ? 'pushed' : 'not pushed'}`);
    }
  }
  assert.equal(table.length, 3 * 6 * 3, 'every cell was asserted');
});

