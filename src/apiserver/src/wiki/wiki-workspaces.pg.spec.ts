/**
 * Which workspaces are in a wiki (contract `space.binding` and `space.workspaces`, docs/mocks/wiki/38-workspaces), over
 * real HTTP and against a real PostgreSQL.
 *
 *   - a workspace on the space's repository is in the space with no row at all, however its URL is spelled, whenever
 *     its URL arrived, and whichever came first, the workspace or the space;
 *   - the owner leaves one out: it reads nothing, feeds nothing, is refused the wiki tools, and stays out;
 *   - the owner turns it back on, or adds one with no repository; one on another repository is refused;
 *   - all of it is the owner's to say: a session header is refused, and nothing is written.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-workspaces.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run created. Only
 * the credential check is stood in for, as in the other wiki specs.
 */
