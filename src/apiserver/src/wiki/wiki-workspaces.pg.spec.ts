const URL = process.env.COORDINATOR_PG_URL;
const skip = !URL;

interface Harness {
  base: string;
  sql: Client;
  prisma: PrismaClient;
  app: INestApplication;
  bearers: Map<string, string>;
  /** Which spaces were announced, in order: `wiki.changed` after each write that changed something. */
  announced: string[];
}

let harness: Promise<Harness> | undefined;

function boot(): Promise<Harness> {
  harness ??= (async () => {
    assertCoordinatorPgUrlIsIsolated(URL);
    const sql = new Client({ connectionString: URL, connectionTimeoutMillis: 5_000 });
    await sql.connect();
    await verifyCoordinatorPgIdentity(sql);
    const prisma = prismaClientFor(URL);
    const bearers = new Map<string, string>();
    const announced: string[] = [];
    const hub = { publishWikiChanged: (_owner: string, spaceId: string) => void announced.push(spaceId) } as unknown as RealtimeService;
    const push = { notifyWikiReviewModeTripped: async () => undefined, notifyWikiVerificationTripped: async () => undefined } as unknown as PushService;
    const service = new WikiService(prisma as unknown as PrismaService, hub, push);

    @Module({
      controllers: [WikiController, RunnerWikiController],
      providers: [
        { provide: WikiService, useValue: service },
        { provide: WikiRetrieval, useValue: new WikiRetrieval(prisma as unknown as PrismaService) },
        { provide: PrismaService, useValue: prisma },
        RunnerAuthGuard,
        JwtAuthGuard,
        Reflector,
        {
          provide: JwtService,
          useValue: {
            verifyAsync: async (token: string) => {
              const sub = bearers.get(token);
              if (!sub) throw new Error('not a bearer this run issued');
              return { sub, email: `${sub}@wiki.invalid` };
            },
          },
        },
      ],
    })
    class WikiWorkspacesModule {}

    const app = await NestFactory.create(WikiWorkspacesModule, { logger: false, abortOnError: false });
    app.setGlobalPrefix('api');
    app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
    app.useGlobalInterceptors(new PublicIdInterceptor());
    await app.listen(0, '127.0.0.1');
    return { base: await app.getUrl(), sql, prisma, app, bearers, announced };
  })();
  return harness;
}

after(async () => {
  if (!harness) return;
  const { app, prisma, sql } = await harness;
  await app.close().catch(() => undefined);
  await prisma.$disconnect().catch(() => undefined);
  await sql.end().catch(() => undefined);
});

// ── requests ─────────────────────────────────────────────────────────────────────────────────────────────────────

interface Answer {
  status: number;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  body: any;
}

interface Caller {
  bearer?: string;
  runner?: string;
  session?: string;
}

async function call(h: Harness, who: Caller, method: string, route: string, body?: unknown): Promise<Answer> {
  const headers: Record<string, string> = { 'content-type': 'application/json' };
  if (who.bearer) headers.authorization = `Bearer ${who.bearer}`;
  if (who.runner) headers['x-runner-token'] = who.runner;
  if (who.session) headers['x-orbit-session-id'] = who.session;
  const response = await fetch(`${h.base}/api${route}`, {
    method,
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await response.text();
  let parsed: unknown = null;
  try {
    parsed = text ? JSON.parse(text) : null;
  } catch {
    parsed = { unparsed: text };
  }
  return { status: response.status, body: parsed };
}

function expectStatus(answer: Answer, status: number, why: string): void {
  assert.equal(answer.status, status, `${why}: answered ${answer.status} ${JSON.stringify(answer.body).slice(0, 1500)}`);
}

// ── fixtures ─────────────────────────────────────────────────────────────────────────────────────────────────────

interface Account {
  id: string;
  bearer: string;
}

async function account(h: Harness): Promise<Account> {
  const id = randomUUID();
  await h.sql.query(`INSERT INTO "user"("id","email","name","password_hash") VALUES ($1,$2,'spec','x')`, [id, `wiki-workspaces-${id}@wiki.invalid`]);
  h.bearers.set(`bearer-${id}`, id);
  return { id, bearer: `bearer-${id}` };
}

async function runner(h: Harness, ownerId: string): Promise<{ id: string; token: string }> {
  const id = randomUUID();
  const token = `runner-${id}`;
  await h.sql.query(`INSERT INTO "runner"("id","name","owner_id","token_hash") VALUES ($1,'build-01',$2,$3)`, [
    id,
    ownerId,
    createHash('sha256').update(token).digest('hex'),
  ]);
  return { id, token };
}

async function workspace(h: Harness, ownerId: string, name: string, repoUrl: string | null, runnerId: string | null = null): Promise<string> {
  const id = randomUUID();
  await h.sql.query(`INSERT INTO "workspace"("id","name","owner_id","repo_url","runner_id") VALUES ($1,$2,$3,$4,$5)`, [id, name, ownerId, repoUrl, runnerId]);
  return id;
}

async function session(h: Harness, ownerId: string, workspaceId: string, runnerId: string): Promise<string> {
  const id = randomUUID();
  await h.sql.query(
    `INSERT INTO "session"("id","title","prompt","owner_id","creator_id","workspace_id","assigned_runner_id",
                            "status","dispatch_origin","updated_at")
     VALUES ($1,'a session','p',$2,$2,$3,$4,'RUNNING'::run_status,'USER',now())`,
    [id, ownerId, workspaceId, runnerId],
  );
  return id;
}

async function space(h: Harness, owner: Account, repoUrl?: string): Promise<string> {
  const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'A wiki', ...(repoUrl ? { repoUrl } : {}) });
  expectStatus(made, 201, 'the owner creates a space');
  return toUuid(made.body.id as string);
}

interface Listed {
  workspaces: Array<{ id: string; name: string; runner: string | null; inWiki: boolean }>;
  addable: Array<{ id: string; name: string; runner: string | null; inWiki: boolean }>;
}

async function listed(h: Harness, owner: Account, spaceId: string): Promise<Listed> {
  const answer = await call(h, { bearer: owner.bearer }, 'GET', `/wiki/spaces/${spaceId}/workspaces`);
  expectStatus(answer, 200, 'the owner reads the Workspaces card');
  const rows = (list: Listed['workspaces']) => list.map((row) => ({ ...row, id: toUuid(row.id) }));
  return { workspaces: rows(answer.body.workspaces), addable: rows(answer.body.addable) };
}

async function rowOf(h: Harness, workspaceId: string) {
  return h.prisma.wikiSpaceWorkspace.findUnique({ where: { workspaceId }, select: { spaceId: true, leftOutAt: true } });
}

async function workspaceIdsOf(h: Harness, owner: Account, spaceId: string): Promise<string[]> {
  const answer = await call(h, { bearer: owner.bearer }, 'GET', '/wiki/spaces');
  expectStatus(answer, 200, 'the owner lists the spaces');
  const row = (answer.body as Array<{ id: string; workspaceIds: string[] }>).find((one) => toUuid(one.id) === spaceId);
  assert.ok(row, 'the space is on the list');
  return row.workspaceIds.map((id) => toUuid(id));
}

const scoped = async (h: Harness, owner: Account, spaceId: string) =>
  (await spaceScope(h.prisma as unknown as PrismaService, owner.id, spaceId)).workspaceIds;

const repository = () => `https://github.com/spec/${randomUUID()}`;

// ── the cases ────────────────────────────────────────────────────────────────────────────────────────────────────

test('a workspace on the repository is in the wiki with no row at all', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const machine = await runner(h, owner.id);
  const url = repository();
  const before = await workspace(h, owner.id, 'shop-cli @ SG', url, machine.id);
  const spaceId = await space(h, owner, url);
  const spelled = await workspace(h, owner.id, 'shop-cli @ EU', `${url.replace('https://github.com/', 'git@github.com:')}.git`);
  const later = await workspace(h, owner.id, 'shop-cli @ US', null);
  await workspace(h, owner.id, 'another repository', repository());

  const first = await listed(h, owner, spaceId);
  assert.deepEqual(first.workspaces.map((row) => [row.id, row.inWiki]), [[spelled, true], [before, true]],
    'made before the space or after it, and however its URL is spelled');
  assert.equal(first.workspaces[1].runner, 'build-01', 'each row names its machine');
  assert.equal(await rowOf(h, before), null, 'nothing was written to put it there');

  // Its URL arrives the way the runner's directory probe writes it: nothing of the wiki's is told.
  await h.sql.query(`UPDATE "workspace" SET "repo_url" = $2 WHERE "id" = $1`, [later, url]);
  assert.deepEqual((await listed(h, owner, spaceId)).workspaces.map((row) => row.name), ['shop-cli @ EU', 'shop-cli @ SG', 'shop-cli @ US'],
    'it joined by itself, and the list goes by name');
  assert.deepEqual(new Set(await scoped(h, owner, spaceId)), new Set([before, spelled, later]), 'maintenance reads all three');
  assert.deepEqual(new Set(await workspaceIdsOf(h, owner, spaceId)), new Set([before, spelled, later]), 'the spaces list carries all three');

  await h.sql.query(`UPDATE "workspace" SET "deleted_at" = now() WHERE "id" = $1`, [spelled]);
  assert.deepEqual((await listed(h, owner, spaceId)).workspaces.map((row) => row.id), [before, later], 'a deleted workspace is not listed');
  assert.ok(!(await workspaceIdsOf(h, owner, spaceId)).includes(spelled), 'nor on the spaces list');
});

test('the owner leaves one out: it reads nothing, feeds nothing, and stays out', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const machine = await runner(h, owner.id);
  const url = repository();
  const spaceId = await space(h, owner, url);
  const kept = await workspace(h, owner.id, 'shop-cli @ SG', url, machine.id);
  const out = await workspace(h, owner.id, 'shop-cli @ EU', url, machine.id);

  h.announced.length = 0;
  const left = await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${spaceId}/workspaces/${out}`);
  expectStatus(left, 200, 'the owner leaves it out');
  assert.deepEqual(h.announced, [spaceId], 'clients are told');

  const once = await rowOf(h, out);
  assert.equal(once?.spaceId, spaceId);
  assert.ok(once?.leftOutAt, 'the row says so');
  assert.deepEqual((await listed(h, owner, spaceId)).workspaces.map((row) => [row.name, row.inWiki]),
    [['shop-cli @ EU', false], ['shop-cli @ SG', true]], 'its row stays on the list, off');
  assert.deepEqual(await scoped(h, owner, spaceId), [kept], 'maintenance no longer reads it');
  assert.deepEqual(await workspaceIdsOf(h, owner, spaceId), [kept], 'it is not on the spaces list');

  const mine = await session(h, owner.id, out, machine.id);
  const refused = await call(h, { runner: machine.token, session: mine }, 'GET', '/runner/wiki/search?q=anything');
  expectStatus(refused, 409, 'a session of it asks the wiki');
  assert.equal(refused.body.code, 'WIKI_SPACE_UNBOUND');
  assert.equal(refused.body.message, 'The owner left this workspace out of its wiki.');
  assert.ok((await rowOf(h, out))?.leftOutAt, 'and asking did not bring it back');

  const neighbour = await session(h, owner.id, kept, machine.id);
  expectStatus(await call(h, { runner: machine.token, session: neighbour }, 'GET', '/runner/wiki/search?q=anything'), 200, 'the other workspace still reads it');

  h.announced.length = 0;
  expectStatus(await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${spaceId}/workspaces/${out}`), 200, 'leaving it out again');
  assert.deepEqual((await rowOf(h, out))?.leftOutAt, once?.leftOutAt, 'changes nothing');
  assert.deepEqual(h.announced, [], 'and announces nothing');

  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${spaceId}/workspaces`, { workspaceId: out }), 200, 'the owner turns it back on');
  assert.equal((await rowOf(h, out))?.leftOutAt, null);
  assert.deepEqual((await listed(h, owner, spaceId)).workspaces.map((row) => row.inWiki), [true, true]);
  assert.deepEqual(new Set(await scoped(h, owner, spaceId)), new Set([kept, out]), 'maintenance reads it again');
  expectStatus(await call(h, { runner: machine.token, session: mine }, 'GET', '/runner/wiki/search?q=anything'), 200, 'and its sessions read the wiki');
});

test('the card and its writes speak the public ids a client holds', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const url = repository();
  const spaceId = await space(h, owner, url);
  const inside = await workspace(h, owner.id, 'shop-cli @ SG', url);
  const notes = await workspace(h, owner.id, 'notes', null);
  const publicSpace = uuidToBase62(spaceId);

  const read = await call(h, { bearer: owner.bearer }, 'GET', `/wiki/spaces/${publicSpace}/workspaces`);
  expectStatus(read, 200, 'the card reads by the space\'s public id');
  assert.equal(read.body.workspaces[0].id, uuidToBase62(inside));
  assert.equal(read.body.addable[0].id, uuidToBase62(notes));

  expectStatus(await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${publicSpace}/workspaces/${read.body.workspaces[0].id}`), 200, 'a switch turned off');
  assert.ok((await rowOf(h, inside))?.leftOutAt);
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${publicSpace}/workspaces`, { workspaceId: read.body.workspaces[0].id }), 200, 'and on again');
  assert.equal((await rowOf(h, inside))?.leftOutAt, null);
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${publicSpace}/workspaces`, { workspaceId: read.body.addable[0].id }), 200, 'Add workspace');
  assert.equal((await rowOf(h, notes))?.spaceId, spaceId);
});

