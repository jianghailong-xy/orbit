/**
 * Automatic verifies before it applies (criterion 7, revision 3; contracts/wiki.contract.json
 * `reviewModes.verification`), over real HTTP and against a real PostgreSQL.
 *
 * What the criterion asks of Automatic and of the spot checks, each read back from the database and
 * from the push the way a session would be handed it:
 *
 *   1. an op Automatic takes waits for its verification: nothing of it applies, it is pushed to
 *      nobody, it is no card in Review, and it takes no place in the queue or the quotas;
 *   2. the four verdicts, each with its own result — supported applies as Auto and is pushed, partial
 *      as Unreviewed, unsupported is rejected with its reason (which the next similar[] shows), and a
 *      duplicate becomes a reinforce of the entry it names — and the trail each leaves on its op;
 *   3. only the session that proposed may report, and anything of another owner's is a 404;
 *   4. no clock moves a waiting op, a space no longer Automatic records no verdict, and a revert
 *      withdraws what still waits;
 *   5. more than 30% unsupported among the latest 50 verdicts sends the space back to Tiered, and the
 *      owner is told once — through the one-off import's own service path, which leaves the same trail;
 *   6. Automatic sends no spot-check card unless the owner turns them on, then one in every 200; and a
 *      spot-check card takes no place in the 30-op queue.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-verify.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the two credential checks are stood in for, as in `wiki-review-mode.pg.spec.ts`; the
 * push is the real `appendWikiContext`, and the owner's notifications stand-ins that record each call.
 */
