// ── 5. the fallback, through the import's own path ──────────────────────────────────────────────

test('verification · over 30% unsupported of the latest 50 sends the space back to Tiered, once', { skip, concurrency: 1, timeout: 600_000 }, async (t) => {
  const h = await boot();
  const owner = await account(h, 'fallback');
  const recordsOf = await session(h, owner.id, null, null);
  const cited = await toolCall(h, recordsOf, 'Bash', 'compiled from the dossier');
  // The preview space: no workspace bound, filled by the one-off import.
  const space = await modeSpace(h, owner, 'automatic');
  const system = importer(owner.id);
  for (const [count, prefix] of [[30, 'first'], [30, 'second']] as const) {
    const answer = await h.service.submitChangeset(system, space, { rationale: `batch ${prefix}`, ops: importOps(count, cited, prefix), idempotencyKey: `${prefix}-${randomUUID()}` });
    assert.deepEqual((answer.ops as Outcome[]).map((op) => op.waitsFor), Array(count).fill('verification'), `${prefix}: every op waits`);
  }
  const all: string[] = [];
  for (let after: string | null = null, page = 0; page < 10; page += 1) {
    const read = await h.service.listVerifications(system, space, { after, limit: WIKI_REVIEW_RULES.verificationListMax });
    all.push(...read.items.map((item) => item.opId));
    after = read.next;
    if (!after) break;
  }
  assert.equal(all.length, 60, 'the import reads its own ops through the service');
  const record = (opId: string, value: string) => h.service.recordVerifications(system, space, [verdict(opId, value)]);

  await t.test('fifteen of fifty is not over 30%', async () => {
    for (const opId of all.slice(0, 35)) assert.equal((await record(opId, 'supported')).outcomes[0].status, 'applied');
    for (const opId of all.slice(35, 50)) assert.equal((await record(opId, 'unsupported')).outcomes[0].status, 'rejected');
    const settings = (await h.prisma.wikiSpace.findFirstOrThrow({ where: { id: space } })).settings as Record<string, unknown>;
    assert.equal(settings.reviewMode, 'automatic');
    assert.deepEqual(h.fellBack, []);
    const trail = await h.prisma.wikiChangesetOp.findFirstOrThrow({ where: { id: all[0] } });
    assert.equal(trail.verificationModel, 'qwen3.8-27b-fp8', 'the import\'s verdicts leave the same trail');
    const revision = await h.prisma.wikiEntryRevision.findFirstOrThrow({ where: { entryId: trail.resultEntryId!, revision: 1 } });
    assert.equal(revision.authorKind, 'system', 'and what they applied is the system\'s, never the owner\'s');
  });

  await t.test('the sixteenth sends it back to Tiered, and the owner is told once', async () => {
    const tripped = await record(all[50], 'unsupported');
    assert.equal(tripped.outcomes[0].status, 'rejected');
    assert.equal(tripped.mode, 'tiered');
    const settings = (await h.prisma.wikiSpace.findFirstOrThrow({ where: { id: space } })).settings as Record<string, unknown>;
    assert.equal(settings.reviewMode, 'tiered');
    assert.equal(settings.reviewModeChangedBy, 'verification');
    assert.deepEqual(h.fellBack, [{ ownerId: owner.id, spaceId: space, unsupported: 16, window: WIKI_REVIEW_RULES.verificationWindow }]);

    // The next verdict finds the space Tiered: refused, nothing written, nobody told again.
    const after = await record(all[51], 'unsupported');
    assert.equal(after.outcomes[0].status, 'refused');
    assert.equal((after.outcomes[0] as { httpStatus: number }).httpStatus, 409);
    assert.equal((await h.prisma.wikiChangesetOp.findFirstOrThrow({ where: { id: all[51] } })).decision, 'verifying');
    assert.equal(h.fellBack.length, 1, 'no second notification');
  });

  await t.test('made Automatic again by the owner, the window starts again: one more unsupported is not over the line', async () => {
    expectStatus(await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${space}`, { reviewMode: 'automatic' }), 200, 'the owner switches back');
    const one = await record(all[51], 'unsupported');
    assert.equal(one.outcomes[0].status, 'rejected');
    assert.equal(one.mode, 'automatic');
    assert.equal(h.fellBack.length, 1);
  });
});

// ── 6. spot checks, and the queue ───────────────────────────────────────────────────────────────

test('verification · Automatic sends no spot check unless asked, one in 200 when asked, and none takes a place in the queue', { skip, concurrency: 1, timeout: 600_000 }, async (t) => {
  const h = await boot();
  const owner = await account(h, 'spot checks');
  const recordsOf = await session(h, owner.id, null, null);
  const cited = await toolCall(h, recordsOf, 'Bash', 'compiled from the dossier');
  const system = importer(owner.id);

  await t.test('one in every block of 200, wherever the draw puts it', () => {
    const space = randomUUID();
    for (let block = 0; block < 3; block += 1) {
      const drawn = Array.from({ length: 200 }, (_unused, n) => block * 200 + n).filter((position) => isSpotCheckDraw(space, position, 200));
      assert.equal(drawn.length, 1, `block ${block}`);
    }
  });

  /** An Automatic space whose next verdict lands on the position its first block draws. */
  const atTheDraw = async (asked: boolean) => {
    const space = await modeSpace(h, owner, 'automatic');
    if (asked) {
      const on = await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${space}`, { automaticSpotChecks: true });
      expectStatus(on, 200, 'the owner asks for spot checks');
      assert.equal(on.body.settings.automaticSpotChecks, true);
    }
    let position = 0;
    while (!isSpotCheckDraw(space, position, WIKI_REVIEW_RULES.automaticSpotCheckEvery)) position += 1;
    // The ops the mode applied before, as the draw counts them: written directly, settled long ago.
    const earlier = randomUUID();
    await h.sql.query(
      `INSERT INTO "wiki_changeset"("id","owner_id","space_id","origin","status","decided_at") VALUES ($1,$2,$3,'import','settled',now())`,
      [earlier, owner.id, space],
    );
    for (let seq = 0; seq < position; seq += 1) {
      await h.sql.query(
        `INSERT INTO "wiki_changeset_op"("id","changeset_id","owner_id","seq","op","payload","decision","decided_at","applied_by_mode")
         VALUES ($1,$2,$3,$4,'add','{}','auto_applied',now(),'automatic')`,
        [randomUUID(), earlier, owner.id, seq],
      );
    }
    const answer = await h.service.submitChangeset(system, space, { rationale: 'two more', ops: importOps(2, cited, 'draw'), idempotencyKey: `draw-${randomUUID()}` });
    return { space, ops: (answer.ops as Outcome[]).map((op) => op.opId!) };
  };

  await t.test('a new space sends none, and only the owner channel turns them on', async () => {
    const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'Defaults' });
    assert.equal(made.body.settings.automaticSpotChecks, false);
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    const someone = await session(h, owner.id, ws, machine);
    const refused = await call(h, { bearer: owner.bearer, headers: { 'x-orbit-session-id': someone } }, 'PATCH', `/wiki/spaces/${made.body.id}`, { automaticSpotChecks: true });
    expectStatus(refused, 403, 'a session turning spot checks on');
    assert.equal(refused.body.code, 'WIKI_OWNER_CHANNEL_ONLY');
    const runnerDoor = await call(h, { runner: machine, headers: { 'x-orbit-session-id': someone } }, 'PATCH', `/runner/wiki/spaces/${made.body.id}`, { automaticSpotChecks: true });
    assert.equal(runnerDoor.status, 404, 'the runner door serves no settings route');
  });

  await t.test('off, the verdict at the drawn position applies with no card', async () => {
    const { space, ops } = await atTheDraw(false);
    const done = await h.service.recordVerifications(system, space, [verdict(ops[0], 'supported')]);
    assert.equal((done.outcomes[0] as { spotCheck?: boolean }).spotCheck, false);
    assert.equal((await h.prisma.wikiChangesetOp.findFirstOrThrow({ where: { id: ops[0] } })).decision, 'auto_applied');
    const review = await call(h, { bearer: owner.bearer }, 'GET', `/wiki/review?space=${space}`);
    assert.deepEqual(review.body, []);
  });

  await t.test('on, the verdict at the drawn position is a spot check in Review, and the next one is not', async () => {
    const { space, ops } = await atTheDraw(true);
    const drawn = await h.service.recordVerifications(system, space, [verdict(ops[0], 'supported')]);
    assert.equal((drawn.outcomes[0] as { spotCheck?: boolean }).spotCheck, true);
    const op = await h.prisma.wikiChangesetOp.findFirstOrThrow({ where: { id: ops[0] } });
    assert.equal(op.decision, 'pending');
    assert.equal(op.spotCheck, true);
    assert.equal(op.appliedByMode, 'automatic');
    assert.equal((await h.prisma.wikiEntry.findFirstOrThrow({ where: { id: op.resultEntryId! } })).trust, 'auto', 'its effect stands');
    const review = await call(h, { bearer: owner.bearer }, 'GET', `/wiki/review?space=${space}`);
    const cards = (review.body as Array<{ ops: Array<{ spotCheck: boolean; decision: string; verification: { verdict: string; model: string } | null }> }>)
      .flatMap((changeset) => changeset.ops.filter((row) => row.decision === 'pending'));
    assert.equal(cards.length, 1, 'one spot-check card');
    assert.equal(cards[0].spotCheck, true);
    assert.equal(cards[0].verification?.verdict, 'supported', 'with the verdict it rests on');
    assert.equal(cards[0].verification?.model, 'qwen3.8-27b-fp8');
    const next = await h.service.recordVerifications(system, space, [verdict(ops[1], 'supported')]);
    assert.equal((next.outcomes[0] as { spotCheck?: boolean }).spotCheck, false, 'one in the block, and only one');
  });

  await t.test('a spot-check card takes no place in the 30-op queue: thirty proposals still wait beside it', async () => {
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    const tiered = await modeSpace(h, owner, 'tiered', ws);
    // Tiered draws one in ten as it applies, and applies an import's adds at once.
    const loaded = await h.service.submitChangeset(system, tiered, { rationale: 'ten', ops: importOps(10, cited, 'tiered'), idempotencyKey: `tiered-${randomUUID()}` });
    assert.deepEqual((loaded.ops as Outcome[]).map((op) => op.status), Array(10).fill('applied'));
    const checks = await h.prisma.wikiChangesetOp.count({ where: { spotCheck: true, decision: 'pending', changeset: { spaceId: tiered } } });
    assert.equal(checks, 1, 'Tiered still draws one in ten');
    // Thirty proposals that wait on the owner's decision: a session that read the web proposes each.
    const outcomes: Outcome[] = [];
    for (let batch = 0; batch < WIKI_LIMITS.pendingOpsPerSpace / WIKI_LIMITS.opsPerTurn; batch += 1) {
      const reader = await session(h, owner.id, ws, machine);
      await toolCall(h, reader, 'WebFetch', 'a page from the web');
      const answer = await call(h, { runner: machine, headers: { 'x-orbit-session-id': reader } }, 'POST', '/runner/wiki/changesets', {
        rationale: 'read off the web', idempotencyKey: `web-${randomUUID()}`,
        ops: Array.from({ length: WIKI_LIMITS.opsPerTurn }, (_unused, n) => ({
          op: 'add', entry: draft('pitfall', `A web pitfall ${batch}-${n}`), sources: [{ kind: 'tool_call', ref: cited }],
        })),
      });
      outcomes.push(...(answer.body.ops as Outcome[]));
    }
    assert.deepEqual(outcomes.map((op) => op.status), Array(WIKI_LIMITS.pendingOpsPerSpace).fill('pending'), 'all thirty wait, the card beside them');
    const reader = await session(h, owner.id, ws, machine);
    await toolCall(h, reader, 'WebFetch', 'one more page');
    const full = await call(h, { runner: machine, headers: { 'x-orbit-session-id': reader } }, 'POST', '/runner/wiki/changesets', {
      rationale: 'one too many', idempotencyKey: `full-${randomUUID()}`,
      ops: [{ op: 'add', entry: draft('pitfall', 'A thirty-first web pitfall'), sources: [{ kind: 'tool_call', ref: cited }] }],
    });
    assert.equal(full.body.ops[0].reasons[0].code, 'WIKI_REVIEW_QUEUE_FULL', 'the thirty-first decision is the one refused');
  });
});
