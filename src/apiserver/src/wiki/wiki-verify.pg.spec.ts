/** A space the owner makes through the door and puts in a mode, bound to a workspace when one is named. */
async function modeSpace(h: Harness, owner: Account, mode: Mode, workspaceId?: string): Promise<string> {
  const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: `A ${mode} space` });
  expectStatus(made, 201, 'the owner creates a space');
  const id = made.body.id as string;
  const switched = await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${id}`, { reviewMode: mode });
  expectStatus(switched, 200, `the owner puts the space in ${mode}`);
  if (workspaceId) {
    const bound = await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${id}/workspaces`, { workspaceId });
    expectStatus(bound, 200, 'the owner binds the workspace');
  }
  return toUuid(id);
}

/** A valid draft of each kind, retitled per use. */
function draft(kind: WikiKind, title: string, summary = `What the space knows about ${title.toLowerCase()}.`): Record<string, unknown> {
  const fields: Record<WikiKind, Record<string, unknown>> = {
    principle: { statement: 'When a record is deleted, every quote taken from it goes too.', rationale: 'Owners delete to forget.' },
    convention: { rule: 'Model a closed set as TEXT plus a CHECK constraint.', scope: ['src/apiserver/prisma/migrations/**'] },
    decision: {
      context: 'People ask what is true now.',
      decision: 'Store atomic entries and project every page from them.',
      alternatives: [{ option: 'A page-shaped wiki', whyRejected: 'Whole-page rewrites collapse.' }],
      consequences: 'Every view can be rebuilt.',
      decidedAt: '2026-09-26',
    },
    pitfall: {
      trigger: { paths: ['src/apiserver/src/wiki/'], commands: ['node --test build/wiki/x.pg.spec.js'] },
      symptom: 'A green run that witnessed no assertion.',
      cause: 'A pg spec skips itself without a database.',
      fix: 'Run it through scripts/run-pg-spec.sh.',
    },
    recipe: {
      steps: ['bash scripts/worktree-overlay.sh', 'bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-schema.pg.spec.ts'],
      verify: { command: 'bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-schema.pg.spec.ts', expectedExit: 0 },
    },
    concept: { definition: 'One owner\'s knowledge about one codebase.', boundaries: 'A space never spans owners.' },
  };
  return { kind, title, summary, fields: fields[kind] };
}

/**
 * An entry a review mode applied earlier, live with the machine's trust — written directly, in the
 * shape 0307's CHECKs ask (status and trust agree, no successor, no retirement), with the revision
 * and the source `applyOp` would have written.
 */
async function machineEntry(h: Harness, ownerId: string, spaceId: string, kind: WikiKind, title: string, sourceSession: string): Promise<string> {
  const id = randomUUID();
  const body = draft(kind, title);
  await h.sql.query(
    `INSERT INTO "wiki_entry"("id","owner_id","space_id","kind","status","trust","current_revision","title","summary","fields")
     VALUES ($1,$2,$3,$4,'active','auto',1,$5,$6,$7)`,
    [id, ownerId, spaceId, kind, body.title, body.summary, JSON.stringify(body.fields)],
  );
  const revision = randomUUID();
  await h.sql.query(
    `INSERT INTO "wiki_entry_revision"("id","entry_id","owner_id","revision","title","summary","fields","content_sha256","author_kind")
     VALUES ($1,$2,$3,1,$4,$5,$6,$7,'agent')`,
    [revision, id, ownerId, body.title, body.summary, JSON.stringify(body.fields), 'b'.repeat(64)],
  );
  await h.sql.query(`INSERT INTO "wiki_source"("id","revision_id","owner_id","kind","ref") VALUES ($1,$2,$3,'turn',$4)`, [
    randomUUID(),
    revision,
    ownerId,
    sourceSession,
  ]);
  return id;
}

