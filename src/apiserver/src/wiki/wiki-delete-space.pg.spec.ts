/**
 * Deleting a wiki (contract `space.delete`, docs/mocks/wiki-delete), over real HTTP and against a real PostgreSQL.
 *
 *   - the schema: every foreign key into a wiki table goes with its parent, but the two supersede links, and each below
 *     the space is indexed, so the cascade finds its rows by index at any size;
 *   - what it takes: every row of the space, a superseded entry and its public link among them; what it keeps: another
 *     space's rows, the workspace and the session;
 *   - whose it is: a session header is refused, another account's space is a 404, and neither deletes or announces;
 *   - what comes back: a session on the repository makes a new, empty wiki; a space with no repository stays gone;
 *   - what was running: a job loses its row and ends with nothing to requeue, a model wait ends, a runner's late result
 *     is told the operation is gone;
 *   - a writer holding its rows: the deadlock it can make is absorbed, and the delete answers 200;
 *   - its size: a wiki of thousands of entries goes well inside the transaction's deadline.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-delete-space.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run created. Only
 * the credential check is stood in for, as in the other wiki specs.
 */
