/** Bulk: entries with a revision, a source, an op, and `exposures` reads each. Chained in pairs by supersede links. */
async function bulk(h: Harness, ownerId: string, spaceId: string, entries: number, exposures: number): Promise<void> {
  const changeset = randomUUID();
  await h.sql.query(
    `INSERT INTO "wiki_changeset"("id","owner_id","space_id","origin","status","decided_at") VALUES ($1,$2,$3,'import','settled',now())`,
    [changeset, ownerId, spaceId],
  );
  await h.sql.query(
    `CREATE TEMP TABLE bulk_ids ON COMMIT PRESERVE ROWS AS
       SELECT n, gen_random_uuid() AS entry, gen_random_uuid() AS revision FROM generate_series(1, $1::int) AS n`,
    [entries],
  );
  await h.sql.query(
    `INSERT INTO "wiki_entry"("id","owner_id","space_id","kind","status","trust","current_revision","title","summary","fields","valid_from","recorded_at")
     SELECT entry, $1::uuid, $2::uuid, 'concept', 'active', 'confirmed', 1, 'Entry ' || n, 'A summary of entry ' || n, '{"definition":"d"}'::jsonb, now(), now() FROM bulk_ids`,
    [ownerId, spaceId],
  );
  await h.sql.query(`
    UPDATE "wiki_entry" e SET "status" = 'superseded', "retired_at" = now(), "superseded_by_id" = b.entry
      FROM bulk_ids a JOIN bulk_ids b ON b.n = a.n + 1 WHERE e."id" = a.entry AND a.n % 2 = 1`);
  await h.sql.query(`
    UPDATE "wiki_entry" e SET "supersedes_id" = a.entry
      FROM bulk_ids a JOIN bulk_ids b ON b.n = a.n + 1 WHERE e."id" = b.entry AND a.n % 2 = 1`);
  await h.sql.query(
    `INSERT INTO "wiki_entry_revision"("id","entry_id","owner_id","revision","title","summary","fields","content_sha256","author_kind")
     SELECT revision, entry, $1::uuid, 1, 'Entry ' || n, 'A summary', '{}'::jsonb, $2, 'system' FROM bulk_ids`,
    [ownerId, SHA],
  );
  await h.sql.query(
    `INSERT INTO "wiki_source"("id","revision_id","owner_id","kind","ref") SELECT gen_random_uuid(), revision, $1::uuid, 'note', 'ref-' || n FROM bulk_ids, generate_series(1, 2)`,
    [ownerId],
  );
  await h.sql.query(
    `INSERT INTO "wiki_exposure"("id","owner_id","entry_id","revision","channel") SELECT gen_random_uuid(), $1::uuid, entry, 1, 'search' FROM bulk_ids, generate_series(1, $2::int)`,
    [ownerId, exposures],
  );
  await h.sql.query(
    `INSERT INTO "wiki_changeset_op"("id","changeset_id","owner_id","seq","op","payload","entry_id","result_entry_id","decision","decided_at")
     SELECT gen_random_uuid(), $1::uuid, $2::uuid, n, 'reinforce', '{}'::jsonb, entry, entry, 'accepted', now() FROM bulk_ids`,
    [changeset, ownerId],
  );
  await h.sql.query('DROP TABLE bulk_ids');
}

test('a wiki of thousands of entries goes well inside the deadline', { skip, timeout: 600_000 }, async () => {
  const h = await boot();
  const owner = await account(h);
  const spaceId = await space(h, owner);
  const entries = 10_000;
  const exposures = 30;
  await bulk(h, owner.id, spaceId, entries, exposures);
  await h.sql.query('ANALYZE');

  const startedAt = performance.now();
  expectStatus(await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${spaceId}`), 200, 'the owner deletes it');
  const ms = Math.round(performance.now() - startedAt);

  console.log(`deleted ${entries} entries, ${entries * exposures} exposures, ${entries * 2} sources and ${entries} ops in ${ms} ms`);
  assert.equal(await h.prisma.wikiEntry.count({ where: { spaceId } }), 0, 'all of it');
  // The deadline is 60 s (`deleteSpace`). Half of it leaves room for a loaded host, and a miss here is a wiki that
  // can no longer be deleted from a dialog.
  assert.ok(ms < 30_000, `took ${ms} ms`);
});
