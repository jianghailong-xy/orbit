/**
 * One entry and what hangs off it: a revision with a source, an exposure, and an op that names it both ways, which is
 * the second cascade path to an op (contract `storage`).
 */
async function entry(h: Harness, ownerId: string, spaceId: string, title: string): Promise<string> {
  const id = randomUUID();
  await h.sql.query(
    `INSERT INTO "wiki_entry"("id","owner_id","space_id","kind","status","trust","current_revision","title","summary","fields","valid_from","recorded_at")
     VALUES ($1,$2,$3,'concept','active','confirmed',1,$4,'a summary','{}'::jsonb,now(),now())`,
    [id, ownerId, spaceId, title],
  );
  const revision = randomUUID();
  await h.sql.query(
    `INSERT INTO "wiki_entry_revision"("id","entry_id","owner_id","revision","title","summary","fields","content_sha256","author_kind","author_user_id")
     VALUES ($1,$2,$3,1,$4,'a summary','{}'::jsonb,$5,'owner',$3)`,
    [revision, id, ownerId, title, SHA],
  );
  await h.sql.query(`INSERT INTO "wiki_source"("id","revision_id","owner_id","kind","ref") VALUES (gen_random_uuid(),$1,$2,'note','a ref')`, [revision, ownerId]);
  await h.sql.query(`INSERT INTO "wiki_exposure"("id","owner_id","entry_id","revision","channel") VALUES (gen_random_uuid(),$1,$2,1,'search')`, [ownerId, id]);
  const changeset = randomUUID();
  await h.sql.query(
    `INSERT INTO "wiki_changeset"("id","owner_id","space_id","origin","status","decided_at") VALUES ($1,$2,$3,'owner','settled',now())`,
    [changeset, ownerId, spaceId],
  );
  await h.sql.query(
    `INSERT INTO "wiki_changeset_op"("id","changeset_id","owner_id","seq","op","payload","entry_id","result_entry_id","decision","decided_at")
     VALUES (gen_random_uuid(),$1,$2,0,'reinforce','{}'::jsonb,$3,$3,'accepted',now())`,
    [changeset, ownerId, id],
  );
  return id;
}

/** Every row of a space, table by table: each table with a `space_id` column, and the ones under its entries. */
async function rowsOf(h: Harness, spaceId: string, entryIds: readonly string[] = []): Promise<Record<string, number>> {
  const { rows: tables } = await h.sql.query<{ table_name: string }>(
    `SELECT table_name FROM information_schema.columns WHERE table_schema = current_schema() AND column_name = 'space_id' ORDER BY 1`,
  );
  const counts: Record<string, number> = {};
  for (const { table_name: table } of tables) {
    const { rows } = await h.sql.query<{ n: number }>(`SELECT count(*)::int AS n FROM "${table}" WHERE "space_id" = $1`, [spaceId]);
    if (rows[0].n > 0) counts[table] = rows[0].n;
  }
  const { rows: links } = await h.sql.query<{ n: number }>(`SELECT count(*)::int AS n FROM "share_link" WHERE "wiki_space_id" = $1`, [spaceId]);
  if (links[0].n > 0) counts.share_link = links[0].n;
  for (const table of ['wiki_entry_revision', 'wiki_exposure', 'wiki_changeset_op']) {
    const { rows } = await h.sql.query<{ n: number }>(`SELECT count(*)::int AS n FROM "${table}" WHERE "entry_id" = ANY($1::uuid[])`, [entryIds]);
    if (rows[0].n > 0) counts[table] = rows[0].n;
  }
  return counts;
}

// ── the schema ───────────────────────────────────────────────────────────────────────────────────

test('every foreign key into a wiki table goes with its parent, and finds its rows by index', { skip }, async () => {
  const h = await boot();
  const { rows } = await h.sql.query<{ name: string; child: string; parent: string; on_delete: string; indexed: boolean }>(`
    SELECT c.conname AS name, c.conrelid::regclass::text AS child, c.confrelid::regclass::text AS parent, c.confdeltype AS on_delete,
           EXISTS (
             SELECT 1 FROM pg_index i
              WHERE i.indrelid = c.conrelid AND i.indisvalid AND i.indkey[0] = c.conkey[1]
           ) AS indexed
      FROM pg_constraint c
     WHERE c.contype = 'f' AND c.confrelid::regclass::text LIKE 'wiki\\_%'`);
  assert.ok(rows.length >= 30, `the census read the wiki's keys, ${rows.length} of them`);

  // NO ACTION on these two alone: both ends of a supersede are in one space, and the one statement over the
  // space's entries takes both before the check runs. The case below proves that on a real chain.
  const held = rows.filter((row) => row.on_delete !== 'c').map((row) => row.name).sort();
  assert.deepEqual(held, ['wiki_entry_superseded_by_fkey', 'wiki_entry_supersedes_fkey'],
    'a new key into a wiki table that does not cascade is one more thing that stops a wiki being deleted, or leaves rows behind');

  // A key under the space itself is read once per delete, whatever its size, and two queue tables have no index for it.
  const unindexed = rows.filter((row) => !row.indexed && row.parent !== 'wiki_space').map((row) => `${row.child} (${row.name})`).sort();
  assert.deepEqual(unindexed, [], 'a cascade over a key with no index reads the whole child table per parent row');
});

// ── what it takes, and what it keeps ─────────────────────────────────────────────────────────────

test('it takes every row of the space, and nothing of anything else', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const stranger = await account(h);
  const machine = await runner(h, owner.id);
  const url = repository();
  const spaceId = await space(h, owner, url);
  const otherId = await space(h, owner);
  const strangerId = await space(h, stranger);
  const home = await workspace(h, owner.id, url, machine.id);
  const talk = await session(h, owner.id, home, machine.id);

  const old = await entry(h, owner.id, spaceId, 'The old way');
  const current = await entry(h, owner.id, spaceId, 'The new way');
  // A real supersede chain: the two NO ACTION keys, in both directions.
  await h.sql.query(`UPDATE "wiki_entry" SET "status" = 'superseded', "retired_at" = now(), "superseded_by_id" = $2 WHERE "id" = $1`, [old, current]);
  await h.sql.query(`UPDATE "wiki_entry" SET "supersedes_id" = $2 WHERE "id" = $1`, [current, old]);
  await h.sql.query(`INSERT INTO "wiki_space_workspace"("id","space_id","owner_id","workspace_id") VALUES (gen_random_uuid(),$1,$2,$3)`, [spaceId, owner.id, home]);
  await h.sql.query(`INSERT INTO "share_link"("id","owner_id","token","wiki_space_id") VALUES (gen_random_uuid(),$1,$2,$3)`, [owner.id, `token-${randomUUID()}`, spaceId]);
  const job = randomUUID();
  await enqueueWikiJob(h.prisma as unknown as PrismaService, { id: job, ownerId: owner.id, spaceId, kind: 'smoke' });

  const kept = await entry(h, owner.id, otherId, 'Another wiki keeps this');
  const theirs = await entry(h, stranger.id, strangerId, 'Another account keeps this');
  const before = await rowsOf(h, spaceId, [old, current]);
  for (const table of ['wiki_entry', 'wiki_changeset', 'wiki_job', 'wiki_space_workspace', 'share_link', 'wiki_entry_revision', 'wiki_exposure', 'wiki_changeset_op']) {
    assert.ok(before[table] > 0, `the fixture has a row in ${table}`);
  }
  const keptBefore = await rowsOf(h, otherId, [kept]);
  const theirsBefore = await rowsOf(h, strangerId, [theirs]);
  h.announced.length = 0;

  const answer = await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${spaceId}`);
  expectStatus(answer, 200, 'the owner deletes the space');
  assert.equal(toUuid(answer.body.spaceId as string), spaceId, 'the answer names it');
  assert.deepEqual(h.announced, [spaceId], 'announced once, after the commit');

  assert.equal(await h.prisma.wikiSpace.count({ where: { id: spaceId } }), 0, 'the space is gone');
  assert.deepEqual(await rowsOf(h, spaceId, [old, current]), {}, 'and nothing of it is left in any table');
  assert.equal((await h.sql.query('SELECT 1 FROM "wiki_source" WHERE "revision_id" NOT IN (SELECT "id" FROM "wiki_entry_revision")')).rowCount, 0, 'no source is left without its revision');

  assert.deepEqual(await rowsOf(h, otherId, [kept]), keptBefore, 'the owner\'s other wiki is as it was');
  assert.deepEqual(await rowsOf(h, strangerId, [theirs]), theirsBefore, 'and so is another account\'s');
  assert.equal(await h.prisma.workspace.count({ where: { id: home, deletedAt: null } }), 1, 'the workspace stays');
  assert.equal(await h.prisma.session.count({ where: { id: talk } }), 1, 'and so does its session');

  const list = await call(h, { bearer: owner.bearer }, 'GET', '/wiki/spaces');
  assert.deepEqual((list.body as Array<{ id: string }>).map((row) => toUuid(row.id)), [otherId], 'the sidebar lists what is left');
  expectStatus(await call(h, { bearer: owner.bearer }, 'GET', `/wiki/spaces/${spaceId}`), 404, 'its pages answer that it is gone');
});

