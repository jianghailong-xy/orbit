test('a writer holding its rows makes the one deadlock it can, and the delete still answers 200', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const spaceId = await space(h, owner);
  const held = await entry(h, owner.id, spaceId, 'A row a writer holds');

  const writer = new Client({ connectionString: URL, connectionTimeoutMillis: 5_000 });
  await writer.connect();
  try {
    await writer.query('BEGIN');
    await writer.query(`UPDATE "wiki_entry" SET "summary" = 'held' WHERE "id" = $1`, [held]);

    const deleting = call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${spaceId}`);
    // The delete has the space FOR UPDATE and waits for the entry.
    for (let i = 0; ; i += 1) {
      const { rows } = await h.sql.query<{ waiting: number }>(
        `SELECT count(*)::int AS waiting FROM pg_stat_activity WHERE wait_event_type = 'Lock' AND query ILIKE '%wiki_%' AND pid <> pg_backend_pid()`,
      );
      if (rows[0].waiting > 0) break;
      assert.ok(i < 200, 'the delete came to wait for the writer');
      await new Promise((resolve) => setTimeout(resolve, 25));
    }

    // Now the writer names the space, which needs FOR KEY SHARE on the row the delete holds: the cycle.
    const wrote = await writer.query(`INSERT INTO "wiki_cursor"("id","space_id","owner_id","source") VALUES (gen_random_uuid(),$1,$2,'facts')`, [spaceId, owner.id])
      .then(() => 'the writer got through' as const, (error: { code?: string }) => error.code ?? 'failed');
    await writer.query(wrote === 'the writer got through' ? 'COMMIT' : 'ROLLBACK');
    assert.ok(wrote === 'the writer got through' || wrote === '40P01', `the writer met the deadlock or won it: ${wrote}`);
    console.log(`the deadlock: ${wrote === '40P01' ? 'the writer was its victim' : 'the delete was its victim, and went again'}`);

    expectStatus(await deleting, 200, 'whichever of the two the detector chose');
    assert.equal(await h.prisma.wikiSpace.count({ where: { id: spaceId } }), 0, 'the space is gone');
    assert.deepEqual(await rowsOf(h, spaceId, [held]), {}, 'and what the writer held with it');
  } finally {
    await writer.end().catch(() => undefined);
  }
});

