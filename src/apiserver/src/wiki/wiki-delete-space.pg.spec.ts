// ── what comes back ──────────────────────────────────────────────────────────────────────────────

test('a wiki with a repository is made again, empty, by the next session to use the wiki', { skip }, async () => {
  const h = await boot();
  const owner = await account(h);
  const machine = await runner(h, owner.id);
  const url = repository();
  const spaceId = await space(h, owner, url);
  await entry(h, owner.id, spaceId, 'What the old wiki knew');
  const inIt = await workspace(h, owner.id, url, machine.id);
  const leftOut = await workspace(h, owner.id, url, machine.id);
  const talk = await session(h, owner.id, inIt, machine.id);
  const quiet = await session(h, owner.id, leftOut, machine.id);
  const asSession = { runner: machine.token, session: talk };

  expectStatus(await call(h, asSession, 'GET', '/runner/wiki/search?q=old'), 200, 'the session reads the wiki, which binds it');
  expectStatus(await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${spaceId}/workspaces/${leftOut}`), 200, 'one workspace is left out');
  assert.equal((await call(h, { runner: machine.token, session: quiet }, 'GET', '/runner/wiki/search?q=old')).body.code, 'WIKI_SPACE_UNBOUND', 'and it is refused');

  expectStatus(await call(h, { bearer: owner.bearer }, 'DELETE', `/wiki/spaces/${spaceId}`), 200, 'the owner deletes the wiki');
  assert.equal(await h.prisma.wikiSpaceWorkspace.count({ where: { workspaceId: { in: [inIt, leftOut] } } }), 0, 'the workspaces\' rows went with it');
  assert.equal(await h.prisma.wikiSpace.count({ where: { ownerId: owner.id } }), 0, 'and nothing makes a wiki until a session asks');

  const again = await call(h, asSession, 'GET', '/runner/wiki/search?q=old');
  expectStatus(again, 200, 'the next session to use the wiki is answered');
  const made = await h.prisma.wikiSpace.findMany({ where: { ownerId: owner.id }, select: { id: true, repoUrlNorm: true } });
  assert.equal(made.length, 1, 'by a new wiki');
  assert.notEqual(made[0].id, spaceId, 'not the old one');
  assert.ok(made[0].repoUrlNorm && url.endsWith(made[0].repoUrlNorm.split('/').pop()!), 'on the same repository');
  assert.equal(await h.prisma.wikiEntry.count({ where: { spaceId: made[0].id } }), 0, 'and empty');

  // The left-out mark lived on the row that went with the old space, as the dialog's "starts a new one" implies.
  expectStatus(await call(h, { runner: machine.token, session: quiet }, 'GET', '/runner/wiki/search?q=old'), 200, 'the workspace left out of the old wiki is not out of the new one');
  assert.equal(await h.prisma.wikiSpace.count({ where: { ownerId: owner.id } }), 1, 'and it finds the same new wiki rather than making another');
});

