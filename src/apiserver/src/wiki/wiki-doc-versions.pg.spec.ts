test('the migration\'s CHECKs are the contract\'s closed set, a reason names only what it has, and deleting the space deletes its versions', { skip }, async () => {
  const h = await boot();
  const def = await h.sql.query<{ def: string }>(
    `SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conname = 'wiki_doc_section_version_reason_chk' AND conrelid = 'wiki_doc_section_version'::regclass`,
  );
  assert.deepEqual([...def.rows[0].def.matchAll(/'([^']+)'::text/gu)].map((m) => m[1]), [...WIKI_DOC_VERSION_REASONS]);
  assert.deepEqual([...WIKI_DOC_VERSION_REASONS], CONTRACT.docs.versions.reasons.values);
  assert.equal(CONTRACT.docs.versions.table, 'wiki_doc_section_version');

  const s = await scene(h);
  const version = await confirmPlan(h, s);
  await write(h, s, version, HEARTBEAT, ['Before.'], { reason: 'build', jobId: randomUUID(), planVersion: version });
  await write(h, s, version, HEARTBEAT, ['After.'], { reason: 'maintenance', jobId: randomUUID() });
  const [row] = await versionRows(h, s.spaceId, HEARTBEAT);
  const refused = async (set: string, why: string) => {
    await assert.rejects(h.sql.query(`UPDATE "wiki_doc_section_version" SET ${set} WHERE "id" = $1`, [row.id]), /violates check constraint/u, why);
  };
  await refused(`"reason" = 'import'`, 'a reason outside the closed set');
  await refused(`"reason_title" = 'a title'`, 'a maintenance run names no title');
  await refused(`"reason" = 'merge', "reason_title" = 'a merge'`, 'a merge names its commit');
  await refused(`"reason" = 'build'`, 'a build names its plan version');
  await refused(`"job_id" = NULL`, 'a job\'s rewrite names its job');
  await refused(`"reason" = 'restore'`, 'a restore names the version it put back, and no job');
  await refused(`"repo_sha" = 'short'`, 'a commit is 40 hex');

  await h.sql.query(`DELETE FROM "wiki_space" WHERE "id" = $1`, [s.spaceId]);
  assert.equal((await h.sql.query(`SELECT 1 FROM "wiki_doc_section_version" WHERE "space_id" = $1`, [s.spaceId])).rowCount, 0);
});
