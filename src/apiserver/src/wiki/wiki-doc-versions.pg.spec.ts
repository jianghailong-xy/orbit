/**
 * One owner's world: a runner, a bound workspace, a space with maintenance on — its first draft made as the
 * wiki-worker's job — the server's writer of its documents, and an ordinary session of the workspace.
 */
interface Scene {
  owner: Account;
  spaceId: string;
  drafter: { ownerId: string; spaceId: string; wikiJobId: string };
  writer: WikiPrincipal;
  session: string;
}

async function scene(h: Harness, title = 'A space whose sections are rewritten'): Promise<Scene> {
  const owner = await account(h, 'owner');
  const runner = randomUUID();
  await h.sql.query(`INSERT INTO "runner"("id","name","owner_id","token_hash") VALUES ($1,'spec',$2,$3)`, [
    runner, owner.id, createHash('sha256').update(`runner-${runner}`).digest('hex'),
  ]);
  const ws = randomUUID();
  await h.sql.query(`INSERT INTO "workspace"("id","name","owner_id") VALUES ($1,'spec',$2)`, [ws, owner.id]);
  const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title });
  expectStatus(made, 201, 'the owner creates a space');
  const spaceId = toUuid(made.body.id as string);
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${spaceId}/workspaces`, { workspaceId: ws }), 200, 'the owner binds the workspace');
  expectStatus(await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${spaceId}`, { maintenance: { enabled: true, workspaceId: ws } }), 200, 'maintenance on');
  const drafting = await h.sql.query<{ job_id: string }>(
    `SELECT "job_id" FROM "wiki_plan_job" WHERE "space_id" = $1 AND "kind" = 'draft' AND "state" = 'made' AND "job_id" IS NOT NULL`,
    [spaceId],
  );
  assert.equal(drafting.rowCount, 1, 'the space\'s first draft is made on the server');
  const session = randomUUID();
  await h.sql.query(
    `INSERT INTO "session"("id","title","prompt","owner_id","creator_id","workspace_id","assigned_runner_id","status","dispatch_origin","updated_at")
     VALUES ($1,'a session','p',$2,$2,$3,$4,'RUNNING'::run_status,'USER',now())`,
    [session, owner.id, ws, runner],
  );
  return {
    owner,
    spaceId,
    drafter: { ownerId: owner.id, spaceId, wikiJobId: drafting.rows[0].job_id },
    writer: wikiDocsBuildJobPrincipal(owner.id),
    session,
  };
}

