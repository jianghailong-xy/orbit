// ── writes ──────────────────────────────────────────────────────────────────────────────────────

const sha256 = (text: string): string => createHash('sha256').update(text).digest('hex');
/** A 40-hex commit named by a word: the commit a write read origin/main at. */
const commit = (word: string): string => createHash('sha1').update(word).digest('hex');

/** A section's text, one sentence a list item, so each sentence is stored exactly as given. */
const markdownOf = (sentences: readonly string[]): string => sentences.map((sentence) => `- ${sentence}`).join('\n');

interface Wrote {
  answer: Answer;
  section: { key: string; outcome: string; versionId: string | null; changed: number | null };
}

/**
 * One section written as the server's jobs write it, with the cause they say: its material's fingerprint is `material`,
 * and its body `markdown` when given, its sentences one a list item otherwise.
 */
async function write(
  h: Harness,
  s: Scene,
  planVersion: number,
  at: { slug: string; key: string },
  sentences: readonly string[],
  cause: WikiDocWriteCause,
  { material = sha256(sentences.join('\n')), repoSha = commit(sentences.join('\n')), footnotes = [] as unknown[], markdown = markdownOf(sentences) } = {},
): Promise<Wrote> {
  const answer = await served(() => h.docs.write(s.writer, s.spaceId, at.slug, {
    planVersion,
    repoSha,
    model: 'qwen3.8-27b-fp8',
    sections: [{ key: at.key, materialSha256: material, markdown, footnotes }],
  }, cause));
  expectStatus(answer, 200, `the write of ${at.slug}#${at.key}`);
  return { answer, section: answer.body.sections[0] };
}

interface VersionRow {
  id: string;
  doc_slug: string;
  section_key: string;
  reason: string;
  reason_title: string | null;
  reason_sha: string | null;
  reason_plan_version: number | null;
  job_id: string | null;
  restored_version_id: string | null;
  material_sha256: string;
  repo_sha: string;
  texts: string[];
}

/** A section's versions as the database holds them, the oldest first. */
async function versionRows(h: Harness, spaceId: string, at: { slug: string; key: string }): Promise<VersionRow[]> {
  return (await h.sql.query<VersionRow>(
    `SELECT "id"::text, "doc_slug", "section_key", "reason", "reason_title", "reason_sha", "reason_plan_version", "job_id"::text,
            "restored_version_id"::text, "material_sha256", "repo_sha",
            ARRAY(SELECT jsonb_array_elements("sentences") ->> 'text') AS "texts"
       FROM "wiki_doc_section_version" WHERE "space_id" = $1 AND "doc_slug" = $2 AND "section_key" = $3 ORDER BY "seq"`,
    [spaceId, at.slug, at.key],
  )).rows;
}

/** A section as the database holds it: its fingerprint, commit, staleness and its sentences in order. */
async function sectionNow(h: Harness, spaceId: string, at: { slug: string; key: string }) {
  const section = await h.prisma.wikiDocSection.findFirst({
    where: { key: at.key, doc: { spaceId, slug: at.slug } },
    include: { sentences: { orderBy: { position: 'asc' }, include: { footnotes: { orderBy: { position: 'asc' } } } } },
  });
  assert.ok(section, `${at.slug}#${at.key} is written`);
  return section;
}

const versionsRoute = (s: Scene, at: { slug: string; key: string }) => `/wiki/spaces/${s.spaceId}/docs/${at.slug}/sections/${at.key}/versions`;

/** Every row the version tables hold for a space, to show a refused request wrote none. */
async function footprint(h: Harness, spaceId: string): Promise<string> {
  const rows = await h.sql.query(
    `SELECT (SELECT count(*) FROM "wiki_doc_section_version" WHERE "space_id" = $1)::int AS "versions",
            (SELECT string_agg(x."id"::text || x."material_sha256", ',' ORDER BY x."id") FROM "wiki_doc_section" x
               JOIN "wiki_doc" d ON d."id" = x."doc_id" WHERE d."space_id" = $1) AS "sections"`,
    [spaceId],
  );
  return JSON.stringify(rows.rows[0]);
}

