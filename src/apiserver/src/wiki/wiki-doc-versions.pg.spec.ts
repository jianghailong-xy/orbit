/**
 * The versions a section keeps (contracts/wiki.contract.json `docs.versions`, docs/wiki-contract.md §30, migration
 * 0475; docs/wiki-chat-design.md §8.4), over real HTTP and against a real PostgreSQL.
 *
 * What the task's acceptance asks, each read back from the doors and from the database:
 *
 *   1. every rewrite keeps the version it replaced, whatever wrote it — a maintenance run, a build, a follow job for a
 *      merge, a landing or a chat's press, and the owner's restore — saying why; the server's own build and
 *      maintenance jobs say theirs where they really write (wiki-docs-build-job.pg.spec.ts, wiki-maintain-job.pg.spec.ts);
 *   2. at most five a section: the sixth deletes the oldest, in the same write, and no other section's;
 *   3. a first write replaced nothing and keeps nothing, and a section whose fingerprint did not change is not written
 *      again and keeps nothing;
 *   4. the sentence-by-sentence comparison the versions read serves is the contract's vectors
 *      (src/shared/src/wiki-chat.fixture.json `sentenceDiff`), row for row;
 *   5. a restore puts the version's fingerprint and commit back, so the next maintenance run — the documents' build
 *      itself, `runWikiDocsBuild`, as the maintain job runs it — finds the section as it was written, asks the model
 *      nothing and writes nothing;
 *   6. a restore with a session header is refused WIKI_OWNER_CHANNEL_ONLY, and another owner's version, space or
 *      section is the plain 404 — nothing written either way;
 *
 * and beside them: the document read's latest change and Activity's Docs rows, in the contract's words
 * (`wikiDocChangeLine`, `wikiDocVersionHeading`); a restore keeping what it replaced, and being taken back the same
 * way; a restore that changes nothing; a restored sentence through an entry retired since, stored withdrawn with its
 * section stale; a restore taking the entry before the document, the order the entry's withdrawal takes them in
 * (§22.6); the 409s; and the migration's CHECKs, which are the contract's closed set.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-doc-versions.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run created. Only
 * the credential checks are stood in for, as in the other wiki specs.
 */
