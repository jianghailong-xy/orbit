/**
 * The wiki's rollout flag (wiki-rollout.ts) over real HTTP and against a real PostgreSQL: what each mode of ORBIT_WIKI
 * lets an account do on the two doors, and what the runner is told when it claims or reclaims that account's sessions.
 *
 *   1. Under off, EVERY route of both doors — enumerated from the controllers, so a route added later is in this case
 *      without anybody listing it — answers 404 WIKI_DISABLED for an account that has a space, entries and a bound
 *      workspace, and nothing is written.
 *   2. Under canary, the listed account keeps both doors; every other account is refused, and writes nothing.
 *   3. A request no credential vouches for is still the credential guard's refusal: the flag says nothing to it.
 *   4. The claim and the reclaim carry `wikiDisabled` exactly for the accounts the wiki is not on for.
 *   5. An `orbit-wiki:` link card is `unavailable` to an account the wiki is off for, its own entry included.
 *
 * The push through the real delivery path is a case of wiki-push.pg.spec.ts; the flag's parsing and the guard's
 * placement on the controllers are wiki-rollout.spec.ts.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-rollout.pg.spec.ts
 *
 * The flag is read from this process's environment on every request, as the apiserver reads it (a real replica is
 * restarted to change it); each case sets it and puts it back. Not destructive: every id is generated by the run.
 */
