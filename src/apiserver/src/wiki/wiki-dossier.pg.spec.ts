  await task(h, owner.id, { status: 'CANCELLED', assigneeId: ws, updatedAt: minutesAgo(35) });
  await expectOneMore('task_terminal', 'a task settled');
  await task(h, owner.id, { status: 'OPEN', assigneeId: ws });
  assert.equal((await backlog()).backlog, state.backlog, 'an open task is no fact');

  await approval(h, talk, {
    tool: 'AskUserQuestion', status: 'ALLOWED', decidedBy: owner.id,
    input: { questions: [{ question: 'Which budget?', options: [{ label: '8k' }, { label: '16k' }] }] },
    answers: { 'Which budget?': '8k' },
  });
  await expectOneMore('approval_answered', 'an answered question');
  await approval(h, talk, { tool: 'Bash', status: 'ALLOWED', input: { command: 'ls' }, decidedBy: owner.id });
  assert.equal((await backlog()).backlog, state.backlog, 'a bare Bash allow carries nothing to learn, and is no fact');

  await receipt(h, owner.id, talk);
  await expectOneMore('merge_receipt', 'a merge receipt');

  await criterion(h, await project(h, owner.id, repo), 1);
  await expectOneMore('criterion_revised', "a criterion of a project on the space's repository");
  await criterion(h, await project(h, owner.id, 'https://github.com/somebody-else/other'), 1);
  assert.equal((await backlog()).backlog, state.backlog, "another repository's criterion is not this space's");

  // A maintenance run feeds nothing to its own backlog: its session, its task and its receipt.
  await h.sql.query(`UPDATE "session" SET "status" = 'AWAITING_INPUT', "last_turn_at" = $2 WHERE "id" = $1`, [run, utc(minutesAgo(5))]);
  await receipt(h, owner.id, run, minutesAgo(5));
  await h.sql.query(`UPDATE "task" SET "status" = 'CANCELLED', "updated_at" = $2 WHERE "list_id" = $1`, [listId, utc(minutesAgo(5))]);
