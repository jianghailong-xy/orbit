  assert.equal(state.backlog, 5);
  assert.equal(state.pendingSessions, 1, 'the session, its approval and its receipt name one session');
  assert.ok(state.oldestPendingAt && new Date(state.oldestPendingAt).getTime() <= minutesAgo(39).getTime());
  assert.ok((state.lagSeconds ?? 0) >= 39 * 60, 'the lag is how long the oldest fact has waited');
  assert.deepEqual(state.due, { backlog: false, age: false }, 'five facts, the oldest forty minutes old: not due');
  const row = await h.sql.query<{ backlog: number; pending_sessions: number }>(
    `SELECT "backlog", "pending_sessions" FROM "wiki_cursor" WHERE "space_id" = $1`, [spaceId]);
  assert.deepEqual(row.rows[0], { backlog: 5, pending_sessions: 1 }, 'the count is written back for the status line to read');

