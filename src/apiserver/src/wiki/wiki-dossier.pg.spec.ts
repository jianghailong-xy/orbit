  let state = await backlog();
  assert.equal(state.backlog, 0, 'a space with no facts has no backlog');
  assert.equal(state.lagSeconds, 0);

  const expectOneMore = async (kind: string, why: string) => {
    const before = state;
    state = await backlog();
    assert.equal(state.backlog, before.backlog + 1, `${why} adds exactly one: ${JSON.stringify(state.byKind)}`);
    assert.equal(state.byKind[kind as keyof typeof state.byKind], before.byKind[kind as keyof typeof state.byKind] + 1, `${why} is a ${kind}`);
  };

  const talk = await session(h, owner.id, { workspaceId: ws, runnerId: machine.id, status: 'AWAITING_INPUT', lastTurnAt: minutesAgo(40) });
  await expectOneMore('session_settled', 'a session come to rest');
