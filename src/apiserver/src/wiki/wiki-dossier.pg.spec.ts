/** Ten minutes ago and earlier: past the grace a fact is given to commit before a page hands it out. */
const minutesAgo = (minutes: number): Date => new Date(Date.now() - minutes * 60_000);

/**
 * A time as the UTC text Orbit's `timestamp(3)` columns hold. Handed a Date, `pg` writes the local
 * time with its offset, which a column without a zone keeps as local wall-clock time — hours off on a
 * host whose clock is not UTC, the way Prisma never writes one.
 */
const utc = (at: Date | null | undefined): string | null => (at ? at.toISOString() : null);

