/**
 * The Orbit Wiki's write path, over real HTTP and against a real PostgreSQL.
 *
 * What is under test is what a caller gets back and what the database then holds, so both are read:
 * every request goes through the real controllers, the real WikiService, the global ValidationPipe
 * and the public-id interceptor, and every claim about "nothing was written" is a count of the rows
 * migration 0307 created. Only the two credential checks are stood in for — `JwtService.verifyAsync`
 * answers with the account a bearer was issued to, and the runner guard reads the runner row this
 * file wrote — which is what `watch-api.pg.spec.ts` stands in for and for the same reason.
 *
 * The contract is `contracts/wiki.contract.json`. Every case below is one of the behaviours design
 * §4 and this task's acceptance criteria name: cross-tenant 404s, a decide that carries a session
 * header, a compare-and-set conflict that answers with the current revision, sources that do not
 * resolve and quotes that are not in the record they cite, an idempotency key replayed, an agent's
 * proposal that waits for the owner while the owner's own writes, reinforces and challenges apply at
 * once, a probe refused, a service token refused on both doors, and which of those writes announce a
 * `wiki.changed` to the owner's other clients.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-api.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created.
 */
