test('0307 · a space reads back what it holds', { skip, concurrency: 1, timeout: 300_000 }, async (t) => {
  const h = await boot();

  await t.test("the owner's spaces carry their pending count, and review and the entries read back", async () => {
    const owner = await account(h, 'reader');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id, { repoUrl: 'github.com/orbit/reader.git' });
    const mine = await session(h, owner.id, { workspaceId: ws, runnerId: machine.id });
    const tool = await toolCall(h, mine, 'Bash', 'two things to review');
    const proposed = await call(h, { runner: machine.token, headers: { 'x-orbit-session-id': mine } }, 'POST', '/runner/wiki/changesets', {
      rationale: 'two proposals',
      ops: [
        addOp({ title: 'A pg spec that skips itself proves nothing' }, [{ kind: 'tool_call', ref: tool, quote: 'two things' }]),
        addOp({ title: 'A pg spec that skips itself proves nothing either' }, [{ kind: 'tool_call', ref: tool, quote: 'to review' }]),
      ],
    });
    expectStatus(proposed, 200, 'two proposals land');

    const spaces = await call(h, { bearer: owner.bearer }, 'GET', '/wiki/spaces');
    expectStatus(spaces, 200, 'the owner lists their spaces');
    assert.equal(spaces.body.length, 1);
    assert.equal(spaces.body[0].pendingOps, 2, 'the sidebar number is the pending ops');
    assert.equal(spaces.body[0].settings.push, true, 'a new space pushes by default');
    assert.equal(spaces.body[0].settings.autoAcceptReinforce, true);

    const review = await call(h, { bearer: owner.bearer }, 'GET', '/wiki/review');
    expectStatus(review, 200, 'the review queue');
    assert.equal(review.body.length, 1);
    assert.equal(review.body[0].ops.length, 2);
    assert.equal(review.body[0].ops[1].similar[0]?.id, proposed.body.ops[0].entryId, 'an op carries the neighbours already in the space');

    const entryId = proposed.body.ops[0].entryId as string;
    const one = await call(h, { bearer: owner.bearer }, 'GET', `/wiki/entries/${entryId}?include=sources,history`);
    expectStatus(one, 200, 'one entry');
    assert.equal(one.body.sources.length, 1);
    assert.equal(one.body.sources[0].quoteVerified, true);
    assert.equal(one.body.history.length, 1);
    assert.equal(one.body.history[0].authorKind, 'agent');

    const listed = await call(h, { bearer: owner.bearer }, 'GET', `/wiki/spaces/${spaces.body[0].id}/entries?kind=pitfall&status=proposed`);
    expectStatus(listed, 200, 'the entries of a space');
    assert.equal(listed.body.length, 2);
    const filtered = await call(h, { bearer: owner.bearer }, 'GET', `/wiki/spaces/${spaces.body[0].id}/entries?kind=principle`);
    assert.equal(filtered.body.length, 0);
  });
});
