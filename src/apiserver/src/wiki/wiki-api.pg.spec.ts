test('0307 · a credential in a submission is taken out of what is stored', { skip, concurrency: 1, timeout: 300_000 }, async (t) => {
  const h = await boot();

  await t.test('a secret in a quote, and an owner env value in a title, are redacted', async () => {
    const owner = await account(h, 'redaction');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id, {
      repoUrl: 'github.com/orbit/redaction.git',
      env: { SPEC_DEPLOY_KEY: 's3cret-deploy-value' },
    });
    const mine = await session(h, owner.id, { workspaceId: ws, runnerId: machine.id });
    const tool = await toolCall(h, mine, 'Bash', 'connect with postgres://orbit:hunter2@db:5432/orbit and it works');
    const propose = (ops: unknown[]) =>
      call(h, { runner: machine.token, headers: { 'x-orbit-session-id': mine } }, 'POST', '/runner/wiki/changesets', {
        rationale: 'what was in the log line',
        ops,
      });

    const secret = await propose([
      addOp({ title: 'A connection string in a log line' }, [
        { kind: 'tool_call', ref: tool, quote: 'postgres://orbit:hunter2@db:5432/orbit' },
      ]),
    ]);
    expectStatus(secret, 200, 'the op is recorded');
    const op = await h.prisma.wikiChangesetOp.findFirstOrThrow({ where: { id: toUuid(secret.body.ops[0].opId) } });
    assert.equal(JSON.stringify(op.payload).includes('hunter2'), false, 'the password is not in the stored payload');
    assert.match(JSON.stringify(op.payload), /\[redacted\]/u);

    // The stored quote is the redacted one, so nothing this account holds carries the credential.
    const revision = await h.prisma.wikiEntryRevision.findFirstOrThrow({ where: { entryId: toUuid(secret.body.ops[0].entryId) } });
    const stored = await h.prisma.wikiSource.findFirstOrThrow({ where: { revisionId: revision.id } });
    assert.equal(stored.quote?.includes('hunter2') ?? false, false, 'the stored quote is redacted too');
    assert.equal(stored.quoteVerified, false, 'and a quote that changed is no longer a verbatim quote');

    const envValue = await propose([
      addOp(
        { title: 'A deploy key that leaked into a summary', summary: 'It was s3cret-deploy-value in the log.' },
        [{ kind: 'turn', session: 'self' }],
      ),
    ]);
    expectStatus(envValue, 200, "a value only this account's environment holds is replaced wherever it appears");
    const second = await h.prisma.wikiChangesetOp.findFirstOrThrow({ where: { id: toUuid(envValue.body.ops[0].opId) } });
    assert.equal(JSON.stringify(second.payload).includes('s3cret-deploy-value'), false);
    assert.match(JSON.stringify(second.payload), /\[redacted\]/u);
  });
});

