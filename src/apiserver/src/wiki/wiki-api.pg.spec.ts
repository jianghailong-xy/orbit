test('0307 · who may reach the wiki, and with what', { skip, concurrency: 1, timeout: 300_000 }, async (t) => {
  const h = await boot();

  await t.test("another account's space, entry and changeset are 404s on both doors", async () => {
    const owner = await account(h, 'tenant');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id, { repoUrl: 'github.com/orbit/tenant.git' });
    const mine = await session(h, owner.id, { workspaceId: ws, runnerId: machine.id });
    const tool = await toolCall(h, mine, 'Bash', 'this belongs to one account');
    const seeded = await call(h, { runner: machine.token, headers: { 'x-orbit-session-id': mine } }, 'POST', '/runner/wiki/changesets', {
      rationale: "one account's entry",
      ops: [addOp({ title: 'An entry one account owns' }, [{ kind: 'tool_call', ref: tool, quote: 'one account' }])],
    });
    expectStatus(seeded, 200, 'the owner of the entry proposes');
    const entryId = seeded.body.ops[0].entryId as string;
    const spaceId = (await h.prisma.wikiEntry.findFirstOrThrow({ where: { id: toUuid(entryId) } })).spaceId;

    const thief = await account(h, 'the other account');
    const thiefMachine = await runner(h, thief.id);
    const thiefWs = await workspace(h, thief.id, { repoUrl: 'github.com/orbit/tenant.git' });
    const thiefSession = await session(h, thief.id, { workspaceId: thiefWs, runnerId: thiefMachine.id });
    expectStatus(await call(h, { bearer: thief.bearer }, 'GET', `/wiki/entries/${entryId}`), 404, 'a foreign entry read');
    expectStatus(await call(h, { bearer: thief.bearer }, 'GET', `/wiki/spaces/${spaceId}`), 404, 'a foreign space read');
    expectStatus(await call(h, { bearer: thief.bearer }, 'GET', `/wiki/spaces/${spaceId}/entries`), 404, 'a foreign space listed');
    expectStatus(
      await call(h, { bearer: thief.bearer }, 'PATCH', `/wiki/spaces/${spaceId}`, { push: false }),
      404,
      'a foreign space patched',
    );
    expectStatus(
      await call(h, { bearer: thief.bearer }, 'POST', `/wiki/spaces/${spaceId}/workspaces`, { workspaceId: thiefWs }),
      404,
      'a foreign space bound',
    );
    expectStatus(
      await call(h, { bearer: thief.bearer }, 'POST', `/wiki/spaces/${spaceId}/changesets`, {
        rationale: 'x',
        ops: [addOp({ title: 'Theirs' }, [])],
      }),
      404,
      'a foreign space written into',
    );
    expectStatus(
      await call(h, { bearer: thief.bearer }, 'POST', `/wiki/changesets/${seeded.body.changesetId}/decide`, {
        decisions: [{ opId: seeded.body.ops[0].opId, action: 'accept' }],
      }),
      404,
      'a foreign changeset decided',
    );
    expectStatus(
      await call(h, { runner: thiefMachine.token, headers: { 'x-orbit-session-id': thiefSession } }, 'GET', `/runner/wiki/entries/${entryId}`),
      404,
      'a foreign entry read from the runner door',
    );
    expectStatus(
      await call(h, { runner: thiefMachine.token, headers: { 'x-orbit-session-id': thiefSession } }, 'POST', '/runner/wiki/changesets', {
        rationale: "an op about somebody else's entry",
        ops: [{ op: 'challenge', entryId, reason: 'not mine to touch' }],
      }),
      404,
      'a foreign entry named by an op',
    );
    const entry = await h.prisma.wikiEntry.findFirstOrThrow({ where: { id: toUuid(entryId) } });
    assert.equal(entry.status, 'proposed', 'nothing the other account did changed anything');
    assert.equal(entry.challenged, false);
    assert.equal(
      await h.prisma.wikiEntry.count({ where: { ownerId: thief.id } }),
      0,
      'and the other account holds no entry of its own out of any of it',
    );
  });

  await t.test('a decide that carries a session header is refused, whatever that session is', async () => {
    const owner = await account(h, 'channel');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id, { repoUrl: 'github.com/orbit/channel.git' });
    const mine = await session(h, owner.id, { workspaceId: ws, runnerId: machine.id });
    const tool = await toolCall(h, mine, 'Bash', 'a proposal the owner has not answered');
    const seeded = await call(h, { runner: machine.token, headers: { 'x-orbit-session-id': mine } }, 'POST', '/runner/wiki/changesets', {
      rationale: 'something to decide',
      ops: [addOp({ title: 'An op that waits for a person' }, [{ kind: 'tool_call', ref: tool, quote: 'not answered' }])],
    });
    const decision = { decisions: [{ opId: seeded.body.ops[0].opId, action: 'accept' }] };

    const withSession: Array<Record<string, string>> = [
      { 'x-orbit-session-id': mine },
      { 'x-orbit-session-token': 'a-proof' },
      { 'x-orbit-session-anything': 'x' },
    ];
    for (const headers of withSession) {
      const refused = await call(h, { bearer: owner.bearer, headers }, 'POST', `/wiki/changesets/${seeded.body.changesetId}/decide`, decision);
      expectStatus(refused, 403, `a decide carrying ${Object.keys(headers)[0]} is refused`);
      assert.equal(refused.body.code, 'WIKI_OWNER_CHANNEL_ONLY');
    }
    const op = await h.prisma.wikiChangesetOp.findFirstOrThrow({ where: { id: toUuid(seeded.body.ops[0].opId) } });
    assert.equal(op.decision, 'pending', 'and nothing was decided');

    // The same decision, on the owner channel with no acting session, goes through.
    expectStatus(
      await call(h, { bearer: owner.bearer }, 'POST', `/wiki/changesets/${seeded.body.changesetId}/decide`, decision),
      200,
      "the owner's own call decides it",
    );
  });

  await t.test('a service token is refused on both doors and writes nothing', async () => {
    const owner = await account(h, 'service');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id, { repoUrl: 'github.com/orbit/service.git' });
    const mine = await session(h, owner.id, { workspaceId: ws, runnerId: machine.id });
    // Minted by the real authorizer: a token this account could really hold, not a made-up string.
    const minted = await new ServiceTokenAuthorizer(
      h.prisma as unknown as PrismaService,
      new JwtService({ secret: 'wiki-spec-service-token' }),
    ).mint({ id: machine.id, ownerId: owner.id }, { scopes: ['session:get'], ttlSeconds: 3_600 });

    const onRunner = await call(h, { runner: minted.token, headers: { 'x-orbit-session-id': mine } }, 'POST', '/runner/wiki/changesets', {
      rationale: 'a bridge token asking for the wiki',
      ops: [addOp({ title: 'A bridge token proposes' }, [{ kind: 'turn', session: 'self' }])],
    });
    expectStatus(onRunner, 401, 'the runner door refuses a service token');
    expectStatus(await call(h, { bearer: minted.token }, 'GET', '/wiki/spaces'), 401, 'the user door refuses a service token');
    assert.equal(await h.prisma.wikiEntry.count({ where: { ownerId: owner.id } }), 0);
    assert.equal(await h.prisma.wikiChangeset.count({ where: { ownerId: owner.id } }), 0);
  });

  await t.test('a session that verifies, forems or judges work is excluded from the wiki', async () => {
    const owner = await account(h, 'excluded');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id, { repoUrl: 'github.com/orbit/excluded.git' });
    const subject = await task(h, owner.id);
    const verifier = await session(h, owner.id, {
      workspaceId: ws,
      runnerId: machine.id,
      taskId: await task(h, owner.id, { verifiesTaskId: subject }),
    });
    const foreman = await session(h, owner.id, {
      workspaceId: ws,
      runnerId: machine.id,
      taskId: await task(h, owner.id, { isForeman: true }),
    });
    const judging = await session(h, owner.id, { workspaceId: ws, runnerId: machine.id, dispatchOrigin: 'PROJECT_COORDINATOR' });

    for (const excluded of [verifier, foreman, judging]) {
      const refused = await call(h, { runner: machine.token, headers: { 'x-orbit-session-id': excluded } }, 'POST', '/runner/wiki/changesets', {
        rationale: 'knowledge is not evidence',
        ops: [addOp({ title: 'An op from a session that judges' }, [{ kind: 'turn', session: 'self' }])],
      });
      expectStatus(refused, 403, 'a session that judges work is refused');
      assert.equal(refused.body.code, 'WIKI_SESSION_EXCLUDED');
    }
    assert.equal(await h.prisma.wikiEntry.count({ where: { ownerId: owner.id } }), 0);
  });

  await t.test("a session another machine hosts is not this door's caller", async () => {
    const owner = await account(h, 'notmine');
    const machine = await runner(h, owner.id);
    const otherMachine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id, { repoUrl: 'github.com/orbit/notmine.git' });
    const mine = await session(h, owner.id, { workspaceId: ws, runnerId: otherMachine.id });
    const refused = await call(
      h,
      { runner: machine.token, headers: { 'x-orbit-session-id': mine } },
      'GET',
      `/runner/wiki/entries/${randomUUID()}`,
    );
    expectStatus(refused, 403, "a session another machine hosts is not this door's caller");
  });
});

