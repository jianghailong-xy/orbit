/** The window the condition names: 2026-09-01 .. 2026-09-30, both days included. */
const SINCE = '2026-09-01';
const UNTIL = '2026-09-30';

async function scene(h: Harness): Promise<Scene> {
  const owner = await account(h, 'owner');
  const machine = await runner(h, owner.id);
  const ws = await workspace(h, owner.id);
  const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: 'A built space' });
  expectStatus(made, 201, 'the owner creates a space');
  const spaceId = toUuid(made.body.id as string);
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${spaceId}/workspaces`, { workspaceId: ws }), 200, 'the owner binds the workspace');
  const on = await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${spaceId}`, { maintenance: { enabled: true, workspaceId: ws } });
  expectStatus(on, 200, 'the owner turns maintenance on');
  const listId = toUuid(on.body.settings.maintenance.listId as string);
  const maintenanceSession = await session(h, owner.id, ws, machine.id, await task(h, owner.id, ws, { listId, title: 'Wiki maintenance run' }));
  const ordinary = await session(h, owner.id, ws, machine.id, null, 'an ordinary session');

  // A project, its coordinator conversation and one of its tasks' sessions, with what was said in them.
  const coordinator = await session(h, owner.id, ws, machine.id, null, 'the coordinator');
  const projectId = await project(h, owner.id, 'Runner 托管后台作业', coordinator);
  const projectTask = await task(h, owner.id, ws, { projectId, title: '整包测试在宿主上跑' });
  const taskSession = await session(h, owner.id, ws, machine.id, projectTask, '执行任务：整包测试在宿主上跑');
  const r = {
    owner: await turn(h, coordinator, OWNER_WORDS, true, '2026-09-20T10:00:00Z'),
    old: await turn(h, coordinator, OLD_OWNER_WORDS, true, '2026-08-01T10:00:00Z'),
    notOwners: await turn(h, taskSession, NOT_OWNERS, false, '2026-09-21T10:00:00Z'),
    delivery: await comment(h, projectTask, owner.id, DELIVERY, 'AGENT', '2026-09-22T10:00:00Z'),
    long: await toolCall(h, ordinary, 'Bash', { command: 'go test ./...' }, LONG_OUTPUT, true),
    plain: await toolCall(h, ordinary, 'Bash', { command: 'git status' }, 'nothing to commit, working tree clean'),
  };

  // The entries the space holds: one a keyword finds, one an anchor path finds, one neither does.
  const agent = { runner: machine.token, session: ordinary };
  const propose = async (entry: Record<string, unknown>, sources: unknown[]): Promise<string> => {
    const proposed = await call(h, agent, 'POST', '/runner/wiki/changesets', {
      rationale: 'what the session learned',
      idempotencyKey: `docs-build-${randomUUID()}`,
      ops: [{ op: 'add', entry, sources }],
    });
    expectStatus(proposed, 200, 'an agent proposes an entry');
    assert.equal(proposed.body.ops[0].status, 'applied', `the space's mode applies it: ${JSON.stringify(proposed.body.ops[0]).slice(0, 400)}`);
    return toUuid(proposed.body.ops[0].entryId as string);
  };
  const entries = {
    keyword: await propose(
      { kind: 'concept', title: '全量测试在 runner 宿主上跑', summary: 'The whole suite runs on the runner host.', fields: { definition: 'where the suite runs', boundaries: 'tests only' } },
      [{ kind: 'tool_call', ref: r.long, quote: 'the suite must run on the runner 宿主' }],
    ),
    path: await propose(
      {
        kind: 'concept',
        title: 'git status 是干净的',
        summary: 'A clean tree before a run.',
        fields: { definition: 'a clean tree', boundaries: 'the checkout' },
        anchors: [{ type: 'path', path: 'src/runner-go/runloop.go' }],
      },
      [{ kind: 'tool_call', ref: r.plain, quote: 'nothing to commit' }],
    ),
    unrelated: await propose(
      { kind: 'concept', title: '别的事', summary: 'Something else entirely.', fields: { definition: 'something else', boundaries: 'none' } },
      [{ kind: 'tool_call', ref: r.plain, quote: 'working tree clean' }],
    ),
  };
  return { owner, runner: machine, ws, spaceId, maintainer: { runner: machine.token, session: maintenanceSession }, maintenanceSession, ordinary, projectId, r, entries };
}

