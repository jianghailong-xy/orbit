// ── the ledger ──────────────────────────────────────────────────────────────────────────────────

test('what became of each piece of material is written with its section, refused when malformed, and read back on both doors', { skip }, async () => {
  const h = await boot();
  const s = await scene(h);
  const { version, keys } = await confirmPlan(h, s);
  const section = (dispositions: unknown[]) => ({
    planVersion: version,
    repoSha: 'c'.repeat(40),
    sections: [{
      key: keys[1],
      materialSha256: createHash('sha256').update(JSON.stringify(dispositions)).digest('hex'),
      markdown: '测试在宿主上跑。',
      footnotes: [],
      dispositions,
    }],
  });
  const write = (body: unknown) => call(h, s.maintainer, 'POST', `/runner/wiki/spaces/${s.spaceId}/docs/${SLUG}`, body);
  const ledger = [
    { material: 'C1', kind: 'code', ref: 'src/runner-go/runloop.go#L10-40', action: 'adopt', into: null, reason: '讲 runLoop 怎么领取' },
    { material: 'S1', kind: 'turn', ref: s.r.owner, action: 'merge', into: 'S2', reason: `与 S2 说的是同一件事，S2 更新；密钥 ${LITERAL}` },
    { material: 'S2', kind: 'task_comment', ref: s.r.delivery, action: 'adopt', into: null, reason: '交付记录' },
    { material: 'S3', kind: 'tool_call', ref: s.r.plain, action: 'drop', into: null, reason: '与本节无关' },
    { material: 'S4', kind: 'turn', ref: s.r.notOwners, action: 'filtered', into: null, reason: '平台自动生成的复查模板' },
    { material: 'D1', kind: 'design_doc', ref: 'docs/architecture.md#L1-80', action: 'over_cap', into: null, reason: '超出本节材料上限' },
  ];
  assert.deepEqual([...new Set(ledger.map((item) => item.action))].sort(), [...WIKI_DOC_DISPOSITION_ACTIONS].sort(), 'every action is exercised');
  expectStatus(await write(section(ledger)), 200, 'a section with its ledger');
  const stored = await h.prisma.wikiDocSection.findFirstOrThrow({ where: { ownerId: s.owner.id, key: keys[1] }, select: { dispositions: true } });
  const kept = stored.dispositions as Array<{ material: string; reason: string }>;
  assert.deepEqual(kept.map((item) => item.material), ledger.map((item) => item.material), 'stored as it came, in its order');
  assert.ok(kept.every((item) => !item.reason.includes(LITERAL)), 'a reason is redacted like everything stored');

  // Both doors read it back with the section.
  const page = await call(h, { bearer: s.owner.bearer }, 'GET', `/wiki/spaces/${s.spaceId}/docs/${SLUG}`);
  expectStatus(page, 200, 'the owner\'s page');
  const onPage = page.body.sections.find((sec: { key: string }) => sec.key === keys[1]);
  assert.deepEqual(onPage.dispositions.map((item: { action: string }) => item.action), ledger.map((item) => item.action));
  const writerDoc = await call(h, s.maintainer, 'GET', `/runner/wiki/spaces/${s.spaceId}/docs/${SLUG}`);
  expectStatus(writerDoc, 200, 'the maintenance run\'s read');
  assert.deepEqual(writerDoc.body, page.body, 'the runner door reads the document as the owner does');
  const unwritten = page.body.sections.find((sec: { key: string }) => sec.key === keys[0]);
  assert.deepEqual(unwritten.dispositions, [], 'a section not written yet has none');

  // Malformed: every error at once, nothing written.
  const bad = await write(section([
    { material: 'S1', kind: 'turn', ref: s.r.owner, action: 'keep', into: null, reason: 'x' },
    { material: 'S2', kind: 'turn', ref: s.r.owner, action: 'merge', into: null, reason: 'x' },
    { material: 'S3', kind: 'turn', ref: s.r.owner, action: 'merge', into: 'S9', reason: 'x' },
    { material: 'S4', kind: 'turn', ref: s.r.owner, action: 'drop', into: 'S1', reason: 'x' },
    { material: 'S5', kind: 'turn', ref: s.r.owner, action: 'drop', into: null, reason: '  ' },
    { material: 'S5', kind: 'nothing', ref: s.r.owner, action: 'drop', into: null, reason: 'x', extra: true },
  ]));
  expectStatus(bad, 422, 'a malformed ledger');
  assert.equal(bad.body.code, 'WIKI_DOC_INVALID');
  const paths = bad.body.errors.map((error: { path: string }) => error.path);
  for (const at of [
    'sections[0].dispositions[0].action',
    'sections[0].dispositions[1].into',
    'sections[0].dispositions[2].into',
    'sections[0].dispositions[3].into',
    'sections[0].dispositions[4].reason',
    'sections[0].dispositions[5].material',
    'sections[0].dispositions[5].kind',
    'sections[0].dispositions[5].extra',
  ]) {
    assert.ok(paths.includes(at), `an error at ${at} among ${paths.join(', ')}`);
  }
  const after = await h.prisma.wikiDocSection.findFirstOrThrow({ where: { ownerId: s.owner.id, key: keys[1] }, select: { dispositions: true } });
  assert.deepEqual(after.dispositions, stored.dispositions, 'nothing was written');
  // Stored as an array, and the migration holds it to one.
  const check = await h.sql.query<{ def: string }>(`SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conname = 'wiki_doc_section_dispositions_chk'`);
  assert.match(check.rows[0]?.def ?? '', /jsonb_typeof\(dispositions\) = 'array'/u);
});
