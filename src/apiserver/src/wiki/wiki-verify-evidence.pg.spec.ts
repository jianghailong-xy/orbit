/** One run event of a session, in the payload shapes the runner stores (run_event.payload). */
async function event(h: Harness, sessionId: string, type: string, payload: Record<string, unknown>): Promise<string> {
  const id = randomUUID();
  await h.sql.query(
    `INSERT INTO "run_event"("id","session_id","seq","type","payload")
     VALUES ($1,$2,(SELECT COALESCE(MAX("seq"), 0) + 1 FROM "run_event" WHERE "session_id" = $2),$3,$4)`,
    [id, sessionId, type, JSON.stringify(payload)],
  );
  return id;
}

/** A space the owner makes through the door and puts in a mode, bound to a workspace when one is named. */
async function modeSpace(h: Harness, owner: Account, mode: Mode, workspaceId?: string): Promise<string> {
  const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: `A ${mode} space` });
  expectStatus(made, 201, 'the owner creates a space');
  const id = made.body.id as string;
  await setMode(h, owner, toUuid(id), mode);
  if (workspaceId) {
    const bound = await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${id}/workspaces`, { workspaceId });
    expectStatus(bound, 200, 'the owner binds the workspace');
  }
  return toUuid(id);
}

async function setMode(h: Harness, owner: Account, spaceId: string, mode: Mode): Promise<void> {
  const switched = await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${spaceId}`, { reviewMode: mode });
  expectStatus(switched, 200, `the owner puts the space in ${mode}`);
}

/** A valid pitfall, retitled per use. */
function pitfall(title: string, summary = `What the space knows about ${title.toLowerCase()}.`): Record<string, unknown> {
  return {
    kind: 'pitfall' satisfies WikiKind,
    title,
    summary,
    fields: {
      trigger: { paths: ['scripts/release.sh'], commands: ['bash scripts/release.sh next'] },
      symptom: 'A tag is pushed before anybody looked at it.',
      cause: 'The script is not a dry run.',
      fix: 'Read the script before running it.',
    },
  };
}

