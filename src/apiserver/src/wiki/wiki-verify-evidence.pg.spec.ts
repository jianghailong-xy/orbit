/** What the verification list hands the calling session, every page of it. */
async function listed(h: Harness, who: Caller, spaceId: string): Promise<VerificationItem[]> {
  const items: VerificationItem[] = [];
  let after: string | null = null;
  for (let page = 0; page < 50; page += 1) {
    const answer = await call(h, who, 'GET', `/runner/wiki/spaces/${spaceId}/verifications?limit=5${after ? `&after=${after}` : ''}`);
    expectStatus(answer, 200, 'the verification list');
    items.push(...(answer.body.items as VerificationItem[]));
    after = answer.body.next;
    if (!after) return items;
  }
  throw new Error('the verification list never ended');
}

async function propose(h: Harness, who: Caller, ops: unknown[], rationale = 'what the records say'): Promise<Outcome[]> {
  const answer = await call(h, who, 'POST', '/runner/wiki/changesets', { rationale, ops, idempotencyKey: `evidence-${randomUUID()}` });
  expectStatus(answer, 200, rationale);
  return answer.body.ops as Outcome[];
}

// ── 1. what a verifier reads ────────────────────────────────────────────────────────────────────

test('evidence · a tool call, a tool result and a thinking reach the verifier as text, and the quote check reads the same', { skip, concurrency: 1, timeout: 300_000 }, async (t) => {
  const h = await boot();
  const owner = await account(h, 'evidence-text');
  const machine = await runner(h, owner.id);
  const literal = 'wiki-evidence-literal-9f3c2a71';
  const ws = await workspace(h, owner.id, { DEPLOY_SECRET: literal });
  const space = await modeSpace(h, owner, 'automatic', ws);
  const records = await session(h, owner.id, ws, machine);
  const toolUse = await event(h, records, 'tool_use', {
    id: 'toolu_01', name: 'Bash', input: { command: 'bash scripts/release.sh next', description: 'Cut the next release' },
  });
  const toolResult = await event(h, records, 'tool_result', {
    toolUseId: 'toolu_01', isError: false, content: 'Tagged v0.1.196 and pushed the tag: release.sh next is not a dry run',
  });
  const blocks = await event(h, records, 'tool_result', {
    toolUseId: 'toolu_02',
    isError: false,
    content: [
      { type: 'text', text: 'The first block of the result' },
      { type: 'image', source: { type: 'base64', media_type: 'image/png', data: 'AAAA' } },
      { type: 'text', text: 'The second block says the index is missing' },
    ],
  });
  const failed = await event(h, records, 'tool_result', { toolUseId: 'toolu_03', isError: true, content: 'permission denied: /var/lib/orbit' });
  const thought = await event(h, records, 'thinking', { text: 'The script tags before it asks anything, so next is not a dry run.' });
  const emptyThought = await event(h, records, 'thinking', { text: '' });
  const counts = await event(h, records, 'system', { subtype: 'context', contextTokens: 51234 });
  const summary = await event(h, records, 'system', { subtype: 'compact_summary', text: 'So far: the release script tags at once.' });
  const long = await event(h, records, 'tool_result', {
    toolUseId: 'toolu_04',
    content: `Authorization: Bearer abcdefghijklmnopqrstuvwx0123 and ${literal} ${'x'.repeat(9_000)} the end of the output`,
  });
  const proposer = await session(h, owner.id, ws, machine);
  const mine = { runner: machine, headers: { 'x-orbit-session-id': proposer } };
  const ev = (ref: string, quote?: string) => ({ kind: 'event', ref, ...(quote ? { quote } : {}) });

  const outcomes = await propose(h, mine, [
    { op: 'add', entry: pitfall('The release script tags at once'), sources: [ev(toolUse, 'release.sh next'), ev(toolResult, 'is not a dry run')] },
    { op: 'add', entry: pitfall('The index is missing after a restore'), sources: [ev(blocks, 'the index is missing')] },
    { op: 'add', entry: pitfall('Permission denied under the orbit state directory'), sources: [ev(failed, 'permission denied')] },
    { op: 'add', entry: pitfall('Next is not a dry run'), sources: [ev(thought, 'tags before it asks anything')] },
    { op: 'add', entry: pitfall('A claim that rests on nothing readable'), sources: [ev(emptyThought), ev(counts)] },
    { op: 'add', entry: pitfall('A long tool output'), sources: [ev(long)] },
    { op: 'add', entry: pitfall('A compaction summary says the script tags'), sources: [ev(summary, 'tags at once')] },
  ]);

  await t.test('every quote is checked against the text the verifier reads: a tool call\'s input, a result, a thinking', async () => {
    assert.deepEqual(outcomes.map((op) => [op.status, op.waitsFor]), Array(7).fill(['pending', 'verification']));
    const quoted = await h.prisma.wikiSource.findMany({ where: { ownerId: owner.id, quote: { not: null } }, select: { ref: true, quoteVerified: true } });
    const verified = new Map(quoted.map((source) => [source.ref, source.quoteVerified]));
    for (const ref of [toolUse, toolResult, blocks, failed, thought, summary]) assert.equal(verified.get(ref), true, `the quote of ${ref} was verified`);
    // A quote the record does not hold is refused, now that its text can be read.
    const wrong = await call(h, mine, 'POST', '/runner/wiki/changesets', {
      rationale: 'a quote the tool never printed',
      idempotencyKey: `wrong-${randomUUID()}`,
      ops: [{ op: 'add', entry: pitfall('A quote nobody printed'), sources: [ev(toolResult, 'the build was green')] }],
    });
    expectStatus(wrong, 422, 'a quote that is not in the result');
    assert.equal(wrong.body.ops[0].reasons[0].code, 'WIKI_QUOTE_NOT_FOUND');
    // An empty thinking has no text to check a quote against: kept, and marked unverified, as before.
    const unchecked = await propose(h, mine, [{ op: 'add', entry: pitfall('A quote of an empty thinking'), sources: [ev(emptyThought, 'something it never said')] }]);
    assert.equal(unchecked[0].status, 'pending');
    const kept = await h.prisma.wikiSource.findFirstOrThrow({ where: { ownerId: owner.id, ref: emptyThought, quote: 'something it never said' } });
    assert.equal(kept.quoteVerified, false);
  });

  await t.test('the list hands each source\'s text: a tool\'s name and input, a result\'s content, a thinking\'s words', async () => {
    const items = await listed(h, mine, space);
    const item = (title: string) => {
      const found = items.find((candidate) => candidate.entry.title === title);
      assert.ok(found, `${title} is not in the list`);
      return found;
    };
    const release = item('The release script tags at once');
    assert.equal(release.sources[0].text, 'Bash\ncommand: bash scripts/release.sh next\ndescription: Cut the next release');
    assert.equal(release.sources[1].text, 'Tagged v0.1.196 and pushed the tag: release.sh next is not a dry run');
    assert.equal(release.evidence, 'readable');
    assert.equal(item('The index is missing after a restore').sources[0].text, 'The first block of the result\nThe second block says the index is missing');
    assert.equal(item('Permission denied under the orbit state directory').sources[0].text, 'The tool reported an error:\npermission denied: /var/lib/orbit');
    assert.equal(item('Next is not a dry run').sources[0].text, 'The script tags before it asks anything, so next is not a dry run.');
    assert.equal(item('A compaction summary says the script tags').sources[0].text, 'So far: the release script tags at once.');
    for (const source of release.sources) assert.equal(source.truncated, false);
  });

  await t.test('an empty thinking and a system event\'s counts are nothing to read, and the op says so', async () => {
    const items = await listed(h, mine, space);
    const nothing = items.find((candidate) => candidate.entry.title === 'A claim that rests on nothing readable')!;
    assert.deepEqual(nothing.sources.map((source) => source.text), [null, null]);
    assert.equal(nothing.evidence, 'unreadable');
    const quotedEmpty = items.find((candidate) => candidate.entry.title === 'A quote of an empty thinking')!;
    assert.equal(quotedEmpty.sources[0].text, null, 'a quote is not the record\'s text');
    assert.equal(quotedEmpty.evidence, 'unreadable');
  });

  await t.test('a long result is redacted before it is cut, and the cut is marked', async () => {
    const items = await listed(h, mine, space);
    const source = items.find((candidate) => candidate.entry.title === 'A long tool output')!.sources[0];
    assert.equal(source.truncated, true);
    assert.equal([...source.text!].length, WIKI_REVIEW_RULES.verificationSourceMaxChars);
    assert.doesNotMatch(source.text!, /abcdefghijklmnopqrstuvwx0123/u, 'a credential shape is redacted');
    assert.ok(!source.text!.includes(literal), 'and so is the owner\'s own workspace value');
    assert.match(source.text!, /\[redacted\]/u);
  });
});

// ── 2. nothing readable: no more than Unreviewed, and not counted ────────────────────────────────

