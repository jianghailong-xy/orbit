/**
 * A verification has to be able to read its evidence (criterion 7, revision 4; contracts/wiki.contract.json
 * `reviewModes.verification.evidence`, `.reopen`, `reviewModes.entryConfirm` and `floors.taintedWaits`),
 * over real HTTP and against a real PostgreSQL.
 *
 *   1. a tool call, a tool result — a string or blocks — a thinking and a system event's words reach the
 *      verifier as text, redacted and cut, and the quote a submission cites is checked against that same
 *      text; an empty thinking and a system event's counts are nothing to read, and an op none of whose
 *      sources has text is listed as having no readable evidence;
 *   2. a verdict about records nobody could read leaves its op no more than Unreviewed — whatever the
 *      verifier said, enforced by the server — a duplicate still adds its sources, and none of it
 *      counts toward the fallback to Tiered;
 *   3. in Automatic a tainted op is verified instead of queued, never more than Unreviewed, pushed to
 *      nobody and invisible to an agent's search and get, and takes no place in the 30-op queue; the
 *      owner's Confirm (their door alone) makes it confirmed, a revision of theirs, and pushed; its
 *      duplicate changes nothing about the entry it names; Manual and Tiered still hold it for the owner;
 *   4. the reopening: an op an unsupported verdict rejected when the reader of the time could read
 *      none of its sources waits for its verification again, the earlier verdict kept in its history
 *      and gone from the neighbours' hints; and a tainted op an automatic space holds for the owner is
 *      sent to its verification.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-verify-evidence.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the two credential checks are stood in for, as in `wiki-verify.pg.spec.ts`; the push is
 * the real `appendWikiContext`, and the owner's notifications stand-ins that record each call.
 */
