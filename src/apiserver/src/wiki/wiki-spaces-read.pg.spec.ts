function docInput(slug: string, title: string): Record<string, unknown> {
  return {
    category: 'product',
    slug,
    title,
    question: `What is ${title}?`,
    audience: ['A new developer: can say how it works after reading it'],
    scopeIn: [`How ${slug} works`],
    scopeOut: [],
    length: { min: 800, max: 4000 },
    sections: [
      { title: '总览', kind: 'overview', covers: '它是什么。', length: 400, sources: {} },
      { title: '怎么运转', kind: 'flow', covers: '它的步骤。', length: 400, sources: {} },
    ],
  };
}

const PLAN = {
  categories: [{ key: 'product', title: 'Product', question: 'What Orbit is and how it runs' }],
  docs: [docInput('session-runtime', '会话运行模型'), docInput('task-dispatch', '任务派发'), docInput('runner-host', 'Runner 托管')],
};

const REPO = { sha: 'a'.repeat(40), checked: 3, missing: [] };

async function draft(h: Harness, maintainer: Caller, spaceId: string, baseVersion: number | null): Promise<number> {
  const drafted = await call(h, maintainer, 'POST', `/runner/wiki/spaces/${spaceId}/plan/drafts`, {
    baseVersion,
    target: { min: 1, max: 10 },
    plan: PLAN,
    repoCheck: REPO,
    model: 'qwen3.8-27b-fp8',
  });
  expectStatus(drafted, 200, 'the maintenance run drafts the plan');
  return drafted.body.version as number;
}

const b62 = (id: string): string => uuidToBase62(id);

interface Row {
  id: string;
  pendingOps: number;
  planWaiting: number;
  workspaceIds: string[];
  workspacePublicIds?: string[];
  docs: { written: number; total: number } | null;
}

async function rows(h: Harness, owner: Account): Promise<Map<string, Row>> {
  const listed = await call(h, { bearer: owner.bearer }, 'GET', '/wiki/spaces');
  expectStatus(listed, 200, 'the owner lists their spaces');
  return new Map((listed.body as Row[]).map((row) => [toUuid(row.id), row]));
}

/** What the space's own plan read says waits on the owner, counted by the rule the list counts by. */
async function fromPlanRead(h: Harness, owner: Account, spaceId: string, runnerOnline: boolean | null): Promise<number> {
  const read = await call(h, { bearer: owner.bearer }, 'GET', `/wiki/spaces/${spaceId}/plan`);
  expectStatus(read, 200, 'the plan read');
  return wikiPlanWaiting(read.body as WikiPlanState, runnerOnline);
}

