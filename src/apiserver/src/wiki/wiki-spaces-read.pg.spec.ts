/**
 * What the spaces list adds to each space (contract `space.list`), over real HTTP and against a real
 * PostgreSQL: `planWaiting`, the things of its plan that wait on the owner; `workspaceIds`, the live
 * workspaces bound to it, in their public spelling; and `docs`, its confirmed plan's documents, written of
 * how many. One owner with four spaces, each in a different state:
 *
 *   - bare: made and never set up — its first draft held for a maintenance workspace: 1, no plan;
 *   - quiet: no job and no plan, three workspaces bound and one of them deleted: 0;
 *   - full: a confirmed plan with one document written, a draft waiting, two proposals and a revision that
 *     failed — 4 — beside a pending changeset op that `pendingOps` counts and `planWaiting` does not;
 *   - offline: a draft made and not started, whose runner is offline, then online, then quiet past the
 *     heartbeat window, then gone from the workspace — as the runners list and the clients read it.
 *
 * Every row's `planWaiting` is also the count of what its own plan read says (`wikiPlanWaiting`, held to
 * the clients' vectors in wiki-plan-waiting.spec.ts), and its `docs` the directory's.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-spaces-read.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the two credential checks are stood in for, as in the other wiki specs.
 */
