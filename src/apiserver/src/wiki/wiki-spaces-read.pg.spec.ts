test('each space carries what of its plan waits on the owner, the workspaces bound to it and its documents written', { skip }, async () => {
  const h = await boot();
  const owner = await account(h, 'owner');
  const machine = await runner(h, owner.id);

  // bare: made and nothing set up — its first draft is held for a maintenance workspace.
  const bare = await space(h, owner, 'A bare space');

  // quiet: no job, no plan; three workspaces bound in turn, the last of them deleted since.
  const quiet = await space(h, owner, 'A quiet space');
  await onlyJob(h, owner.id, quiet, null);
  const [wsA, wsB, wsGone] = [await workspace(h, owner.id), await workspace(h, owner.id), await workspace(h, owner.id)];
  for (const ws of [wsA, wsB, wsGone]) await bind(h, owner, quiet, ws);
  await h.sql.query(`UPDATE "workspace" SET "deleted_at" = now() WHERE "id" = $1`, [wsGone]);

  // full: v1 confirmed with one of its three documents written, two proposals, v2 drafted, a revision failed.
  const full = await space(h, owner, 'A full space');
  const wsFull = await workspace(h, owner.id, machine.id);
  await bind(h, owner, full, wsFull);
  const maintainer = await maintain(h, owner, full, wsFull, machine);
  const v1 = await draft(h, maintainer, full, null);
  expectStatus(await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${full}/plan/versions/${v1}/confirm`), 200, 'the owner confirms v1');
  expectStatus(await call(h, maintainer, 'POST', `/runner/wiki/spaces/${full}/docs/session-runtime`, {
    planVersion: v1,
    repoSha: 'c'.repeat(40),
    model: 'qwen3.8-27b-fp8',
    sections: [{ key: 's1', materialSha256: 'd'.repeat(64), markdown: 'Orbit 的会话跑在 runner 上。turn 先落库再投递。', footnotes: [] }],
  }), 200, 'one document is written');
  for (const slug of ['wiki-plan', 'wiki-docs']) {
    expectStatus(await call(h, maintainer, 'POST', `/runner/wiki/spaces/${full}/plan/proposals`, {
      reason: `The plan has no document for ${slug}.`,
      change: { doc: docInput(slug, slug) },
      facts: [{ kind: 'session', id: maintainer.session }],
    }), 200, `a proposal for ${slug}`);
  }
  const v2 = await draft(h, maintainer, full, v1);
  assert.equal(v2, v1 + 1);
  await onlyJob(h, owner.id, full, { kind: 'revise', state: 'ended', outcome: 'failed', startedAt: true });
  // A changeset op waiting in Review, beside the plan: the sidebar's number, which the plan's never joins.
  // Manual, so that the agent's add waits for the owner whatever the other modes would make of it.
  expectStatus(await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${full}`, { reviewMode: 'manual' }), 200, 'the owner sets Manual');
  const ordinary = await session(h, owner.id, wsFull, machine.id);
  const tool = await toolCall(h, ordinary, 'a pg spec that skips itself proves nothing');
  const proposed = await call(h, { runner: maintainer.runner, session: ordinary }, 'POST', '/runner/wiki/changesets', {
    rationale: 'one proposal',
    ops: [{
      op: 'add',
      entry: {
        kind: 'pitfall',
        title: 'A pg spec that skips itself proves nothing',
        summary: 'A pg spec skips itself when its URL is unset.',
        fields: {
          trigger: { paths: ['src/apiserver/src/wiki/*.pg.spec.ts'], commands: ['node --test build/x.pg.spec.js'] },
          symptom: 'node exits 0 and no assertion ran.',
          cause: 'A pg spec skips itself when the URL is unset.',
          fix: 'Run it through scripts/run-pg-spec.sh, which treats a skip as red.',
        },
      },
      sources: [{ kind: 'tool_call', ref: tool, quote: 'skips itself' }],
    }],
  });
  expectStatus(proposed, 200, 'an agent proposes an entry');

  // offline: maintenance in a workspace on a second runner, and its draft made but not started.
  const offline = await space(h, owner, 'An offline space');
  const elsewhere = await runner(h, owner.id);
  const wsOff = await workspace(h, owner.id, elsewhere.id);
  await bind(h, owner, offline, wsOff);
  await maintain(h, owner, offline, wsOff, elsewhere);
  await onlyJob(h, owner.id, offline, { kind: 'draft', state: 'made' });

  // Another owner's space is in nobody's list but theirs.
  const stranger = await account(h, 'stranger');
  const theirs = await space(h, stranger, 'Not yours');

  const listed = await rows(h, owner);
  assert.deepEqual([...listed.keys()].sort(), [bare, quiet, full, offline].sort(), 'the owner lists their four spaces, and only those');

  const bareRow = listed.get(bare)!;
  assert.deepEqual([bareRow.planWaiting, bareRow.docs, bareRow.workspaceIds, bareRow.pendingOps], [1, null, [], 0], 'bare: the draft held, no plan, nothing bound');

  const quietRow = listed.get(quiet)!;
  assert.deepEqual([quietRow.planWaiting, quietRow.docs, quietRow.pendingOps], [0, null, 0], 'quiet: nothing waits, no plan');
  assert.deepEqual(quietRow.workspaceIds, [b62(wsA), b62(wsB)], 'the live workspaces, in the order they were bound, in their public spelling');
  assert.deepEqual(quietRow.workspacePublicIds, quietRow.workspaceIds, 'the codec\'s twin says the same');

  const fullRow = listed.get(full)!;
  assert.equal(fullRow.planWaiting, 4, 'full: the draft to confirm, two proposals and the revision that failed');
  assert.equal(fullRow.pendingOps, 1, 'the changeset op is the sidebar\'s, and the plan\'s proposals are not');
  assert.deepEqual(fullRow.docs, { written: 1, total: 3 }, 'one of the confirmed plan\'s three documents written');
  assert.deepEqual(fullRow.workspaceIds, [b62(wsFull)]);
  const directory = await call(h, { bearer: owner.bearer }, 'GET', `/wiki/spaces/${full}/docs`);
  expectStatus(directory, 200, 'the directory');
  assert.deepEqual(fullRow.docs, directory.body.docs, 'the list counts the documents as the directory does');
  assert.equal(directory.body.plan.version, v1, 'counted from the confirmed version, not the draft');

  const offlineRow = listed.get(offline)!;
  assert.deepEqual([offlineRow.planWaiting, offlineRow.docs, offlineRow.workspaceIds], [1, null, [b62(wsOff)]], 'offline: made, not started, its runner offline: held');

  // Every row says what its own plan read says, counted by the clients' rule.
  for (const [spaceId, runnerOnline] of [[bare, null], [quiet, null], [full, false], [offline, false]] as const) {
    assert.equal(listed.get(spaceId)!.planWaiting, await fromPlanRead(h, owner, spaceId, runnerOnline), `the plan read of ${spaceId}`);
  }

  const strangers = await rows(h, stranger);
  assert.deepEqual([...strangers.keys()], [theirs]);
  assert.deepEqual([strangers.get(theirs)!.planWaiting, strangers.get(theirs)!.workspaceIds], [1, []]);
});

test('a draft made and not started waits on the owner only while its runner is known to be offline, by the runners list\'s own rule', { skip }, async () => {
  const h = await boot();
  const owner = await account(h, 'owner');
  const machine = await runner(h, owner.id);
  const spaceId = await space(h, owner, 'A space on one runner');
  const ws = await workspace(h, owner.id, machine.id);
  await bind(h, owner, spaceId, ws);
  await maintain(h, owner, spaceId, ws, machine);
  await onlyJob(h, owner.id, spaceId, { kind: 'draft', state: 'made' });
  const waiting = async () => (await rows(h, owner)).get(spaceId)!.planWaiting;

  assert.equal(await waiting(), 1, 'never heard from: offline');
  await heard(h, machine.id, 'ONLINE', 5);
  assert.equal(await waiting(), 0, 'heard from five seconds ago: online, and the draft only waits for its run');
  assert.equal(await fromPlanRead(h, owner, spaceId, true), 0);
  await heard(h, machine.id, 'ONLINE', 300);
  assert.equal(await waiting(), 1, 'quiet for five minutes, whatever its status says: offline');
  await heard(h, machine.id, 'OFFLINE', 5);
  assert.equal(await waiting(), 1, 'marked offline: offline');

  // Started: the run is under way on its runner, offline or not — nothing waits on the owner.
  await onlyJob(h, owner.id, spaceId, { kind: 'draft', state: 'made', startedAt: true });
  assert.equal(await waiting(), 0, 'a run under way');

  // A runner nobody can see: the workspace has none, or the space names a workspace since deleted — unknown, not offline.
  await onlyJob(h, owner.id, spaceId, { kind: 'draft', state: 'made' });
  await h.sql.query(`UPDATE "workspace" SET "runner_id" = NULL WHERE "id" = $1`, [ws]);
  assert.equal(await waiting(), 0, 'a workspace with no runner');
  assert.equal(await fromPlanRead(h, owner, spaceId, null), 0);
  await h.sql.query(`UPDATE "workspace" SET "runner_id" = $2, "deleted_at" = now() WHERE "id" = $1`, [ws, machine.id]);
  assert.equal(await waiting(), 0, 'a maintenance workspace deleted');
  assert.deepEqual((await rows(h, owner)).get(spaceId)!.workspaceIds, [], 'and it is no longer listed as bound');

  // The build of a confirmed version, held: the writing waits on the owner as a draft does.
  await onlyJob(h, owner.id, spaceId, { kind: 'build', state: 'held', version: 1 });
  assert.equal(await waiting(), 1, 'the writing held');
  // A build that failed is not counted, as the clients do not count it.
  await onlyJob(h, owner.id, spaceId, { kind: 'build', state: 'ended', outcome: 'failed', startedAt: true, version: 1 });
  assert.equal(await waiting(), 0, 'a build that failed');
});
