/** A space the owner makes through the door, in a mode, bound to a workspace when one is named. */
async function modeSpace(h: Harness, owner: Account, mode: Mode, workspaceId?: string): Promise<string> {
  const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: `An ${mode} import` });
  expectStatus(made, 201, 'the owner creates a space');
  const id = made.body.id as string;
  const switched = await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${id}`, { reviewMode: mode });
  expectStatus(switched, 200, `the owner puts the space in ${mode}`);
  if (workspaceId) {
    const bound = await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${id}/workspaces`, { workspaceId });
    expectStatus(bound, 200, 'the owner binds the workspace');
  }
  return id;
}

/** The owner, their machine, a workspace, a space in `mode` bound to it, and a session that imports. */
interface Importer {
  owner: Account;
  machine: Machine;
  workspaceId: string;
  spaceId: string;
  session: string;
  as: Caller;
  /** Who its proposals are recorded as. */
  by: Proposer;
}

/** Who an import's proposals are recorded as: the account, and the session that ran `orbit wiki import`. */
interface Proposer {
  ownerId: string;
  sessionId: string;
}

async function importer(h: Harness, name: string, mode: Mode, env?: Record<string, string>): Promise<Importer> {
  const owner = await account(h, name);
  const machine = await runner(h, owner.id);
  const workspaceId = await workspace(h, owner.id, env);
  const spaceId = await modeSpace(h, owner, mode, workspaceId);
  const importing = await session(h, owner.id, { workspaceId, runnerId: machine.id });
  return {
    owner, machine, workspaceId, spaceId, session: importing,
    as: { runner: machine.token, session: importing },
    by: { ownerId: owner.id, sessionId: importing },
  };
}

/** One file registered through the door, as the command registers it: the server reads the note, so it says so. */
