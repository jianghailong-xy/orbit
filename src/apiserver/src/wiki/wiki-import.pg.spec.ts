/** Any eight characters in a row of `secret` (all of it, when shorter) that `text` still holds. */
function survivingPiece(text: string, secret: string): string | undefined {
  const width = Math.min(8, secret.length);
  for (let start = 0; start + width <= secret.length; start += 1) {
    const piece = secret.slice(start, start + width);
    if (text.includes(piece)) return piece;
  }
  return undefined;
}

/** Every wiki row the owner has, each as its JSON text: what "stored" means. */
async function everythingStored(h: Harness, ownerId: string): Promise<string> {
  const tables = ['wiki_note', 'wiki_space', 'wiki_entry', 'wiki_entry_revision', 'wiki_source', 'wiki_changeset', 'wiki_changeset_op'];
  const parts: string[] = [];
  for (const table of tables) {
    const rows = await h.sql.query<{ row: string }>(`SELECT row_to_json(t)::text AS row FROM "${table}" t WHERE "owner_id" = $1`, [ownerId]);
    parts.push(...rows.rows.map((r) => r.row));
  }
  return parts.join('\n');
}

