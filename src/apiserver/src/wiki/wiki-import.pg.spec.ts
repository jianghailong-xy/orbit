/** A pitfall the space already holds, live: what a note can say is wrong. */
async function liveEntry(h: Harness, owner: Account, spaceId: string, title: string): Promise<string> {
  const made = await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${spaceId}/changesets`, {
    rationale: 'the owner writes it',
    ops: [{ op: 'add', entry: draft('pitfall', title) }],
  });
  expectStatus(made, 200, 'the owner adds an entry');
  return toUuid(made.body.ops[0].entryId as string);
}

