/** The push as a session starting now would be handed it: the wiki on, whatever this shell says. */
const WIKI_ON = { mode: 'on' as const, canaryOwners: new Set<string>(), problems: [] };

type Mode = 'manual' | 'tiered' | 'automatic';

interface Harness {
  base: string;
  sql: Client;
  prisma: PrismaClient;
  app: INestApplication;
  service: WikiService;
  /** bearer → the account it was issued to */
  bearers: Map<string, string>;
}

let harness: Promise<Harness> | undefined;

function boot(): Promise<Harness> {
  harness ??= (async () => {
    assertCoordinatorPgUrlIsIsolated(URL);
    const sql = new Client({ connectionString: URL, connectionTimeoutMillis: 5_000 });
    await sql.connect();
    await verifyCoordinatorPgIdentity(sql);
    const prisma = prismaClientFor(URL);
    const bearers = new Map<string, string>();
    const hub = { publishWikiChanged: () => undefined } as unknown as RealtimeService;
    const service = new WikiService(prisma as unknown as PrismaService, hub);

    @Module({
      controllers: [WikiController, RunnerWikiController],
      providers: [
        { provide: WikiService, useValue: service },
        { provide: WikiRetrieval, useValue: new WikiRetrieval(prisma as unknown as PrismaService) },
        { provide: PrismaService, useValue: prisma },
        RunnerAuthGuard,
        JwtAuthGuard,
        Reflector,
        {
          provide: JwtService,
          useValue: {
            verifyAsync: async (token: string) => {
              const sub = bearers.get(token);
              if (!sub) throw new Error('not a bearer this run issued');
              return { sub, email: `${sub}@wiki.invalid` };
            },
          },
        },
      ],
    })
    class WikiChallengeAnswerModule {}

    const app = await NestFactory.create(WikiChallengeAnswerModule, { logger: false, abortOnError: false });
    app.setGlobalPrefix('api');
    app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true, forbidNonWhitelisted: false }));
    app.useGlobalInterceptors(new PublicIdInterceptor());
    await app.listen(0, '127.0.0.1');
    return { base: await app.getUrl(), sql, prisma, app, service, bearers };
  })();
  return harness;
}

after(async () => {
  if (!harness) return;
  const { app, prisma, sql } = await harness;
  await app.close().catch(() => undefined);
  await prisma.$disconnect().catch(() => undefined);
  await sql.end().catch(() => undefined);
});

// ── requests ────────────────────────────────────────────────────────────────────────────────────

interface Answer {
  status: number;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  body: any;
}

interface Caller {
  bearer?: string;
  runner?: string;
  headers?: Record<string, string>;
}

async function call(h: Harness, who: Caller, method: string, route: string, body?: unknown): Promise<Answer> {
  const headers: Record<string, string> = { 'content-type': 'application/json', ...(who.headers ?? {}) };
  if (who.bearer) headers.authorization = `Bearer ${who.bearer}`;
  if (who.runner) headers['x-runner-token'] = who.runner;
  const response = await fetch(`${h.base}/api${route}`, {
    method,
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await response.text();
  let parsed: unknown = null;
  try {
    parsed = text ? JSON.parse(text) : null;
  } catch {
    parsed = { unparsed: text };
  }
  return { status: response.status, body: parsed };
}

function expectStatus(answer: Answer, status: number, why: string): void {
  assert.equal(answer.status, status, `${why}: answered ${answer.status} ${JSON.stringify(answer.body)}`);
}

interface Outcome {
  seq: number;
  status: 'pending' | 'applied' | 'conflict' | 'refused';
  opId?: string | null;
  entryId?: string | null;
  waitsFor?: string;
  reasons?: Array<{ code: string; message: string }>;
}

/** The first refusal in an answer, by its contract code. */
function refusalOf(answer: Answer): { code: string; message: string } {
  const ops = answer.body.ops as Array<{ status: string; reasons: Array<{ code: string; message: string }> }>;
  const refused = ops.find((op) => op.status === 'refused');
  assert.ok(refused, `expected a refusal, got ${JSON.stringify(answer.body)}`);
  return refused!.reasons[0];
}

// ── fixtures ────────────────────────────────────────────────────────────────────────────────────

interface Account {
  id: string;
  bearer: string;
}

async function account(h: Harness, name: string): Promise<Account> {
  const id = randomUUID();
  await h.sql.query(`INSERT INTO "user"("id","email","name","password_hash") VALUES ($1,$2,$3,'x')`, [
    id,
    `wiki-challenge-${id}@wiki.invalid`,
    name,
  ]);
  h.bearers.set(`bearer-${id}`, id);
  return { id, bearer: `bearer-${id}` };
}

async function runner(h: Harness, ownerId: string): Promise<string> {
  const id = randomUUID();
  const token = `runner-${id}`;
  await h.sql.query(`INSERT INTO "runner"("id","name","owner_id","token_hash") VALUES ($1,'spec',$2,$3)`, [
    id,
    ownerId,
    createHash('sha256').update(token).digest('hex'),
  ]);
  return token;
}

async function runnerId(h: Harness, token: string): Promise<string> {
  const { rows } = await h.sql.query<{ id: string }>(`SELECT "id" FROM "runner" WHERE "token_hash" = $1`, [
    createHash('sha256').update(token).digest('hex'),
  ]);
  return rows[0].id;
}

async function workspace(h: Harness, ownerId: string): Promise<string> {
  const id = randomUUID();
  await h.sql.query(`INSERT INTO "workspace"("id","name","owner_id") VALUES ($1,'spec',$2)`, [id, ownerId]);
  return id;
}

async function session(h: Harness, ownerId: string, workspaceId: string | null, machine: string | null): Promise<string> {
  const id = randomUUID();
  await h.sql.query(
    `INSERT INTO "session"("id","title","prompt","owner_id","creator_id","workspace_id","assigned_runner_id",
                            "dispatch_origin","updated_at")
     VALUES ($1,'a wiki session','p',$2,$2,$3,$4,'USER',now())`,
    [id, ownerId, workspaceId, machine ? await runnerId(h, machine) : null],
  );
  return id;
}

async function toolCall(h: Harness, sessionId: string, name: string, output: string): Promise<string> {
  const id = randomUUID();
  await h.sql.query(`INSERT INTO "tool_call"("id","session_id","name","output") VALUES ($1,$2,$3,$4)`, [
    id,
    sessionId,
    name,
    JSON.stringify(output),
  ]);
  return id;
}

/** A space the owner makes through the door and puts in a mode, bound to a workspace when one is named. */
async function modeSpace(h: Harness, owner: Account, mode: Mode, workspaceId?: string): Promise<string> {
  const made = await call(h, { bearer: owner.bearer }, 'POST', '/wiki/spaces', { title: `A ${mode} space` });
  expectStatus(made, 201, 'the owner creates a space');
  const id = made.body.id as string;
  const switched = await call(h, { bearer: owner.bearer }, 'PATCH', `/wiki/spaces/${id}`, { reviewMode: mode });
  expectStatus(switched, 200, `the owner puts the space in ${mode}`);
  if (workspaceId) {
    const bound = await call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${id}/workspaces`, { workspaceId });
    expectStatus(bound, 200, 'the owner binds the workspace');
  }
  return toUuid(id);
}

/**
 * A valid convention — always pushed, so the push rule can be witnessed — whose title differs per use.
 */
function convention(title: string): Record<string, unknown> {
  return {
    kind: 'convention' as WikiKind,
    title,
    summary: `What the space knows about ${title.toLowerCase()}.`,
    fields: { rule: 'A challenge waits for an answer, and an amend can give it.', scope: ['src/apiserver/src/wiki/**'] },
  };
}

/** The runner door's proposal, under the calling session's header. */
function propose(h: Harness, machine: string, sessionId: string, body: Record<string, unknown>): Promise<Answer> {
  return call(h, { runner: machine, headers: { 'x-orbit-session-id': sessionId } }, 'POST', '/runner/wiki/changesets', body);
}

/** The owner's own write, through the user door. */
function ownerPropose(h: Harness, owner: Account, spaceId: string, body: Record<string, unknown>): Promise<Answer> {
  return call(h, { bearer: owner.bearer }, 'POST', `/wiki/spaces/${uuidToBase62(spaceId)}/changesets`, body);
}

function decide(h: Harness, owner: Account, changesetId: string, decisions: unknown[]): Promise<Answer> {
  return call(h, { bearer: owner.bearer }, 'POST', `/wiki/changesets/${changesetId}/decide`, { decisions });
}

async function entryRow(h: Harness, id: string) {
  return h.prisma.wikiEntry.findFirstOrThrow({ where: { id: toUuid(id) } });
}

async function opRow(h: Harness, id: string) {
  return h.prisma.wikiChangesetOp.findFirstOrThrow({ where: { id: toUuid(id) } });
}

/** The entries the next session in this workspace is handed, by id. */
async function pushed(h: Harness, ownerId: string, workspaceId: string, sessionId: string): Promise<Set<string>> {
  const content = await appendWikiContext(h.prisma as unknown as Prisma.TransactionClient, {
    sessionId,
    turnId: randomUUID(),
    leaseGeneration: randomUUID(),
    ownerId,
    workspaceId,
    taskId: null,
    task: null,
    dispatchOrigin: 'USER',
    content: 'What should I know about this codebase?',
  }, WIKI_ON);
  return new Set([...String(content).matchAll(/\(orbit-wiki:([0-9A-Za-z]+)\)/gu)].map((match) => toUuid(match[1])));
}

/** What a challenge op looks like at rest, and whether it has been answered. */
interface ChallengeRow {
  decision: string;
  answeredBy: string | null;
  decidedAt: Date | null;
}

async function challengeRow(h: Harness, id: string): Promise<ChallengeRow> {
  const row = await opRow(h, id);
  return { decision: row.decision, answeredBy: row.answeredBy, decidedAt: row.decidedAt };
}

/** How many rows of each table this owner holds, for the "a refusal writes nothing" claim. */
async function census(h: Harness, ownerId: string): Promise<{ changesets: number; ops: number; revisions: number; entries: number }> {
  return {
    changesets: await h.prisma.wikiChangeset.count({ where: { ownerId } }),
    ops: await h.prisma.wikiChangesetOp.count({ where: { ownerId } }),
    revisions: await h.prisma.wikiEntryRevision.count({ where: { ownerId } }),
    entries: await h.prisma.wikiEntry.count({ where: { ownerId } }),
  };
}

/**
 * An entry an agent added and the owner accepted: live and confirmed, so the push rule can be read
 * on both sides of a challenge. Returns its entry id and the revision the amend is written against.
 */
async function liveEntry(
  h: Harness,
  owner: Account,
  machine: string,
  proposer: string,
  record: string,
  title: string,
): Promise<{ entryId: string; revision: number }> {
  const added = await propose(h, machine, proposer, {
    rationale: `the entry ${title} is about`,
    ops: [{ op: 'add', entry: convention(title), sources: [{ kind: 'tool_call', ref: record, quote: 'a convention' }] }],
  });
  expectStatus(added, 200, 'the entry is proposed');
  const outcome = added.body.ops[0] as Outcome;
  const accepted = await decide(h, owner, added.body.changesetId as string, [{ opId: outcome.opId, action: 'accept' }]);
  expectStatus(accepted, 200, 'the owner accepts the entry');
  const entry = await entryRow(h, outcome.entryId!);
  assert.equal(entry.status, 'active');
  return { entryId: entry.id, revision: entry.currentRevision };
}

/** One challenge op, filed by the session, applied at once as every challenge is. */
async function challenge(h: Harness, machine: string, proposer: string, entryId: string, reason: string): Promise<string> {
  const filed = await propose(h, machine, proposer, {
    rationale: 'the entry says something that is no longer true',
    ops: [{ op: 'challenge', entryId, reason }],
  });
  expectStatus(filed, 200, 'a challenge is recorded');
  const outcome = filed.body.ops[0] as Outcome;
  assert.equal(outcome.status, 'applied', 'a challenge applies at once');
  return outcome.opId!;
}

// ── 1. the answer paths ─────────────────────────────────────────────────────────────────────────

test('challenge answer · an amend that names a challenge closes it when the amend takes effect', { skip, concurrency: 1, timeout: 300_000 }, async (t) => {
  const h = await boot();

  await t.test('manual · the owner accepts the amend, and the challenge closes as the agent\'s answer', async () => {
    const owner = await account(h, 'manual answer');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    await modeSpace(h, owner, 'manual', ws);
    const proposer = await session(h, owner.id, ws, machine);
    const record = await toolCall(h, proposer, 'Bash', 'a convention the run observed');
    const citation = [{ kind: 'tool_call', ref: record, quote: 'a convention' }];
    const { entryId, revision } = await liveEntry(h, owner, machine, proposer, record, 'A challenge waits for an answer');
    const reader = await session(h, owner.id, ws, machine);

    // The entry is pushed until a challenge takes it out.
    assert.equal((await pushed(h, owner.id, ws, reader)).has(entryId), true, 'the entry is pushed before the challenge');
    const challengeOp = await challenge(h, machine, proposer, entryId, 'the rule was replaced by a different one');
    const challenged = await entryRow(h, entryId);
    assert.equal(challenged.challenged, true, 'a challenge takes the entry out of the push at once');
    assert.equal((await pushed(h, owner.id, ws, reader)).has(entryId), false, 'and it is pushed to nobody meanwhile');

    // The amend names the challenge; in Manual it waits for the owner, and nothing closes yet.
    const amended = await propose(h, machine, proposer, {
      rationale: 'the rule the entry states was replaced',
      ops: [{ op: 'amend', entryId, baseRevision: revision, changes: { summary: 'The rule as it stands now.' }, sources: citation, answersChallenge: challengeOp }],
    });
    expectStatus(amended, 200, 'the amend is recorded');
    const amendOp = (amended.body.ops[0] as Outcome).opId!;
    assert.equal((amended.body.ops[0] as Outcome).status, 'pending', 'in Manual the amend waits for the owner');
    assert.equal((await opRow(h, amendOp)).answersChallenge, toUuid(challengeOp), 'the op row keeps the challenge it answers');
    assert.equal((await challengeRow(h, challengeOp)).decision, 'pending', 'an amend that has not applied closes nothing');
    assert.equal((await entryRow(h, entryId)).challenged, true, 'the entry stays out of the push until it applies');
    assert.equal((await entryRow(h, entryId)).currentRevision, revision, 'and its content has not changed');

    const accepted = await decide(h, owner, amended.body.changesetId as string, [{ opId: amendOp, action: 'accept' }]);
    expectStatus(accepted, 200, 'the owner accepts the amend');
    const after = await entryRow(h, entryId);
    assert.equal(after.currentRevision, revision + 1, 'the amend took effect');
    assert.equal(after.challenged, false, 'the challenge answered, the flag is recomputed away');
    const closed = await challengeRow(h, challengeOp);
    assert.equal(closed.decision, 'edited', 'the challenge records the amendment');
    assert.equal(closed.answeredBy, 'agent', 'answered by an agent\'s amend');
    assert.ok(closed.decidedAt, 'and decided when it applied');
    const challengeChangeset = await h.prisma.wikiChangeset.findFirstOrThrow({
      where: { id: (await opRow(h, challengeOp)).changesetId },
    });
    assert.equal(challengeChangeset.status, 'settled', 'the challenge\'s own changeset settles with its answer');
    assert.equal((await pushed(h, owner.id, ws, reader)).has(entryId), true, 'the entry is back in the push');
  });

  await t.test('tiered · the mode applies the amend as it records it, and closes the challenge then', async () => {
    const owner = await account(h, 'tiered answer');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    await modeSpace(h, owner, 'tiered', ws);
    const proposer = await session(h, owner.id, ws, machine);
    const record = await toolCall(h, proposer, 'Bash', 'a convention the run observed');
    const citation = [{ kind: 'tool_call', ref: record, quote: 'a convention' }];

    // Tiered applies the agent's add at once, as unreviewed: the entry is live.
    const added = await propose(h, machine, proposer, {
      rationale: 'the entry the challenge is about',
      ops: [{ op: 'add', entry: convention('A tiered entry that is challenged'), sources: citation }],
    });
    expectStatus(added, 200, 'the add is recorded');
    const entryId = (added.body.ops[0] as Outcome).entryId!;
    const entry = await entryRow(h, entryId);
    assert.equal(entry.status, 'active', 'Tiered applies the add at once');
    const challengeOp = await challenge(h, machine, proposer, entryId, 'the convention was replaced');
    assert.equal((await entryRow(h, entryId)).challenged, true, 'the challenge flags the entry');

    const amended = await propose(h, machine, proposer, {
      rationale: 'the convention as it stands now',
      ops: [{
        op: 'amend',
        entryId,
        baseRevision: entry.currentRevision,
        changes: { summary: 'The convention as it stands now.' },
        sources: citation,
        answersChallenge: challengeOp,
      }],
    });
    expectStatus(amended, 200, 'the amend is recorded');
    const outcome = amended.body.ops[0] as Outcome;
    assert.equal(outcome.status, 'applied', 'Tiered applies the amend as it records it');
    assert.equal((await opRow(h, outcome.opId!)).appliedByMode, 'tiered');
    const closed = await challengeRow(h, challengeOp);
    assert.equal(closed.decision, 'edited', 'the applied amend closed the challenge');
    assert.equal(closed.answeredBy, 'agent');
    assert.equal((await entryRow(h, entryId)).challenged, false, 'and the flag is gone');
  });

  await t.test('automatic · the verdict that applies the amend closes it; one that does not leaves it open', async () => {
    const owner = await account(h, 'automatic answer');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    const space = await modeSpace(h, owner, 'automatic', ws);
    const proposer = await session(h, owner.id, ws, machine);
    const record = await toolCall(h, proposer, 'Bash', 'a convention the run observed');
    const citation = [{ kind: 'tool_call', ref: record, quote: 'a convention' }];
    const report = (verdicts: unknown[]) =>
      h.service.recordVerifications(wikiVerifyPrincipal(owner.id, proposer), space, verdicts);
    const verdict = (opId: string, value: string) => ({
      opId,
      verdict: value,
      reason: `The sources ${value === 'supported' ? 'bear it out' : 'do not say this'}.`,
      model: 'qwen3.8-27b-fp8',
    });

    const added = await propose(h, machine, proposer, {
      rationale: 'the entry the challenge is about',
      ops: [{ op: 'add', entry: convention('An automatic entry that is challenged'), sources: citation }],
    });
    expectStatus(added, 200, 'the add is recorded');
    const addOp = added.body.ops[0] as Outcome;
    assert.equal(addOp.status, 'pending', 'Automatic holds the add for its verdict');
    const supported = await report([verdict(addOp.opId!, 'supported')]);
    assert.equal((supported.outcomes[0] as { status: string }).status, 'applied');
    const entry = await entryRow(h, addOp.entryId!);
    assert.equal(entry.status, 'active');
    assert.equal(entry.trust, 'auto', 'the verdict made it live as Auto');
    const reader = await session(h, owner.id, ws, machine);
    assert.equal((await pushed(h, owner.id, ws, reader)).has(entry.id), true, 'and pushed');

    const challengeOp = await challenge(h, machine, proposer, entry.id, 'the convention was replaced');
    assert.equal((await pushed(h, owner.id, ws, reader)).has(entry.id), false, 'the challenge takes it out of the push');

    // A verdict that does not apply the amend leaves the challenge exactly as it was.
    const refusedAmendment = await propose(h, machine, proposer, {
      rationale: 'a first attempt at the amendment',
      ops: [{
        op: 'amend',
        entryId: entry.id,
        baseRevision: entry.currentRevision,
        changes: { summary: 'The convention as it stands now.' },
        sources: citation,
        answersChallenge: challengeOp,
      }],
    });
    expectStatus(refusedAmendment, 200, 'the amend is recorded');
    const refusedOp = refusedAmendment.body.ops[0] as Outcome;
    assert.equal(refusedOp.status, 'pending', 'Automatic holds it for its verdict');
    assert.equal(refusedOp.waitsFor, 'verification');
    const unsupported = await report([verdict(refusedOp.opId!, 'unsupported')]);
    assert.equal((unsupported.outcomes[0] as { status: string }).status, 'rejected');
    assert.equal((await challengeRow(h, challengeOp)).decision, 'pending', 'a rejected amend closes no challenge');
    assert.equal((await entryRow(h, entry.id)).challenged, true, 'the entry stays out of the push');

    // A verdict that applies it closes the challenge.
    const amendment = await propose(h, machine, proposer, {
      rationale: 'the convention as it stands now',
      ops: [{
        op: 'amend',
        entryId: entry.id,
        baseRevision: entry.currentRevision,
        changes: { summary: 'The convention as it stands now.' },
        sources: citation,
        answersChallenge: challengeOp,
      }],
    });
    expectStatus(amendment, 200, 'the amend is recorded');
    const amendOp = amendment.body.ops[0] as Outcome;
    const applying = await report([verdict(amendOp.opId!, 'supported')]);
    assert.equal((applying.outcomes[0] as { status: string }).status, 'applied');
    const closed = await challengeRow(h, challengeOp);
    assert.equal(closed.decision, 'edited', 'the verdict that applied the amend closed the challenge');
    assert.equal(closed.answeredBy, 'agent');
    assert.equal((await entryRow(h, entry.id)).challenged, false);
    assert.equal((await pushed(h, owner.id, ws, reader)).has(entry.id), true, 'the entry is back in the push');
  });

  await t.test('the owner\'s own amend answers it as the owner', async () => {
    const owner = await account(h, 'owner answer');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    const space = await modeSpace(h, owner, 'manual', ws);
    const proposer = await session(h, owner.id, ws, machine);
    const record = await toolCall(h, proposer, 'Bash', 'a convention the run observed');
    const { entryId, revision } = await liveEntry(h, owner, machine, proposer, record, 'An entry the owner answers for');
    const challengeOp = await challenge(h, machine, proposer, entryId, 'the convention was replaced');

    const amended = await ownerPropose(h, owner, space, {
      rationale: 'the owner rewrites the convention themselves',
      ops: [{
        op: 'amend',
        entryId,
        baseRevision: revision,
        changes: { summary: 'The convention as the owner states it.' },
        answersChallenge: challengeOp,
      }],
    });
    expectStatus(amended, 200, 'the owner writes the amend');
    const outcome = amended.body.ops[0] as Outcome;
    assert.equal(outcome.status, 'applied', 'the owner\'s own write applies at once');
    const closed = await challengeRow(h, challengeOp);
    assert.equal(closed.decision, 'edited');
    assert.equal(closed.answeredBy, 'owner', 'the owner answered it themselves');
    assert.equal((await entryRow(h, entryId)).challenged, false);
  });
});

// ── 2. what an amend does NOT answer ────────────────────────────────────────────────────────────

test('challenge answer · only an amend that names a pending challenge of its own entry closes one', { skip, concurrency: 1, timeout: 300_000 }, async (t) => {
  const h = await boot();

  await t.test('an amend that names no challenge closes none', async () => {
    const owner = await account(h, 'no field');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    await modeSpace(h, owner, 'manual', ws);
    const proposer = await session(h, owner.id, ws, machine);
    const record = await toolCall(h, proposer, 'Bash', 'a convention the run observed');
    const { entryId, revision } = await liveEntry(h, owner, machine, proposer, record, 'An entry with an unnamed challenge');
    const challengeOp = await challenge(h, machine, proposer, entryId, 'the convention was replaced');

    const amended = await propose(h, machine, proposer, {
      rationale: 'an unrelated typo fix',
      ops: [{ op: 'amend', entryId, baseRevision: revision, changes: { summary: 'Fixed a typo in the summary.' }, sources: [{ kind: 'tool_call', ref: record, quote: 'a convention' }] }],
    });
    expectStatus(amended, 200, 'the amend is recorded');
    const accepted = await decide(h, owner, amended.body.changesetId as string, [{ opId: (amended.body.ops[0] as Outcome).opId, action: 'accept' }]);
    expectStatus(accepted, 200, 'and accepted');
    assert.equal((await entryRow(h, entryId)).currentRevision, revision + 1, 'the amend took effect');
    assert.equal((await challengeRow(h, challengeOp)).decision, 'pending', 'the unnamed challenge is untouched');
    assert.equal((await entryRow(h, entryId)).challenged, true, 'and the entry stays out of the push');
  });

  await t.test('a challenge answered in Review keeps the historical NULL answered_by', async () => {
    const owner = await account(h, 'review answer');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    await modeSpace(h, owner, 'manual', ws);
    const proposer = await session(h, owner.id, ws, machine);
    const record = await toolCall(h, proposer, 'Bash', 'a convention the run observed');
    const { entryId } = await liveEntry(h, owner, machine, proposer, record, 'An entry answered in Review');
    const challengeOp = await challenge(h, machine, proposer, entryId, 'the convention was replaced');

    const answered = await decide(h, owner, (await opRow(h, challengeOp)).changesetId, [{ opId: challengeOp, action: 'reconfirm' }]);
    expectStatus(answered, 200, 'the owner re-confirms it in Review');
    const row = await challengeRow(h, challengeOp);
    assert.equal(row.decision, 'accepted');
    assert.equal(row.answeredBy, null, 'Review\'s answer predates answered_by, and reads as the owner\'s');
    assert.equal((await entryRow(h, entryId)).challenged, false);
  });

  await t.test('an amend naming a challenge it cannot answer is refused WIKI_SCHEMA and writes nothing', async () => {
    const owner = await account(h, 'refusals');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    await modeSpace(h, owner, 'manual', ws);
    const proposer = await session(h, owner.id, ws, machine);
    const record = await toolCall(h, proposer, 'Bash', 'a convention the run observed');
    const first = await liveEntry(h, owner, machine, proposer, record, 'The entry whose challenge is named');
    const second = await liveEntry(h, owner, machine, proposer, record, 'The entry the amend changes');
    const challengeOp = await challenge(h, machine, proposer, first.entryId, 'the first entry is wrong');
    // A second entry's own challenge, so "already decided" is read on this entry and not only across entries.
    const decidedOp = await challenge(h, machine, proposer, second.entryId, 'the second entry is wrong');
    expectStatus(await decide(h, owner, (await opRow(h, decidedOp)).changesetId, [{ opId: decidedOp, action: 'reject', reason: 'not_true' }]), 200, 'the second challenge is answered');
    const addOpOfSecond = await h.prisma.wikiChangesetOp.findFirstOrThrow({
      where: { resultEntryId: second.entryId, ownerId: owner.id, op: 'add' },
      select: { id: true },
    });

    const amendOp = (answersChallenge: unknown, baseRevision = second.revision) => ({
      rationale: 'an amend that names something it cannot answer',
      ops: [{
        op: 'amend',
        entryId: second.entryId,
        baseRevision,
        changes: { summary: 'A summary the refusal must not write.' },
        sources: [{ kind: 'tool_call', ref: record, quote: 'a convention' }],
        answersChallenge,
      }],
    });
    const cases: Array<[string, Record<string, unknown>]> = [
      ['another entry\'s pending challenge', amendOp(challengeOp)],
      ['a challenge already decided', amendOp(decidedOp)],
      ['an op that is not a challenge', amendOp(uuidToBase62(addOpOfSecond.id))],
      ['an id that names no op', amendOp(uuidToBase62(randomUUID()))],
      ['a number', amendOp(42)],
      ['a string that decodes to no id', amendOp('not-an-id')],
    ];
    for (const [why, body] of cases) {
      const before = await census(h, owner.id);
      const entryBefore = await entryRow(h, second.entryId);
      const answer = await propose(h, machine, proposer, body);
      expectStatus(answer, 400, `an amend naming ${why} is refused`);
      assert.equal(refusalOf(answer).code, 'WIKI_SCHEMA', why);
      assert.equal(answer.body.changesetId, null, `nothing is recorded for ${why}`);
      assert.deepEqual(await census(h, owner.id), before, `no row is written for ${why}`);
      const entryAfter = await entryRow(h, second.entryId);
      assert.equal(entryAfter.currentRevision, entryBefore.currentRevision, `no revision for ${why}`);
      assert.equal(entryAfter.challenged, entryBefore.challenged, `no flag moves for ${why}`);
    }
    // The pending challenge the first amend named is still pending: a refused request answered nothing.
    assert.equal((await challengeRow(h, challengeOp)).decision, 'pending');
    assert.equal((await challengeRow(h, challengeOp)).answeredBy, null);
  });

  await t.test('a challenge already decided when the amend applies is not overwritten, and nothing is refused', async () => {
    const owner = await account(h, 'decided first');
    const machine = await runner(h, owner.id);
    const ws = await workspace(h, owner.id);
    await modeSpace(h, owner, 'manual', ws);
    const proposer = await session(h, owner.id, ws, machine);
    const record = await toolCall(h, proposer, 'Bash', 'a convention the run observed');
    const { entryId, revision } = await liveEntry(h, owner, machine, proposer, record, 'An entry whose challenge is answered first');
    const challengeOp = await challenge(h, machine, proposer, entryId, 'the convention was replaced');

    const amended = await propose(h, machine, proposer, {
      rationale: 'the amend that names the challenge',
      ops: [{
        op: 'amend',
        entryId,
        baseRevision: revision,
        changes: { summary: 'The convention as it stands now.' },
        sources: [{ kind: 'tool_call', ref: record, quote: 'a convention' }],
        answersChallenge: challengeOp,
      }],
    });
    expectStatus(amended, 200, 'the amend is recorded');
    const amendOp = (amended.body.ops[0] as Outcome).opId!;

    // The owner answers the challenge first: re-confirm records the challenge accepted.
    const answered = await decide(h, owner, (await opRow(h, challengeOp)).changesetId, [{ opId: challengeOp, action: 'reconfirm' }]);
    expectStatus(answered, 200, 'the owner answers the challenge first');
    assert.equal((await challengeRow(h, challengeOp)).decision, 'accepted');

    const accepted = await decide(h, owner, amended.body.changesetId as string, [{ opId: amendOp, action: 'accept' }]);
    expectStatus(accepted, 200, 'the amend still applies');
    const row = await challengeRow(h, challengeOp);
    assert.equal(row.decision, 'accepted', 'the decision is not overwritten');
    assert.equal(row.answeredBy, null, 'and no answer source is written over it');
    assert.equal((await entryRow(h, entryId)).currentRevision, revision + 1, 'the amend took effect');
    assert.equal((await entryRow(h, entryId)).challenged, false, 'and the flag follows the answered challenge');
  });
});
