/**
 * An amend answers the challenge it names (contract `reviewModes.challenge`; design
 * `docs/wiki-challenge-resolution-design.md` §3.3 hard rule 4 and §9 P1), over real HTTP and against a
 * real PostgreSQL.
 *
 * A challenge takes effect at once — the entry leaves the push — but its answer used to be the
 * owner's alone, so an agent's amend could apply through the ordinary review path and leave the
 * challenge pending and the entry challenged. What is witnessed here, each read back from the
 * database and from the push a session would be handed:
 *
 *   1. an amend that names a pending challenge of its own entry closes it when the amend TAKES
 *      EFFECT — through the owner's decision in Manual, Tiered applying it as it records, and
 *      Automatic applying it on a verdict — recording `edited` and who answered it, and clearing
 *      `challenged` so the entry returns to the push;
 *   2. an amend that names none closes none, however many revisions it writes;
 *   3. a challenge that is already decided, a challenge of another entry, an id that names no op,
 *      an op that is not a challenge, or a malformed value is refused WIKI_SCHEMA and the request
 *      writes no row at all;
 *   4. a verdict that does not apply the amend leaves the challenge exactly as it was;
 *   5. the answer's source: `agent` for an agent's amend, `owner` for the owner's own — and a
 *      challenge answered in Review keeps the historical NULL, which reads as the owner's.
 *
 *     bash scripts/run-pg-spec.sh src/apiserver/src/wiki/wiki-challenge-answer.pg.spec.ts
 *
 * Not destructive: every id is generated by the run, and every fixture belongs to an account the run
 * created. Only the two credential checks are stood in for, as in `wiki-verify.pg.spec.ts`.
 */
