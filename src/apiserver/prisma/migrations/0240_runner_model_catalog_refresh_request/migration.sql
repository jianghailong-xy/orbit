-- 0240 —— 让「重新读一遍模型列表」成为用户可以要求的事。
--
-- 模型下拉列出的是 runner 自己那台机器上的 CLI 说有什么（`codex debug models`、`claude -p
-- "/model"`），由 runner 定期抓一次存进 `runner.model_catalog`。定期的意思是：CLI 升级、或者
-- 服务端放出一个新模型之后，Orbit 要等到下一次抓取才看得见它。周期本身已经从一天收到四小时，
-- 但「等」和「现在就去看」是两件事——本迁移加的是后者。
--
-- 为什么是一列时间戳，不是一张表
-- ==============================
-- 这个请求没有结果要回报。sign-in / install 那两条中继要存 status + message，是因为它们的产出
-- 是一段只有那台机器知道的过程；而这里，刷新完的目录本身就是回执,它照常走下一次心跳的
-- `model_catalog` 回来。所以这一格只需要回答一个问题:「有没有人要求过、什么时候要求的」,
-- 心跳把它交出去的同时清空。NULL = 没有待办。
--
-- 时间戳而不是 boolean:它同时是这次请求的凭据和它的年龄。一台离线的机器上线后仍然会执行这次
-- 请求(用户要的就是这个),而一条留在那里的记录读起来仍然是「谁在什么时候按的」。
--
-- 明确没有做的事
-- ==============
-- 不建表、不加索引、不加触发器、不加枚举、没有 DML。没有索引是刻意的:唯一的读者是心跳,它按
-- 主键取自己那一行。没有回填:NULL 正是「没人要求过」,每台已有的机器现在就是这个状态。
ALTER TABLE "runner" ADD COLUMN "model_catalog_refresh_at" TIMESTAMP(3);
