-- 1700 — a Drive chat's changes, one card a turn with Undo (project "Drive chat: manage files by talking to an agent",
-- owner decision Q2 A of 2026-11-26, board docs/mocks/drive-chat/01-board.html frames ③ ④; drive/drive-chat-changes.ts).
--
-- WHAT IT ADDS
-- ============
--   1. `drive_chat_change_group` — the drive changes one turn of a Drive chat made (`session_id`, `turn_id`), which one
--      Undo reverses. `status`: DONE (made), PENDING (held past the turn's 200th change: nothing made until the owner
--      presses Apply), APPLYING and UNDOING while those run, UNDONE. `held` says it began PENDING. At most one group a
--      turn collects changes as they are made (DONE and not held), and at most one waits for Apply.
--   2. `drive_chat_change` — one change of a group, in the order made (`ord`): its kind (NEW_FOLDER, NEW_FILE, MOVE,
--      RENAME, TRASH, EDIT), the entry, where it was before and after (parent id, name), the entry's `seq` after it (what
--      Undo reads "changed since" from), the Trash group a TRASH went to, and for an EDIT the version it made current and
--      the one it replaced. `state`: DONE, UNDONE, or SKIPPED with the reason Undo gave.
--   3. `drive_chat_held_change` — one write held in a PENDING group, as the agent asked for it (`op`), with what the
--      card shows (kind, name, from and to paths). `state`: PENDING, APPLIED, or SKIPPED with the reason Apply gave.
--   4. `drive_chat_question` — a move or rename a Drive chat asked for onto a live file, refused (a Drive chat never
--      replaces a file), kept as the card that asks the owner Keep both or Replace: both files as they were when asked,
--      where it was going, and the answer and its outcome.
--
--   No foreign key to drive_entry, drive_version, drive_trash_group or conversation_turn: entries are deleted for good
--   and turns pruned on their own clocks; each is read by id and checked. The owner and the session take theirs with
--   them.
--
-- LOCKS
-- =====
-- The foreign keys take SHARE ROW EXCLUSIVE on "user" and "session" for a moment, so the locks are taken in short tries,
-- as 1668 takes its own: 2 s each, 1 s apart, at most 45, then a clear error. The tables are new and empty: nothing is
-- scanned. Every statement is safe to run twice.
--
-- BACKWARD COMPATIBLE
-- ===================
-- New tables nothing older reads or writes.
--
-- 1700: the highest number in use on origin/main, every origin/project/* and origin/orbit/* branch was 1681, and a local
-- branch held 1691 (2026-11-27); 1700 leaves room for the ones in flight.

DO $$
DECLARE
  tries integer := 0;
BEGIN
  PERFORM set_config('lock_timeout', '2s', true);
  LOOP
    BEGIN
      CREATE TABLE IF NOT EXISTS "drive_chat_change_group" (
        "id"         UUID NOT NULL,
        "owner_id"   UUID NOT NULL,
        "session_id" UUID NOT NULL,
        "turn_id"    UUID NOT NULL,
        "status"     TEXT NOT NULL,
        "held"       BOOLEAN NOT NULL DEFAULT false,
        "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
        "updated_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
        "applied_at" TIMESTAMPTZ(3),
        "undone_at"  TIMESTAMPTZ(3),
        CONSTRAINT "drive_chat_change_group_pkey" PRIMARY KEY ("id"),
        CONSTRAINT "drive_chat_change_group_status_chk"
          CHECK ("status" IN ('DONE', 'PENDING', 'APPLYING', 'UNDOING', 'UNDONE')),
        CONSTRAINT "drive_chat_change_group_owner_id_fkey" FOREIGN KEY ("owner_id")
          REFERENCES "user"("id") ON DELETE CASCADE ON UPDATE CASCADE,
        CONSTRAINT "drive_chat_change_group_session_id_fkey" FOREIGN KEY ("session_id")
          REFERENCES "session"("id") ON DELETE CASCADE ON UPDATE CASCADE
      );
      CREATE UNIQUE INDEX IF NOT EXISTS "drive_chat_change_group_collecting_key"
        ON "drive_chat_change_group"("session_id", "turn_id") WHERE "status" = 'DONE' AND NOT "held";
      CREATE UNIQUE INDEX IF NOT EXISTS "drive_chat_change_group_waiting_key"
        ON "drive_chat_change_group"("session_id", "turn_id") WHERE "status" IN ('PENDING', 'APPLYING');
      CREATE INDEX IF NOT EXISTS "drive_chat_change_group_session_idx"
        ON "drive_chat_change_group"("session_id", "created_at");

      CREATE TABLE IF NOT EXISTS "drive_chat_change" (
        "id"                  UUID NOT NULL,
        "ord"                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
        "group_id"            UUID NOT NULL,
        "owner_id"            UUID NOT NULL,
        "kind"                TEXT NOT NULL,
        "entry_id"            UUID NOT NULL,
        "entry_kind"          TEXT NOT NULL,
        "before_parent_id"    UUID,
        "before_name"         TEXT,
        "after_parent_id"     UUID,
        "after_name"          TEXT NOT NULL,
        "after_seq"           BIGINT NOT NULL,
        "trash_group_id"      UUID,
        "version_id"          UUID,
        "replaced_version_id" UUID,
        "state"               TEXT NOT NULL DEFAULT 'DONE',
        "reason"              TEXT,
        "created_at"          TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
        "updated_at"          TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT "drive_chat_change_pkey" PRIMARY KEY ("id"),
        CONSTRAINT "drive_chat_change_kind_chk"
          CHECK ("kind" IN ('NEW_FOLDER', 'NEW_FILE', 'MOVE', 'RENAME', 'TRASH', 'EDIT')),
        CONSTRAINT "drive_chat_change_state_chk" CHECK ("state" IN ('DONE', 'UNDONE', 'SKIPPED')),
        CONSTRAINT "drive_chat_change_group_id_fkey" FOREIGN KEY ("group_id")
          REFERENCES "drive_chat_change_group"("id") ON DELETE CASCADE ON UPDATE CASCADE,
        CONSTRAINT "drive_chat_change_owner_id_fkey" FOREIGN KEY ("owner_id")
          REFERENCES "user"("id") ON DELETE CASCADE ON UPDATE CASCADE
      );
      CREATE INDEX IF NOT EXISTS "drive_chat_change_group_ord_idx" ON "drive_chat_change"("group_id", "ord");
      CREATE INDEX IF NOT EXISTS "drive_chat_change_group_entry_idx" ON "drive_chat_change"("group_id", "entry_id");

      CREATE TABLE IF NOT EXISTS "drive_chat_held_change" (
        "id"         UUID NOT NULL,
        "ord"        BIGINT GENERATED BY DEFAULT AS IDENTITY,
        "group_id"   UUID NOT NULL,
        "owner_id"   UUID NOT NULL,
        "kind"       TEXT NOT NULL,
        "op"         JSONB NOT NULL,
        "entry_id"   UUID,
        "name"       TEXT NOT NULL,
        "from_path"  TEXT,
        "to_path"    TEXT,
        "state"      TEXT NOT NULL DEFAULT 'PENDING',
        "reason"     TEXT,
        "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
        "updated_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT "drive_chat_held_change_pkey" PRIMARY KEY ("id"),
        CONSTRAINT "drive_chat_held_change_kind_chk" CHECK ("kind" IN ('NEW_FOLDER', 'MOVE', 'RENAME', 'TRASH')),
        CONSTRAINT "drive_chat_held_change_state_chk" CHECK ("state" IN ('PENDING', 'APPLIED', 'SKIPPED')),
        CONSTRAINT "drive_chat_held_change_op_chk" CHECK (jsonb_typeof("op") = 'object'),
        CONSTRAINT "drive_chat_held_change_group_id_fkey" FOREIGN KEY ("group_id")
          REFERENCES "drive_chat_change_group"("id") ON DELETE CASCADE ON UPDATE CASCADE,
        CONSTRAINT "drive_chat_held_change_owner_id_fkey" FOREIGN KEY ("owner_id")
          REFERENCES "user"("id") ON DELETE CASCADE ON UPDATE CASCADE
      );
      CREATE INDEX IF NOT EXISTS "drive_chat_held_change_group_ord_idx" ON "drive_chat_held_change"("group_id", "ord");

      CREATE TABLE IF NOT EXISTS "drive_chat_question" (
        "id"              UUID NOT NULL,
        "owner_id"        UUID NOT NULL,
        "session_id"      UUID NOT NULL,
        "turn_id"         UUID NOT NULL,
        "status"          TEXT NOT NULL DEFAULT 'OPEN',
        "choice"          TEXT,
        "source_entry_id" UUID NOT NULL,
        "target_entry_id" UUID NOT NULL,
        "dest_parent_id"  UUID NOT NULL,
        "dest_name"       TEXT NOT NULL,
        "moving"          JSONB NOT NULL,
        "existing"        JSONB NOT NULL,
        "outcome"         JSONB,
        "reason"          TEXT,
        "created_at"      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
        "updated_at"      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
        "answered_at"     TIMESTAMPTZ(3),
        CONSTRAINT "drive_chat_question_pkey" PRIMARY KEY ("id"),
        CONSTRAINT "drive_chat_question_status_chk" CHECK ("status" IN ('OPEN', 'ANSWERING', 'ANSWERED', 'STALE')),
        CONSTRAINT "drive_chat_question_choice_chk" CHECK ("choice" IS NULL OR "choice" IN ('KEEP_BOTH', 'REPLACE')),
        CONSTRAINT "drive_chat_question_owner_id_fkey" FOREIGN KEY ("owner_id")
          REFERENCES "user"("id") ON DELETE CASCADE ON UPDATE CASCADE,
        CONSTRAINT "drive_chat_question_session_id_fkey" FOREIGN KEY ("session_id")
          REFERENCES "session"("id") ON DELETE CASCADE ON UPDATE CASCADE
      );
      CREATE INDEX IF NOT EXISTS "drive_chat_question_session_idx" ON "drive_chat_question"("session_id", "created_at");
      EXIT;
    EXCEPTION WHEN lock_not_available OR deadlock_detected THEN
      tries := tries + 1;
      IF tries >= 45 THEN
        RAISE EXCEPTION '1700: "user" or "session" was not free in 45 tries of 2 s each. Once what holds it has ended, mark the migration rolled back (prisma migrate resolve --rolled-back 1700_drive_chat_change_group) and deploy again: it is safe to run twice.'
          USING ERRCODE = 'lock_not_available';
      END IF;
      PERFORM pg_sleep(1);
    END;
  END LOOP;
END $$;
