// shots/boxes.json -> the board's marks.js: per shot, its clip size and the boxes the pins ring.
import fs from 'node:fs';
const [, , boxesFile, outFile] = process.argv;
const all = JSON.parse(fs.readFileSync(boxesFile, 'utf8'));
const out = {};
for (const [shot, b] of Object.entries(all)) {
  const boxes = {};
  for (const key of ['nav', 'scroll', 'lists', 'ws', 'wsHead', 'pj', 'pjHead', 'user', 'firstWsRow', 'firstPjRow']) {
    const v = b[key];
    if (v) boxes[key] = [v.x, v.y, v.w, v.h];
  }
  out[shot] = { w: b.clip.width, h: b.clip.height, rows: { ws: b.wsRows, pj: b.pjRows }, boxes };
}
fs.writeFileSync(outFile, `// Generated by capture/marks.mjs from the capture's boxes.json: clip size and element boxes per shot.\nwindow.SHOT_MARKS = ${JSON.stringify(out, null, 1)};\n`);
