#!/usr/bin/env python3
"""Where the initial JS/CSS of built trees comes from: usage bundle-composition.py name=<dist> ... > out.json

Each dist is a `vite build --sourcemap` of a tree. For the assets dist/index.html loads (as
bundle-size.py counts them), every generated byte is attributed through the asset's source map to the
source it came from; sources are grouped by npm package (node_modules/<package>), by the tree's own
src/components/ui, or as the rest of src. Bytes no mapping covers are reported as unmapped. Per group:
bytes in each tree and the difference from the first tree; and per tree the Orbit component modules the
initial JS contains, whose stylesheets come with them into the initial CSS (Vite emits no CSS source
maps here, so the CSS is only totalled). Reads only."""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

DIGITS = {c: i for i, c in enumerate('ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/')}


def decode(segment):
    values, shift, value = [], 0, 0
    for char in segment:
        digit = DIGITS[char]
        value += (digit & 31) << shift
        if digit & 32:
            shift += 5
        else:
            values.append(-(value >> 1) if value & 1 else value >> 1)
            shift = value = 0
    return values


def group(source):
    path = source.replace('\\', '/')
    if 'node_modules/' in path:
        parts = path.rsplit('node_modules/', 1)[1].split('/')
        return '/'.join(parts[:2]) if parts[0].startswith('@') else parts[0]
    if 'src/components/ui/' in path:
        return 'src/components/ui'
    if '/src/' in path or path.startswith('src/'):
        return 'src (rest)'
    return 'other: ' + path


def attribute(asset, totals, modules):
    code = asset.read_text()
    source_map = json.loads(Path(f'{asset}.map').read_text())
    sources = source_map['sources']
    mapped = 0
    source = 0
    for line, mappings in zip(code.split('\n'), source_map['mappings'].split(';')):
        spans, column = [], 0
        for segment in filter(None, mappings.split(',')):
            fields = decode(segment)
            column += fields[0]
            if len(fields) >= 4:
                source += fields[1]
                spans.append((column, source))
            else:
                spans.append((column, None))
        for (start, index), (end, _) in zip(spans, spans[1:] + [(len(line), None)]):
            if index is not None:
                size = len(line[start:end].encode())
                totals[group(sources[index])] += size
                mapped += size
                if group(sources[index]) == 'src/components/ui':
                    modules[sources[index].replace('\\', '/').split('src/components/ui/', 1)[1]] += size
    totals['unmapped'] += asset.stat().st_size - mapped


result = {}
for argument in sys.argv[1:]:
    name, dist = argument.split('=', 1)
    dist = Path(dist)
    html = (dist / 'index.html').read_text()
    files = sorted(set(re.findall(r'(?:src|href)="/(assets/[^"]+\.(?:js|css))"', html)))
    tree = {'files': files, 'js': defaultdict(int), 'css': defaultdict(int), 'uiModules': defaultdict(int)}
    for file in files:
        kind = 'css' if file.endswith('.css') else 'js'
        if Path(f'{dist / file}.map').exists():
            attribute(dist / file, tree[kind], tree['uiModules'])
        else:
            tree[kind]['no source map'] += (dist / file).stat().st_size
    result[name] = tree

names = list(result)
comparison = {}
for kind in ('js', 'css'):
    groups = sorted(set().union(*(result[name][kind] for name in names)))
    rows = {g: {name: result[name][kind].get(g, 0) for name in names} for g in groups}
    for row in rows.values():
        row['difference'] = row[names[-1]] - row[names[0]]
    comparison[kind] = {'totals': {name: sum(result[name][kind].values()) for name in names},
                        'groups': dict(sorted(rows.items(), key=lambda item: -abs(item[1]['difference'])))}
modules = sorted(set().union(*(result[name]['uiModules'] for name in names)))
comparison['uiModules'] = {module: {name: result[name]['uiModules'].get(module, 0) for name in names} for module in modules}
json.dump({'files': {name: result[name]['files'] for name in names}, **comparison}, sys.stdout, indent=1)
print()
