#!/usr/bin/env python3
"""Write UITests/ReplayTests.swift: one test per scene in scenes/ (in name order), each playing the scene's
own steps (its meta): wait for words, take a picture, type, send, press a button, see words go or never come.

  python3 -I gen_tests.py PROBE_DIR
"""
import json
import re
import sys
from pathlib import Path

probe = Path(sys.argv[1])
scenes = sorted(p.stem for p in (probe / 'scenes').glob('*.json'))


def test_name(scene):
    return 'test' + ''.join(part[:1].upper() + part[1:] for part in re.split(r'[^A-Za-z0-9]+', scene) if part)


tests = '\n\n'.join(f'    func {test_name(s)}() {{\n        play("{s}")\n    }}' for s in scenes)
source = f'''import XCTest

// TEMPORARY evidence probe (see ../README.md); generated by gen_tests.py from scenes/. Each test replays one
// scene of the Orbit test server's recorded answers to the real app, and plays the scene's steps.
final class ReplayTests: ProbeCase {{
    func play(_ scene: String) {{
        let meta = loadScene(scene)
        let surface = meta["surface"] as? String ?? "compose"
        let app = launch(surface: surface, agent: meta["agent"] as? String, session: meta["session"] as? String, scene)
        let steps = meta["steps"] as? [[String: Any]] ?? []
        for (i, step) in steps.enumerated() {{
            run(step, String(format: "%@-%02d", scene, i), app)
        }}
        settle(2)
        expectNoViolations(scene)
        app.terminate()
    }}

    private func run(_ step: [String: Any], _ label: String, _ app: XCUIApplication) {{
        let timeout = (step["timeout"] as? Double) ?? 120
        if let words = step["wait"] as? String {{
            if appears(app, words, timeout: timeout) {{
                note("\\(label): \\"\\(words)\\" shows")
            }} else {{
                XCTFail("\\(label): \\"\\(words)\\" never showed in \\(timeout) s")
                write(app.debugDescription, "missing-\\(label).txt")
            }}
        }}
        if let words = step["gone"] as? String {{
            if !disappears(app, words, timeout: timeout) {{ XCTFail("\\(label): \\"\\(words)\\" still shows after \\(timeout) s") }}
        }}
        for words in step["absent"] as? [String] ?? [] where shows(app, words) {{
            XCTFail("\\(label): \\"\\(words)\\" shows, and must not")
            write(app.debugDescription, "present-\\(label).txt")
        }}
        if let text = step["type"] as? String {{
            let field = composer(app)
            if field.waitForExistence(timeout: 20) {{
                press(field)
                settle(0.6)
                field.typeText(text)
                settle(0.8)
                note("\\(label): typed into \\(describe(field))")
            }} else {{
                XCTFail("\\(label): no composer to type into")
                write(app.debugDescription, "no-composer-\\(label).txt")
            }}
        }}
        if step["send"] as? Bool == true {{
            let send = sendButton(app)
            note("\\(label): send \\(describe(send))")
            if send.exists && send.isHittable {{
                press(send)
            }} else {{
                #if os(macOS)
                app.typeKey(.return, modifierFlags: [])
                #else
                XCTFail("\\(label): no Send to press")
                #endif
            }}
            settle(2)
        }}
        if let title = step["press"] as? String {{
            let target = button(app, beginning: title)
            if target.waitForExistence(timeout: timeout) {{
                note("\\(label): pressing \\(describe(target))")
                press(target)
                settle(2)
            }} else {{
                XCTFail("\\(label): no \\(title) to press")
            }}
        }}
        if let name = step["shot"] as? String {{
            settle(1.5)
            shot(name)
        }}
    }}

{tests}
}}
'''
(probe / 'UITests' / 'ReplayTests.swift').write_text(source)
print(json.dumps({'tests': [test_name(s) for s in scenes]}))
